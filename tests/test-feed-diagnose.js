/**
 * Тесты: разбор «почему лента короткая» (app/feed-diagnose.js). Без сети.
 * Запуск: node tests/test-feed-diagnose.js
 */
const { разборЛенты, видПричины } = require('../app/feed-diagnose');

let failures = 0;
function check(ok, label) {
  console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${label}`);
  if (!ok) failures++;
}

const срок = '2099-12-31';
const карточка = (номер, объект, цена, extra = {}) => ({ number: номер, object: объект, orgName: 'Школа', price: цена, law: '44-ФЗ Электронный аукцион', status: 'Подача заявок', deadline: срок, ...extra });
const клиент = { searchWords: ['бумага офисная'], filter: { keywords: ['бумаг'], minPrice: 100000, stopWords: ['туалетн'] } };
const карточки = [
  карточка('1', 'Поставка бумаги офисной А4', 500000),
  карточка('2', 'Поставка бумаги для принтера', 50000),          // слово есть, цена ниже порога
  карточка('3', 'Поставка бумаги туалетной', 300000),           // стоп-слово
  карточка('4', 'Ремонт кровли', 900000),                        // нет слова
  карточка('5', 'Поставка товаров для школы', 400000, { okpdGroup: '17.12' }), // нет слова, кода у клиента нет
  карточка('6', 'Ремонт дороги', 20000)                          // нет слова и цена ниже
];

console.log('=== Подсчёт отбора ===');
const р = разборЛенты(карточки, клиент);
check(р.всего === 6 && р.прошло === 1 && р.отсеяно === 5, `всего 6, прошло 1, отсеяно 5 (${р.всего}/${р.прошло}/${р.отсеяно})`);
check(р.толькоСлова === 2, `только словами - 2: ремонт кровли и «товары для школы» (${р.толькоСлова})`);
check(р.безСлов === 2, `слова подошли, убрала цена или стоп-слово - 2 (${р.безСлов})`);
const п = new Map(р.причины);
check(п.get('нет совпадений по ключевым словам') === 3, 'причина «нет слов» у 3 закупок');
check(п.get('НМЦК ниже порога клиента') === 2, 'причина «ниже порога» у 2 закупок, числа в причине сведены');
check(р.причины[0][0] === 'нет совпадений по ключевым словам', 'причины по убыванию');

console.log('=== Код ОКПД2 клиента пропускает закупку без слова ===');
const р2 = разборЛенты(карточки, { ...клиент, filter: { ...клиент.filter, okpd: ['17.12'] } });
check(р2.прошло === 2 && р2.толькоСлова === 1, `«товары для школы» с 17.12 прошла (${р2.прошло}, только словами ${р2.толькоСлова})`);

console.log('=== Причины без чисел ===');
check(видПричины('НМЦК 12 ниже порога 100') === 'НМЦК ниже порога клиента', 'ниже порога');
check(видПричины('стоп-слова: туалетн') === 'стоп-слова клиента', 'стоп-слова');
check(видПричины('другой закон') === 'другой закон', 'прочие как есть');

console.log(failures ? `\nСБОЕВ: ${failures}` : '\nВсе проверки прошли');
process.exit(failures ? 1 : 0);
