/**
 * Рейтинг тендеров: пять звёзд по рентабельности, падение цены по похожим
 * прошлым закупкам, денежные риски. Запуск: node tests/test-rating.js
 *
 * Арифметика на круглых числах, чтобы её можно было пересчитать в уме.
 * Каждое правило отбора проверено и в обратную сторону: чужая закупка,
 * которая не должна влиять, действительно не влияет.
 */
const { оценка, падениеПоПохожим, упорядочить } = require('../src/rating');

let failures = 0;
const check = (ok, message) => {
  console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${message}`);
  if (!ok) failures++;
};
const section = (name) => console.log(`\n=== ${name} ===`);

const АУК = 'электронный аукцион';
const н = (снижение, нмцк = 1000000, способ = АУК, номер = 'Н' + снижение) => ({ снижение, нмцк, способ, номер });
const база = { нмцк: 1000000, способ: '44-ФЗ Электронный аукцион', закупка: 500000, закупкаПолная: true, доставкаПроцент: 5, налог: 0.06 };

section('Падение цены — самое глубокое у похожих');
const похожие = [н(10), н(15), н(20)];
const п = падениеПоПохожим(похожие, { нмцк: 1000000, способ: АУК });
check(п.достаточно && п.падение === 20 && п.закупка === 'Н20', `берётся самое глубокое падение и его закупка (${п.падение}%, ${п.закупка})`);
check(п.медиана === 15, 'медиана показывается рядом');
// Отрицательные контроли: чужие закупки не влияют.
const сЧужими = [...похожие, н(60, 3000000), н(70, 1000000, 'запрос котировок')];
check(падениеПоПохожим(сЧужими, { нмцк: 1000000, способ: АУК }).падение === 20,
  'закупка на 3 млн и закупка другим способом не тянут падение вниз');
check(!падениеПоПохожим([н(10), н(20)], { нмцк: 1000000, способ: АУК }).достаточно,
  'две похожие — мало, звёзд по ним нет');
check(!падениеПоПохожим(похожие, { нмцк: 1000000, способ: 'иной способ' }).достаточно,
  'иной способ закупки ни с чем не сравнивается');

section('Прошлые закупки с несколькими кодами ОКПД2 (список с карточки, 20.10.2026)');
{
  const сКодом = (с, группы, одна = null) => ({ ...н(с), группаОкпд2: одна, ...(группы ? { группыОкпд2: группы } : {}) });
  const выборка = [сКодом(10, ['27.32', '27.40']), сКодом(15, ['27.32']), сКодом(20, null, '27.32'), сКодом(50, ['17.12'])];
  const р = падениеПоПохожим(выборка, { нмцк: 1000000, способ: АУК, группыОкпд2: ['27.32'] });
  check(р.достаточно && р.падение === 20, `три закупки кабеля (списком и из ИКЗ), бумага 50% не взята (получено ${р.падение})`);
  check(!падениеПоПохожим(выборка, { нмцк: 1000000, способ: АУК, группыОкпд2: ['26.30'] }).достаточно,
    'чужой товар - похожих нет');
}

section('Арифметика звёзд');
// Падение 20% → цена победы 800 000. Закупка 500 000, доставка 5% = 25 000,
// налог 6% от 800 000 = 48 000. Прибыль 227 000, рентабельность 28,4%.
const пять = оценка({ ...база, наблюдения: похожие });
check(пять.ценаПобеды === 800000 && пять.прибыль === 227000, `цена победы 800 000, прибыль 227 000 (${пять.ценаПобеды}, ${пять.прибыль})`);
check(пять.рентабельность === 28.4 && пять.звёзды === 5, `28,4% — пять звёзд (${пять.рентабельность}%, ${пять.звёзды}★)`);
// Закупка 700 000: прибыль 800 − 700 − 35 − 48 = 17 000, 2,1% — две звезды.
const две = оценка({ ...база, закупка: 700000, наблюдения: похожие });
check(две.звёзды === 2, `рентабельность ${две.рентабельность}% — две звезды`);
const убыток = оценка({ ...база, закупка: 800000, наблюдения: похожие });
check(убыток.звёзды === 1 && убыток.прибыль < 0, 'убыток — одна звезда');
// Граница: ровно 15% не пять звёзд — «выше 15%» сказано владельцем.
const граница = оценка({ ...база, закупка: 800000 - 25000 * 0 - 48000 - 120000, доставкаПроцент: 0, наблюдения: похожие });
check(граница.рентабельность === 15 && граница.звёзды === 4, `ровно 15% — четыре звезды, пять только выше (${граница.рентабельность}%)`);

section('Денежные риски снимают звезду с причиной');
const глубоко = [н(10), н(20), н(30)];
const анти = оценка({ ...база, закупка: 400000, наблюдения: глубоко });
check(анти.минусы.some((м) => /антидемпинг/.test(м)), 'падение 30% — названа причина «антидемпинг»');
// Падение 30% → 700 000; закупка 400 000, доставка 20 000, налог 42 000 →
// прибыль 238 000, 34% — пять звёзд по рентабельности, минус одна за антидемпинг.
check(анти.рентабельность === 34 && анти.звёзды === 4 && анти.минусы.length === 1,
  `34% даёт пять звёзд, антидемпинг снимает ровно одну (${анти.рентабельность}%, ${анти.звёзды}★)`);
const обесп = оценка({ ...база, наблюдения: похожие, обеспечениеКонтрактаПроцент: 30 });
check(обесп.звёзды === 4 && обесп.минусы.length === 1, 'обеспечение 30% — минус звезда (5 → 4)');
const обеспНорм = оценка({ ...база, наблюдения: похожие, обеспечениеКонтрактаПроцент: 5 });
check(обеспНорм.звёзды === 5 && обеспНорм.минусы.length === 0, 'обеспечение 5% звезду не снимает');
const самоеНизкое = оценка({ ...база, закупка: 800000, наблюдения: глубоко, обеспечениеКонтрактаПроцент: 30 });
check(самоеНизкое.звёзды === 1, 'ниже одной звезды не опускается');

section('Без звёзд — и с причиной, а не с выдуманным числом');
check(оценка({ ...база, закупка: null, наблюдения: похожие }).звёзды === null, 'без прайса звёзд нет');
check(/прайс/.test(оценка({ ...база, закупка: null, наблюдения: похожие }).почему), 'причина: нужен прайс');
check(оценка({ ...база, закупкаПолная: false, наблюдения: похожие }).звёзды === null, 'прайс покрыл не всё — звёзд нет');
check(оценка({ ...база, ценаЗаЕдиницу: true, наблюдения: похожие }).звёзды === null, 'закупка по цене за единицу — звёзд нет');
check(оценка({ ...база, наблюдения: [н(10)] }).звёзды === null, 'одна похожая закупка — звёзд нет');
const пусто = оценка({ ...база, закупка: null, наблюдения: [] });
check(пусто.прибыль === null && пусто.рентабельность === null, 'прибыль и рентабельность — «неизвестно», а не ноль');

section('Порядок: звёзды, затем прибыль, срок — в самом конце');
const список = упорядочить([
  { номер: 'а', срок: '2026-10-20', оценка: { звёзды: 4, прибыль: 500000 } },
  { номер: 'б', срок: '2026-10-25', оценка: { звёзды: 5, прибыль: 100000 } },
  { номер: 'в', срок: '2026-10-21', оценка: { звёзды: 5, прибыль: 300000 } },
  { номер: 'г', срок: '2026-10-19', оценка: { звёзды: null, прибыль: null } },
  { номер: 'д', срок: '2026-10-18', оценка: { звёзды: 5, прибыль: 300000 } }
]);
check(список.map((x) => x.номер).join('') === 'двбаг', `порядок д,в,б,а,г (${список.map((x) => x.номер).join(',')})`);

console.log(`\n${failures === 0 ? 'ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ' : 'ПРОВАЛЕНО ПРОВЕРОК: ' + failures}`);
process.exit(failures === 0 ? 0 : 1);
