/**
 * Аналитика ниши (src/niche-report.js). Случаи придуманы мной; формулы - те же,
 * что в расчёте за единицу. Запуск: node tests/test-niche-report.js
 */
const { аналитикаНиши } = require('../src/niche-report');
const { разобратьПрайс } = require('../src/price-list');

let failures = 0;
const check = (ok, m) => { console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${m}`); if (!ok) failures++; };

const прайс = разобратьПрайс(Buffer.from('Наименование;Ед.;Цена\nБумага для офисной техники А4;пачка;300\nКабель ВВГ 3х1,5;м;60\n', 'utf8'), { имяФайла: 'прайс.csv' });
const позиция = (name, unit, ...цены) => ({ name, unit, quantity: 10, prices: цены.map((value) => ({ value })) });
const закупки = [
  { номер: '1', группы: ['17.12'], позиции: [позиция('Бумага для офисной техники А4', 'пачка', 420, 440, 460)] },
  { номер: '2', группы: ['17.12'], позиции: [позиция('Бумага для офисной техники А4', 'пачка', 400, 410, 420)] },
  { номер: '3', группы: ['17.12'], позиции: [позиция('Бумага для офисной техники А4', 'пачка', 430, 450, 470), позиция('Бумага для офисной техники А4', 'пачка', 1, 1, 1)] },
  { номер: '4', группы: ['27.32'], позиции: [позиция('Кабель ВВГ 3х1,5', 'шт', 5000)] },
  { номер: '5', группы: ['17.12'], позиции: [позиция('Бумага для офисной техники А3', 'пачка', 900)] }
];
const протоколы = [
  ...[20, 22, 25, 18, 24, 21, 23, 19, 26, 22].map((с, i) => ({ снижение: с, участников: 3 + (i % 3), группаОкпд2: '17.12' })),
  { снижение: 0, единственнаяЗаявка: true, группаОкпд2: '17.12' },
  { снижение: 60, группаОкпд2: '27.32' }
];
const р = аналитикаНиши({ прайс, закупки, протоколы });
const бумага = р.товары.find((т) => /А4/.test(т.товар)) || {};
check(р.ok && бумага.закупок === 3, `бумага А4 найдена в 3 закупках, повтор позиции в закупке 3 - один раз (${бумага.закупок})`);
check(бумага.ценаЗаказчика === 440, `цена заказчика - медиана средних предложений: 440 (${бумага.ценаЗаказчика})`);
check(р.падение.n === 10 && р.падение.медиана === 22, `падение по группе 17.12 без единственной заявки: 10 протоколов, медиана 22% (${р.падение.n}, ${р.падение.медиана})`);
check(бумага.ожидаемаяЦенаПобеды === 343.2 && бумага.безубыточная === Math.round(300 * 1.08 / 0.94 * 100) / 100, `ожидаемая цена победы 440 × 0,78 = 343,2; безубыточная ${бумага.безубыточная}`);
check(бумага.запасПроцент < 0 && /себестоимость выше/.test(бумага.вывод), `при цене 300 ₽ безубыточная 344,68 выше 343,2: ${бумага.вывод} (${бумага.запасПроцент}%)`);
{
  const дешевле = разобратьПрайс(Buffer.from('Наименование;Ед.;Цена\nБумага для офисной техники А4;пачка;280\n', 'utf8'), { имяФайла: 'прайс.csv' });
  const б2 = аналитикаНиши({ прайс: дешевле, закупки, протоколы }).товары[0];
  check(/^заходить/.test(б2.вывод) && б2.запасПроцент >= 5, `при цене 280 ₽ - ${б2.вывод} (запас ${б2.запасПроцент}%)`);
}
check(р.участников === 4, `участников обычно 4 (${р.участников})`);
check(!р.товары.some((т) => /Кабель/.test(т.товар)), 'кабель в метрах не сопоставлен с позицией в штуках');
check(!р.товары.some((т) => /А3/.test(т.товар)), 'бумага А3 не сопоставлена со строкой А4 (числа строки прайса)');
const мало = аналитикаНиши({ прайс, закупки: закупки.slice(0, 2), протоколы });
check(/^мало данных/.test(мало.товары[0].вывод), 'две закупки - «мало данных», вывода нет');
check(!аналитикаНиши({ прайс: null, закупки, протоколы }).ok, 'без прайса отчёта нет');

console.log(failures ? `\nСБОЕВ: ${failures}` : '\nВСЕ ПРОВЕРКИ ПРОЙДЕНЫ');
process.exit(failures ? 1 : 0);
