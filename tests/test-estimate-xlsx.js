/** Достаёт XML листа из готового файла — чтобы проверять именно разметку. */
function sheetXmlOf(buffer, index) {
  const dir = readZipDirectory(buffer);
  const entry = dir.find((e) => e.name === `xl/worksheets/sheet${index}.xml`);
  return entry ? readZipEntry(buffer, entry).toString('utf8') : '';
}

