/**
 * Накопленная база поставщиков (src/supplier-base.js) - без сети.
 * Запуск: node tests/test-supplier-base.js
 */
const Б = require('../src/supplier-base');
const { сверитьПоставщика } = require('../src/verify');

let failures = 0;
const check = (ok, m) => { console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${m}`); if (!ok) failures++; };

const бумага = { name: 'Бумага для офисной техники, белая, А4', unit: 'пачка' };
const найдено = [
  { name: 'ООО «МКФ Групп»', url: 'https://mkf.example/paper-a4', site: 'https://mkf.example', price: 330, unit: 'пачка', evidence: 'Бумага А4 SvetoCopy 500 листов 330 ₽', phone: '+7 000', region: 'Москва' },
  { name: 'Самсон-опт', url: 'https://samson.example/a4', price: null, evidence: 'Бумага офисная А4' },
  { name: 'Выдумка', url: '', price: 100, evidence: 'x' }
];

console.log('\n=== Запись ===');
const база = {};
check(Б.записать(база, бумага, найдено, new Date('2026-10-22')) === 2, 'поставщик без ссылки в базу не попадает');
check(Object.keys(база.поставщики).join() === 'mkf.example,samson.example', 'поставщики - по домену');
check(Б.кандидаты(база, бумага).length === 1 && Б.кандидаты(база, бумага)[0].цена === 330, 'кандидат для цены - только с подтверждённой ценой');
check(Б.ключПозиции({ name: 'Бумага для офисной техники, белая, А4' }) === Б.ключПозиции({ name: 'бумага  для офисной техники белая А4' }), 'ключ позиции не зависит от регистра и знаков');
check(Б.кандидаты(база, { name: 'Бумага для офисной техники, цветная, А4' }).length === 0, 'другая позиция - кандидатов нет (по профилю компании не предполагаем)');
check(Б.ключПозиции({ name: 'Кабель 3 x 1,5' }) === Б.ключПозиции({ name: 'Кабель 3х1,5' }), '«3 x 1,5» и «3х1,5» - один ключ');
Б.записать(база, бумага, [{ ...найдено[0], price: 320 }], new Date('2026-10-23'));
check(база.позиции[Б.ключПозиции(бумага)].filter((x) => x.url === 'https://mkf.example/paper-a4').length === 1 && Б.кандидаты(база, бумага)[0].цена === 320, 'повторная находка обновляет запись, а не дублирует');

console.log('\n=== Проверка страницы ===');
const к = Б.кандидаты(база, бумага)[0];
const страницаДа = 'Каталог. ' + 'Бумага А4 SvetoCopy 500 листов 330 ₽. Цена 320 ₽ за пачку. '.repeat(10);
const сДа = сверитьПоставщика({ name: к.поставщик.имя, url: к.url, price: к.цена, evidence: к.цитата }, страницаДа);
const п = Б.подтверждённый(к, сДа, new Date('2026-10-24'));
check(п && п.price === 320 && п.изБазы && /2026-10-24/.test(п.priceNote), 'цена подтверждена сегодня - поставщик в расчёт с датой проверки');
const сНет = сверитьПоставщика({ name: к.поставщик.имя, url: к.url, price: к.цена, evidence: к.цитата }, 'Каталог. Товар снят с продажи. '.repeat(20));
check(Б.подтверждённый(к, сНет) === null, 'цены на странице нет - не подставляется');
check(Б.подтверждённый(к, сверитьПоставщика({ name: 'x', url: к.url, price: 320 }, null, 'код ответа 404')) === null, 'страница не ответила - не «цена прежняя»');
Б.отметитьПроверку(база, бумага, к.url, false);
check(Б.кандидаты(база, бумага).length === 0, 'не подтвердил - убран из базы («искать заново»)');

console.log('\n=== Предел ===');
const много = {};
Б.записать(много, бумага, Array.from({ length: 20 }, (_, i) => ({ name: `П${i}`, url: `https://p${i}.example/a`, price: 300 + i, evidence: 'Бумага А4 цена' })));
check(много.позиции[Б.ключПозиции(бумага)].length === Б.ПРЕДЕЛ_НА_ПОЗИЦИЮ, `не больше ${Б.ПРЕДЕЛ_НА_ПОЗИЦИЮ} записей на позицию`);

console.log('\n=== Данные клиента в базу не попадают ===');
const исходник = require('fs').readFileSync(require('path').join(__dirname, '..', 'src', 'supplier-base.js'), 'utf8');
check(!/require\([^)]*(price-list|http|proxy|anthropic)/.test(исходник), 'модуль базы не подключает прайс клиента и сеть');

console.log(failures ? `\nСБОЕВ: ${failures}` : '\nВСЕ ПРОВЕРКИ ПРОЙДЕНЫ');
process.exit(failures ? 1 : 0);
