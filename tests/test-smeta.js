const работы = р.positions.find((x) => x.работыСметы);
const матер = р.positions.filter((x) => !x.работыСметы).reduce((s, x) => s + x.quantity * x.min, 0);
check(работы && Math.abs(работы.min + матер - 48800) < 0.05, 'работы = ВСЕГО по смете минус материалы, сумма сходится с итогом');
