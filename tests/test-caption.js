const { подписьДляФайла, закрытьТеги } = require('../src/notify');

let failures = 0;
const check = (ok, message) => {
  console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${message}`);
  if (!ok) failures++;
};
const section = (name) => console.log(`\n=== ${name} ===`);

/** Теги закрыты попарно? Та же проверка, что делает Telegram. */
function разметкаЦела(текст) {
  const стек = [];
  const ТЕГИ = /<(\/?)([a-zA-Z][a-zA-Z0-9]*)[^>]*>/g;
  let m;
  while ((m = ТЕГИ.exec(текст)) !== null) {
    const имя = m[2].toLowerCase();
    if (m[1] === '/') {
      const где = стек.lastIndexOf(имя);
      if (где === -1) return false;
      стек.splice(где, 1);
    } else стек.push(имя);
  }
  return стек.length === 0;
}

section('Короткая подпись не трогается');
const коротко = '<b>Закупка</b>\nНМЦК: <b>100 ₽</b>';
check(подписьДляФайла(коротко) === коротко, 'текст в пределах нормы возвращается как есть');
check(разметкаЦела(подписьДляФайла(коротко)), 'разметка цела');

section('ГЛАВНОЕ: длинная подпись не ломает разметку');
// Воспроизводим тот самый случай: срез приходится на середину тега.
const длинно = '<b>Поставка бланков документов установленного образца</b>\n'
  + 'ФЕДЕРАЛЬНОЕ ГОСУДАРСТВЕННОЕ БЮДЖЕТНОЕ ОБРАЗОВАТЕЛЬНОЕ УЧРЕЖДЕНИЕ\n\n'
  + ('<i>строка с источниками цены, длинная настолько, что подпись не влезает</i>\n'.repeat(40));

const обрезана = подписьДляФайла(длинно);
check(обрезана.length <= 1000, `уложилось в предел (получено ${обрезана.length})`);
check(разметкаЦела(обрезана), 'РАЗМЕТКА ЦЕЛА — Telegram такое примет');
check(/в приложенном файле/.test(обрезана), 'сказано, где искать полный расчёт');

section('Срез посреди тега отодвигается назад');
// 'A' добивает длину так, чтобы срез пришёлся ровно внутрь «<b…».
const внутриТега = 'A'.repeat(950) + '<b>жирный хвост</b>';
const ровно = подписьДляФайла(внутриТега);
check(разметкаЦела(ровно), 'обрезка внутри тега не оставила огрызка');
check(!/<b?$|<$/.test(ровно), 'в конце нет незавершённого тега');

section('Незакрытые теги закрываются');
check(закрытьТеги('<b>жирный') === '<b>жирный</b>', 'один незакрытый закрыт');
check(закрытьТеги('<b><i>оба') === '<b><i>оба</i></b>',
  'вложенные закрываются в обратном порядке');
check(закрытьТеги('<b>целый</b>') === '<b>целый</b>', 'целую разметку не трогает');
check(закрытьТеги('без тегов') === 'без тегов', 'текст без тегов не меняется');

section('Битый вход не роняет');
check(подписьДляФайла(null) === '', 'null даёт пустую строку');
check(подписьДляФайла(undefined) === '', 'undefined даёт пустую строку');
check(typeof подписьДляФайла(12345) === 'string', 'число приводится к строке');

section('Предел задаётся и соблюдается');
const узко = подписьДляФайла(длинно, 200);
check(узко.length <= 200, `узкий предел соблюдён (получено ${узко.length})`);
check(разметкаЦела(узко), 'и разметка при этом цела');

section('Проверка умеет не проходить');
// Если бы обрезка осталась прежней, эта проверка поймала бы поломку.
const поСтарому = длинно.slice(0, 1000);
check(!разметкаЦела(поСтарому),
  'СТАРАЯ обрезка по числу знаков действительно ломает разметку — проверка рабочая');

console.log('');
if (failures) {
  console.log(`ПРОВЕРОК НЕ ПРОШЛО: ${failures}`);
  process.exit(1);
}
console.log('ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ');
