/**
 * Тесты шанса на победу (src/chance.js). Запуск: node tests/test-chance.js
 * Наблюдения придуманы мной, по форме - как у сборщика протоколов.
 */
const { шансПобеды, текстШанса } = require('../src/chance');

let failures = 0;
const check = (ok, message) => {
  console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${message}`);
  if (!ok) failures++;
};

const н = (снижение, нмцк = 200000, extra = {}) => ({ номер: String(Math.random()), способ: 'электронный аукцион', нмцк, снижение, участников: 4, группаОкпд2: '17.12', ...extra });
const прошлые = [н(5), н(10), н(12), н(20), н(30), н(40), н(0, 200000, { единственнаяЗаявка: true, участников: 1 }),
  н(15, 900000), н(8, 200000, { группаОкпд2: '32.50' }), н(9, 200000, { способ: 'запрос котировок' })];
const тендер = { нмцк: 210000, способ: '44-ФЗ Электронный аукцион', группыОкпд2: ['17.12'] };

const ш = шансПобеды(прошлые, тендер, { запас: 15, запасЛучший: 25 });
check(ш.оценён && ш.похожих === 6, `похожие: тот же способ, сумма ±50%, тот же товар, без единственной заявки (${ш.похожих})`);
check(ш.поХудшей === 3 && ш.поЛучшей === 4, `по худшей цене 3 из 6, по лучшей 4 из 6 (${ш.поХудшей}, ${ш.поЛучшей})`);
check(ш.единственных === 1 && ш.снижениеОт === 5 && ш.снижениеДо === 40, 'размах снижения без закупки с единственной заявкой');
const т = текстШанса(ш);
check(/В 3 из 6 похожих закупок/.test(т) && /4 из 6/.test(т) && !/гарант|вероятн/i.test(т), 'текст - счёт по прошлым закупкам, без «гарантий»');

// Отрицательные контроли
check(!шансПобеды(прошлые, тендер, { запас: 15, толькоПотолки: true }).оценён, 'по одним ценам обоснования НМЦК шанс не оценивается');
check(!шансПобеды(прошлые.slice(0, 2), тендер, { запас: 15 }).оценён, 'меньше трёх похожих - не оценивается');
check(!шансПобеды(прошлые, { ...тендер, группыОкпд2: ['26.20'] }, { запас: 15 }).оценён, 'чужой товар не добирает выборку');
check(!шансПобеды(прошлые, тендер, {}).оценён, 'без безубыточности - не оценивается');
check(!шансПобеды(прошлые, { ...тендер, способ: 'Закупка у единственного поставщика' }, { запас: 15 }).оценён, 'единственный поставщик - сравнивать не с чем');
const минус = текстШанса(шансПобеды(прошлые, тендер, { запас: -5, запасЛучший: -2 }));
check(/выиграть без убытка нельзя/.test(минус) && !/-5%/.test(минус), 'убыток при любой цене - сказано прямо, без «снижения не больше -5%»');
const развилка = текстШанса(шансПобеды(прошлые, тендер, { запас: -5, запасЛучший: 12 }));
check(/По худшей цене поставщика расходы выше/.test(развилка) && /12%/.test(развилка), 'исход зависит от поставщика - оба варианта названы');
check(/не оценён/.test(текстШанса(null)), 'нет данных - честная строка');

// Похожие закупки в карточке тендера (22.10.2026) - до расчёта, без запаса.
const { историяПохожих } = require('../src/chance');
const х = историяПохожих(прошлые, тендер);
check(х.оценена && х.похожих === 6 && х.единственных === 1, 'похожие: тот же способ, сумма и товар; единственная заявка не в счёт');
check(х.медиана === 16 && х.от === 5 && х.до === 40, `снижение: обычно ${х.медиана}%, от ${х.от} до ${х.до}`);
check(х.q1 <= х.медиана && х.медиана <= х.q3, 'половина закупок - между четвертями');
check(х.примеры.length === 5 && х.примеры.every((п) => typeof п.снижение === 'number'), 'до 5 примеров с номерами');
