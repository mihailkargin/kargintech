/**
 * Тесты: данные для сайта — лента клиента и запись настроек (app/site-api.js).
 * Запуск: node tests/test-site-api.js
 *
 * Главное здесь — отрицательные контроли: сайт не может перезаписать файл
 * клиента, заведённого владельцем, не может подставить путь и не может
 * протащить в настройки поле, которого нет в белом списке (прайс, чаты).
 */
const fs = require('fs');
const os = require('os');
const path = require('path');
const { лентаКлиента, записатьНастройкиСайта, основа } = require('../app/site-api');

let failures = 0;
const check = (ok, message) => {
  console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${message}`);
  if (!ok) failures++;
};
const section = (name) => console.log(`\n=== ${name} ===`);

const корень = fs.mkdtempSync(path.join(os.tmpdir(), 'siteapi-'));
const к = { состояние: path.join(корень, 'state'), клиенты: path.join(корень, 'clients') };
fs.mkdirSync(к.состояние, { recursive: true });
fs.mkdirSync(к.клиенты, { recursive: true });

section('Запись настроек клиента сайта');
const r = записатьНастройкиСайта('site-abc123', {
  слова: ['кабель', 'розетки выключатели', ' кабель ', ''], стопСлова: ['ремонт'],
  ценаОт: '30000', ценаДо: 5e6, законы: ['44-ФЗ', 'левый'], налог: 0.06,
  прайс: '/etc/passwd', clientChatId: '123', searchWords: ['взлом']
}, к);
check(r.ok, 'записано');
const файл = JSON.parse(fs.readFileSync(path.join(к.клиенты, 'site-abc123.json'), 'utf8'));
check(JSON.stringify(файл.searchWords) === JSON.stringify(['кабель', 'розетки выключатели']), 'слова без пустых и повторов');
check(JSON.stringify(файл.filter.keywords) === JSON.stringify(['кабел', 'розетк', 'выключател']), `основы всех значимых слов фразы (получено ${JSON.stringify(файл.filter.keywords)})`);
{
  const { основыФраз } = require('../app/site-api');
  // Живой случай 21.10.2026: «промышленный клининг» давало «промышленн», и
  // закупки клининга («клининговые услуги») отсекались все.
  check(JSON.stringify(основыФраз(['промышленный клининг'])) === '["клининг"]', 'общее слово не становится основой отбора');
  check(основыФраз(['поставка оборудования']).length === 1, 'фраза из общих слов не теряется');
  // Живой случай 22.10.2026 по архиву: «белье» → «бель» внутри «кабель».
  check(!основыФраз(['постельное белье']).some((о) => 'поставка кабельной продукции'.includes(о)), 'текстиль не ловит закупки кабеля');
  check(JSON.stringify(основыФраз(['пожарная сигнализация'])) === '["сигнализаци"]', 'пожарная сама по себе не становится признаком ниши');
}
check(файл.filter.minPrice === 30000 && файл.filter.maxPrice === 5e6, 'диапазон цены');
check(JSON.stringify(файл.filter.laws) === JSON.stringify(['44-ФЗ']), 'законы - только 44-ФЗ и 223-ФЗ');
check(файл.economics.taxRate === 0.06, 'налог');
// Отрицательные контроли
check(!('прайс' in файл), 'путь к прайсу из запроса не записан');
check(файл.clientChatId === '', 'адрес чата из запроса не записан');
check(!JSON.stringify(файл).includes('взлом'), 'поле searchWords из запроса не протащено мимо «слов»');
check(!записатьНастройкиСайта('kargin', { слова: ['x'] }, к).ok, 'файл клиента владельца (kargin) сайт перезаписать не может');
check(!записатьНастройкиСайта('site-../../etc', { слова: ['x'] }, к).ok, 'подстановка пути отвергнута');
check(!записатьНастройкиСайта('site-abc123', { слова: [] }, к).ok, 'без слов - отказ');
check(!fs.existsSync(path.join(к.клиенты, 'kargin.json')), 'файла kargin не появилось');
const слова30 = Array.from({ length: 30 }, (_, i) => `фраза ${i + 1}`);
check(записатьНастройкиСайта('site-abc123', { слова: слова30 }, к).ok, '30 слов и фраз с учётом категорий принимаются');
check(!записатьНастройкиСайта('site-abc123', { слова: [...слова30, 'лишняя'] }, к).ok, '31-я фраза отвергается явно, а не обрезается');

section('Реквизиты покупателя');
{
  const с = (реквизиты) => { записатьНастройкиСайта('site-abc123', { слова: ['кабель'], реквизиты }, к); return JSON.parse(fs.readFileSync(path.join(к.клиенты, 'site-abc123.json'), 'utf8')).покупатель; };
  check(с({ название: 'ООО «Тест»', инн: '7707083893', согласие: true }).инн === '7707083893', 'с согласием и верным ИНН - записано');
  check(с({ название: 'ООО «Тест»', инн: '7707083893', согласие: false }) === undefined, 'без согласия - не записано');
  check(с({ название: 'ООО «Тест»', инн: '7707083894', согласие: true }) === undefined, 'неверный ИНН - не записано');
  check(с(null) === undefined, 'реквизитов нет - не записано');
}

section('Основы слов');
check(основа('Кабель') === 'кабел' && основа('выключатели') === 'выключател' && основа('лампа') === 'ламп', 'основы');
check(основа('мясная') === 'мясн' && основа('провод') === 'провод' && основа('шины') === 'шины', 'окончание отрезается, короткое слово остаётся целым (провод - не «пров», шины - не «шин»)');
check(основа('инженерных') === 'инженерн', 'окончание -ых');

section('Лента клиента');
записатьНастройкиСайта('site-abc123', { слова: ['кабель'], стопСлова: ['ремонт'] }, к);
fs.writeFileSync(path.join(к.состояние, 'site-abc123.json'), JSON.stringify({
  обновлено: '2026-10-21T09:00:00Z',
  карточки: {
    '111': { объект: 'Поставка кабеля', заказчик: 'ГБУ', нмцк: 100000, срок: '2026-10-30', закон: '44-ФЗ Электронный аукцион', url: 'https://x/111', изменения: [{ поле: 'deadline', что: 'срок подачи', было: '2026-10-28', стало: '2026-10-30', когда: '2026-10-21' }] },
    '222': { объект: 'Поставка розеток', заказчик: 'МБУ', нмцк: 50000, срок: '2026-10-25', закон: '223-ФЗ', url: 'https://x/222' },
    '333': { объект: 'Провод', заказчик: 'ООО', нмцк: 70000, срок: '2026-11-02', закон: '44-ФЗ', url: 'https://x/333' },
    '444': { объект: 'Ремонт кабельных сетей', заказчик: 'ГБУ', нмцк: 80000, срок: '2026-11-03', закон: '44-ФЗ', url: 'https://x/444' },
    '555': { объект: 'Поставка и ремонт оборудования', заказчик: 'ГБУ', нмцк: 90000, срок: '2026-11-04', закон: '44-ФЗ', url: 'https://x/555' },
    '666': { объект: 'Поставка оборудования', заказчик: 'ГБУ', нмцк: 90000, срок: '2026-11-05', закон: '44-ФЗ', url: 'https://x/666' }
  }
}));
fs.writeFileSync(path.join(к.состояние, 'site-abc123-parsed.json'), JSON.stringify({
  '111': { ок: true, позиций: 4, естьТЗ: true, когда: '2026-10-21' },
  '666': { ок: true, позиций: 1, наименования: ['Ремонт кабеля'] }
}));
fs.writeFileSync(path.join(к.состояние, 'site-abc123-queue.json'), JSON.stringify([{ number: '222' }]));
const л = лентаКлиента('site-abc123', к);
check(л.ok && л.тендеры.length === 3, 'три тендера');
check(!л.тендеры.some((т) => т.номер === '444' || т.номер === '555'), 'текущие стоп-слова скрывают старые карточки ленты');
check(!л.тендеры.some((т) => т.номер === '666'), 'текущие стоп-слова скрывают старую закупку по наименованиям из ТЗ');
check(л.тендеры[0].номер === '222', 'сначала ближайший срок');
check(л.тендеры.find((т) => т.номер === '111').разбор.позиций === 4, 'итог разбора приложен');
check(л.тендеры.find((т) => т.номер === '111').изменения.length === 1, 'изменения срока переданы в ленту');
check(л.тендеры.find((т) => т.номер === '222').разбор.вОчереди === true, 'стоящий в очереди помечен');
check(л.тендеры.find((т) => т.номер === '333').разбор === null, 'не разобранный - null, а не «0 позиций»');
check(лентаКлиента('site-нет', к).тендеры.length === 0, 'нет файла - пустая лента, а не сбой');

section('Прайс клиента сайта');
{
  const { сохранитьПрайсСайта } = require('../app/site-api');
  const csv = Buffer.from('Наименование;Ед. изм.;Цена с НДС, руб\nКабель ВВГ 3х2,5;м;105\nРозетка двойная;шт;250\n');
  const р = сохранитьПрайсСайта('site-abc123', 'Мой прайс.csv', csv, к);
  check(р.ok && р.позиций === 2, `прайс принят, позиций 2 (${р.сбой || р.позиций})`);
  const н = JSON.parse(fs.readFileSync(path.join(к.клиенты, 'site-abc123.json'), 'utf8'));
  check(н.прайс === path.join(к.клиенты, 'site-abc123-price.csv'), 'путь к прайсу задан кодом, а не именем из запроса');
  check(fs.existsSync(path.join(к.клиенты, 'site-abc123-price.csv')), 'файл лежит в папке клиентов');
  записатьНастройкиСайта('site-abc123', { слова: ['кабель'] }, к);
  const н2 = JSON.parse(fs.readFileSync(path.join(к.клиенты, 'site-abc123.json'), 'utf8'));
  check(н2.прайс === н.прайс, 'сохранение настроек не теряет прайс');
  // Отрицательные контроли
  check(!сохранитьПрайсСайта('kargin', 'p.csv', csv, к).ok, 'прайс клиенту владельца сайт записать не может');
  check(!сохранитьПрайсСайта('site-abc123', '../../x.exe', csv, к).ok, 'чужое расширение - отказ');
  const испорченный = сохранитьПрайсСайта('site-abc123', 'p.csv', Buffer.from('просто текст без шапки'), к);
  check(!испорченный.ok && fs.readFileSync(path.join(к.клиенты, 'site-abc123-price.csv'), 'utf8').includes('Розетка'), 'негодный файл не применён, прежний прайс на месте');
  check(!сохранитьПрайсСайта('site-new0001', 'p.csv', csv, к).ok, 'без настроек поиска прайс не принимается');
}

section('Поставщики из следов расчётов');
{
  const { поставщикиПоЗакупкам } = require('../app/site-api');
  fs.writeFileSync(path.join(к.состояние, 'verify-0301100049626001767.json'), JSON.stringify({
    когда: '2026-10-21T00:00:00Z',
    поставщики: [
      { позиция: 'Кабель 5х16', name: 'ООО Кабель', url: 'https://kabel.example/p', price: 1200, unit: 'м', region: 'Москва', phone: '+7' },
      { позиция: 'Кабель 5х16', name: 'Злой', url: 'javascript:alert(1)', price: 1 }
    ]
  }));
  const р = поставщикиПоЗакупкам(['0301100049626001767', '../../etc/passwd', '99999999999'], к);
  check(р.поставщики.length === 1 && р.поставщики[0].имя === 'ООО Кабель' && р.поставщики[0].телефон === '+7', 'поставщик из следа, телефон и регион на месте');
  check(!р.поставщики.some((с) => /javascript/.test(с.url)), 'ссылка не http(s) отброшена');
}

fs.rmSync(корень, { recursive: true, force: true });
console.log('');
if (failures) {
  console.log(`ПРОВЕРОК НЕ ПРОШЛО: ${failures}`);
  process.exit(1);
}
console.log('ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ');
