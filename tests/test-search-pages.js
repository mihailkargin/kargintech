/**
 * Листание выдачи ежедневного поиска (app/search-run.js, собратьВыдачу):
 * сколько страниц берётся и остановка на отказе портала. Портал подменён.
 * Запуск: node tests/test-search-pages.js
 */
const { собратьВыдачу, адресПоиска } = require('../app/search-run');

let failures = 0;
const check = (ok, m) => { console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${m}`); if (!ok) failures++; };

const now = new Date('2026-10-22T09:00:00Z');
const тело = 'x'.repeat(3000);
// Портал: по слову и номеру страницы - сколько карточек и с какой датой обновления.
function портал(страницы, коды = {}) {
  const адреса = [];
  return {
    адреса,
    взять: async (u) => {
      адреса.push(u);
      const слово = decodeURIComponent(/searchString=([^&]*)/.exec(u)[1]);
      const стр = Number(/pageNumber=(\d+)/.exec(u)[1]);
      const код = коды[`${слово}:${стр}`];
      if (код) return { ok: false, код };
      return { ok: true, код: 200, тело: JSON.stringify({ слово, стр }) + тело };
    },
    разобрать: (т) => {
      const { слово, стр } = JSON.parse(т.slice(0, т.indexOf('}') + 1));
      const [n, дата] = (страницы[слово] || [])[стр - 1] || [0, ''];
      return Array.from({ length: n }, (_, i) => ({ number: `${слово}-${стр}-${i}`, updated: дата }));
    }
  };
}
const оп = (п) => ({ взять: п.взять, разобрать: п.разобрать, now, вАрхив: false, хранилище: null });
const память = () => { const м = new Map(); return { м, взять: (к) => (м.has(к) ? JSON.parse(м.get(к)) : null), положить: (к, д) => м.set(к, JSON.stringify(д)) }; };
const общие = { паузаПоиска: 0 };

(async () => {
  console.log('\n=== Сколько страниц ===');
  check(/sortBy=UPDATE_DATE/.test(адресПоиска('бумага', {}, 1)) && /sortDirection=false/.test(адресПоиска('бумага', {}, 1)), 'сортировка по дате обновления задана явно');
  {
    const п = портал({ бумага: [[50, '2026-10-22'], [50, '2026-10-22'], [50, '2026-10-22'], [50, '2026-10-22']] });
    const r = await собратьВыдачу(['бумага'], {}, общие, оп(п));
    check(п.адреса.length === 3 && r.разобрано.length === 150, 'все страницы за сутки - не больше трёх');
  }
  {
    const п = портал({ бумага: [[50, '2026-10-22'], [50, '2026-10-20'], [50, '2026-10-19']] });
    await собратьВыдачу(['бумага'], {}, общие, оп(п));
    check(п.адреса.length === 2, 'на странице есть закупки старше суток - дальше не листаем');
  }
  {
    const п = портал({ бумага: [[50, '2026-10-19'], [50, '2026-10-18']] });
    await собратьВыдачу(['бумага'], {}, общие, оп(п));
    check(п.адреса.length === 1, 'первая страница уже старая - одна страница');
  }
  {
    const п = портал({ бумага: [[23, '2026-10-22'], [50, '2026-10-22']] });
    await собратьВыдачу(['бумага'], {}, общие, оп(п));
    check(п.адреса.length === 1, 'неполная страница - последняя');
  }
  {
    const п = портал({ бумага: [[50, ''], [50, ''], [50, '']] });
    await собратьВыдачу(['бумага'], {}, общие, оп(п));
    check(п.адреса.length === 2, 'дат обновления нет - как раньше, не дальше второй страницы');
  }

  console.log('\n=== Отказ портала ===');
  for (const код of [403, 429]) {
    const п = портал({ бумага: [[50, '2026-10-22']], кабель: [[10, '2026-10-22']], лампы: [[10, '2026-10-22']] }, { 'кабель:1': код });
    const журнал = [];
    const r = await собратьВыдачу(['бумага', 'кабель', 'лампы'], {}, общие, { ...оп(п), журнал });
    check(r.отказПортала === код && п.адреса.length === 3 && !п.адреса.some((u) => /%D0%BB%D0%B0%D0%BC%D0%BF/.test(u)),
      `код ${код}: следующие слова не запрашиваются`);
    check(r.разобрано.length === 50 && журнал.some((с) => /остановлен/.test(с)), `код ${код}: собранное до отказа сохраняется, причина в журнале`);
  }
  {
    const п = портал({ бумага: [[50, '2026-10-22']], кабель: [[10, '2026-10-22']] }, { 'бумага:1': 500 });
    const r = await собратьВыдачу(['бумага', 'кабель'], {}, общие, оп(п));
    check(!r.отказПортала && r.негодных === 1 && r.разобрано.length === 10, 'сбой 500 - не остановка, следующее слово запрашивается');
  }

  console.log('\n=== Общая выдача: несколько прогонов в день ===');
  {
    const х = память();
    // Утро: 2 страницы свежих, третья неполная.
    const п1 = портал({ бумага: [[50, '2026-10-22'], [50, '2026-10-22'], [20, '2026-10-22']] });
    const r1 = await собратьВыдачу(['бумага'], {}, общие, { ...оп(п1), хранилище: х });
    check(п1.адреса.length === 3 && r1.разобрано.length === 120, 'первый прогон: всё свежее');
    // Через 10 минут другой клиент с той же фразой - портал не трогаем.
    const п2 = портал({ бумага: [[50, '2026-10-22']] });
    const r2 = await собратьВыдачу(['Бумага '], {}, общие, { ...оп(п2), хранилище: х, now: new Date(now.getTime() + 10 * 60000) });
    check(п2.адреса.length === 0 && r2.разобрано.length === 120, 'та же фраза меньше 30 минут назад - без запросов, вся общая выдача');
    // Через 3 часа: сверху 30 новых, ниже - уже известные.
    const позже = new Date(now.getTime() + 3 * 3600000);
    const п3 = {
      адреса: [],
      взять: async (u) => { п3.адреса.push(u); return { ok: true, код: 200, тело: u.match(/pageNumber=(\d+)/)[1] + тело }; },
      разобрать: (т) => (т[0] === '1'
        ? [...Array.from({ length: 30 }, (_, i) => ({ number: `новая-${i}`, updated: '2026-10-22' })),
          ...Array.from({ length: 20 }, (_, i) => ({ number: `бумага-1-${i}`, updated: '2026-10-22' }))]
        : Array.from({ length: 50 }, (_, i) => ({ number: `бумага-2-${i}`, updated: '2026-10-22' })))
    };
    const r3 = await собратьВыдачу(['бумага'], {}, общие, { ...оп(п3), хранилище: х, now: позже });
    check(п3.адреса.length === 1, 'следующий прогон: дошли до известных на первой странице - одна страница');
    check(r3.разобрано.length === 150 && r3.разобрано.some((к) => к.number === 'новая-0') && r3.разобрано.some((к) => к.number === 'бумага-3-0'),
      'клиенту - новые и прежние за трое суток');
    // Через четыре дня утренние карточки уходят из общей выдачи.
    const п4 = портал({ бумага: [[5, '2026-10-26']] });
    const r4 = await собратьВыдачу(['бумага'], {}, общие, { ...оп(п4), хранилище: х, now: new Date(now.getTime() + 4 * 86400000) });
    check(r4.разобрано.length === 5, 'старше трёх суток - не держим');
    // Хвост: утром все 3 страницы свежие - остаток добирает следующий прогон.
    const х3 = память();
    const лента = Array.from({ length: 300 }, (_, i) => ({ number: `т${i}`, updated: '2026-10-22' })).concat(
      Array.from({ length: 50 }, (_, i) => ({ number: `с${i}`, updated: '2026-10-20' })));
    const сдвиг = (новых) => {
      const все = Array.from({ length: новых }, (_, i) => ({ number: `н${i}`, updated: '2026-10-22' })).concat(лента);
      const п = { адреса: [], взять: async (u) => { п.адреса.push(u); return { ok: true, код: 200, тело: u.match(/pageNumber=(\d+)/)[1] + '|' + тело }; },
        разобрать: (т) => { const с = Number(т.split('|')[0]); return все.slice((с - 1) * 50, с * 50); } };
      return п;
    };
    const у = сдвиг(0);
    await собратьВыдачу(['мебель'], {}, общие, { ...оп(у), хранилище: х3 });
    check(у.адреса.length === 3 && х3.взять('мебель').хвост === 150, 'утро: 3 свежие страницы - запомнено, что взято 150 сверху');
    const д = сдвиг(20);
    const rд = await собратьВыдачу(['мебель'], {}, общие, { ...оп(д), хранилище: х3, now: позже });
    const страницы = д.адреса.map((u) => Number(/pageNumber=(\d+)/.exec(u)[1]));
    check(страницы.join() === '1,4,5', 'днём: страница 1 с новыми, затем перескок за взятое (4, 5)');
    check(rд.разобрано.some((к) => к.number === 'н0') && rд.разобрано.some((к) => к.number === 'т200') && х3.взять('мебель').хвост === 250,
      'добраны и новые сверху, и закупки ниже 150-й; хвост сдвинулся');
    const в = сдвиг(20);
    await собратьВыдачу(['мебель'], {}, общие, { ...оп(в), хранилище: х3, now: new Date(позже.getTime() + 3 * 3600000) });
    check(х3.взять('мебель').хвост === 0 && х3.взять('мебель').карточки.some((к) => к.number === 'т299'), 'вечером: дошли до вчерашних - хвост закрыт, всё взято');

    // Отказ портала: общая выдача не помечается свежей.
    const х2 = память();
    х2.положить('кабель', { at: new Date(now.getTime() - 3600000).toISOString(), карточки: [{ number: 'к1', updated: '2026-10-22', seenAt: now.toISOString() }] });
    const п5 = портал({}, { 'кабель:1': 403 });
    const r5 = await собратьВыдачу(['кабель'], {}, общие, { ...оп(п5), хранилище: х2 });
    check(r5.отказПортала === 403 && r5.разобрано.length === 1 && Date.parse(х2.взять('кабель').at) < now.getTime(), 'отказ - прежняя выдача отдаётся, время запроса не обновлено');
  }

  console.log(failures ? `\nСБОЕВ: ${failures}` : '\nВСЕ ПРОВЕРКИ ПРОЙДЕНЫ');
  process.exit(failures ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
