/**
 * Проверки поиска поставщиков.
 *
 * Главное, что здесь проверяется, — защита от выдумок модели. Она никогда
 * не отвечает «не нашёл» охотно: она отвечает уверенно и выдаёт правдоподобное
 * название с правдоподобным телефоном. Клиент позвонит, попадёт не туда
 * и перестанет верить всему расчёту.
 *
 * Запуск: node tests/test-suppliers.js
 */
const {
  buildSupplierSearchRequest, parseSupplierResponse, toPriceRecords,
  похожеНаСсылку, ценаИз, НЕ_ИСТОЧНИКИ
} = require('../src/suppliers');
const { makePrice, resolvePosition, SOURCES } = require('../src/pricing');

let failures = 0;
const check = (ok, message) => {
  console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${message}`);
  if (!ok) failures++;
};
const section = (name) => console.log(`\n=== ${name} ===`);

// ------------------------------------------------------------ сборка запроса

section('Сборка запроса');
const req = buildSupplierSearchRequest(
  { name: 'Бумага А4 80 г/м2', quantity: 500, unit: 'упак' },
  { регион: 'Москва' }
);
check(req.ok === true, 'запрос собран');
check(req.request.model === 'claude-sonnet-5-5',
  `модель по умолчанию Sonnet, а не Opus — вдвое дешевле (${req.request.model})`);
// Имя параметра принимается в двух написаниях: вызывающий код передавал
// «модель», а читалось «model» — параметр не доходил, и подменить модель
// на пробу было невозможно. Сравнение моделей дало бы одинаковый результат
// и неверный вывод.
check(buildSupplierSearchRequest({ name: 'Бумага А4' }, { модель: 'claude-haiku-4-5' })
  .request.model === 'claude-haiku-4-5', 'модель можно задать русским именем параметра');
check(buildSupplierSearchRequest({ name: 'Бумага А4' }, { model: 'claude-haiku-4-5' })
  .request.model === 'claude-haiku-4-5', 'и латинским тоже');
check(req.request.tools[0].type === 'web_search_20260209', 'подключён веб-поиск');
check(typeof req.request.tools[0].max_uses === 'number',
  'число поисков ограничено — инструмент тарифицируется отдельно от токенов');

/**
 * ВЕСЬ ТЕКСТ ЗАПРОСА — и системная часть, и сообщение.
 *
 * С 07.10.2026 постоянная инструкция уехала в `system`, чтобы её можно было
 * кэшировать, а в сообщении остались только наименование, количество и регион.
 * Проверки, смотревшие только в `messages[0]`, на этом переносе сломались —
 * хотя сам запрос остался правильным.
 *
 * Поэтому смотрим обе части разом: проверка должна отвечать на вопрос
 * «ушло ли это в модель», а не «в каком поле оно лежит». Заодно это ловит
 * и утечку данных клиента в любую часть запроса, а не только в сообщение.
 */
const весьЗапрос = (r) => [
  ...(Array.isArray(r.request.system) ? r.request.system.map((b) => b.text || '') : [r.request.system || '']),
  ...r.request.messages.map((m) => (typeof m.content === 'string' ? m.content : JSON.stringify(m.content)))
].join('\n');

const текстЗапроса = весьЗапрос(req);
check(текстЗапроса.includes('Бумага А4 80 г/м2'), 'наименование передано');
check(текстЗапроса.includes('500 упак'), 'количество передано');
check(текстЗапроса.includes('Москва'), 'регион передан');
check(/price = null/.test(текстЗапроса) || /price":число или null/.test(текстЗапроса),
  'модели прямо разрешено ответить «цены нет»');
check(/Выдуманная цена хуже отсутствующей/.test(текстЗапроса),
  'сказано, почему выдумывать нельзя, а не просто «не выдумывай»');
check(/верни пустой список/.test(текстЗапроса), 'пустой ответ назван нормальным результатом');

