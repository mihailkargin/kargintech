function запрос(метод, путь, { форма = null, json = null, cookie = '', origin = true } = {}) {
  return new Promise((ok, нет) => {
    const тело = форма ? new URLSearchParams(форма).toString() : (json ? JSON.stringify(json) : '');
    const h = {};
    if (форма) h['Content-Type'] = 'application/x-www-form-urlencoded';
    if (json) h['Content-Type'] = 'application/json';
    if (тело) h['Content-Length'] = Buffer.byteLength(тело);
    if (cookie) h.Cookie = cookie;
    if (origin) h.Origin = `https://127.0.0.1:${порт}`;
    const req = http.request({ hostname: '127.0.0.1', port: порт, path: путь, method: метод, headers: h }, (res) => {
      const к = [];
      res.on('data', (c) => к.push(c));
      res.on('end', () => ok({ код: res.statusCode, з: res.headers, тело: Buffer.concat(к).toString('utf8') }));
    });
    req.on('error', нет);
    req.end(тело);
  });
}
