"""
Таблица без линий на скане (deploy/tables/borderless.py). Слова с
координатами собраны так, как их отдаёт `tesseract … tsv`.
Запуск: python -I tests/test_borderless.py
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'deploy', 'tables'))
import borderless  # noqa: E402

сбоев = 0


def check(ok, текст):
    global сбоев
    print(('  OK   ' if ok else '  СБОЙ ') + текст)
    if not ok:
        сбоев += 1


H = 30  # высота буквы при 300 точках на дюйм
счёт = [0]


def строка(y, куски, ключ=None):
    """куски: [(x, 'слова через пробел')] -> слова Tesseract с координатами."""
    счёт[0] += 1
    слова = []
    for x, текст in куски:
        for слово in текст.split():
            w = len(слово) * 16
            слова.append({'текст': слово, 'x': x, 'y': y, 'w': w, 'h': H, 'строка': ключ or ('1', '1', str(счёт[0]))})
            x += w + 10  # обычный пробел - треть буквы
    return слова


КОЛ = [100, 300, 1100, 1300, 1600]  # №, наименование, ед., количество, цена


def ряд(y, *ячейки):
    return строка(y, [(КОЛ[i], т) for i, т in enumerate(ячейки) if т])


print('\n=== Таблица без линий ===')
слова = []
слова += строка(40, [(100, 'Обоснование начальной (максимальной) цены контракта')])
слова += ряд(120, '№', 'Наименование товара', 'Ед.', 'Кол-во', 'Цена')
слова += ряд(180, '1', 'Бумага офисная А4 80 г/м2', 'пачка', '500', '330,00')
слова += ряд(240, '2', 'Папка-регистратор 75 мм', 'шт', '40', '215,50')
слова += ряд(282, '', 'с арочным механизмом')  # перенос наименования - строка ниже, плотно
слова += ряд(350, '3', 'Скобы для степлера №10', 'уп', '100', '25,00')
слова += строка(440, [(100, 'Итого по позициям указано в расчёте')])
текст = borderless.собрать(слова)
строки = текст.split('\n')
check(строки[0].startswith('Обоснование') and '\t' not in строки[0], 'текст над таблицей - обычной строкой')
check(строки[1].split('\t') == ['№', 'Наименование товара', 'Ед.', 'Кол-во', 'Цена'], 'шапка разложена по колонкам')
check(строки[2].split('\t') == ['1', 'Бумага офисная А4 80 г/м2', 'пачка', '500', '330,00'], 'строка товара разложена по колонкам')
check(строки[3].split('\t')[1] == 'Папка-регистратор 75 мм с арочным механизмом', 'перенос наименования приклеен к своей строке')
check(строки[3].split('\t')[3:] == ['40', '215,50'], 'количество и цена у перенесённой позиции на месте')
check(len([с for с in строки if '\t' in с]) == 4, 'строка переноса отдельной позицией не стала')
check(строки[-1].startswith('Итого по позициям'), 'текст под таблицей сохранён')

print('\n=== Отрицательные контроли ===')
абзац = []
for i, т in enumerate(['Поставщик обязан поставить товар в срок, установленный контрактом,',
                       'в соответствии с требованиями технического задания и нормами',
                       'законодательства Российской Федерации о контрактной системе.',
                       'Приёмка товара осуществляется заказчиком по месту поставки.']):
    абзац += строка(100 + i * 50, [(100, т)])
check(borderless.собрать(абзац) == '', 'обычный текст таблицей не считается')
две = []
for i in range(5):
    две += строка(100 + i * 50, [(100, 'Срок поставки'), (900, '10 дней')])
check(borderless.собрать(две) == '', 'две колонки «подпись - значение» таблицей не считаются')
check(borderless.собрать([]) == '', 'пустой лист - пусто')

print('\n=== Вывод tesseract tsv ===')
tsv = 'level\tpage_num\tblock_num\tpar_num\tline_num\tword_num\tleft\ttop\twidth\theight\tconf\ttext\n' \
      '5\t1\t1\t1\t1\t1\t100\t40\t80\t30\t91.5\tБумага\n' \
      '4\t1\t1\t1\t1\t0\t100\t40\t300\t30\t-1\t\n' \
      '5\t1\t1\t1\t1\t2\t300\t40\t40\t30\t88\t500\n'
с = borderless.слова_из_tsv(tsv)
check(len(с) == 2 and с[0]['текст'] == 'Бумага' and с[1]['x'] == 300 and с[0]['строка'] == с[1]['строка'], 'слова и их строка из tsv, служебные строки пропущены')

print('\nСБОЕВ: %d' % сбоев if сбоев else '\nВСЕ ПРОВЕРКИ ПРОЙДЕНЫ')
sys.exit(1 if сбоев else 0)
