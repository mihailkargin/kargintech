/**
 * Тесты: товар или работа (src/item-kind.js), 28.10.2026.
 * Запуск: node tests/test-item-kind.js
 * Наименования - из реальных закупок: кровля 32616502960, металл 32616503996.
 */
const { видПозиции, видЗакупки } = require('../src/item-kind');

let failures = 0;
function check(ok, label) {
  console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${label}`);
  if (!ok) failures++;
}
const вид = (name, unit, okpd) => видПозиции({ name, unit, okpd }).вид;

console.log('=== Работы из ведомости объёмов (кровля) ===');
for (const [имя, ед] of [
  ['Разборка покрытий кровель: из рулонных материалов', 'м2'],
  ['Укрытие зоны производства работ тентом тарпаулиновым', 'м2'],
  ['Устройство кровель плоских из наплавляемых материалов в два слоя', 'м2'],
  ['Монтаж планки прижимной по периметру вент. шахт', 'п.м.'],
  ['Огрунтовка грунтом глубокого проникновения парапетов', 'м2'],
  ['Герметизация стыков и мест примыкания поликарбоната', 'п.м.']
]) check(вид(имя, ед) === 'работа', `«${имя}» - работа`);

console.log('=== Товары (металл) ===');
for (const [имя, ед] of [
  ['Арматура А500С 8 мм ГОСТ Р 52544/34028', 'т'],
  ['Лист г/к 3х1250х2500 ст3', 'т'],
  ['Швеллер ст3 16П', ''],
  ['Бумага для офисной техники', 'пачка']
]) check(вид(имя, ед) === 'товар', `«${имя}» - товар`);

console.log('=== Ловушки ===');
check(вид('Установка ультрафиолетовая обеззараживающая', 'шт') === 'товар', '«Установка ультрафиолетовая» - оборудование, товар');
check(вид('Установка для дезинфекции воздуха', 'шт') === 'товар', '«Установка для…» - оборудование, товар');
check(вид('Установка кондиционера', 'шт') === 'работа', '«Установка кондиционера» - работа');
check(вид('Поставка и монтаж кондиционера', 'шт') === 'товар+работа', '«Поставка и монтаж» - одна позиция, товар+работа');
check(вид('Кондиционер настенный с установкой', 'шт') === 'товар+работа', '«…с установкой» - товар+работа');
check(вид('Поставка камер видеонаблюдения и их монтаж', 'шт') === 'товар+работа', 'поставка и монтаж с местоимением - одна смешанная позиция');
check(вид('Монтаж и поставка системы видеонаблюдения', 'шт') === 'товар+работа', 'монтаж перед поставкой - тоже смешанная позиция');
check(вид('Уборка помещений', 'м2') === 'работа', 'уборка - услуга');
check(вид('Охрана объекта', 'час') === 'работа', 'единица «час» - услуга');
check(вид('Пиломатериал обрезной', 'м3', '16.10.10.110') === 'товар', 'код ОКПД2 раздела 16 - товар');
check(вид('Работы по ремонту кровли', 'м2', '43.91.19.110') === 'работа', 'код ОКПД2 раздела 43 - работа');
check(вид('Изготовление мебели по размерам', 'шт') === 'товар', 'изготовление изделия для посредника - товар');
// Найдено на 2370 реальных позициях 28.10.2026.
check(вид('Подвеска провода СИП-2 напряжением от 0,4 кВ до 1 кВ на опорах', '') === 'работа', 'подвеска провода - работа');
check(вид('Оценка объекта арестованного имущества должника', '') === 'работа', 'оценка имущества - услуга');
check(вид('Запасные частей, специальные жидкости и расходные материалы', 'Усл. ед.') === 'товар', '«усл. ед.» сама по себе работу не означает');

console.log('=== Вид закупки ===');
check(видЗакупки({ object: 'Поставка металла' }) === 'товары', 'поставка металла - товары');
check(видЗакупки({ object: 'Выполнение работ по ремонту аварийной кровли' }) === 'работы и услуги', 'ремонт кровли - работы');
check(видЗакупки({ object: 'x', группыОкпд2: ['43.91', '24.10'] }) === 'товары и работы', 'коды разных разделов - товары и работы');
check(видЗакупки({ object: 'x' }, [{ name: 'Арматура', unit: 'т' }, { name: 'Монтаж арматуры', unit: 'т' }]) === 'товары и работы',
  'по позициям: арматура и монтаж - товары и работы');

console.log(`\n${failures === 0 ? 'ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ' : 'ПРОВАЛЕНО ПРОВЕРОК: ' + failures}`);
process.exit(failures === 0 ? 0 : 1);
