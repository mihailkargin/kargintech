/**
 * Объём услуги из ТЗ (src/service-volume.js): площадь, часы, м³, срок, цена
 * заказчика за единицу объёма в месяц. Строки уборки - дословно из
 * 0372100001926000241, остальные придуманы мной.
 * Запуск: node tests/test-service-volume.js
 */
const { объёмУслуги, срокМесяцев, ценаЗаказчикаЗаОбъём, текстОбъёма } = require('../src/service-volume');

let failures = 0;
const check = (ok, m) => { console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${m}`); if (!ok) failures++; };

console.log('\n=== Уборка ===');
{
  const тз = [
    '2.2. Ежедневная комплексная уборка внутренних помещений осуществляется согласно перечню площадей, приведенных в настоящем Техническом задании.',
    ' \tПлощадь убираемых помещений – 5 429,98 кв. м.',
    'Срок оказания услуг: с 01.01.2027 по 31.12.2027 г.'
  ].join('\n');
  const о = объёмУслуги(тз);
  check(о && о.однозначно && о.значение === 5429.98 && о.ед === 'м²', `площадь 5 429,98 м² (получено ${о && о.значение})`);
  check(/Площадь убираемых помещений/.test(о.цитата), 'с дословной цитатой строки ТЗ');
  const с = срокМесяцев(тз);
  check(с && с.месяцев === 12, `срок с 01.01.2027 по 31.12.2027 - 12 мес. (получено ${с && с.месяцев})`);
  const р = ценаЗаказчикаЗаОбъём(тз, 21768520.73);
  check(р.заЕдиницуВМесяц === Math.round(21768520.73 / 5429.98 / 12 * 100) / 100, `заказчик платит ${р.заЕдиницуВМесяц} ₽ за м² в месяц`);
  const т = текстОбъёма(р);
  check(/за м² в месяц/.test(т) && !/null|NaN|undefined/.test(т), 'текст для клиента без null/NaN');
}

console.log('\n=== Итог среди многих площадей ===');
{
  const тз = 'Кабинет 101 площадью 20 м2 (уборка ежедневно)\nКабинет 102 площадью 35 м2 (уборка ежедневно)\nОбщая площадь убираемых помещений: 1 200 м2\nв течение 6 (шести) месяцев';
  const о = объёмУслуги(тз);
  check(о.однозначно && о.значение === 1200, 'из нескольких площадей берётся строка «общая площадь»');
  check(срокМесяцев(тз).месяцев === 6, '«в течение 6 (шести) месяцев» - 6');
}

console.log('\n=== Охрана и вывоз ===');
{
  check(объёмУслуги('Количество постов: 1 пост, 8 784 часов охраны в год').значение === 8784, 'охрана: 8 784 часов');
  check(объёмУслуги('Объем вывоза твердых коммунальных отходов - 1 500 куб. м').значение === 1500, 'вывоз ТКО: 1 500 куб. м');
}

{
  // Дословно из 32616485839: всё ТЗ - один огромный абзац, площадь «м.кв.».
  const тз = 'Наименование объекта: здание. ' + 'Текст требований. '.repeat(60)
    + 'Площадь охраняемого объекта:   1600 м.кв. Характеристики оказываемых услуг:      В соответствии с Федеральный закон от 30.11.2024 № 427-ФЗ «О частной охранной деятельности». '
    + 'Обеспечение внутриобъектового и пропускного режима. '.repeat(40);
  const о = объёмУслуги(тз);
  check(о && о.значение === 1600 && о.ед === 'м²', `«1600 м.кв.» внутри огромного абзаца (получено ${о && о.значение})`);
  const { видыДляУслуги, ценаЗаказчикаЗаОбъём: цена } = require('../src/service-volume');
  check(цена(тз, 3387229.2, 'Оказание услуг по физической охране объекта') === null, 'для охраны площадь не объём: часов в ТЗ нет - цены за м² нет');
  check(видыДляУслуги('Услуги по погрузке и вывозу снега').join() === 'объём' && видыДляУслуги('Оказание услуг по уборке помещений').join() === 'площадь',
    'вывоз - м³, уборка - площадь');
}

console.log('\n=== Перевозки: пробег по маршрутам складывается ===');
{
  // Дословно из 0116300000126001143 (3 маршрута из 7).
  const тз = [
    '1\tКоличество рейсов на срок контракта\t1 134',
    '2\tПробег автобуса на срок контракта\t13 977\tкм',
    '4.\tХарактеристика услуг\t\tПеревозка пассажиров и багажа по маршруту №11. Протяженность маршрута – 23,53 км. Остановочные пункты',
    '1\tКоличество рейсов на срок контракта\t1 530',
    '2\tПробег автобуса на срок контракта\t31 956\tкм',
    '1\tКоличество рейсов на срок контракта\t894',
    '2\tПробег автобуса на срок контракта\t33 566\tкм'
  ].join('\n');
  const { видыДляУслуги: виды, ценаЗаказчикаЗаОбъём: цена, текстОбъёма: текст } = require('../src/service-volume');
  const о = объёмУслуги(тз, виды('Обеспечение деятельности по перевозке пассажиров по пригородным маршрутам'));
  check(о && о.однозначно && о.ед === 'км' && о.значение === 13977 + 31956 + 33566 && о.слагаемых === 3,
    `пробег по трём маршрутам сложен: ${о && о.значение} км (протяжённость маршрута 23,53 км не взята)`);
  const р = цена(тз, 15705094.76, 'Обеспечение деятельности по перевозке пассажиров');
  check(р.заЕдиницуВМесяц === null && р.заЕдиницуЗаСрок === Math.round(15705094.76 / 79499 * 100) / 100, 'цена заказчика за км - на весь срок, не в месяц');
  check(/за км/.test(текст(р)) && !/null|NaN/.test(текст(р)), 'текст: «за км», без null');
  const рейсы = объёмУслуги(тз, ['рейсы']);
  check(рейсы && рейсы.значение === 1134 + 1530 + 894, `рейсы сложены: ${рейсы && рейсы.значение}`);
  const дважды = объёмУслуги(тз + '\n' + тз, ['пробег']);
  check(дважды.значение === 79499, `две редакции одного ТЗ - сумма не удваивается (${дважды.значение})`);
}

console.log('\n=== Отрицательные контроли ===');
{
  const тз = 'Площадь здания А - 1 000 м2, уборка ежедневно\nПлощадь здания Б - 2 500 м2, уборка ежедневно';
  const р = ценаЗаказчикаЗаОбъём(тз, 1000000);
  check(!р.объём.однозначно && р.заЕдиницуВМесяц === null, 'две разные площади без итога - объём не выбирается, цены нет');
  check(/несколькими значениями/.test(текстОбъёма(р)), 'и это сказано клиенту');
  check(ценаЗаказчикаЗаОбъём('Поставка бумаги офисной А4, 500 пачек', 100000) === null, 'у товара объёма услуги нет');
  check(объёмУслуги('Размер листа 210х297 мм, плотность 80 г/м2') === null, '«г/м2» плотности бумаги - не площадь');
  check(объёмУслуги('Уборка помещений: средство расходуется 50 мл/м2, площадь помещений 300 м2').значение === 300, '«50 мл/м2» в строке про помещения - не площадь, площадь 300');
}

console.log(failures ? `\nСБОЕВ: ${failures}` : '\nВСЕ ПРОВЕРКИ ПРОЙДЕНЫ');
process.exit(failures ? 1 : 0);
