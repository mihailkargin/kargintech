/**
 * Тесты разбора адреса запроса.
 * Запуск: node tests/test-routes.js
 *
 * ЗАЧЕМ ЭТОТ НАБОР СУЩЕСТВУЕТ. 09.10.2026 выяснилось, что точки входа
 * `/смета` и `/поиск` не отвечали НИКОГДА: `new URL(...).pathname` возвращает
 * путь в закодированном виде, и сравнение с кириллической строкой не совпадает
 * ни при каких условиях. Проба вызывает расчёт напрямую, минуя сеть, поэтому
 * дыра дожила до первого живого запроса из n8n.
 *
 * Здесь закреплено то, что должно работать: оба написания адреса, кодирование
 * процентами, параметры в адресе, завершающая косая черта и битое кодирование.
 */
const { нормальныйПуть, маршрут, ТОЧКИ, ПЕРЕЧЕНЬ } = require('../app/routes');

let failures = 0;
const check = (ok, message) => {
  console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${message}`);
  if (!ok) failures++;
};
const section = (name) => console.log(`\n=== ${name} ===`);

section('ГЛАВНОЕ: закодированный кириллический путь совпадает');
// Ровно тот случай, из-за которого ничего не работало.
check(маршрут('/%D1%81%D0%BC%D0%B5%D1%82%D0%B0') === ТОЧКИ.СМЕТА,
  'закодированная «/смета» ведёт к смете');
check(маршрут('/%D0%BF%D0%BE%D0%B8%D1%81%D0%BA') === ТОЧКИ.ПОИСК,
  'закодированный «/поиск» ведёт к поиску');
check(маршрут(encodeURI('/смета')) === ТОЧКИ.СМЕТА,
  'путь, закодированный стандартной функцией, тоже совпадает');

section('Латинские имена — основные, они стоят в воркфлоу');
check(маршрут('/estimate') === ТОЧКИ.СМЕТА, '/estimate');
check(маршрут('/search') === ТОЧКИ.ПОИСК, '/search');
check(маршрут('/health') === ТОЧКИ.ЗДОРОВЬЕ, '/health');

section('Кириллические имена остались рабочими');
check(маршрут('/смета') === ТОЧКИ.СМЕТА, '/смета');
check(маршрут('/поиск') === ТОЧКИ.ПОИСК, '/поиск');
check(маршрут('/здоровье') === ТОЧКИ.ЗДОРОВЬЕ, '/здоровье');

section('Параметры и косая черта не мешают');
check(маршрут('/estimate?клиент=kargin') === ТОЧКИ.СМЕТА, 'параметры отрезаются');
check(маршрут('/estimate/') === ТОЧКИ.СМЕТА, 'завершающая косая черта отрезается');
check(маршрут('/health#якорь') === ТОЧКИ.ЗДОРОВЬЕ, 'якорь отрезается');
check(нормальныйПуть('/') === '/', 'корень остаётся корнем, а не пустой строкой');

section('Чужое и битое не роняет разбор');
check(маршрут('/wp-login.php') === null, 'посторонний адрес — отказ');
check(маршрут('') === null, 'пустой адрес — отказ');
check(маршрут(undefined) === null, 'отсутствующий адрес — отказ');

// Одиночный процент ломает раскодирование. Сканеры присылают такое постоянно,
// и обработчик не должен на этом падать.
let упало = false;
let битый = null;
try { битый = маршрут('/%'); } catch (e) { упало = true; }
check(!упало, 'БИТОЕ КОДИРОВАНИЕ НЕ РОНЯЕТ РАЗБОР — сканеры присылают такое постоянно');
check(битый === null, 'и даёт честный отказ');

let упало2 = false;
try { нормальныйПуть('/%E0%A4%A'); } catch (e) { упало2 = true; }
check(!упало2, 'оборванная последовательность процентов тоже не роняет');

section('Перечень точек входа годится для сообщения об отказе');
check(/estimate/.test(ПЕРЕЧЕНЬ) && /search/.test(ПЕРЕЧЕНЬ) && /health/.test(ПЕРЕЧЕНЬ),
  'в перечне названы все три точки входа');

section('Проверка умеет не проходить');
// У проверки обязан быть исход, при котором она не проходит — правило проекта.
check(маршрут('/смета') !== ТОЧКИ.ПОИСК, 'смета не путается с поиском');
check(маршрут('/сметa') === null,
  'похожий адрес с латинской «a» в конце НЕ совпадает — опечатка не проходит молча');

console.log('');
if (failures) {
  console.log(`ПРОВЕРОК НЕ ПРОШЛО: ${failures}`);
  process.exit(1);
}
console.log('ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ');
