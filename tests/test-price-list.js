/**
 * Тесты разбора прайс-листа клиента и сопоставления позиций.
 * Запуск: node tests/test-price-list.js
 *
 * ЧТО ЗДЕСЬ ГЛАВНОЕ. Прайс клиента — единственный источник, который отвечает на
 * вопрос «почём Я куплю», а не «почём это продают заказчику». Поэтому цена
 * отсюда идёт в себестоимость напрямую, и ошибка в сопоставлении уходит прямо
 * в вывод «идти / не идти». Проверяется не то, что модуль «работает», а то, что
 * он ОТКАЗЫВАЕТСЯ работать молча:
 *
 *   — не найденная позиция остаётся не найденной, а не получает цену соседней;
 *   — порченная Excel-ем цена не берётся, а называется порченой;
 *   — пропавший столбец отвергает файл целиком, а не подменяется соседним;
 *   — числа в наименовании обязаны совпасть: «80 г/м²» и «100 г/м²» — разные
 *     товары с разной ценой, и перепутать их значит собрать правдоподобную
 *     смету не на тот товар.
 *
 * Книга Excel для проверок собирается здесь же, нашим же `writeXlsx`, и
 * читается обратно разбором. Двоичный образец в проекте не хранится: формат мы
 * и пишем, и читаем сами, поэтому сквозная проверка честнее файла-слепка.
 */
