/**
 * Тесты: расчёт по загруженным документам (владелец 31.10.2026, ООО «ЭКОПАК» -
 * коммерческие закупки на Сбербанк-АСТ). Весь расчёт без портала и без сети:
 * файл Excel собирается здесь, поиск поставщиков выключен.
 * Запуск: node tests/test-upload-calc.js
 */
const os = require('os');
const fs = require('fs');
const path = require('path');
process.env.STATE_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'upl-'));
const { writeXlsx } = require('../src/xlsx-write');
const { собратьСмету } = require('../app/estimate-run');
const { файлЗагрузки } = require('../src/docs-page');

let failures = 0;
function check(ok, label) {
  console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${label}`);
  if (!ok) failures++;
}

console.log('=== Файл из загрузки - как файл портала ===');
const ф = файлЗагрузки('Обоснование НМЦК.xlsx', Buffer.from('x'));
check(ф.kind === 'обоснование НМЦК' && ф.ext === 'xlsx' && ф.данные.length === 1, 'назначение по имени, расширение, данные в памяти');
check(файлЗагрузки('Документация.zip', Buffer.from('x')).isArchive, 'архив опознан');
check(!файлЗагрузки('фото ТЗ.jpg', Buffer.from('x')).isImage, 'фото документа не пропускается - пойдёт в распознавание');

const книга = writeXlsx([{ name: 'НМЦК', rows: [
  ['№', 'Наименование', 'Ед. изм.', 'Кол-во', 'Цена 1', 'Цена 2', 'Цена 3'],
  [1, 'Пакет фасовочный ПНД 24х37 см', 'шт', 10000, 1.2, 1.35, 1.4],
  [2, 'Пакет-майка ПНД 30х55 см', 'шт', 5000, 2.1, 2.3, 2.25]
] }]);

(async () => {
  console.log('=== Весь расчёт по документам, без портала ===');
  const настройки = { искатьПоставщиков: false, адресКонвертера: 'http://127.0.0.1:9', economics: { taxRate: 0.06 } };
  const r = await собратьСмету({
    файлы: [{ имя: 'Обоснование НМЦК.xlsx', данные: книга }],
    номер: 'D-1', объект: 'Поставка пакетов', заказчик: 'ООО «Покупатель»', нмцк: 25000,
    срокПодачи: '2026-11-10', площадка: 'Сбербанк-АСТ', способ: 'запрос предложений',
    обеспечениеЗаявки: 0, обеспечениеКонтракта: 5
  }, настройки);
  if (!r.ok) console.log('   сбой:', r.сбой, r.подробно, '\n   ' + (r.журнал || []).slice(-8).join('\n   '));
  check(r.ok, 'расчёт готов без карточки и страницы документов портала');
  check(r.ok && r.estimate.rows.length === 2, `позиции из загруженного Excel: ${r.ok ? r.estimate.rows.length : 0} из 2`);
  check(r.ok && r.номер === 'D-1' && r.итоги.нмцк === 25000, 'номер и НМЦК - из того, что вписал клиент');
  check(r.ok && /Сбербанк-АСТ/.test(r.журнал.join('\n')), 'площадка названа в журнале');
  check(r.ok && r.итоги.обеспечениеЗаявки === 0, `обеспечение заявки «0» - не требуется (${r.ok ? r.итоги.обеспечениеЗаявки : '-'})`);
  check(r.ok && Math.abs(r.итоги.обеспечениеКонтракта - 1250) < 1, `обеспечение контракта 5% от 25 000 = 1 250 (${r.ok ? r.итоги.обеспечениеКонтракта : '-'})`);
  check(r.ok && r.файл && r.файл.данные.length > 1000, 'файл Excel расчёта собран');
  check(r.ok && /1,20 ₽\/шт — 1,40 ₽\/шт/.test(r.подпись) && /— 1,35 ₽/.test(r.подпись), 'дешёвые позиции - с копейками: 1,20-1,40 ₽/шт, источники 1,35 ₽');

  const безЦены = await собратьСмету({ файлы: [{ имя: 'ТЗ.xlsx', данные: книга }], номер: 'D-2', объект: 'x' }, настройки);
  check(!безЦены.ok && /начальная цена/.test(безЦены.сбой), 'без НМЦК - отказ с причиной, а не расчёт от нуля');
  const безФайлов = await собратьСмету({ файлы: [], номер: 'D-3', нмцк: 1000 }, настройки);
  check(!безФайлов.ok, 'без файлов и без ссылки - отказ');

  fs.rmSync(process.env.STATE_DIR, { recursive: true, force: true });
  console.log(failures ? `\nСБОЕВ: ${failures}` : '\nВсе проверки прошли');
  process.exit(failures ? 1 : 0);
})().catch((e) => { console.log(e.stack); process.exit(1); });
