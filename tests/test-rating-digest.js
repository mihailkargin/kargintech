/**
 * Сообщение с рейтингом и файл со списком. Запуск: node tests/test-rating-digest.js
 *
 * Разборы собраны в том виде, в каком их пишет app/parse-queue.js (итогРазбора).
 * Числа круглые, чтобы пересчитать в уме.
 */
const { оценитьРазборы, сообщениеРейтинга, файлРейтинга } = require('../src/rating-digest');
const { readXlsxRows } = (() => {
  const et = require('../src/extract-text');
  return { readXlsxRows: et.xlsxRows };
})();

let failures = 0;
const check = (ok, message) => {
  console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${message}`);
  if (!ok) failures++;
};
const section = (name) => console.log(`\n=== ${name} ===`);

const АУК = 'электронный аукцион';
// Падение у похожих 10/15/20% → цена победы 800 000 при НМЦК 1 000 000.
const наблюдения = [10, 15, 20].map((с) => ({ снижение: с, нмцк: 1000000, способ: АУК, номер: 'П' + с, группаОкпд2: '17.12' }));
const тендер = (номер, extra = {}) => ({ number: номер, object: 'Поставка бумаги ' + номер, price: 1000000,
  law: '44-ФЗ Электронный аукцион', url: 'https://zakupki.gov.ru/x?' + номер, deadline: '2026-10-30T10:00:00', okpdGroup: '17.12', ...extra });
const разбор = (номер, закупка, extra = {}) => ({ ок: true, тендер: тендер(номер), позиций: 2, сЗакупочнойЦеной: 2,
  закупка, группыОкпд2: [], годен: true, ...extra });
const клиент = { economics: { taxRate: 0.06, logisticsMaxPct: 5, otherCosts: 0 } };

section('Оценка и порядок');
const разборы = {
  'Дешёвый': разбор('Дешёвый', 500000),        // прибыль 800 000 − 500 000 − 25 000 − 48 000 = 227 000, 28,4% → 5
  'Средний': разбор('Средний', 620000),        // 800 000 − 620 000 − 31 000 − 48 000 = 101 000, 12,6% → 4
  'Убыток': разбор('Убыток', 760000),          // 800 000 − 760 000 − 38 000 − 48 000 = −46 000 → 1
  'БезПрайса': разбор('БезПрайса', null, { сЗакупочнойЦеной: 0 }),
  'ЗаЕдиницу': разбор('ЗаЕдиницу', null, { ценаЗаЕдиницу: true }),
  'Отменена': { ок: false, отменена: true, тендер: тендер('Отменена') },
  'Чужой': разбор('Чужой', 500000, { фильтрПоТЗ: { прошёл: false, причины: ['стоп-слово'] } }),
  'НеРазобран': { ок: false, сбой: 'карточка не открылась', тендер: тендер('НеРазобран') }
};
const оц = оценитьРазборы(разборы, наблюдения, клиент);
const по = Object.fromEntries(оц.map((x) => [x.номер, x.оценка]));
check(по['Дешёвый'].звёзды === 5 && по['Дешёвый'].прибыль === 227000, `5 звёзд, прибыль 227 000 (${по['Дешёвый'].звёзды}, ${по['Дешёвый'].прибыль})`);
check(по['Средний'].звёзды === 4, `рентабельность 12,6% — 4 звезды (${по['Средний'].звёзды})`);
check(по['Убыток'].звёзды === 1 && по['Убыток'].прибыль < 0, 'убыток — одна звезда, прибыль отрицательная');
check(оц[0].номер === 'Дешёвый' && оц[1].номер === 'Средний' && оц[2].номер === 'Убыток', 'порядок по убыванию выгоды');
check(!('Отменена' in по) && !('Чужой' in по), 'отменённая и отсеянная стоп-словами по ТЗ не показываются');
check(по['БезПрайса'].звёзды === null && /прайс/.test(по['БезПрайса'].почему), 'без прайса — без звёзд, причина названа');
// Живой случай 19.10.2026: сумма по потолкам НМЦК есть, закупочных цен ноль.
const потолки = оценитьРазборы({ 'П': разбор('П', 900000, { сЗакупочнойЦеной: 0 }) }, наблюдения, клиент);
check(/нужен прайс/.test(потолки[0].оценка.почему), `сумма по потолкам НМЦК без прайса — «нужен прайс» (${потолки[0].оценка.почему})`);
check(по['ЗаЕдиницу'].звёзды === null && /цене за единицу/.test(по['ЗаЕдиницу'].почему), 'цена за единицу — без звёзд');
check(по['НеРазобран'].звёзды === null && /не разобрана/.test(по['НеРазобран'].почему), 'неразобранная — без звёзд, не ноль');

section('Налог и доставка не выдумываются');
const безНалога = оценитьРазборы({ 'А': разбор('А', 500000) }, наблюдения, { economics: { logisticsMaxPct: 5 } });
check(безНалога[0].оценка.звёзды === null && /налог/.test(безНалога[0].оценка.почему), 'налог не задан — звёзд нет, а не 6% по умолчанию');
const безДоставки = оценитьРазборы({ 'А': разбор('А', 500000) }, наблюдения, { economics: { taxRate: 0.06 } });
check(безДоставки[0].оценка.звёзды === null && /доставк/.test(безДоставки[0].оценка.почему), 'доставка не задана — звёзд нет');
const сПрочими = оценитьРазборы({ 'А': разбор('А', 500000) }, наблюдения, { economics: { ...клиент.economics, otherCosts: 10000 } });
// Прочие входят в закупку: 510 000 → доставка 25 500, прибыль 800 000 − 510 000 − 25 500 − 48 000 = 216 500.
check(сПрочими[0].оценка.прибыль === 216500, `прочие расходы на контракт вычтены (${сПрочими[0].оценка.прибыль})`);

section('ОКПД2: чужой товар не сравнивается');
const картриджи = оценитьРазборы({ 'К': разбор('К', 500000, { тендер: тендер('К', { okpdGroup: '20.59' }) }) }, наблюдения, клиент);
check(картриджи[0].оценка.звёзды === null && /похожих прошлых закупок 0/.test(картриджи[0].оценка.почему),
  'прошлые закупки бумаги не дают звёзд закупке другого товара');

section('Сообщение');
const с = сообщениеРейтинга(оц);
check(с.parseMode === 'HTML' && с.text.length <= 4096, `HTML, не длиннее предела (${с.text.length})`);
check(с.text.indexOf('Поставка бумаги Дешёвый') < с.text.indexOf('Поставка бумаги Средний'), 'выгоднее — выше');
check(/<blockquote>[^]*Дешёвый/.test(с.text), 'группа 5 звёзд развёрнута');
check(/<blockquote expandable>[^]*Убыток/.test(с.text), 'группа 1 звезды свёрнута');
// Правило владельца 25.10.2026: в Telegram только тендеры с вилкой прибыли.
check(!/Без оценки/.test(с.text) && !/Поставка бумаги БезПрайса/.test(с.text)
  && !/Поставка бумаги НеРазобран/.test(с.text), 'тендеры без оценки в сообщение не идут');
check(!/null|NaN|undefined/.test(с.text), 'в тексте нет null, NaN, undefined');
check(/прибыль от 227 000 ₽ до 274 000 ₽ \(от 28,4% до 32,2%\)/.test(с.text), 'вилка прибыли и рентабельности напечатана');
const откр = (с.text.match(/<blockquote/g) || []).length;
const закр = (с.text.match(/<\/blockquote>/g) || []).length;
check(откр === закр, `теги цитат закрыты (${откр}/${закр})`);

section('Длинный список не превышает предел Telegram');
const много = {};
for (let i = 0; i < 300; i++) много['Т' + i] = разбор('Т' + i, 400000 + i * 1000);
const длинное = сообщениеРейтинга(оценитьРазборы(много, наблюдения, клиент));
const о2 = (длинное.text.match(/<blockquote/g) || []).length;
const з2 = (длинное.text.match(/<\/blockquote>/g) || []).length;
check(длинное.text.length <= 4096 && о2 === з2, `300 тендеров: ${длинное.text.length} знаков, теги закрыты`);
check(/в файле/.test(длинное.text), 'не вошедшие отправлены в файл');

section('Файл');
const ф = файлРейтинга(оц, new Date('2026-10-19T10:00:00Z'));
check(ф.fileName === 'Рейтинг тендеров 2026-10-19.xlsx', `имя файла (${ф.fileName})`);
const строки = readXlsxRows ? readXlsxRows(ф.buffer) : null;
const лист = строки && (строки.rows || строки[0] && строки[0].rows || строки);
const текст = JSON.stringify(лист || '');
check(/Дешёвый/.test(текст) && /НеРазобран/.test(текст) && /БезПрайса/.test(текст),
  'в файле все тендеры — и с оценкой, и без');

console.log(failures ? `\nПРОВАЛЕНО ПРОВЕРОК: ${failures}` : '\nВСЕ ПРОВЕРКИ ПРОЙДЕНЫ');
process.exit(failures ? 1 : 0);
