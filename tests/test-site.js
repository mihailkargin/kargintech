function запрос(метод, путь, { форма = null, cookie = '', origin = true, заголовки = {} } = {}) {
  return new Promise((ok, нет) => {
    const тело = форма ? new URLSearchParams(форма).toString() : '';
    const h = { ...заголовки };
    if (форма) { h['Content-Type'] = 'application/x-www-form-urlencoded'; h['Content-Length'] = Buffer.byteLength(тело); }
    if (cookie) h.Cookie = cookie;
    if (origin === true) h.Origin = `https://127.0.0.1:${порт}`;
    else if (origin) h.Origin = origin;
    const req = http.request({ hostname: '127.0.0.1', port: порт, path: путь, method: метод, headers: h }, (res) => {
      const к = [];
      res.on('data', (c) => к.push(c));
      res.on('end', () => ok({ код: res.statusCode, з: res.headers, тело: Buffer.concat(к).toString('utf8'), буфер: Buffer.concat(к) }));
    });
    req.on('error', нет);
    req.end(тело);
  });
}
