/**
 * Тесты чтения PDF языковой моделью.
 * Запуск: node tests/test-pdf-extract.js
 *
 * ЧТО ЗДЕСЬ ГЛАВНОЕ. Модель читает PDF и отдаёт таблицу текстом; позиции из
 * этого текста извлекает наш собственный разбор. Проверяется стык: что запрос
 * собран правильно, что ответ проверен перед употреблением, и что текст,
 * пришедший от модели, действительно разбирается `parseNmckTable`.
 *
 * Отдельно проверяется обрыв ответа по пределу вывода. Это самая опасная
 * ошибка здесь: таблица обрывается на середине, разбор отрабатывает и даёт
 * позиции — просто не все. Смета собирается, сумма выглядит правдоподобной
 * и заниженной, клиент видит несуществующий запас по цене.
 */
const {
  buildPdfTableRequest, parsePdfTableResponse, ПРЕДЕЛ_БАЙТ, НЕТ_ТАБЛИЦЫ
} = require('../src/pdf-extract');
const { parseNmckTable } = require('../src/nmck-table');

let failures = 0;
const check = (ok, message) => {
  console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${message}`);
  if (!ok) failures++;
};
const section = (name) => console.log(`\n=== ${name} ===`);

/** Минимальный буфер, который выглядит как PDF. */
const пдф = (размер = 2000) => {
  const b = Buffer.alloc(размер, 0x20);
  b.write('%PDF-1.7', 0, 'latin1');
  return b;
};

// ------------------------------------------------------------- сборка запроса

section('Запрос собирается только из настоящего PDF');

const пустой = buildPdfTableRequest('а.pdf', Buffer.alloc(0));
check(!пустой.ok, 'пустой файл отвергнут');
check(/пустой/.test(пустой.issue), 'причина названа');

const неПдф = buildPdfTableRequest('а.pdf', Buffer.from('PK\u0003\u0004 это zip'));
check(!неПдф.ok, 'ФАЙЛ С РАСШИРЕНИЕМ .pdf, НО НЕ PDF — отвергнут');
check(/не является PDF/.test(неПдф.issue),
  'сказано прямо: расширение врёт, платить за отказ API незачем');

const огромный = buildPdfTableRequest('а.pdf', пдф(ПРЕДЕЛ_БАЙТ + 1024));
check(!огромный.ok, 'файл больше предела отвергнут ДО отправки');
check(/МБ/.test(огромный.issue) && /20 МБ/.test(огромный.issue),
  'назван и размер файла, и предел — иначе причина непонятна');

const годный = buildPdfTableRequest('Обоснование НМЦК.pdf', пдф());
check(годный.ok, 'настоящий PDF принят');

section('Устройство запроса');
const r = годный.request;
check(r.model === 'claude-sonnet-5-5', 'модель Sonnet: задача чтения, не рассуждения');
check(typeof r.max_tokens === 'number' && r.max_tokens > 0, 'предел вывода задан');

const содержимое = r.messages[0].content;
check(содержимое[0].type === 'document', 'ДОКУМЕНТ СТОИТ ПЕРВЫМ — этого требует формат запроса');
check(содержимое[0].source.media_type === 'application/pdf', 'тип указан как PDF');
check(содержимое[0].source.type === 'base64', 'файл передаётся как base64');
check(содержимое[0].source.data.indexOf('\n') === -1,
  'В BASE64 НЕТ ПЕРЕВОДОВ СТРОК — с ними API отвергает данные');
check(содержимое[1].type === 'text' && /Обоснование НМЦК\.pdf/.test(содержимое[1].text),
  'имя файла передано — по нему человек поймёт, что именно читали');

section('Кэширование постоянной части');
check(Array.isArray(r.system) && r.system[0].cache_control,
  'инструкция вынесена в system и помечена к кэшированию');
check(r.cache_control && r.cache_control.type === 'ephemeral',
  'пометка стоит и на запросе целиком');
check(/ТОЛЬКО таблицу/.test(r.system[0].text), 'в инструкции требование отдать только таблицу');
check(/табуляции/.test(r.system[0].text), 'и разделять ячейки табуляцией');
check(/не придумывай|Не придумывай/i.test(r.system[0].text), 'и запрет придумывать строки');

// ------------------------------------------------------------- разбор ответа

section('Пустой и отказной ответ');

check(!parsePdfTableResponse('').ok, 'пустая строка — отказ');
check(/пустой ответ/.test(parsePdfTableResponse({ content: [] }).issue),
  'ответ без текстовых блоков назван пустым');

const отказ = parsePdfTableResponse({ stop_reason: 'refusal', stop_details: { explanation: 'политика' } });
check(!отказ.ok, 'отказ модели распознан');
check(/отказалась/.test(отказ.issue) && /политика/.test(отказ.issue),
  'назван и факт отказа, и пояснение');

section('«Таблицы нет» — честный исход, а не сбой');
const нет = parsePdfTableResponse(НЕТ_ТАБЛИЦЫ);
check(!нет.ok, 'таблицы нет — результат не годится для расчёта');
check(нет.нетТаблицы === true, 'помечено отдельным признаком');
check(/нет таблицы с позициями/.test(нет.issue), 'причина читается человеком');

section('ОТВЕТ БЕЗ ТАБУЛЯЦИЙ — таблицу разобрать нечем');
const безТаб = parsePdfTableResponse('Наименование Количество Цена\nБумага 100 420');
check(!безТаб.ok, 'отвергнут');
check(/без табуляций/.test(безТаб.issue), 'причина названа прямо');
check(/Наименование/.test(безТаб.issue),
  'в причине показано начало ответа — иначе непонятно, что вернула модель');

// ------------------------------------------------------------ рабочий ответ

const таблица = [
  '№\tНаименование товара\tКол-во\tЕд. изм.\tЦена за ед., руб.',
  '1\tБумага офисная А4 80 г/м2\t536\tшт\t420,00',
  '2\tПапка-регистратор 70 мм\t120\tшт\t180,50'
].join('\n');

section('Рабочий ответ принимается');
const ок = parsePdfTableResponse(таблица);
check(ок.ok, 'таблица принята');
check(ок.строк === 3, `строк 3 (получено ${ок.строк})`);
check(ок.усечён === false || ок.усечён === undefined, 'обрыва нет');

section('Пояснения вокруг таблицы отрезаются');
const сПояснениями = parsePdfTableResponse(
  'Вот таблица из документа:\n\n' + таблица + '\n\nЕсли нужно что-то ещё, скажите.'
);
check(сПояснениями.ok, 'ответ с пояснениями принят');
check(сПояснениями.строк === 3, 'строки пояснений отрезаны');
check(сПояснениями.отброшеноСтрок >= 2, 'число отброшенных строк посчитано');
check(!/Вот таблица/.test(сПояснениями.текст),
  'ПОЯСНЕНИЕ НЕ ПОПАЛО В ТЕКСТ — иначе разбор принял бы его за шапку');

section('ОБРЫВ ПО ПРЕДЕЛУ ВЫВОДА ПОМЕЧАЕТСЯ');
// Самая опасная ошибка: таблица обрывается, разбор даёт позиции, но не все.
// Смета собирается заниженной, и клиент видит запас, которого нет.
const обрыв = parsePdfTableResponse({
  stop_reason: 'max_tokens',
  content: [{ type: 'text', text: таблица }]
});
check(обрыв.ok, 'текст всё равно отдаётся — часть позиций лучше, чем ничего');
check(обрыв.усечён === true, 'НО ПОМЕЧЕН КАК ОБРЕЗАННЫЙ');

const целый = parsePdfTableResponse({
  stop_reason: 'end_turn',
  content: [{ type: 'text', text: таблица }]
});
check(целый.усечён === false, 'нормально завершённый ответ обрезанным не помечается');

// --------------------------------------------- стык с разбором таблиц НМЦК

section('ТЕКСТ ОТ МОДЕЛИ РАЗБИРАЕТСЯ НАШИМ КОДОМ — главная проверка');
// Весь замысел держится на этом: модель отдаёт текст в том же виде, что
// и чтение Word, а позиции извлекает `parseNmckTable` — код, выверенный
// на реальных обоснованиях НМЦК с портала.
const разбор = parseNmckTable(ок.текст);
check(разбор.positions.length === 2,
  `позиций разобрано 2 (получено ${разбор.positions.length})`);
check(разбор.positions[0].name.indexOf('Бумага офисная А4') === 0,
  'наименование первой позиции на месте');
check(разбор.positions[0].quantity === 536, 'количество 536');
check(разбор.positions[0].unit === 'шт', 'единица измерения');
check(разбор.positions[1].quantity === 120, 'количество второй позиции');

section('Пустая ячейка остаётся пустой');
// Разбор настроен на вывод чтения Word, где объединённая по вертикали ячейка
// у следующих строк пуста. Если модель повторит наименование, сработает
// другая ветка разбора и позиции удвоятся — поэтому в инструкции это
// требование стоит отдельной строкой.
check(/оставь её пустой/.test(r.system[0].text),
  'в инструкции сказано оставлять пустые ячейки пустыми');
const сПустой = parsePdfTableResponse(
  '№\tНаименование\tКол-во\tЕд.\tЦена\n1\tБумага А4\t10\tшт\t420,00\n\t\t\t\t430,00'
);
check(сПустой.ok, 'строка с пустыми ячейками принята');
check(сПустой.текст.indexOf('\t\t\t\t') !== -1,
  'подряд идущие табуляции сохранены — по ним разбор узнаёт объединённую ячейку');

console.log('');
if (failures) {
  console.log(`ПРОВЕРОК НЕ ПРОШЛО: ${failures}`);
  process.exit(1);
}
console.log('ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ');
