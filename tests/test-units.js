/**
 * Тесты сверки единицы цены поставщика (src/units.js). Запуск: node tests/test-units.js
 * Примеры - по живым случаям проекта (пенокартон 14.10.2026), остальные придуманы мной.
 */
const { сверитьЕдиницу, видЕдиницы, числоВФасовке } = require('../src/units');

let failures = 0;
const check = (ok, message) => {
  console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${message}`);
  if (!ok) failures++;
};

check(видЕдиницы('шт.').род === 'шт' && видЕдиницы('Лист').род === 'лист' && видЕдиницы('пог. м').род === 'м' && видЕдиницы('упак.').род === 'фасовка', 'виды единиц');
check(видЕдиницы('') === null && видЕдиницы('условная') === null, 'неизвестная единица - null');

const пено = сверитьЕдиницу({ unit: 'лист' }, { price: 2804, unit: 'упаковка', evidence: 'Пенокартон 70×100 см, 5 мм, упаковка 40 листов' });
check(пено.вид === 'пересчитано' && пено.цена === 70.1, `пенокартон: 2804 за упаковку 40 листов → 70,10 за лист (${пено.цена})`);
check(/40/.test(пено.пояснение), 'пересчёт назван в пояснении');

const кабель = сверитьЕдиницу({ unit: 'м' }, { price: 9800, unit: 'бухта', evidence: 'ВВГнг 3х2,5, бухта 100 м' });
check(кабель.вид === 'пересчитано' && кабель.цена === 98, 'кабель: бухта 100 м → за метр');
check(сверитьЕдиницу({ unit: 'м' }, { price: 9800, unit: 'бухта', evidence: 'ВВГнг 3х2,5 мм' }).вид === 'другая', '«мм» в сечении не принимается за метры в бухте');
check(сверитьЕдиницу({ unit: 'шт' }, { price: 500, unit: 'упак', evidence: 'упаковка' }).вид === 'другая', 'упаковка без числа - не в расчёт');
check(сверитьЕдиницу({ unit: 'шт' }, { price: 500, unit: 'упак', evidence: 'в упаковке 10 шт, 20 шт в коробке' }).вид === 'другая', 'два разных числа - не решаем');
check(сверитьЕдиницу({ unit: 'м' }, { price: 120, unit: 'кг', evidence: '' }).вид === 'другая', 'метры против килограммов - не в расчёт');
check(сверитьЕдиницу({ unit: 'пачка' }, { price: 330, unit: 'упаковка', evidence: '500 листов' }).вид === 'та же', 'пачка и упаковка - одно и то же');
check(сверитьЕдиницу({ unit: 'шт.' }, { price: 45, unit: 'штука', evidence: '' }).вид === 'та же', 'шт и штука - одно');
check(сверитьЕдиницу({ unit: '' }, { price: 45, unit: 'упак', evidence: '' }).вид === 'неизвестно', 'единица позиции неизвестна - не решаем');
check(сверитьЕдиницу({ unit: 'шт' }, { price: 45, unit: '', evidence: '' }).вид === 'неизвестно', 'единица поставщика неизвестна - не решаем');
check(числоВФасовке('по 500 шт.', 'шт') === 500 && числоВФасовке('1 шт', 'шт') === null, 'число в фасовке; «1 шт» фасовкой не считается');

console.log('\n=== Род единицы услуг (23.10.2026) ===');
{
  const { родЕдиницы } = require('../src/units');
  check(родЕдиницы('м²') === 'площадь' && родЕдиницы('кв. м') === 'площадь' && родЕдиницы('м2') === 'площадь', 'м², кв. м, м2 - площадь');
  check(родЕдиницы('КУБ.М.') === 'объём' && родЕдиницы('м³') === 'объём', 'куб. м, м³ - объём');
  check(родЕдиницы('час') === 'время' && родЕдиницы('чел.-час') === 'время' && родЕдиницы('г.ч.') === 'время', 'час, чел.-час, г.ч. - время');
  check(родЕдиницы('6 мес') === null && родЕдиницы('мес') === 'срок' && родЕдиницы('Год') === 'срок', 'мес, год - срок');
  check(родЕдиницы('шт') === null && родЕдиницы('пачка') === null && родЕдиницы('') === null, 'штуки и пачки - не сравниваются (товары - своя проверка фасовки)');
  check(родЕдиницы('м²') !== родЕдиницы('мес'), 'ставка за м² и объём в месяцах - разный род: цена прайса не подставится');
}

console.log('');
if (failures) { console.log(`ПРОВЕРОК НЕ ПРОШЛО: ${failures}`); process.exit(1); }
console.log('ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ');
