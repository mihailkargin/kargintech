/**
 * Тесты самопроверки расчёта.
 * Запуск: node tests/test-verify.js
 *
 * ГЛАВНОЕ ЗДЕСЬ — ОТРИЦАТЕЛЬНЫЕ КОНТРОЛИ.
 *
 * Проверка, которая проходит всегда, ничего не проверяет. В этом проекте такое
 * уже случалось дважды: фильтр посредника проверялся на адресе, который и так
 * не отвечает, а фильтры портала сверялись по карточкам вместо общего числа.
 * Поэтому каждая проверка здесь идёт парой: сначала «на правильных данных
 * подтверждается», потом «на испорченных НЕ подтверждается».
 *
 * Испорченные данные делаются ровно теми ошибками, которые возможны:
 * сдвиг колонки, выдуманное наименование, пересказанная цитата, цена не из
 * диапазона, ноль вместо неизвестного значения.
 */
