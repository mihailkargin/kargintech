/**
 * Тесты: поиск поставщиков через Яндекс (src/yandex-search.js) - без сети.
 * Запуск: node tests/test-yandex-search.js
 */
const Я = require('../src/yandex-search');

let failures = 0;
function check(ok, label) {
  console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${label}`);
  if (!ok) failures++;
}

const бумага = { name: 'Бумага для офисной техники (Бумага офисная А4 80 г/м2 500 листов)', quantity: 100, unit: 'пачка' };

console.log('=== Запросы ===');
const з = Я.запросыПоиска(бумага);
check(з.length === 2 && /^Бумага офисная А4 80/.test(з[0]) && /оптом цена/.test(з[0]), `суть из скобок + «оптом цена»: ${з[0]}`);
check(/расценки/.test(Я.запросыПоиска({ name: 'Устройство кровли из профнастила', unit: 'м2' })[0]), 'работа - запрос про расценки');
check(Я.запросыПоиска({ name: 'Ab' }).length === 0, 'слишком короткое - не ищем');
check(/^Пенокартон белый, 70\*100/.test(Я.суть({ name: 'Пенокартон (белый, 70*100)' })), `короткое имя - суть с товаром, а не только признаки: ${Я.суть({ name: 'Пенокартон (белый, 70*100)' })}`);
check(!Я.изРазметки({ name: 'Пенокартон (белый, 70*100)' }, '<script type="application/ld+json">{"@type":"Product","name":"Термоэтикетка полипропилен белый 70х100 мм","offers":{"price":"865","priceCurrency":"RUB"}}</script>', 'https://u.ru/x').совпало, 'термоэтикетка 70х100 не совпадает с пенокартоном');
// Эталон 0373100010426000011: код КТРУ в наименовании, всё нужное - в ТЗ.
const эталон = { name: 'Бумага для офисной техники 17.12.14.110-00000005', unit: 'Пачка',
  spec: 'Формат листов: А4. Количество листов в пачке: не менее 500 листов в пачке. Марка бумаги: не ниже С Цветность: Белая' };
const зЭ = Я.запросыПоиска(эталон)[0];
check(!/17\.12/.test(зЭ) && /А4/.test(зЭ) && /500 листов/.test(зЭ) && /марка С/.test(зЭ), `код убран, признаки ТЗ добавлены: ${зЭ}`);
check(Я.товарПодходит(эталон, 'Бумага для офисной техники SvetoCopy А4, класс C, 80 г/м, 500л'), 'SvetoCopy А4 500л подходит (плотность сверх ТЗ не мешает)');
check(!Я.товарПодходит(эталон, 'Бумага для офисной техники А3 500 листов'), 'А3 не подходит');
check(!Я.товарПодходит(эталон, 'Бумага А4 250 листов для офисной техники'), '250 листов не подходит');
check(Я.товарПодходит({ ...эталон, spec: эталон.spec + ' Плотность 80 г/м2' }, 'Бумага для офисной техники А4 80 г/м² 500 л'), '«80 г/м2» в ТЗ совпадает с «80 г/м²» на странице');

console.log('=== Выдача ===');
const xml = `<?xml version="1.0" encoding="utf-8"?><yandexsearch><response><results><grouping>
<group><doc><url>https://www.opt-bumaga.ru/a4</url><title>Бумага &lt;hlword&gt;А4&lt;/hlword&gt;</title></doc></group>
<group><doc><url>https://www.ozon.ru/x</url><title>Ozon</title></doc></group>
<group><doc><url>https://opt-bumaga.ru/b</url><title>повтор домена</title></doc></group>
<group><doc><url>https://zavod.ru/p</url><title>Завод</title></doc></group>
</grouping></results></response></yandexsearch>`;
const в = Я.ссылкиИзВыдачи({ rawData: Buffer.from(xml).toString('base64') });
check(в.ссылки.length === 2 && в.ссылки[0].домен === 'opt-bumaga.ru' && в.ссылки[1].домен === 'zavod.ru', 'маркетплейс отсечён, домен один раз');
const ош = Я.ссылкиИзВыдачи({ rawData: Buffer.from('<yandexsearch><response><error code="15">Нет результатов</error></response></yandexsearch>').toString('base64') });
check(ош.ссылки.length === 0 && /Нет результатов/.test(ош.ошибка), 'ошибка выдачи названа');
const агрег = Я.ссылкиИзВыдачи({ rawData: Buffer.from('<yandexsearch><response><results><grouping>'
  + '<group><doc><url>https://rostender.info/region/t</url><title>Тендер</title></doc></group>'
  + '<group><doc><url>https://opt-bumaga.ru/c</url><title>Бумага опт</title></doc></group>'
  + '</grouping></results></response></yandexsearch>').toString('base64') });
check(агрег.ссылки.length === 1 && агрег.ссылки[0].домен === 'opt-bumaga.ru', 'тендерный агрегатор отсечён (живой расчёт 13.11: rostender.info съел запрос модели)');

console.log('=== Цена из разметки ===');
const карточка = (имя, цена) => `<html><head><meta property="og:site_name" content="ОптБумага"></head><body>
<script type="application/ld+json">{"@type":"Product","name":"${имя}","offers":{"@type":"Offer","price":"${цена}","priceCurrency":"RUB"}}</script></body></html>`;
const р1 = Я.изРазметки(бумага, карточка('Бумага офисная SvetoCopy А4 80 г/м2 500 листов', '289.00'), 'https://opt-bumaga.ru/a4');
check(р1 && р1.совпало && р1.поставщик.price === 289 && р1.поставщик.name === 'ОптБумага', 'совпавший товар: 289 ₽, имя из og:site_name');
const р2 = Я.изРазметки(бумага, карточка('Бумага офисная А3 80 г/м2 500 листов', '590'), 'https://opt-bumaga.ru/a3');
check(р2 && !р2.совпало, 'А3 вместо А4 - не совпадение, цены нет');
check(Я.изРазметки(бумага, '<html>нет разметки</html>', 'https://x.ru') === null, 'нет разметки - null');

console.log('=== Страница по теме ===');
check(Я.страницаПоТеме(бумага, 'Купить бумагу офисную формата А4 плотность 80 г/м2, пачка 500 листов'), 'страница про бумагу - модель читает');
check(!Я.страницаПоТеме(бумага, 'Доставка пиццы по Москве, роллы и суши'), 'чужая страница - модель не вызывается');

console.log('=== Ответ модели и проверка по странице ===');
const текст = 'Бумага офисная А4 80 г/м2 500 л. SvetoCopy Classic. Цена: 289 руб./пачка. От 5 коробок 271 руб. '.repeat(4);
const хорошо = Я.поставщикИзОтвета('```json\n{"found":true,"company":"ООО Бумага","product":"SvetoCopy","price":289,"unit":"пачка","evidence":"Цена: 289 руб./пачка","priceNote":""}\n```', бумага, 'https://opt-bumaga.ru/a4', текст);
check(хорошо.поставщик && хорошо.поставщик.price === 289, 'цена с цитатой со страницы - принята');
const выдумка = Я.поставщикИзОтвета('{"found":true,"company":"ООО Бумага","price":245,"unit":"пачка","evidence":"Цена: 245 руб./пачка"}', бумага, 'https://opt-bumaga.ru/a4', текст);
check(выдумка.поставщик && выдумка.поставщик.price === null && выдумка.поставщик.priceDropped, 'цены нет на странице - выброшена, компания осталась контактом');
const сОт = 'Бумага SvetoCopy А4 500л купить оптом от 357,65 рублей. В наличии. '.repeat(5);
const нижняя = Я.поставщикИзОтвета('{"found":true,"company":"Урал Тойз","price":357.65,"unit":"пачка","evidence":"купить оптом от 357,65 рублей"}', бумага, 'https://ural.toys/x', сОт);
check(нижняя.поставщик && нижняя.поставщик.price === null, '«от 357,65» - нижняя граница, цена не берётся');
const тысячи = Я.поставщикИзОтвета('{"found":true,"company":"Завод","price":1250,"unit":"шт","evidence":"Цена от 1 250 ₽"}', бумага, 'https://z.ru/x', 'Цена от 1 250 ₽ за штуку. '.repeat(10));
check(тысячи.поставщик && тысячи.поставщик.price === null, '«от 1 250» с пробелом в разрядах - тоже граница');
const вОтделе = Я.поставщикИзОтвета('{"found":true,"company":"Бумага","price":289,"unit":"пачка","evidence":"Цена: 289 руб./пачка"}', бумага, 'https://opt-bumaga.ru/a4', текст);
check(вОтделе.поставщик && вОтделе.поставщик.price === 289, 'обычная цена без «от» - принята');
const каталожная = Я.поставщикИзОтвета('{"found":true,"company":"Safes","price":289,"unit":"пачка","evidence":"Цена: 289 руб./пачка","priceNote":"цена варьируется, приведена минимальная из представленных"}', бумага, 'https://opt-bumaga.ru/a4', текст);
check(каталожная.поставщик && каталожная.поставщик.price === null, '«минимальная из представленных» на странице-каталоге - не цена');
const скрепки = { name: 'Скрепки, металлические (28 мм (оцинкованные))' };
const металл = 'Пластина оцинкованная прямоугольная 200х500х28 мм. Цена 8030 руб. '.repeat(6);
check(Я.поставщикИзОтвета('{"found":true,"company":"МЕТАЛЛКОНТУР","product":"Пластина оцинкованная 200х500х28 мм","price":8030,"evidence":"Цена 8030 руб."}', скрепки, 'https://metallkontur.ru/x', металл).поставщик === null, 'пластина вместо скрепок - отброшена');
const кистемойка = 'Подставка-стакан для промывки кистей. Цена 100 руб. за 1 шт. '.repeat(6);
check(!!Я.поставщикИзОтвета('{"found":true,"company":"Точка","product":"Подставка-стакан для промывки кистей","price":100,"evidence":"Цена 100 руб. за 1 шт."}', { name: 'Емкость для промывания кисточек' }, 'https://t.ru/x', кистемойка).поставщик, 'стакан для промывки кистей - принят как ёмкость для промывания');
check(Я.поставщикИзОтвета('{"found":false}', бумага, 'https://opt-bumaga.ru/a4', текст).поставщик === null, 'found=false - поставщика нет');
check(Я.поставщикИзОтвета('не знаю', бумага, 'https://x.ru', текст).поставщик === null, 'без JSON - поставщика нет');

console.log('=== Запрос к модели ===');
const q = Я.запросКМодели({ ...бумага, spec: 'Плотность 80 г/м2. Контакт: Иванов И.И., тел. +7 (495) 123-45-67' }, 'x'.repeat(20000), 'https://opt-bumaga.ru/a4', 'gpt://f/deepseek-v4.1-flash/latest');
const польз = q.messages[1].content;
check(!/123-45-67/.test(польз), 'телефон из ТЗ вырезан до отправки');
check(польз.length < Я.ТЕКСТА_МОДЕЛИ + 1000, 'текст страницы обрезан');
check(q.model === 'gpt://f/deepseek-v4.1-flash/latest' && q.temperature === 0, 'модель и температура');

console.log(failures ? `\nСБОЕВ: ${failures}` : '\nВсе проверки прошли');
process.exit(failures ? 1 : 0);
