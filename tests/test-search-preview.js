/**
 * Проверка слов в настройках (app/search-run.js, предпросмотрПоиска) и
 * стоп-слова «работы и услуги» (site/categories.js). Портал подменён
 * сохранённой выдачей. Запуск: node tests/test-search-preview.js
 */
const fs = require('fs');
const path = require('path');
const { предпросмотрПоиска } = require('../app/search-run');
const { разобратьСтоп, собратьСтоп, СТОП_УСЛУГИ, стопСловаПоУмолчанию, стопСловаКатегорий, словаКатегорий } = require('../site/categories');

let failures = 0;
const check = (ok, m) => { console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${m}`); if (!ok) failures++; };

const выдача = fs.readFileSync(path.join(__dirname, '..', 'fixtures', 'search-bumaga-2026-09-19.html'), 'utf8');
const адреса = [];
const портал = async (u) => { адреса.push(u); return { ok: true, тело: выдача }; };
const молчит = async () => ({ ok: false, код: 0 });

(async () => {
  console.log('\n=== Проверка слов ===');
  // Сохранённая выдача от 19.09 - сроки в ней прошли; «сегодня» в
  // предпросмотре настоящее, поэтому живых закупок в ней 0. Проверяем
  // устройство ответа, а не числа рынка.
  const r = await предпросмотрПоиска({ слова: ['бумага', 'бумага', 'канцелярские товары'], стопСлова: [] }, { взять: портал, пауза: 0 });
  check(r.ok && r.слова.length === 2, 'повторы слов не запрашиваются дважды');
  check(адреса.every((u) => /af=on/.test(u) && /pageNumber=1/.test(u)), 'только этап подачи заявок, первая страница');
  check(r.слова.every((с) => typeof с.портал === 'number' && typeof с.прошло === 'number'), 'по каждому слову - на портале и в ленту');
  check(r.слова.every((с) => с.портал === 0), 'закупки с прошедшим сроком не считаются');
  check(r.слова[0].всего === 'более 15 000', 'общее число на портале - из подписи над выдачей, а не число карточек');
  check(require('../app/search-run').всегоНаПортале('<div class="search-results__total"> 23 записи </div>') === '23'
    && require('../app/search-run').всегоНаПортале('<html></html>') === null, 'точное число и отсутствие подписи');
  const много = await предпросмотрПоиска({ слова: 'а б в г д е ж з и к'.split(' ') }, { взять: портал, пауза: 0 });
  check(много.слова.length === 8, 'не больше 8 слов за проверку');
  const нет = await предпросмотрПоиска({ слова: ['бумага'] }, { взять: молчит, пауза: 0 });
  check(!нет.ok && /не ответил/.test(нет.сбой), 'портал молчит - отказ с причиной, а не «0 закупок»');
  check(!(await предпросмотрПоиска({ слова: [] })).ok, 'без слов - отказ');

  console.log('\n=== Работы и услуги ===');
  check(собратьСтоп(['аренда'], false).join() === [...new Set(['аренда', ...СТОП_УСЛУГИ])].join(), 'услуги скрыты - служебные стоп-слова добавлены, без повторов');
  check(собратьСтоп(['пиломатериалы'], true).join() === 'пиломатериалы', 'услуги показываются - только свои «Исключая»');
  const старые = разобратьСтоп({ стопСлова: ['ремонт', 'услуг', 'аренда', 'работ по', 'обслуживан', 'туалетн'] });
  check(!старые.работыУслуги && старые.свои.join() === 'туалетн', 'старые настройки: служебные слова распознаны, свои отделены');
  check(разобратьСтоп({ стопСлова: ['туалетн'] }).работыУслуги === true, 'старые настройки без служебных слов - услуги показывались');
  check(стопСловаПоУмолчанию(['cleaning']).length === 0 && стопСловаПоУмолчанию(['office']).length > 0, 'категория услуг - без служебных стоп-слов');
  check(стопСловаПоУмолчанию(['lowcurrent']).length === 0, 'слаботочная категория по умолчанию включает монтаж и обслуживание');
  const свои20 = Array.from({ length: 20 }, (_, i) => `своя фраза ${i + 1}`);
  check(словаКатегорий(['lowcurrent'], свои20).length === 28, '8 фраз слаботочной категории и 20 своих не обрезаются');
  check(стопСловаКатегорий(['lowcurrent']).includes('охранные услуги'), 'у слаботочной категории есть отдельные стоп-слова физической охраны');

  console.log('\n=== Код ОКПД2 - второй путь в ленту ===');
  {
    const { applyFilters } = require('../src/filter');
    const { кодыКатегорий, ОКПД_ПОДТВЕРЖДЕНЫ } = require('../site/categories');
    const з = (object, okpdGroup) => ({ number: String(Math.random()), object, orgName: 'Школа № 1', okpdGroup, law: '44-ФЗ', price: 100000 });
    const ф = { keywords: ['бумаг'], stopWords: ['ремонт'], okpd: кодыКатегорий(['office']) };
    const список = [з('Поставка товаров для нужд школы', '17.12'), з('Поставка товаров для нужд школы', '31.01'), з('Поставка бумаги офисной', null),
      з('Ремонт помещений', '17.12'), з('Поставка товаров', null)];
    const { passed } = applyFilters(список, ф);
    check(passed.length === 2 && passed[0].okpdGroup === '17.12' && /бумаги/.test(passed[1].object), 'проходит по слову ИЛИ по коду категории; чужой код и закупка без кода и слова - нет');
    check(!applyFilters([з('Ремонт помещений', '17.12')], ф).passed.length, 'стоп-слова действуют и при совпадении кода');
    check(applyFilters([з('Поставка товаров', '17.12')], { keywords: ['бумаг'], okpd: ['17.12.14'] }).passed.length === 1, 'код клиента точнее группы закупки - совпадение');
    check(applyFilters([з('Поставка товаров', '17.12')], { keywords: ['бумаг'] }).passed.length === 0, 'без кодов клиента - как раньше, только по словам');
    check(ОКПД_ПОДТВЕРЖДЕНЫ.has('office') && кодыКатегорий(['office']).includes('17.12'), 'бумага 17.12 - код, подтверждённый по архиву');
    check(кодыКатегорий([], ['17.12', 'abc', '1']).join() === '17.12', 'свои коды проверяются на вид');
  }

  console.log(failures ? `\nСБОЕВ: ${failures}` : '\nВСЕ ПРОВЕРКИ ПРОЙДЕНЫ');
  process.exit(failures ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
