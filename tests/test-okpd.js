/**
 * Коды ОКПД2: из ИКЗ выдачи, с карточки закупки, похожесть в рейтинге.
 * Запуск: node tests/test-okpd.js
 *
 * Часть проверок — на настоящих сохранённых страницах портала.
 */
const fs = require('fs');
const path = require('path');
const { группаИзИкз, кодыИзТекста, группаКода, группыЗакупки, похожиПоОкпд } = require('../src/okpd');
const { parseSearchPage } = require('../src/parser');
const { parseNoticePage } = require('../src/notice-page');
const { падениеПоПохожим, оценка } = require('../src/rating');

let failures = 0;
const check = (ok, message) => {
  console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${message}`);
  if (!ok) failures++;
};
const section = (name) => console.log(`\n=== ${name} ===`);
const FX = path.join(__dirname, '..', 'fixtures');

section('Группа из ИКЗ');
check(группаИзИкз('261503800544850380100100580021723244').группа === '17.23', 'знаки 30–33 → 17.23');
const нули = группаИзИкз('262773511700877350100100350010000244');
check(нули.группа === null && /несколько кодов/.test(нули.причина), '«0000» — несколько кодов, группы нет, причина названа');
check(группаИзИкз('12345').группа === null, 'короткий номер — не ИКЗ');
check(группаИзИкз('').группа === null, 'пусто — группы нет');

section('Выдача поиска — на настоящих страницах');
const выдача = parseSearchPage(fs.readFileSync(path.join(FX, 'phase3', 'completed-search-2026-09-26.html'), 'utf8'));
const с44 = выдача.filter((т) => т.number.length === 19);
check(с44.length > 0 && с44.every((т) => /^\d{36}$/.test(т.ikz)), `у каждой закупки 44-ФЗ взят ИКЗ (${с44.length} шт.)`);
const первая = выдача.find((т) => т.number === '0173200021826000009');
check(первая && первая.ikz === '262773511700877350100100350010000244' && первая.okpdGroup === null,
  'ИКЗ взят у своей карточки, а не у соседней; «0000» → группы нет');
const сГруппой = выдача.filter((т) => т.okpdGroup);
check(сГруппой.every((т) => /^\d{2}\.\d{2}$/.test(т.okpdGroup)), `группы вида «17.12» (${сГруппой.map((т) => т.okpdGroup).join(', ')})`);
const с223 = parseSearchPage(fs.readFileSync(path.join(FX, 'search-fz223-mebel-2026-09-19.html'), 'utf8'))
  .filter((т) => т.number.length === 11);
check(с223.length === 0 || с223.every((т) => т.ikz === ''), 'у 223-ФЗ ИКЗ нет — и он не подставляется чужой');

section('Карточка закупки — на настоящей странице');
const карточка = parseNoticePage(fs.readFileSync(path.join(FX, 'notice-44fz-zk20-2026-10-03.html'), 'utf8'),
  'https://zakupki.gov.ru/epz/order/notice/zk20/view/common-info.html?regNumber=0');
check(карточка.ikz === '261503800544850380100100580021723244', 'ИКЗ с карточки');
check(карточка.окпд2.length === 1 && карточка.окпд2[0] === '17.23.13.140', `полный код позиции (${карточка.окпд2.join(', ')})`);
check(карточка.группыОкпд2.join() === '17.23', 'группа совпадает с ИКЗ');
check(карточка.нацРежим && карточка.нацРежим.виды.join() === 'преимущество' && карточка.нацРежим.строки.length === 1,
  `национальный режим: преимущество российским товарам, повтор строки один раз (${JSON.stringify(карточка.нацРежим && карточка.нацРежим.виды)})`);
check(require('../src/notice-page').нацРежим('<div>нет таблицы</div>') === null, 'таблицы нет - null, а не «режима нет»');

section('Полные коды в тексте');
check(кодыИзТекста('17.12.14.110-00000006 и 20.52.10.190').join() === '17.12.14.110,20.52.10.190', 'код КТРУ даёт свой код ОКПД2');
check(кодыИзТекста('дата 12.10.2026, сумма 1.234.567.890').length === 0, 'даты и суммы кодом не считаются');
check(кодыИзТекста('117.12.14.110').length === 0, 'кусок более длинного числа — не код');
check(группаКода('17.23.13.140') === '17.23', 'группа кода');
check(группыЗакупки({ икз: '262773511700877350100100350010000244', коды: ['17.23.13.140', '22.29.25.000'] }).join() === '17.23,22.29',
  'при «0000» группы берутся из кодов карточки');
// Живой случай 21.10.2026 (0326100005026000005, бумага А4): в ИКЗ «2229», у позиции 17.12.14.110.
check(группыЗакупки({ икз: '261770865288831230200100010012229244', коды: ['17.12.14.110'] }).join() === '17.12',
  'коды позиций главнее ИКЗ: бумага не становится пластмассой');
check(группыЗакупки({ икз: '261770865288831230200100010012229244', коды: [] }).join() === '22.29',
  'кодов позиций нет - берётся ИКЗ');
check(похожиПоОкпд(['17.12'], ['17.12', '17.23']) === true && похожиПоОкпд(['17.12'], ['22.29']) === false, 'похожесть по группам');
check(похожиПоОкпд([], ['17.12']) === null, 'неизвестно — это null, а не «похожи»');

section('Рейтинг: похожие только по тому же товару');
const АУК = 'электронный аукцион';
const н = (снижение, группа, номер) => ({ снижение, нмцк: 1000000, способ: АУК, группаОкпд2: группа, номер });
const выборка = [н(10, '17.12', 'б1'), н(15, '17.12', 'б2'), н(20, '17.12', 'б3'), н(60, '20.59', 'картридж')];
const бумага = падениеПоПохожим(выборка, { нмцк: 1000000, способ: АУК, группыОкпд2: ['17.12'] });
check(бумага.достаточно && бумага.падение === 20 && бумага.похожих === 3,
  `бумага сравнивается с бумагой: падение 20%, не 60% от картриджей (${бумага.падение}%)`);
// Отрицательный контроль: без кода тот же картридж утянул бы падение до 60%.
check(падениеПоПохожим(выборка, { нмцк: 1000000, способ: АУК }).падение === 60,
  'без кода чужой товар действительно попадает в выборку — фильтр по коду не пустой');
const мало = падениеПоПохожим([н(10, '17.12'), н(15, '17.12'), н(60, '20.59'), н(50, null)],
  { нмцк: 1000000, способ: АУК, группыОкпд2: ['17.12'] });
check(!мало.достаточно && /ОКПД2 17\.12/.test(мало.причина), 'двух похожих по товару мало — чужими не добирается, причина с кодом');
const звёзды = оценка({ нмцк: 1000000, способ: 'Электронный аукцион', закупка: 500000, закупкаПолная: true,
  налог: 0.06, наблюдения: выборка, группыОкпд2: ['17.12'] });
check(звёзды.звёзды === 5 && звёзды.падение.поТовару, 'оценка идёт по товару и даёт звёзды');

console.log(`\n${failures === 0 ? 'ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ' : 'ПРОВАЛЕНО ПРОВЕРОК: ' + failures}`);
process.exit(failures === 0 ? 0 : 1);
