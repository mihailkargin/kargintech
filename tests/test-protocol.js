section('ЧИСЛО УЧАСТНИКОВ: точно только когда страница не заполнена доверху');
// ======================================================================
// Блок постраничности в разметке пустой — его рисует JavaScript. Если заявок
// ровно столько, сколько вмещает страница, их может быть больше.
check(списокАвк.участниковТочно === true,
  'у аукциона 7 заявок из 10 — число участников известно точно');
