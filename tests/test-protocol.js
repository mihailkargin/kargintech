section('СТАТИСТИКА: ОБЕ МЕДИАНЫ, А НЕ ВЫБОР ОДНОЙ');
// ======================================================================
// Правило владельца 04.10.2026: «если из разных источников результаты рознятся,
// нужно не выбирать и не выдумывать, а показывать диапазон и его обоснование».
// Здесь расхождение закономерное: в закупке с единственной заявкой торга не было.
const смешанные = [
  { способ: P.СПОСОБ.КОТИРОВКИ, снижение: 24, ценаПобеды: 76000, участников: 3 },
  { способ: P.СПОСОБ.КОТИРОВКИ, снижение: 26, ценаПобеды: 74000, участников: 4 },
  { способ: P.СПОСОБ.КОТИРОВКИ, снижение: 30, ценаПобеды: 70000, участников: 5 },
  { способ: P.СПОСОБ.КОТИРОВКИ, снижение: 1.6, ценаПобеды: 98400, участников: 1, единственнаяЗаявка: true },
  { способ: P.СПОСОБ.КОТИРОВКИ, снижение: 2, ценаПобеды: 98000, участников: 1, единственнаяЗаявка: true }
];
const разрезыСмешанных = S.разложить(смешанные);
const кот2 = разрезыСмешанных.поСпособу.find((с) => с.ключ === P.СПОСОБ.КОТИРОВКИ);

check(разрезыСмешанных.единственныхЗаявок === 2,
  `единственных заявок посчитано 2 (получено ${разрезыСмешанных.единственныхЗаявок})`);
check(кот2.n === 5 && кот2.медиана === 24,
  `со всеми наблюдениями медиана 24% (получено ${кот2.медиана} по ${кот2.n})`);
check(Boolean(кот2.безЕдинственных) && кот2.безЕдинственных.n === 3
  && кот2.безЕдинственных.медиана === 26,
  'только конкурентные: 3 наблюдения, медиана 26% — выше, и это главное: смешивание '
  + 'ЗАНИЖАЕТ снижение, то есть делает убыточный тендер выгодным на вид '
  + `(получено ${кот2.безЕдинственных && кот2.безЕдинственных.медиана})`);
check(кот2.единственных === 2, 'число единственных заявок названо в самом срезе');

const одинУчастник = разрезыСмешанных.поУчастникам.find((с) => /один участник/.test(с.ключ));
check(Boolean(одинУчастник) && одинУчастник.n === 2,
  'закупки с одной заявкой попали в свою группу «один участник»');

const безЕдинственных = S.разложить(смешанные.filter((н) => !н.единственнаяЗаявка));
check(безЕдинственных.поСпособу[0].безЕдинственных === null,
  'когда единственных заявок нет, второй расчёт не печатается — лишней строки не будет');

// Предложения всех участников (30.10.2026) - в наблюдение, по возрастанию, без отклонённых.
const сПредложениями = P.наблюдение(
  { номер: '0373100010426000011', способ: P.СПОСОБ.АУКЦИОН, нмцк: 100000, ценаПобеды: 81000 },
  { участников: 3, участниковТочно: true, заявки: [{ цена: 90000 }, { цена: null, отклонена: true }, { цена: 81000 }] }
);
check(сПредложениями.годится && JSON.stringify(сПредложениями.наблюдение.предложения) === '[81000,90000]',
  'предложения участников сохранены: 81 000 и 90 000, отклонённая без цены не попала');
check(JSON.stringify(P.наблюдение({ номер: '1', способ: P.СПОСОБ.АУКЦИОН, нмцк: 100000, ценаПобеды: 90000 }).наблюдение.предложения) === '[]',
  'без списка заявок предложений нет - пустой список, а не выдуманные');

console.log(`\n${failures === 0 ? 'ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ' : 'ПРОВАЛЕНО ПРОВЕРОК: ' + failures}`);
process.exit(failures === 0 ? 0 : 1);
