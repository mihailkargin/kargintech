/**
 * Проверки разбора протоколов и статистики снижения цены.
 *
 * Разбор проверяется НА РЕАЛЬНЫХ СТРАНИЦАХ ПОРТАЛА из fixtures/phase3 — две
 * закупки, два разных способа: электронный аукцион и запрос котировок.
 * Ожидаемые числа ниже — это результат разбора КОНКРЕТНЫХ сохранённых страниц.
 * Они проверяют код и ничего не утверждают о рынке: по двум закупкам судить
 * о снижении в нише нельзя.
 *
 * Статистика проверяется на придуманных наборах — иначе правила «медиана, а не
 * среднее» и «мало наблюдений — не статистика» не проверить: настоящей выборки
 * пока нет.
 *
 * Запуск: node tests/test-protocol.js
 */
const fs = require('fs');
const path = require('path');

const P = require('../src/protocol-page');
const S = require('../src/discount-stats');

let failures = 0;
const check = (ok, message) => {
  console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${message}`);
  if (!ok) failures++;
};
const section = (name) => console.log(`\n=== ${name} ===`);

const ФИКС = path.join(__dirname, '..', 'fixtures', 'phase3');
const читать = (имя) => fs.readFileSync(path.join(ФИКС, имя), 'utf8');

// ======================================================================
section('РЕАЛЬНАЯ СТРАНИЦА: электронный аукцион 0119600018526000086');
// ======================================================================
const авк = P.parseSupplierResults(
  читать('supplier-results-0119600018526000086.html'),
  'https://zakupki.gov.ru/x?regNumber=0119600018526000086'
);

check(авк.способ === P.СПОСОБ.АУКЦИОН, `способ распознан: ${авк.способ}`);
check(авк.нмцк === 79452.37, `НМЦК 79 452,37 (получено ${авк.нмцк})`);
check(авк.ценаПобеды === 52041.28, `цена победы 52 041,28 (получено ${авк.ценаПобеды})`);
check(авк.issues.length === 0, 'замечаний нет');

// Ожидаемое значение посчитано от НМЦК и цены победы с этой же страницы.
check(P.снижение(авк.нмцк, авк.ценаПобеды) === 34.5,
  `снижение по этой странице посчитано верно (получено ${P.снижение(авк.нмцк, авк.ценаПобеды)})`);

check(авк.победители.length === 1 && /победител/i.test(авк.победители[0].место),
  'победитель один и помечен как победитель');

