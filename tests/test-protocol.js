section('НАБЛЮДЕНИЕ: негодное отбрасывается с названной причиной');
// ======================================================================
const нАвк = P.наблюдение(авк, списокАвк);
check(нАвк.годится === true, 'аукцион годится для статистики');
check(нАвк.наблюдение.участников === 7, 'точное число участников записано');
check(нАвк.наблюдение.участниковНеМенее === null, 'нижней границы не поставлено — число известно');

const нКот = P.наблюдение(кот, списокКот);
check(нКот.годится === true, 'котировки годятся');
check(нКот.наблюдение.участников === null,
  'число участников не записано — оно неизвестно');
check(нКот.наблюдение.участниковНеМенее === 10,
  'записана нижняя граница: не менее 10');

// ТОЛЬКО ЗАКУПКИ С ОПРЕДЕЛЁННЫМ ПОБЕДИТЕЛЕМ. Требование владельца 05.10.2026:
// «не бери в расчёт несостоявшиеся тендеры, бери только те контракты, которые
// были заключены». Несостоявшаяся закупка снижения не даёт вовсе; если бы такие
// случаи попадали как «снижение 0%», медиана поехала бы к нулю — та же ошибка,
// из-за которой убрали допущение 12%.
const несостоявшаяся = P.наблюдение({
  способ: P.СПОСОБ.АУКЦИОН, нмцк: 100000, ценаПобеды: null, неСостоялась: true
});
check(несостоявшаяся.годится === false, 'несостоявшаяся закупка отброшена');
check(/не состоялась/.test(несостоявшаяся.причина),
  `причина названа своим словом: ${несостоявшаяся.причина}`);
check(!/проверить разбор/.test(несостоявшаяся.причина),
  'не свалено в «ошибку разбора» — это штатный исход, а не поломка');

// Отличать штатный исход от ошибки кода обязательно: первый сбор 05.10.2026
// отбросил 36 закупок из 50 с одной формулировкой, и по такому выводу нельзя
// понять, надо ли что-то чинить.
const непонятно = P.наблюдение({
  способ: P.СПОСОБ.АУКЦИОН, нмцк: 100000, ценаПобеды: null, неСостоялась: false
});
check(непонятно.годится === false, 'без цены победы наблюдения нет');
check(/проверить разбор/.test(непонятно.причина),
  `а вот это помечено как вероятная ошибка кода: ${непонятно.причина}`);

// ЗАКУПКА С ЦЕНОЙ ЗА ЕДИНИЦУ ТОВАРА. Найдено на первом сборе: снижения 89,9%,
// 81,6%, 76,3% на бумаге. Причина не в рынке — при цене за единицу (ч. 24
// ст. 42) НМЦК это максимальное значение цены контракта, а участник подаёт цену
// за единицу. Величины разного порядка, разность снижением не является.
const заЕдиницу = P.наблюдение({
  способ: P.СПОСОБ.КОТИРОВКИ, нмцк: 500000, ценаПобеды: 50, ценаЗаЕдиницу: true
});
check(заЕдиницу.годится === false, 'закупка с ценой за единицу отброшена');
check(/несравнимы/.test(заЕдиницу.причина), `причина названа: ${заЕдиницу.причина}`);

// Отбрасываем по ПРИЗНАКУ НА СТРАНИЦЕ, а не по величине результата: выбрасывать
// наблюдение за то, что число большое, значит подгонять выборку под ожидание.
// Настоящие глубокие снижения бывают, и терять их нельзя.
const глубокое = P.наблюдение({
  способ: P.СПОСОБ.АУКЦИОН, нмцк: 100000, ценаПобеды: 25000, ценаЗаЕдиницу: false
});
check(глубокое.годится === true,
  'снижение 75% без признака цены за единицу остаётся в выборке — это может быть правдой');

const единственный = P.наблюдение({
  номер: '1', способ: P.СПОСОБ.ЕДИНСТВЕННЫЙ, нмцк: 100000, ценаПобеды: 100000
});
check(единственный.годится === false, 'закупка у единственного поставщика отброшена');
check(/единственн/.test(единственный.причина), `причина названа: ${единственный.причина}`);

const выше = P.наблюдение({ способ: P.СПОСОБ.АУКЦИОН, нмцк: 100000, ценаПобеды: 120000 });
check(выше.годится === false, 'цена победы выше НМЦК отброшена — это невозможно по 44-ФЗ');
check(/разбор неверен/.test(выше.причина), 'названо, что виноват разбор, а не рынок');

const дико = P.наблюдение({ способ: P.СПОСОБ.АУКЦИОН, нмцк: 100000, ценаПобеды: 1000 });
check(дико.годится === false, 'снижение 99% отброшено как неправдоподобное');

const безЦены = P.наблюдение({ способ: P.СПОСОБ.АУКЦИОН, нмцк: 100000, ценаПобеды: null });
check(безЦены.годится === false, 'без цены победы наблюдения нет');

