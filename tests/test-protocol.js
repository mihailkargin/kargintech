check(ндЕд.наблюдение && ндЕд.наблюдение.снижение === 14,
  `снижение 14% (получено ${ндЕд.наблюдение && ндЕд.наблюдение.снижение})`);
check(ндЕд.наблюдение && ндЕд.наблюдение.единственнаяЗаявка === true,
  'пометка «единственная заявка» доходит до наблюдения — без неё статистика смешала бы '
  + 'её с конкурентными и занизила снижение');
check(ндЕд.наблюдение && ндЕд.наблюдение.участников === 1,
  'число участников известно точно и без списка заявок: портал назвал это основанием');

