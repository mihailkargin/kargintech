section('АДРЕСА СТРАНИЦ: сверены с разметкой, а не выведены по аналогии');
// ======================================================================
// Имя страницы списка заявок я сначала написал как protocol-bids-list — по
// аналогии с подписью вкладки «Список заявок». Это был домысел, настоящее имя
// protocol-bid-list, в единственном числе. Опечатка не падает, а даёт 404, то
// есть выглядела бы как «списка заявок у этой закупки нет», и число участников
// не определялось бы НИ ПО ОДНОЙ закупке. Поэтому ожидаемые адреса здесь взяты
// дословно из разметки сохранённых страниц.
check(
  P.адресРезультатов('https://zakupki.gov.ru/epz/order/notice/ea20/view/common-info.html?regNumber=0119600018526000086')
  === 'https://zakupki.gov.ru/epz/order/notice/ea20/view/supplier-results.html?regNumber=0119600018526000086',
  'адрес результатов у аукциона совпал с тем, что печатает портал'
);
check(
  P.адресРезультатов('https://zakupki.gov.ru/epz/order/notice/zk20/view/common-info.html?regNumber=0173200021826000009')
  === 'https://zakupki.gov.ru/epz/order/notice/zk20/view/supplier-results.html?regNumber=0173200021826000009',
  'и у запроса котировок — сегмент пути zk20 сохранён, а не заменён'
);
check(P.адресРезультатов('') === '', 'пустая ссылка даёт пустую, а не мусор');

const адресПротокола = 'https://zakupki.gov.ru/epz/order/notice/ea20/view/protocol/'
  + 'protocol-main-info.html?regNumber=0119600018526000086&type=iea&version=1';
check(
  P.адресСпискаЗаявок(адресПротокола)
  === 'https://zakupki.gov.ru/epz/order/notice/ea20/view/protocol/'
     + 'protocol-bid-list.html?regNumber=0119600018526000086&type=iea&version=1',
  'адрес списка заявок — protocol-bid-list, в единственном числе'
);
check(!/protocol-bids-list/.test(P.адресСпискаЗаявок(адресПротокола)),
  'прежний домысел protocol-bids-list не вернулся');
check(/type=iea&version=1/.test(P.адресСпискаЗаявок(адресПротокола)),
  'тип протокола и версия сохранены — из номера закупки их не вывести');

// Ссылки на протоколы берутся из разметки: сконструировать их нельзя, в них тип
