// ======================================================================
// Найдено 05.10.2026. Закупка 0117100015526000101 («заправка картриджей и ремонт
// печатной техники», НМЦК 1 412 900) дала «снижение 89,9%». Предложения
// участников: 143 145, 147 762, 401 730, 914 281 — разброс в шесть раз на один
// лот. В обычной закупке предложения кучкуются: участники считают одну и ту же
// поставку. Шестикратный разброс означает, что они считали РАЗНОЕ.
function списокИзЦен(цены) {
  const строки = цены.map((ц, i) => `
    <tr><td class="tableBlock__col">${1219000 + i}</td>
        <td class="tableBlock__col">0${i + 1}.10.2026 10:0${i} (МСК)</td>
        <td class="tableBlock__col">Соответствует требованиям</td>
        <td class="tableBlock__col">${i === 0 ? '1 - Победитель' : ''}</td>
        <td class="tableBlock__col">${ц} &#8381;</td></tr>`).join('');
  return `<table><thead><tr>
    <th class="tableBlock__col_header">Идентификационный номер участника</th>
    <th class="tableBlock__col_header">Дата и время подачи заявки</th>
    <th class="tableBlock__col_header">Результат рассмотрения заявки</th>
    <th class="tableBlock__col_header">Порядковый номер</th>
    <th class="tableBlock__col_header">Предлагаемая цена</th>
  </tr></thead><tbody>${строки}</tbody></table>`;
}

