section('РЕАЛЬНАЯ СТРАНИЦА: запрос котировок 0173200021826000009');
// ======================================================================
const кот = P.parseSupplierResults(
  читать('supplier-results-0173200021826000009.html'),
  'https://zakupki.gov.ru/x?regNumber=0173200021826000009'
);

check(кот.способ === P.СПОСОБ.КОТИРОВКИ, `способ распознан: ${кот.способ}`);
check(кот.нмцк === 491302, `НМЦК 491 302 (получено ${кот.нмцк})`);
check(кот.ценаПобеды === 418600, `цена победы 418 600 (получено ${кот.ценаПобеды})`);
check(P.снижение(кот.нмцк, кот.ценаПобеды) === 14.8,
  `снижение по этой странице посчитано верно (получено ${P.снижение(кот.нмцк, кот.ценаПобеды)})`);

// Два способа закупки дают сильно разное снижение — причина не смешивать их
// в одной выборке. Сравниваются ПОСЧИТАННЫЕ значения, а не вписанные числа:
// сравнение двух констант не проверяет ничего.
const снижениеАукцион = P.снижение(авк.нмцк, авк.ценаПобеды);
const снижениеКотировки = P.снижение(кот.нмцк, кот.ценаПобеды);
check(Math.abs(снижениеАукцион - снижениеКотировки) > 15,
  'снижение у аукциона и котировок на этих страницах различается больше чем вдвое '
  + '— смешивать способы в одной выборке нельзя');

