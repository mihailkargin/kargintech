const списокКот = P.parseBidList(читать('bid-list-0173200021826000009-izk.html'));
check(списокКот.заявки.length === 10, `заявок на странице ровно 10 (получено ${списокКот.заявки.length})`);
check(списокКот.участниковТочно === false,
  'страница заполнена доверху — число участников НЕ считается известным');
check(списокКот.issues.some((i) => /возможно, есть ещё/.test(i)),
  'сказано прямо, что заявок может быть больше');

// Почему это важно: занижение числа участников делает закупку менее
// конкурентной на вид, то есть ожидаемое снижение занижается.
function списокАvk_безопасно(s) { return s.участников; }

