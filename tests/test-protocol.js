section('ЦЕНА ИЗ ТЕКСТА НЕ ВЫДУМЫВАЕТСЯ — ловушка найдена на реальной странице');
// ======================================================================
// У отклонённых заявок колонки цены нет, зато есть причина отклонения:
// «Несоответствие требованиям ст. 14 Закона № 44 ФЗ». Общая parseMoney
// выбрасывает всё кроме цифр, склеивает «14» и «44» и возвращает 1444 — и это
// попадало в вывод как цена предложения у четырёх заявок.
const списокАвк = P.parseBidList(читать('bid-list-0119600018526000086-iea.html'));

check(списокАвк.заявки.length === 7, `заявок на странице 7 (получено ${списокАвк.заявки.length})`);

const отклонённые = списокАвк.заявки.filter((з) => з.отклонена);
check(отклонённые.length === 4, `отклонённых 4 (получено ${отклонённые.length})`);
check(отклонённые.every((з) => з.цена === null),
  'у отклонённых заявок цена именно null, а не выдуманная из текста причины');
check(!списокАвк.заявки.some((з) => з.цена === 1444),
  'числа 1444, склеенного из «ст. 14» и «№ 44», нигде нет');

const принятые = списокАвк.заявки.filter((з) => !з.отклонена);
check(принятые.length === 3 && принятые.every((з) => з.цена > 1000),
  'у принятых заявок цены на месте');
check(принятые[0].цена === 52041.28 && принятые[1].цена === 65150.92,
  `цены по возрастанию: ${принятые.map((з) => з.цена).join(', ')}`);

// Идентификационный номер участника для parseMoney — законное число.
check(!списокАвк.заявки.some((з) => з.цена !== null && String(з.цена) === з.ид),
  'идентификатор участника не принят за цену');

