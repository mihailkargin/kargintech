section('ПОДПИСЬ ПУСТОГО ПОЛЯ ПРИЗНАКОМ НЕ СЧИТАЕТСЯ');
// ======================================================================
// Слово «несостоявшимися» стоит в самой подписи поля, а подпись портал может
// печатать всегда — в том числе над пустым значением. Если считать её признаком,
// несостоявшимися окажутся ВСЕ закупки подряд, и настоящие ошибки разбора
// спрячутся под штатной причиной. Это тот же класс ошибки, что «Недействующая»
// редакция документации: подстрока «действующ» есть и в слове «недействующая».
const страницаСПустойПодписью = `
<div class="section__title">Способ определения поставщика</div>
<div class="section__info">Электронный аукцион</div>
<div class="section__title">Основание признания торгов несостоявшимися</div>
<div class="section__info"></div>
<div class="cardMainInfo__title">Начальная цена</div>
<div class="cardMainInfo__content">100 000,00 &#8381;</div>
<table><thead><tr><th>Предложения участников, &#8381;</th><th>Порядковые номера</th></tr></thead>
<tbody><tr><td>80 000,00</td><td>1 - Победитель</td></tr></tbody></table>`;

const пуст = P.parseSupplierResults(страницаСПустойПодписью, '?regNumber=1');
check(пуст.неСостоялась === false,
  'подпись есть, значения нет — закупка НЕ считается несостоявшейся');
check(пуст.признакиНесостоявшейся.some((п) => /может быть подписью/.test(п)),
  'но слово в тексте названо отдельно, как ненадёжный признак');
check(пуст.ценаПобеды === 80000, `цена победы найдена (получено ${пуст.ценаПобеды})`);

// ======================================================================
section('НЕСКОЛЬКО СТРОК БЕЗ ПОБЕДИТЕЛЯ: ЦЕНА НЕ УГАДЫВАЕТСЯ');
// ======================================================================
// Привязка строк к своей таблице убрала требование слова «Победитель». Но она
// не должна превратиться в «бери первую строку с ценой»: у многолотовой закупки
// строк несколько, и выбор наугад дал бы тихо неверное снижение.
const многоЛотов = `
<div class="cardMainInfo__title">Начальная цена</div>
<div class="cardMainInfo__content">500 000,00 &#8381;</div>
<table><thead><tr><th>Предложения участников, &#8381;</th></tr></thead>
<tbody><tr><td>300 000,00</td></tr><tr><td>120 000,00</td></tr></tbody></table>`;

const мл = P.parseSupplierResults(многоЛотов, '?regNumber=2');
check(мл.победители.length === 2, `строк предложений 2 (получено ${мл.победители.length})`);
check(мл.ценаПобеды === null, 'цена победы не выбрана — угадывать нельзя');
check(мл.многоБезПобедителя === true, 'случай помечен отдельным признаком');
const ндМл = P.наблюдение(мл, null);
check(!ндМл.годится && /многолотов/.test(ндМл.причина),
  'причина отказа названа своим именем, а не «проверить разбор»');

