/**
 * Фоновый разбор документации и повторная проверка фильтров по ТЗ.
 * Запуск: node tests/test-parse-queue.js
 *
 * Расчёт подменяется: портал и модель здесь не нужны, проверяется порядок,
 * сохранность очереди, остановка при отказе портала и отсутствие денег.
 */
const fs = require('fs');
const os = require('os');
const path = require('path');
const { проверкаПоТЗ } = require('../src/filter');
const очередь = require('../app/parse-queue');

let failures = 0;
const check = (ok, message) => {
  console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${message}`);
  if (!ok) failures++;
};
const section = (name) => console.log(`\n=== ${name} ===`);

section('Фильтр по ТЗ: только стоп-слова');
const фильтр = { keywords: ['канцеляр'], stopWords: ['ремонт', 'аренда'] };
const чисто = проверкаПоТЗ(['Антистеплер', 'Дырокол 30 л'], фильтр);
check(чисто.прошёл, 'позиции без основы «канцеляр» НЕ отсеиваются — ключевые слова по ТЗ не проверяются');
const грязно = проверкаПоТЗ(['Бумага А4', 'Ремонт принтера HP'], фильтр);
check(!грязно.прошёл && /ремонт/.test(грязно.причины[0]), `стоп-слово в позиции отсеивает: ${грязно.причины[0]}`);
check(проверкаПоТЗ(['Бумага'], {}).прошёл, 'без стоп-слов всё проходит');

section('Очередь: порядок, сохранность, деньги');
const каталог = fs.mkdtempSync(path.join(os.tmpdir(), 'queue-'));
const н = { каталогДанных: каталог };
const тендер = (n) => ({ number: String(n), url: `https://x/${n}`, price: 100000, object: 'Бумага' });

const добавлено = очередь.поставитьВОчередь('kargin', [тендер(1), тендер(2), тендер(2), { number: '3' }], н);
check(добавлено === 2, `повтор и тендер без ссылки не ставятся (добавлено ${добавлено})`);

const вызовы = [];
const подмена = async (закупка, настройки) => {
  вызовы.push({ закупка, настройки });
  return {
    ok: true,
    estimate: { rows: [{ name: 'Бумага А4', priceForCalc: 300, basis: 'верхняя граница цены' }] },
    сводкаРазбора: { годен: true, естьТЗ: true, прочитаноКодом: 3 },
    итоги: { закупкаИзвестна: true, закупка: 300 }
  };
};

(async () => {
  const r = await очередь.обработатьОчередь('kargin', фильтр, н, { собрать: подмена, пауза: 0, журнал: () => {} });
  check(r.сделано === 2, `разобраны оба (${r.сделано})`);
  check(вызовы.every((в) => в.настройки.anthropicKey === '' && в.настройки.proxyUrl === ''
    && в.настройки.искатьПоставщиков === false && в.настройки.сканыМоделью === false),
  'в расчёт переданы пустой ключ и посредник — платных обращений нет устройством');
  const с = очередь.состояние('kargin', н);
  check(с.очередь.length === 0 && Object.keys(с.разборы).length === 2, 'очередь пуста, итоги записаны');
  check(с.разборы['1'].позиций === 1 && с.разборы['1'].естьТЗ === true, 'итог разбора содержит позиции и ТЗ');
  check(!('estimate' in с.разборы['1']), 'смета в файл итогов не пишется — лишнего места хранения прайса нет');
  check(очередь.поставитьВОчередь('kargin', [тендер(1)], н) === 0, 'уже разобранный тендер повторно не ставится');

  section('Отказ портала — остановка, остаток сохранён');
  очередь.поставитьВОчередь('k2', [тендер(10), тендер(11), тендер(12), тендер(13)], н);
  const отказ = async () => ({ ok: false, сбой: 'карточка закупки недоступна: код 403' });
  const о = await очередь.обработатьОчередь('k2', {}, н, { собрать: отказ, пауза: 0, журнал: () => {} });
  check(о.остановлен && о.сделано === 2, `после двух отказов подряд остановлено (${о.сделано})`);
  check(очередь.состояние('k2', н).очередь.length === 2, 'остаток очереди сохранён для следующего запуска');

  section('Отменённая закупка — не неудача разбора');
  const отм = очередь.итогРазбора(тендер(30), { ok: false, сбой: 'закупка отменена заказчиком', отменена: true }, {}, new Date());
  check(отм.отменена === true && отм.ок === false, 'признак отмены сохранён в итоге');
  const обычный = очередь.итогРазбора(тендер(31), { ok: false, сбой: 'карточка закупки недоступна' }, {}, new Date());
  check(обычный.отменена === false, 'обычный сбой отменой не помечается');

  section('Два обхода одновременно не запускаются');
  очередь.поставитьВОчередь('k3', [тендер(20), тендер(21)], н);
  const медленно = async () => { await new Promise((r2) => setTimeout(r2, 30)); return { ok: false, сбой: 'нет' }; };
  const [а, б] = await Promise.all([
    очередь.обработатьОчередь('k3', {}, н, { собрать: медленно, пауза: 0, журнал: () => {} }),
    очередь.обработатьОчередь('k3', {}, н, { собрать: медленно, пауза: 0, журнал: () => {} })
  ]);
  check(а.запущен !== б.запущен, 'второй вызов отказывается, пока идёт первый');

  // Тест «слаботочка» 20.10.2026: просроченные и «единственный поставщик» не разбираются.
  {
    const { незачемРазбирать } = require('../app/parse-queue');
    const сегодня = new Date('2026-10-20T10:00:00Z');
    check(/срок подачи истёк/.test(незачемРазбирать({ deadline: '2026-10-14' }, сегодня) || ''), 'срок подачи истёк — не разбираем');
    check(незачемРазбирать({ deadline: '2026-10-20' }, сегодня) === null, 'срок сегодня — разбираем');
    check(/единственного/.test(незачемРазбирать({ deadline: '2026-10-30', law: '223-ФЗ Закупка у единственного поставщика' }, сегодня) || ''),
      'единственный поставщик — не разбираем');
    check(незачемРазбирать({ law: '44-ФЗ Электронный аукцион' }, сегодня) === null, 'без срока и обычный способ — разбираем');
  }

  section('Только выбранные номера - прочая очередь не трогается (20.10.2026)');
  {
    очередь.поставитьВОчередь('k4', [тендер(40), тендер(41), тендер(42)], н);
    const взяты = [];
    const учёт = async (закупка) => { взяты.push(закупка.ссылка); return { ok: false, сбой: 'нет' }; };
    const р = await очередь.обработатьОчередь('k4', {}, н, { собрать: учёт, пауза: 0, журнал: () => {}, только: new Set(['41']) });
    check(р.сделано === 1 && взяты.length === 1 && /41$/.test(взяты[0]), `разобран только № 41 (взяты: ${взяты.join(', ')})`);
    const ост = очередь.состояние('k4', н).очередь.map((x) => x.number);
    check(ост.join(',') === '40,42', `40 и 42 остались в очереди по порядку (${ост.join(',')})`);
  }

  section('Ближайший срок подачи - первым (24.10.2026)');
  {
    const через = (дней) => new Date(Date.now() + дней * 86400000).toISOString().slice(0, 10);
    очередь.поставитьВОчередь('k5', [{ ...тендер(50), deadline: через(9) }, { ...тендер(51) }, { ...тендер(52), deadline: через(1) }, { ...тендер(53), deadline: через(4) }], н);
    const взяты = [];
    const учёт = async (закупка) => { взяты.push(закупка.ссылка.slice(-2)); return { ok: false, сбой: 'нет' }; };
    await очередь.обработатьОчередь('k5', {}, н, { собрать: учёт, пауза: 0, журнал: () => {} });
    check(взяты.join(',') === '52,53,50,51', `порядок по сроку, без срока - последним (${взяты.join(',')})`);
    очередь.поставитьВОчередь('k6', [тендер(60), тендер(61), тендер(62)], н);
    const р6 = await очередь.обработатьОчередь('k6', {}, н, { собрать: учёт, пауза: 0, журнал: () => {}, предел: 2 });
    check(р6.предел && р6.сделано === 2 && очередь.состояние('k6', н).очередь.length === 1, 'предел 2 - разобраны две, третья ждёт своей очереди');
  }

  section('Поставленное во время разбора не теряется (24.10.2026)');
  {
    очередь.поставитьВОчередь('k9', [тендер(90)], н);
    const вовремя = async () => { очередь.поставитьВОчередь('k9', [тендер(91)], н); return { ok: false, сбой: 'нет' }; };
    await очередь.обработатьОчередь('k9', {}, н, { собрать: вовремя, пауза: 0, журнал: () => {}, только: new Set(['90']) });
    const ост = очередь.состояние('k9', н).очередь.map((x) => x.number);
    check(ост.join() === '91', `закупка 91, добавленная поиском во время разбора 90, осталась в очереди (${ост.join()})`);
  }

  section('Готовый разбор другого клиента (24.10.2026)');
  {
    // У «kargin» тендер 1 разобран удачно выше. Клиент без прайса берёт его без портала.
    const настройки = { kargin: {}, k7: {}, k8: { прайс: 'k8.csv' }, ksp: {} };
    const чтение = (x) => настройки[x] || null;
    const взяты = [];
    const учёт = async (закупка) => { взяты.push(закупка.ссылка); return { ok: false, сбой: 'нет' }; };
    очередь.поставитьВОчередь('k7', [тендер(1)], н);
    await очередь.обработатьОчередь('k7', { filter: { stopWords: ['бумаг'] } }, н, { собрать: учёт, пауза: 0, журнал: () => {}, настройкиКлиента: чтение });
    const р7 = очередь.состояние('k7', н).разборы['1'];
    check(взяты.length === 0 && р7 && р7.ок && р7.изОбщего === 'kargin', `взят готовый разбор kargin, к порталу не ходили (${взяты.length})`);
    check(р7 && р7.фильтрПоТЗ && !р7.фильтрПоТЗ.прошёл, 'стоп-слова пересчитаны по фильтру своего клиента');
    // Клиент с прайсом чужой разбор не берёт.
    очередь.поставитьВОчередь('k8', [тендер(1)], н);
    await очередь.обработатьОчередь('k8', { прайс: 'k8.csv' }, н, { собрать: учёт, пауза: 0, журнал: () => {}, настройкиКлиента: чтение });
    check(взяты.length === 1, 'у клиента с прайсом - свой разбор');
    // Разбор клиента с прайсом другим не отдаётся; неудачный - тоже.
    очередь.поставитьВОчередь('ksp', [тендер(10)], н);
    await очередь.обработатьОчередь('ksp', {}, н, { собрать: учёт, пауза: 0, журнал: () => {}, настройкиКлиента: чтение });
    check(взяты.length === 2, 'неудачный чужой разбор не берётся');
  }

  // Архив закупок держит файл открытым - на Windows открытый файл не удалить.
  require('../app/archive').закрыть();
  fs.rmSync(каталог, { recursive: true, force: true });
  console.log(`\n${failures === 0 ? 'ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ' : 'ПРОВАЛЕНО ПРОВЕРОК: ' + failures}`);
  process.exit(failures === 0 ? 0 : 1);
})();
