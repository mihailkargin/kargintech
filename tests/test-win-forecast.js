/**
 * Тесты: прогноз цены победы (src/win-forecast.js), 30.10.2026.
 * Запуск: node tests/test-win-forecast.js
 */
const В = require('../src/win-forecast');

let failures = 0;
function check(ok, label) {
  console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${label}`);
  if (!ok) failures++;
}

// Наблюдение: аукцион, группа 17.12, 2026 год (знаки 12-13 номера 44-ФЗ).
let счётчик = 0;
const н = (снижение, о = {}) => ({
  номер: о.номер || `03731000104${о.гг || '26'}${String(++счётчик).padStart(6, '0')}`,
  способ: 'электронный аукцион', нмцк: о.нмцк || 100000, снижение,
  участников: о.участников ?? (снижение === 0 ? 1 : 3), единственнаяЗаявка: снижение === 0,
  группаОкпд2: о.группа || '17.12'
});
const тендер = { нмцк: 100000, способ: 'электронный аукцион', группыОкпд2: ['17.12'], год: 2026 };

console.log('=== Год из номера ===');
check(В.годЗакупки('0373100010426000011') === 2026, '44-ФЗ 0373100010426000011 - 2026');
check(В.годЗакупки('32616502292') === 2026, '223-ФЗ 32616502292 - 2026');
check(В.годЗакупки('123') === null, 'непонятный номер - год неизвестен, не «текущий»');

console.log('=== Отбор: меньше 10 - не показывается, товар не отпускается ===');
const мало = Array.from({ length: 9 }, (_, i) => н(10 + i));
check(!В.прогнозЦеныПобеды(мало, тендер).показан && /нужно не меньше 10/.test(В.прогнозЦеныПобеды(мало, тендер).причина), '9 похожих - прогноза нет, причина названа');
const чужие = Array.from({ length: 40 }, (_, i) => н(10 + i % 20, { группа: '20.59' }));
check(В.отобрать(чужие, тендер).похожие.length === 0, '40 закупок другого товара (20.59) - в похожие не берутся, даже на широкой ступени');
check(В.отобрать(чужие, { ...тендер, группыОкпд2: [] }).причина.includes('ОКПД2'), 'товар тендера неизвестен - похожие не отбираются');
const старые = Array.from({ length: 35 }, (_, i) => н(10 + i % 20, { гг: '22' }));
check(В.отобрать(старые, тендер).похожие.length === 0, 'закупки 2022 года для тендера 2026 - не берутся');

console.log('=== Расширение отбора до 30 ===');
const узко = Array.from({ length: 12 }, (_, i) => н(10 + i));
const шире = Array.from({ length: 25 }, (_, i) => н(10 + i % 15, { нмцк: 280000 }));
const о = В.отобрать([...узко, ...шире], тендер);
check(о.похожие.length === 37 && /1\/3 до 3/.test(о.ступень.текст), '12 рядом + 25 с НМЦК 2,8 раза - расширено до «1/3-3 раза», 37 похожих');

console.log('=== Частоты и процентили ===');
// 40 закупок: 10 с одной заявкой (0%), 30 - снижения 5..34%.
const набор = [...Array.from({ length: 10 }, () => н(0)), ...Array.from({ length: 30 }, (_, i) => н(5 + i))];
const п = В.прогнозЦеныПобеды(набор, тендер, { запас: 20, запасЛучший: 25, налог: 0.06 }, { калибровка: { прошла: true } });
check(п.показан && п.похожих === 40 && !п.мало, '40 похожих, прогноз показан (калибровка пройдена)');
check(п.одинУчастник === 25, 'одна заявка - в 25% закупок');
check(п.снижение.медиана === 14.5 && п.снижение.p2_5 === 0, 'медиана снижения 14,5%, нижний край 0% (пик одной заявки не срезан)');
check(п.антидемпинг === 25, 'снижение от 25% - в 25% закупок (10 из 40)');
check(Math.abs(В.вероятностьПобеды(набор.map((x) => x.снижение), 20) - 25 / 40) < 1e-9, 'ставка 20%: выиграл бы там, где победитель снизил меньше 20% - 25 из 40');

console.log('=== Рекомендуемая цена ===');
const р = п.поЛучшей.рекомендация;
check(р && р.снижение > 5 && р.снижение < 25, `рекомендация между снижением конкурентов и безубыточностью, не «0,1% у одной заявки» (снижение ${р && р.снижение}%)`);
// Перебором по конкурентным: ожидаемая прибыль рекомендации не меньше, чем у любой ставки 0..24,9.
const сн = набор.filter((x) => !x.единственнаяЗаявка).map((x) => x.снижение);
let максE = 0;
for (let d = 0; d < 25; d += 0.1) максE = Math.max(максE, (1 - 0.06) * 100000 * (25 - d) / 100 * В.вероятностьПобеды(сн, d));
check(р.ожидаемаяПрибыль >= Math.round(максE) - 1, `ожидаемая прибыль ${р.ожидаемаяПрибыль} - максимум перебора (${Math.round(максE)})`);
check(В.рекомендация(сн, 0, 100000) === null && В.рекомендация(сн, -5, 100000) === null, 'запаса нет - рекомендации нет');
check(п.поЛучшей.вероятностьПриБезубыточности === 66.7, 'по цене безубыточности (снижение 25%) - победа в 20 из 30 конкурентных');
const малоКонк = [...Array.from({ length: 25 }, () => н(0)), ...Array.from({ length: 6 }, (_, i) => н(10 + i))];
const мк = В.прогнозЦеныПобеды(малоКонк, тендер, { запас: 20 }, { калибровка: { прошла: true } });
check(мк.показан && !мк.поХудшей && /2\+ участниками 6/.test(мк.безВероятности), '6 конкурентных из 31 - рынок показан, вероятность победы - нет, причина названа');
const бп = В.прогнозЦеныПобеды(набор, тендер, { запас: 20, толькоПотолки: true }, { калибровка: { прошла: true } });
check(!бп.поХудшей && !бп.поЛучшей, 'только потолочные цены - вывода о выгоде нет, только рынок');

console.log('=== Показ - только после обратной проверки ===');
const без = В.прогнозЦеныПобеды(набор, тендер, { запас: 20 });
check(!без.показан && /не проводилась/.test(без.причина) && В.текстПрогноза(без) === '', 'без калибровки - клиенту не показывается');
check(/Рекомендуемая цена/.test(В.текстПрогноза(п)) && /не обещание/.test(В.текстПрогноза(п)), 'текст: рекомендуемая цена и оговорка «не обещание»');

console.log('=== Обратная проверка обязана уметь не пройти ===');
// Однородный рынок: снижение не зависит от суммы - прогноз сбывается.
let сид = 7;
const случ = () => { сид = (сид * 16807) % 2147483647; return сид / 2147483647; };
const рынок = Array.from({ length: 300 }, () => н(Math.round(случ() * 35 * 10) / 10, { нмцк: 50000 + Math.round(случ() * 100000) }));
const к1 = В.калибровка(рынок);
check(к1.закупок > 100 && к1.корзины.length >= 3, `однородный рынок: проверено ${к1.закупок} закупок, ${к1.пар} пар`);
check(к1.корзины.filter((к) => к.пар >= 20).every((к) => Math.abs(к.предсказано - к.сбылось) <= 10), 'однородный рынок: прогноз и факт сходятся в пределах 10 п.п.');
check(к1.прошла, `однородный рынок: проверка пройдена${к1.почему ? ' - ' + к1.почему : ''}`);
// Рынок сменился: в 2025 снижали на 0-10%, в 2026 - на 20-35%. Прогноз для 2026
// берёт и прошлый год - вероятность «победить со снижением 15%» около половины,
// а на деле в 2026 никто не снижал меньше 20%. Проверка обязана это поймать.
const сдвиг = Array.from({ length: 300 }, (_, i) => (i % 2
  ? н(Math.round(случ() * 100) / 10, { гг: '25' })
  : н(Math.round((20 + случ() * 15) * 10) / 10, { гг: '26' })));
const к3 = В.калибровка(сдвиг);
check(!к3.прошла && /расхождение больше 10/.test(к3.почему), `рынок сменился за год - проверка НЕ пройдена (${к3.почему.slice(0, 90)})`);
// Рынок, где глубина снижения зависит от суммы: отбор по НМЦК должен помогать.
const зависит = Array.from({ length: 300 }, () => { const нм = случ() < 0.5 ? 50000 : 400000; return н(Math.round((нм < 100000 ? случ() * 10 : 20 + случ() * 15) * 10) / 10, { нмцк: нм }); });
const к2 = В.калибровка(зависит);
check(к2.брайер < к2.брайерБазовый, `снижение зависит от суммы: по похожим точнее (Брайер ${к2.брайер} < ${к2.брайерБазовый})`);
check(к2.прошла, `и проверка пройдена${к2.почему ? ': ' + к2.почему : ''}`);
check(!В.калибровка(рынок.slice(0, 15)).прошла, '15 закупок - мало данных, не пройдена');

console.log('=== Поправка по обратной проверке (31.10) ===');
// Прогноз завышен как на реальных данных: говорит p, сбывается 0,85·p.
const пары = [];
for (let i = 0; i < 2000; i++) { const p = случ(); пары.push({ номер: `N${i}`, p, базовая: 0.5, было: случ() < 0.85 * p ? 1 : 0 }); }
check(!В.оценитьПары(пары).прошла, 'завышенный прогноз без поправки - не проходит');
const т = В.таблицаПоправки(пары);
check(т.every((x, i) => i === 0 || x.f >= т[i - 1].f), 'таблица поправки не убывает: больший прогноз не даёт меньший шанс');
check(Math.abs(В.поправить(0.8, т) - 0.68) < 0.06, `прогноз 80% поправлен до ~68% (${(100 * В.поправить(0.8, т)).toFixed(1)}%)`);
check(В.поправить(0.999, т) <= т[т.length - 1].f + 1e-9, 'выше последней точки шанс не повышается');
const пп = В.проверитьПоправку(пары);
check(пп.проверена && пп.половины.length === 2, `поправка проверена на половинах, которых не видела${пп.почему ? ' - ' + пп.почему : ''}`);
// Шум без связи прогноза с исходом: поправка не должна «спасать» такой прогноз.
const шум = Array.from({ length: 2000 }, (_, i) => ({ номер: `S${i}`, p: случ(), базовая: 0.5, было: случ() < 0.5 ? 1 : 0 }));
check(!В.проверитьПоправку(шум).проверена, 'прогноз без связи с исходом - поправка не проходит (хуже общей доли или мало корзин)');
const сП = В.прогнозЦеныПобеды(набор, тендер, { запас: 20, запасЛучший: 25 }, { калибровка: { прошла: false, почему: 'x', поправка: { проверена: true, таблица: [{ p: 0.2, f: 0.15 }, { p: 0.8, f: 0.6 }] } } });
check(сП.показан && сП.споправкой && сП.поЛучшей.вероятностьБезПоправки === 66.7 && сП.поЛучшей.вероятностьПриБезубыточности < 66.7, `проверенная поправка: шанс показан поправленным (${сП.поЛучшей.вероятностьПриБезубыточности}% вместо 66,7%)`);
const неП = В.прогнозЦеныПобеды(набор, тендер, { запас: 20 }, { калибровка: { прошла: false, почему: 'x', поправка: { проверена: false, почему: 'y', таблица: т } } });
check(!неП.показан, 'непроверенная поправка - прогноз не показывается');

console.log(failures ? `\nСБОЕВ: ${failures}` : '\nВсе проверки прошли');
process.exit(failures ? 1 : 0);
