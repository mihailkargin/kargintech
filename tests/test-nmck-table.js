let failures = 0;
const check = (ok, message) => {
  console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${message}`);
  if (!ok) failures++;
};
const section = (name) => console.log(`\n=== ${name} ===`);

const DIR = path.join(__dirname, '..', 'fixtures', 'phase2');
const have = fs.existsSync(DIR);
const readReal = (file) => {
  const full = path.join(DIR, file);
  if (!fs.existsSync(full)) return null;
  const r = extractText(fs.readFileSync(full), file);
  return r.ok ? parseNmckTable(r.text) : null;
};

