/**
 * Полный поток закупок (app/stream.js): свежее до известного, добор вглубь,
 * сдвиг позиции добора, отказ портала, срок хранения. Портал подменён, база -
 * во временном каталоге. Запуск: node --disable-warning=ExperimentalWarning tests/test-stream.js
 */
const fs = require('fs');
const os = require('os');
const path = require('path');
const поток = require('../app/stream');

let failures = 0;
const check = (ok, m) => { console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${m}`); if (!ok) failures++; };

const каталог = fs.mkdtempSync(path.join(os.tmpdir(), 'stream-'));
const файл = path.join(каталог, 'archive.db');
const now = new Date('2026-10-23T09:00:00Z');
const тело = 'x'.repeat(3000);

// Портал: лента карточек сверху вниз (новые сверху), страница по 100.
function портал(лента, коды = {}) {
  const п = {
    адреса: [],
    адрес: (стр) => `https://zakupki.gov.ru/x?pageNumber=${стр}`,
    взять: async (u) => {
      п.адреса.push(u);
      const стр = Number(/pageNumber=(\d+)/.exec(u)[1]);
      if (коды[стр]) return { ok: false, код: коды[стр] };
      return { ok: true, код: 200, тело: стр + '|' + тело };
    },
    разобрать: (т) => { const стр = Number(т.split('|')[0]); return лента.slice((стр - 1) * 100, стр * 100); }
  };
  return п;
}
const карт = (префикс, n, updated, deadline = '2026-11-10') => Array.from({ length: n }, (_, i) => ({ number: `${префикс}${i}`, updated, deadline, object: `Закупка ${префикс}${i}` }));
const стр = (п) => п.адреса.map((u) => Number(/pageNumber=(\d+)/.exec(u)[1])).join();

(async () => {
  try {
    console.log('\n=== Свежее ===');
    // На портале: 250 сегодняшних, ниже 900 старых (до месяца).
    let лента = [...карт('с', 250, '2026-10-23'), ...карт('ст', 900, '2026-10-10')];
    const п1 = портал(лента);
    const r1 = await поток.прогон({ ...п1, режим: 'свежее', страниц: 3, пауза: 0, now, файл });
    check(r1.запросов === 3 && r1.новых === 300, 'первый прогон: 3 страницы по пределу');

    // Через 10 минут: сверху 30 новых.
    лента = [...карт('н', 30, '2026-10-23'), ...лента];
    const п2 = портал(лента);
    const r2 = await поток.прогон({ ...п2, режим: 'свежее', страниц: 20, пауза: 0, now, файл });
    check(стр(п2) === '1' && r2.новых === 30, 'свежее: одна страница, дошли до известных');

    console.log('\n=== Добор ночью срезами ===');
    {
      // Портал как настоящий: фильтры по закону, дню размещения и цене, не глубже
      // 50 страниц (дальше - снова 50-я), подпись «всего» над выдачей.
      const { всегоНаПортале } = require('../app/search-run');
      const все = [];
      for (let i = 0; i < 7000; i++) все.push({ number: `a${i}`, law: '44', day: '2026-10-20', price: 50000 + (i % 700) * 10000, updated: '2026-10-20', deadline: '2026-11-05' });
      for (let i = 0; i < 300; i++) все.push({ number: `b${i}`, law: '223', day: '2026-10-20', price: 200000, updated: '2026-10-20', deadline: '2026-11-05' });
      for (let i = 0; i < 40; i++) все.push({ number: `c${i}`, law: '44', day: '2026-10-05', price: 90000, updated: '2026-10-05', deadline: '2026-11-01' });
      const адреса = [];
      const дата = (д) => д.split('-').reverse().join('.');
      const о = {
        адрес: () => 'не нужен',
        адресСреза: (с, стр) => `закон=${с.закон}&день=${дата(с.день)}&от=${с.от ?? ''}&до=${с.до ?? ''}&стр=${стр}`,
        взять: async (u) => {
          адреса.push(u);
          const п = Object.fromEntries(u.split('&').map((x) => x.split('=')));
          const отбор = все.filter((к) => к.law === п['закон'] && дата(к.day) === п['день']
            && (п['от'] === '' || к.price >= Number(п['от'])) && (п['до'] === '' || к.price <= Number(п['до'])));
          const стрн = Math.min(50, Number(п['стр']));
          const подпись = отбор.length > 5000 ? `более ${отбор.length}` : `${отбор.length}`;
          return { ok: true, код: 200, тело: JSON.stringify(отбор.slice((стрн - 1) * 100, стрн * 100)) + `\n<div class="search-results__total"> ${подпись} записей </div>` + тело };
        },
        разобрать: (т) => JSON.parse(т.slice(0, т.indexOf('\n'))),
        всего: всегоНаПортале
      };
      const файл2 = path.join(каталог, 'a2.db');
      const журнал = [];
      let прогонов = 0;
      while (!поток.сводка(файл2).доборГотов && прогонов < 20) {
        await поток.прогон({ ...о, режим: 'добор', страниц: 30, пауза: 0, now, файл: файл2, журнал });
        прогонов++;
      }
      const взято = поток.действующие(now, файл2).length;
      check(поток.сводка(файл2).доборГотов && взято === 7340, `добор прошёл все срезы за 30 дней: взято ${взято} из 7340, прогонов ${прогонов}`);
      check(журнал.some((с) => /2026-10-20 44-ФЗ - .*делим на 4/.test(с)), 'день с 7000 закупок 44-ФЗ разделён по цене (предел выдачи 5000)');
      check(!адреса.some((u) => /стр=5[1-9]/.test(u)), 'глубже 50-й страницы не запрашивает');
      const до = адреса.length;
      await поток.прогон({ ...о, режим: 'добор', страниц: 30, пауза: 0, now, файл: файл2 });
      check(адреса.length === до, 'законченный добор портал не трогает');
      поток.закрыть();
    }

    console.log('\n=== Срок подачи ===');
    const после = new Date('2026-11-12T09:00:00Z');
    check(поток.действующие(now, файл).length === 330, 'в потоке все взятые свежие (330)');
    check(поток.действующие(после, файл).length === 0, 'срок подачи прошёл - в действующие не попадает');
    лента = [...карт('п', 5, '2026-11-12', '2026-11-30'), ...лента];
    await поток.прогон({ ...портал(лента), режим: 'свежее', страниц: 1, пауза: 0, now: new Date('2026-12-20T09:00:00Z'), файл });
    check(поток.сводка(файл).всего === 5, 'срок подачи старше 30 дней - карточки удалены, свежие остались');

    console.log('\n=== Отказ портала ===');
    const п5 = портал(лента, { 1: 403 });
    const журнал = [];
    const r5 = await поток.прогон({ ...п5, режим: 'свежее', страниц: 20, пауза: 0, now, файл, журнал });
    check(r5.отказ === 403 && п5.адреса.length === 1 && журнал.some((с) => /отказал/.test(с)), '403 - сразу стоп, причина в журнале');

    console.log('\n=== Отбор под клиента из потока ===');
    const { applyFilters } = require('../src/filter');
    const к = [{ number: '1', object: 'Поставка товаров для нужд школы', okpdGroup: '17.12', law: '44-ФЗ', price: 100000 },
      { number: '2', object: 'Поставка бумаги офисной', law: '44-ФЗ', price: 100000 },
      { number: '3', object: 'Ремонт кровли', okpdGroup: '43.91', law: '44-ФЗ', price: 100000 }];
    const { passed } = applyFilters(к, { keywords: ['бумаг'], okpd: ['17.12'] });
    check(passed.map((x) => x.number).join() === '1,2', 'из потока проходят и по слову, и по коду; чужое - нет');
  } finally {
    поток.закрыть();
    fs.rmSync(каталог, { recursive: true, force: true });
  }
  console.log(failures ? `\nСБОЕВ: ${failures}` : '\nВСЕ ПРОВЕРКИ ПРОЙДЕНЫ');
  process.exit(failures ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
