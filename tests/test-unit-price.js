/**
 * Закупка по цене за единицу (src/unit-price.js): цена заказчика, безубыточная
 * цена, запас, сценарий потолка, честный отказ без закупочных цен.
 * Запуск: node tests/test-unit-price.js
 */
const { расчётЗаЕдиницу, текстЗаЕдиницу, листЗаЕдиницу } = require('../src/unit-price');
const { STYLE, writeXlsx } = require('../src/xlsx-write');

let failures = 0;
const check = (ok, m) => { console.log(`  ${ok ? 'OK  ' : 'СБОЙ'} ${m}`); if (!ok) failures++; };

// Позиции - как их отдаёт parseNmckTable по обоснованию без количества.
const п = (name, unit, ...цены) => ({ name, unit, quantity: null, prices: цены.map((value) => ({ value, column: 'КП' })) });
const позиции = [п('Бинт марлевый 7х14', 'шт', 35, 38.5, 36.2), п('Вата медицинская 100 г', 'уп', 120, 118, 125), п('Перчатки нитриловые', 'пара', 14.1, 15, 13.8)];
const строка = (name, ...закупки) => ({ name, sources: [...закупки.map((price) => ({ price, kind: 'закупочная', source: 'прайс клиента' })), { price: 99999, kind: 'верхняя граница', source: 'обоснование НМЦК' }] });

console.log('\n=== Расчёт ===');
{
  const р = расчётЗаЕдиницу({ позиции, строки: [строка('Бинт марлевый 7х14', 25, 28), строка('Вата медицинская 100 г', 90), строка('Перчатки нитриловые', 10)], нмцк: 500000, налог: 0.06, доставка: 0.03 });
  const б = р.позиции[0];
  check(б.ценаЗаказчика === 36.57, `цена заказчика - среднее предложений (36,57; получено ${б.ценаЗаказчика})`);
  check(б.закупка === 28 && б.закупкаЛучшая === 25, 'закупка: худшая 28, лучшая 25; потолок обоснования закупкой не считается');
  check(б.безубыточно === Math.round(28 * 1.03 / 0.94 * 100) / 100, `безубыточно = закупка × (1 + доставка) / (1 − налог) (${б.безубыточно})`);
  check(Math.abs(б.запас - ((36.57 - б.безубыточно) / 36.57) * 100) < 0.01, `запас = (цена − безубыточно) / цена (${б.запас}%)`);
  check(р.сЗакупкой === 3 && р.прибыльПриПотолке && р.прибыльПриПотолке.худшая === Math.round(500000 * р.запасСредний / 100), 'прибыль на весь потолок = НМЦК × средний запас');
  check(р.прибыльПриПотолке.лучшая >= р.прибыльПриПотолке.худшая, 'у самых дешёвых поставщиков прибыль не меньше');
  const т = текстЗаЕдиницу(р, 'Поставка перевязочных материалов');
  check(/по цене за единицу/.test(т) && /36,57/.test(т) && /допущение/.test(т) && !/null|NaN|undefined/.test(т), 'текст: цена заказчика, слово «допущение», без null/NaN');
  check(!/Не учтено/.test(т), 'налог и доставка заданы - оговорки «не учтено» нет');
  const xlsx = writeXlsx([листЗаЕдиницу(р, STYLE)]);
  check(xlsx.length > 1000 && xlsx[0] === 0x50 && xlsx[1] === 0x4b, 'лист Excel собирается (ZIP)');
}

console.log('\n=== Отрицательные контроли ===');
{
  const р = расчётЗаЕдиницу({ позиции, строки: позиции.map((x) => ({ name: x.name, sources: [{ price: 36, kind: 'верхняя граница' }] })), нмцк: 500000 });
  check(р.сЗакупкой === 0 && р.запасСредний === null && р.прибыльПриПотолке === null, 'одни цены обоснования - ни запаса, ни прибыли');
  const т = текстЗаЕдиницу(р);
  check(/вывода о выгоде нет/.test(т) && !/прибыль около/.test(т), 'текст прямо говорит «вывода нет», прибыли нет');
  check(/Не учтено.*налог.*доставка/.test(т), 'налог и доставка не заданы - сказано, что не учтены');
}
{
  const р = расчётЗаЕдиницу({ позиции, строки: [строка('Бинт марлевый 7х14', 25), { name: 'Вата медицинская 100 г', sources: [] }, строка('Перчатки нитриловые', 10)], нмцк: 500000 });
  check(р.сЗакупкой === 2 && р.прибыльПриПотолке === null, 'у одной позиции нет закупки - прибыль на потолок не считается (позиция не выпадает молча)');
  check(/у 1 позиций нет закупочной цены/.test(текстЗаЕдиницу(р)), 'и это сказано в тексте');
}
{
  const р = расчётЗаЕдиницу({ позиции: [п('Бинт', 'шт', 30)], строки: [строка('Бинт', 40)], нмцк: 100000, налог: 0.06 });
  check(р.позиции[0].запас < 0, 'закупка дороже цены заказчика - запас отрицательный, а не обрезан до нуля');
}

console.log(failures ? `\nСБОЕВ: ${failures}` : '\nВСЕ ПРОВЕРКИ ПРОЙДЕНЫ');
process.exit(failures ? 1 : 0);
