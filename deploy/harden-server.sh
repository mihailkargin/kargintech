#!/usr/bin/env bash
#
# ЗАЩИТА СЕРВЕРА ОТ ПЕРЕБОРА ПАРОЛЕЙ. Запускать на основном сервере:
#
#     cd ~/kargintech/deploy && sudo ./harden-server.sh
#
# ЧТО ДЕЛАЕТ
#   1. показывает, сколько попыток входа уже было — чтобы риск был не на словах;
#   2. ставит fail2ban и включает блокировку адресов, подбирающих пароль к SSH;
#   3. проверяет, что защита РАБОТАЕТ, а не «установилась».
#
# ЧЕГО НЕ ДЕЛАЕТ НАМЕРЕННО: НЕ ОТКЛЮЧАЕТ ВХОД ПО ПАРОЛЮ.
#
# Это следующий и главный шаг, но одной командой вслепую его делать нельзя.
# Порядок такой: сначала завести ключ и ПРОВЕРИТЬ вход по нему в отдельном окне,
# не закрывая текущее, и только потом запрещать пароль. Если сделать наоборот и
# ключ окажется неверным, доступ к серверу теряется целиком — а на сервере данные
# клиентов, и возврат идёт через консоль хостинга.
#
# Автоматизировать операцию, у которой цена ошибки — потеря сервера, значит
# сэкономить минуту и поставить на риск всё. Поэтому отключение пароля вынесено
# в памятку с проверкой на каждом шаге, она печатается в конце.
#
# Имена переменных латинские: bash не поддерживает кириллицу в именах, он
# разбирает `ИМЯ=x` как команду и падает с «command not found».
set -euo pipefail

if [ "$(id -u)" -ne 0 ]; then
  echo "Нужны права root:  sudo ./harden-server.sh"
  exit 1
fi

echo "=== 1. Сколько уже было попыток входа ==="
# Это не украшение вывода. Пока число не названо, «нет защиты от перебора»
# звучит как теория. Сервер с публичным адресом подбирают с первого дня.
LOG=""
for f in /var/log/auth.log /var/log/secure; do
  if [ -f "$f" ]; then LOG="$f"; break; fi
done

if [ -n "$LOG" ]; then
  FAILS="$(grep -c 'Failed password' "$LOG" || true)"
  echo "в $LOG неудачных попыток входа: ${FAILS:-0}"
  echo "самые настойчивые адреса:"
  grep 'Failed password' "$LOG" 2>/dev/null \
    | grep -oE '([0-9]{1,3}\.){3}[0-9]{1,3}' \
    | sort | uniq -c | sort -rn | head -5 | sed 's/^/   /' || echo "   (ни одной)"
else
  echo "файла журнала нет — на этой системе входы пишет journald:"
  FAILS="$(journalctl -u ssh -u sshd --no-pager 2>/dev/null | grep -c 'Failed password' || true)"
  echo "   неудачных попыток: ${FAILS:-0}"
fi

echo ""
echo "=== 2. Установка fail2ban ==="
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq fail2ban

# Свои настройки кладём в jail.local, а не правим jail.conf: обновление пакета
# перезапишет jail.conf, и защита молча вернётся к значениям по умолчанию.
cat > /etc/fail2ban/jail.local <<'SETTINGS'
# Настройки проекта KarginTech. Править этот файл, а не jail.conf:
# jail.conf перезаписывается при обновлении пакета, и правки в нём исчезают.
[DEFAULT]
# Сколько держать адрес заблокированным. Сутки, а не десять минут: подбор ведут
# роботы, и короткая блокировка их только замедляет.
bantime  = 86400
# За какое время считаем попытки.
findtime = 600
# Сколько неудач до блокировки. Пять — запас на собственную опечатку в пароле.
maxretry = 5

[sshd]
enabled = true
SETTINGS

systemctl enable fail2ban >/dev/null 2>&1 || true
systemctl restart fail2ban
sleep 3

echo ""
echo "=== 3. Проверка, что защита РАБОТАЕТ, а не установлена ==="
# У проверки обязан быть исход, при котором она не проходит. Поэтому смотрим не
# «стоит ли пакет», а отвечает ли сторож и следит ли он именно за SSH.
if ! systemctl is-active --quiet fail2ban; then
  echo "СБОЙ: служба fail2ban не запущена"
  systemctl status fail2ban --no-pager | tail -20
  exit 1
fi
echo "служба запущена: да"

if ! fail2ban-client status | grep -q sshd; then
  echo "СБОЙ: fail2ban запущен, но за SSH не следит — настройки не применились"
  fail2ban-client status
  exit 1
fi
echo "следит за SSH: да"
fail2ban-client status sshd | sed 's/^/   /'

echo ""
echo "=== 4. Сетевой экран (только показываем) ==="
# Экран настраивал setup-server.sh. Здесь лишь состояние: менять правила вслепую
# нельзя, закрытый не тот порт обрывает доступ к серверу.
ufw status verbose 2>/dev/null | sed 's/^/   /' || echo "   ufw не установлен"

cat <<'PAMYATKA'

=== ОСТАЛОСЬ ГЛАВНОЕ: ВХОД ПО КЛЮЧУ ВМЕСТО ПАРОЛЯ ===

Делать по шагам и НЕ ЗАКРЫВАТЬ текущее окно до самого конца. Цена ошибки —
потеря доступа к серверу, на котором лежат данные клиентов.

ШАГ 1. На ноутбуке (PowerShell) создать ключ:
    ssh-keygen -t ed25519 -C "kargin-noutbuk"
  На вопрос про файл нажать Enter. Пароль на ключ задать: он защищает ключ,
  если ноутбук попадёт в чужие руки.

ШАГ 2. Отправить открытую часть ключа на сервер (с ноутбука):
    type $env:USERPROFILE\.ssh\id_ed25519.pub | ssh kargin@<адрес сервера> "mkdir -p ~/.ssh && chmod 700 ~/.ssh && cat >> ~/.ssh/authorized_keys && chmod 600 ~/.ssh/authorized_keys"

ШАГ 3. ПРОВЕРИТЬ вход по ключу в НОВОМ окне PowerShell, старое не закрывать:
    ssh kargin@<адрес сервера> "echo вошёл по ключу"
  Пароль спрашивать НЕ должен. Спросил — ключ не работает, и шаг 4 делать нельзя.

ШАГ 4. Только после успешного шага 3 запретить вход по паролю:
    # Правка основного файла НЕ работает на образах Beget: /etc/ssh/sshd_config.d/
    # 50-cloud-init.conf с «PasswordAuthentication yes» читается раньше и
    # побеждает (найдено 20.10.2026). Надёжно — свой файл 01-…, он первый:
    printf 'PasswordAuthentication no\nKbdInteractiveAuthentication no\nPermitRootLogin no\n' | sudo tee /etc/ssh/sshd_config.d/01-kargintech.conf
    sudo sed -i 's/^#\?PasswordAuthentication.*/PasswordAuthentication no/' /etc/ssh/sshd_config
    sudo sed -i 's/^#\?KbdInteractiveAuthentication.*/KbdInteractiveAuthentication no/' /etc/ssh/sshd_config
    sudo sshd -t && sudo systemctl reload ssh
  Команда sshd -t проверяет настройки ДО перезапуска: при опечатке служба
  не перезапустится с битым файлом.

ШАГ 5. Проверить вход по ключу ещё раз, в третьем окне, и только потом закрыть
  первое.

ЕСЛИ ДОСТУП ВСЁ ЖЕ ПОТЕРЯН: в панели Beget есть консоль, работающая в обход SSH.
Через неё вернуть PasswordAuthentication yes и перезапустить ssh.

ПОБОЧНОЕ СЛЕДСТВИЕ, О КОТОРОМ НАДО ЗНАТЬ ЗАРАНЕЕ: после шага 4 команды вида
`ssh kargin@...` перестанут спрашивать пароль — и это же значит, что любой
помощник, работающий на ноутбуке от вашей учётной записи, сможет заходить на
сервер без пароля. Пароль на самом ключе (шаг 1) — ровно та защита, которая
здесь остаётся.
PAMYATKA
