       cp <копия>/env ~/kargintech/deploy/.env
  2. Поднять только базу:
       cd ~/kargintech/deploy && docker compose up -d db
  3. Залить dump. Имя пользователя и базы посмотреть в .env ГЛАЗАМИ:
       grep -E '^(DB_USER|DB_NAME)=' ~/kargintech/deploy/.env
     и подставить руками. Выполнять .env командой `. ./.env` НЕЛЬЗЯ:
     так из него уже утёк ключ API в терминал.
       docker compose exec -T db psql -U <пользователь> -d <база> < <копия>/n8n-db.sql
