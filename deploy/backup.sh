#!/usr/bin/env bash
#
# РЕЗЕРВНАЯ КОПИЯ ОСНОВНОГО СЕРВЕРА.
#
# Запуск вручную:
#     cd ~/kargintech/deploy && ./backup.sh
#
# Раз в сутки по расписанию:
#     ./backup.sh --cron
#
# ЧТО КОПИРУЕТСЯ И ПОЧЕМУ ИМЕННО ЭТО
#
#   1. База n8n (dump postgres) — воркфлоу, история запусков, сохранённые доступы
#      клиентов в зашифрованном виде.
#   2. Том n8n_data — внутреннее состояние панели.
#   3. Том app_data — /data/state (состояние дедупликации, собранная статистика
#      снижения цены) и /data/clients (настройки каждого клиента). Это часы
#      работы и данные клиентов.
#   4. Файл .env — В НЁМ КЛЮЧ ШИФРОВАНИЯ N8N_ENCRYPTION_KEY. Без него база
#      бесполезна: доступы расшифровать нечем, их придётся заводить заново по
#      всем клиентам.
#
# ПОЭТОМУ ПРЯМО: ГОТОВАЯ КОПИЯ — САМЫЙ ОПАСНЫЙ ФАЙЛ НА СЕРВЕРЕ. В ней и настройки
# клиентов, и ключ, которым расшифровываются их доступы. Выкладывать её в облако,
# пересылать в Telegram или почтой нельзя: главный аргумент в продаже — «данные
# клиента не утекают», и копия это ровно те данные. Права ставятся 600 на файлы
# и 700 на каталог.
#
# КОПИЯ, КОТОРУЮ НЕ ПРОБОВАЛИ ВОССТАНОВИТЬ, — НЕ КОПИЯ. Скрипт проверяет, что
# архивы созданы, непустые и читаются, и что dump содержит настоящие таблицы, а
# не сообщение об ошибке. Это НЕ заменяет пробного восстановления на чистом
# сервере: его надо сделать один раз руками, и до него копия остаётся обещанием.
# Порядок восстановления печатается в конце каждого прогона.
#
# ПОЧЕМУ ИМЕНА ПЕРЕМЕННЫХ ЛАТИНСКИЕ, хотя весь проект на русском: bash не
# поддерживает кириллицу в именах переменных. `КАТАЛОГ=x` он разбирает не как
# присваивание, а как команду, и падает с «command not found». В JavaScript
# русские имена работают, в bash — нет, и это разные языки.
set -euo pipefail

BACKUP_ROOT="${BACKUP_DIR:-$HOME/backups}"
KEEP="${BACKUP_KEEP:-7}"
STAMP="$(date +%Y-%m-%d_%H%M)"
DEST="$BACKUP_ROOT/$STAMP"

cd "$(dirname "$0")"
HERE="$(pwd)"

# --- установка расписания -----------------------------------------------------
if [ "${1:-}" = "--cron" ]; then
  # `bash ./backup.sh`, а не `./backup.sh`: архив комплекта распаковывается
  # без права на запуск, и ночной запуск молча падал бы с «Permission denied».
  LINE="15 4 * * * cd $HERE && bash ./backup.sh >> $HOME/backup.log 2>&1"
  # Своя строка убирается перед добавлением: иначе при повторном запуске
  # расписание задвоится и копии начнут делаться дважды.
  { crontab -l 2>/dev/null | grep -v 'backup\.sh' || true; echo "$LINE"; } | crontab -
  echo "Расписание установлено: каждый день в 04:15, журнал в $HOME/backup.log"
  crontab -l | grep 'backup\.sh'
  exit 0
fi

echo "=== РЕЗЕРВНАЯ КОПИЯ $STAMP ==="

# Имя проекта docker compose. По умолчанию это имя каталога, но полагаться на
# догадку нельзя: при неверном имени тома просто не нашлись бы, и копия вышла бы
# пустой — молча. Поэтому имена проверяются, и при несовпадении скрипт падает.
PROJECT="${COMPOSE_PROJECT_NAME:-$(basename "$HERE" | tr '[:upper:]' '[:lower:]' | tr -cd 'a-z0-9_-')}"
echo "проект docker compose: $PROJECT"

for vol in n8n_data app_data; do
  if ! docker volume inspect "${PROJECT}_${vol}" >/dev/null 2>&1; then
    echo "ОШИБКА: тома ${PROJECT}_${vol} не существует."
    echo "Так выглядит неверно определённое имя проекта — копия вышла бы пустой."
    echo "Существующие тома:"
    docker volume ls --format '  {{.Name}}'
    echo "Задать имя вручную:  COMPOSE_PROJECT_NAME=<имя> ./backup.sh"
    exit 1
  fi
done

mkdir -p "$DEST"
chmod 700 "$BACKUP_ROOT" "$DEST"

# --- 1. база ------------------------------------------------------------------
# Переменные берём из .env: дублировать имя базы и пользователя в двух местах
# нельзя — разойдутся, и dump пойдёт в пустоту.
if [ ! -f ./.env ]; then
  echo "ОШИБКА: файла .env рядом нет, имя базы и пользователя брать негде"
  exit 1
fi

# .env НЕ ВЫПОЛНЯЕТСЯ. Здесь стояло `. ./.env`, и 09.10.2026 это привело
# к утечке ключа Anthropic.
#
# Как было: `.` (source) исполняет файл как программу. Любая строка, не
# являющаяся присваиванием, выполняется как команда, и bash печатает её
# содержимое в сообщении «command not found». В .env оказалась строка
# с ключом API, и ключ ушёл на экран целиком.
#
# Почему это хуже обычной ошибки: ночной запуск пишет вывод в ~/backup.log,
# то есть ключ попадал бы в файл журнала каждую ночь. Журнал прав 600 не
# имеет, в резервную копию не входит, и никто бы туда не заглянул.
#
# Теперь значения ДОСТАЮТСЯ ТЕКСТОМ, без исполнения. Берутся только два
# нужных имени; всё остальное в .env скрипт не читает вовсе.
env_value() {
  sed -n "s/^[[:space:]]*$1[[:space:]]*=[[:space:]]*//p" ./.env \
    | head -n 1 \
    | tr -d '\r' \
    | sed -e 's/^"//' -e 's/"$//' -e "s/^'//" -e "s/'$//"
}

DB_USER="$(env_value DB_USER)"
DB_NAME="$(env_value DB_NAME)"

# Пустое значение означает, что строки в .env нет или она записана иначе.
# Без проверки pg_dump пошёл бы в базу по умолчанию и создал правдоподобный
# файл не с теми данными — то есть копия выглядела бы сделанной.
if [ -z "$DB_USER" ] || [ -z "$DB_NAME" ]; then
  echo "ОШИБКА: в .env не нашлись DB_USER и/или DB_NAME."
  echo "Ожидается вид «DB_NAME=n8n», каждая переменная отдельной строкой."
  echo "Найдено имён переменных в файле:"
  cut -d= -f1 ./.env | grep -v '^[[:space:]]*#' | grep . | sed 's/^/   /'
  exit 1
fi

echo "-- база ${DB_NAME} --"
docker compose exec -T db pg_dump -U "$DB_USER" -d "$DB_NAME" > "$DEST/n8n-db.sql"

# ТРИ ПРОВЕРКИ, А НЕ ОДНА. pg_dump умеет завершиться успешно и выдать почти
# пустой файл, если подключился не к той базе. Поэтому проверяем размер и
# содержимое, а не только код возврата.
if [ ! -s "$DEST/n8n-db.sql" ]; then
  echo "ОШИБКА: dump базы пустой"
  exit 1
fi
TABLES="$(grep -c 'CREATE TABLE' "$DEST/n8n-db.sql" || true)"
if [ "${TABLES:-0}" -eq 0 ]; then
  echo "ОШИБКА: в dump нет ни одной таблицы — подключились не к той базе?"
  head -5 "$DEST/n8n-db.sql"
  exit 1
fi
echo "   таблиц в dump: $TABLES"

# --- 2 и 3. тома --------------------------------------------------------------
# Том копируется вспомогательным контейнером: с самого сервера содержимое тома
# доступно только через docker.
# САЙТ (21.10.2026): том site_data с базой SQLite - почта и хеши паролей
# клиентов, их отметки и расчёты. Работающая база копируется снимком
# (VACUUM INTO): копия файла посреди записи вышла бы несогласованной.
# Тома ещё нет (сайт не развёрнут) - пропускается с замечанием, не падает.
VOLS="n8n_data app_data"
if docker volume inspect "${PROJECT}_site_data" >/dev/null 2>&1; then
  if docker compose exec -T site node --disable-warning=ExperimentalWarning -e \
      "const fs=require('fs');try{fs.unlinkSync('/data/site-snapshot.db')}catch(e){};const {DatabaseSync}=require('node:sqlite');new DatabaseSync('/data/site.db').exec(\"VACUUM INTO '/data/site-snapshot.db'\");console.log('   снимок базы сайта сделан')"; then
    VOLS="$VOLS site_data"
  else
    echo "ОШИБКА: снимок базы сайта не сделан - контейнер site не отвечает?"
    exit 1
  fi
else
  echo "-- тома site_data нет: сайт не развёрнут, пропускаю --"
fi

for vol in $VOLS; do
  echo "-- том $vol --"
  docker run --rm \
    -v "${PROJECT}_${vol}:/src:ro" \
    -v "$DEST:/out" \
    alpine:3 sh -c "tar czf /out/${vol}.tgz -C /src . && chown $(id -u):$(id -g) /out/${vol}.tgz && chmod 600 /out/${vol}.tgz"
  # Владелец и права ставятся ВНУТРИ контейнера: архив создаёт root, и
  # `chmod 600` ниже от имени пользователя падал на нём с «Operation not
  # permitted» — 19.10.2026 скрипт обрывался, не дойдя до прав на .env.

  if [ ! -s "$DEST/${vol}.tgz" ]; then
    echo "ОШИБКА: архив ${vol}.tgz пустой"
    exit 1
  fi
  # Архив, который не читается, выглядит как успех: файл есть, размер есть.
  if ! tar tzf "$DEST/${vol}.tgz" >/dev/null 2>&1; then
    echo "ОШИБКА: архив ${vol}.tgz не читается"
    exit 1
  fi
  echo "   файлов в архиве: $(tar tzf "$DEST/${vol}.tgz" | wc -l)"
done

# Отдельно печатаем, что именно уехало из настроек клиентов и состояния — чтобы
# пропажа файла была видна в журнале, а не обнаруживалась при восстановлении.
echo "-- в app_data лежит --"
tar tzf "$DEST/app_data.tgz" | grep -E 'clients/|state/' | sed 's/^/   /' || echo "   (ни настроек клиентов, ни состояния — проверить!)"

# --- 4. .env ------------------------------------------------------------------
cp ./.env "$DEST/env"
if ! grep -q 'N8N_ENCRYPTION_KEY=.\+' "$DEST/env"; then
  echo "ВНИМАНИЕ: в .env нет заполненного N8N_ENCRYPTION_KEY."
  echo "Без него сохранённые доступы клиентов из базы не расшифровать."
fi

# Права: копия содержит ключ шифрования и настройки клиентов.
chmod 600 "$DEST"/*

echo ""
echo "=== ГОТОВО: $DEST ($(du -sh "$DEST" | cut -f1)) ==="

# Отметка успеха — в данные приложения. Ежедневный поиск проверяет её и шлёт
# владельцу алерт, если копии нет больше 36 часов. С 09 по 19.10.2026 ночная
# копия падала каждую ночь, и об этом не знал никто: журнал не читали.
docker run --rm -v "${PROJECT}_app_data:/v" alpine:3 \
  sh -c "mkdir -p /v/state && date -u +%Y-%m-%dT%H:%M:%SZ > /v/state/backup-ok"

# Копия вне сервера (02.11.2026, авария Beget). Её сбой не отменяет местную
# копию и чистку, но виден: отметка backup-offsite-ok не обновится, и
# самопроверка пришлёт сигнал владельцу.
bash "$HERE/backup-offsite.sh" "$DEST" || echo "ВНИМАНИЕ: копия вне сервера НЕ сделана (код $?) - данные только на этом сервере"

# --- чистка старых ------------------------------------------------------------
# Без неё диск заполнится молча, и первым признаком станет упавший сервис.
cd "$BACKUP_ROOT"
OLD="$(ls -1d 20*_* 2>/dev/null | sort | head -n "-$KEEP" || true)"
if [ -n "$OLD" ]; then
  echo "удаляю старые копии (храним $KEEP):"
  echo "$OLD" | sed 's/^/   /'
  echo "$OLD" | xargs rm -rf
fi
echo "копий на диске: $(ls -1d 20*_* 2>/dev/null | wc -l), свободно: $(df -h "$BACKUP_ROOT" | awk 'NR==2{print $4}')"

cat <<'PAMYATKA'

