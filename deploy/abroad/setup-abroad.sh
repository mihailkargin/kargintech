#!/usr/bin/env bash
# Подготовка зарубежного сервера — двери к Claude API.
#
# Запускать ОДИН РАЗ на зарубежном сервере, от пользователя с sudo,
# передав адрес российского сервера:
#
#     bash deploy/abroad/setup-abroad.sh <адрес основного сервера>
#
# ПОЧЕМУ БЕЗ DOCKER — решено 02.10.2026, после того как выяснилось, что этот
# сервер служит владельцу ещё и личным VPN. Docker при установке меняет
# политику пересылки пакетов в сетевом экране на «запрещать», а VPN на
# пересылке и держится. Последствие буквально такое: VPN отваливается,
# владелец теряет доступ к Claude, то есть и возможность спросить, как это
# починить. Ради программы размером меньше мегабайта такой риск не берём.
# Плюс диск: на сервере свободно около 5 ГБ, Docker съел бы заметную часть.
#
# Посредник ставится из репозитория Ubuntu. Обновления безопасности к нему
# приходят вместе с системными, и правила сетевого экрана он не трогает.
#
# ЧЕГО СКРИПТ НЕ ДЕЛАЕТ НАМЕРЕННО: не включает сетевой экран и не сбрасывает
# его правила. На основном сервере правила сбрасывались начисто — здесь так
# нельзя, иначе разом отвалятся VPN и SSH. Правила добавляются, включение
# остаётся человеку.

set -euo pipefail

say() { printf '\n\033[1m%s\033[0m\n' "$*"; }
ok()  { printf '  OK   %s\n' "$*"; }
bad() { printf '  СБОЙ %s\n' "$*"; }
warn(){ printf '  ВНИМАНИЕ %s\n' "$*"; }

if [[ $EUID -eq 0 ]]; then
  bad "Запускать не от root, а от обычного пользователя с sudo."
  exit 1
fi

RU_IP="${1:-}"
if [[ -z "$RU_IP" ]]; then
  bad "Не передан адрес российского сервера."
  bad "Запуск: bash deploy/abroad/setup-abroad.sh <адрес основного сервера>"
  exit 1
fi
if [[ ! "$RU_IP" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ ]]; then
  bad "«$RU_IP» не похож на адрес вида 93.188.187.30"
  exit 1
fi

SRC_DIR="$(cd "$(dirname "$0")" && pwd)"

say "1. Проверка, что сервер НЕ российский"
# Проверка обратная той, что на основном сервере, и не формальность:
# российский адрес здесь означает, что дверь ведёт в ту же комнату.
# Anthropic на него не ответит, и обнаружилось бы это только при первом
# разборе документации у клиента.
COUNTRY=$(curl -s --max-time 15 http://ip-api.com/line/?fields=countryCode || echo '??')
IP=$(curl -s --max-time 15 https://api.ipify.org || echo '?')
echo "  IP: $IP, страна: $COUNTRY"
if [[ "$COUNTRY" == "RU" ]]; then
  bad "Это российский сервер. Claude API с него не ответит — дверь должна быть за рубежом."
  exit 1
fi
if [[ "$COUNTRY" == "??" ]]; then
  warn "страну определить не удалось — ip-api.com не ответил. Проверка не пройдена, а пропущена"
else
  ok "сервер зарубежный ($COUNTRY)"
fi

say "2. Отвечает ли Anthropic с этого сервера напрямую"
# До установки посредника. Если здесь отказ, посредник не поможет: значит
# страна или хостер не подходят, и это надо знать до всякой установки.
CODE=$(curl -s --max-time 30 -o /dev/null -w '%{http_code}' \
  https://api.anthropic.com/v1/messages -X POST -H 'content-type: application/json' -d '{}' || echo '000')
case "$CODE" in
  401|400) ok "Anthropic отвечает (код $CODE — это «нет ключа», то есть связь есть)" ;;
  403)     bad "Anthropic отвечает кодом 403 — доступ с этого адреса закрыт. Нужен другой сервер"; exit 1 ;;
  000)     bad "соединение с Anthropic не установилось вовсе. Нужен другой сервер"; exit 1 ;;
  *)       warn "неожиданный код $CODE — связь, похоже, есть, но проверить стоит вручную" ;;
esac

say "3. Установка посредника из репозитория Ubuntu"
sudo apt-get update -qq
sudo DEBIAN_FRONTEND=noninteractive apt-get install -yqq tinyproxy ufw openssl curl
ok "посредник установлен: $(tinyproxy -v 2>&1 | head -1)"

say "4. Настройки и пароль"
# Пароль генерируем, а не придумываем. Конфиг с оставленной заглушкой —
# это открытый посредник, которого сканеры находят за сутки и через который
# начинают ходить чужие люди: с нашего адреса и за наш счёт.
#
# Пароль из цифр и латинских букв (-hex), потому что он попадает в адрес
# вида http://tender:ПАРОЛЬ@сервер:8888. Двоеточие, собака или косая черта
# внутри пароля разорвали бы такой адрес, и разбираться в этом неприятно.
# Прежний пароль запоминается ДО копирования шаблона: иначе повторный запуск
# молча выдавал бы новый, и основной сервер терял бы связь с моделью и
# Telegram до правки .env (найдено 04.11.2026).
OLD_PASS=$(sudo grep -m1 '^BasicAuth' /etc/tinyproxy/tinyproxy.conf 2>/dev/null | awk '{print $3}' || true)
if [[ "$OLD_PASS" == 'ЗАМЕНИТЬ_НА_СГЕНЕРИРОВАННЫЙ_ПАРОЛЬ' ]]; then OLD_PASS=''; fi
sudo cp "$SRC_DIR/tinyproxy.conf" /etc/tinyproxy/tinyproxy.conf
sudo cp "$SRC_DIR/allowed.txt" /etc/tinyproxy/allowed.txt
if [[ -n "$OLD_PASS" ]]; then
  sudo sed -i "s|ЗАМЕНИТЬ_НА_СГЕНЕРИРОВАННЫЙ_ПАРОЛЬ|$OLD_PASS|" /etc/tinyproxy/tinyproxy.conf
fi

if sudo grep -q 'ЗАМЕНИТЬ_НА_СГЕНЕРИРОВАННЫЙ_ПАРОЛЬ' /etc/tinyproxy/tinyproxy.conf; then
  PROXY_PASS=$(openssl rand -hex 20)
  sudo sed -i "s|ЗАМЕНИТЬ_НА_СГЕНЕРИРОВАННЫЙ_ПАРОЛЬ|$PROXY_PASS|" /etc/tinyproxy/tinyproxy.conf
  ok "пароль сгенерирован и подставлен"
else
  PROXY_PASS=$(sudo grep -m1 '^BasicAuth' /etc/tinyproxy/tinyproxy.conf | awk '{print $3}')
  ok "пароль в настройках уже стоит, оставляю как есть"
fi

# Подключаться к посреднику - только этот сервер (его проверки ниже) и
# основной. Строка «Allow 0.0.0.0/0» из шаблона заменяется; при повторном
# запуске с другим адресом основного - заменяется прежний адрес.
sudo sed -i -E "/^Allow /d" /etc/tinyproxy/tinyproxy.conf
sudo sed -i -E "s|^ConnectPort 443$|ConnectPort 443\nAllow 127.0.0.1\nAllow $RU_IP|" /etc/tinyproxy/tinyproxy.conf
if [[ "$(sudo grep -c '^Allow ' /etc/tinyproxy/tinyproxy.conf)" -ne 2 ]] || ! sudo grep -qx "Allow $RU_IP" /etc/tinyproxy/tinyproxy.conf; then
  bad "не удалось ограничить посредника адресом $RU_IP - проверить строки Allow в /etc/tinyproxy/tinyproxy.conf"
  exit 1
fi
ok "подключаться можно только с $RU_IP и с самого сервера"

if [[ -z "$PROXY_PASS" ]]; then
  bad "не удалось определить пароль — проверить строку BasicAuth в /etc/tinyproxy/tinyproxy.conf"
  exit 1
fi

# Файл с паролем закрываем от посторонних, но оставляем читаемым самому
# посреднику — иначе он не запустится и скажет об этом невнятно.
sudo chown root:tinyproxy /etc/tinyproxy/tinyproxy.conf /etc/tinyproxy/allowed.txt
sudo chmod 640 /etc/tinyproxy/tinyproxy.conf
sudo chmod 644 /etc/tinyproxy/allowed.txt
ok "список разрешённых адресов на месте: $(grep -c . /etc/tinyproxy/allowed.txt) строк"

say "5. Запуск"
sudo systemctl enable tinyproxy >/dev/null 2>&1 || true
sudo systemctl restart tinyproxy
sleep 2
if systemctl is-active --quiet tinyproxy; then
  ok "посредник запущен"
else
  bad "посредник не запустился. Причина:"
  sudo systemctl status tinyproxy --no-pager -l | tail -20
  exit 1
fi

say "6. Сетевой экран: порт 8888 только для российского сервера"
# Правила ДОБАВЛЯЮТСЯ, существующие не сбрасываются. На этом сервере стоит
# VPN, и сброс правил начисто оборвал бы его вместе с доступом по SSH.
sudo ufw allow from "$RU_IP" to any port 8888 proto tcp >/dev/null
sudo ufw deny 8888/tcp >/dev/null
ok "правило добавлено: 8888 разрешён только с $RU_IP"
if ! sudo ufw status | grep -q 'Status: active'; then
  warn "СЕТЕВОЙ ЭКРАН ВЫКЛЮЧЕН, и включать его сам я не буду."
  warn "На сервере с VPN включение ufw без заранее разрешённых портов"
  warn "обрывает и VPN, и SSH — то есть доступ к серверу вообще."
  warn "Включать так, убедившись, что порты VPN перечислены:"
  warn "    sudo ufw allow OpenSSH"
  warn "    sudo ufw allow <порт вашего VPN>"
  warn "    sudo ufw enable"
  warn "Пока экран выключен, посредник защищён только паролем — это один рубеж."
else
  ok "экран включён, правило действует"
fi

say "7. Проверка: проходит ли запрос к Anthropic через посредника"
PCODE=$(curl -x "http://tender:$PROXY_PASS@127.0.0.1:8888" \
  -s --max-time 30 -o /dev/null -w '%{http_code}' \
  https://api.anthropic.com/v1/messages -X POST -H 'content-type: application/json' -d '{}' || echo '000')
case "$PCODE" in
  401|400) ok "через посредника Anthropic отвечает (код $PCODE)" ;;
  407)     bad "посредник не принял пароль — проверить строку BasicAuth"; exit 1 ;;
  403)     bad "посредник отклонил сам запрос. Проверить, что api.anthropic.com есть в /etc/tinyproxy/allowed.txt"; exit 1 ;;
  000)     bad "соединение не установилось. Смотреть: sudo journalctl -u tinyproxy -n 30"; exit 1 ;;
  *)       warn "неожиданный код $PCODE" ;;
esac

say "8. ГЛАВНАЯ ПРОВЕРКА: держит ли посредник ограничение по адресам"
# Здесь было прямо названное сомнение: фильтр по адресам в tinyproxy может
# не применяться к защищённым соединениям, а все наши запросы именно такие.
#
# Зачем это нужно: не от злоумышленника, а от собственной ошибки. Если
# воркфлоу однажды по недосмотру отправит запрос к порталу через посредника,
# портал увидит зарубежный адрес и откажет. Искать такую причину можно долго —
# выглядеть будет как «портал сломался».
#
# ПОЧЕМУ ПРОВЕРЯЕМ НЕ НА ПОРТАЛЕ ЗАКУПОК. Первая версия проверяла именно
# на нём — и это была негодная проверка, подтверждавшая что угодно. Портал
# и так не отвечает на зарубежные адреса, поэтому отказ приходил бы и при
# неработающем фильтре. Отличить «фильтр не пустил» от «портал сам не ответил»
# по такому ответу невозможно. Проверка выглядела пройденной, не проверив ничего.
#
# Поэтому берём адрес, который с зарубежного сервера ОТВЕЧАЕТ ТОЧНО
# и в список разрешённых не входит. Если фильтр работает, посредник откажет
# сам; если не работает — вернётся 200, и тогда это настоящий 200.
PROBE_HOST='https://example.com'
FCODE=$(curl -x "http://tender:$PROXY_PASS@127.0.0.1:8888" \
  -s --max-time 30 -o /dev/null -w '%{http_code}' "$PROBE_HOST" || echo '000')

# Контрольный замер: отвечает ли этот адрес вообще, в обход посредника.
# Без него нельзя отличить работу фильтра от того, что адрес просто лёг.
DIRECT=$(curl -s --max-time 30 -o /dev/null -w '%{http_code}' "$PROBE_HOST" || echo '000')

echo "  $PROBE_HOST напрямую: $DIRECT, через посредника: $FCODE"
if [[ "$DIRECT" != "200" ]]; then
  warn "контрольный адрес не отвечает и напрямую (код $DIRECT) — проверка НЕ ПРОЙДЕНА, а невозможна."
  warn "Повторить позже или взять другой заведомо живой адрес."
elif [[ "$FCODE" == "200" ]]; then
  bad "ОГРАНИЧЕНИЕ НЕ РАБОТАЕТ: посторонний адрес прошёл через посредника."
  bad "Значит фильтр к защищённым соединениям не применяется — ровно то, в чём я сомневался."
  bad "Это не авария: основная защита — пароль и правило экрана, фильтр третий рубеж."
  bad "Сказать мне: заменю на решение, где ограничение работает по имени узла."
else
  ok "посторонний адрес отвечает напрямую, но через посредника не прошёл (код $FCODE)"
  ok "ограничение по адресам работает — сомнение снято"
fi

say "Готово. Что дальше"
cat <<NEXT
  Адрес посредника для n8n — СОХРАНИТЬ В МЕНЕДЖЕР ПАРОЛЕЙ СРАЗУ:

      http://tender:$PROXY_PASS@$IP:8888

  Вписывать его в n8n ТОЛЬКО в настройки той ноды, которая обращается
  к Claude: Settings -> Proxy. Переменные HTTP_PROXY и HTTPS_PROXY на
  российском сервере НЕ задавать — они подействуют на все ноды сразу,
  портал увидит зарубежный адрес и перестанет отвечать.

  Проверить с РОССИЙСКОГО сервера, что дверь видна снаружи:

      curl -x http://tender:$PROXY_PASS@$IP:8888 \\
           -s -o /dev/null -w '%{http_code}\\n' \\
           -X POST -H 'content-type: application/json' -d '{}' \\
           https://api.anthropic.com/v1/messages

  Ожидается 401 — «связь есть, ключа нет». На этом шаге это и есть успех.
NEXT
