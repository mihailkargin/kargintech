"""
Таблица БЕЗ линий на скане - 22.10.2026, требование владельца «почему сканы
таблиц без линий не читаются - надо исправить».

Линий нет - ячейки не найти по рамкам (server.py, ячейки()). Зато колонки
видны по пустоте: между колонками есть вертикальная полоса, где нет ни одного
слова ни в одной строке таблицы. Tesseract отдаёт каждое слово с координатами
(вывод tsv), по ним и строим:

1. строки - как их видит Tesseract;
2. внутри строки слова разделены на куски по большим промежуткам (больше
   полутора высот буквы - обычный пробел втрое уже);
3. строки, где кусков три и больше, - строки таблицы; по ним считается, сколько
   строк занимает каждая вертикаль листа, и пустые вертикали - границы колонок;
4. каждое слово ставится в колонку по своей середине;
5. строка, где заполнена одна ячейка, - перенос текста внутри ячейки
   (длинное наименование в две строки): приклеивается к ближайшей по высоте
   полной строке - сверху или снизу.

Вывод - ячейки через табуляцию, строки через перевод строки, как у таблиц с
линиями: дальше работает обычный разбор (src/nmck-table.js), а его самопроверка
и сверка суммы с начальной ценой ловят неверно собранную таблицу.

Без сторонних библиотек - чтобы проверялось и без OpenCV (tests/test_borderless.py).

Пределы, говорю прямо: ячейки, где текст стоит вплотную к соседней колонке
(промежуток меньше полутора букв), сливаются; таблица с одной-двумя колонками
таблицей не считается; номер позиции в отдельной узкой колонке может слиться
с наименованием, если между ними обычный пробел.
"""

import statistics


def слова_из_tsv(tsv):
    """Слова из вывода `tesseract … tsv`: текст, рамка, ключ строки."""
    слова = []
    for i, строка in enumerate((tsv or '').splitlines()):
        поля = строка.split('\t')
        if i == 0 or len(поля) < 12:
            continue
        текст = поля[11].strip()
        try:
            conf = float(поля[10])
        except ValueError:
            continue
        if not текст or conf < 0:
            continue
        слова.append({
            'текст': текст,
            'x': int(поля[6]), 'y': int(поля[7]), 'w': int(поля[8]), 'h': int(поля[9]),
            'строка': (поля[2], поля[3], поля[4]),
        })
    return слова


def строки_листа(слова):
    """Слова по строкам Tesseract, строки сверху вниз, слова слева направо."""
    по_ключу = {}
    for с in слова:
        по_ключу.setdefault(с['строка'], []).append(с)
    строки = []
    for список in по_ключу.values():
        список.sort(key=lambda с: с['x'])
        строки.append({
            'слова': список,
            'верх': min(с['y'] for с in список),
            'низ': max(с['y'] + с['h'] for с in список),
        })
    строки.sort(key=lambda с: с['верх'])
    return строки


def куски(строка, разрыв):
    """Слова строки, разделённые промежутками шире `разрыв`."""
    итог, текущий = [], []
    for с in строка['слова']:
        if текущий and с['x'] - (текущий[-1]['x'] + текущий[-1]['w']) > разрыв:
            итог.append(текущий)
            текущий = []
        текущий.append(с)
    if текущий:
        итог.append(текущий)
    return [(к[0]['x'], к[-1]['x'] + к[-1]['w']) for к in итог]


def колонки_по_пустоте(строки_таблицы, разрыв):
    """Границы колонок - вертикали, которые не заняты почти ни в одной строке таблицы."""
    отрезки = [о for с in строки_таблицы for о in куски(с, разрыв)]
    if not отрезки:
        return []
    ширина = max(п for _, п in отрезки) + 1
    занято = [0] * (ширина + 1)
    for л, п in отрезки:
        for x in range(max(0, л), min(ширина, п + 1)):
            занято[x] += 1
    # Порог - десятая часть строк: одно длинное наименование, залезшее в
    # промежуток, не должно склеивать две колонки.
    порог = max(1, len(строки_таблицы) // 10)
    колонки, начало = [], None
    for x in range(ширина + 1):
        есть = x < ширина and занято[x] > порог
        if есть and начало is None:
            начало = x
        elif not есть and начало is not None:
            колонки.append([начало, x - 1])
            начало = None
    # Промежуток уже обычного пробела - это не граница колонки.
    слитые = []
    for к in колонки:
        if слитые and к[0] - слитые[-1][1] <= разрыв:
            слитые[-1][1] = к[1]
        else:
            слитые.append(к)
    return слитые


def колонка_слова(с, колонки):
    середина = с['x'] + с['w'] / 2
    for i, (л, п) in enumerate(колонки):
        if л - 2 <= середина <= п + 2:
            return i
    return min(range(len(колонки)), key=lambda i: min(abs(середина - колонки[i][0]), abs(середина - колонки[i][1])))


def собрать(слова):
    """Текст таблицы без линий или '' - если таблицы на листе не видно."""
    if not слова:
        return ''
    высота = statistics.median(с['h'] for с in слова)
    разрыв = 1.5 * высота
    строки = строки_листа(слова)
    признак = [len(куски(с, разрыв)) >= 3 for с in строки]
    if sum(признак) < 3:
        return ''
    первая = признак.index(True)
    последняя = len(признак) - 1 - признак[::-1].index(True)
    таблица = строки[первая:последняя + 1]
    колонки = колонки_по_пустоте([с for с, п in zip(строки, признак) if п], разрыв)
    if len(колонки) < 3:
        return ''

    ряды = []
    for с in таблица:
        ячейки = [''] * len(колонки)
        for слово in с['слова']:
            i = колонка_слова(слово, колонки)
            ячейки[i] = (ячейки[i] + ' ' + слово['текст']).strip()
        ряды.append({'ячейки': ячейки, 'верх': с['верх'], 'низ': с['низ'],
                     'полный': sum(1 for я in ячейки if я) >= 2})

    # Перенос внутри ячейки: строка с одной заполненной ячейкой - к ближайшей
    # по высоте полной строке. Перенос в ячейке плотнее, чем зазор между
    # строками таблицы, поэтому ближайшая и есть своя.
    итог = [р for р in ряды if р['полный']]
    for р in ряды:
        if р['полный']:
            continue
        выше = [п for п in итог if п['низ'] <= р['верх'] + 2]
        ниже = [п for п in итог if п['верх'] >= р['низ'] - 2]
        кандидаты = []
        if выше:
            кандидаты.append((р['верх'] - выше[-1]['низ'], выше[-1], 'после'))
        if ниже:
            кандидаты.append((ниже[0]['верх'] - р['низ'], ниже[0], 'перед'))
        if not кандидаты:
            continue
        _, цель, куда = min(кандидаты, key=lambda к: к[0])
        for i, я in enumerate(р['ячейки']):
            if я:
                цель['ячейки'][i] = (цель['ячейки'][i] + ' ' + я if куда == 'после' else я + ' ' + цель['ячейки'][i]).strip()

    до = [' '.join(с['текст'] for с in с2['слова']) for с2 in строки[:первая]]
    после = [' '.join(с['текст'] for с in с2['слова']) for с2 in строки[последняя + 1:]]
    тело = ['\t'.join(р['ячейки']) for р in итог]
    return '\n'.join(до + тело + после)
