/**
 * Что компании доступно сейчас.
 * расчётовЗаМесяц - число расчётов по кнопке с начала месяца (без сбоев).
 */
function доступ(компания, расчётовЗаМесяц = 0, now = new Date()) {
  const т = ТАРИФЫ[компания.tariff];
  const до = компания.paid_until ? Date.parse(компания.paid_until) : NaN;
  if (т && до > now.getTime()) {
    return { ...т, активен: true, пробный: false, до: компания.paid_until, осталось: null, можноСчитать: true, причина: '' };
  }
  const осталось = Math.max(0, (компания.calcs_limit || 0) - (компания.calcs_used || 0));
  return {
    ...ПРОБНЫЙ, активен: false, пробный: true, истёк: т ? компания.paid_until : null, осталось,
    можноСчитать: осталось > 0,
    причина: осталось > 0 ? '' : (т ? `Тариф «${т.имя}» закончился. Продлите его на странице «Тариф».` : 'Пробные расчёты закончились. Выберите тариф на странице «Тариф».')
  };
}

