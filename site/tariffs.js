function нуженВнедрение(компания, платежи = []) {
  if (компания && компания.paid_until) return false;
  return !платежи.some((п) => п.status === 'оплачен');
}

/** Сумма платежа за тариф: подписка, при первой оплате - плюс внедрение. */
function суммаОплаты(т, внедрение) {
  return т.цена + (внедрение ? ВНЕДРЕНИЕ : 0);
}

/** Новый срок оплаты: от сегодня или от конца уже оплаченного - что позже. */
function продлить(доСейчас, дней = ДНЕЙ_ОПЛАТЫ, now = new Date()) {
  const от = Math.max(now.getTime(), доСейчас ? Date.parse(доСейчас) || 0 : 0);
  return new Date(от + дней * 86400000).toISOString();
}

