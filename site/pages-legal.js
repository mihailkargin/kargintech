<p>2.1. После регистрации Заказчику доступен пробный период - ${ПРОБНЫХ_РАСЧЁТОВ} расчётов закупок без оплаты. Расчёт, не выполненный по причине на стороне Сервиса, в число использованных не входит.</p>
