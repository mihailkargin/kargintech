const { esc, страница } = require('./views');
const { ТАРИФЫ, ПРОБНЫХ_РАСЧЁТОВ, ДНЕЙ_ОПЛАТЫ, ВНЕДРЕНИЕ, ВНЕДРЕНИЕ_ПУНКТЫ } = require('./tariffs');
const { groupDigits } = require('../src/notify');

function реквизиты(env = process.env) {
  return {
    имя: String(env.LEGAL_NAME || '').trim(),
    инн: String(env.LEGAL_INN || '').trim(),
    почта: String(env.LEGAL_EMAIL || '').trim(),
    готово: env.LEGAL_READY === '1'
  };
}

const исполнитель = (р) => (р.имя
  ? `${esc(р.имя)}, применяющий специальный налоговый режим «Налог на профессиональный доход» (самозанятый)${р.инн ? `, ИНН ${esc(р.инн)}` : ''}`
  : 'физическое лицо, применяющее специальный налоговый режим «Налог на профессиональный доход» (самозанятый), реквизиты которого указаны в разделе «Реквизиты»');
const почтаДляОбращений = (р) => (р.почта ? `<a href="mailto:${esc(р.почта)}">${esc(р.почта)}</a>` : 'адрес, указанный в разделе «Реквизиты»');

function пометка(р) {
  return р.готово ? '' : '<div class="alert info">Документ на согласовании. Действующая редакция будет опубликована на этой странице до начала приёма оплаты.</div>';
}

function блокРеквизитов(р) {
  return `<h2>Реквизиты</h2><p>${р.имя ? esc(р.имя) : 'ФИО исполнителя будет указано в действующей редакции'}<br>
    ${р.инн ? `ИНН ${esc(р.инн)}<br>` : ''}Статус: самозанятый (налог на профессиональный доход)<br>
    ${р.почта ? `Почта для обращений: <a href="mailto:${esc(р.почта)}">${esc(р.почта)}</a><br>` : ''}Сайт: https://kargintech.ru</p>`;
}

function документ(заголовок, тело, р) {
  return страница({
    заголовок,
    описание: заголовок,
    тело: `<main class="section"><div class="wrap legal" style="max-width:860px">${пометка(р)}${тело}${блокРеквизитов(р)}
      <p class="small muted">Редакция от 21.10.2026.</p></div></main>`,
    безИндекса: !р.готово
  });
}

