/**
 * ВЫГРУЗКА ЛЕНТЫ В EXCEL - 22.10.2026. Тот же отбор, что на экране (фильтры
 * из адреса), одна строка на закупку. Только данные ленты клиента: публичные
 * сведения закупок и его же отметки.
 */
const { writeXlsx, STYLE } = require('../src/xlsx-write');
const { названиеРегиона } = require('../src/region');

const текстОбесп = (о) => {
  if (!о) return '';
  if (о.требуется === false) return 'не требуется';
  if (typeof о.сумма === 'number') return о.сумма;
  return typeof о.процент === 'number' ? `${о.процент}%` : '';
};

/**
 * @param {Array<object>} список закупки после отобратьЛенту
 * @param {object} отметки по номеру: saved, decision, note
 * @returns {Buffer}
 */
function лентаВExcel(список, отметки = {}) {
  const шапка = ['№ извещения', 'Закон и способ', 'Объект закупки', 'Заказчик', 'Регион заказчика', 'Начальная цена, ₽',
    'Окончание подачи заявок', 'Обеспечение заявки', 'Обеспечение контракта', 'Позиций в спецификации', 'Решение', 'Заметка', 'Ссылка на извещение']
    .map((v) => ({ v, s: STYLE.ШАПКА_ТАБЛИЦЫ }));
  const строки = список.map((т) => {
    const м = отметки[т.номер] || {};
    const р = т.разбор || {};
    const об = р.обеспечения || {};
    const заяв = текстОбесп(об.заявка);
    const контр = текстОбесп(об.контракт);
    return [
      { v: String(т.номер), s: STYLE.ЧИСЛО },
      { v: т.закон || '', s: STYLE.ПЕРЕНОС },
      { v: т.объект || '', s: STYLE.ПЕРЕНОС },
      { v: т.заказчик || '', s: STYLE.ПЕРЕНОС },
      { v: названиеРегиона(т.регион) || '', s: STYLE.ЧИСЛО },
      { v: typeof т.нмцк === 'number' ? т.нмцк : null, s: STYLE.ДЕНЬГИ },
      { v: т.срок ? String(т.срок).slice(0, 10).split('-').reverse().join('.') : '', s: STYLE.ЧИСЛО },
      { v: заяв, s: typeof заяв === 'number' ? STYLE.ДЕНЬГИ : STYLE.ЧИСЛО },
      { v: контр, s: typeof контр === 'number' ? STYLE.ДЕНЬГИ : STYLE.ЧИСЛО },
      { v: р.ок && р.позиций ? р.позиций : null, s: STYLE.ЧИСЛО },
      { v: м.decision || '', s: STYLE.ЧИСЛО },
      { v: м.note || '', s: STYLE.ПЕРЕНОС },
      { v: /^https:\/\/zakupki\.gov\.ru\//.test(т.url || '') ? т.url : '', s: STYLE.ЧИСЛО }
    ];
  });
  return writeXlsx([{
    name: 'Закупки',
    columns: [24, 26, 60, 40, 22, 18, 14, 18, 18, 12, 14, 30, 50].map((width) => ({ width })),
    rows: [шапка, ...строки],
    freezeRow: 1
  }]);
}

module.exports = { лентаВExcel };
