/**
 * РАСЧЁТ ПО ЗАГРУЖЕННЫМ ДОКУМЕНТАМ - проверка формы (владелец 31.10.2026).
 * Закупка с любой площадки, которой нет в ЕИС (коммерческие на Сбербанк-АСТ,
 * B2B-Center): клиент загружает файлы и вписывает то, что в ЕИС берётся из
 * карточки. Сетевых обращений нет.
 */

const ФАЙЛОВ_МАКС = 15;
const РАЗМЕР_МАКС = 30 * 1024 * 1024;
const РАСШИРЕНИЯ = /\.(docx?|xlsx?|xlsm|pdf|rtf|odt|ods|txt|csv|zip|rar|7z|jpe?g|png|tiff?)$/i;
const СПОСОБЫ = ['аукцион', 'запрос предложений', 'запрос котировок', 'конкурс', 'иной'];

const первое = (v) => (Array.isArray(v) ? v[0] : v);
const текст = (v, n) => String(первое(v) || '').replace(/\s+/g, ' ').trim().slice(0, n);

/** «25 000,50 ₽» → 25000.5; пусто или не число → null. */
function число(v) {
  const s = String(первое(v) || '').replace(/[\s ₽]|руб\.?/gi, '').replace(',', '.');
  if (!s) return null;
  if (!/^\d+(\.\d+)?$/.test(s)) return NaN;
  return Number(s);
}

function разобратьФормуЗагрузки(поля = {}, файлы = []) {
  const ошибки = [];
  const объект = текст(поля.object, 300);
  if (!объект) ошибки.push('укажите предмет закупки');
  const нмцк = число(поля.nmck);
  if (нмцк === null || Number.isNaN(нмцк) || нмцк <= 0) ошибки.push('укажите начальную цену числом, например 250000');
  const процент = (имя, подпись) => {
    const v = число(поля[имя]);
    if (v === null) return null;
    if (Number.isNaN(v) || v > 100) { ошибки.push(`${подпись}: процент числом от 0 до 100`); return null; }
    return v;
  };
  const обеспечениеЗаявки = процент('bid', 'обеспечение заявки');
  const обеспечениеКонтракта = процент('contract', 'обеспечение контракта');
  const срок = текст(поля.deadline, 10);
  if (срок && !/^\d{4}-\d{2}-\d{2}$/.test(срок)) ошибки.push('срок подачи - дата');
  const способ = СПОСОБЫ.includes(текст(поля.method, 40)) ? текст(поля.method, 40) : '';
  const ссылка = текст(поля.url, 500);

  const годные = (файлы || []).filter((ф) => ф && ф.имя && ф.данные && ф.данные.length);
  if (!годные.length) ошибки.push('приложите хотя бы один файл закупки');
  if (годные.length > ФАЙЛОВ_МАКС) ошибки.push(`не больше ${ФАЙЛОВ_МАКС} файлов - остальное можно сложить в архив`);
  const размер = годные.reduce((s, ф) => s + ф.данные.length, 0);
  if (размер > РАЗМЕР_МАКС) ошибки.push('файлы больше 30 МБ вместе');
  const чужие = годные.filter((ф) => !РАСШИРЕНИЯ.test(ф.имя));
  if (чужие.length) ошибки.push(`формат не читается: ${чужие.map((ф) => ф.имя).slice(0, 3).join(', ')} (подходят Word, Excel, PDF, архивы, фото)`);

  if (ошибки.length) return { ok: false, ошибка: ошибки.join('; ') };
  return {
    ok: true,
    мета: {
      объект, заказчик: текст(поля.customer, 300), нмцк, срокПодачи: срок || null,
      площадка: текст(поля.platform, 100), способ, ссылка: /^https?:\/\//i.test(ссылка) ? ссылка : '',
      обеспечениеЗаявки, обеспечениеКонтракта
    },
    файлы: годные.map((ф) => ({ имя: String(ф.имя).replace(/[\\/]/g, '_').slice(0, 200), данные: ф.данные }))
  };
}

module.exports = { разобратьФормуЗагрузки, СПОСОБЫ, ФАЙЛОВ_МАКС };
