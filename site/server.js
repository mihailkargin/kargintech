/**
 * Расход на модель за расчёт - из журнала приложения: строки вида
 * «стоимость: токены 0.0542 $ + поиски 0.0200 $ = 0.0742 $». Строк может быть
 * несколько (чтение скана моделью, поиск поставщиков) - складываются.
 * Нет строк - 0: модель не вызывалась.
 */
function стоимостьИзЖурнала(журнал) {
  let сумма = 0;
  for (const с of журнал || []) {
    const m = String(с).match(/стоимост[а-яё]*[^=\n]*=\s*([\d.]+)\s*\$/i);
    if (m) сумма += Number(m[1]) || 0;
  }
  return Math.round(сумма * 10000) / 10000;
}
