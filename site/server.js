function читатьФорму(req) {
  return new Promise((ok, нет) => {
    const куски = [];
    let размер = 0;
    req.on('data', (c) => {
      размер += c.length;
      if (размер > МАКС_ФОРМА) { нет(new Error('форма слишком велика')); req.destroy(); return; }
      куски.push(c);
    });
    req.on('end', () => {
      const п = new URLSearchParams(Buffer.concat(куски).toString('utf8'));
      const out = {};
      for (const [к, з] of п) {
        if (к in out) out[к] = [].concat(out[к], з); else out[к] = з;
      }
      ok(out);
    });
    req.on('error', нет);
  });
}

/**
 * Форма с файлом (multipart/form-data): поля и один файл. Без библиотек.
 * Предел - для прайса клиента (10 МБ) с запасом на разметку формы.
 */
function читатьФормуСФайлом(req, макс = 11 * 1024 * 1024) {
  return new Promise((ok, нет) => {
    const граница = (String(req.headers['content-type'] || '').match(/boundary=(?:"([^"]+)"|([^;]+))/i) || []).slice(1).find(Boolean);
    if (!граница) { нет(new Error('форма без границы частей')); return; }
    const куски = [];
    let размер = 0;
    req.on('data', (c) => {
      размер += c.length;
      if (размер > макс) { нет(new Error('файл слишком велик')); req.destroy(); return; }
      куски.push(c);
    });
    req.on('end', () => {
      const всё = Buffer.concat(куски);
      const разд = Buffer.from('--' + граница);
      const поля = {};
      let файл = null;
      const файлы = [];
      let i = всё.indexOf(разд);
      while (i !== -1) {
        const начало = i + разд.length;
        if (всё.slice(начало, начало + 2).toString() === '--') break;
        const след = всё.indexOf(разд, начало);
        if (след === -1) break;
        const часть = всё.slice(начало + 2, след - 2);
        const конецЗаголовков = часть.indexOf('\r\n\r\n');
        if (конецЗаголовков !== -1) {
          const заг = часть.slice(0, конецЗаголовков).toString('utf8');
          const тело = часть.slice(конецЗаголовков + 4);
          const имя = (заг.match(/name="([^"]*)"/) || [])[1];
          const имяФайла = (заг.match(/filename="([^"]*)"/) || [])[1];
          if (имяФайла !== undefined) {
            if (имяФайла && тело.length) файлы.push({ имя: имяФайла, данные: тело });
            if (!файл && имяФайла) файл = { имя: имяФайла, данные: тело };
          } else if (имя) поля[имя] = тело.toString('utf8');
        }
        i = след;
      }
      ok({ поля, файл, файлы });
    });
    req.on('error', нет);
  });
}

