/**
 * POST в приложение. Не fetch: у него предел ожидания заголовков 5 минут, а
 * расчёт с поиском поставщиков идёт дольше (20.10.2026: «fetch failed» при
 * том, что расчёт на сервере продолжался и тратил деньги).
 */
function вПриложение(путь, тело, мс = 60000, адрес = APP_URL) {
  return new Promise((ok) => {
    const u = new URL(путь, адрес);
    const данные = Buffer.from(JSON.stringify(тело || {}));
    const req = http.request({
      hostname: u.hostname, port: u.port || 80, path: u.pathname, method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length },
      timeout: мс
    }, (res) => {
      const куски = [];
      res.on('data', (c) => куски.push(c));
      res.on('end', () => {
        try { ok(JSON.parse(Buffer.concat(куски).toString('utf8'))); } catch (e) { ok({ ok: false, сбой: 'ответ приложения не разобран' }); }
      });
    });
    req.on('timeout', () => { req.destroy(new Error(`приложение не ответило за ${Math.round(мс / 1000)} с`)); });
    req.on('error', (e) => ok({ ok: false, сбой: e.message }));
    req.end(данные);
  });
}

