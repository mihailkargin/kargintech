/**
 * Настройки клиента → стоп-слова для поиска: свои «Исключая» плюс, если
 * работы и услуги не нужны, СТОП_УСЛУГИ. Старые настройки (до 22.10.2026)
 * хранили всё одним списком - из него служебные слова выделяются обратно.
 */
function разобратьСтоп(н = {}) {
  const все = (н.стопСлова || []).map(String);
  if (н.работыУслуги !== undefined) return { свои: все.filter((с) => !СТОП_УСЛУГИ.includes(с)), работыУслуги: !!н.работыУслуги };
  const былиУслуги = СТОП_УСЛУГИ.every((с) => все.includes(с));
  return { свои: все.filter((с) => !СТОП_УСЛУГИ.includes(с)), работыУслуги: !былиУслуги };
}
const собратьСтоп = (свои, работыУслуги) => [...new Set([...свои, ...(работыУслуги ? [] : СТОП_УСЛУГИ)])];

