/**
 * Приводит сырой адрес запроса к сравнимому виду.
 *
 * Отрезает строку параметров, раскодирует проценты, убирает завершающую
 * косую черту. Битое кодирование не роняет разбор: `decodeURIComponent`
 * бросает исключение на одиночном `%`, и запрос с таким адресом должен
 * получить честный отказ, а не обрушить обработчик.
 */
function нормальныйПуть(сырой) {
  let п = String(сырой || '').split('?')[0].split('#')[0];
  try {
    п = decodeURIComponent(п);
  } catch (e) {
    // Оставляем как есть: совпадения не будет, вернётся отказ с перечнем
    // точек входа. Это лучше, чем падение на чужом кривом запросе.
  }
  if (п.length > 1 && п.endsWith('/')) п = п.slice(0, -1);
  return п;
}

/**
 * Канонное имя точки входа либо null.
 *
 * @param {string} сырой значение `req.url`
 * @returns {string|null} одно из `ТОЧКИ`
 */
function маршрут(сырой) {
  return АДРЕСА[нормальныйПуть(сырой)] || null;
}

