/** Файл прайса: Excel/CSV - разбор прайса; старый .xls и PDF - через конвертер; YML и HTML - по содержимому. */
async function изФайла(url, н) {
  const r = await скачать(url);
  if (!r.ok) return r;
  return разобратьФайл(r.тело, decodeURIComponent((new URL(url).pathname.split('/').pop() || 'прайс')).slice(0, 80), url, н, r);
}

/**
 * ДИЛЕРСКИЙ ПРАЙС, ПОЛУЧЕННЫЙ ОТ ПОСТАВЩИКА (30.10.2026). Замер на 4 оптовиках
 * канцелярии: ни один не отдаёт цены кодом со страниц сайта (Комус закрыл
 * доступ, ОфисМаг без разметки, Самсон - цены после входа дилера, у Релефа нет
 * карты сайта). Рабочий путь - прайс, запрошенный во внедрении (владелец
 * 28.10.2026): файл кладётся в /data/state/catalog-files/, источник «локальный».
 * Дата цены - дата файла (когда получен), не дата чтения.
 */
async function изЛокального(путь, н) {
  const папка = path.resolve(path.join(н.каталогДанных || process.env.STATE_DIR || '/data/state', 'catalog-files'));
  const полный = path.resolve(папка, String(путь || ''));
  if (!полный.startsWith(папка + path.sep)) return { ok: false, отказ: `файл вне ${папка}` };
  let б, когда;
  try { б = fs.readFileSync(полный); когда = fs.statSync(полный).mtime; } catch (e) { return { ok: false, отказ: `файл не прочитан: ${e.message}` }; }
  const р = await разобратьФайл(б, path.basename(полный), '', н, null);
  return р.ok ? { ...р, тип: 'дилерский прайс', когда } : р;
}

async function разобратьФайл(б, имя, url, н, r) {
  const начало = б.slice(0, 600).toString('latin1');
  const текст = () => текстОтвета(r || { тело: б, заголовки: {} });
  if (/<yml_catalog/i.test(начало)) return { ...К.разобратьYml(текст()), тип: 'yml' };
  if (/<html|<!doctype html/i.test(начало)) return изСтраницыHtml(текст(), url);
  let данные = б;
  let имяДляРазбора = имя;
  const ER = require('./estimate-run');
  const конвертер = н.адресКонвертера || process.env.CONVERTER_URL || 'http://converter:3000';
  if (б[0] === 0xd0 && б[1] === 0xcf) {
    const п = await ER.пересохранить(б, имя, 'xls', конвертер);
    if (!п.ok) return { ok: false, отказ: `старый Excel не пересохранён: ${п.причина}` };
    данные = п.данные;
    имяДляРазбора = имя.replace(/\.xls$/i, '') + '.xlsx';
  } else if (начало.startsWith('%PDF')) {
    const п = await ER.текстPdfКодом(б, имя, конвертер);
    if (!п.ok) return { ok: false, отказ: `PDF прайса не прочитан: ${п.причина}` };
    данные = п.текст;
    имяДляРазбора = имя + '.csv';
  }
  const р = разобратьПрайс(данные, { имяФайла: имяДляРазбора });
  if (!р.ok) return { ok: false, отказ: `прайс не разобран: ${р.отказ}` };
  return { ok: true, тип: 'файл', позиции: р.позиции.map((п) => ({ ...п, url })) };
}

/** Страница с таблицами расценок или цен. */
function изСтраницыHtml(html, url) {
  const позиции = [];
  for (const т of К.таблицыИзHtml(html)) {
    const р = разобратьПрайс(т, { имяФайла: 'страница.csv' });
    if (р.ok) позиции.push(...р.позиции.map((п) => ({ ...п, url })));
  }
  if (!позиции.length) {
    const товар = К.товарИзСтраницы(html);
    if (товар) return { ok: true, тип: 'страница', позиции: [{ ...товар, url }] };
    return { ok: false, тип: 'страница', отказ: `на странице нет таблицы с наименованием и ценой (${текстИзHtml(html).length} знаков текста)` };
  }
  return { ok: true, тип: 'страница', позиции };
}

/** Сайт целиком: robots.txt → карты сайта → страницы товаров ниши → цена из разметки. */
async function изСайта(сайт, словаНиши, журнал) {
  const корень = new URL(сайт).origin;
  const rb = await взять(`${корень}/robots.txt`, { мс: 30000 });
  const robots = rb.ok ? К.разобратьRobots(rb.тело.toString('utf8')) : { правила: [], карты: [] };
  const очередь = robots.карты.length ? [...robots.карты] : [`${корень}/sitemap.xml`];
  const адреса = [];
  let карт = 0;
  while (очередь.length && карт < КАРТ_САЙТА && адреса.length < 200000) {
    const u = очередь.shift();
    карт++;
    const r = await скачать(u, 60000);
    if (!r.ok) continue;
    let текст;
    if (r.тело[0] === 0x1f && r.тело[1] === 0x8b) {
      try { текст = require('zlib').gunzipSync(r.тело).toString('utf8'); } catch (e) { continue; }
    } else текст = текстОтвета(r);
    const с = К.ссылкиИзSitemap(текст);
    // Сначала карты, похожие на товары: у магазинов они называются products/goods/catalog.
    очередь.push(...с.вложенные.sort((a, b) => Number(/prod|good|catalog|tovar|item/i.test(b)) - Number(/prod|good|catalog|tovar|item/i.test(a))));
    адреса.push(...с.страницы);
    await спать(ПАУЗА);
  }
  if (!адреса.length) return { ok: false, тип: 'сайт', отказ: 'карта сайта не найдена или пуста' };
  const отбор = К.отобратьСтраницы(адреса.filter((u) => доменИз(u) === доменИз(корень) && К.разрешено(robots, u)), словаНиши, СТРАНИЦ_С_САЙТА);
  журнал.push(`${доменИз(корень)}: в карте сайта ${адреса.length} адресов, по словам ниши отобрано ${отбор.length}`);
  if (!отбор.length) return { ok: false, тип: 'сайт', отказ: `в карте сайта (${адреса.length} адресов) нет страниц со словами ниши в адресе` };
  const позиции = [];
  let безРазметки = 0;
  // Причины незагрузки - числом по виду: «271 не загрузилась» без причины не
  // отличает отказ сайта от таймаута (Комус, 30.10.2026).
  const незагрузки = {};
  for (const u of отбор) {
    const r = await скачать(u, 30000);
    if (r.ok) {
      const т = К.товарИзСтраницы(текстОтвета(r));
      if (т) позиции.push({ ...т, url: u }); else безРазметки++;
    } else {
      const вид = (/код \d+/.exec(r.отказ) || [String(r.отказ).replace(/^.*?: /, '').slice(0, 40)])[0];
      незагрузки[вид] = (незагрузки[вид] || 0) + 1;
      // 503 - тоже отказ: защита Комуса закрыла доступ на 30.10.2026 после
      // обхода раз в секунду, и дальше отвечала 503 на всё, включая robots.txt.
      if (/код (403|429|503)/.test(r.отказ)) {
        журнал.push(`${доменИз(корень)}: сайт ответил отказом (${r.отказ}) - обход остановлен`);
        break;
      }
    }
    await спать(ПАУЗА);
  }
  const незагр = Object.entries(незагрузки).map(([к, n]) => `${к}: ${n}`).join(', ');
  if (незагр) журнал.push(`${доменИз(корень)}: не загрузились - ${незагр}`);
  if (!позиции.length) return { ok: false, тип: 'сайт', отказ: `из ${отбор.length} страниц ни на одной нет цены в разметке schema.org (загрузились без разметки ${безРазметки}${незагр ? `; не загрузились - ${незагр}` : ''})` };
  return { ok: true, тип: 'сайт', позиции, безРазметки };
}

