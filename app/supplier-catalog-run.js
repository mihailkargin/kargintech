/**
 * Обновить каталог одного поставщика. `сведения`: {домен, имя, сайт, телефон,
 * регион, вид: 'поставщик'|'подрядчик', источники: [{тип: 'файл'|'yml'|
 * 'страница'|'сайт', url}], словаНиши}. Источники пробуются по порядку до
 * первого, давшего цены.
 */
async function обновитьКаталог(сведения, н = {}, журнал = []) {
  const домен = сведения.домен || доменИз(сведения.сайт);
  if (!домен) return { ok: false, отказ: 'у поставщика нет сайта' };
  const папка = каталогПапка(н);
  fs.mkdirSync(папка, { recursive: true });
  const файл = path.join(папка, имяФайла(домен));
  let прежняя = null;
  try { прежняя = JSON.parse(fs.readFileSync(файл, 'utf8')); } catch (e) { /* новой записи нет */ }
  const источники = [...(сведения.источники || [])];
  // Дилерский прайс есть - обход сайта не нужен: на 4 оптовиках из 4 он цен не дал.
  if (сведения.сайт && !источники.some((и) => и.тип === 'сайт' || и.тип === 'локальный')) источники.push({ тип: 'сайт', url: сведения.сайт });
  const отказы = [];
  for (const и of источники) {
    let р;
    try {
      if (и.тип === 'сайт') р = await изСайта(и.url, сведения.словаНиши || [], журнал);
      else if (и.тип === 'локальный') р = await изЛокального(и.путь, н);
      else if (и.тип === 'страница') {
        const r = await скачать(и.url, 60000);
        р = r.ok ? изСтраницыHtml(текстОтвета(r), и.url) : r;
      } else р = await изФайла(и.url, н);
    } catch (e) { р = { ok: false, отказ: e.message }; }
    if (р.ok && р.позиции.length) {
      const { словаНиши, источники: _, ...мета } = сведения;
      const запись = { ...К.записьКаталога({ ...мета, домен, источник: { тип: р.тип || и.тип, url: и.url || '' }, источники: сведения.источники || [], словаНиши: словаНиши || [] }, р.позиции, р.когда || new Date()), последняяПопытка: new Date().toISOString() };
      fs.writeFileSync(файл + '.tmp', JSON.stringify(запись), 'utf8');
      fs.renameSync(файл + '.tmp', файл);
      журнал.push(`${домен}: каталог обновлён, ${р.тип || и.тип}, позиций ${р.позиции.length}`);
      return { ok: true, домен, тип: р.тип || и.тип, позиций: р.позиции.length };
    }
    отказы.push(`${и.тип}: ${р.отказ}`);
  }
  // Цен нет ни в одном источнике - поставщик остаётся контактом «прайс закрыт».
  const { словаНиши, ...мета } = сведения;
  const запись = прежняя && прежняя.позиции && прежняя.позиции.length
    ? { ...прежняя, последняяПопытка: new Date().toISOString(), отказ: отказы.join('; ').slice(0, 600) }
    : { ...мета, домен, словаНиши: словаНиши || [], прайсЗакрыт: true, позиций: 0, позиции: [], последняяПопытка: new Date().toISOString(), отказ: отказы.join('; ').slice(0, 600) };
  fs.writeFileSync(файл + '.tmp', JSON.stringify(запись), 'utf8');
  fs.renameSync(файл + '.tmp', файл);
  журнал.push(`${домен}: цен не получено - ${запись.отказ}`);
  return { ok: false, домен, отказ: запись.отказ, прайсЗакрыт: !запись.позиций };
}

/** Записи каталогов с диска (сырые). */
function записиКаталогов(н = {}) {
  const папка = каталогПапка(н);
  let файлы = [];
  try { файлы = fs.readdirSync(папка).filter((ф) => ф.endsWith('.json')); } catch (e) { return []; }
  const итог = [];
  for (const ф of файлы) {
    try { итог.push(JSON.parse(fs.readFileSync(path.join(папка, ф), 'utf8'))); } catch (e) { /* битый файл пропускаем */ }
  }
  return итог;
}

// Построенные каталоги держатся в памяти до изменения файла: каталог в
// десятки тысяч строк не перестраивается на каждый расчёт.
const кэш = new Map();
function прочитатьКаталоги(н = {}) {
  const папка = каталогПапка(н);
  let файлы = [];
  try { файлы = fs.readdirSync(папка).filter((ф) => ф.endsWith('.json')); } catch (e) { return []; }
  const итог = [];
  for (const ф of файлы) {
    const полный = path.join(папка, ф);
    try {
      const м = fs.statSync(полный).mtimeMs;
      const был = кэш.get(полный);
      if (был && был.м === м) { if (был.к.позиции.length) итог.push(был.к); continue; }
      const к = К.построитьКаталог(JSON.parse(fs.readFileSync(полный, 'utf8')));
      кэш.set(полный, { м, к });
      if (к.позиции.length) итог.push(к);
    } catch (e) { /* битый файл пропускаем */ }
  }
  return итог;
}

/** Обновить устаревшие каталоги по одному (вызывается ночью). */
async function обновитьУстаревшие(н = {}, предел = 3) {
  const журнал = [];
  const старые = записиКаталогов(н)
    .filter((з) => !К.свежий({ обновлено: з.обновлено }, new Date(), К.ОБНОВЛЯТЬ_ДНЕЙ))
    // Недавно уже пробовали и не вышло - не чаще раза в сутки.
    .filter((з) => !з.последняяПопытка || Date.now() - Date.parse(з.последняяПопытка) > 86400000)
    .slice(0, предел);
  for (const з of старые) {
    await обновитьКаталог({ домен: з.домен, имя: з.имя, сайт: з.сайт, телефон: з.телефон, регион: з.регион, вид: з.вид, источники: з.источники || (з.источник ? [з.источник] : []), словаНиши: з.словаНиши || [] }, н, журнал);
  }
  return { обновлялось: старые.length, журнал };
}

/**
 * Загрузка дилерского прайса, полученного от поставщика:
 *   1) файл (xlsx, xls, csv, pdf) - в /data/state/catalog-files/ на сервере;
 *   2) docker compose exec -T app node app/supplier-catalog-run.js --add
 *        --domain samsonopt.ru --name "ГК Самсон" --file samson-2026-10.xlsx
 *        [--site https://www.samsonopt.ru] [--phone ...] [--region ...] [--contractor]
 * Ключи латиницей (команду набирают на Windows). Цена действует 14 дней от
 * даты файла - потом нужен свежий прайс (правило «у цены есть дата»).
 */
if (require.main === module) {
  const ключ = (и) => { const i = process.argv.indexOf('--' + и); return i > 0 ? process.argv[i + 1] : null; };
  const { общиеНастройки } = require('./settings');
  if (!process.argv.includes('--add') || !ключ('domain') || !ключ('file')) {
    console.log('нужно: --add --domain <домен> --name <название> --file <имя файла в catalog-files>');
    process.exit(1);
  }
  const журнал = [];
  обновитьКаталог({
    домен: ключ('domain').toLowerCase(), имя: ключ('name') || ключ('domain'), сайт: ключ('site') || `https://${ключ('domain')}`,
    телефон: ключ('phone') || '', регион: ключ('region') || '', вид: process.argv.includes('--contractor') ? 'подрядчик' : 'поставщик',
    источники: [{ тип: 'локальный', путь: ключ('file') }]
  }, общиеНастройки(), журнал).then((r) => {
    for (const с of журнал) console.log(с);
    console.log(r.ok ? `загружено: позиций ${r.позиций}` : `НЕ загружено: ${r.отказ}`);
    process.exit(r.ok ? 0 : 1);
  });
}

