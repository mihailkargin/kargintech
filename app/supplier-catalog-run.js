const fs = require('fs');
const path = require('path');
const { взять } = require('./http');
const { раскодировать, текстИзHtml } = require('./verify-suppliers');
const К = require(path.join(__dirname, '..', 'src', 'supplier-catalog'));
const { разобратьПрайс } = require(path.join(__dirname, '..', 'src', 'price-list'));

// 2 с между страницами чужого сайта: при 1 с защита Комуса закрыла доступ (30.10.2026).
const ПАУЗА = 2000;
const СТРАНИЦ_С_САЙТА = 400;
const КАРТ_САЙТА = 20;
const ПРЕДЕЛ_ФАЙЛА = 30 * 1024 * 1024;

const спать = (мс) => new Promise((ok) => setTimeout(ok, мс));
const каталогПапка = (н = {}) => path.join(н.каталогДанных || process.env.STATE_DIR || '/data/state', 'catalogs');
const имяФайла = (домен) => String(домен || '').toLowerCase().replace(/[^a-z0-9а-яё.-]/gi, '_').slice(0, 120) + '.json';
const доменИз = (url) => { try { return new URL(url).hostname.replace(/^www\./, '').toLowerCase(); } catch (e) { return ''; } };

/** Текст ответа с учётом кодировки; у XML кодировка объявлена в <?xml encoding>. */
function текстОтвета(r) {
  const начало = r.тело.slice(0, 200).toString('latin1');
  const xml = /<\?xml[^>]*encoding=["']([a-z0-9_-]+)/i.exec(начало);
  const р = раскодировать(r.тело, xml ? `charset=${xml[1]}` : ((r.заголовки || {})['content-type'] || ''));
  return р.ok ? р.текст : r.тело.toString('utf8');
}

async function скачать(url, мс = 120000) {
  const r = await взять(url, { мс, заголовки: { Accept: '*/*' } });
  if (!r.ok) return { ok: false, отказ: `${url}: ${r.ошибка || 'код ' + r.код}` };
  if (r.тело.length > ПРЕДЕЛ_ФАЙЛА) return { ok: false, отказ: `${url}: файл больше ${ПРЕДЕЛ_ФАЙЛА / 1048576} МБ` };
  return { ok: true, ...r };
}

