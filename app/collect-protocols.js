/**
 * Сбор статистики снижения цены по протоколам прошлых закупок.
 *
 * ЗАПУСКАТЬ НА РОССИЙСКОМ СЕРВЕРЕ, внутри контейнера приложения:
 *
 *   docker compose exec -T app node app/collect-protocols.js --слово "бумага"
 *   docker compose exec -T app node app/collect-protocols.js --слово "бумага" --страниц 5
 *
 * Результат складывается в /data/state/protocols-<слово>.json и печатается
 * сводкой. Повторный запуск дополняет файл, не затирая: собранное стоит часов
 * работы, и терять его из-за опечатки в слове нельзя.
 *
 * ПОЧЕМУ НЕ С НОУТБУКА ВЛАДЕЛЬЦА. Портал не отвечает на зарубежные адреса, а у
 * владельца постоянно включён AmneziaVPN, нужный для доступа к Claude. С
 * сервера портал отвечает — это проверено.
 *
 * ПОЧЕМУ МЕДЛЕННО И ЭТО ПРАВИЛЬНО. Между запросами стоит пауза. Портал
 * государственный, и выжимать из него страницы на полной скорости — верный
 * способ получить отказ по адресу сервера, то есть потерять доступ ко всему
 * продукту. Сбор нескольких сотен протоколов занимает часы, и так и должно быть.
 *
 * ЧТО СОБИРАЕТСЯ ПО КАЖДОЙ ЗАКУПКЕ
 *   1. выдача по завершённым закупкам — список закупок со ссылками;
 *   2. страница результатов определения поставщика — НМЦК и цена победы;
 *   3. вкладка списка заявок, если ссылка на протокол нашлась — число
 *      участников и все предложенные цены.
 *
 * Шаг 3 необязателен: снижение считается и без него. Число участников — разрез,
 * а не условие.
 */
const fs = require('fs');
const path = require('path');

const { взятьТекст } = require('./http');
const { parseSearchPage } = require('../src/parser');
const {
  parseSupplierResults, parseBidList, наблюдение,
  адресРезультатов, адресСпискаЗаявок, ссылкиНаПротоколы
} = require('../src/protocol-page');
const { разложить } = require('../src/discount-stats');
const { parseNoticePage } = require('../src/notice-page');

const БАЗА = 'https://zakupki.gov.ru';

/**
 * Пауза между запросами к порталу, мс. Уменьшать нельзя.
 *
 * ПОВЫШЕНА С 1500 ДО 3000 ПОСЛЕ СБОРА 05.10.2026. Прогон на 10 страниц сделал
 * около 230 запросов за примерно 6 минут, и портал начал отвечать кодом 403 —
 * сначала на отдельных страницах результатов, затем на всех страницах выдачи
 * подряд, с четвёртой по десятую. Это отказ по адресу сервера, а не ошибка кода.
 *
 * Цена такого отказа несоизмерима с выигрышем в скорости: доступ к порталу с
 * российского адреса — это весь продукт. Поэтому пауза удвоена, а не подобрана
 * «поближе к границе»: границу мы не знаем, и искать её запросами значит
 * нарываться на неё снова.
 */
const ПАУЗА = 3000;

/** Ниже этого значения пауза не опускается ни ключом, ни правкой вызова. */
const ПАУЗА_МИНИМУМ = 1500;

/**
 * Предел запросов к порталу за один прогон.
 *
 * ТРЕБОВАНИЕ ВЛАДЕЛЬЦА 05.10.2026: «не нужно так много, не гонись за
 * количеством». Он прав, и предел по страницам этого не обеспечивал: одна
 * страница выдачи — до 50 закупок, а это до сотни с лишним запросов, и «страниц
 * 10» незаметно превращалось в двести с лишним.
 *
 * Поэтому предел стоит там, где измеряется риск — в числе обращений к порталу, а
 * не в числе страниц. Прогон на одной странице (около 80 запросов) проходил
 * благополучно четыре раза; отказ пришёл где-то между 150 и 230. Предел взят ниже
 * проверенного благополучного значения, а не близко к границе отказа.
 *
 * Это не ошибка, а плановая остановка: собранное дописано, продолжить можно той
 * же командой позже, уже собранные закупки повторно не запрашиваются.
 */
const ЗАПРОСОВ_ЗА_ПРОГОН = 80;

/**
 * Сколько отказов подряд считаем сигналом «портал нас больше не обслуживает».
 *
 * Один отказ бывает случайным, пять подряд — нет.
 */
const ОТКАЗОВ_ПОДРЯД_ДОВОЛЬНО = 5;

const ждать = (мс) => new Promise((ok) => setTimeout(ok, мс));

/**
 * Адрес выдачи по ЗАВЕРШЁННЫМ закупкам.
 *
 * НЕНУЖНЫЕ СТАДИИ НЕ ПЕРЕДАЮТСЯ ВОВСЕ, А НЕ СТАВЯТСЯ В «off».
 *
 * Здесь было `af=off&ca=off&pc=on&pa=off`, и фильтр не работал: на первом сборе
 * 05.10.2026 в выдачу попала закупка 0817200000326014925 со сроком подачи заявок
 * 14.10.2026, то есть ещё принимающая заявки. Протокола у такой нет и быть не
 * может, а в отказах она выглядела как ошибка разбора.
 *
 * Причина: фильтры стадий на портале — обычные галочки в форме, а невыбранная
 * галочка браузером НЕ ОТПРАВЛЯЕТСЯ. Портал видит присутствие параметра, а не
 * его значение, поэтому `af=off` включает подачу заявок вместо того, чтобы её
 * выключить. Правильно — передать только `pc=on`.
 *
 * Стадии портала: af — подача заявок, ca — работа комиссии, pc — закупка
 * завершена, pa — закупка отменена. Нужна только pc.
 */
function адресЗавершённых(слово, страница, наСтранице = 50) {
  return БАЗА + '/epz/order/extendedsearch/results.html?'
    + [
      'searchString=' + encodeURIComponent(слово),
      'fz44=on',
      'pc=on',
      'pageNumber=' + страница,
      'recordsPerPage=_' + наСтранице
    ].join('&');
}

/**
 * Основа слова для проверки однородности выборки.
 *
 * Берём слово без последних двух букв: «бумага» → «бума», и этого довольно,
 * чтобы поймать и бумагу, и бумаги. Разбирать русскую морфологию здесь незачем.
 */
function основаСлова(слово) {
  const s = String(слово || '').trim().toLowerCase().split(/\s+/)[0];
  return s.length > 4 ? s.slice(0, s.length - 2) : s;
}

/**
 * Основы слов, по которым закупка считается «своим рынком».
 *
 * ПОЧЕМУ НЕ ОДНА ОСНОВА ИСКОМОГО СЛОВА. Первый рабочий сбор 05.10.2026 показал,
 * что проверка по слову «бума» выбросила «Поставку канцелярских товаров»,
 * «Поставку бланочной продукции», «Поставку печатной продукции». Для поставщика
 * бумаги это ЕГО рынок — в проекте это записано прямо: портал ищет по смыслу, и
 * канцтовары в выдаче по слову «бумага» поставщику бумаги, скорее всего, нужны.
 *
 * Правильная граница рынка — те же ключевые слова, по которым клиенту отбираются
 * тендеры (`filter.keywords` в его настройках). Тогда выборка снижений
 * соответствует ровно тому, на что он заявляется, а не случайному слову запроса.
 *
 * Если ключевые слова не заданы, остаётся основа искомого слова — узко, но
 * предсказуемо. Пустой список означал бы «брать всё», то есть смешать товары с
 * услугами, а снижение по такой выборке не описывает ни один рынок.
 */
function основыРынка(слово, ключевые) {
  const список = String(ключевые || '')
    .split(/[,;]+/)
    .map((s) => s.trim().toLowerCase())
    .filter(Boolean);
  return список.length ? список : [основаСлова(слово)].filter(Boolean);
}

/** Относится ли объект закупки к рынку клиента. */
function относитсяКРынку(объект, основы) {
  const низ = String(объект || '').toLowerCase();
  return основы.some((о) => низ.indexOf(о) >= 0);
}

/**
 * Проверка, что закупка действительно завершена.
 *
 * Вторая защита к фильтру стадии: если срок подачи заявок ещё не истёк, закупка
 * не завершена, и запрашивать её протокол бессмысленно. Проверка остаётся даже
 * после починки адреса — поведение фильтров портала мы не контролируем, а тихо
 * считать незавершённые закупки ошибкой разбора нельзя.
 */
function срокЕщёНеИстёк(deadline, сегодня) {
  if (!deadline) return false;
  const д = String(deadline).slice(0, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(д)) return false;
  return д > сегодня;
}

function путьФайла(слово) {
  const каталог = process.env.STATE_DIR || '/data/state';
  const имя = 'protocols-' + String(слово).replace(/[^a-zA-Zа-яёА-ЯЁ0-9]+/g, '-').toLowerCase() + '.json';
  return path.join(каталог, имя);
}

function прочитать(файл) {
  try {
    const d = JSON.parse(fs.readFileSync(файл, 'utf8'));
    return Array.isArray(d.наблюдения) ? d : { наблюдения: [] };
  } catch (e) {
    return { наблюдения: [] };
  }
}

function записать(файл, данные) {
  fs.mkdirSync(path.dirname(файл), { recursive: true });
  // Через временный файл: прерванная запись не должна оставить мусор вместо
  // часов собранных данных.
  const врем = файл + '.tmp';
  fs.writeFileSync(врем, JSON.stringify(данные, null, 1));
  fs.renameSync(врем, файл);
}

async function собрать(слово, страниц, ключевые = '', пауза = ПАУЗА, пределЗапросов = ЗАПРОСОВ_ЗА_ПРОГОН) {
  const файл = путьФайла(слово);
  const данные = прочитать(файл);
  const было = данные.наблюдения.length;
  const известные = new Set(данные.наблюдения.map((н) => н.номер));

  const основы = основыРынка(слово, ключевые);
  const сегодня = new Date().toISOString().slice(0, 10);

  const задержка = Math.max(ПАУЗА_МИНИМУМ, Number(пауза) || ПАУЗА);
  const предел = Math.max(1, Number(пределЗапросов) || ЗАПРОСОВ_ЗА_ПРОГОН);

  // СЧЁТ ЗАПРОСОВ И ВРЕМЕНИ НУЖЕН НЕ ДЛЯ КРАСОТЫ. 05.10.2026 портал начал
  // отказывать на четвёртой странице, и выяснить, после какого числа запросов
  // это произошло, было нечем: сборщик не считал ни запросы, ни время. Без этих
  // двух чисел подобрать безопасный темп невозможно — остаётся гадать.
  const счёт = { запросов: 0, отказов: 0, подрядОтказов: 0, начало: Date.now() };
  let остановка = '';

  /**
   * Один запрос к порталу с паузой, учётом и ОСТАНОВКОЙ ПРИ ОТКАЗЕ.
   *
   * ПРОДОЛЖАТЬ ПОСЛЕ 403 НЕЛЬЗЯ. На сборе 05.10.2026 портал ответил 403 на
   * четвёртой странице, а сборщик спокойно запросил пятую, шестую и так до
   * десятой — то есть семь раз постучал в дверь, которую нам только что
   * закрыли. Так временное ограничение превращают в постоянное, а потеря адреса
   * сервера означает потерю доступа к порталу, то есть всего продукта.
   */
  async function запросить(адрес) {
    // Предел проверяется ДО запроса: «уже сделали столько» — не оправдание
    // сделать ещё один.
    if (счёт.запросов >= предел) {
      остановка = `предел ${предел} запросов за прогон достигнут — остановились сами, `
        + 'портал не отказывал';
      return { ok: false, код: 0, ошибка: 'предел запросов за прогон' };
    }

    счёт.запросов++;
    const r = await взятьТекст(адрес, 60000);
    await ждать(задержка);

    if (r.ok) { счёт.подрядОтказов = 0; return r; }

    счёт.отказов++;
    счёт.подрядОтказов++;

    if (r.код === 403 || r.код === 429) {
      остановка = `портал ответил кодом ${r.код} — это отказ по адресу сервера, `
        + `а не ошибка разбора. Сделано ${счёт.запросов} запросов за `
        + `${Math.round((Date.now() - счёт.начало) / 1000)} с`;
    } else if (счёт.подрядОтказов >= ОТКАЗОВ_ПОДРЯД_ДОВОЛЬНО) {
      остановка = `${счёт.подрядОтказов} отказов подряд (последний: `
        + `${r.ошибка || 'код ' + r.код}) — похоже, портал перестал отвечать`;
    }
    return r;
  }

  console.log(`слово «${слово}», страниц ${страниц}, уже собрано ${было} наблюдений`);
  console.log(`файл: ${файл}`);
  console.log(`рынок задан основами: ${основы.join(', ')} — закупка вне них в выборку не идёт`);
  console.log(`предел ${предел} запросов за прогон, пауза ${задержка} мс. Дойдя до предела, `
    + 'сбор остановится сам — это плановая остановка, а не сбой');
  if (!ключевые) {
    console.log('ключевые слова не заданы, взята основа искомого слова. Это узко: '
      + 'для поставщика бумаги его рынок — ещё и канцтовары, бланки, печатная продукция.');
    console.log('Задать шире: --ключевые "бумаг,канцеляр,блан,печатн"');
  }

  const отказы = [];

  for (let стр = 1; стр <= страниц; стр++) {
    if (остановка) break;
    const адрес = адресЗавершённых(слово, стр);
    const r = await запросить(адрес);

    if (!r.ok) { отказы.push(`страница ${стр}: ${r.ошибка || 'код ' + r.код}`); continue; }
    const страница = String(r.тело || '');
    if (страница.length < 2000) { отказы.push(`страница ${стр}: ответ короче 2000 знаков`); continue; }

    const карточки = parseSearchPage(страница) || [];
    console.log(`\nстраница ${стр}: карточек ${карточки.length}`);
    if (карточки.length === 0) break;

    for (const к of карточки) {
      if (остановка) break;
      if (!к.url) continue;
      if (известные.has(к.number)) {
        // Наблюдения, собранные до 19.10.2026, кода ОКПД2 не содержат. ИКЗ есть
        // в этой же выдаче — дописываем без нового запроса к порталу.
        const старое = данные.наблюдения.find((x) => x.номер === к.number);
        if (старое && старое.группаОкпд2 === undefined && к.ikz) {
          старое.ikz = к.ikz;
          старое.группаОкпд2 = к.okpdGroup || null;
          записать(файл, данные);
        }
        // «0000» без списка кодов - дозаполнить с карточки (20.10.2026).
        if (старое && !старое.группаОкпд2 && !(старое.группыОкпд2 || []).length && к.ikz && !остановка) {
          const кк = await запросить(к.url);
          const г = кк.ok ? (parseNoticePage(String(кк.тело || ''), к.url).группыОкпд2 || []) : [];
          if (г.length) { старое.группыОкпд2 = г; записать(файл, данные); }
        }
        continue;
      }

      // ОБЪЕКТА ЗАКУПКИ МОЖЕТ НЕ БЫТЬ ВОВСЕ — ЭТО НЕ «ДРУГОЙ РЫНОК».
      //
      // Известная особенность портала: у закупок по части 12 статьи 93
      // (электронный магазин, сегмент пути ezt20) поля «Объект закупки» в
      // карточке нет. Такую закупку нельзя ни отнести к рынку, ни уверенно
      // отбросить, и причина у неё своя. На сборе 05.10.2026 таких было 4 из 50,
      // и они попадали в «другой рынок» — то есть причина была названа неверно.
      if (!String(к.object || '').trim()) {
        отказы.push(`${к.number}: в карточке нет объекта закупки — к рынку не отнести `
          + '(бывает у закупок по ч. 12 ст. 93)');
        continue;
      }

      // ОДНОРОДНОСТЬ ВЫБОРКИ. Портал ищет по смыслу, и по слову «бумага» он
      // вернул «заправку картриджей и ремонт печатной техники» — другой рынок
      // с другим поведением цены. Снижение по смешанной выборке не описывает
      // ни один товар.
      //
      // Границу рынка задают ключевые слова клиента — те же, по которым ему
      // отбираются тендеры. Проверка по одной основе искомого слова выбрасывала
      // «канцелярские товары» и «бланочную продукцию», а это рынок поставщика
      // бумаги.
      //
      // Проверка всё равно грубая и этого не скрывает: она не отделяет «бумагу
      // туалетную» от «бумаги для регистрирующих приборов», а это разные рынки.
      // Настоящая однородность достигается кодом ОКПД2 — следующий шаг.
      if (!относитсяКРынку(к.object, основы)) {
        отказы.push(`${к.number}: объект «${String(к.object).slice(0, 60)}» вне рынка `
          + `(${основы.join(', ')})`);
        continue;
      }

      // Вторая защита к фильтру стадии: срок подачи ещё не истёк — закупка не
      // завершена, протокола у неё нет.
      if (срокЕщёНеИстёк(к.deadline, сегодня)) {
        отказы.push(`${к.number}: срок подачи заявок ${к.deadline} ещё не истёк — `
          + 'закупка не завершена');
        continue;
      }

      const адресРез = адресРезультатов(к.url);
      if (!адресРез) continue;

      const рр = await запросить(адресРез);
      if (!рр.ok) {
        // КОД ОТВЕТА НАЗЫВАЕТСЯ. Раньше здесь стояло просто «результаты не
        // открылись», и на сборе 05.10.2026 таких оказалось 19 — различить среди
        // них отказ портала (403) и обычный таймаут было нечем. Отказ портала
        // выглядел как разрозненные неудачи, хотя это был один и тот же сигнал.
        отказы.push(`${к.number}: результаты не открылись — ${рр.ошибка || 'код ' + рр.код}`);
        continue;
      }

      const результаты = parseSupplierResults(String(рр.тело || ''), к.url);

      // Список заявок — по желанию. Нужен для разреза по числу участников.
      let список = null;
      const протоколы = ссылкиНаПротоколы(String(рр.тело || ''));
      const главный = протоколы.find((u) => /protocol-main-info/.test(u));
      if (главный && !остановка) {
        const сз = await запросить(адресСпискаЗаявок(главный));
        if (сз.ok) список = parseBidList(String(сз.тело || ''));
      }

      const н = наблюдение(результаты, список);
      if (!н.годится) {
        отказы.push(`${к.number}: ${н.причина}`);
        continue;
      }

      // Группа ОКПД2 из ИКЗ выдачи (src/okpd.js) — бесплатно, отдельного
      // запроса нет. «0000» в ИКЗ (несколько кодов) - коды берутся с карточки
      // закупки: один запрос, только для таких (около 40%, 20.10.2026). Не
      // открылась - группы неизвестны, а не «любые».
      let группы = [];
      if (!к.okpdGroup && к.ikz && !остановка) {
        const кк = await запросить(к.url);
        if (кк.ok) группы = (parseNoticePage(String(кк.тело || ''), к.url).группыОкпд2 || []);
      }
      данные.наблюдения.push({ ...н.наблюдение, ikz: к.ikz || '', группаОкпд2: к.okpdGroup || null,
        ...(группы.length ? { группыОкпд2: группы } : {}),
        собрано: new Date().toISOString().slice(0, 10) });
      известные.add(к.number);
      записать(файл, данные);
      // Архив закупок (app/archive.js): протокол - в общую базу для аналитики.
      require('./archive').записатьПротокол(данные.наблюдения[данные.наблюдения.length - 1],
        path.join(path.dirname(файл), 'archive.db'));

      console.log(`  ${н.наблюдение.номер}  ${н.наблюдение.способ}`
        + `  снижение ${н.наблюдение.снижение}%`
        + `  участников ${н.наблюдение.участников !== null ? н.наблюдение.участников
          : (н.наблюдение.участниковНеМенее !== null ? '≥' + н.наблюдение.участниковНеМенее : '—')}`
        + (н.наблюдение.единственнаяЗаявка ? '  (единственная заявка, торга не было)' : ''));
    }
  }

  const секунд = Math.round((Date.now() - счёт.начало) / 1000);
  console.log(`\n=== СОБРАНО: ${данные.наблюдения.length} наблюдений (было ${было}) ===`);
  console.log(`запросов к порталу: ${счёт.запросов}, из них отказов ${счёт.отказов}, `
    + `время ${Math.floor(секунд / 60)} мин ${секунд % 60} с, пауза ${задержка} мс`);

  if (остановка) {
    const самиОстановились = /предел/.test(остановка);
    console.log('\n' + (самиОстановились ? '-' : '!').repeat(70));
    console.log((самиОстановились ? 'ОСТАНОВИЛИСЬ ПО ПЛАНУ: ' : 'СБОР ОСТАНОВЛЕН ДОСРОЧНО: ')
      + остановка);
    console.log('');
    console.log('Собранное сохранено — файл дописывается после каждой закупки, ничего');
    console.log('не потеряно. Продолжить можно той же командой позже: уже собранные');
    console.log('закупки повторно не запрашиваются.');

    if (самиОстановились) {
      console.log('');
      console.log('Это не сбой. Предел стоит затем, чтобы один прогон не мог упереться');
      console.log('в ограничение портала: 05.10.2026 портал отказал кодом 403 после');
      console.log('примерно 200 запросов, и доступ к нему с российского адреса — это');
      console.log('весь продукт. Следующую порцию брать не раньше чем через час.');
    } else {
      console.log('');
      console.log('ЧТО ДЕЛАТЬ. Переждать, а не пробовать снова сразу: повторные запросы');
      console.log('в закрытую дверь превращают временное ограничение в постоянное, а');
      console.log('доступ к порталу с российского адреса — это весь продукт.');
      console.log('Проверить одним запросом, отвечает ли портал снова:');
      console.log('  docker compose exec -T app node -e "require(\'./app/http\')'
        + '.взятьТекст(\'https://zakupki.gov.ru/epz/order/extendedsearch/results.html'
        + '?searchString=%D0%B1%D1%83%D0%BC%D0%B0%D0%B3%D0%B0\').then(r=>'
        + 'console.log(r.код, r.ok))"');
    }
    console.log((самиОстановились ? '-' : '!').repeat(70));
  }

  const разрезы = разложить(данные.наблюдения);
  console.log(`\nПО СПОСОБУ ЗАКУПКИ (смешивать способы нельзя):`);
  for (const с of разрезы.поСпособу) {
    console.log(`  ${с.ключ}: наблюдений ${с.n}`
      + (с.медиана !== null ? `, медиана ${с.медиана}%, половина случаев ${с.q1}–${с.q3}%, `
        + `от ${с.мин}% до ${с.макс}%` : '')
      + (с.достаточно ? '' : '  ← МАЛО, это не статистика'));

    // Две медианы вместо одной — обе названы условием. Закупка с единственной
    // заявкой это заключённый контракт, но торга в ней не было, и снижение в ней
    // почти нулевое. Смешать — занизить ожидаемое снижение, то есть назвать
    // выгодным убыточный тендер. Убрать — потерять исход, который с клиентом
    // случится. Поэтому печатаются оба, а решение принимает владелец.
    if (с.безЕдинственных) {
      console.log(`     из них с единственной заявкой: ${с.единственных} (торга не было)`);
      console.log(`     только конкурентные: наблюдений ${с.безЕдинственных.n}`
        + (с.безЕдинственных.медиана !== null
          ? `, медиана ${с.безЕдинственных.медиана}%, половина случаев `
            + `${с.безЕдинственных.q1}–${с.безЕдинственных.q3}%`
          : ''));
    }
    for (const п of с.предупреждения) console.log(`     ⚠️ ${п}`);
  }

  console.log(`\nПО ЧИСЛУ УЧАСТНИКОВ (только где число известно точно):`);
  if (разрезы.поУчастникам.length === 0) {
    console.log('  разрезов нет — ни по одной закупке число участников не определено');
  }
  for (const с of разрезы.поУчастникам) {
    console.log(`  ${с.ключ}: наблюдений ${с.n}`
      + (с.медиана !== null ? `, медиана ${с.медиана}%` : '')
      + (с.достаточно ? '' : '  ← МАЛО'));
  }
  console.log(`\nбез точного числа участников: ${разрезы.безЧислаУчастников} из ${разрезы.всего}`);
  console.log('блок постраничности портал рисует JavaScript, поэтому при полной '
    + 'странице заявок их число считается неизвестным');
  if (разрезы.единственныхЗаявок) {
    console.log(`\nс единственной заявкой: ${разрезы.единственныхЗаявок} из ${разрезы.всего}. `
      + 'Такая закупка признана несостоявшейся по п. 1 ч. 1 ст. 52, но контракт с '
      + 'единственным участником заключается — поэтому наблюдение берётся. Торга в ней '
      + 'не было, поэтому она же показана отдельно.');
  }

  // ОТКАЗЫ ГРУППИРУЮТСЯ ПО ПРИЧИНЕ, А НЕ ПЕЧАТАЮТСЯ СПИСКОМ.
  //
  // Первый сбор напечатал 36 строк с одинаковым текстом — по такому выводу
  // нельзя понять, это закупки, которые не состоялись (штатный исход), или
  // страницы, с которыми не справился разбор (ошибка в коде). Теперь видно
  // сразу, какая причина сколько весит.
  if (отказы.length) {
    const поПричине = new Map();
    for (const о of отказы) {
      const причина = о.replace(/^\S+:\s*/, '');
      if (!поПричине.has(причина)) поПричине.set(причина, []);
      поПричине.get(причина).push(о.split(':')[0]);
    }
    console.log(`\nНЕ ВЗЯТО (${отказы.length}), по причинам:`);
    const отсортированные = [...поПричине.entries()].sort((a, b) => b[1].length - a[1].length);
    for (const [причина, номера] of отсортированные) {
      const это_ошибка = /проверить разбор|ошибка разбора|разбор неверен/.test(причина);
      console.log(`\n  ${номера.length} × ${причина}${это_ошибка ? '   ← ЭТО ПОХОЖЕ НА ОШИБКУ В КОДЕ' : ''}`);
      console.log(`     ${номера.slice(0, 6).join(', ')}`
        + (номера.length > 6 ? ` …и ещё ${номера.length - 6}` : ''));
      if (это_ошибка) {
        console.log('     посмотреть, что на этих страницах:');
        console.log(`     docker compose exec -T app node app/diagnose-protocol.js `
          + `--слово "${слово}" --номера "${номера.slice(0, 2).join(',')}"`);
      }
    }
  }
}

