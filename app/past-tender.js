/**
 * РАЗБОР ПРОШЛОГО ТЕНДЕРА - пункт внедрения владельца 24.10.2026: «считаем ваши
 * прошлые тендеры заново и показываем, сколько вы могли заработать и какие
 * риски были в условиях контракта».
 *
 * Номер завершённой закупки → карточка (портал отдаёт карточку 44-ФЗ по номеру
 * при любом сегменте типа процедуры, проверено 25.10.2026) → разбор
 * документации и расчёт ПО ЦЕНАМ КЛИЕНТА (без модели и без поиска поставщиков) →
 * протокол: цена победы, падение, участники → прибыль при цене победы.
 *
 * Вывод о прибыли - только когда закупочные цены клиента есть у ВСЕХ позиций:
 * по ценам заказчика «прибыль» - сравнение числа с собой же (правило 04.10.2026).
 */
const path = require('path');
const { взятьТекст } = require('./http');
const { собратьСмету } = require('./estimate-run');
const { настройкиКлиента, общиеНастройки } = require('./settings');
const { посчитатьИтоги } = require(path.join(__dirname, '..', 'src', 'estimate-xlsx'));
const { parseSupplierResults, наблюдение, адресРезультатов, ссылкиНаПротоколы, адресСпискаЗаявок, parseBidList } = require(path.join(__dirname, '..', 'src', 'protocol-page'));

const адресКарточки = (номер) => (номер.length === 19
  ? `https://zakupki.gov.ru/epz/order/notice/ea20/view/common-info.html?regNumber=${номер}`
  : `https://zakupki.gov.ru/223/purchase/public/purchase/info/common-info.html?regNumber=${номер}`);

/** Цена победы, падение и участники из протокола (только 44-ФЗ). */
async function протокол(ссылка, взять = взятьТекст) {
  const адрес = адресРезультатов(ссылка);
  if (!адрес) return { ok: false, причина: 'адрес результатов не построить' };
  const р = await взять(адрес);
  if (!р.ok) return { ok: false, причина: `результаты не открылись: код ${р.код || р.ошибка}` };
  const рез = parseSupplierResults(String(р.тело || ''), ссылка);
  let список = null;
  const главный = ссылкиНаПротоколы(String(р.тело || '')).find((u) => /protocol-main-info/.test(u));
  if (главный) { const с = await взять(адресСпискаЗаявок(главный)); if (с.ok) список = parseBidList(String(с.тело || '')); }
  const н = наблюдение(рез, список);
  return н.годится ? { ok: true, ...н.наблюдение } : { ok: false, причина: н.причина };
}

async function разборПрошлого(клиент, номер, опции = {}) {
  const н = String(номер || '').trim();
  if (!/^(\d{11}|\d{19})$/.test(н)) return { ok: false, сбой: 'номер закупки - 19 цифр (44-ФЗ) или 11 (223-ФЗ)' };
  const настройки = настройкиКлиента(клиент);
  if (!настройки) return { ok: false, сбой: 'настроек клиента нет' };
  const ссылка = адресКарточки(н);
  const р = await (опции.собрать || собратьСмету)({ ссылка }, {
    ...общиеНастройки(), ...настройки, anthropicKey: '', proxyUrl: '', искатьПоставщиков: false, сканыМоделью: false
  }).catch((e) => ({ ok: false, сбой: e.message }));
  if (!р.ok) return { ok: false, номер: н, сбой: р.сбой || 'расчёт не собрался' };

  const сводка = р.сводкаРазбора || {};
  const строки = (р.estimate && р.estimate.rows) || [];
  const сЗакупочной = строки.filter((r) => r.priceForCalc !== null && r.priceForCalc !== undefined && r.basis !== 'верхняя граница цены').length;
  const пр = н.length === 19 ? await протокол(ссылка, опции.взять).catch((e) => ({ ok: false, причина: e.message }))
    : { ok: false, причина: 'цену победы 223-ФЗ портал не публикует в разборчивом виде - сравнение только с начальной ценой' };

  let приЦенеПобеды = null;
  if (пр.ok && typeof пр.снижение === 'number' && р.estimate) {
    приЦенеПобеды = посчитатьИтоги({ tender: р.tender, estimate: р.estimate, logistics: {},
      economics: { ...(настройки.economics || {}), expectedDiscount: пр.снижение / 100 } });
  }
  const всеПоВашимЦенам = строки.length > 0 && сЗакупочной === строки.length;
  let вывод;
  if (!строки.length) вывод = 'позиции закупки не разобраны - посчитать нельзя';
  else if (!всеПоВашимЦенам) вывод = `ваши закупочные цены есть для ${сЗакупочной} из ${строки.length} позиций - вывод о прибыли не делается: по ценам заказчика он ничего не значит`;
  else if (!приЦенеПобеды) вывод = `по вашим ценам безубыточная цена ${Math.round(р.итоги.безубыточность)} ₽; цены победы нет: ${пр.причина}`;
  else if (приЦенеПобеды.прибыль >= 0) вывод = `при цене победы вы заработали бы ${Math.round(приЦенеПобеды.прибыль)} ₽ (${приЦенеПобеды.маржа}% от цены)`;
  else вывод = `при цене победы контракт был бы убыточен для вас: ${Math.round(приЦенеПобеды.прибыль)} ₽ - выигрывать по такой цене не стоило`;

  return {
    ok: true, номер: н, объект: (р.tender && р.tender.object) || '', ссылка,
    нмцк: р.tender && р.tender.price, позиций: строки.length, сЗакупочной,
    протокол: пр.ok ? { ценаПобеды: пр.ценаПобеды, снижение: пр.снижение, участников: пр.участников ?? null, единственнаяЗаявка: !!пр.единственнаяЗаявка } : { причина: пр.причина },
    закупка: р.итоги && р.итоги.закупкаИзвестна ? р.итоги.закупка : null,
    безубыточность: р.итоги ? р.итоги.безубыточность : null,
    прибыль: приЦенеПобеды && всеПоВашимЦенам ? приЦенеПобеды.прибыль : null,
    маржа: приЦенеПобеды && всеПоВашимЦенам ? приЦенеПобеды.маржа : null,
    условия: сводка.условия || null,
    обеспечениеГарантии: р.итоги ? р.итоги.обеспечениеГарантии : null,
    вывод
  };
}

module.exports = { разборПрошлого, адресКарточки };
