/**
 * Поиск поставщиков через Яндекс: сеть и учёт расхода. Логика и проверки -
 * `src/yandex-search.js`.
 *
 * Запуск сравнения на одной закупке (позиции из следа расчёта):
 *   docker compose exec -T app node app/yandex-run.js --number 0373100010426000011 [--model deepseek-v4.1-flash]
 *
 * Сайты поставщиков: пауза 1 с между страницами, не больше СТРАНИЦ_НА_ПОЗИЦИЮ,
 * отказ сайта (403/429/503) - страница пропускается, защиту не обходим.
 */
const fs = require('fs');
const path = require('path');
const { взять } = require('./http');
const { раскодировать, текстИзHtml } = require('./verify-suppliers');
const { ценыИзРазметки } = require('../src/verify');
const Я = require('../src/yandex-search');

const ПОИСК = 'https://searchapi.api.cloud.yandex.net/v2/web/search';
const МОДЕЛЬ = 'https://llm.api.cloud.yandex.net/v1/chat/completions';
const МОДЕЛЬ_КИМИ = 'https://api.moonshot.ai/v1/chat/completions';
const СТРАНИЦ_НА_ПОЗИЦИЮ = 4;
const ДОСТАТОЧНО_ЦЕН = 3;
const спать = (мс) => new Promise((ok) => setTimeout(ok, мс));

function настройкиЯндекса(н = {}) {
  const провайдер = н.провайдер || 'yandex';
  return {
    провайдер,
    ключ: провайдер === 'kimi' ? (н.kimiKey || process.env.KIMI_API_KEY || '') : (н.yandexKey || process.env.YANDEX_API_KEY || ''),
    папка: н.yandexFolder || process.env.YANDEX_FOLDER_ID || '',
    // Alice AI Flash: на эталоне 0373100010426000011 (1 позиция, 31.10.2026)
    // 5 цен за 1,45 ₽ против 4 цен за 8,63 ₽ у DeepSeek V4.1 и 2 за 7,36 ₽ у Qwen.
    модель: провайдер === 'kimi'
      ? (н.kimiModel || process.env.KIMI_MODEL || 'kimi-k2.8-preview')
      : (н.yandexModel || process.env.YANDEX_MODEL || 'aliceai-llm-flash')
  };
}

// Search API разрешает 1 запрос в секунду (живой расчёт 12.11.2026 упёрся
// в 429: «allowed 1 requests», позиция осталась без поиска). Держим паузу
// между запросами и повторяем только 429 - ключ или счёт (401/403) без
// повторов останавливают поиск, как раньше.
let прошлыйПоиск = 0;

async function искать(текст, я, расход) {
  const ждать = 1150 - (Date.now() - прошлыйПоиск);
  if (ждать > 0) await спать(ждать);
  let r;
  for (let попытка = 1; ; попытка++) {
    прошлыйПоиск = Date.now();
    r = await взять(ПОИСК, {
      метод: 'POST', мс: 30000,
      заголовки: { Authorization: `Api-Key ${я.ключ}`, 'Content-Type': 'application/json' },
      тело: JSON.stringify(Я.телоПоиска(текст, я.папка))
    });
    расход.поисков += 1;
    if (r.ok || r.код !== 429 || попытка >= 3) break;
    await спать(2000 * попытка);
  }
  if (!r.ok) return { ссылки: [], ошибка: `поиск Яндекса: код ${r.код} ${String(r.тело || '').slice(0, 200)}` };
  return Я.ссылкиИзВыдачи(r.тело.toString('utf8'));
}

async function страница(url) {
  let r;
  try { r = await взять(url, { мс: 25000 }); } catch (e) { return { ok: false, почему: e.message }; }
  if (!r.ok) return { ok: false, почему: `код ${r.код}` };
  const тип = (r.заголовки || {})['content-type'] || '';
  if (тип && !/html|xml|text/i.test(тип)) return { ok: false, почему: `не страница (${тип.slice(0, 40)})` };
  const р = раскодировать(r.тело, тип);
  if (!р.ok) return { ok: false, почему: р.почему };
  return { ok: true, html: р.текст, текст: текстИзHtml(р.текст), разметка: ценыИзРазметки(р.текст) };
}

function телоДляПровайдера(тело, я) {
  if (я.провайдер !== 'kimi') return тело;
  const { max_tokens, ...остальное } = тело;
  return {
    ...остальное,
    model: я.модель,
    max_completion_tokens: max_tokens || 3000,
    reasoning_effort: 'low',
    response_format: { type: 'json_object' }
  };
}

async function спроситьМодель(тело, я, расход) {
  const кими = я.провайдер === 'kimi';
  const r = await взять(кими ? МОДЕЛЬ_КИМИ : МОДЕЛЬ, {
    метод: 'POST', мс: 120000,
    заголовки: { Authorization: `${кими ? 'Bearer' : 'Api-Key'} ${я.ключ}`, 'Content-Type': 'application/json' },
    тело: JSON.stringify(телоДляПровайдера(тело, я))
  });
  if (!r.ok) return { ok: false, почему: `модель: код ${r.код} ${String(r.тело || '').slice(0, 200)}` };
  try {
    const о = JSON.parse(r.тело.toString('utf8'));
    const u = о.usage || {};
    расход.вход += Number(u.prompt_tokens || 0);
    расход.выход += Number(u.completion_tokens || 0);
    расход.запросовМодели += 1;
    const м = (о.choices && о.choices[0] && о.choices[0].message) || {};
    return { ok: true, текст: м.content || '' };
  } catch (e) { return { ok: false, почему: 'ответ модели не разобран: ' + e.message }; }
}

/**
 * Лимиты чужих сайтов при конвейере позиций (решение 13.11.2026: расчёт
 * должен уложиться в 3 минуты, скорость НЕ достигается давкой на сайты).
 * Общая пауза между любыми страницами и отдельно не чаще 1 запроса в секунду
 * к одному домену — вместо прежней фиксированной паузы внутри одной позиции.
 */
let последняяСтраница = 0;
const доменВремя = new Map();
async function паузаПередСтраницей(домен) {
  const кДомену = 1000 - (Date.now() - (доменВремя.get(домен) || 0));
  const общая = 500 - (Date.now() - последняяСтраница);
  const ждать = Math.max(кДомену, общая, 0);
  if (ждать > 0) await спать(ждать);
  const сейчас = Date.now();
  последняяСтраница = сейчас;
  доменВремя.set(домен, сейчас);
}

/**
 * Поставщики одной позиции. Возвращает их в виде `parseSupplierResponse`,
 * чтобы дальше шли общие проверки расчёта.
 */
async function поставщикиПозиции(позиция, я, журнал, расход) {
  const найдено = [];
  const просмотрено = new Set();
  const счёт = { разметка: 0, модель: 0, неПоТеме: 0, отказСайта: 0, безТовара: 0 };
  for (const запрос of Я.запросыПоиска(позиция)) {
    const { ссылки, ошибка } = await искать(запрос, я, расход);
    if (ошибка) { журнал.push(`   ${ошибка}`); if (/код 40[13]/.test(ошибка)) return { найдено, стоп: ошибка }; continue; }
    for (const с of ссылки) {
      if (просмотрено.has(с.домен) || просмотрено.size >= СТРАНИЦ_НА_ПОЗИЦИЮ) continue;
      просмотрено.add(с.домен);
      await паузаПередСтраницей(с.домен);
      const стр = await страница(с.url);
      if (!стр.ok) { счёт.отказСайта++; continue; }
      const р = Я.изРазметки(позиция, стр.html, с.url);
      if (р && р.совпало) { найдено.push(р.поставщик); счёт.разметка++; continue; }
      if (!Я.страницаПоТеме(позиция, стр.текст)) { счёт.неПоТеме++; continue; }
      const модель = я.провайдер === 'kimi' ? я.модель : `gpt://${я.папка}/${я.модель}/latest`;
      const о = await спроситьМодель(Я.запросКМодели(позиция, стр.текст, с.url, модель, стр.разметка), я, расход);
      if (!о.ok) { журнал.push(`   ${о.почему}`); if (/код 40[13]/.test(о.почему)) return { найдено, стоп: о.почему }; continue; }
      const п = Я.поставщикИзОтвета(о.текст, позиция, с.url, стр.текст, стр.разметка);
      if (п.поставщик) { найдено.push(п.поставщик); счёт.модель++; } else счёт.безТовара++;
    }
    if (найдено.filter((п) => п.price !== null).length >= ДОСТАТОЧНО_ЦЕН) break;
  }
  журнал.push(`   страниц ${просмотрено.size}: цена из разметки ${счёт.разметка}, прочитано моделью ${счёт.модель}, `
    + `без нужного товара ${счёт.безТовара}, не по теме ${счёт.неПоТеме}, сайт не отдал ${счёт.отказСайта}`);
  return { найдено };
}

function стоимость(расход, модель) {
  const ц = Я.ЦЕНЫ_МОДЕЛЕЙ[модель] || { вход: 0.5, выход: 1.2 };
  const рублей = расход.поисков * Я.ЦЕНА_ПОИСКА + (расход.вход * ц.вход + расход.выход * ц.выход) / 1000;
  return Math.round(рублей * 100) / 100;
}

/** Все позиции: Map(наименование -> поставщики), как у поиска моделью.
 * Позиции идут конвейером втроём (решение владельца 13.11.2026: расчёт
 * не дольше 3 минут): пока одна позиция ждёт ответ модели, другие читают
 * страницы. Лимиты выше соблюдаются глобально и потокобезопасны — Node
 * выполняет JS по одному, переключение только на await.
 */
async function найтиПоставщиковЯндексом(позиции, настройки, журнал) {
  const я = настройкиЯндекса(настройки);
  const расход = { поисков: 0, вход: 0, выход: 0, запросовМодели: 0 };
  const результат = new Map();
  const issues = [];
  if (!я.ключ || !я.папка) {
    журнал.push('поиск через Яндекс пропущен: не задан YANDEX_API_KEY или YANDEX_FOLDER_ID');
    return { поЗаказчикам: результат, issues: ['поиск поставщиков не выполнялся - нет ключа'], расход };
  }
  const t0 = Date.now();
  const очередь = позиции.slice();
  let отказ = null;
  async function рабочий() {
    for (;;) {
      const позиция = очередь.shift();
      if (!позиция || отказ) return;
      журнал.push(`поиск через Яндекс: «${позиция.name}»`);
      let найдено = [];
      let стоп = null;
      try {
        ({ найдено, стоп } = await поставщикиПозиции(позиция, я, журнал, расход));
      } catch (e) {
        // Сетевая ошибка одной позиции не должна ронять весь расчёт.
        журнал.push(`   позиция «${позиция.name}»: сбой поиска - ${String(e.message || e).slice(0, 160)}`);
      }
      результат.set(позиция.name, найдено);
      журнал.push(`поставщики для «${позиция.name}»: найдено ${найдено.length}, с подтверждённой ценой ${найдено.filter((п) => п.price !== null).length}`);
      if (стоп) отказ = стоп;
      if (отказ) return;
    }
  }
  const рабочие = [];
  for (let i = 0; i < Math.min(3, позиции.length); i++) рабочие.push(рабочий());
  await Promise.all(рабочие);
  // Стоп по ключу/счёту (401/403) всплывает из позиций: повторный прогон
  // оставшихся позиций дал бы тот же отказ, поэтому честное замечание.
  for (const позиция of позиции) {
    if (!результат.has(позиция.name)) {
      результат.set(позиция.name, []);
      issues.push('поиск цен у поставщиков не завершён по техническим причинам - цены взяты из обоснования НМЦК, расчёт повторим');
      журнал.push(`ОТКАЗ YANDEX CLOUD ПО КЛЮЧУ ИЛИ СЧЁТУ: ${отказ || 'позиция не обработана'}`);
      break;
    }
  }
  журнал.push(`поиск поставщиков занял ${Math.round((Date.now() - t0) / 1000)} с`);
  if (я.провайдер === 'kimi') {
    // Тариф K2.8 Preview не опубликован на странице публичных цен: не выдумываем,
    // считаем только поиск Яндекса. Для известных моделей цены - здесь.
    расход.рублей = Math.round(расход.поисков * Я.ЦЕНА_ПОИСКА * 100) / 100;
    const тариф = { 'kimi-k2.6': [0.95, 4], 'kimi-k3.1-pro': [2, 10] }[я.модель];
    if (тариф) расход.долларов = Math.round((расход.вход * тариф[0] + расход.выход * тариф[1]) / 10000) / 100;
    else журнал.push(`   тариф ${я.модель} не найден - расход модели не посчитан, поиск учтён в рублях`);
  } else {
    расход.рублей = стоимость(расход, я.модель);
  }
  журнал.push(`расход ${я.провайдер}: поисков ${расход.поисков}, запросов к модели ${расход.запросовМодели} (${я.модель}), `
    + `токенов ${расход.вход} + ${расход.выход}, ≈ ${расход.рублей} ₽`
    + (расход.долларов !== undefined ? ` + $${расход.долларов}` : ''));
  return { поЗаказчикам: результат, issues, расход };
}

/**
 * Поставщики ниши без модели (app/niche-suppliers.js): по запросу на каждую
 * из первых `позицийНаГруппу` позиций группы, отбор сайтов - в
 * src/yandex-search.js поставщикиНишиИзВыдач. Отказ по ключу или счёту
 * (401/403) - остановка.
 *
 * @param {Array<{вид: string, позиции: object[]}>} группы
 * @returns {Promise<{поставщики: object[], стоп: string|null, расход: object}>}
 */
async function поставщикиНишиЯндексом(группы, настройки, журнал, опции = {}) {
  const я = настройкиЯндекса(настройки);
  const расход = { поисков: 0, вход: 0, выход: 0, запросовМодели: 0 };
  if (!я.ключ || !я.папка) return { поставщики: [], стоп: 'не задан YANDEX_API_KEY или YANDEX_FOLDER_ID', расход };
  const искатьФ = опции.искать || искать;
  const позицийНаГруппу = Number(опции.позицийНаГруппу) || 12;
  const поставщики = [];
  let стоп = null;
  for (const г of группы) {
    const выдачи = [];
    for (const позиция of г.позиции.slice(0, позицийНаГруппу)) {
      const запрос = Я.запросНиши(позиция);
      if (!запрос) continue;
      const { ссылки, ошибка } = await искатьФ(запрос, я, расход);
      if (ошибка) {
        журнал.push(`   ${ошибка}`);
        if (/код 40[13]/.test(ошибка)) { стоп = ошибка; break; }
        continue;
      }
      выдачи.push({ позиция, ссылки });
    }
    const найдены = Я.поставщикиНишиИзВыдач(выдачи, г.вид);
    журнал.push(`Яндекс, ${г.вид === 'работа' ? 'подрядчики' : 'поставщики'} ниши: запросов ${выдачи.length}, сайтов по 2+ позициям ${найдены.length}`);
    for (const п of найдены) if (!поставщики.some((x) => x.домен === п.домен)) поставщики.push(п);
    if (стоп) break;
  }
  расход.рублей = стоимость(расход, я.модель);
  журнал.push(`расход Яндекса на нишу: поисков ${расход.поисков}, ≈ ${расход.рублей} ₽`);
  return { поставщики, стоп, расход };
}

// --- сравнение на закупке из командной строки ---------------------------
function ключ(имя, поУмолчанию = null) {
  const i = process.argv.indexOf('--' + имя);
  return i !== -1 && process.argv[i + 1] ? process.argv[i + 1] : поУмолчанию;
}

async function main() {
  const номер = ключ('number');
  const каталог = process.env.STATE_DIR || '/data/state';
  const файл = fs.readdirSync(каталог).filter((f) => /^verify-.+\.json$/.test(f) && (!номер || f.includes(номер)))
    .map((f) => path.join(каталог, f)).sort((a, b) => fs.statSync(b).mtimeMs - fs.statSync(a).mtimeMs)[0];
  if (!файл) { console.log(`нет следа расчёта ${номер || ''} (verify-*.json)`); process.exit(1); }
  const след = JSON.parse(fs.readFileSync(файл, 'utf8'));
  const тз = (след.тз && след.тз.поПозициям) || {};
  const текстТЗ = (v) => (typeof v === 'string' ? v : (v && (v.текст || v.text)) || '');
  const позиции = (след.позиции || []).map((п) => {
    const name = п.наименование || п.name;
    return { name, quantity: п.количество || п.quantity, unit: п.единица || п.unit, spec: п.spec || текстТЗ(тз[name]) };
  }).filter((п) => п.name);
  // --priced: сначала позиции, по которым прежний поиск дал цены, - чтобы было с чем сравнить.
  const сЦеной = new Set((след.поставщики || []).filter((п) => п.price > 0).map((п) => п.позиция));
  if (process.argv.includes('--priced')) позиции.sort((a, b) => сЦеной.has(b.name) - сЦеной.has(a.name));
  позиции.splice(Number(ключ('limit', 50)));
  const провайдер = ключ('provider', 'yandex');
  console.log(`закупка ${след.номер}, позиций ${позиции.length}, провайдер ${провайдер}, модель ${настройкиЯндекса({ провайдер, yandexModel: ключ('model') }).модель}`);
  const журнал = [];
  const t = Date.now();
  const р = await найтиПоставщиковЯндексом(позиции, { провайдер, yandexModel: ключ('model') }, журнал);
  for (const с of журнал) console.log(с);
  for (const [имя, сп] of р.поЗаказчикам) {
    console.log(`\n=== ${имя}`);
    for (const п of сп) console.log(`  ${п.price !== null ? п.price + ' ₽' : 'без цены'}${п.unit ? ' / ' + п.unit : ''} - ${п.name} ${п.url}${п.изРазметки ? ' [разметка]' : ''}\n     ${String(п.priceNote || '').slice(0, 160)}`);
    // Для сравнения - что нашёл прежний поиск (Claude) по той же позиции.
    const прежние = (след.поставщики || []).filter((п) => п.позиция === имя);
    if (прежние.length) console.log(`  прежний поиск: ${прежние.length} поставщиков, цены ${прежние.map((п) => п.price).filter((x) => x !== null && x !== undefined).join(', ') || 'нет'}`);
  }
  console.log(`\nвремя ${Math.round((Date.now() - t) / 1000)} с`);
  if (р.issues.length) console.log('замечания: ' + р.issues.join('; '));
}

if (require.main === module) main().catch((e) => { console.error(e.stack); process.exit(1); });

