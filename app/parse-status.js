/**
 * Состояние фонового разбора документации. Без ключей на портал не ходит.
 *
 *   docker compose exec -T app node app/parse-status.js --client kargin
 *   … --number 0372200018326000028      подробности одного тендера
 *   … --retry-bad                        заново разобрать неудачные и показать почему
 *
 * --retry-bad ходит на портал (по одному тендеру, пауза 40 с) и идёт долго —
 * запускать в фоне с выводом в файл:
 *   docker compose exec -d app sh -c "node app/parse-status.js --client kargin --retry-bad > /data/state/retry.log 2>&1"
 *   docker compose exec -T app cat /data/state/retry.log
 */
const { состояние, поставитьВОчередь, обработатьОчередь, файлРазборов } = require('./parse-queue');
const { настройкиКлиента, общиеНастройки } = require('./settings');
const { строкаВерсии } = require('./fingerprint');
const fs = require('fs');

function ключ(имя, поУмолчанию = '') {
  const i = process.argv.indexOf('--' + имя);
  return i !== -1 && process.argv[i + 1] ? process.argv[i + 1] : поУмолчанию;
}
const есть = (имя) => process.argv.includes('--' + имя);

/** Неудача: позиций нет либо разбор негоден не по причине «цена за единицу». */
const неудача = (р) => (!р.ок && !р.отменена && !р.пропущен) || (р.ок && (р.позиций === 0 || (!р.годен && !р.ценаЗаЕдиницу)));

function подробно(номер, р) {
  console.log(`\n--- ${номер} ${String((р.тендер && р.тендер.object) || '').slice(0, 70)}`);
  if (!р.ок) { console.log(`   сбой: ${р.сбой}`); return; }
  // «позиций 0, годен» читалось как успех — при нуле годности нет.
  const оценка = !р.позиций ? 'позиции не найдены'
    : р.годен ? 'годен' : 'НЕГОДЕН: ' + р.причиныНегодности.join('; ');
  console.log(`   позиций ${р.позиций}, ${оценка}`);
  for (const ч of р.чтение || []) console.log(`   файл «${ч.имя}» (${ч.вид || '—'}): ${ч.итог}`);
  for (const о of р.отброшено || []) console.log(`   не взят отбором: ${о}`);
  for (const п of р.проблемы || []) console.log(`   замечание: ${п}`);
  for (const ф of р.разборФайлов || []) {
    console.log(`   разбор «${ф.имя}»: с ценами — ${ф.сЦенами}; без цен — ${ф.безЦен}`);
    if (ф.образец) console.log(`      образец: ${ф.образец}`);
  }
}

function строка(номер, р) {
  const объект = String((р.тендер && р.тендер.object) || '').slice(0, 55);
  if (р.отменена) return `○ ${номер} ${объект} — закупка отменена заказчиком`;
  if (р.пропущен) return `○ ${номер} ${объект} — не разбиралась: ${р.сбой}`;
  if (!р.ок) return `✗ ${номер} ${объект} — ${р.сбой}`;
  if (р.позиций === 0) return `✗ ${номер} ${объект} — позиции не найдены`;
  const части = [`позиций ${р.позиций}`, р.естьТЗ ? 'ТЗ есть' : 'ТЗ нет'];
  if (р.сканов) части.push(`сканов ${р.сканов}`);
  if (р.ценаЗаЕдиницу) части.push('цена за единицу');
  if (!р.годен && !р.ценаЗаЕдиницу) части.push('разбор негоден: ' + (р.причиныНегодности[0] || ''));
  if (р.фильтрПоТЗ && !р.фильтрПоТЗ.прошёл) части.push('ОТСЕЯН: ' + р.фильтрПоТЗ.причины[0]);
  const знак = р.ценаЗаЕдиницу ? '·' : р.годен ? '✓' : '!';
  return `${знак} ${номер} ${объект} — ${части.join(', ')}`;
}

async function main() {
  const ид = ключ('client', 'kargin');
  console.log(строкаВерсии());

  if (есть('retry-bad')) {
    const с = состояние(ид);
    // `--retry-bad --number N` — заново только эту закупку, даже если она
    // уже разобрана: нужно после правки разбора, чтобы проверить её саму.
    const один = ключ('number');
    const плохие = один
      ? Object.entries(с.разборы).filter(([н]) => н === один)
      : Object.entries(с.разборы).filter(([, р]) => неудача(р));
    console.log(`заново разбираю неудачные: ${плохие.length}`);
    const разборы = { ...с.разборы };
    for (const [номер] of плохие) delete разборы[номер];
    fs.writeFileSync(файлРазборов(ид), JSON.stringify(разборы), 'utf8');
    поставитьВОчередь(ид, плохие.map(([, р]) => р.тендер));
    const клиент = { ...(настройкиКлиента(ид) || {}), ид };
    // Только поставленные заново: прочая очередь ждёт своего часа. Номер,
    // который ещё стоит в очереди и не разбирался, берётся оттуда.
    const только = new Set(плохие.map(([н]) => н));
    if (один && (с.очередь || []).some((x) => x.number === один)) только.add(один);
    const итог = await обработатьОчередь(ид, клиент, общиеНастройки(), { только });
    console.log(`разбор: ${JSON.stringify(итог)}`);
    const после = состояние(ид).разборы;
    for (const номер of только) if (после[номер]) подробно(номер, после[номер]);
    return;
  }

  const с = состояние(ид);
  const номер = ключ('number');
  if (номер) {
    if (!с.разборы[номер]) { console.log(`разбора ${номер} нет`); return; }
    подробно(номер, с.разборы[номер]);
    return;
  }

  const разборы = Object.entries(с.разборы).sort((a, b) => String(b[1].когда).localeCompare(String(a[1].когда)));
  const заЕд = разборы.filter(([, р]) => р.ценаЗаЕдиницу).length;
  const отменено = разборы.filter(([, р]) => р.отменена).length;
  const плохих = разборы.filter(([, р]) => неудача(р)).length;
  const годных = разборы.length - плохих - заЕд - отменено;
  const отсеяно = разборы.filter(([, р]) => р.фильтрПоТЗ && !р.фильтрПоТЗ.прошёл).length;
  console.log(`клиент ${ид}: ждут разбора ${с.очередь.length}, разобрано ${разборы.length}`);
  console.log(`позиции разобраны: ${годных} · по цене за единицу: ${заЕд} · отменены: ${отменено} · неудач: ${плохих} · `
    + `отсеяно стоп-словами по ТЗ: ${отсеяно}`);
  console.log('');
  // `--rows 0` — только итог. `|| 200` превращал ноль в двести.
  const предел = Number.isFinite(Number(ключ('rows', '200'))) ? Number(ключ('rows', '200')) : 200;
  for (const [н, р] of разборы.slice(0, предел)) console.log(строка(н, р));
}

main().catch((e) => { console.log('сбой: ' + e.message); process.exit(1); });
