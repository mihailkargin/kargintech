/**
 * Проба сметы из командной строки — одна команда вместо длинного node -e.
 *
 * ЗАЧЕМ. Порт приложения наружу не опубликован (это правильно: снаружи только
 * HTTPS через Caddy), поэтому проверить расчёт запросом с ноутбука нельзя.
 * Раньше проверка выглядела как многострочный node -e, вбиваемый руками в
 * окно сервера, — такую команду легко испортить при копировании, и владелец
 * тратил круг на опечатку, а не на суть.
 *
 * Запуск на сервере — без всяких аргументов:
 *   docker compose exec app node app/probe.js
 *
 * Тогда проба сама найдёт на портале свежую закупку по слову «бумага» и
 * посчитает её. Это важно именно для владельца: у него на ноутбуке включён
 * VPN, из-за которого портал недоступен, то есть ссылку скопировать негде.
 * У сервера российский адрес, и портал ему отвечает.
 *
 * Своё слово или своя закупка:
 *   docker compose exec app node app/probe.js --слово "кабель"
 *   docker compose exec app node app/probe.js "<ссылка на карточку закупки>"
 *
 * Имя файла латиницей намеренно. Архив с комплектом собирается на Windows и
 * распаковывается на Linux, и русские имена файлов на этом переходе иногда
 * портятся — получается «файл не найден» там, где файл лежит на месте.
 *
 * По умолчанию поставщики НЕ ищутся — значит, прогон бесплатный. Платный
 * поиск включается ключом --поставщики, и тогда в выводе появится настоящая
 * закупочная цена вместо потолка из обоснования НМЦК.
 *
 * Выводится ровно то, что увидит клиент в Telegram: та же подпись, та же
 * функция подписьДляЧата. Файл Excel не пишется — его собирает сервер.
 */
const path = require('path');
const { собратьСмету } = require('./estimate-run');
const { общиеНастройки } = require('./settings');
const { адресПоиска } = require('./search-run');
const { parseSearchPage } = require(path.join(__dirname, '..', 'src', 'parser'));
const { взятьТекст } = require('./http');
const { строкаВерсии } = require('./fingerprint');

const аргументы = process.argv.slice(2);

// У КАЖДОГО КЛЮЧА ЕСТЬ ЛАТИНСКОЕ ИМЯ, И ПОЛЬЗОВАТЬСЯ НАДО ИМ.
//
// Команду набирают на ноутбуке под Windows, а выполняется она на сервере
// под Linux. На этом переходе кириллица уже портилась в проекте: файл,
// названный `проба.js`, приехал как `╨┐╤А╨╛╨▒╨░.js`. С ключом командной
// строки было бы хуже, чем с именем файла: испорченный `--поставщики`
// просто не совпадёт, поиск поставщиков молча пропустится, и вывод
// «поставщики не искались» выглядел бы как настройка, а не как поломка.
//
// Кириллические имена оставлены — ими удобно пользоваться на сервере
// напрямую, — но в памятках и командах пишутся латинские.
const искатьПоставщиков = аргументы.includes('--suppliers') || аргументы.includes('--поставщики');
const явнаяСсылка = аргументы.find((a) => a.indexOf('http') === 0);

const где = (() => {
  const л = аргументы.indexOf('--word');
  return л >= 0 ? л : аргументы.indexOf('--слово');
})();
const слово = где >= 0 && аргументы[где + 1] ? аргументы[где + 1] : 'бумага';

/**
 * Найти на портале первую закупку по слову — чтобы пробу можно было запустить
 * вообще без аргументов.
 *
 * Почему не по реестровому номеру: поиск по номеру на портале не работает,
 * проверено 03.10.2026. Поэтому берётся обычный поиск по слову, и из выдачи
 * берётся первая карточка, у которой есть ссылка.
 */
async function найтиЛюбуюЗакупку() {
  const адрес = адресПоиска(слово, {});
  console.log(`ищу закупку по слову «${слово}»`);

  const ответ = await взятьТекст(адрес, 60000);
  if (!ответ.ok) {
    console.log('портал не ответил: ' + ответ.ошибка);
    console.log('');
    console.log('Это проверяется отдельно: bash deploy/check-portal.sh');
    return null;
  }

  // Текст ответа лежит в поле «тело», а не «текст». Первая версия пробы читала
  // «текст», получала undefined и печатала «карточек: 0» — то есть выглядела
  // как поломка портала. Отсюда проверка длины: страница поиска портала меньше
  // 2000 знаков не бывает, и короткий ответ надо называть коротким ответом,
  // а не пустой выдачей. Тот же порог стоит в search-run.js.
  const страница = String(ответ.тело || '');
  console.log(`портал ответил: код ${ответ.код}, ${страница.length} знаков`);

  if (страница.length < 2000) {
    console.log('ответ слишком короткий для страницы поиска — это не пустая выдача, а сбой');
    console.log('первые 300 знаков ответа:');
    console.log(страница.slice(0, 300) || '(пусто)');
    return null;
  }

  const карточки = parseSearchPage(страница) || [];
  console.log(`в выдаче карточек: ${карточки.length}`);

  if (карточки.length === 0) {
    // Пустая выдача — законный исход (например, редкое слово). Отличить её от
    // сломанной разметки можно по числу блоков карточек в самой странице.
    //
    // Считаем, а не просто ищем: на настоящей пустой выдаче портала признак
    // search-registry-entry встречается ОДИН раз (он есть в шаблоне страницы).
    // Проверено на fixtures/search-pustaya-vydacha-2026-09-19.html — там 1,
    // а на выдаче с десятью карточками 11. Поиск вхождения вместо подсчёта
    // объявил бы пустую выдачу сломанной разметкой.
    const блоков = (страница.match(/search-registry-entry/g) || []).length;
    console.log(блоков > 1
      ? `в странице ${блоков} блоков карточек, но парсер их не разобрал — разметка портала изменилась`
      : `по слову «${слово}» портал ничего не нашёл — попробуйте другое слово: --слово "кабель"`);
    return null;
  }

  // Нужны карточки со ссылкой: без неё документацию не открыть.
  const годные = карточки.filter((к) => к.url);
  if (годные.length === 0) {
    console.log('карточки есть, но ни у одной нет ссылки — разметка портала изменилась');
    return [];
  }

  return годные;
}

(async () => {
  // ПЕРВОЙ СТРОКОЙ — КАКАЯ ВЕРСИЯ КОДА РАБОТАЕТ.
  // Две выкатки подряд выглядели успешными и не были, и оба раза это
  // определялось по косвенным признакам. Отпечаток превращает вопрос
  // «выкатилось ли» в сравнение двух чисел.
  console.log(строкаВерсии());

  // НАСТРОЙКИ БЕРУТСЯ ИЗ ОКРУЖЕНИЯ, А НЕ СОЧИНЯЮТСЯ ЗДЕСЬ.
  //
  // Раньше сюда уходил один флаг, и ключ модели с адресом посредника до
  // расчёта не доезжали вовсе: при верно прописанном ключе проба печатала
  // «поиск поставщиков пропущен: ключ Anthropic не задан», и причину искали
  // бы в ключе, в консоли Anthropic, в посреднике — где угодно, кроме пробы.
  const общие = общиеНастройки();

  // Состояние условий печатается ДО расчёта: иначе «поставщиков не нашлось»
  // и «поиск не выполнялся» выглядят в выводе одинаково. Сам ключ не
  // печатается никогда — только факт, что он есть.
  if (искатьПоставщиков) {
    // Печатается состояние ДЕЙСТВУЮЩЕГО пути (Яндекс, владелец 13.11:
    // «поиск поставщиков — только Яндекс»). Старые строки про ключ Anthropic
    // и посредника здесь врали: поиск шёл, а проба печатала «будет пропущен».
    const ключЯндекса = process.env.YANDEX_API_KEY || общие.yandexKey || '';
    const папкаЯндекса = process.env.YANDEX_FOLDER_ID || '';
    console.log(`ключ Яндекса: ${ключЯндекса ? 'задан' : 'НЕ ЗАДАН'}, `
      + `папка: ${папкаЯндекса ? 'задана' : 'НЕ ЗАДАНА'}`);
    if (!ключЯндекса || !папкаЯндекса) {
      console.log('   поиск поставщиков будет пропущен — нужны YANDEX_API_KEY и YANDEX_FOLDER_ID в deploy/.env');
    }
    console.log('');
  }

  // ПЕРЕБОР ЗАКУПОК, А НЕ ПЕРВАЯ ПОПАВШАЯСЯ.
  //
  // Проба брала первую карточку выдачи. На прогоне 07.10.2026 это оказалась
  // закупка, в документах которой таблицы позиций не было вовсе: расчёт
  // прошёл, но считать было нечего, а повторный запуск взял бы ту же самую —
  // порядок выдачи у портала устойчивый. То есть проба зациклилась бы на
  // неудачном примере, и выглядело бы это как поломка разбора.
  //
  // Теперь при неудаче берётся следующая закупка. Предел жёсткий: каждая
  // попытка — это десяток обращений к порталу, а частить к нему нельзя,
  // 05.10.2026 он уже отвечал отказом по адресу сервера.
    // Число поисков на позицию можно задать ключом — чтобы сравнить расход и
  // качество между вариантами на ОДНОЙ И ТОЙ ЖЕ закупке. Сравнение на разных
  // закупках ничего не доказывает: товары разные, выдача разная.
  const гдеС = аргументы.indexOf('--searches');
  const поисков = гдеС >= 0 ? Number(аргументы[гдеС + 1]) : null;

  const гдеПоз = аргументы.indexOf('--positions');
  const позицийМакс = гдеПоз >= 0 ? Number(аргументы[гдеПоз + 1]) : null;

  const гдеП = аргументы.indexOf('--tries');
  const попыток = Math.min(
    Math.max(1, Number(гдеП >= 0 ? аргументы[гдеП + 1] : 3) || 3),
    5
  );

  const кандидаты = явнаяСсылка
    ? [{ url: явнаяСсылка }]
    : await найтиЛюбуюЗакупку();

  if (!кандидаты || кандидаты.length === 0) {
    console.log('');
    console.log('--- НЕЧЕГО СЧИТАТЬ ---');
    console.log('Можно задать закупку руками:');
    console.log('  docker compose exec app node app/probe.js "https://zakupki.gov.ru/epz/order/notice/..."');
    process.exit(1);
  }

  let итог = null;
  const пропущены = [];

  for (let i = 0; i < Math.min(попыток, кандидаты.length); i++) {
    const к = кандидаты[i];
    // При заданной вручную ссылке карточки нет, и печатать «номер не распознан —
    // объект не указан» значит показывать поломку разбора там, где разбирать
    // было нечего.
    if (к.number || к.object) {
      console.log(`беру: ${к.number || 'номер не распознан'} — ${к.object || 'объект не указан'}`);
    }
    console.log(`считаю: ${к.url}`);
    console.log('');

    итог = await собратьСмету({ ссылка: к.url, адресДокументов: к.docsUrl || '' }, {
      ...общие,
      искатьПоставщиков,
      ...(Number.isFinite(поисков) && поисков > 0 ? { поисковНаПозицию: поисков } : {}),
      ...(Number.isFinite(позицийМакс) && позицийМакс > 0 ? { искатьПоПозициям: позицийМакс } : {})
    });

    // Годной считается закупка, по которой разобрались позиции: только на ней
    // проверяется то, ради чего проба и нужна — цены, поставщики, расход.
    const позиций = (итог.estimate && итог.estimate.rows && итог.estimate.rows.length) || 0;
    if (итог.ok === true && позиций > 0) break;

    const причина = итог.ok !== true
      ? (итог.сбой || 'не получилось')
      : 'позиции не разобрались — считать нечего';
    пропущены.push(`${к.number || к.url}: ${причина}`);

    const остались = Math.min(попыток, кандидаты.length) - i - 1;
    if (остались > 0) {
      console.log('');
      console.log(`--- ${причина}. Беру следующую закупку (осталось попыток: ${остались}) ---`);
      console.log('');
    }
  }

  if (пропущены.length) {
    console.log('');
    console.log('--- ПРОПУЩЕНЫ ПО ПУТИ ---');
    for (const п of пропущены) console.log('  ' + п);
    console.log('');
  }

  // Журнал печатаем всегда, в том числе при успехе: по нему видно, какие
  // файлы разобрались, а какие ушли человеку. Без него «смета неполная»
  // остаётся без объяснения.
  console.log('--- ЖУРНАЛ ПРОГОНА ---');
  for (const строка of (итог.журнал || [])) console.log('  ' + строка);

  if (итог.ok !== true) {
    console.log('');
    console.log('--- НЕ ПОЛУЧИЛОСЬ ---');
    console.log(итог.сбой || 'причина не названа');
    if (итог.подробно) console.log(итог.подробно);
    process.exit(1);
  }

  console.log('');
  console.log('--- ЧТО УВИДИТ КЛИЕНТ В TELEGRAM ---');
  // Теги HTML оставляем как есть: именно их Telegram превращает в жирный
  // шрифт. Если в выводе видны сами теги — это нормально, в чате их не будет.
  console.log(итог.подпись || '(подпись не собрана)');

  // Файл здесь приходит буфером (в base64 его переводит сервер перед
  // отправкой в Telegram), поэтому меряем длину буфера, а не строки.
  if (итог.файл && итог.файл.данные) {
    console.log('');
    console.log(`--- ФАЙЛ: ${итог.файл.имя}, ${Math.round(итог.файл.данные.length / 1024)} КБ ---`);
  }

  if (!искатьПоставщиков) {
    console.log('');
    console.log('ВНИМАНИЕ: поставщики не искались, цены взяты из обоснования НМЦК.');
    console.log('Это ПОТОЛОК рынка, а не закупочная цена. Настоящая прибыль выше.');
  }
})().catch((e) => {
  // Падение с трассировкой — тоже результат: молчаливый выход хуже.
  console.log('--- ПРОГОН УПАЛ ---');
  console.log(e && e.stack ? e.stack : String(e));
  process.exit(1);
});
