/**
 * Запросы к порталу и прочим внешним источникам.
 *
 * ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ КОД ВНУТРИ n8n. До 03.10.2026 эта логика
 * жила в Code-нодах n8n и обошлась в пять находок подряд, каждая из которых
 * обнаруживалась только запуском на сервере: в песочнице нод нет fetch, нет
 * AbortController, нет process, не действует NODE_EXTRA_CA_CERTS. Здесь
 * обычный Node — всё это работает, и проверить можно локально.
 *
 * Функции НИКОГДА не бросают исключение: любой отказ возвращается полем ok.
 * Вызывающий код обязан обработать неудачу явно, а не полагаться на то, что
 * «обычно отвечает». Портал умеет открыть соединение и замолчать.
 */

/** Сколько ждём ответа по умолчанию. */
const СРОК = 60000;

/**
 * КТО МЫ — ЗАГОЛОВОК, БЕЗ КОТОРОГО ПОРТАЛ БОЛЬШЕ НЕ ОТВЕЧАЕТ.
 *
 * ИЗМЕРЕНО НА СЕРВЕРЕ 06.10.2026, выборка — три запроса. Портал отвечает кодом
 * 404 на запрос без заголовка браузера и кодом 200 с ним. Корневая страница
 * ведёт себя так же, то есть дело не в адресе страницы, а в том, кто спрашивает.
 * До этого дня заголовков не отправлялось вовсе (`headers: {}`), и портал
 * отвечал — значит поведение источника изменилось, а не наш код.
 *
 * ПОЧЕМУ ЭТО ОПАСНЕЕ ОБЫЧНОЙ ПОЛОМКИ. Код 404 означает «страницы нет», то есть
 * выглядит как смена разметки портала или ошибка в адресе. Поломка ДОСТУПА
 * прикидывается поломкой РАЗБОРА, и чинить полезли бы парсер. Поэтому ниже у
 * ответа 404 от портала появляется отдельная подсказка.
 *
 * ЧЕСТНОЕ ПРЕДСТАВЛЕНИЕ, А НЕ МАСКИРОВКА. Мы называем себя своим именем с
 * адресом сайта — это обычная практика HTTP и вежливость к источнику. Выдавать
 * себя за браузер в проекте запрещено тем же правилом, по которому закрыт ГИСП
 * Минпромторга: защиту источника не обходим. Если источник перестанет пускать
 * честно назвавшегося клиента — это решение владельца, а не моя правка строки.
 */
const Я = 'KarginTech/1.0 (+https://kargintech.ru)';

/**
 * Заголовки, которые уходят с каждым запросом, если вызывающий не задал своих.
 *
 * Accept и Accept-Language добавлены не «на всякий случай»: портал отдаёт и
 * HTML, и JSON, и без явного Accept выбор остаётся за ним. Русский язык —
 * чтобы страница пришла в том же виде, в каком её разбирали эталоны в
 * `fixtures/`: разметка у локалей расходится, и это тихо ломает разбор.
 */
const ЗАГОЛОВКИ = {
  'User-Agent': Я,
  Accept: 'text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8',
  'Accept-Language': 'ru-RU,ru;q=0.9'
};

/** Признак того, что запрос шёл к порталу закупок, а не к нашему конвертеру. */
function этоПортал(url) {
  return /(^|\/\/|\.)zakupki\.gov\.ru(\/|$|:)/i.test(String(url || ''));
}

/**
 * Запрос с пределом времени.
 *
 * @param {string} url
 * @param {object} [опции] {метод, тело, заголовки, мс}
 * @returns {Promise<{ok: boolean, код: number, тело?: Buffer, ошибка?: string}>}
 */
// ОЧЕРЕДЬ К ПОРТАЛУ - одна на всё приложение (23.10.2026). Поиск клиентов,
// полный поток, фоновый разбор и сбор протоколов работают одновременно, и
// каждый держит свою паузу - а портал видит их сумму. Между любыми двумя
// запросами к порталу из этого процесса - не меньше ПОРТАЛ_ЗАЗОР_МС.
const ПОРТАЛ_ЗАЗОР_МС = Number(process.env.PORTAL_GAP_MS || 1500);
let порталСвободен = 0;
let порталЦепь = Promise.resolve();
function дождатьсяПортала() {
  const ход = порталЦепь.then(async () => {
    const ждать = порталСвободен - Date.now();
    if (ждать > 0) await new Promise((ok) => setTimeout(ok, ждать));
    порталСвободен = Date.now() + ПОРТАЛ_ЗАЗОР_МС;
  });
  порталЦепь = ход.catch(() => {});
  return ход;
}

async function взять(url, опции = {}) {
  if (этоПортал(url)) await дождатьсяПортала();
  const мс = опции.мс || СРОК;
  const c = new AbortController();
  const таймер = setTimeout(() => c.abort(), мс);

  try {
    const r = await fetch(url, {
      method: опции.метод || 'GET',
      // Свои заголовки ДОБАВЛЯЮТСЯ к общим, а не заменяют их целиком: иначе
      // вызов, которому нужен один свой заголовок, молча лишался бы
      // представления и получал 404 — ровно та поломка, из-за которой этот
      // блок и появился.
      headers: { ...ЗАГОЛОВКИ, ...(опции.заголовки || {}) },
      body: опции.тело || undefined,
      redirect: 'follow',
      signal: c.signal
    });
    const тело = Buffer.from(await r.arrayBuffer());
    const ответ = {
      ok: r.status >= 200 && r.status < 300,
      код: r.status,
      тело,
      заголовки: Object.fromEntries(r.headers.entries())
    };

    // ПОДСКАЗКА ВМЕСТО ЛОЖНОГО СЛЕДА. 404 и 403 от портала означают не «такой
    // страницы нет» и не ошибку разбора, а то, что нас не пустили. Без этой
    // строки отказ доступа читается как смена разметки, и чинить начинают
    // парсер — проверено на себе 06.10.2026.
    if (!ответ.ok && этоПортал(url) && (r.status === 404 || r.status === 403)) {
      ответ.подсказка = r.status === 404
        ? 'портал ответил 404 — это почти наверняка отказ пускать, а не отсутствие '
          + `страницы: он отдаёт 404 на запросы без представления. Наш заголовок: «${Я}». `
          + 'Проверить одним запросом с сервера: '
          + "curl -s -o /dev/null -w '%{http_code}\\n' -A 'Mozilla/5.0' '<адрес>' — "
          + 'если так приходит 200, портал перестал принимать наше имя'
        : 'портал ответил 403 — отказ по адресу сервера. Запросы прекратить немедленно: '
          + 'повторные обращения в закрытую дверь превращают временное ограничение в постоянное';
    }

    return ответ;
  } catch (e) {
    const причина = e.name === 'AbortError'
      ? `не дождались за ${Math.round(мс / 1000)} с`
      : (e.cause && e.cause.code ? `${e.message} (${e.cause.code})` : e.message);
    return { ok: false, код: 0, ошибка: причина };
  } finally {
    clearTimeout(таймер);
  }
}

/** То же, но ответ нужен текстом. */
async function взятьТекст(url, мс = СРОК) {
  const r = await взять(url, { мс });
  return r.ok ? { ...r, тело: r.тело.toString('utf8') } : r;
}

/**
 * Запрос с повторами.
 *
 * Портал закупок иногда отвечает отказом на ровном месте, и один такой отказ
 * не должен означать «тендеров сегодня нет». Повторяем только то, что может
 * пройти со второй попытки: таймаут, обрыв связи, временная ошибка сервера.
 * Ответ «не найдено» повторять бессмысленно.
 */
async function взятьСПовторами(url, опции = {}) {
  const попыток = опции.попыток || 3;
  const пауза = опции.пауза || 2000;
  let последний = null;

  for (let i = 1; i <= попыток; i++) {
    const r = await взять(url, опции);
    if (r.ok) return { ...r, попыток: i };
    последний = r;

    const стоитПовторить = r.код === 0 || r.код === 429 || r.код >= 500;
    if (!стоитПовторить || i === попыток) break;
    await new Promise((ok) => setTimeout(ok, пауза * i));
  }
  return { ...последний, попыток };
}

module.exports = { взять, взятьТекст, взятьСПовторами };
