/**
 * Пауза между тендерами - 15 с, решение владельца 25.10.2026 («жди 15 сек, а
 * не 40»). Ниже 10 с не опускается ни настройкой, ни правкой вызова. Сверху
 * держит общая очередь app/http.js (1,5 с между любыми запросами) и остановка
 * на 403/429: при 15 с выходит около 1 200-1 500 запросов в час против
 * ~2 300 в час, на которых портал отказал 05.10.
 */
const ПАУЗА_ПО_УМОЛЧАНИЮ = 15000;
const ПАУЗА_МИНИМУМ = 10000;
/** Два тендера подряд без карточки — портал, скорее всего, нас не пускает. */
const ОТКАЗОВ_ПОДРЯД = 2;
/** Сколько разборов хранить: старые закупки давно закрыты. */
const ХРАНИТЬ_ДНЕЙ = 45;

function каталог(настройки = {}) {
  return настройки.каталогДанных || process.env.STATE_DIR || '/data/state';
}
function имяФайла(ид) {
  return String(ид || 'default').replace(/[^A-Za-z0-9_-]/g, '_');
}
function файлОчереди(ид, н) { return path.join(каталог(н), `${имяФайла(ид)}-queue.json`); }
function файлРазборов(ид, н) { return path.join(каталог(н), `${имяФайла(ид)}-parsed.json`); }

// КЭШ РАЗБОРОВ ПО ВРЕМЕНИ МОДИФИКАЦИИ. Файл разборов клиента вырос до
// десятков мегабайт (по 130 КБ на закупку), а читался и разбирался ЦЕЛИКОМ
// на каждом тендере очереди и в чужомРазборе на каждом совпадении — чтение
// по 25 МБ × несколько файлов × каждый тендер укладывало процессор на часы
// и раздувал память до лимита контейнера (15.11.2026: два «зависших тендера»
// оказались не зависшими разборами, а этим). Кэш держит разобранный объект
// и сбрасывается по mtime: запись из другого процесса не останется незамеченной.
const кэшРазборов = new Map();
function прочитать(файл, пусто) {
  try {
    const mtime = fs.statSync(файл).mtimeMs;
    const вКэше = кэшРазборов.get(файл);
    if (вКэше && вКэше.mtime === mtime) return вКэше.данные;
    const данные = JSON.parse(fs.readFileSync(файл, 'utf8'));
    кэшРазборов.set(файл, { mtime, данные });
    return данные;
  } catch (e) { return пусто; }
}
function записать(файл, данные) {
  fs.mkdirSync(path.dirname(файл), { recursive: true });
  const врем = файл + '.tmp';
  fs.writeFileSync(врем, JSON.stringify(данные), 'utf8');
  fs.renameSync(врем, файл);
  try { кэшРазборов.set(файл, { mtime: fs.statSync(файл).mtimeMs, данные }); } catch (e) { /* кэш не критичен */ }
}

/**
 * ГОТОВЫЙ РАЗБОР ДРУГОГО КЛИЕНТА (24.10.2026). Одна закупка стоит в очередях
 * нескольких клиентов: из 228 закупок очереди тестовой компании 166 уже были у
 * компании владельца, из 929 у kargin - 535. Каждая - около десяти запросов к
 * порталу. Разбор документации от клиента не зависит, кроме двух вещей: прайса
 * (закупка по прайсу) и стоп-слов по ТЗ. Поэтому берётся только удачный разбор
 * не старше 2 суток от клиента БЕЗ прайса и только клиентом без прайса; стоп-
 * слова пересчитываются по своему фильтру. Прайс одного клиента в чужой файл не
 * попадает: у обоих его нет.
 */
const СВЕЖЕСТЬ_ЧУЖОГО_МС = 2 * 24 * 3600 * 1000;
function чужойРазбор(ид, номер, н, настройкиКлиента) {
  let файлы = [];
  try { файлы = fs.readdirSync(каталог(н)).filter((ф) => ф.endsWith('-parsed.json') && ф !== `${имяФайла(ид)}-parsed.json`); } catch (e) { return null; }
  for (const ф of файлы) {
    const другой = ф.slice(0, -'-parsed.json'.length);
    const его = настройкиКлиента(другой);
    if (!его || его.прайс) continue;
    const р = прочитать(path.join(каталог(н), ф), {})[номер];
    if (р && р.ок && !р.изОбщего && Date.now() - Date.parse(р.когда) < СВЕЖЕСТЬ_ЧУЖОГО_МС) return { р, другой };
  }
  return null;
}

/**
 * Ставит тендеры в очередь. Уже разобранные и уже стоящие — не ставятся.
 * @returns {number} сколько добавлено
 */
/**
 * Почему тендер разбирать незачем, или null. Срок подачи истёк — подать
 * заявку уже нельзя; единственный поставщик — участвовать нельзя. Тест
 * «слаботочка» 20.10.2026: такие шли в разбор и тратили обращения к порталу.
 */
function незачемРазбирать(т, сейчас = new Date()) {
  const срок = т && т.deadline ? String(т.deadline).slice(0, 10) : '';
  if (срок && срок < сейчас.toISOString().slice(0, 10)) return `срок подачи истёк ${срок}`;
  if (/единственн[а-яё]*\s+поставщик/i.test(String((т && т.law) || ''))) return 'закупка у единственного поставщика';
  return null;
}

function поставитьВОчередь(ид, тендеры, настройки = {}) {
  const очередь = прочитать(файлОчереди(ид, настройки), []);
  const разборы = прочитать(файлРазборов(ид, настройки), {});
  const есть = new Set(очередь.map((т) => т.number));
  let добавлено = 0;
  for (const т of тендеры || []) {
    if (!т || !т.number || !т.url) continue;
    if (незачемРазбирать(т)) continue;
    if (есть.has(т.number) || разборы[т.number]) continue;
    очередь.push({
      number: т.number, url: т.url, docsUrl: т.docsUrl || '', price: т.price,
      object: т.object, orgName: т.orgName, deadline: т.deadline, law: т.law,
      ikz: т.ikz || '', okpdGroup: т.okpdGroup || null
    });
    есть.add(т.number);
    добавлено++;
  }
  записать(файлОчереди(ид, настройки), очередь);
  return добавлено;
}

/**
 * Итог разбора одного тендера — то, на чём строится рейтинг.
 * Сама смета сюда не пишется: в ней может быть прайс клиента, а этот файл
 * лишнее место его хранения. Пишется только закупка по прайсу итогом.
 */
function итогРазбора(т, р, клиент, сейчас) {
  if (!р || !р.ok) {
    // «подробно» - код ответа портала и число попыток: 503 (сбой портала) и
    // 403 (отказ нам) иначе неотличимы (24.10.2026).
    return { когда: сейчас.toISOString(), ок: false, сбой: (р && р.сбой) || 'сбой без названия',
      ...(р && р.подробно ? { подробно: String(р.подробно).slice(0, 300) } : {}),
      отменена: !!(р && р.отменена), тендер: т };
  }
  const св = р.сводкаРазбора || {};
  const имена = (р.estimate && р.estimate.rows || []).map((r) => r.name);
  const поТЗ = проверкаПоТЗ(имена, клиент.filter || {});
  const строки = (р.estimate && р.estimate.rows) || [];
  const сЦеной = строки.filter((r) => r.priceForCalc !== null && r.priceForCalc !== undefined);
  return {
    когда: сейчас.toISOString(),
    ок: true,
    тендер: т,
    позиций: строки.length,
    годен: св.годен !== false,
    причиныНегодности: св.причиныНегодности || [],
    ценаЗаЕдиницу: !!св.ценаЗаЕдиницу,
    естьТЗ: !!св.естьТЗ,
    файлов: св.прочитаноКодом || 0,
    сканов: св.сканов || 0,
    нечитаемых: св.нечитаемых || 0,
    фильтрПоТЗ: поТЗ,
    // Закупочных цен (прайс клиента) — сколько позиций из всех. Рейтинг по
    // рентабельности ставится только при полной закупке по прайсу.
    сЗакупочнойЦеной: сЦеной.filter((r) => r.basis !== 'верхняя граница цены').length,
    // Чем кончилось чтение каждого файла и что сказал разбор таблиц —
    // чтобы чинить неудачи по причине, без повторного обхода портала.
    // Только публичные документы закупки, данных клиента здесь нет.
    чтение: св.чтение || [],
    разборФайлов: св.разборФайлов || [],
    отброшено: св.отброшено || [],
    группыОкпд2: св.группыОкпд2 || [],
    проблемы: св.проблемы || [],
    закупка: р.итоги && р.итоги.закупкаИзвестна ? р.итоги.закупка : null,
    обеспечениеКонтрактаПроцент: р.tender && р.tender.обеспечениеКонтракта
      ? р.tender.обеспечениеКонтракта.процент ?? null : null,
    // Наименования позиций - для поиска по спецификации в ленте сайта
    // (22.10.2026). Публичные данные закупки; до 300 строк по 160 знаков.
    наименования: строки.slice(0, 300).map((r) => String(r.name || '').slice(0, 160)).filter(Boolean),
    // Условия контракта (аванс, оплата, поставка) с цитатами - для карточки
    // тендера на сайте (22.10.2026). Цитата - публичный текст документа.
    условия: сжатьУсловия(св.условия),
    // Национальный режим из карточки 44-ФЗ (24.10.2026): запрет, ограничение,
    // преимущество российским товарам - публичная таблица карточки.
    нацРежим: р.tender && р.tender.нацРежим ? { виды: р.tender.нацРежим.виды, строки: р.tender.нацРежим.строки.slice(0, 5) } : null,
    // Обеспечения из карточки закупки - для ленты сайта (22.10.2026).
    обеспечения: р.tender ? {
      заявка: кратко(р.tender.обеспечениеЗаявки),
      контракт: кратко(р.tender.обеспечениеКонтракта)
    } : null
  };
}

/** Условия контракта без лишнего: цитаты до 400 знаков. */
function сжатьУсловия(у) {
  if (!у || !у.источник) return null;
  const к = (о) => (о ? { ...о, цитата: String(о.цитата || '').slice(0, 400) } : null);
  return {
    аванс: к(у.аванс), оплата: к(у.оплата), поставка: к(у.поставка),
    штраф: к(у.штраф), пеня: к(у.пеня), гарантия: к(у.гарантия), гарантийныйСрок: к(у.гарантийныйСрок),
    приёмка: к(у.приёмка), казначейство: к(у.казначейство), разгрузка: к(у.разгрузка),
    годность: к(у.годность), партиями: к(у.партиями), смп: к(у.смп),
    источник: у.источник
  };
}

/** {требуется, процент, сумма} из разбора карточки; нет данных - null. */
function кратко(о) {
  if (!о || typeof о !== 'object') return null;
  const ч = (v) => (typeof v === 'number' && isFinite(v) ? v : null);
  return { требуется: typeof о.требуется === 'boolean' ? о.требуется : null, процент: ч(о.процент), сумма: ч(о.сумма) };
}

const работают = new Set();

/**
 * Разбирает очередь клиента до конца. Повторный вызов, пока идёт разбор,
 * ничего не делает: два одновременных обхода удвоили бы нагрузку на портал.
 *
 * @param {string} ид латинское имя клиента
 * @param {object} клиент настройки клиента
 * @param {object} [общие] общие настройки
 * @param {object} [опции] { пауза, журнал(строка), собрать — подмена расчёта в проверках }
 */
async function обработатьОчередь(ид, клиент, общие = {}, опции = {}) {
  if (работают.has(ид)) return { запущен: false, причина: 'разбор уже идёт' };
  работают.add(ид);
  const лог = опции.журнал || ((с) => console.log(new Date().toISOString(), `[разбор ${ид}]`, с));
  const собрать = опции.собрать || собратьСмету;
  // Пауза ниже минимума допустима только с подменённым расчётом, то есть
  // в проверках: настоящий расчёт ходит на портал.
  const пауза = опции.собрать && typeof опции.пауза === 'number'
    ? опции.пауза
    // Пауза - общее правило сервера (портал один на всех), а не настройка
    // клиента: сайт записывал в файл каждой компании 40 000, и решение
    // владельца 25.10 до очереди не дошло бы. Менять - PARSE_PAUSE_MS.
    : Math.max(ПАУЗА_МИНИМУМ, Number(process.env.PARSE_PAUSE_MS) || ПАУЗА_ПО_УМОЛЧАНИЮ);
  const н = { ...общие, ...клиент };
  let сделано = 0;
  let готовых = 0;
  let подрядБезКарточки = 0;
  try {
    for (;;) {
      const очередь = прочитать(файлОчереди(ид, н), []);
      // опции.только - номера, которые разобрать; прочая очередь не трогается
      // (20.10.2026: повторный разбор одной закупки разобрал всю очередь).
      // Без «только» - ближайший срок подачи первым (24.10.2026): с полным
      // потоком в очереди тысячи закупок, и в порядке поступления закупка со
      // сроком завтра ждала бы сутки. Без срока - в конце.
      const срок = (x) => (x.deadline ? String(x.deadline).slice(0, 16) : '9999');
      const место = опции.только
        ? очередь.findIndex((x) => опции.только.has(x.number))
        : очередь.reduce((л, x, i) => (срок(x) < срок(очередь[л]) ? i : л), 0);
      if (!очередь.length || место === -1) break;
      const т = очередь[место];
      // Очередь перечитывается в момент записи: разбор закупки идёт десятки
      // секунд, и всё, что поиск добавил за это время, иначе затиралось копией,
      // прочитанной в начале (24.10.2026). Убирается только разобранная.
      const убратьИзОчереди = () => записать(файлОчереди(ид, н), прочитать(файлОчереди(ид, н), []).filter((x) => x.number !== т.number));
      // Уже стоящие в очереди просроченные и «единственный поставщик» —
      // пропускаются с причиной, без обращения к порталу и без паузы.
      const незачем = незачемРазбирать(т);
      if (незачем) {
        const разборы = прочитать(файлРазборов(ид, н), {});
        разборы[т.number] = { когда: new Date().toISOString(), ок: false, пропущен: true, сбой: незачем, тендер: т };
        записать(файлРазборов(ид, н), разборы);
        убратьИзОчереди();
        лог(`тендер ${т.number}: пропущен — ${незачем}`);
        continue;
      }
      // Готовый разбор другого клиента - без портала и без паузы.
      const чужой = !н.прайс && опции.общийРазбор !== false
        ? чужойРазбор(ид, т.number, н, опции.настройкиКлиента || require('./settings').настройкиКлиента) : null;
      if (чужой) {
        const разборы = прочитать(файлРазборов(ид, н), {});
        разборы[т.number] = { ...чужой.р, когда: new Date().toISOString(), тендер: т, изОбщего: чужой.другой,
          фильтрПоТЗ: проверкаПоТЗ(чужой.р.наименования || [], клиент.filter || {}) };
        записать(файлРазборов(ид, н), разборы);
        убратьИзОчереди();
        сделано++;
        готовых++;
        лог(`тендер ${т.number}: готовый разбор ${чужой.другой}, позиций ${чужой.р.позиций}`);
        continue;
      }
      лог(`тендер ${т.number}, в очереди ${очередь.length}`);

      let р;
      try {
        р = await собрать({
          ссылка: т.url, адресДокументов: т.docsUrl, нмцк: т.price,
          объект: т.object, заказчик: т.orgName, срокПодачи: т.deadline
        }, { ...н, anthropicKey: '', proxyUrl: '', искатьПоставщиков: false, сканыМоделью: false });
      } catch (e) {
        р = { ok: false, сбой: 'исключение: ' + e.message };
      }

      const разборы = прочитать(файлРазборов(ид, н), {});
      разборы[т.number] = итогРазбора(т, р, клиент, new Date());
      записать(файлРазборов(ид, н), разборы);
      // Архив закупок (app/archive.js): итог разбора - публичные данные закупки.
      require('./archive').записатьРазбор(т.number, разборы[т.number], path.join(каталог(н), 'archive.db'));
      убратьИзОчереди();
      сделано++;
      // опции.предел - разобрать N с порталом и уступить очередь другому клиенту
      // (по кругу). Готовые разборы других клиентов в предел не входят.
      const хватит = опции.предел && сделано - готовых >= опции.предел;
      лог(`тендер ${т.number}: ${р.ok ? `позиций ${разборы[т.number].позиций}` : 'сбой — ' + р.сбой + (р.подробно ? ` (${String(р.подробно).slice(0, 120)})` : '')}`);

      // Портал перестал пускать — останавливаемся, а не стучим дальше.
      // Остаток очереди сохранён и продолжится со следующего запуска.
      подрядБезКарточки = !р.ok && /карточк/i.test(String(р.сбой)) ? подрядБезКарточки + 1 : 0;
      if (подрядБезКарточки >= ОТКАЗОВ_ПОДРЯД) {
        лог(`остановлено: ${ОТКАЗОВ_ПОДРЯД} карточки подряд не открылись — портал, вероятно, не пускает`);
        return { запущен: true, сделано, остановлен: 'портал не отдаёт карточки' };
      }
      if (хватит) return { запущен: true, сделано, предел: true };
      const осталось = прочитать(файлОчереди(ид, н), []);
      if (опции.только ? осталось.some((x) => опции.только.has(x.number)) : осталось.length) await спать(пауза);
    }
    почистить(ид, н);
    return { запущен: true, сделано };
  } finally {
    работают.delete(ид);
  }
}

/** Убирает разборы старше ХРАНИТЬ_ДНЕЙ. */
function почистить(ид, н) {
  const разборы = прочитать(файлРазборов(ид, н), {});
  const граница = Date.now() - ХРАНИТЬ_ДНЕЙ * 24 * 3600 * 1000;
  let убрано = 0;
  for (const [номер, р] of Object.entries(разборы)) {
    if (Date.parse(р.когда) < граница) { delete разборы[номер]; убрано++; }
  }
  if (убрано) записать(файлРазборов(ид, н), разборы);
}

/** Состояние для команды проверки: сколько ждёт, сколько разобрано, итоги. */
function состояние(ид, настройки = {}) {
  return {
    идёт: работают.has(ид),
    очередь: прочитать(файлОчереди(ид, настройки), []),
    разборы: прочитать(файлРазборов(ид, настройки), {})
  };
}

