/**
 * ОБРАТНАЯ ПРОВЕРКА ПРОГНОЗА ЦЕНЫ ПОБЕДЫ (src/win-forecast.js, калибровка).
 * Без неё прогноз клиенту не показывается (решение владельца 28.10.2026).
 *
 * Запуск: docker compose exec -T app node app/win-calibration.js
 * Сама идёт раз в сутки (app/server.js): протоколы дособираются ночью.
 * Результат - /data/state/win-calibration.json; расчёт читает его поле «прошла».
 * Портал и модель не нужны: протоколы уже на диске.
 */
const fs = require('fs');
const path = require('path');
const { калибровка } = require(path.join(__dirname, '..', 'src', 'win-forecast'));

const файл = (каталог) => path.join(каталог || process.env.STATE_DIR || '/data/state', 'win-calibration.json');

function проверить(каталог) {
  const { наблюденияПротоколов } = require('./rating-run');
  const к = калибровка(наблюденияПротоколов(каталог || process.env.STATE_DIR || '/data/state'));
  fs.writeFileSync(файл(каталог) + '.tmp', JSON.stringify(к), 'utf8');
  fs.renameSync(файл(каталог) + '.tmp', файл(каталог));
  return к;
}

/** Последний итог; старше 3 суток - как не проводилась (протоколы с тех пор менялись). */
function итог(каталог) {
  try {
    const к = JSON.parse(fs.readFileSync(файл(каталог), 'utf8'));
    if (Date.now() - Date.parse(к.когда) > 3 * 86400000) return null;
    return к;
  } catch (e) { return null; }
}

if (require.main === module) {
  const к = проверить();
  console.log(`наблюдений ${к.наблюдений}, проверено закупок ${к.закупок}, пар ${к.пар}`);
  for (const б of к.корзины) console.log(`  прогноз ${б.от}-${б.до}%: пар ${б.пар}, предсказано ${б.предсказано}%, сбылось ${б.сбылось}%`);
  console.log(`Брайер: по похожим ${к.брайер}, одна доля по всем ${к.брайерБазовый}`);
  if (к.прошла) console.log('ПРОЙДЕНА - прогноз показывается клиентам Макс');
  else {
    console.log(`без поправки НЕ пройдена: ${к.почему}`);
    const п = к.поправка;
    console.log(`таблица поправки (прогноз → сбылось): ${п.таблица.map((т) => `${Math.round(т.p * 100)}→${Math.round(т.f * 100)}% (${т.n})`).join(', ')}`);
    for (const h of п.половины) {
      console.log(`  проверка на половине ${h.половина} (училась на ${h.учились} парах, проверено ${h.проверено}):`);
      for (const б of h.корзины) console.log(`    ${б.от}-${б.до}%: пар ${б.пар}, поправленный прогноз ${б.предсказано}%, сбылось ${б.сбылось}%`);
    }
    console.log(п.проверена ? 'С ПОПРАВКОЙ ПРОЙДЕНА - клиентам Макс показывается поправленный шанс' : `с поправкой НЕ пройдена - прогноз не показывается: ${п.почему}`);
  }
}

module.exports = { проверить, итог };
