const path = require('path');
const { applyFilters } = require('../src/filter');

/** Причина отсева без чисел: «НМЦК 12 ниже порога 100» -> «НМЦК ниже порога». */
function видПричины(r) {
  const s = String(r);
  if (/^НМЦК .* ниже порога/.test(s)) return 'НМЦК ниже порога клиента';
  if (/^НМЦК .* выше порога/.test(s)) return 'НМЦК выше порога клиента';
  if (/^стоп-слова/.test(s)) return 'стоп-слова клиента';
  if (/^статус/.test(s)) return 'статус не из выбранных';
  return s;
}

/**
 * Разбор отбора ленты. Чистая функция - под проверками.
 * @param {object[]} карточки действующие закупки потока и выдачи
 * @param {object} клиент настройки клиента (filter, searchWords)
 * @returns {{всего:number, прошло:number, отсеяно:number, причины:Array<[string,number]>, толькоСлова:number, безСлов:number}}
 */
function разборЛенты(карточки, клиент = {}) {
  const { passed, rejected } = applyFilters(карточки, { ...(клиент.filter || {}), phrases: клиент.searchWords || [] });
  const причины = new Map();
  const словами = (в) => /ключевым словам|ОКПД2 не из/.test(в);
  let толькоСлова = 0;
  // Прошли бы по словам и кодам, но их убрал другой фильтр (цена, закон,
  // стоп-слова). Если таких много - лента короткая из-за настроек, не из-за слов.
  let безСлов = 0;
  for (const r of rejected) {
    const виды = [...new Set(r.reasons.map(видПричины))];
    for (const в of виды) причины.set(в, (причины.get(в) || 0) + 1);
    if (виды.every(словами)) толькоСлова++;
    else if (!виды.some(словами)) безСлов++;
  }
  return {
    всего: карточки.length,
    прошло: passed.length,
    отсеяно: rejected.length,
    причины: [...причины.entries()].sort((a, b) => b[1] - a[1]),
    толькоСлова,
    безСлов
  };
}

function напечатать(р, клиент, вЛенте) {
  const ф = клиент.filter || {};
  console.log(`Действующих закупок в потоке: ${р.всего}`);
  console.log(`Прошло фильтр клиента сейчас: ${р.прошло}; в ленте (состояние): ${вЛенте}`);
  console.log(`Отсеяно: ${р.отсеяно}, из них только словами и кодами ОКПД2: ${р.толькоСлова}; слова подошли, убрал другой фильтр: ${р.безСлов}`);
  console.log('Причины отсева (одна закупка может иметь несколько):');
  for (const [п, n] of р.причины.slice(0, 12)) console.log(`  ${String(n).padStart(6)}  ${п}`);
  console.log('Настройки клиента:');
  console.log(`  слов ${(ф.keywords || []).length}, кодов ОКПД2 ${(ф.okpd || []).length}, стоп-слов ${(ф.stopWords || []).length}`);
  console.log(`  НМЦК от ${ф.minPrice ?? '-'} до ${ф.maxPrice ?? '-'}, законы ${(ф.laws || []).join(', ') || 'все'}, статусы ${(ф.statuses || []).join(', ') || 'все'}`);
}

if (require.main === module) {
  const арг = process.argv.slice(2);
  const ключ = (имя) => { const i = арг.indexOf('--' + имя); return i >= 0 ? арг[i + 1] : null; };
  const ид = ключ('client');
  if (!ид) { console.log('Запуск: node app/feed-diagnose.js --client <имя файла клиента>'); process.exit(1); }
  const { настройкиКлиента, общиеНастройки } = require('./settings');
  const клиент = настройкиКлиента(ид);
  if (!клиент) { console.log(`Нет файла настроек клиента «${ид}» в ${process.env.CLIENTS_DIR || '/data/clients'} или в нём ошибка JSON`); process.exit(1); }
  const каталог = общиеНастройки().каталогДанных;
  const поток = require('./stream').действующие(new Date(), path.join(каталог, 'archive.db'));
  let вЛенте = '?';
  try {
    const сост = JSON.parse(require('fs').readFileSync(path.join(каталог, `${String(клиент.ид || клиент.имя || ид).replace(/[^A-Za-z0-9_-]/g, '_')}.json`), 'utf8'));
    вЛенте = Object.keys(сост.карточки || {}).length;
  } catch (e) { /* состояния ещё нет - клиент не искал */ }
  напечатать(разборЛенты(поток, клиент), клиент, вЛенте);
}

