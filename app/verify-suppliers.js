/**
 * СВЕРКА ЦЕН ПОСТАВЩИКОВ С ИХ СТРАНИЦАМИ.
 *
 * Запуск на сервере:
 *   docker compose exec -T app node app/verify-suppliers.js
 *   docker compose exec -T app node app/verify-suppliers.js --number 0119200000826000018
 *
 * ЧТО ЭТО ОТВЕЧАЕТ НА САМОМ ДЕЛЕ. Цены поставщиков называет модель, и до этой
 * команды проверить её было нечем: клиент получал название компании, ссылку
 * и цену, а убедиться, что цена на странице действительно стоит, мог только
 * человек, открывший все ссылки руками.
 *
 * Здесь это делает наш код. Он скачивает ту же страницу, на которую модель
 * дала ссылку, и ищет на ней дословную строку, которой модель подтвердила
 * цену. Модель в проверке не участвует: страницу приносит наш запрос, сверяет
 * текст `src/verify.js`. Поэтому проверка независима от того, что модель
 * утверждает, — и денег не стоит вовсе.
 *
 * ТРИ ИСХОДА, И СМЕШИВАТЬ ИХ НЕЛЬЗЯ:
 *   подтверждено    — строка или число цены найдены на странице;
 *   не подтверждено — страница прочитана, ни строки, ни числа на ней нет;
 *   не проверено    — страница не ответила, отдала отказ или рисует цену
 *                     скриптом, которого у нас нет.
 *
 * «Не проверено» это не «выдумано». Выбросить настоящего поставщика за то,
 * что его сайт лежал, значит ошибиться в сторону отказа — а пропущенный
 * тендер в этом продукте дороже лишнего.
 *
 * ЧЕГО КОМАНДА НЕ ДОКАЗЫВАЕТ: что найденный товар совпадает с нужным по
 * характеристикам. «Бумага А4 80 г/м²» и «100 г/м²» — разные товары с разной
 * ценой, и это решает человек звонком.
 */
const fs = require('fs');
const path = require('path');
const { взять } = require('./http');
const { сверитьПоставщика, сводка, ИСХОДЫ, ценыИзРазметки } = require('../src/verify');

const КАТАЛОГ = process.env.STATE_DIR || '/data/state';
const ПАУЗА = 1500;

/**
 * Ключи командной строки только латиницей — команду набирают на Windows,
 * а выполняется она на Linux, и на этом переходе кириллица уже портилась.
 */
function ключ(имя, поУмолчанию = null) {
  const i = process.argv.indexOf('--' + имя);
  return i !== -1 && process.argv[i + 1] ? process.argv[i + 1] : поУмолчанию;
}

const спать = (мс) => new Promise((r) => setTimeout(r, мс));

/**
 * Текст страницы из HTML.
 *
 * Скрипты и стили выбрасываются целиком: в них лежат и цены (у магазинов на
 * JavaScript), и мусор, и совпадение внутри скрипта подтверждением считать
 * нельзя — покупатель его не видит.
 */
function текстИзHtml(html) {
  return String(html || '')
    .replace(/<script\b[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style\b[\s\S]*?<\/style>/gi, ' ')
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/gi, ' ')
    .replace(/&amp;/gi, '&')
    .replace(/&quot;/gi, '"')
    .replace(/&laquo;|&raquo;/gi, '"')
    .replace(/&[mn]dash;/gi, '-')
    .replace(/&#(\d+);/g, (_, n) => String.fromCharCode(Number(n)))
    .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCharCode(parseInt(n, 16)))
    .replace(/&[a-z]+;/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Декодирование страницы с учётом её кодировки.
 *
 * ВАЖНО, И ЭТО ЛОВУШКА, А НЕ ТОНКОСТЬ. Магазины на старых движках отдают
 * windows-1251. Прочитанная как UTF-8, такая страница превращается в
 * нечитаемый набор знаков, русская цитата на ней не находится — и проверка
 * обвинила бы модель в выдумке там, где виновата кодировка.
 *
 * Если кодировку не поддерживает сборка Node, исход «не проверено», а не
 * «не найдено»: сказать «не знаю» дешевле, чем сказать неправду.
 */
function раскодировать(буфер, contentType = '') {
  // Заголовок ответа главнее разметки: так велит сам стандарт, и у части
  // магазинов кодировка объявлена ТОЛЬКО там, а в разметке её нет вовсе.
  const изЗаголовка = String(contentType || '').match(/charset\s*=\s*["']?\s*([a-z0-9_-]+)/i);
  const начало = буфер.slice(0, 4096).toString('latin1');
  const изРазметки = начало.match(/charset\s*=\s*["']?\s*([a-z0-9_-]+)/i);
  const m = изЗаголовка || изРазметки;
  const имя = (m ? m[1] : 'utf-8').toLowerCase();

  if (/^(utf-?8|us-ascii)$/.test(имя)) return { ok: true, текст: буфер.toString('utf8') };

  try {
    const d = new TextDecoder(имя);
    return { ok: true, текст: d.decode(буфер) };
  } catch (e) {
    return { ok: false, почему: `кодировка страницы «${имя}» не поддерживается: ${e.message}` };
  }
}

async function страница(url) {
  let r;
  try {
    r = await взять(url, { мс: 30000 });
  } catch (e) {
    return { ok: false, почему: `запрос не удался: ${e.message}` };
  }
  if (!r.ok) {
    return {
      ok: false,
      почему: `код ответа ${r.код || '—'}${r.ошибка ? ', ' + r.ошибка : ''}`
    };
  }

  const раскодировано = раскодировать(r.тело, (r.заголовки || {})['content-type'] || '');
  if (!раскодировано.ok) return { ok: false, почему: раскодировано.почему };

  return { ok: true, текст: текстИзHtml(раскодировано.текст), разметка: ценыИзРазметки(раскодировано.текст) };
}

function следы() {
  if (!fs.existsSync(КАТАЛОГ)) return [];
  return fs.readdirSync(КАТАЛОГ)
    .filter((f) => /^verify-.+\.json$/.test(f))
    .map((f) => path.join(КАТАЛОГ, f))
    .sort((a, b) => fs.statSync(b).mtimeMs - fs.statSync(a).mtimeMs);
}

async function main() {
  const номер = ключ('number');
  const все = следы();

  if (!все.length) {
    console.log(`В ${КАТАЛОГ} нет следов прогонов (файлов verify-*.json).`);
    console.log('Сначала надо посчитать хотя бы одну закупку — след пишется сам:');
    console.log('  docker compose exec -T app node app/probe.js --suppliers');
    process.exit(1);
  }

  const файл = номер
    ? все.find((f) => f.includes(номер))
    : все[0];

  if (!файл) {
    console.log(`Следа по закупке ${номер} нет. Есть такие:`);
    for (const f of все) console.log('  ' + path.basename(f));
    process.exit(1);
  }

  const след = JSON.parse(fs.readFileSync(файл, 'utf8'));
  console.log(`След: ${path.basename(файл)}`);
  console.log(`Закупка ${след.номер}, расчёт от ${след.когда}`);
  console.log(`Позиций ${(след.позиции || []).length}, поставщиков ${(след.поставщики || []).length}`);

  // --- что уже проверено без сети, при самом расчёте -------------------
  if (след.сверка) {
    console.log('');
    console.log('=== Позиции: сверка со строкой исходного документа ===');
    for (const р of след.сверка.позиции || []) {
      const метка = р.исход === ИСХОДЫ.ПОДТВЕРЖДЕНО ? 'ОК  '
        : (р.исход === ИСХОДЫ.НЕ_ПОДТВЕРЖДЕНО ? 'НЕТ ' : '??  ');
      console.log(`  ${метка} «${р.наименование}» — ${р.причина}`);
    }
    const а = след.сверка.арифметика || { замечания: [] };
    console.log(а.замечания.length
      ? `  Арифметика: ${а.замечания.length} замечаний: ${а.замечания.join('; ')}`
      : `  Арифметика: пересчёт дал ${а.сумма} — сходится`);
  }

  // --- сверка цитат поставщиков с их страницами ------------------------
  const поставщики = след.поставщики || [];
  if (!поставщики.length) {
    console.log('');
    console.log('Поставщиков в следе нет — сверять цитаты не с чем.');
    console.log('Либо все позиции нашлись в прайсе клиента, либо поиск не запускался.');
    return;
  }

  console.log('');
  console.log('=== Цены поставщиков: сверка с их страницами ===');
  console.log(`Запросов будет ${поставщики.length}, пауза между ними ${ПАУЗА} мс.`);
  console.log('');

  const результаты = [];
  for (let i = 0; i < поставщики.length; i++) {
    const с = поставщики[i];
    if (i > 0) await спать(ПАУЗА);

    const п = await страница(с.url);
    const р = п.ok
      ? сверитьПоставщика(с, п.текст, '', п.разметка)
      : сверитьПоставщика(с, null, п.почему);
    р.позиция = с.позиция;
    результаты.push(р);

    const метка = р.исход === ИСХОДЫ.ПОДТВЕРЖДЕНО ? 'ОК  '
      : (р.исход === ИСХОДЫ.НЕ_ПОДТВЕРЖДЕНО ? 'НЕТ ' : '??  ');
    console.log(`${метка} ${р.поставщик} — ${р.цена === null ? 'без цены' : р.цена + ' ₽'}`);
    console.log(`     ${р.ссылка}`);
    console.log(`     ${р.причина}`);
  }

  // --- итог ------------------------------------------------------------
  const счёт = (и) => результаты.filter((р) => р.исход === и).length;
  console.log('');
  console.log('=== ИТОГ ===');
  console.log(сводка(след.сверка ? след.сверка.позиции : [], результаты));
  // Два вида подтверждения называются раздельно. Дословная строка у поставщика
  // БЕЗ цены подтверждает, что товар у него есть, а не цену — и считать такие
  // случаи «подтверждёнными ценами» значило бы завышать результат проверки.
  const подтв = результаты.filter((р) => р.исход === ИСХОДЫ.ПОДТВЕРЖДЕНО);
  const сЦеной = подтв.filter((р) => р.цена !== null && р.цена !== undefined);
  const всегоСЦеной = результаты.filter((р) => р.цена !== null && р.цена !== undefined).length;
  console.log(`  ЦЕН ПОДТВЕРЖДЕНО: ${сЦеной.length} из ${всегоСЦеной} названных `
    + `(дословной строкой ${сЦеной.filter((р) => р.сила === 'дословно').length}, `
    + `точным числом ${сЦеной.filter((р) => р.сила === 'число').length}, `
    + `по данным разметки ${сЦеной.filter((р) => р.сила === 'разметка').length})`);
  console.log(`  наличие товара без цены подтверждено: ${подтв.length - сЦеной.length}`);
  console.log(`  подтверждено:    ${счёт(ИСХОДЫ.ПОДТВЕРЖДЕНО)}`);
  console.log(`  не подтверждено: ${счёт(ИСХОДЫ.НЕ_ПОДТВЕРЖДЕНО)}`);
  console.log(`  не проверено:    ${счёт(ИСХОДЫ.НЕ_ПРОВЕРЕНО)}`);

  const плохие = результаты.filter((р) => р.исход === ИСХОДЫ.НЕ_ПОДТВЕРЖДЕНО);
  if (плохие.length) {
    console.log('');
    console.log('НЕ ПОДТВЕРЖДЕНЫ — проверить руками, прежде чем верить цене:');
    for (const р of плохие) console.log(`  ${р.поставщик} · ${р.ссылка}`);
  }

  const непроверенные = результаты.filter((р) => р.исход === ИСХОДЫ.НЕ_ПРОВЕРЕНО);
  if (непроверенные.length) {
    console.log('');
    console.log('НЕ ПРОВЕРЕНЫ — страница не далась, это не обвинение модели:');
    for (const р of непроверенные) console.log(`  ${р.поставщик} · ${р.причина}`);
  }

  // Результат сверки дописывается в тот же след: по одной команде видно,
  // что проверялось и когда, без повторных запросов к сайтам поставщиков.
  try {
    след.сверкаПоставщиков = { когда: new Date().toISOString(), результаты };
    fs.writeFileSync(файл, JSON.stringify(след, null, 1), 'utf8');
    console.log('');
    console.log(`Результат дописан в ${path.basename(файл)}`);
  } catch (e) {
    console.log(`Результат НЕ дописан в след: ${e.message}`);
  }
}

if (require.main === module) {
  main().catch((e) => {
    console.error('сверка не выполнена: ' + e.stack);
    process.exit(1);
  });
}

