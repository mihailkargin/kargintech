/**
 * ПОЛНЫЙ ПОТОК ЗАКУПОК - 23.10.2026, задача владельца «не упустить ни один
 * выгодный тендер».
 *
 * Поиск по фразам зависит от того, что портал «по смыслу» сочтёт подходящим,
 * и от того, как заказчик назвал закупку. Закупка «Поставка товаров для нужд
 * школы» с кодом бумаги по слову «бумага» может не прийти вовсе. Поэтому
 * приложение забирает ВСЕ закупки на этапе подачи заявок - выдача портала без
 * слова поиска, по дате обновления, новые сверху, по 100 на страницу - и
 * держит их у себя. Отбор под клиента (его слова, стоп-слова, коды ОКПД2,
 * цена, законы) делается здесь же, без запросов к порталу.
 *
 * Два режима:
 *  - свежее: каждые 10 минут, страницы сверху до уже известных (20+ на
 *    странице) - обычно 1-3 запроса;
 *  - добор: ночью, СРЕЗАМИ. Портал отдаёт не глубже 50 страниц по 100
 *    (проверено 23.10.2026: страницы 50, 51 и 80 одинаковые), то есть 5000
 *    закупок на запрос. Поэтому действующее, появившееся до включения потока,
 *    берётся по дням размещения за 30 дней, 44-ФЗ и 223-ФЗ отдельно; срез,
 *    где больше 4900, делится по ценовым диапазонам. Очередь срезов хранится
 *    в базе и проходится за несколько ночей.
 *
 * Хранится в /data/state/archive.db, таблица stream: только публичные
 * карточки портала, ни слова о клиентах. Закупки со сроком подачи старше
 * 30 дней удаляются.
 */
const path = require('path');

const НА_СТРАНИЦЕ = 100;
const ИЗВЕСТНЫХ_ДЛЯ_ОСТАНОВКИ = 20;
const ГЛУБИНА_ДОБОРА_ДНЕЙ = 30;
const ДЕРЖАТЬ_ПОСЛЕ_СРОКА_ДНЕЙ = 30;

let база = null;
let файлБазы = null;
function открыть(файл) {
  const нужный = файл || path.join(process.env.STATE_DIR || '/data/state', 'archive.db');
  if (база && файлБазы === нужный) return база;
  закрыть();
  const { DatabaseSync } = require('node:sqlite');
  база = new DatabaseSync(нужный);
  файлБазы = нужный;
  база.exec(`
    PRAGMA journal_mode = WAL;
    CREATE TABLE IF NOT EXISTS stream (number TEXT PRIMARY KEY, updated TEXT, deadline TEXT, card TEXT, seen TEXT);
    CREATE INDEX IF NOT EXISTS stream_deadline ON stream(deadline);
    CREATE TABLE IF NOT EXISTS stream_meta (key TEXT PRIMARY KEY, value TEXT);
  `);
  return база;
}
function закрыть() { try { if (база) база.close(); } catch (e) { /* уже закрыта */ } база = null; файлБазы = null; }

function мета(б, ключ, значение) {
  if (значение === undefined) {
    const r = б.prepare('SELECT value FROM stream_meta WHERE key = ?').get(ключ);
    return r ? JSON.parse(r.value) : null;
  }
  б.prepare('INSERT INTO stream_meta(key, value) VALUES (?, ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value').run(ключ, JSON.stringify(значение));
  return значение;
}

const день = (d) => String(d || '').slice(0, 10);

const ПРЕДЕЛ_ВЫДАЧИ = 4900;
const ЦЕНОВЫЕ_ДИАПАЗОНЫ = [[null, 300000], [300000, 1000000], [1000000, 5000000], [5000000, null]];

/** Очередь срезов добора: дни размещения за 30 дней, по закону отдельно. */
function срезыДобора(now) {
  const срезы = [];
  for (let i = 0; i <= ГЛУБИНА_ДОБОРА_ДНЕЙ; i++) {
    const д = new Date(now.getTime() - i * 86400000).toISOString().slice(0, 10);
    for (const закон of ['44', '223']) срезы.push({ день: д, закон, от: null, до: null, стр: 1 });
  }
  return срезы;
}

/** «более 9 700» / «166» -> число; «более» - значит не меньше. Нет подписи - null. */
function числоВсего(подпись) {
  if (!подпись) return null;
  const n = Number(String(подпись).replace(/\D/g, ''));
  return isFinite(n) ? n : null;
}

/** Срез больше предела выдачи - делим по цене; узкий ценовой диапазон - пополам. */
function разделить(срез) {
  if (срез.от === null && срез.до === null) return ЦЕНОВЫЕ_ДИАПАЗОНЫ.map(([от, до]) => ({ ...срез, от, до, стр: 1 }));
  if (срез.от !== null && срез.до !== null && срез.до - срез.от > 1000) {
    const середина = Math.round(Math.sqrt(Math.max(1, срез.от) * срез.до));
    return [{ ...срез, до: середина, стр: 1 }, { ...срез, от: середина, стр: 1 }];
  }
  return null;
}

/** Добор срезами (ночью). о.адресСреза(срез, страница), о.всего(тело страницы). */
async function добор(о, б, состояние, записатьКарточки, журнал, now) {
  const бюджет = Math.max(1, Math.min(50, Number(о.страниц) || 30));
  const пауза = о.пауза ?? 4000;
  if (!Array.isArray(состояние.срезы)) состояние.срезы = срезыДобора(now);
  let запросов = 0;
  let новых = 0;
  let отказ = null;
  while (состояние.срезы.length && запросов < бюджет) {
    const срез = состояние.срезы[0];
    if (запросов > 0 && пауза) await new Promise((ok) => setTimeout(ok, пауза));
    запросов++;
    const r = await о.взять(о.адресСреза(срез, срез.стр));
    if (r.код === 403 || r.код === 429) { отказ = r.код; журнал.push(`поток: портал отказал кодом ${r.код}, добор остановлен`); break; }
    if (!r.ok || String(r.тело).length < 2000) { журнал.push(`поток: срез ${срез.день} ${срез.закон}-ФЗ стр. ${срез.стр} не получен (${r.ошибка || 'код ' + r.код})`); break; }
    const карточки = о.разобрать(r.тело);
    const итог = записатьКарточки(карточки);
    новых += итог.новых;
    if (срез.стр === 1) {
      const всего = числоВсего(о.всего ? о.всего(r.тело) : null);
      if (всего !== null && всего > ПРЕДЕЛ_ВЫДАЧИ) {
        const части = разделить(срез);
        if (части) {
          состояние.срезы.splice(0, 1, ...части);
          журнал.push(`поток: срез ${срез.день} ${срез.закон}-ФЗ${срез.от !== null || срез.до !== null ? ` цена ${срез.от ?? 0}-${срез.до ?? '∞'}` : ''} - ${всего}, больше предела выдачи, делим на ${части.length}`);
          continue;
        }
        журнал.push(`поток: срез ${срез.день} ${срез.закон}-ФЗ цена ${срез.от}-${срез.до} - ${всего}, делить дальше нельзя, берём первые 5000`);
      }
    }
    if (карточки.length < НА_СТРАНИЦЕ || срез.стр >= 50) состояние.срезы.shift();
    else срез.стр++;
  }
  if (!состояние.срезы.length) { состояние.доборГотов = true; журнал.push('поток: добор закончен - пройдены все срезы за 30 дней'); }
  журнал.push(`поток (добор): запросов ${запросов}, новых ${новых}, срезов осталось ${состояние.срезы.length}`);
  return { запросов, новых, обновлено: 0, отказ, хвост: состояние.срезы.length };
}

/**
 * Один прогон потока.
 * @param {{режим?: 'свежее'|'добор', страниц?: number, взять: Function, разобрать: Function,
 *   адрес: (страница:number)=>string, адресСреза?: (срез:object, страница:number)=>string,
 *   всего?: (тело:string)=>string|null, now?: Date, пауза?: number, журнал?: string[], файл?: string}} о
 * @returns {Promise<{запросов:number, новых:number, обновлено:number, отказ:number|null, хвост:number}>}
 */
async function прогон(о) {
  const б = открыть(о.файл);
  const now = о.now || new Date();
  const журнал = о.журнал || [];
  const режим = о.режим || 'свежее';
  const бюджет = Math.max(1, Math.min(50, Number(о.страниц) || 5));
  const пауза = о.пауза ?? 4000;
  const состояние = мета(б, 'состояние') || { доборГотов: false };
  const известна = б.prepare('SELECT updated FROM stream WHERE number = ?');
  const записать = б.prepare(`INSERT INTO stream(number, updated, deadline, card, seen) VALUES (?,?,?,?,?)
    ON CONFLICT(number) DO UPDATE SET updated = excluded.updated, deadline = excluded.deadline, card = excluded.card, seen = excluded.seen`);
  function записатьКарточки(карточки) {
    const итог = { новых: 0, обновлено: 0, знакомых: 0 };
    б.exec('BEGIN');
    try {
      for (const к of карточки) {
        if (!к || !к.number) continue;
        const было = известна.get(к.number);
        if (было && было.updated === String(к.updated || '')) итог.знакомых++;
        else if (было) итог.обновлено++;
        else итог.новых++;
        записать.run(к.number, String(к.updated || ''), к.deadline ? String(к.deadline) : null, JSON.stringify(к), now.toISOString());
      }
      б.exec('COMMIT');
    } catch (e) { б.exec('ROLLBACK'); throw e; }
    if (о.вАрхив) о.вАрхив(карточки);
    return итог;
  }

  let итогПрогона;
  if (режим === 'добор') {
    if (состояние.доборГотов) {
      журнал.push('поток: добор уже закончен');
      итогПрогона = { запросов: 0, новых: 0, обновлено: 0, отказ: null, хвост: 0 };
    } else {
      итогПрогона = await добор(о, б, состояние, записатьКарточки, журнал, now);
    }
  } else {
    let стр = 1;
    const итог = { запросов: 0, новых: 0, обновлено: 0, отказ: null, хвост: 0 };
    for (let взято = 0; взято < бюджет; взято++) {
      if (взято > 0 && пауза) await new Promise((ok) => setTimeout(ok, пауза));
      итог.запросов++;
      const r = await о.взять(о.адрес(стр));
      if (r.код === 403 || r.код === 429) { итог.отказ = r.код; журнал.push(`поток: портал отказал кодом ${r.код}, остановлено`); break; }
      if (!r.ok || String(r.тело).length < 2000) { журнал.push(`поток: стр. ${стр} не получена (${r.ошибка || 'код ' + r.код})`); break; }
      const карточки = о.разобрать(r.тело);
      const з = записатьКарточки(карточки);
      итог.новых += з.новых;
      итог.обновлено += з.обновлено;
      журнал.push(`поток (свежее): стр. ${стр}, карточек ${карточки.length}, уже известных ${з.знакомых}`);
      // Сверху новые, ниже - взятое раньше. Дошли до известных - стоп.
      if (карточки.length < НА_СТРАНИЦЕ || з.знакомых >= ИЗВЕСТНЫХ_ДЛЯ_ОСТАНОВКИ || стр >= 50) break;
      стр++;
    }
    итогПрогона = итог;
  }
  состояние[режим === 'свежее' ? 'последнийСвежий' : 'последнийДобор'] = now.toISOString();
  мета(б, 'состояние', состояние);
  const { запросов, новых, обновлено, отказ, хвост } = итогПрогона;
  // Срок подачи давно прошёл - карточка больше не нужна.
  const старше = день(new Date(now.getTime() - ДЕРЖАТЬ_ПОСЛЕ_СРОКА_ДНЕЙ * 86400000).toISOString());
  б.prepare('DELETE FROM stream WHERE deadline IS NOT NULL AND substr(deadline, 1, 10) < ?').run(старше);
  return { запросов, новых, обновлено, отказ, хвост };
}

/** Действующие закупки потока: срок подачи не прошёл (или не указан). */
function действующие(now = new Date(), файл) {
  let б;
  try { б = открыть(файл); } catch (e) { return []; }
  const сегодня = день(now.toISOString());
  return б.prepare('SELECT card FROM stream WHERE deadline IS NULL OR substr(deadline, 1, 10) >= ?').all(сегодня)
    .map((r) => { try { return JSON.parse(r.card); } catch (e) { return null; } }).filter(Boolean);
}

function сводка(файл) {
  const б = открыть(файл);
  const всего = б.prepare('SELECT count(*) AS n FROM stream').get().n;
  const сегодня = день(new Date().toISOString());
  const живых = б.prepare('SELECT count(*) AS n FROM stream WHERE deadline IS NULL OR substr(deadline, 1, 10) >= ?').get(сегодня).n;
  return { всего, действующих: живых, ...(мета(б, 'состояние') || {}) };
}

module.exports = { прогон, действующие, сводка, закрыть, НА_СТРАНИЦЕ };
