/**
 * ОТПЕЧАТОК КОДА — короткое число, по которому видно, та ли версия работает.
 *
 * Зачем он появился. Две выкатки подряд выглядели успешными и не были:
 *
 *   — `docker compose restart app` перезапустил контейнер со старым образом.
 *     Команда отработала без ошибок, и только проверка файла внутри
 *     контейнера показала, что нового кода там нет;
 *   — `unzip` распаковал архив, который не обновляли на сервере. Распаковка
 *     напечатала все 41 файл, Docker пересобрал образ из кэша, прогон выдал
 *     дословно прежний вывод. Понять это можно было только по строке
 *     `transferring context: 1.47kB` в выводе сборки.
 *
 * Общее у обоих случаев: **успех выкатки приходилось выводить из косвенных
 * признаков.** Отпечаток превращает это в сравнение двух чисел.
 *
 * Считается по содержимому `src/*.js` и `app/*.js` — то есть ровно по тому,
 * что попадает в образ. Переводы строк приводятся к одному виду: архив
 * собирается на Windows, распаковывается на Linux, и разница в них дала бы
 * разные отпечатки у одинакового кода.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const КОРЕНЬ = path.join(__dirname, '..');

function отпечатокКода() {
  const имена = [];
  for (const каталог of ['src', 'app']) {
    const п = path.join(КОРЕНЬ, каталог);
    if (!fs.existsSync(п)) continue;
    for (const ф of fs.readdirSync(п)) {
      if (ф.endsWith('.js')) имена.push(каталог + '/' + ф);
    }
  }
  имена.sort();

  const h = crypto.createHash('sha256');
  for (const имя of имена) {
    const содержимое = fs.readFileSync(path.join(КОРЕНЬ, имя), 'utf8').replace(/\r\n/g, '\n');
    h.update(имя);
    h.update('\0');
    h.update(содержимое);
    h.update('\0');
  }

  return { хеш: h.digest('hex').slice(0, 12), файлов: имена.length };
}

/** Строка для журнала и для вывода проб. */
function строкаВерсии() {
  try {
    const о = отпечатокКода();
    return `версия кода: ${о.хеш} (${о.файлов} файлов)`;
  } catch (e) {
    return `версия кода: не определена — ${e.message}`;
  }
}

module.exports = { отпечатокКода, строкаВерсии };
