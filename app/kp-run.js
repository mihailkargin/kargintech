/**
 * Запросы КП поставщикам по готовому расчёту и сбор ответов. 21.10.2026.
 *
 * Отправка: из следа расчёта (verify-<номер>.json) берутся найденные
 * поставщики и их позиции; страницу каждого поставщика скачивает наш код и
 * находит на ней почту (src/kp.js). Одному поставщику - одно письмо со всеми
 * его позициями.
 *
 * ПРЕДЕЛЫ - защита репутации домена kargintech.ru, а не экономия:
 * не больше ПИСЕМ_НА_ЗАКУПКУ на закупку и ПИСЕМ_В_ДЕНЬ всего, пауза между
 * письмами, одной компании повторно по той же закупке не пишем, стоп-список
 * исполняется всегда. Почтовые службы блокируют домен за всплески рассылки.
 *
 * Ответы: непрочитанные письма из ящика, метка [КП-…] в теме связывает ответ
 * с запросом. Ответ «отписаться» - адрес и домен в стоп-список.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const К = require('../src/kp');
const почта = require('./mail');
const { взять } = require('./http');

const ПИСЕМ_НА_ЗАКУПКУ = 10;
const ПИСЕМ_В_ДЕНЬ = 50;
const ПАУЗА_МС = 3000;

const каталог = (о = {}) => о.каталог || process.env.STATE_DIR || '/data/state';
const прочитать = (ф, по) => { try { return JSON.parse(fs.readFileSync(ф, 'utf8')); } catch (e) { return по; } };
function записать(ф, д) {
  const врем = ф + '.tmp';
  fs.writeFileSync(врем, JSON.stringify(д, null, 1));
  fs.renameSync(врем, ф);
}
const файлКП = (номер, о) => path.join(каталог(о), `kp-${номер}.json`);
const ид8 = () => [...crypto.randomBytes(8)].map((b) => 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'[b % 32]).join('');

function характеристикиИзСледа(след, позиция) {
  const х = след.тз && след.тз.поПозициям ? след.тз.поПозициям[позиция] : null;
  if (!х) return '';
  if (typeof х === 'string') return х;
  if (Array.isArray(х)) return х.join(' ');
  return String(х.текст || (х.строки || []).join(' ') || '');
}
function количествоИзСледа(след, позиция) {
  const п = (след.позиции || []).find((x) => x && (x.name === позиция || String(позиция).startsWith(String(x.name || '~'))));
  return п ? { количество: typeof п.quantity === 'number' ? п.quantity : null, единица: п.unit || '' } : { количество: null, единица: '' };
}

/**
 * Разослать запросы по закупке.
 * @param {string} номер
 * @param {{клиент: string, сеть?: Function, почтовик?: object, пауза?: number, каталог?: string, сейчас?: Date}} о
 */
async function разослать(номер, о = {}) {
  const н = о.почтовик ? о.почтовик.настройки : почта.настройкиПочты();
  if (!н) return { ok: false, сбой: 'почта не настроена', отправлено: 0 };
  if (!/^\d{8,25}$/.test(String(номер))) return { ok: false, сбой: 'номер закупки не похож на номер', отправлено: 0 };
  const к = каталог(о);
  // Покупатель - из файла клиента: реквизиты попадают туда только с его
  // разрешения (app/site-api.js). Нет разрешения - не пишем никому.
  const файлКлиента = /^[a-z0-9-]{2,60}$/i.test(String(о.клиент || ''))
    ? path.join(о.клиенты || process.env.CLIENTS_DIR || '/data/clients', `${о.клиент}.json`) : null;
  const покупатель = о.покупатель !== undefined ? о.покупатель
    : ((файлКлиента && прочитать(файлКлиента, {}).покупатель) || null);
  if (!покупатель || !покупатель.согласие || !покупатель.инн) {
    return { ok: true, отправлено: 0, причина: 'клиент не разрешил указывать название и ИНН в запросах цены' };
  }
  const след = прочитать(path.join(к, `verify-${номер}.json`), null);
  if (!след || !(след.поставщики || []).length) return { ok: true, отправлено: 0, причина: 'в расчёте нет поставщиков' };

  const сейчас = о.сейчас || new Date();
  const день = сейчас.toISOString().slice(0, 10);
  const счётчик = прочитать(path.join(к, 'kp-day.json'), { день, отправлено: 0 });
  if (счётчик.день !== день) { счётчик.день = день; счётчик.отправлено = 0; }
  const стоп = прочитать(path.join(к, 'kp-stop.json'), { адреса: [], домены: [] });
  const индекс = прочитать(path.join(к, 'kp-index.json'), {});
  const кп = прочитать(файлКП(номер, о), { номер, клиент: о.клиент || '', запросы: [], ответы: [] });
  const уже = new Set(кп.запросы.map((з) => К.корень(К.домен(з.url))));

  // Поставщик - домен его сайта; позиции собираются вместе.
  const поДомену = new Map();
  for (const с of след.поставщики) {
    const д = К.корень(К.домен(с.url));
    if (!д || уже.has(д) || стоп.домены.includes(д)) continue;
    if (!поДомену.has(д)) поДомену.set(д, { имя: с.name, url: с.url, позиции: [] });
    const з = поДомену.get(д);
    if (!з.позиции.includes(с.позиция)) з.позиции.push(с.позиция);
  }

  const сеть = о.сеть || ((u) => взять(u, { мс: 20000 }));
  const отправка = о.почтовик ? о.почтовик.отправить : (письмо) => почта.отправить(н, письмо);
  const пауза = о.пауза === undefined ? ПАУЗА_МС : о.пауза;
  let отправлено = 0;
  const журнал = [];
  for (const [д, з] of поДомену) {
    if (кп.запросы.filter((x) => x.статус === 'отправлено').length >= ПИСЕМ_НА_ЗАКУПКУ) { журнал.push(`предел ${ПИСЕМ_НА_ЗАКУПКУ} писем на закупку`); break; }
    if (счётчик.отправлено >= ПИСЕМ_В_ДЕНЬ) { журнал.push(`предел ${ПИСЕМ_В_ДЕНЬ} писем в день - остальные завтра`); break; }
    // Почта - со страницы товара, а если там нет - со страниц контактов
    // того же сайта (до трёх запросов, по одному, до первой найденной).
    const годный = (a) => !стоп.адреса.includes(a) && !стоп.домены.includes(К.корень(a.split('@')[1]));
    let адрес = null;
    for (const u of [з.url, ...К.страницыКонтактов(з.url)]) {
      const стр = await сеть(u);
      const html = стр && стр.ok ? (Buffer.isBuffer(стр.тело) ? стр.тело.toString('utf8') : String(стр.тело || '')) : '';
      адрес = К.почтыСоСтраницы(html, з.url).find(годный) || null;
      if (адрес) break;
    }
    if (!адрес) { кп.запросы.push({ ид: null, имя: з.имя, url: з.url, почта: null, позиции: з.позиции, когда: сейчас.toISOString(), статус: 'нет почты на сайте' }); continue; }
    const ид = ид8();
    const письмо = К.письмоКП({
      ид, покупатель,
      позиции: з.позиции.map((п) => ({ наименование: п, ...количествоИзСледа(след, п), характеристики: характеристикиИзСледа(след, п) }))
    });
    const r = await отправка({ кому: адрес, ...письмо });
    кп.запросы.push({ ид, имя: з.имя, url: з.url, почта: адрес, позиции: з.позиции, когда: new Date().toISOString(), статус: r.ok ? 'отправлено' : 'сбой', сбой: r.ok ? undefined : r.сбой });
    if (r.ok) { индекс[ид] = String(номер); отправлено++; счётчик.отправлено++; }
    else журнал.push(`${адрес}: ${r.сбой}`);
    записать(файлКП(номер, о), кп);
    записать(path.join(к, 'kp-index.json'), индекс);
    записать(path.join(к, 'kp-day.json'), счётчик);
    if (пауза) await new Promise((ok) => setTimeout(ok, пауза));
  }
  записать(файлКП(номер, о), кп);
  return { ok: true, отправлено, всего: кп.запросы.length, журнал };
}

/** Забрать ответы из ящика и разложить по закупкам. */
async function собратьОтветы(о = {}) {
  const н = о.почтовик ? о.почтовик.настройки : почта.настройкиПочты();
  if (!н) return { ok: false, сбой: 'почта не настроена', ответов: 0, новые: [] };
  const к = каталог(о);
  const r = о.почтовик ? await о.почтовик.новыеПисьма() : await почта.новыеПисьма(н);
  if (!r.ok) return { ok: false, сбой: r.сбой, ответов: 0, новые: [] };
  const индекс = прочитать(path.join(к, 'kp-index.json'), {});
  const стоп = прочитать(path.join(к, 'kp-stop.json'), { адреса: [], домены: [] });
  const новые = [];
  for (const п of r.письма) {
    const m = String(п.тема || '').match(К.МЕТКА);
    const номер = m ? индекс[m[1].toUpperCase()] : null;
    if (!номер) continue; // не наш ответ (рассылки, спам) - не трогаем
    const кп = прочитать(файлКП(номер, о), null);
    if (!кп) continue;
    const запрос = кп.запросы.find((з) => з.ид === m[1].toUpperCase());
    if (К.отписка(п.текст)) {
      if (п.почтаОт && !стоп.адреса.includes(п.почтаОт)) стоп.адреса.push(п.почтаОт);
      const д = запрос ? К.корень(К.домен(запрос.url)) : '';
      if (д && !стоп.домены.includes(д)) стоп.домены.push(д);
      записать(path.join(к, 'kp-stop.json'), стоп);
      if (запрос) запрос.отписался = true;
      записать(файлКП(номер, о), кп);
      continue;
    }
    const текст = К.текстОтвета(п.текст);
    const ответ = { ид: m[1].toUpperCase(), имя: запрос ? запрос.имя : '', url: запрос ? запрос.url : '', от: п.почтаОт, когда: new Date().toISOString(), текст, суммы: К.суммыВОтвете(текст) };
    кп.ответы.push(ответ);
    записать(файлКП(номер, о), кп);
    новые.push({ номер, клиент: кп.клиент, имя: ответ.имя });
  }
  return { ok: true, ответов: новые.length, новые };
}

/** Состояние запросов по закупкам - для страницы расчёта на сайте. */
function состояниеКП(номера, о = {}) {
  const out = {};
  for (const н of [].concat(номера || []).slice(0, 200)) {
    if (!/^\d{8,25}$/.test(String(н))) continue;
    const кп = прочитать(файлКП(н, о), null);
    if (!кп) continue;
    out[н] = {
      отправлено: кп.запросы.filter((з) => з.статус === 'отправлено').length,
      безПочты: кп.запросы.filter((з) => з.статус === 'нет почты на сайте').length,
      ответы: кп.ответы.map((о2) => ({ имя: о2.имя, url: о2.url, когда: о2.когда, текст: о2.текст, суммы: о2.суммы }))
    };
  }
  return out;
}

module.exports = { разослать, собратьОтветы, состояниеКП, ПИСЕМ_НА_ЗАКУПКУ, ПИСЕМ_В_ДЕНЬ };
