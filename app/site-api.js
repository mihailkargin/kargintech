/** Имя клиента сайта. Только латиница в нижнем регистре и цифры после «site-». */
const ИМЯ_КЛИЕНТА_САЙТА = /^site-[a-z0-9]{6,40}$/;

function прочитать(файл, запасное) {
  try { return JSON.parse(fs.readFileSync(файл, 'utf8')); } catch (e) { return запасное; }
}

function записатьАтомарно(файл, объект) {
  fs.mkdirSync(path.dirname(файл), { recursive: true });
  const врем = файл + '.tmp';
  fs.writeFileSync(врем, JSON.stringify(объект, null, 2), 'utf8');
  fs.renameSync(врем, файл);
}

/**
 * Лента тендеров клиента.
 *
 * @param {string} ид имя клиента (как у файла настроек)
 * @param {object} [каталоги] { состояние, клиенты } — для проверок
 * @returns {{ok: boolean, тендеры: Array, обновлено: string|null, вОчереди: number}}
 */
function лентаКлиента(ид, каталоги = {}) {
  const имя = String(ид || '').replace(/[^A-Za-z0-9_-]/g, '_');
  if (!имя) return { ok: false, сбой: 'не задан клиент' };
  const каталог = каталоги.состояние || process.env.STATE_DIR || '/data/state';
  const сост = прочитать(path.join(каталог, `${имя}.json`), {});
  const разборы = прочитать(path.join(каталог, `${имя}-parsed.json`), {});
  const очередь = прочитать(path.join(каталог, `${имя}-queue.json`), []);
  const вОчереди = new Set(очередь.map((т) => т.number));
  const настройки = прочитать(path.join(каталоги.клиенты || process.env.CLIENTS_DIR || '/data/clients', `${имя}.json`), {});
  const фильтр = { stopWords: (настройки.filter || {}).stopWords || [] };
  const { matchesFilters, проверкаПоТЗ } = require('../src/filter');

  const тендеры = Object.entries(сост.карточки || {}).filter(([номер, к]) => {
    const поКарточке = matchesFilters({ object: к.объект, orgName: к.заказчик, law: к.закон, method: к.закон }, фильтр);
    return поКарточке.passed && проверкаПоТЗ((разборы[номер] || {}).наименования || [], фильтр).прошёл;
  }).map(([номер, к]) => {
    const р = разборы[номер];
    return {
      номер,
      объект: к.объект, заказчик: к.заказчик, нмцк: к.нмцк, срок: к.срок,
      закон: к.закон, статус: к.статус, url: к.url, впервые: к.впервые, изменения: к.изменения || [],
      регион: к.регион || null,
      // Коды ОКПД2: из номера закупки (ИКЗ) и, после разбора, из документации.
      окпд: [...new Set([к.окпд, ...((р && р.группыОкпд2) || [])].filter(Boolean))],
      разбор: р ? {
        ок: !!р.ок, позиций: р.позиций || 0, ценаЗаЕдиницу: !!р.ценаЗаЕдиницу,
        отменена: !!р.отменена, пропущен: !!р.пропущен,
        сбой: р.ок ? null : (р.сбой || null),
        естьТЗ: !!р.естьТЗ, когда: р.когда || null,
        обеспечения: р.обеспечения || null,
        наименования: Array.isArray(р.наименования) ? р.наименования : [],
        условия: р.условия || null,
        нацРежим: р.нацРежим || null
      } : (вОчереди.has(номер) ? { вОчереди: true } : null)
    };
  });
  тендеры.sort((a, b) => String(a.срок || '9999').localeCompare(String(b.срок || '9999')));
  return { ok: true, тендеры, обновлено: сост.обновлено || null, вОчереди: очередь.length };
}

/** Список строк: обрезка, без пустых и повторов, пределы длины и числа. */
function строки(v, сколько, длина) {
  if (!Array.isArray(v)) return [];
  const out = [];
  for (const s of v) {
    const t = String(s == null ? '' : s).replace(/\s+/g, ' ').trim().slice(0, длина);
    if (t && !out.includes(t)) out.push(t);
    if (out.length >= сколько) break;
  }
  return out;
}

function число(v, мин, макс) {
  const n = Number(v);
  if (v === null || v === undefined || v === '' || !isFinite(n)) return undefined;
  return Math.min(макс, Math.max(мин, n));
}

/**
 * Похожие прошлые закупки для тендера из ленты клиента (22.10.2026): как
 * падала цена. Только файлы на диске: протоколы, собранные ночным сбором,
 * и разбор документации (группы ОКПД2). На портал не ходит.
 */
function похожиеДляТендера(ид, номер, каталоги = {}) {
  const имя = String(ид || '').replace(/[^A-Za-z0-9_-]/g, '_');
  const каталог = каталоги.состояние || process.env.STATE_DIR || '/data/state';
  const сост = прочитать(path.join(каталог, `${имя}.json`), {});
  const к = (сост.карточки || {})[String(номер)];
  if (!к) return { ok: false, сбой: 'тендер не найден в ленте' };
  const р = прочитать(path.join(каталог, `${имя}-parsed.json`), {})[String(номер)] || {};
  const { наблюденияПротоколов } = require('./rating-run');
  const { историяПохожих } = require('../src/chance');
  const группы = (р.группыОкпд2 && р.группыОкпд2.length) ? р.группыОкпд2 : ((р.тендер && р.тендер.okpdGroup) ? [р.тендер.okpdGroup] : []);
  const наблюдения = наблюденияПротоколов(каталог);
  return { ok: true, всегоНаблюдений: наблюдения.length, ...историяПохожих(наблюдения, { нмцк: к.нмцк, способ: к.закон, группыОкпд2: группы }) };
}

