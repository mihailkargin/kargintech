const fs = require('fs');
const path = require('path');

/**
 * Общие настройки приложения — из переменных окружения.
 *
 * Их задаёт `deploy/.env`, а `docker-compose.yml` передаёт в контейнер.
 */
function общиеНастройки() {
  return {
    адресКонвертера: process.env.CONVERTER_URL || 'http://converter:3000',

    // ЗАПАСНОЙ АДРЕС ДЛЯ АЛЕРТА ВЛАДЕЛЬЦУ.
    //
    // Алерт о поломке не должен зависеть от того, что сломалось. Адреса чатов
    // лежат в файле клиента — но если пропал сам файл, сообщить об этом будет
    // некуда, и поломка настроек станет полным молчанием: клиент не получает
    // тендеров, владелец не получает причины. Поэтому у владельца есть адрес
    // в переменных окружения, независимый от файлов клиентов.
    ownerChatIdЗапасной: process.env.OWNER_CHAT_ID || '',

    anthropicKey: process.env.ANTHROPIC_API_KEY || '',

    // Зарубежный посредник: Anthropic не отвечает на российские адреса.
    // Указывается ТОЛЬКО здесь и действует только на обращения к модели.
    // Глобальные HTTP_PROXY задавать нельзя — портал увидел бы зарубежный
    // адрес и перестал отвечать, то есть сломалась бы основная функция.
    proxyUrl: process.env.CLAUDE_PROXY_URL || '',

    каталогДанных: process.env.STATE_DIR || '/data/state'
  };
}

/**
 * Настройки одного клиента — файлом на томе.
 *
 * Лежат файлом, а не в коде: их правит владелец, и перезапуск контейнера ради
 * смены ключевого слова — плохой порядок. Имя файла чистится от всего, кроме
 * латиницы, цифр, дефиса и подчёркивания: имя приходит из запроса, и без
 * чистки им можно было бы выйти за каталог.
 *
 * Возвращает null, если файла нет или в нём ошибка JSON. Вызывающий обязан
 * различить это и назвать сбоем с именем файла — молчаливый переход к пустым
 * настройкам даёт прогон, который ничего не находит без объяснения причины.
 */
function настройкиКлиента(имя) {
  const каталог = process.env.CLIENTS_DIR || '/data/clients';
  const файл = path.join(каталог, `${String(имя || 'default').replace(/[^A-Za-z0-9_-]/g, '_')}.json`);
  try {
    return JSON.parse(fs.readFileSync(файл, 'utf8'));
  } catch (e) {
    return null;
  }
}

module.exports = { общиеНастройки, настройкиКлиента };
