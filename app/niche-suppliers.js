/**
 * ПОСТАВЩИКИ ПО НИШЕ НА ВНЕДРЕНИИ - пункт внедрения владельца 24.10.2026,
 * переделан 30.10.2026: «не по товару, а в целом ... чтобы не тратить деньги и
 * при оплате подписки клиент уже имел готовую базу контактов с ценами».
 *
 * До 30.10 здесь искались поставщики по 15 самым частым товарам и писались в
 * базу под точным наименованием. В новом тендере тот же товар назван иначе,
 * ключ не совпадал - и модель искала заново. Теперь:
 *   1. модель ищет поставщиков НИШИ В ЦЕЛОМ (оптовики, подрядчики комплекса) и
 *      где у них прайс - по запросу на товары и на работы, $0,3-0,4 каждый;
 *   2. наш код скачивает их прайсы (app/supplier-catalog-run.js) - бесплатно;
 *   3. в каждом тендере позиции сверяются с прайсами кодом - бесплатно.
 * Прайса нет ни в одном виде - поставщик остаётся контактом «прайс закрыт»:
 * дилерский прайс у него запрашивается во внедрении (владелец 28.10.2026).
 *
 * Запуск (стоит денег на модель, только вручную, с пределом):
 *   docker compose exec -T app node app/niche-suppliers.js --client site-xxxx --limit 3
 * Прайс клиента в модель не уходит - уходят наименования из публичных закупок.
 */
const fs = require('fs');
const path = require('path');
const { настройкиКлиента, общиеНастройки } = require('./settings');
const { нормализовать } = require(path.join(__dirname, '..', 'src', 'price-list'));
const { видПозиции } = require(path.join(__dirname, '..', 'src', 'item-kind'));
const { buildNicheSourcesRequest, parseNicheSourcesResponse } = require(path.join(__dirname, '..', 'src', 'suppliers'));
const { поставщикиИзКаталогов } = require(path.join(__dirname, '..', 'src', 'supplier-catalog'));

// $ за запрос с 4 поисками - замер 07.10.2026 без кэша ($0,3356, одна закупка).
const ЗА_ЗАПРОС = 0.34;
const ЦЕНА = { вход: 2, выход: 10, кэш: 0.2, поиск: 0.01 };

function файлКлиента(каталог, ид) { return path.join(каталог, `${ид}-niche-suppliers.json`); }

/** Самые частые позиции в разобранных закупках клиента - товары и работы. */
function товарыНиши(каталог, ид, сколько) {
  let номера = [];
  try { номера = Object.keys(JSON.parse(fs.readFileSync(path.join(каталог, `${ид}-parsed.json`), 'utf8'))); } catch (e) { /* разборов нет */ }
  const счёт = new Map();
  for (const н of номера) {
    let j; try { j = JSON.parse(fs.readFileSync(path.join(каталог, `verify-${н}.json`), 'utf8')); } catch (e) { continue; }
    const видели = new Set();
    for (const п of j.позиции || []) {
      const имя = String(п && п.name || '').trim();
      if (имя.length < 8 || /^работы по смете/i.test(имя)) continue;
      const ключ = нормализовать(имя);
      if (видели.has(ключ)) continue;
      видели.add(ключ);
      const б = счёт.get(ключ) || { позиция: { name: имя, unit: п.unit || '', quantity: п.quantity || null }, закупок: 0 };
      б.закупок++;
      счёт.set(ключ, б);
    }
  }
  return [...счёт.values()].sort((a, b) => b.закупок - a.закупок).slice(0, сколько);
}

async function спроситьМодель(запрос, н, журнал) {
  const { взятьЧерезПосредника } = require('./proxy');
  const r = await взятьЧерезПосредника('https://api.anthropic.com/v1/messages', {
    метод: 'POST', тело: JSON.stringify(запрос),
    заголовки: { 'content-type': 'application/json', 'x-api-key': н.anthropicKey, 'anthropic-version': '2023-06-01' },
    мс: 240000, посредник: н.proxyUrl
  });
  if (!r.ok) return { ok: false, сбой: `модель не ответила: ${r.ошибка || 'код ' + r.код}` };
  try {
    const о = JSON.parse(r.тело.toString('utf8'));
    const u = о.usage || {};
    const долл = (Number(u.input_tokens || 0) * ЦЕНА.вход + Number(u.output_tokens || 0) * ЦЕНА.выход
      + Number(u.cache_read_input_tokens || 0) * ЦЕНА.кэш) / 1e6
      + Number((u.server_tool_use && u.server_tool_use.web_search_requests) || 0) * ЦЕНА.поиск;
    журнал.push(`расход модели: вход ${u.input_tokens || 0}, выход ${u.output_tokens || 0}, кэш ${u.cache_read_input_tokens || 0}, `
      + `поисков ${(u.server_tool_use && u.server_tool_use.web_search_requests) || 0}, $${долл.toFixed(4)}`);
    return { ok: true, текст: (о.content || []).filter((b) => b.type === 'text').map((b) => b.text).join('\n'), долл };
  } catch (e) { return { ok: false, сбой: `ответ модели не разобран: ${e.message}` }; }
}

/** Покрытие ниши каталогами: по каждой частой позиции - поставщики с ценой, дешёвые первыми. */
function покрытие(товары, каталоги) {
  return товары.map((т) => ({
    товар: т.позиция.name, единица: т.позиция.unit, закупок: т.закупок, вид: видПозиции(т.позиция).вид,
    поставщики: поставщикиИзКаталогов(т.позиция, каталоги).sort((a, b) => a.price - b.price)
  }));
}

let идёт = false;

async function поставщикиНиши(ид, опции = {}) {
  if (!/^(site-[a-z0-9]{6,40}|kargin)$/.test(String(ид || ''))) return { ok: false, сбой: 'не клиент сайта' };
  const клиент = настройкиКлиента(ид);
  if (!клиент) return { ok: false, сбой: 'настроек клиента нет' };
  const общие = общиеНастройки();
  const н = { ...общие, ...клиент };
  const каталог = общие.каталогДанных || '/data/state';
  const КР = require('./supplier-catalog-run');
  if (опции.толькоПрочитать) {
    try {
      const сохранено = JSON.parse(fs.readFileSync(файлКлиента(каталог, ид), 'utf8'));
      // Покрытие пересчитывается при каждом чтении: каталоги обновляются раз в неделю.
      if (сохранено.позицииНиши) сохранено.товары = покрытие(сохранено.позицииНиши, КР.прочитатьКаталоги(общие));
      return { ok: true, ...сохранено };
    } catch (e) { return { ok: false, сбой: 'поставщики по нише ещё не собраны' }; }
  }
  if (идёт) return { ok: false, сбой: 'сбор поставщиков ниши уже идёт' };
  // Источники (04.11.2026): как у поиска по позициям (app/estimate-run.js) -
  // сначала Claude, при отказе по ключу или счёту Yandex Cloud без модели;
  // SUPPLIER_SEARCH=yandex - Яндекс основной.
  const Я = require('./yandex-run');
  const я = Я.настройкиЯндекса(н);
  const яндексЕсть = !!(я.ключ && я.папка);
  const claudeЕсть = !!(н.anthropicKey && н.proxyUrl);
  if (!claudeЕсть && !яндексЕсть) return { ok: false, сбой: 'не задан ключ модели или посредник, и нет ключа Yandex Cloud' };
  const сначалаЯндекс = !claudeЕсть || String(process.env.SUPPLIER_SEARCH || '').toLowerCase() === 'yandex';
  const лимит = Math.min(5, Math.max(0.3, Number(опции.лимитДолл) || 3));
  const товары = товарыНиши(каталог, ид, Number(опции.товаров) || 60);
  if (!товары.length) return { ok: false, сбой: 'в разобранных закупках клиента нет позиций - сначала нужна лента' };
  const группы = [
    { вид: 'товар', позиции: товары.filter((т) => видПозиции(т.позиция).вид !== 'работа') },
    { вид: 'работа', позиции: товары.filter((т) => видПозиции(т.позиция).вид !== 'товар') }
  ].filter((г) => г.позиции.length);
  const журнал = [сначалаЯндекс
    ? `позиций ниши: ${товары.length}; поиск Yandex Cloud без модели, до 12 запросов на группу × ${группы.length} (~0,5 ₽ запрос)`
    : `позиций ниши: ${товары.length}; запросов к модели ${группы.length} × ~$${ЗА_ЗАПРОС} (предел $${лимит})`];
  if (!сначалаЯндекс && группы.length * ЗА_ЗАПРОС > лимит) return { ok: false, сбой: `предел $${лимит} меньше ожидаемого расхода $${(группы.length * ЗА_ЗАПРОС).toFixed(2)}`, журнал };

  идёт = true;
  try {
    let долл = 0;
    let рублей = 0;
    const поставщики = [];
    const замечания = [];
    const дляЯндекса = [];
    for (const [номерГруппы, г] of группы.entries()) {
      if (сначалаЯндекс) { дляЯндекса.push(г); continue; }
      const з = buildNicheSourcesRequest({ вид: г.вид, примеры: г.позиции.map((т) => т.позиция.name), регион: н.регионПоставки }, { модель: н.модель });
      if (!з.ok) { замечания.push(з.issue); continue; }
      const о = await спроситьМодель(з.request, н, журнал);
      if (!о.ok && яндексЕсть && /код 40[13]/.test(о.сбой)) {
        журнал.push(`Claude отказал (${о.сбой}) - группы с «${г.вид}» и дальше ищет Yandex Cloud`);
        дляЯндекса.push(...группы.slice(номерГруппы));
        break;
      }
      if (!о.ok) { замечания.push(`${г.вид}: ${о.сбой}`); continue; }
      долл += о.долл;
      const р = parseNicheSourcesResponse(о.текст, г.вид);
      замечания.push(...р.issues);
      журнал.push(`${г.вид === 'работа' ? 'подрядчиков' : 'поставщиков'} найдено ${р.поставщики.length}, отброшено ${р.отброшено.length}`);
      for (const п of р.поставщики) {
        if (поставщики.some((x) => x.домен === п.домен)) continue;
        поставщики.push({ ...п, словаНиши: г.позиции.map((т) => т.позиция.name).slice(0, 40) });
      }
    }
    for (const г of дляЯндекса) {
      const р = await Я.поставщикиНишиЯндексом([{ вид: г.вид, позиции: г.позиции.map((т) => т.позиция) }], н, журнал);
      рублей += Number(р.расход && р.расход.рублей) || 0;
      for (const п of р.поставщики) {
        if (поставщики.some((x) => x.домен === п.домен)) continue;
        поставщики.push({ ...п, словаНиши: г.позиции.map((т) => т.позиция.name).slice(0, 40) });
      }
      if (р.стоп) { замечания.push(`Yandex Cloud: ${р.стоп}`); break; }
    }
    // Прайсы - кодом, по одному поставщику; сайт целиком - до 400 страниц с паузой 1 с.
    const итогиКаталогов = [];
    for (const п of поставщики) {
      const r = await КР.обновитьКаталог(п, общие, журнал);
      итогиКаталогов.push({ домен: п.домен, имя: п.имя, сайт: п.сайт, телефон: п.телефон, регион: п.регион, вид: п.вид,
        покрывает: п.покрывает, позиций: r.позиций || 0, источник: r.тип || null, прайсЗакрыт: !r.ok, отказ: r.ok ? '' : String(r.отказ || '').slice(0, 300) });
    }
    const итог = {
      когда: new Date().toISOString(),
      позицииНиши: товары,
      поставщики: итогиКаталогов,
      товары: покрытие(товары, КР.прочитатьКаталоги(общие)),
      стоимость: `стоимость $${долл.toFixed(4)}${рублей ? `, Yandex Cloud ≈ ${рублей} ₽` : ''}`,
      замечания: замечания.slice(0, 20)
    };
    fs.writeFileSync(файлКлиента(каталог, ид), JSON.stringify(итог), 'utf8');
    return { ok: true, ...итог, журнал };
  } finally {
    идёт = false;
  }
}

if (require.main === module) {
  const ключ = (и) => { const i = process.argv.indexOf('--' + и); return i > 0 ? process.argv[i + 1] : null; };
  поставщикиНиши(ключ('client'), { лимитДолл: Number(ключ('limit')) || 3 }).then((r) => {
    for (const с of r.журнал || []) console.log(с);
    if (!r.ok) { console.log('СБОЙ: ' + r.сбой); process.exit(1); }
    console.log(`\nпоставщиков ниши ${r.поставщики.length}: с прайсом ${r.поставщики.filter((п) => !п.прайсЗакрыт).length}, прайс закрыт ${r.поставщики.filter((п) => п.прайсЗакрыт).length}`);
    for (const п of r.поставщики) console.log(`  ${п.прайсЗакрыт ? 'ЗАКРЫТ' : 'ПРАЙС '} ${п.имя} (${п.домен}) ${п.позиций ? `- ${п.источник}, позиций ${п.позиций}` : '- ' + п.отказ}`);
    const покрыто = r.товары.filter((т) => т.поставщики.length).length;
    console.log(`\nпокрытие частых позиций ниши каталогами: ${покрыто} из ${r.товары.length}`);
    for (const т of r.товары.slice(0, 40)) console.log(`  ${т.поставщики.length ? 'ДА ' : 'НЕТ'} ${т.товар.slice(0, 80)}${т.поставщики.length ? ` - от ${т.поставщики[0].price} ₽ (${т.поставщики[0].domain}), источников ${т.поставщики.length}` : ''}`);
    console.log(r.стоимость);
  }).catch((e) => { console.error(e.stack); process.exit(1); });
}

module.exports = { поставщикиНиши, товарыНиши, покрытие };
