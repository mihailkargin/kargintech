/**
 * ПРАЙС КЛИЕНТА — ПЕРВЫЙ ИСТОЧНИК ЦЕН, И ЕДИНСТВЕННЫЙ БЕСПЛАТНЫЙ.
 *
 * Требование владельца 04.10.2026: «если у клиента нет поставщиков — мы ищем
 * сами. если есть, он загружает его базу данных ко мне и система должна сама по
 * этим данным все высчитывать».
 *
 * Сопоставление целиком местное: `src/price-list.js` не подключает ничего, что
 * ходит в сеть, и это закреплено проверкой по исходнику. Прайс в модель не
 * уходит ни при каком качестве совпадения — правило безопасности №1.
 *
 * ОТКАЗ ПРАЙСА ОБЯЗАН БЫТЬ ГРОМКИМ. Если файл не прочитался, расчёт не падает —
 * он молча считается по верхним границам из обоснования НМЦК, то есть по ценам
 * с чужой маржой. Сумма выйдет правдоподобной, а вывод о выгодности —
 * противоположным. Поэтому любой отказ идёт в `проблемы`, а оттуда алертом
 * владельцу, а не только в журнал.
 */
function загрузитьПрайс(настройки, журнал, проблемы) {
  const адрес = настройки.прайс;
  if (!адрес) {
    журнал.push('прайс клиента не задан — цены будут только из внешних источников');
    return null;
  }

  // ПУТЬ К ПРАЙСУ ЗАПЕРТ В КАТАЛОГЕ КЛИЕНТОВ — ИНАЧЕ ЭТО ЧТЕНИЕ ЛЮБОГО ФАЙЛА.
  //
  // Найдено при разборе безопасности 07.10.2026, в коде, написанном днём ранее
  // мной же. `настройки` собираются как `{...общие, ...файлКлиента, ...тело}`,
  // то есть поле `прайс` может прийти ПРЯМО В ЗАПРОСЕ к `/смета`. Без проверки
  // сюда можно было подставить любой путь: разборщик CSV прочитает почти любой
  // текстовый файл, а его содержимое попадёт в наименования позиций и в
  // сообщения об отказе — то есть утечёт наружу. Настройки ДРУГИХ клиентов
  // лежат в том же контейнере, и прочитать их можно было бы так же.
  //
  // Нападение требует доступа внутрь docker-сети (наружу порт не published),
  // то есть это не дыра в интернет, а второй рубеж. Но второй рубеж и нужен
  // ровно для случая, когда первый уже пройден.
  //
  // `path.resolve` схлопывает `..`, поэтому проверять надо ПОСЛЕ него, а не
  // искать «..» в строке: `/data/clients/../../etc/passwd` строкой не ловится.
  const каталог = path.resolve(process.env.CLIENTS_DIR || '/data/clients');
  const полный = path.resolve(каталог, String(адрес));
  if (полный !== каталог && !полный.startsWith(каталог + path.sep)) {
    проблемы.push(
      'прайс клиента НЕ ПРИМЕНЁН: путь к файлу ведёт за пределы каталога клиентов. '
      + 'Это либо опечатка в настройках, либо попытка прочитать посторонний файл. '
      + `Разрешён только каталог ${каталог}`
    );
    журнал.push(`прайс отвергнут: путь «${адрес}» вне каталога клиентов`);
    return null;
  }

  let данные;
  try {
    данные = fs.readFileSync(полный);
  } catch (e) {
    проблемы.push(
      `прайс клиента не прочитан (${адрес}): ${e.code === 'ENOENT' ? 'файла нет' : e.message}. `
      + 'Расчёт идёт по ценам из обоснования НМЦК, а это верхняя граница с чужой маржой'
    );
    журнал.push(`прайс не открылся: ${e.message}`);
    return null;
  }

  const разбор = разобратьПрайс(данные, { имяФайла: path.basename(адрес) });
  if (!разбор.ok) {
    проблемы.push(`прайс клиента НЕ ПРИМЕНЁН: ${разбор.отказ}`);
    журнал.push(`прайс отвергнут: ${разбор.отказ}`);
    return null;
  }

  журнал.push(
    `прайс клиента: позиций ${разбор.позиции.length}, лист ${разбор.лист}, `
    + `шапка в строке ${разбор.строкаШапки}, цена из столбца «${разбор.столбецЦены}»`
  );
  for (const з of разбор.замечания) журнал.push(`   ${з}`);
  return разбор;
}

