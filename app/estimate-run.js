/**
 * Пересохранение старого формата Microsoft через контейнер-конвертер.
 *
 * Внутрь образа n8n конвертер поставить нельзя — менеджер пакетов оттуда
 * вырезан намеренно. Поэтому он отдельный контейнер, и это же разделение
 * защищает от его зависаний: LibreOffice умеет вставать намертво.
 */
/** RAR и 7z — распаковка в конвертере (POST /unpack, bsdtar). */
async function распаковатьВКонвертере(файл, адресКонвертера, тома = null, вложенные = false) {
  const парам = [тома ? `volumes=${тома.join(',')}` : '', вложенные ? 'nested=1' : ''].filter(Boolean).join('&');
  const r = await взять(`${String(адресКонвертера).replace(/\/+$/, '')}/unpack${парам ? '?' + парам : ''}`, {
    метод: 'POST', тело: файл, заголовки: { 'Content-Type': 'application/octet-stream' }, мс: 200000
  });
  let j = null;
  try { j = JSON.parse(r.тело.toString('utf8')); } catch (e) { /* не JSON */ }
  if (!r.ok || !j || !j.ok) {
    return { ok: false, причина: (j && j.issue) || r.ошибка || `код ${r.код}` };
  }
  return {
    ok: true,
    файлы: (j.файлы || []).map((ф) => ({ имя: ф.имя, данные: Buffer.from(ф.base64, 'base64') })),
    пропущено: j.пропущено || []
  };
}

async function пересохранить(файл, имя, формат, адресКонвертера, цель = null) {
  const url = `${String(адресКонвертера).replace(/\/+$/, '')}/convert`
    + `?name=${encodeURIComponent(имя)}&format=${encodeURIComponent(формат)}${цель === 'pdf' ? '&to=pdf' : ''}`;

  const r = await взять(url, {
    метод: 'POST',
    тело: файл,
    заголовки: { 'Content-Type': 'application/octet-stream' },
    мс: 200000
  });

  if (!r.ok) {
    // Конвертер отвечает JSON с полем issue — там сказано, что именно не вышло.
    // Пустой ответ с кодом 200 он не отдаёт никогда: это его правило, потеря
    // текста не должна выглядеть как успех.
    let детали = r.ошибка || `код ${r.код}`;
    try {
      const j = JSON.parse(r.тело.toString('utf8'));
      if (j && j.issue) детали = j.issue;
      // Вывод самого LibreOffice: без него «отчитался об успехе, но файла не
      // создал» не объясняет ничего — так было дважды подряд.
      if (j && j.details) детали += ` [${String(j.details).slice(0, 200)}]`;
    } catch (e) { /* ответ не JSON — оставляем код */ }
    детали += ` (формат ${формат})`;
    return { ok: false, причина: детали };
  }
  return { ok: true, данные: r.тело };
}

/**
 * Текст из PDF кодом — программой pdftotext в контейнере конвертера.
 *
 * Решение владельца 14.10.2026: «тз должен читать код, а не модель, только
 * если она в картинке». PDF с текстовым слоем — обычный текст, и платить
 * модели за его переписывание незачем: на одной закупке это стоило $0,37.
 *
 * Колонки pdftotext передаёт пробелами. Разбор таблиц в проекте ждёт ячейки
 * через табуляцию (так их даёт чтение Word), поэтому два и больше пробела
 * подряд становятся табуляцией. Одиночный пробел — внутри ячейки, его не трогаем.
 *
 * @returns {Promise<{ok: boolean, текст?: string, скан?: boolean, причина?: string}>}
 */
async function текстPdfКодом(файл, имя, адресКонвертера) {
  const url = `${String(адресКонвертера).replace(/\/+$/, '')}/pdf-text`
    + `?name=${encodeURIComponent(имя)}`;
  const r = await взять(url, {
    метод: 'POST',
    тело: файл,
    заголовки: { 'Content-Type': 'application/octet-stream' },
    мс: 90000
  });

  let j = null;
  try { j = JSON.parse(r.тело.toString('utf8')); } catch (e) { /* разберём ниже */ }

  if (!r.ok || !j || !j.ok) {
    return {
      ok: false,
      скан: !!(j && j.скан),
      причина: (j && j.issue) || r.ошибка || `код ${r.код}`
    };
  }

  return { ok: true, текст: текстPdfВТаблицу(j.text), страниц: j.страниц };
}

