      // нет, а в нём лежат изображения - они идут в сервис таблиц, как скан.
      // Проект договора не трогается: позиций там не ищем.
      const текстБезТаблицы = !/договор|контракт/i.test(String(f.kind || ''))
        && !parseNmckTable(r.text).positions.length && !parseSpecTable(r.text).positions.length;
      const картинкиПропустить = текстБезТаблицы && таблицыУжеЕсть();
