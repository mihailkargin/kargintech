/**
 * Текст сообщения в чат.
 *
 * Должен отвечать на вопрос «идти или нет» без открытия файла: человек читает
 * чат с телефона, и «позиций 2, закупка 328 тысяч» решения не даёт.
 */
function подписьДляЧата(tender, estimate, итоги, нечитаемые, проблемы,
  поставщикиИскались = true, годность = null) {
  const д = (n) => groupDigits(Math.round(n)) + ' ₽';

  // Диапазон печатается одним правилом на весь текст: если края совпали,
  // показывается одно число. Иначе два через тире. Два места, где это делалось
  // по-разному, уже дали расхождение формулировок — теперь способ один.
  const вилка = (a, b) => (Math.round(a) === Math.round(b)) ? д(a) : `${д(a)} — ${д(b)}`;

  // Проценты — с запятой и одним знаком. JavaScript печатает «18.83», в
  // русском деловом тексте это «18,8». toLocaleString здесь применять нельзя:
  // на урезанной сборке Node русской локали нет, и формат молча меняется
  // (та же ловушка, из-за которой в проекте своя groupDigits).
  const пр = (n) => (n === null || n === undefined)
    ? '—'
    : (Math.round(n * 10) / 10).toFixed(1).replace('.', ',') + '%';
  const s = [];

  s.push(`<b>${tender.object || 'объект закупки не указан'}</b>`);
  if (tender.orgName) s.push(tender.orgName);
  s.push('');

  // ======================================================================
  //  ОДИН РАСЧЁТ, БЕЗ ДЕЛЕНИЯ НА «БЕСПЛАТНО» И «ПЛАТНО»
  // ======================================================================
  //
  // Переписано 04.10.2026 по прямому указанию владельца. До этого сообщение
  // существовало в двух видах: «до нажатия кнопки» и «после». Владелец убрал
  // саму конструкцию: «какая платная бесплатная части. клиент в любом случае
  // платит. нам нужно рассчитать тендер». Клиент платит за подписку, а не за
  // каждый расчёт, и получает полный расчёт по каждому отобранному тендеру.
  //
  // Откуда берутся цены — это вопрос источников, а не тарифа:
  //   1) база поставщиков клиента, если он её загрузил (сопоставление местное,
  //      прайс в модель НЕ уходит — правило безопасности №1);
  //   2) обоснование НМЦК и реестр контрактов — верхняя граница с чужой маржой;
  //   3) поиск поставщиков моделью, если своей базы нет.
  //
  // ДИАПАЗОН ВМЕСТО ВЫБОРА НАУГАД. Второе указание владельца того же дня:
  // «если из разных источников результаты рознятся, нужно не выбирать и не
  // выдумывать, а показывать диапазон и его обоснование». Поэтому у каждой
  // позиции перечислены источники с ценами, а прибыль и маржа печатаются
  // вилкой, если края разошлись.
  s.push(`НМЦК: <b>${д(итоги.нмцк === null ? 0 : итоги.нмцк)}</b>`);
  if (итоги.нмцк === null) {
    // Без НМЦК прибыли не существует — не ноль, а именно не существует.
    s.push('⚠️ НМЦК в карточке не указана — прибыль посчитать не от чего');
  }
  if (tender.deadline) s.push(`Подача заявок до: ${tender.deadline}`);

  // --- РАЗБОР НЕГОДЕН: СМЕТА НЕ ПОКАЗЫВАЕТСЯ ВОВСЕ ---------------------
  //
  // Добавлено 12.10.2026 после живого прогона, в котором клиенту ушла бы
  // смета из 172 «позиций», оказавшихся подписями колонок таблицы: «Цена за
  // ед. Товара», «Количество единиц товара, шт». Пометка «неполная» здесь
  // не годится — клиент сначала смотрит на строки и сумму, а оговорку читает
  // после. Поэтому строки не печатаются, а вместо них стоит причина.
  if (годность && !годность.годен) {
    s.push('');
    s.push('⚠️ <b>По этой закупке автоматический расчёт ненадёжен</b>');
    s.push('');
    s.push('Таблица позиций в документах свёрстана нестандартно, и программа '
      + 'не может прочитать её так, чтобы гарантировать правильные строки. '
      + 'Числа в таком файле могли бы оказаться не теми, поэтому вместо '
      + 'сомнительной сметы мы честно останавливаемся.');
    s.push('');
    s.push('Пришлите нам номер этой закупки — разберём документы вручную '
      + 'и доведём разбор до автоматики: с такими находками система учится.');
    s.push('');
    s.push(`Ссылка на закупку: ${tender.url || '—'}`);
    return s.join('\n');
  }

  // --- Позиции с ценами и источниками ---------------------------------
  s.push('');
  s.push(`<b>Что закупают</b> — позиций ${estimate.rows.length}`);

  // Не больше восьми позиций: длинное сообщение Telegram обрежет, а полный
  // список всё равно есть в файле.
  const показать = (estimate.rows || []).slice(0, 8);
  for (const r of показать) {
    const сколько = r.quantity !== null
      ? `${groupDigits(r.quantity)}${r.unit ? ' ' + r.unit : ''}`
      : 'количество не указано';
    s.push(`• ${r.name} — ${сколько}`);

    if (r.priceForCalc === null) {
      // Позиция без цены НЕ заполняется догадкой — правило проекта.
      s.push('  цены не нашлось ни в одном источнике');
      continue;
    }

    // ЦЕНА ЗА ЕДИНИЦУ ДО 100 ₽ - С КОПЕЙКАМИ (31.10.2026, расчёт пакетов для
    // ЭКОПАК): 1,20 и 1,40 ₽ печатались «1 ₽», и вилка цен исчезала.
    const цена = (p) => (Math.abs(p) < 100 ? (Math.round(p * 100) / 100).toFixed(2).replace('.', ',') : groupDigits(Math.round(p)));
    const заЕд = (p) => цена(p) + ' ₽' + (r.unit ? '/' + r.unit : '');
    const сумма = r.quantity !== null
      ? `, всего ${вилка(r.min * r.quantity, r.max * r.quantity)}`
      : '';
    s.push(`  ${цена(r.min) === цена(r.max) ? заЕд(r.min) : заЕд(r.min) + ' — ' + заЕд(r.max)}${сумма}`);

    // ОБОСНОВАНИЕ ДИАПАЗОНА: кто именно назвал эту цену. Без этого вилка
    // выглядит как неуверенность системы, а не как расхождение рынка.
    const ист = (r.sources || []).slice(0, 3).map((x) => {
      const кто = x.supplier ? `${x.source}, ${x.supplier}` : x.source;
      return `${кто} — ${цена(x.price)} ₽`;
    });
    if (ист.length) s.push(`  <i>${ист.join(' · ')}</i>`);
    if ((r.sources || []).length > ист.length) {
      s.push(`  <i>…и ещё ${r.sources.length - ист.length} источников в файле</i>`);
    }
    // Пояснения про происхождение цены здесь НЕ печатаем — владелец убрал
    // 04.10.2026. Источник каждой цены назван строкой выше, и этого довольно:
    // «обоснование НМЦК» и «прайс клиента» специалист различает без подсказки,
    // а лишний текст в сообщении мешает читать с телефона.
  }
  if ((estimate.rows || []).length > показать.length) {
    s.push(`…и ещё ${estimate.rows.length - показать.length} позиций — все в файле`);
  }

  // --- Итог закупки ----------------------------------------------------
  s.push('');
  if (итоги.закупка > 0) {
    s.push(`Стоимость закупки: <b>${вилка(итоги.закупкаМин, итоги.закупкаМакс)}</b>`);
    if (итоги.разбросЗакупки !== null && итоги.разбросЗакупки > 5) {
      s.push(`<i>расхождение источников ${пр(итоги.разбросЗакупки)}, приведены оба значения; `
        + 'в расчёт принята лучшая цена поставщика, худшая - нижний край прибыли</i>');
    }
  } else {
    s.push('⚠️ <b>цены не найдены ни в одном источнике</b> — расчёт невозможен');
  }

  // Про город поставщика сказано отдельно: без него расстояние неизвестно, и
  // доставка остаётся вилкой «процент от закупки». Это не наша недоработка,
  // а порядок вещей — пока поставщик не выбран, отправная точка не определена.
  // Доставка печатается, только если есть от чего её считать. Вилка берётся
  // процентом от стоимости закупки — при неизвестной закупке получался «0 ₽»,
  // и клиент прочитал бы это как бесплатную доставку. Найдено на живом
  // прогоне 07.10.2026.
  if (итоги.логистикаИзвестна) {
    s.push(`Доставка: ${д(итоги.логистика)}`);
  } else if (итоги.закупкаИзвестна) {
    s.push(`Доставка: ${вилка(итоги.логистикаЛучшая, итоги.логистика)} — предварительно. `
      + 'Точный расчёт — после выбора поставщика, когда известен пункт отправления');
  } else {
    s.push('Доставка: не рассчитана — она считается от стоимости закупки, '
      + 'а цены позиций не определены');
  }

  // --- Безубыточная цена: считается ВСЕГДА, допущений не требует ---------
  //
  // Это главный ответ расчёта, и он факт, а не прикидка: расходы известны,
  // значит цена, ниже которой контракт убыточен, выводится из них точно.
  // Прибыль, в отличие от неё, требует знать цену победы — а её не знает
  // никто, пока торги не закончились.
  // ВЫВОД ПО ЦЕНАМ ОБОСНОВАНИЯ НМЦК НЕ ДЕЛАЕТСЯ — замкнутый круг.
  //
  // Найдено на живом прогоне 14.10.2026: закупочных цен не нашлось ни по одной
  // позиции, все цены взяты из обоснования НМЦК, и сообщение напечатало
  // «расходы превышают начальную цену — участие нерентабельно». Это ровно та
  // версия, которую владелец отверг 04.10.2026: заказчик вывел НМЦК из этих
  // самых цен, и сравнить их с НМЦК — значит сравнить число с собой же. Ответ
  // «запаса нет» получается почти всегда и сведений не содержит. А клиент
  // прочитал бы его как приговор тендеру.
  // Считаются именно ПОТОЛКИ — строки, явно помеченные `pricing.js` как
  // верхняя граница. Строка без пометки потолком не объявляется: молча
  // снять вывод там, где он законен, — ошибка в сторону отказа.
  const сЦеной = (estimate.rows || []).filter((r) => r.priceForCalc !== null);
  const потолков = сЦеной.filter((r) => r.basis === 'верхняя граница цены').length;
  const закупочных = сЦеной.length - потолков;

  const толькоПотолки = !!(итоги.посчитано && итоги.закупка > 0 && сЦеной.length && потолков === сЦеной.length);
  if (толькоПотолки) {
    s.push('');
    s.push('<b>Вывод о выгодности не делается:</b> закупочных цен не найдено ни по одной '
      + 'позиции. Все цены взяты из обоснования НМЦК, а заказчик и вывел НМЦК из них, '
      + 'поэтому сравнивать их с НМЦК бессмысленно.');
    s.push('<i>Ответ появится, когда будут цены поставщиков или ваш прайс</i>');
  } else if (итоги.посчитано && итоги.закупка > 0 && итоги.безубыточность !== null) {
    s.push('');
    if (закупочных < сЦеной.length) {
      // Смешанная смета: часть цен — закупочные, часть — потолок с чужой
      // маржой. Потолок завышает расходы, то есть вывод смещён в сторону
      // «невыгодно». Сказать об этом обязательно рядом с выводом, а не внизу.
      s.push(`<i>${сЦеной.length - закупочных} из ${сЦеной.length} позиций посчитаны по ценам `
        + 'обоснования НМЦК — это верхняя граница, настоящие закупочные цены ниже. '
        + 'Вывод ниже предварительный и смещён в сторону «невыгодно»</i>');
    }
    if (итоги.запасПроцент !== null && итоги.запасПроцент > 0) {
      s.push(`<b>Предельная цена предложения: ${д(итоги.безубыточность)}</b>`);
      s.push(`<i>ниже этой цены контракт убыточен. От НМЦК это снижение на ${пр(итоги.запасПроцент)}</i>`);
      if (итоги.граница === 'запас уходит ниже порога антидемпинга') {
        s.push(`⚠️ при цене ниже ${д(итоги.порогАнтидемпинга)} применяются `
          + 'антидемпинговые меры (ст. 37): обеспечение контракта увеличивается '
          + 'в 1,5 раза, аванс не допускается');
      }
    } else if (итоги.исходЗависитОтЦены) {
      // ИСХОД РЕШАЕТ ВЫБОР ПОСТАВЩИКА, А НЕ САМ ТЕНДЕР.
      //
      // Найдено на живом прогоне 07.10.2026. По худшей закупочной цене расходы
      // превышали НМЦК, по лучшей — оставляли 15% запаса. Сообщение печатало
      // плоское «участие нерентабельно», то есть выдавало один край диапазона
      // за приговор, строкой выше показав сам диапазон. Клиент прошёл бы мимо
      // выгодного тендера, и узнать об этом ему было бы неоткуда.
      //
      // Правило владельца 04.10.2026: расхождение источников показывается
      // диапазоном с обоснованием, а не выбором за человека. То же, что уже
      // сделано для прибыли — два расчёта с НАЗВАННЫМИ условиями.
      s.push('⚠️ <b>исход зависит от того, у кого купить</b>');
      s.push(`<i>по лучшей найденной цене безубыточность ${д(итоги.безубыточностьЛучшая)} — `
        + `это запас ${пр(итоги.запасПроцентЛучший)} от НМЦК;</i>`);
      s.push(`<i>по худшей — ${д(итоги.безубыточность)}, то есть выше НМЦК: `
        + 'контракт убыточен ещё до торгов</i>');
      s.push('<i>Согласуйте цену с поставщиком до подачи заявки — '
        + 'от неё зависит, идти или нет</i>');
    } else {
      // Расходы выше НМЦК по ЛЮБОЙ из найденных закупочных цен — вывод
      // окончательный и снижения не требует: даже без единого шага вниз
      // контракт убыточен.
      s.push('❌ <b>расходы превышают начальную цену контракта</b> — '
        + 'участие нерентабельно');
      if (!поставщикиИскались) {
        // Не предложение доплатить, а признание неполноты расчёта: поиск
        // поставщиков не выполнялся, значит в расчёте только потолочные цены.
        s.push('<i>в расчёте использованы только цены из документов закупки. '
          + 'Причина указана ниже</i>');
      }
    }
  }

  // --- Прибыль: только если снижение задано клиентом ---------------------
  //
  // БЕЗ ЗАДАННОГО СНИЖЕНИЯ ПРИБЫЛЬ НЕ ПЕЧАТАЕТСЯ ВОВСЕ. Раньше здесь стояло
  // допущение 12%, под которым не было никакого основания — я его выдумал.
  // Владелец 04.10.2026: «раз обоснования нет, зачем ты его пишешь».
  //
  // Снижение определяет цену победы, то есть всю выручку, поэтому ошибка в нём
  // переворачивает вывод о выгодности целиком — и в опасную сторону:
  // заниженное снижение делает убыточный тендер выгодным на вид.
  // ТОЛЬКО ПОТОЛКИ — ни прибыли, ни убытка (20.10.2026, 0326100005026000005:
  // строкой выше «вывод не делается», ниже «убыток 46 200 ₽» по ценам, из
  // которых заказчик и вывел НМЦК). Цена победы остаётся: она от снижения
  // клиента и цен закупки не требует.
  if (толькоПотолки && итоги.снижениеЗадано) {
    s.push('');
    s.push(`Ожидаемая цена победы: <b>${д(итоги.ценаПобеды)}</b>`);
    s.push(`<i>при снижении ${пр(итоги.снижениеПроцент)} от НМЦК — ваше значение из настроек. `
      + 'Прибыль появится вместе с закупочными ценами</i>');
  }

  if (итоги.посчитано && итоги.закупка > 0 && !итоги.снижениеЗадано && !толькоПотолки) {
    s.push('');
    s.push('<i>Прибыль не рассчитана: неизвестно, до какой цены опустятся '
      + 'участники. Укажите ожидаемое снижение в настройках — либо оно будет '
      + 'взято из статистики по протоколам похожих закупок</i>');
  }

  if (итоги.посчитано && итоги.закупка > 0 && итоги.снижениеЗадано && !толькоПотолки) {
    s.push('');
    s.push(`Ожидаемая цена победы: <b>${д(итоги.ценаПобеды)}</b>`);
    s.push(`<i>при снижении ${пр(итоги.снижениеПроцент)} от НМЦК — ваше значение из настроек</i>`);
    s.push('');

    // ПРИБЫЛЬ ДАЁТСЯ ПО УСЛОВИЯМ, А НЕ ОДНОЙ ВИЛКОЙ.
    //
    // Правка владельца 04.10.2026: «у тебя прибыль скачет на 100%. ты вообще
    // понимаешь, что это ненормально». И это справедливо. Прибыль — разность
    // двух больших чисел, поэтому расхождение источников по цене на треть
    // превращается в размах прибыли от крупного убытка до крупного дохода.
    // Математически верно, а как ответ бесполезно: по строке
    // «Прибыль: −52 606 ₽ — 108 394 ₽» решение принять нельзя.
    //
    // Поэтому вместо одной вилки печатаются два расчёта с НАЗВАННЫМИ условиями.
    // Это то же содержание, но в виде, по которому можно действовать: видно,
    // что исход определяется выбором поставщика, и видно цена какого источника
    // к какому исходу ведёт.
    const разошлись = Math.round(итоги.прибыльХудшая) !== Math.round(итоги.прибыльЛучшая);

    if (!разошлись) {
      s.push(`<b>Прибыль: ${д(итоги.прибыль)}</b>, рентабельность ${пр(итоги.маржа)}`);
    } else {
      s.push('<b>Результат зависит от цены закупки:</b>');
      s.push(`• по нижним ценам (${д(итоги.закупкаМин)}) — `
        + (итоги.прибыльЛучшая >= 0
          ? `прибыль ${д(итоги.прибыльЛучшая)}, рентабельность ${пр(итоги.маржаЛучшая)}`
          : `убыток ${д(Math.abs(итоги.прибыльЛучшая))}`));
      s.push(`• по верхним ценам (${д(итоги.закупкаМакс)}) — `
        + (итоги.прибыльХудшая >= 0
          ? `прибыль ${д(итоги.прибыльХудшая)}, рентабельность ${пр(итоги.маржаХудшая)}`
          : `убыток ${д(Math.abs(итоги.прибыльХудшая))}`));
      if (итоги.разбросЗакупки !== null) {
        s.push(`<i>источники расходятся на ${пр(итоги.разбросЗакупки)}. До подтверждения `
          + 'цены у поставщика результат не определён</i>');
      }
    }

    // Вывод при ЭТОМ снижении. Предельная цена и отказ по расходам напечатаны
    // выше — они от снижения не зависят, и повторять их здесь нельзя: два
    // одинаковых блока в одном сообщении читаются как противоречие.
    if (итоги.запасПроцент !== null && итоги.запасПроцент > 0) {
      s.push('');
      if (итоги.прибыльХудшая > 0) {
        s.push('✅ контракт рентабелен при любой из найденных цен закупки');
      } else if (итоги.прибыльЛучшая > 0) {
        s.push('⚠️ рентабельность не подтверждена: требуется согласовать цену '
          + 'с поставщиком. Контакты и ссылки — в приложенном файле');
      } else {
        s.push(`⚠️ <b>контракт рентабелен только при снижении менее ${пр(итоги.запасПроцент)}</b>. `
          + `Указанное вами снижение ${пр(итоги.снижениеПроцент)} приводит к убытку`);
      }
    }
  }

  // --- Деньги и обеспечения -------------------------------------------
  if (итоги.деньги !== null) {
    s.push('');
    s.push(`<b>Требуемый объём средств: ${д(итоги.деньги)}</b>`);
    // Состав называется ПО ФАКТУ. При неизвестной закупке в сумме лежат одни
    // обеспечения, и подпись «закупка, доставка, обеспечение…» превращала бы
    // её в «всё, что нужно на контракт». Найдено на живом прогоне 07.10.2026.
    const сГарантией = итоги.обеспечениеГарантии > 0;
    s.push(итоги.закупкаИзвестна
      ? `<i>закупка, доставка${итоги.обеспеченияИзвестны ? ', обеспечение заявки и обеспечение контракта' : ''}${сГарантией ? ', обеспечение гарантии' : ''}</i>`
      : `<i>ТОЛЬКО обеспечения заявки и контракта${сГарантией ? ' и гарантии' : ''}. Стоимость самой закупки `
        + 'и доставки сюда НЕ входит — цены позиций не определены, '
        + 'и настоящая потребность в деньгах выше</i>');
    if (!итоги.обеспеченияИзвестны) {
      // Допущение убрано решением владельца 15.11.2026: ставка не указана
      // заказчиком — суммы нет, молчать о разрыве нельзя: клиент прочитал бы
      // сумму как полную потребность и не заложил бы денег на обеспечения.
      s.push('⚠️ <i>обеспечения в карточке не указаны — в этой сумме их НЕТ, '
        + 'настоящая потребность в деньгах выше. Проверьте документацию закупки</i>');
    }
    if (сГарантией) s.push(`обеспечение гарантийных обязательств — ${д(итоги.обеспечениеГарантии)} (по проекту контракта)`);
    // Источник каждого обеспечения называется: из карточки — факт; не из
    // карточки — суммы нет и это сказано прямо, без «принятых 5%».
    const из = итоги.обеспеченияИзКарточки || [];
    const строкиОбеспечений = [];
    if (из.includes('заявки по закону')) {
      строкиОбеспечений.push('обеспечение заявки не требуется (44-ФЗ, ст. 44: только при НМЦК свыше 1 млн и не в запросе котировок)');
    } else if (из.includes('заявки')) {
      строкиОбеспечений.push(`обеспечение заявки — ${д(итоги.обеспечениеЗаявки)} (по карточке закупки)`);
    } else {
      строкиОбеспечений.push('обеспечение заявки в карточке не указано — в сумме не учтено, проверьте документацию');
    }
    if (из.includes('контракта')) {
      строкиОбеспечений.push(`обеспечение контракта — ${д(итоги.обеспечениеКонтракта)} (по карточке закупки)`);
    } else {
      строкиОбеспечений.push('обеспечение контракта в карточке не указано — в сумме не учтено (заказчик устанавливает 0,5–30%), проверьте документацию');
    }
    s.push(`<i>${строкиОбеспечений.join('; ')}</i>`);
  }

  // --- Чего не хватает в расчёте ---------------------------------------
  if (!estimate.complete) {
    s.push('');
    s.push('⚠️ <b>цены определены не по всем позициям</b> — итоговая сумма неполная, '
      + 'сопоставление с НМЦК некорректно');
  }
  if (!поставщикиИскались) {
    s.push('');
    s.push('⚠️ <b>поиск поставщиков не выполнялся</b> — использованы только цены '
      + 'из документов закупки, то есть предложения, сделанные заказчику. '
      + 'Фактическая стоимость закупки ниже');
  }
  if (нечитаемые.length) {
    s.push('');
    s.push('<b>Документы, не поддающиеся разбору:</b>');
    for (const н of нечитаемые) s.push(`• ${н.имя} — ${н.причина}`);
  }
  if (проблемы.length) {
    s.push('');
    for (const p of проблемы) s.push(`⚠️ ${p}`);
  }

  s.push('');
  s.push('Полный расчёт, источники цен и ссылки — в приложенном файле. '
    + 'Любое значение можно заменить своим, расчёт пересчитается.');

  return s.join('\n');
}


