/**
 * Порядок файлов из архива: по назначению, бланки и анкеты — в конец. Предел
 * режет уже упорядоченный список (32616447271, RAR на 13 файлов, 20.10.2026:
 * первые 10 по порядку были бланками «Блок II. Формы», ТЗ не попадало).
 */
function порядокВАрхиве(файлы) {
  const вес = (имя) => {
    const k = KIND_PRIORITY.indexOf(kindOf(имя));
    const бланк = /форм[аы]\s*\d|бланк|анкет|опись|инструкц|памятк/i.test(имя);
    return (бланк ? 1000 : 0) + (k === -1 ? 500 : k);
  };
  // Служебные файлы архива (временные «~$…» Office, Thumbs.db, __MACOSX) - не
  // документы: они занимали места в пределе «первые 10» и вытесняли настоящее
  // обоснование НМЦ (32616502485, 25.10.2026, 7 из 10 мест).
  const служебный = (имя) => /(^|\/)(~\$|\.~lock|thumbs\.db$|desktop\.ini$|\.ds_store$|__macosx\/)/i.test(String(имя));
  return [...файлы].filter((ф) => !служебный(ф.имя)).sort((a, b) => вес(a.имя) - вес(b.имя));
}
