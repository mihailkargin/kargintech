/** Где лежит состояние. Том монтируется в docker-compose. */
function путьСостояния(клиент, настройки) {
  const каталог = настройки.каталогДанных || '/data/state';
  const имя = String(клиент || 'default').replace(/[^A-Za-z0-9_-]/g, '_');
  return path.join(каталог, `${имя}.json`);
}

/** Отметка успешной резервной копии; её пишет deploy/backup.sh. */
const СРОК_КОПИИ_ЧАСОВ = 36;
function свежестьКопии(настройки, now = new Date()) {
  const файл = path.join(настройки.каталогДанных || '/data/state', 'backup-ok');
  let когда;
  try { когда = new Date(fs.readFileSync(файл, 'utf8').trim()); } catch (e) {
    return { ok: false, причина: 'Отметки об успешной копии нет. Проверьте ~/backup.log на сервере.' };
  }
  if (isNaN(когда)) return { ok: false, причина: 'Отметка о копии испорчена. Проверьте ~/backup.log на сервере.' };
  const часов = (now - когда) / 3600000;
  if (часов > СРОК_КОПИИ_ЧАСОВ) {
    return { ok: false, причина: `Последняя успешная копия — ${Math.round(часов)} ч назад. Проверьте ~/backup.log на сервере.` };
  }
  return { ok: true };
}

/**
 * Отметка об отказе модели (app/estimate-run.js, отметитьОтказМодели).
 * Прочитанная отметка переименовывается — алерт уходит один раз, а файл
 * остаётся следом. Нет отметки — null.
 */
function отказМодели(настройки) {
  const файл = path.join(настройки.каталогДанных || '/data/state', 'model-fail');
  let д;
  try { д = JSON.parse(fs.readFileSync(файл, 'utf8')); } catch (e) { return null; }
  try { fs.renameSync(файл, `${файл}.sent-${Date.now()}`); } catch (e) { /* алерт важнее */ }
  return `${д.причина || 'причина не записана'} (последний отказ ${д.когда || '—'}). `
    + 'Пока это не исправлено, расчёты идут по ценам обоснования НМЦК, без поиска поставщиков.';
}

function прочитатьСостояние(файл) {
  try {
    return JSON.parse(fs.readFileSync(файл, 'utf8'));
  } catch (e) {
    // Файла ещё нет или он испорчен. Пустое состояние безопаснее попытки
    // починить: худшее последствие — клиент получит тендеры повторно.
    return {};
  }
}

function записатьСостояние(файл, состояние) {
  fs.mkdirSync(path.dirname(файл), { recursive: true });
  // Пишем через временный файл: обрыв на середине записи не должен
  // оставить испорченное состояние, из-за которого новые тендеры
  // будут считаться виденными.
  const врем = файл + '.tmp';
  fs.writeFileSync(врем, JSON.stringify(состояние), 'utf8');
  fs.renameSync(врем, файл);
}

function адресПоиска(слово, настройки, страница = 1) {
  const пар = [
    'searchString=' + encodeURIComponent(слово),
    'fz44=on',
    'fz223=on',
    // Только этап «Подача заявок». Без него портал отдаёт и завершённые, и
    // отменённые закупки: по слову «слаботочка» 21.10.2026 из 13 отобранных
    // все были прошлогодними или отменёнными, и лента клиента вышла пустой.
    // Галочка стадии - присутствие параметра (см. адресЗавершённых, pc=on).
    'af=on',
    // По дате обновления, новые сверху. Портал и так сортирует так по
    // умолчанию (проверено 22.10.2026), но мы на этом строим, сколько страниц
    // брать, - смена умолчания портала не должна менять наш поиск молча.
    'sortBy=UPDATE_DATE',
    'sortDirection=false',
    'pageNumber=' + (Number(страница) || 1),
    'recordsPerPage=_' + (настройки.записейНаСтраницу || 50)
  ];
  return БАЗА_ПОИСКА + '?' + пар.join('&');
}

/**
 * Ищет тендеры и готовит сообщения.
 *
 * @param {object} клиент настройки одного клиента
 * @param {object} [общие] общие настройки приложения
 * @returns {Promise<object>} сообщения, сводка прогона, журнал
 */
async function найтиТендеры(клиент, общие = {}) {
  const now = new Date();
  const журнал = [];
  const сообщения = [];

  const слова = клиент.searchWords || [];
  if (слова.length === 0) {
    return {
      ok: false,
      сбой: 'не заданы слова для поиска',
      подробно: 'Без списка слов система не знает, что искать. '
        + 'Составление этого списка — основная работа на онбординге.',
      журнал
    };
  }

  // --- 1. Запросы к порталу --------------------------------------------
  const выдача = await собратьВыдачу(слова, клиент, общие, { now, журнал });
  let разобрано = выдача.разобрано;
  const { негодных, отказПортала } = выдача;
  // Полный поток (app/stream.js): все действующие закупки портала, отбор
  // под клиента - тем же applyFilters ниже. Ловит то, что портал по фразам не
  // показал: общие названия («Поставка товаров») с кодом ОКПД2 категории,
  // закупки, ушедшие за третью страницу выдачи. Запросов к порталу не делает.
  if (общие.полныйПоток !== false) {
    const изПотока = require('./stream').действующие(now, path.join(общие.каталогДанных || '/data/state', 'archive.db'));
    if (изПотока.length) {
      журнал.push(`полный поток: действующих закупок ${изПотока.length}, отбор по настройкам клиента`);
      разобрано = разобрано.concat(изПотока);
    }
  }

  // Портал при «Подаче заявок» отдаёт и закупки с давно истёкшим сроком
  // (21.10.2026: «промышленный клининг» - закупка 2014 года). Срок прошёл -
  // участвовать нельзя, в ленту и в «новые» такие не попадают.
  const сегодняДата = now.toISOString().slice(0, 10);
  const доИстёкших = разобрано.length;
  разобрано = разобрано.filter((t) => !t.deadline || String(t.deadline).slice(0, 10) >= сегодняДата);
  if (разобрано.length < доИстёкших) журнал.push(`со сроком подачи в прошлом отброшено: ${доИстёкших - разобрано.length}`);
  return продолжитьПоиск({ клиент, общие, now, журнал, сообщения, слова, разобрано, негодных, отказПортала });
}

/**
 * Общая выдача по фразе за последние трое суток, на всех клиентов
 * (решение владельца 22.10.2026: поиск несколько раз в день, без лишних
 * запросов к порталу). Только публичные карточки портала - ни слова о
 * клиенте, поэтому общая. Файл на фразу: <каталог>/phrase-cache/<хеш>.json.
 */
const ДЕРЖАТЬ_ВЫДАЧУ_МС = 3 * 86400000;
const СВЕЖАЯ_ВЫДАЧА_МС = 30 * 60000;
function хранилищеВыдачи(каталог) {
  const папка = path.join(каталог, 'phrase-cache');
  const файл = (фраза) => path.join(папка, require('crypto').createHash('sha1').update(фраза).digest('hex').slice(0, 20) + '.json');
  return {
    взять(фраза) {
      try { return JSON.parse(fs.readFileSync(файл(фраза), 'utf8')); } catch (e) { return null; }
    },
    положить(фраза, данные) {
      try {
        fs.mkdirSync(папка, { recursive: true });
        const путь = файл(фраза);
        fs.writeFileSync(путь + '.tmp', JSON.stringify(данные));
        fs.renameSync(путь + '.tmp', путь);
      } catch (e) { /* без общей выдачи поиск работает как раньше */ }
    }
  };
}

/**
 * Листание выдачи портала по всем фразам клиента.
 *
 * Выдача идёт по дате обновления, новые сверху. Следующая страница - только
 * если текущая заполнена целиком, на ней нет закупок старше суток И почти нет
 * уже известных: по «бумаге» 22.10.2026 все 150 карточек трёх страниц были
 * обновлены в тот же день. Известные - из общей выдачи по фразе (прошлый
 * прогон любого клиента); дошли до них - дальше то, что уже взято. Не больше
 * 3 страниц на фразу за прогон. Фразу запрашивали меньше 30 минут назад -
 * портал не трогаем, берём общую выдачу. Клиенту отдаётся вся общая выдача
 * за трое суток: новое для него отделяет его собственное состояние (dedup).
 * Пауза между запросами - портал бережём (403 от 05.10.2026).
 *
 * @param {{взять?: Function, разобрать?: Function, now?: Date, журнал?: string[], вАрхив?: boolean,
 *   хранилище?: {взять: Function, положить: Function}|null}} [опции] для проверок; хранилище null - без общей выдачи
 */
async function собратьВыдачу(слова, клиент = {}, общие = {}, опции = {}) {
  const взять = опции.взять || взятьТекст;
  const разобрать = опции.разобрать || parseSearchPage;
  const now = опции.now || new Date();
  const журнал = опции.журнал || [];
  const хранилище = опции.хранилище === undefined ? хранилищеВыдачи(общие.каталогДанных || '/data/state') : опции.хранилище;
  let разобрано = [];
  let негодных = 0;
  const наСтранице = Number(клиент.записейНаСтраницу || общие.записейНаСтраницу || 50);
  const страниц = Math.min(3, Math.max(1, Number(клиент.страницНаСлово || общие.страницНаСлово || 3)));
  const граница = new Date(now.getTime() - 86400000).toISOString().slice(0, 10);
  // Ниже 1 с - только явной настройкой (проверки подменяют портал).
  // 2,5 с: 230 запросов за 6 минут 05.10.2026 портал счёл слишком частыми.
  const пауза = общие.паузаПоиска !== undefined ? Math.max(0, Number(общие.паузаПоиска) || 0) : 2500;
  let запросов = 0;
  let отказПортала = null;
  for (const слово of слова) {
    if (отказПортала) break;
    const ключ = String(слово).trim().toLowerCase();
    const общая = хранилище ? хранилище.взять(ключ) : null;
    if (общая && now.getTime() - Date.parse(общая.at) < СВЕЖАЯ_ВЫДАЧА_МС) {
      журнал.push(`«${слово}»: общая выдача ${Math.round((now.getTime() - Date.parse(общая.at)) / 60000)} мин назад, портал не запрашивался, карточек ${общая.карточки.length}`);
      разобрано = разобрано.concat(общая.карточки);
      continue;
    }
    const известные = new Map(((общая && общая.карточки) || []).map((к) => [к.number, String(к.updated || '')]));
    const свежие = [];
    let дошли = true;
    // ХВОСТ. Прошлый прогон взял сверху хвост карточек подряд и упёрся в предел
    // страниц, а все были свежие - ниже остались невзятые. Этот прогон, дойдя
    // до известных, перескакивает за них: новых сверху N, значит взятое прошлым
    // прогоном теперь лежит на позициях N…N+хвост, а невзятое - дальше.
    const хвост = Number((общая && общая.хвост) || 0);
    let новыйХвост = хвост;
    let новыхСверху = 0;
    let прыгнули = false;
    let стр = 1;
    for (let взято = 0; взято < страниц; взято++) {
      if (запросов++ > 0) await new Promise((ok) => setTimeout(ok, пауза));
      const r = await взять(адресПоиска(слово, { ...общие, ...клиент }, стр));
      // 403 и 429 - портал просит перестать. Продолжать - значит превратить
      // временное ограничение в постоянное (сборщик 05.10.2026 стучал ещё 7 раз).
      if (r.код === 403 || r.код === 429) {
        отказПортала = r.код;
        if (стр === 1) негодных++;
        дошли = false;
        журнал.push(`«${слово}», стр. ${стр}: портал отказал кодом ${r.код} - поиск остановлен, остальные слова не запрашивались`);
        break;
      }
      if (!r.ok || String(r.тело).length < 2000) {
        if (стр === 1) негодных++;
        дошли = false;
        журнал.push(`«${слово}», стр. ${стр}: страница не получена (${r.ошибка || 'код ' + r.код})`);
        break;
      }
      const карточки = разобрать(r.тело);
      // Архив закупок: всё, что отдал портал, а не только прошедшее отбор
      // (app/archive.js, решение владельца 22.10.2026).
      if (опции.вАрхив !== false) require('./archive').записатьВыдачу(карточки, слово, path.join(общие.каталогДанных || '/data/state', 'archive.db'));
      if (стр === 1 && карточки.length === 0) негодных++;
      const знакомых = карточки.filter((к) => известные.has(к.number) && известные.get(к.number) === String(к.updated || '')).length;
      журнал.push(`«${слово}», стр. ${стр}: карточек ${карточки.length}${известные.size ? `, уже известных ${знакомых}` : ''}`);
      if (!прыгнули) новыхСверху += карточки.length - знакомых;
      свежие.push(...карточки);
      if (карточки.length < наСтранице) { новыйХвост = 0; break; }
      // Даты обновления нет ни у одной карточки - судить не по чему, как
      // раньше: не дальше второй страницы.
      const даты = карточки.map((к) => String(к.updated || '').slice(0, 10)).filter(Boolean);
      if (даты.length ? даты.some((д) => д < граница) : стр >= 2) { новыйХвост = 0; break; }
      // Дошли до взятого прошлым прогоном. Порог 10, а не 1: закупку,
      // обновлённую заново, портал поднимает наверх, и одна известная среди
      // новых не значит, что новые кончились.
      if (!прыгнули && знакомых >= 10) {
        if (!хвост) { новыйХвост = 0; break; }
        прыгнули = true;
        стр = Math.max(стр + 1, Math.floor((новыхСверху + хвост) / наСтранице) + 1);
        журнал.push(`«${слово}»: дошли до известных, добираем невзятое прошлым прогоном со стр. ${стр}`);
        continue;
      }
      новыйХвост = стр * наСтранице;
      стр++;
      if (взято === страниц - 1) журнал.push(`«${слово}»: предел ${страниц} страницы за прогон, все свежие - остальное доберёт следующий прогон`);
    }
    // Общая выдача: свежие поверх прежних, старше трёх суток - вон, не больше 1000.
    const поНомеру = new Map(((общая && общая.карточки) || []).map((к) => [к.number, к]));
    for (const к of свежие) if (к && к.number) поНомеру.set(к.number, { ...к, seenAt: now.toISOString() });
    const держать = now.getTime() - ДЕРЖАТЬ_ВЫДАЧУ_МС;
    const вся = [...поНомеру.values()].filter((к) => Date.parse(к.seenAt || 0) >= держать).slice(-1000);
    // Отказ или сбой - время запроса не обновляем: следующий прогон спросит снова.
    if (хранилище && свежие.length) {
      хранилище.положить(ключ, {
        at: дошли ? now.toISOString() : ((общая && общая.at) || new Date(0).toISOString()),
        хвост: дошли ? новыйХвост : хвост,
        карточки: вся
      });
    }
    разобрано = разобрано.concat(хранилище ? вся : свежие);
  }
  return { разобрано, негодных, отказПортала, запросов };
}

/** Шаги после запросов к порталу: отбор, состояние, сообщения. */
async function продолжитьПоиск({ клиент, общие, now, журнал, сообщения, слова, разобрано, негодных, отказПортала }) {

  // Один тендер приходит по нескольким словам.
  const видели = new Set();
  const уникальные = [];
  for (const t of разобрано) {
    if (!t.number || видели.has(t.number)) continue;
    видели.add(t.number);
    уникальные.push(t);
  }

  // --- ТИХИЙ ОТКАЗ -------------------------------------------------------
  // Ноль карточек при непустом списке слов — это не «сегодня ничего нет».
  // Так выглядит сломанный парсер и недоступный портал. Клиент в обоих
  // случаях просто перестаёт получать тендеры и узнаёт об этом последним.
  if (уникальные.length === 0) {
    const a = buildOwnerAlert(
      отказПортала ? `портал отказал кодом ${отказПортала}` : 'пустая выдача портала',
      отказПортала
        ? 'Поиск остановлен на первом отказе. Не повторять поиск вручную в течение дня: проверить доступ одним запросом завтра.'
        : `Слов запрошено: ${слова.length}, из них негодных страниц: ${негодных}, `
          + 'разобрано карточек: 0. Либо изменилась разметка портала, либо запросы не дошли.',
      { 'клиент': клиент.имя || '—', 'слова': слова.join(', ') },
      now
    );
    return {
      ok: true,
      алертВладельцу: a.text,
      сообщения: [],
      сводка: { карточек: 0, негодных, новых: 0, отправлено: 0 },
      журнал
    };
  }

  let алертВладельцу = null;
  if (отказПортала) {
    алертВладельцу = buildOwnerAlert(
      `портал отказал кодом ${отказПортала}`,
      'Поиск остановлен на первом отказе, остальные слова в этот прогон не запрашивались. '
      + 'Не повторять поиск вручную в течение дня: проверить доступ одним запросом завтра.',
      { 'клиент': клиент.имя || '—' },
      now
    ).text;
  } else if (негодных > 0) {
    const a = buildOwnerAlert(
      'часть запросов к порталу не дала результата',
      `Негодных страниц: ${негодных} из ${слова.length}. `
      + 'Тендеры по этим словам в этот прогон не искались.',
      { 'клиент': клиент.имя || '—' },
      now
    );
    алертВладельцу = a.text;
  }

  // НОЧНАЯ РЕЗЕРВНАЯ КОПИЯ — ПРОВЕРКА СВЕЖЕСТИ. С 09 по 19.10.2026 расписание
  // падало каждую ночь с «Permission denied», и никто не знал: журнал не
  // читали. deploy/backup.sh после успеха пишет отметку в state/backup-ok;
  // нет отметки или ей больше полутора суток — алерт владельцу.
  const копия = свежестьКопии(общие, now);
  if (!копия.ok) {
    const a = buildOwnerAlert('резервная копия не обновлялась', копия.причина, {}, now);
    алертВладельцу = алертВладельцу ? алертВладельцу + '\n\n' + a.text : a.text;
  }

  // ОТКАЗ ANTHROPIC ПО СЧЁТУ ИЛИ КЛЮЧУ — расчёт по кнопке оставил отметку,
  // клиенту ушла нейтральная строка, владельцу причина — здесь.
  const модель = отказМодели(общие);
  if (модель) {
    const a = buildOwnerAlert('модель не отвечает — счёт или ключ', модель, {}, now);
    алертВладельцу = алертВладельцу ? алертВладельцу + '\n\n' + a.text : a.text;
  }

  // --- 2. Отбор ----------------------------------------------------------
  const { passed, rejected } = applyFilters(уникальные, { ...клиент.filter, phrases: клиент.searchWords || [] });

  // --- 3. Что новое ------------------------------------------------------
  // По латинскому `ид`, тому же, по которому кнопка ищет ссылку
  // (ссылкаПоНомеру). По русскому `имя` они расходились — 16.10.2026.
  const файлСостояния = путьСостояния(клиент.ид || клиент.имя, общие);
  const состояние = прочитатьСостояние(файлСостояния);
  const diff = diffAgainstState(passed, состояние.tenders || {}, { now });

  // ССЫЛКИ СОХРАНЯЕМ ОТДЕЛЬНО, и это не удобство, а необходимость.
  //
  // Расчёт сметы запускается нажатием кнопки в Telegram, а оттуда приходит
  // только реестровый номер — больше в кнопку не помещается. По номеру же
  // портал не находит НИЧЕГО: проверено 03.10.2026, свежая закупка, найденная
  // по слову, по собственному номеру даёт ноль результатов.
  //
  // Значит адрес карточки надо запомнить в момент обнаружения. Потом
  // восстановить его будет неоткуда.
  const ссылки = { ...(состояние.ссылки || {}) };
  // Адрес документов из выдачи — тоже сохраняется. У 223-ФЗ в нём noticeGuid,
  // который из номера не вывести; без него расчёт по кнопке в Telegram
  // повторил бы ошибку, из-за которой 223-ФЗ не считался до 14.10.2026.
  const документы = { ...(состояние.документы || {}) };
  for (const t of уникальные) {
    if (t.number && t.url) ссылки[t.number] = t.url;
    if (t.number && t.docsUrl) документы[t.number] = t.docsUrl;
  }

  // КАРТОЧКИ ОТОБРАННЫХ ТЕНДЕРОВ - для ленты сайта (21.10.2026): объект,
  // заказчик, способ, срок. Состояние дедупликации хранит только срок и цену.
  // Чистка: срок подачи прошёл больше 30 дней назад - карточка не нужна.
  const карточки = { ...(состояние.карточки || {}) };
  // Изменения срока и цены (dedup.js) - в карточку, для меток в ленте сайта
  // и «было → стало». Хранятся последние 10.
  const изменения = new Map(diff.updated.map((t) => [t.number, t.changes || []]));
  const сегодня = now.toISOString().slice(0, 10);
  for (const t of passed) {
    if (!t.number) continue;
    const было = карточки[t.number] || {};
    const новые = (изменения.get(t.number) || []).map((c) => ({ поле: c.field, что: c.label, было: c.from ?? null, стало: c.to ?? null, когда: сегодня }));
    карточки[t.number] = {
      объект: t.object || '', заказчик: t.orgName || '', нмцк: t.price ?? null, срок: t.deadline || null,
      закон: t.law || '', статус: t.status || '', url: t.url || '', размещено: t.published || null,
      регион: t.region || было.регион || null,
      окпд: t.okpdGroup || было.окпд || null,
      впервые: было.впервые || сегодня,
      изменения: [...(было.изменения || []), ...новые].slice(-10)
    };
  }
  const граница = new Date(now.getTime() - 30 * 86400000).toISOString().slice(0, 10);
  for (const [н, к] of Object.entries(карточки)) {
    if (к.срок && String(к.срок).slice(0, 10) < граница) delete карточки[н];
  }

  записатьСостояние(файлСостояния, {
    tenders: diff.nextState,
    ссылки,
    документы,
    карточки,
    обновлено: now.toISOString()
  });

  // --- 4. Расчёт ---------------------------------------------------------
  const кОтправке = [
    ...diff.fresh.map((t) => ({ tender: t, changes: [] })),
    ...diff.updated.map((t) => ({ tender: t, changes: t.changes || [] }))
  ].map((item) => ({
    tender: item.tender,
    scored: scoreTender(item.tender, клиент.economics, now),
    changes: item.changes
  }));

  // --- 5. Сколько и чего слать -------------------------------------------
  // Первый прогон 02.10.2026 прислал 60+ отдельных сообщений, включая
  // помеченные «пропустить». Поток уведомлений, который не читают,
  // равносилен отсутствию уведомлений.
  const ncfg = клиент.notify || {};
  const подробноДля = ncfg.detailFor || ['высокий', 'средний'];
  const пределПодробных = typeof ncfg.maxDetailed === 'number' ? ncfg.maxDetailed : 10;
  const сводкаОт = typeof ncfg.digestFrom === 'number' ? ncfg.digestFrom : 4;

  // Изменившиеся показываем всегда: сдвинутый срок подачи или изменённая
  // НМЦК — это то, из-за чего клиент может сорвать подачу по тендеру,
  // который он уже готовит.
  const заслуживают = кОтправке.filter((x) =>
    (x.changes && x.changes.length > 0) || подробноДля.includes(x.scored.priority));
  const подробные = заслуживают.slice(0, пределПодробных);
  const скрыто = заслуживают.length - подробные.length;

  // Если всё найденное помечено «пропустить» — молчим совсем.
  // Это не тихий отказ: отказ ловит проверка выше и шлёт алерт владельцу.
  // Здесь система отработала и честно не нашла ничего стоящего.
  const стоящие = кОтправке.filter((x) => x.scored.priority !== 'пропустить');

  // Список тендеров без расчёта в Telegram больше не идёт — правило владельца
  // 25.10.2026: «либо вилку прибыли и маржи, либо ничего». Он остаётся в
  // кабинете и в файле; число в журнале — для проверки.
  if (стоящие.length > 0 && кОтправке.length >= сводкаОт) {
    журнал.push(`сводка списком в Telegram не отправлена (правило вилки): тендеров ${кОтправке.length}`);
  }

  // ПРЕДВАРИТЕЛЬНЫЙ РАСЧЁТ ПО САМЫМ ВАЖНЫМ ТЕНДЕРАМ, ЧТОБЫ РЕШЕНИЕ БЫЛО СРАЗУ.
  //
  // Клиент видит не «нажмите кнопку, чтобы узнать», а предельную цену
  // предложения прямо в сообщении — то есть может отсеять заведомо невыгодное,
  // не нажимая ничего.
  //
  // ДЕЛЕНИЯ НА ПЛАТНУЮ И БЕСПЛАТНУЮ ЧАСТИ НЕТ — решение владельца 04.10.2026:
  // «клиент в любом случае платит, нам нужно рассчитать тендер». Здесь был
  // комментарий про «бесплатный» расчёт и «платный только поиск поставщиков» —
  // он остался от отменённой конструкции и возвращал бы её при первой правке.
  //
  // Ограничение здесь по ВРЕМЕНИ: каждый разбор — это скачивание нескольких
  // файлов, около минуты. Поэтому заранее считаются только те тендеры, что и так
  // уходят подробным сообщением, а поиск поставщиков моделью не запускается
  // (`искатьПоставщиков: false`) — он занимает минуты и делается по кнопке, когда
  // клиент выбрал тендер.
  const сметы = new Map();
  const разборы = new Map();
  const считатьДо = typeof ncfg.считатьСметуДля === 'number' ? ncfg.считатьСметуДля : 5;

  for (const x of подробные.slice(0, считатьДо)) {
    if (!x.tender.url) continue;
    try {
      const r = await собратьСмету(
        { ссылка: x.tender.url, нмцк: x.tender.price, объект: x.tender.object,
          заказчик: x.tender.orgName, срокПодачи: x.tender.deadline,
          адресДокументов: x.tender.docsUrl || '' },
        { ...общие, ...клиент, искатьПоставщиков: false }
      );
      if (r.ok && r.сводкаРазбора && r.сводкаРазбора.годен === false) {
        // Негодный разбор клиенту цифрами не показывается — тот же закон,
        // что в расчёте по кнопке. До 16.10.2026 этот путь его не соблюдал.
        журнал.push(`смета ${x.tender.number} не показана: разбор негоден — `
          + (r.сводкаРазбора.причиныНегодности || []).join('; '));
        // Клиенту — только факт: сколько файлов прочитано. Внутренние причины
        // негодности разбора («передано человеку» и т.п.) клиенту не пишутся —
        // решение владельца 16.10.2026; они остаются в журнале выше.
        // Цена за единицу — исключение: это свойство закупки, оно меняет деньги.
        разборы.set(x.tender.number, `прочитано файлов ${r.сводкаРазбора.прочитаноКодом || 0}`
          + (r.сводкаРазбора.ценаЗаЕдиницу
            ? '. Закупка по цене за единицу: объём не фиксирован, НМЦК — потолок договора'
            : ''));
      } else if (r.ok) {
        сметы.set(x.tender.number, r);
        const св = r.сводкаРазбора || {};
        разборы.set(x.tender.number, `прочитано файлов ${св.прочитаноКодом || 0}`);
        журнал.push(`смета ${x.tender.number}: позиций ${r.estimate.rows.length}, `
          + `безубыточность ${r.итоги.безубыточность}, прибыль `
          + (r.итоги.снижениеЗадано ? r.итоги.прибыль : 'не считается — снижение не задано'));
      } else {
        журнал.push(`смета ${x.tender.number} не собралась: ${r.сбой}`);
      }
    } catch (e) {
      // Сбой расчёта по одному тендеру не должен обрушить весь прогон:
      // остальные клиент всё равно получит.
      журнал.push(`смета ${x.tender.number} оборвалась: ${e.message}`);
    }
  }

  for (const x of подробные) {
    // Без посчитанной прибыли тендер в Telegram не идёт (правило 25.10.2026).
    // Исключение - изменился срок подачи или НМЦК (владелец 27.10.2026): клиент
    // может сорвать подачу по тендеру, который уже готовит.
    const смета = сметы.get(x.tender.number);
    const изменился = x.changes && x.changes.length > 0;
    if (!изменился && (!смета || !прибыльПосчитана(смета.итоги, смета.estimate))) {
      журнал.push(`${x.tender.number} в Telegram не отправлен: прибыль не посчитана`);
      continue;
    }
    const note = buildNotification({
      tender: x.tender,
      scored: x.scored,
      changes: x.changes,
      // Обычная наценка клиента по его категории. Он знает её лучше всех,
      // и ориентир по ней — его собственное число, а не наша выдумка.
      // Без неё система не показывает прибыль вовсе: до разбора документации
      // её неоткуда взять, а выдуманное число хуже отсутствующего.
      typicalMarginPct: клиент.typicalMarginPct,
      разбор: разборы.get(x.tender.number)
        || 'ещё не разбиралась — разбор по кнопке «Рассчитать тендер»'
    }, now);

    // ЗДЕСЬ БЫЛА ТИХАЯ ЛОЖЬ КЛИЕНТУ, найдена 05.10.2026.
    //
    // Стояло: «Прибыль не менее {прибыль} ₽ (маржа от {маржа}%)». После того как
    // 05.10 убрали выдуманное снижение цены, `прибыль` стала null — цены победы
    // больше нет, пока клиент не задал снижение сам. А `Math.round(null)` в
    // JavaScript равен НУЛЮ, и клиент получал бы в ежедневном сообщении
    // «Прибыль не менее 0 ₽ (маржа от null%)». Ничего не падает, числа на месте.
    //
    // Причина глубже опечатки: правка 04–05.10 прошла по пути РАСЧЁТА ПО КНОПКЕ
    // (app/estimate-run.js), а путь ЕЖЕДНЕВНОГО ПОИСКА остался на прежней
    // формулировке. Вместе с нулём здесь жили ещё три отменённые вещи: слово
    // «маржа» (владелец потребовал деловой язык 04.10), строка «потолок рынка, у
    // производителя дешевле» (владелец велел её убрать) и расчёт «бесплатно» из
    // отменённого деления на платную и бесплатную части.
    //
    // Поэтому здесь печатается то же и по тем же правилам, что в расчёте по
    // кнопке: безубыточность — всегда, она допущений не требует; прибыль — только
    // если снижение задано клиентом.
    // Текст расчёта собирает строкаРасчёта() в src/notify.js — одно описание на
    // проект, и его можно проверить без обращений к сети. Пока он собирался
    // здесь, внутри сетевой функции, проверить его было нельзя, и ноль вместо
    // прибыли дожил до сервера.
    let текст = note.telegram.text;
    if (смета) {
      const строка = строкаРасчёта(смета.итоги, смета.estimate);
      if (строка) текст += '\n\n' + строка;
    }

    сообщения.push({
      вид: 'подробно',
      номер: x.tender.number,
      ссылка: x.tender.url,
      текст,
      // Кнопка «Уточнить»: поиск поставщиков моделью — единственный платный
      // шаг, поэтому запускается нажатием, а не по каждому тендеру подряд.
      // Кнопка «📊 Рассчитать тендер» (КНОПКА_РАСЧЁТА в src/notify.js). Она не
      // тариф, а выбор тендера: клиенту приходит полсотни тендеров в неделю,
      // подробно нужны пять-десять. Деления на платную и бесплатную части нет —
      // решение владельца 04.10.2026.
      клавиатура: note.telegram.keyboard,
      // Файл со сметой уходит отдельным сообщением, если она собралась.
      файл: смета && смета.файл
        ? { имя: смета.файл.имя, base64: смета.файл.данные.toString('base64') }
        : null,
      audit: note.audit
    });
  }

  const сводка = {
    время: now.toISOString(),
    клиент: клиент.имя || '—',
    словПоиска: слова.length,
    негодныхСтраниц: негодных,
    карточек: уникальные.length,
    прошлоФильтр: passed.length,
    отсеяно: rejected.length,
    новых: diff.fresh.length,
    изменившихся: diff.updated.length,
    безИзменений: diff.unchanged.length,
    заслуживаютПодробностей: заслуживают.length,
    отправленоПодробно: подробные.length,
    сообщенийВсего: сообщения.length
  };
  // РАЗБОР ДОКУМЕНТАЦИИ ВСЕХ НОВЫХ ТЕНДЕРОВ — В ФОНЕ (app/parse-queue.js).
  // Ответ n8n его не ждёт: сотни обращений к порталу идут с паузами.
  // Запускается ПОСЛЕ расчёта первых тендеров выше, чтобы два обхода
  // не ходили на портал одновременно.
  const ид = клиент.ид || клиент.имя;
  try {
    const добавлено = поставитьВОчередь(ид, кОтправке.map((x) => x.tender), общие);
    сводка.вОчередьРазбора = добавлено;
    журнал.push(`в очередь фонового разбора поставлено: ${добавлено}`);
    if (!общие.безФоновогоРазбора) {
      обработатьОчередь(ид, клиент, общие).catch((e) =>
        console.log(new Date().toISOString(), `[разбор ${ид}] оборвался: ${e.message}`));
    }
  } catch (e) {
    журнал.push(`очередь разбора не записана: ${e.message}`);
  }

  журнал.push(JSON.stringify(сводка));

  return { ok: true, сообщения, алертВладельцу, сводка, журнал };
}

/**
 * Находит сохранённый адрес карточки по реестровому номеру.
 *
 * Нужна, когда расчёт запускают кнопкой из Telegram: оттуда приходит только
 * номер, а портал по номеру не ищет. Адрес был сохранён при обнаружении
 * тендера — см. комментарий в найтиТендеры.
 *
 * @returns {string|null} адрес или null, если тендер этому клиенту не слали
 */
function ссылкаПоНомеру(номер, клиент, общие = {}) {
  const состояние = прочитатьСостояние(путьСостояния(клиент, общие));
  const url = (состояние.ссылки || {})[String(номер).trim()];
  // Клиенту не показывали - из общего архива и потока (только публичные
  // карточки портала).
  return url || (общие.безАрхива ? null : (require('./archive').адресПоНомеру(номер) || {}).url) || null;
}

/** Адрес страницы документов, сохранённый при обнаружении тендера. */
function документыПоНомеру(номер, клиент, общие = {}) {
  const состояние = прочитатьСостояние(путьСостояния(клиент, общие));
  return (состояние.документы || {})[String(номер).trim()]
    || (общие.безАрхива ? '' : (require('./archive').адресПоНомеру(номер) || {}).docsUrl) || '';
}

/**
 * Сколько всего закупок нашёл портал по запросу - подпись над выдачей
 * («более 15 000 записей», «23 записи»). Мы читаем только первые страницы,
 * поэтому число карточек и число на портале - разные вещи. Нет подписи - null.
 */
function всегоНаПортале(html) {
  const м = /search-results__total[^>]*>([\s\S]{0,300}?)<\/div>/.exec(String(html || ''));
  if (!м) return null;
  const т = м[1].replace(/<[^>]+>/g, ' ').replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();
  const ч = /(более\s+)?(\d[\d\s]*)\s+запис/i.exec(т);
  return ч ? (ч[1] ? 'более ' : '') + ч[2].trim() : null;
}

/**
 * Проверка слов до сохранения настроек (сайт, 22.10.2026): по каждой фразе
 * первая страница выдачи и тот же отбор, что в ежедневном поиске. Ничего не
 * записывает. Не больше 8 фраз - каждая фраза один запрос к порталу.
 *
 * @param {{слова: string[], стопСлова?: string[], законы?: string[], ценаОт?: number, ценаДо?: number}} п
 * @param {{взять?: Function, пауза?: number}} [опции] для проверок
 */
async function предпросмотрПоиска(п = {}, опции = {}) {
  const { основыФраз } = require('./site-api');
  const взять = опции.взять || взятьТекст;
  const пауза = опции.пауза ?? 1500;
  const слова = [...new Set((п.слова || []).map((с) => String(с).trim()).filter(Boolean))].slice(0, 8);
  if (!слова.length) return { ok: false, сбой: 'нет слов для проверки' };
  const фильтр = {
    keywords: основыФраз(слова), phrases: слова, stopWords: п.стопСлова || [],
    ...((п.окпд || []).length ? { okpd: п.окпд } : {}),
    ...(Number(п.ценаОт) > 0 ? { minPrice: Number(п.ценаОт) } : {}),
    ...(Number(п.ценаДо) > 0 ? { maxPrice: Number(п.ценаДо) } : {}),
    ...((п.законы || []).length ? { laws: п.законы } : {})
  };
  const сегодня = new Date().toISOString().slice(0, 10);
  const итог = [];
  const всеПрошли = new Map();
  let отказов = 0;
  for (let i = 0; i < слова.length; i++) {
    if (i) await new Promise((ok) => setTimeout(ok, пауза));
    const r = await взять(адресПоиска(слова[i], {}, 1));
    if (!r.ok || String(r.тело).length < 2000) { отказов++; итог.push({ слово: слова[i], портал: 'нет ответа', прошло: 0 }); continue; }
    const живые = parseSearchPage(r.тело).filter((t) => !t.deadline || String(t.deadline).slice(0, 10) >= сегодня);
    const { passed } = applyFilters(живые, фильтр);
    for (const t of passed) всеПрошли.set(t.number, t);
    итог.push({ слово: слова[i], всего: всегоНаПортале(r.тело), портал: живые.length, прошло: passed.length });
  }
  if (отказов === слова.length) return { ok: false, сбой: 'портал закупок не ответил' };
  const примеры = [...всеПрошли.values()].slice(0, 3).map((t) => String(t.object || '').slice(0, 90));
  return { ok: true, всего: всеПрошли.size, слова: итог, примеры };
}

