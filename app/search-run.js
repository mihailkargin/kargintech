/**
 * Поиск тендеров по настройкам клиента.
 *
 * ОРКЕСТРАТОР: знает порядок шагов, логика — в модулях из src/.
 *
 *   1. запросы к порталу по каждому слову  -> parser.js
 *   2. отбор по словам, стоп-словам, цене  -> filter.js
 *   3. что из этого новое или изменилось   -> dedup.js
 *   4. расчёт выгоды и приоритета          -> scoring.js
 *   5. сводка и подробные сообщения        -> notify.js
 *
 * СОСТОЯНИЕ. Раньше список уже показанных тендеров хранился внутри n8n.
 * Теперь он в файле на томе — переживает перезапуск контейнера и попадает
 * в резервную копию вместе с остальными данными.
 *
 * Потеря состояния не ломает систему, но означает, что клиент получит заново
 * все подходящие тендеры разом. Это неприятно, но не опасно — в отличие
 * от обратного случая, когда состояние «слиплось» и новый тендер считается
 * виденным.
 */
