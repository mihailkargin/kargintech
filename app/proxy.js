/**
 * Запрос через зарубежного посредника — единственный путь к Claude API.
 *
 * ЗАЧЕМ. Anthropic не отвечает на российские адреса, а портал закупок —
 * на зарубежные. Поэтому схема двухсерверная: вся работа на российском VPS,
 * а для вызовов модели стоит минимальный сервер в Сингапуре с посредником.
 *
 * ПОЧЕМУ НЕ ПЕРЕМЕННЫЕ HTTP_PROXY. Они подействовали бы на ВСЕ запросы сразу,
 * включая опрос портала. Портал увидел бы зарубежный адрес и перестал
 * отвечать — то есть сломалась бы основная функция сервиса, а выглядело бы
 * это как «портал недоступен». Поэтому посредник указывается только здесь,
 * в одном месте, и только для обращений к модели.
 *
 * ПОЧЕМУ СВОЙ КОД, А НЕ ГОТОВАЯ БИБЛИОТЕКА. У проекта нет ни одной внешней
 * зависимости — нечему устаревать и ломаться из-за чужого обновления.
 * Встроенный fetch в Node работать через посредника не умеет, поэтому
 * туннель до него открывается вручную: это полсотни строк и полная
 * предсказуемость.
 *
 * КАК ЭТО РАБОТАЕТ. Посреднику отправляется CONNECT — просьба соединить нас
 * с api.anthropic.com. Он соединяет и дальше просто перекладывает байты.
 * Содержимое запроса он не видит: шифрование сквозное, от нас до Anthropic.
 * Это важно для продажи: даже наш собственный сервер в Сингапуре не может
 * прочитать то, что уходит в модель.
 */
const http = require('http');
const https = require('https');
const tls = require('tls');

/** Разбор адреса посредника вида http://логин:пароль@сервер:8888 */
function разобратьПосредника(url) {
  const m = String(url || '').match(/^http:\/\/(?:([^:@]+):([^@]*)@)?([^:/]+):(\d+)/);
  if (!m) return null;
  return { логин: m[1] || '', пароль: m[2] || '', узел: m[3], порт: Number(m[4]) };
}

/**
 * Открывает туннель до нужного узла через посредника.
 *
 * @returns {Promise<{ok: boolean, сокет?: object, ошибка?: string}>}
 */
function открытьТуннель(посредник, узел, порт, мс) {
  return new Promise((готово) => {
    const заголовки = { Host: `${узел}:${порт}` };
    if (посредник.логин) {
      const пара = Buffer.from(`${посредник.логин}:${посредник.пароль}`).toString('base64');
      заголовки['Proxy-Authorization'] = `Basic ${пара}`;
    }

    const req = http.request({
      host: посредник.узел,
      port: посредник.порт,
      method: 'CONNECT',
      path: `${узел}:${порт}`,
      headers: заголовки,
      timeout: мс
    });

    req.on('connect', (res, сокет) => {
      if (res.statusCode !== 200) {
        сокет.destroy();
        // 407 — посредник не принял пароль. Самая частая причина: пароль
        // в настройках разошёлся с тем, что лежит на зарубежном сервере.
        готово({
          ok: false,
          ошибка: res.statusCode === 407
            ? 'посредник не принял пароль (код 407) — сверить адрес в настройках с тем, что на сервере'
            : `посредник отказал, код ${res.statusCode}`
        });
        return;
      }
      готово({ ok: true, сокет });
    });

    req.on('error', (e) => готово({ ok: false, ошибка: `посредник недоступен: ${e.message}` }));
    req.on('timeout', () => {
      req.destroy();
      готово({ ok: false, ошибка: `посредник не ответил за ${Math.round(мс / 1000)} с` });
    });

    req.end();
  });
}

/**
 * Запрос к защищённому адресу через посредника.
 *
 * Возвращает то же, что app/http.js: отказ приходит полем ok, исключений нет.
 *
 * @param {string} url полный адрес, обязательно https
 * @param {object} опции {метод, тело, заголовки, мс, посредник}
 */
function взятьЧерезПосредника(url, опции = {}) {
  return new Promise(async (готово) => {
    const мс = опции.мс || 180000;

    const адрес = String(url).match(/^https:\/\/([^:/?#]+)(?::(\d+))?([^?#]*(?:\?[^#]*)?)/);
    if (!адрес) { готово({ ok: false, код: 0, ошибка: 'разобран только https-адрес' }); return; }
    const узел = адрес[1];
    const порт = адрес[2] ? Number(адрес[2]) : 443;
    const путь = адрес[3] || '/';

    const посредник = разобратьПосредника(опции.посредник);
    if (!посредник) {
      готово({ ok: false, код: 0, ошибка: 'адрес посредника не разобран — ожидается http://логин:пароль@сервер:порт' });
      return;
    }

    const туннель = await открытьТуннель(посредник, узел, порт, мс);
    if (!туннель.ok) { готово({ ok: false, код: 0, ошибка: туннель.ошибка }); return; }

    // Поверх туннеля поднимаем обычное защищённое соединение прямо
    // с api.anthropic.com. Проверка сертификата НЕ отключается: посредник
    // перекладывает байты и содержимое не видит, подменить его он не может.
    const тело = опции.тело || null;
    const заголовки = { Host: узел, Connection: 'close', ...(опции.заголовки || {}) };
    if (тело) заголовки['Content-Length'] = Buffer.byteLength(тело);

    const req = https.request({
      socket: туннель.сокет,
      servername: узел,
      method: опции.метод || 'GET',
      path: путь,
      headers: заголовки,
      timeout: мс,
      agent: false
    }, (res) => {
      const куски = [];
      res.on('data', (c) => куски.push(c));
      res.on('end', () => готово({
        ok: res.statusCode >= 200 && res.statusCode < 300,
        код: res.statusCode,
        тело: Buffer.concat(куски),
        заголовки: res.headers
      }));
      res.on('error', (e) => готово({ ok: false, код: res.statusCode, ошибка: e.message }));
    });

    req.on('error', (e) => готово({ ok: false, код: 0, ошибка: e.message }));
    req.on('timeout', () => {
      req.destroy();
      готово({ ok: false, код: 0, ошибка: `ответ не пришёл за ${Math.round(мс / 1000)} с` });
    });

    if (тело) req.write(тело);
    req.end();
  });
}

module.exports = { взятьЧерезПосредника, разобратьПосредника };
