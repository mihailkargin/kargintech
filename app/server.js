// ПОЛНЫЙ ПОТОК ЗАКУПОК (app/stream.js, 23.10.2026): каждые 10 минут - свежее
// сверху до уже известного; с 01:00 до 05:59 МСК - ещё и добор вглубь.
// Отказ портала 403/429 - поток молчит 6 часов. Выключается STREAM=off.
let потокИдёт = false;
let потокМолчитДо = 0;
async function шагПотока() {
  if (потокИдёт || Date.now() < потокМолчитДо || process.env.STREAM === 'off') return;
  потокИдёт = true;
  try {
    const поток = require('./stream');
    const { адресПоиска } = require('./search-run');
    const { взятьТекст } = require('./http');
    const { parseSearchPage } = require(path.join(__dirname, '..', 'src', 'parser'));
    const общие = общиеНастройки();
    const файл = path.join(общие.каталогДанных || '/data/state', 'archive.db');
    const { всегоНаПортале } = require('./search-run');
    const адрес = (стр) => адресПоиска('', { записейНаСтраницу: поток.НА_СТРАНИЦЕ }, стр);
    const дата = (д) => д.split('-').reverse().join('.');
    const адресСреза = (с, стр) => {
      let u = адрес(стр);
      if (с.закон === '44') u = u.replace('&fz223=on', '');
      if (с.закон === '223') u = u.replace('fz44=on&', '');
      u += `&publishDateFrom=${дата(с.день)}&publishDateTo=${дата(с.день)}`;
      if (с.от !== null) u += `&priceFromGeneral=${с.от}`;
      if (с.до !== null) u += `&priceToGeneral=${с.до}`;
      return u;
    };
    const база = { взять: взятьТекст, разобрать: parseSearchPage, адрес, адресСреза, всего: всегоНаПортале, файл,
      вАрхив: (к) => require('./archive').записатьВыдачу(к, '', файл) };
    const журнал = [];
    const r = await поток.прогон({ ...база, режим: 'свежее', страниц: 20, журнал });
    let итог = `поток: свежее - запросов ${r.запросов}, новых ${r.новых}, обновлено ${r.обновлено}`;
    if (!r.отказ && new Date(Date.now() + 3 * 3600000).getUTCHours() < 6) {
      const д = await поток.прогон({ ...база, режим: 'добор', страниц: 30, журнал });
      итог += `; добор - запросов ${д.запросов}, новых ${д.новых}, срезов осталось ${д.хвост}`;
      печататьЖурнал(журнал.filter((с) => /делим|делить|закончен|отказал|не получен/.test(с)));
      if (д.отказ) r.отказ = д.отказ;
    }
    if (r.отказ) { потокМолчитДо = Date.now() + 6 * 3600000; итог += ` - ОТКАЗ ПОРТАЛА ${r.отказ}, поток молчит 6 часов`; }
    лог(итог);
  } catch (e) {
    лог('поток: сбой -', e.message);
  } finally {
    потокИдёт = false;
  }
}
setTimeout(шагПотока, 60 * 1000);
setInterval(шагПотока, 10 * 60 * 1000);

// ВОЗОБНОВЛЕНИЕ ОЧЕРЕДЕЙ РАЗБОРА (24.10.2026). Разбор запускался только после
// поиска: пересоздание контейнера (выкатка) останавливало очередь до утреннего
// поиска - у компании владельца так встали 2 321 закупка. Через 3 минуты после
// запуска и каждые 30 минут - очередь каждого клиента с непустой очередью.
// ОДНА ОЧЕРЕДЬ ЗА РАЗ: пять очередей сразу упирались в общий предел app/http.js
// (запрос в 1,5 с ≈ 2 400 в час) - темп, при котором портал отказывал 05.10.2026.
// Пока идёт любая очередь, новая не запускается. По кругу: 20 закупок клиента,
// затем следующий - 3 закупки Жени не ждут, пока разберутся 2 300 владельца.
// Клиенты сайта - в круге первыми, старые клиенты n8n - после них.
let последнийКлиент = '';
function возобновитьОчереди() {
  try {
    const { состояние, обработатьОчередь } = require('./parse-queue');
    const каталог = process.env.CLIENTS_DIR || '/data/clients';
    const ид = fs.readdirSync(каталог)
      .map((ф) => (/^([A-Za-z0-9_-]+)\.json$/.exec(ф) || [])[1]).filter(Boolean)
      .sort((a, b) => Number(!a.startsWith('site-')) - Number(!b.startsWith('site-')) || a.localeCompare(b));
    if (ид.some((x) => состояние(x).идёт)) return;
    // Клиенты сайта - пока у них есть очередь, старые клиенты n8n ждут: вся
    // пропускная способность (≈ 60 закупок в час) - тем, кто смотрит ленту.
    const всеЖдут = ид.filter((x) => состояние(x).очередь.length && настройкиКлиента(x));
    const сайта = всеЖдут.filter((x) => x.startsWith('site-'));
    const ждут = сайта.length ? сайта : всеЖдут;
    if (!ждут.length) return;
    // Следующий после прошлого по кругу; прошлый уже без очереди - первый ждущий.
    const кто = ждут[(ждут.indexOf(последнийКлиент) + 1) % ждут.length];
    последнийКлиент = кто;
    лог(`разбор ${кто}: возобновлён, в очереди ${состояние(кто).очередь.length}`);
    обработатьОчередь(кто, { ...настройкиКлиента(кто), ид: кто }, общиеНастройки(), { предел: 20 })
      .then((r) => { лог(`разбор ${кто}: ${JSON.stringify(r)}`); if (r.запущен && !r.остановлен) setTimeout(возобновитьОчереди, 40 * 1000); })
      .catch((e) => лог(`разбор ${кто}: оборвался - ${e.message}`));
  } catch (e) {
    лог('возобновление очередей: сбой -', e.message);
  }
}
setTimeout(возобновитьОчереди, 3 * 60 * 1000);
setInterval(возобновитьОчереди, 30 * 60 * 1000);

