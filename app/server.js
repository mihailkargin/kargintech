function читатьТело(req, макс = МАКС_ТЕЛО) {
  return new Promise((ok, нет) => {
    const куски = [];
    let размер = 0;
    req.on('data', (c) => {
      размер += c.length;
      if (размер > макс) { нет(new Error('тело запроса слишком велико')); req.destroy(); return; }
      куски.push(c);
    });
    req.on('end', () => {
      const s = Buffer.concat(куски).toString('utf8');
      if (!s) { ok({}); return; }
      try { ok(JSON.parse(s)); } catch (e) { нет(new Error('тело запроса не разбирается как JSON')); }
    });
    req.on('error', нет);
  });
}

const сервер = http.createServer(async (req, res) => {
  const url = new URL(req.url, 'http://app');

  // Куда пришёл запрос. Сравнивать `url.pathname` с кириллической строкой
  // нельзя: он возвращает путь в закодированном виде, и совпадения не будет
  // никогда. Подробности — в заголовке app/routes.js.
  const куда = маршрут(req.url);

  // ЗАПИСЬ О ПРИХОДЕ ЗАПРОСА, А НЕ ТОЛЬКО О ЕГО ЗАВЕРШЕНИИ.
  //
  // До 09.10.2026 журнал писался только после окончания работы. Запрос,
  // который идёт пять минут или оборвался на середине, не оставлял следа
  // вовсе: в журнале была одна строка «приложение слушает порт». Диагностика
  // первого же отказа в бою уткнулась в пустой журнал.
  лог(`→ ${req.method} ${нормальныйПуть(req.url)}`
    + (куда ? '' : ' — НЕИЗВЕСТНАЯ ТОЧКА ВХОДА'));

  const отдать = (код, объект) => {
    // Длинное и среднее тире — дефисом во всём тексте ответа: отсюда n8n берёт
    // сообщения клиенту и алерты (требование владельца 20.10.2026). Base64
    // файла и адреса этих знаков не содержат.
    const тело = JSON.stringify(объект).replace(/[—–]/g, '-');
    res.writeHead(код, { 'Content-Type': 'application/json; charset=utf-8' });
    res.end(тело);
  };

  try {
    // --- Проверка живости ------------------------------------------------
    if (req.method === 'GET' && куда === ТОЧКИ.ЗДОРОВЬЕ) {
      const н = общиеНастройки();
      // Показываем состояние обоих условий поиска поставщиков. Без ключа
      // ИЛИ без посредника он молча пропускается — и выяснилось бы это
      // по пустой смете, а не сразу. Сам ключ и пароль не печатаются.
      отдать(200, {
        ok: true,
        конвертер: н.адресКонвертера,
        ключМодели: н.anthropicKey ? 'задан' : 'НЕ ЗАДАН',
        посредник: н.proxyUrl
          ? 'задан: ' + н.proxyUrl.replace(/\/\/[^@]*@/, '//***@')
          : 'НЕ ЗАДАН',
        поискПоставщиков: process.env.YANDEX_API_KEY && process.env.YANDEX_FOLDER_ID
          ? 'включён: Yandex Cloud'
          : ((н.anthropicKey && н.proxyUrl) ? 'включён: Anthropic' : 'ВЫКЛЮЧЕН')
      });
      return;
    }

    // --- Смета по одной закупке ------------------------------------------
    if (req.method === 'POST' && куда === ТОЧКИ.СМЕТА) {
      // Расчёт по загруженным документам (31.10.2026): файлы приходят в base64 -
      // до 30 МБ файлов плюс треть на кодирование.
      const тело = await читатьТело(req, 45 * 1024 * 1024);
      const клиент = тело.клиент ? (настройкиКлиента(тело.клиент) || {}) : {};
      const настройки = { ...общиеНастройки(), ...клиент, ...(тело.настройки || {}) };

      const закупка = { ...(тело.закупка || {}) };
      if (Array.isArray(тело.документы) && тело.документы.length) {
        закупка.файлы = тело.документы.slice(0, 20)
          .map((д) => ({ имя: String(д.имя || 'файл').slice(0, 200), данные: Buffer.from(String(д.base64 || ''), 'base64') }))
          .filter((д) => д.данные.length);
      }

      // Расчёт можно запустить двумя путями: передать ссылку целиком или
      // прислать только номер — так приходит нажатие кнопки в Telegram,
      // туда больше не помещается.
      //
      // По номеру портал не ищет (проверено 03.10.2026), поэтому адрес
      // берётся из того, что сохранили при обнаружении тендера.
      if (!закупка.ссылка && тело.номер && !закупка.файлы) {
        const найдена = ссылкаПоНомеру(тело.номер, тело.клиент, общиеНастройки());
        if (!найдена) {
          отдать(200, {
            ok: false,
            номер: тело.номер,
            сбой: 'адрес закупки не найден',
            подробно: `Тендер ${тело.номер} не числится среди отправленных этому клиенту. `
              + 'Адрес карточки сохраняется в момент обнаружения, восстановить его по номеру нельзя: '
              + 'портал по реестровому номеру не ищет. Пришлите ссылку на карточку целиком.'
          });
          return;
        }
        закупка.ссылка = найдена;
        // Адрес документов из выдачи — главный для 223-ФЗ (в нём noticeGuid).
        закупка.адресДокументов = закупка.адресДокументов
          || документыПоНомеру(тело.номер, тело.клиент, общиеНастройки());
      }

      const начало = Date.now();
      const r = await собратьСмету(закупка, настройки);
      лог(`смета ${r.номер}: ${r.ok ? 'готова' : 'сбой — ' + r.сбой} за ${Date.now() - начало} мс`);
      печататьЖурнал(r.журнал);

      if (!r.ok) {
        отдать(200, {
          ok: false, номер: r.номер, сбой: r.сбой, подробно: r.подробно, журнал: r.журнал
        });
        return;
      }

      // Файл отдаём в base64: n8n кладёт его во вложение сообщения.
      отдать(200, {
        ok: true,
        номер: r.номер,
        подпись: r.подпись,

        // ГОТОВАЯ ПОДПИСЬ К ФАЙЛУ, обрезанная безопасно для разметки.
        //
        // У подписи к файлу предел 1024 знака. 09.10.2026 нода воркфлоу резала
        // её по числу знаков и разорвала тег пополам: Telegram отказался
        // принять сообщение целиком, и клиент не получил ни текста, ни файла,
        // хотя расчёт был готов и оплачен.
        //
        // Обрезка перенесена сюда, под проверки. В ноде воркфлоу код не попадает
        // ни в тесты, ни в историю правок.
        подписьФайла: подписьДляФайла(r.подпись),
        файл: { имя: r.файл.имя, base64: r.файл.данные.toString('base64') },
        итоги: r.итоги,
        позиций: r.estimate.rows.length,
        сЦеной: r.estimate.pricedCount,
        полная: r.estimate.complete,
        нечитаемые: r.нечитаемые,
        проблемы: r.проблемы,
        журнал: r.журнал
      });
      return;
    }

    // --- Рейтинг по готовым разборам --------------------------------------
    // Вызывается n8n вторым расписанием, когда фоновый разбор прошёл очередь.
    // Адреса чатов отдаются всегда — по той же причине, что у поиска.
    if (req.method === 'POST' && куда === ТОЧКИ.РЕЙТИНГ) {
      const тело = await читатьТело(req);
      const общие = общиеНастройки();
      const изФайла = тело.клиент ? настройкиКлиента(тело.клиент) : null;
      const адреса = {
        clientChatId: (изФайла && изФайла.clientChatId) || '',
        ownerChatId: (изФайла && изФайла.ownerChatId) || общие.ownerChatIdЗапасной || ''
      };
      if (!изФайла) {
        отдать(200, { ok: false, ...адреса, сбой: `настройки клиента «${тело.клиент || '—'}» не прочитаны` });
        return;
      }
      const r = собратьРейтинг(тело.клиент, изФайла, общие);
      лог(r.журнал.join('; '));
      отдать(200, { ...r, ...адреса });
      return;
    }

    // --- Для сайта: лента и настройки клиента (21.10.2026) -----------------
    if (req.method === 'POST' && куда === ТОЧКИ.ЛЕНТА) {
      const тело = await читатьТело(req);
      отдать(200, лентаКлиента(тело.клиент));
      return;
    }
    // Поставщики по нише: «прочитать» - для страницы сайта; запуск поиска (стоит
    // денег на модель) - только с явным лимитом расхода, его задаёт владелец.
    if (req.method === 'POST' && куда === ТОЧКИ.ПОСТАВЩИКИ_НИШИ) {
      const тело = await читатьТело(req);
      const r = await require('./niche-suppliers').поставщикиНиши(String(тело.клиент || ''), {
        толькоПрочитать: тело.запустить !== true, лимитДолл: тело.лимитДолл, товаров: тело.товаров
      });
      if (тело.запустить === true) лог(`поставщики по нише ${тело.клиент}: ${r.ok ? `товаров ${r.товары.length}; ${r.стоимость}` : r.сбой}`);
      отдать(200, тело.запустить === true ? r : { ...r, журнал: undefined });
      return;
    }
    if (req.method === 'POST' && куда === ТОЧКИ.ПРОШЛЫЙ) {
      const тело = await читатьТело(req);
      if (!/^site-[a-z0-9]{6,40}$/.test(String(тело.клиент || ''))) { отдать(400, { ok: false, сбой: 'не клиент сайта' }); return; }
      const r = await require('./past-tender').разборПрошлого(String(тело.клиент), String(тело.номер || ''));
      лог(`разбор прошлого тендера ${тело.номер}: ${r.ok ? r.вывод : r.сбой}`);
      отдать(200, r);
      return;
    }
    if (req.method === 'POST' && куда === ТОЧКИ.НИША) {
      const тело = await читатьТело(req);
      отдать(200, require('./niche-run').отчётНиши(тело.клиент));
      return;
    }
    if (req.method === 'POST' && куда === ТОЧКИ.ПОСТАВЩИКИ) {
      const тело = await читатьТело(req);
      отдать(200, поставщикиПоЗакупкам(тело.номера));
      return;
    }
    if (req.method === 'POST' && (куда === ТОЧКИ.КП_ОТПРАВИТЬ || куда === ТОЧКИ.КП_ОТВЕТЫ || куда === ТОЧКИ.КП_СОСТОЯНИЕ)) {
      const тело = await читатьТело(req);
      const КП = require('./kp-run');
      if (куда === ТОЧКИ.КП_СОСТОЯНИЕ) { отдать(200, { ok: true, кп: КП.состояниеКП(тело.номера) }); return; }
      // Рассылка и чтение ящика - по одному: два параллельных прогона
      // разослали бы одной компании два письма.
      if (кпИдёт) { отдать(200, { ok: false, сбой: 'почта уже обрабатывается' }); return; }
      кпИдёт = true;
      try {
        const r = куда === ТОЧКИ.КП_ОТПРАВИТЬ
          ? await КП.разослать(String(тело.номер || ''), { клиент: String(тело.клиент || '') })
          : await КП.собратьОтветы();
        лог(`запросы КП ${куда === ТОЧКИ.КП_ОТПРАВИТЬ ? `по ${тело.номер}: отправлено ${r.отправлено}` : `: ответов ${r.ответов}`}${r.ok ? '' : ' - ' + r.сбой}`);
        отдать(200, r);
      } finally {
        кпИдёт = false;
      }
      return;
    }
    // Самопроверка сервиса (сайт зовёт раз в час, 22.10.2026): портал одним
    // лёгким запросом, конвертер, сервис таблиц, свободное место. Каждая
    // беда - своей строкой; сайт шлёт владельцу сигнал.
    if (req.method === 'POST' && куда === ТОЧКИ.САМОПРОВЕРКА) {
      const н = общиеНастройки();
      const беды = [];
      const жив = async (имя, адрес) => {
        const r = await взять(адрес, { мс: 20000 });
        if (!r.ok) беды.push(`${имя} не отвечает (${r.ошибка || 'код ' + r.код})`);
      };
      await жив('конвертер документов', `${String(н.адресКонвертера).replace(/\/+$/, '')}/health`);
      await жив('сервис таблиц со сканов', `${process.env.TABLES_URL || 'http://tables:3001'}/health`);
      // Портал - только по просьбе (сайт спрашивает раз в 15 минут), свои
      // сервисы - при каждой самопроверке (раз в 2 минуты): лишние запросы
      // к порталу стоят нам доступа, свои - ничего.
      const тело = await читатьТело(req).catch(() => ({}));
      if (тело.портал !== false) {
        const п = await взятьТекст('https://zakupki.gov.ru/epz/main/public/home.html');
        if (!п.ok) беды.push(`портал закупок не отвечает (${п.ошибка || 'код ' + п.код})${п.подсказка ? ' - ' + п.подсказка : ''}`);
      }
      try {
        const с = require('fs').statfsSync('/data');
        const свободно = (с.bavail * с.bsize) / 1e9;
        if (свободно < 3) беды.push(`на диске осталось ${свободно.toFixed(1)} ГБ`);
      } catch (e) { /* statfs нет в старом Node - пропускаем */ }
      // Полный поток молча встал - лента клиентов перестаёт расти, и никто не
      // узнает. Свежее обновляется каждые 10 минут; 40 минут тишины - беда.
      if (process.env.STREAM !== 'off') {
        try {
          const с = require('./stream').сводка(path.join(н.каталогДанных || '/data/state', 'archive.db'));
          const минут = с.последнийСвежий ? Math.round((Date.now() - Date.parse(с.последнийСвежий)) / 60000) : null;
          if (минут === null || минут > 40) беды.push(`полный поток закупок не обновлялся ${минут === null ? 'ни разу' : минут + ' мин'}${потокМолчитДо > Date.now() ? ' (портал отказал, пауза 6 часов)' : ''}`);
        } catch (e) { беды.push(`полный поток закупок недоступен (${e.message})`); }
      }
      // Ночная резервная копия (deploy/backup.sh, 04:15) пишет отметку
      // state/backup-ok только при успехе. Старше 26 часов - копия не сделалась:
      // 10 ночей подряд в октябре она падала молча (19.10.2026).
      try {
        const когда = Date.parse(String(require('fs').readFileSync(path.join(н.каталогДанных || '/data/state', 'backup-ok'), 'utf8')).trim());
        const часов = Number.isFinite(когда) ? Math.round((Date.now() - когда) / 3600000) : null;
        if (часов === null || часов > 26) беды.push(`ночная резервная копия не делалась ${часов === null ? '(отметка не читается)' : часов + ' ч'} - смотрите ~/backup.log на сервере`);
      } catch (e) { беды.push('ночная резервная копия: отметки об успехе нет - смотрите ~/backup.log на сервере'); }
      // Копия ВНЕ сервера (deploy/backup-offsite.sh, 02.11.2026): авария Beget
      // показала, что копия на том же диске от потери сервера не защищает.
      try {
        const когда = Date.parse(String(require('fs').readFileSync(path.join(н.каталогДанных || '/data/state', 'backup-offsite-ok'), 'utf8')).trim());
        const часов = Number.isFinite(когда) ? Math.round((Date.now() - когда) / 3600000) : null;
        if (часов === null || часов > 26) беды.push(`копия вне сервера не делалась ${часов === null ? '(отметка не читается)' : часов + ' ч'} - данные клиентов только на этом сервере, смотрите ~/backup.log`);
      } catch (e) { беды.push('копии вне сервера нет ни одной - данные клиентов только на этом сервере (deploy/backup-offsite.sh не настроен)'); }
      // Чат владельца для сигналов сайта: тот же, что у алертов приложения
      // (OWNER_CHAT_ID или ownerChatId клиента kargin). Сайт свой диск, этот
      // файл ему не виден. Отдаётся только внутри docker-сети.
      let чатВладельца = String(process.env.OWNER_CHAT_ID || '').trim();
      if (!чатВладельца) { try { чатВладельца = String((настройкиКлиента('kargin') || {}).ownerChatId || '').trim(); } catch (e) { /* нет файла */ } }
      отдать(200, { ok: беды.length === 0, беды, чатВладельца: /^-?\d{1,20}$/.test(чатВладельца) ? чатВладельца : null });
      return;
    }
    if (куда === ТОЧКИ.ПОТОК) {
      отдать(200, { ...require('./stream').сводка(path.join(общиеНастройки().каталогДанных || '/data/state', 'archive.db')), идёт: потокИдёт });
      return;
    }
    if (куда === ТОЧКИ.АРХИВ) {
      отдать(200, require('./archive').сводкаАрхива(path.join(общиеНастройки().каталогДанных || '/data/state', 'archive.db')));
      return;
    }
    if (req.method === 'POST' && куда === ТОЧКИ.ПОХОЖИЕ) {
      const тело = await читатьТело(req);
      if (!/^site-[a-z0-9]{6,40}$/.test(String(тело.клиент || ''))) { отдать(400, { ok: false, сбой: 'не клиент сайта' }); return; }
      отдать(200, require('./site-api').похожиеДляТендера(String(тело.клиент), String(тело.номер || '')));
      return;
    }
    if (req.method === 'POST' && куда === ТОЧКИ.ПРОВЕРКА_СЛОВ) {
      const тело = await читатьТело(req);
      const r = await require('./search-run').предпросмотрПоиска(тело);
      лог(`проверка слов: ${r.ok ? `слов ${r.слова.length}, закупок ${r.всего}` : r.сбой}`);
      отдать(200, r);
      return;
    }
    if (req.method === 'POST' && куда === ТОЧКИ.ПИСЬМО_СБРОСА) {
      // Текст письма собирается здесь, от сайта приходят только адрес и
      // ссылка, и ссылка обязана вести на страницу смены пароля нашего сайта:
      // через эту точку нельзя отправить произвольное письмо.
      const тело = await читатьТело(req);
      const ссылка = String(тело.ссылка || '');
      if (!/^https:\/\/(www\.)?kargintech\.ru\/reset\/[a-f0-9]{64}$/.test(ссылка)) { отдать(400, { ok: false, сбой: 'ссылка не на страницу смены пароля' }); return; }
      const почта = require('./mail');
      const r = await почта.отправить(почта.настройкиПочты(), {
        кому: String(тело.почта || ''),
        тема: 'KarginTech: восстановление пароля',
        текст: [
          'Здравствуйте.',
          '',
          'Для вашей учётной записи на kargintech.ru запрошено восстановление пароля.',
          'Задать новый пароль можно по ссылке (действует 1 час, однократно):',
          ссылка,
          '',
          'Если вы не запрашивали восстановление, проигнорируйте это письмо: пароль останется прежним.',
          '',
          'KarginTech'
        ].join('\n')
      });
      лог(`письмо восстановления пароля: ${r.ok ? 'отправлено' : r.сбой}`);
      отдать(200, { ok: r.ok, сбой: r.ok ? undefined : r.сбой });
      return;
    }
    if (req.method === 'POST' && куда === ТОЧКИ.ПРОТОКОЛЫ) {
      // Сбор прошлых закупок под нишу клиента сайта (шанс на победу, Макс).
      // Один прогон - не больше 80 запросов к порталу с паузой 3 с; сайт
      // зовёт это ночью и по одному слову. Одновременно - только один сбор.
      const тело = await читатьТело(req);
      const слово = String(тело.слово || '').trim().toLowerCase();
      if (!/^[а-яёa-z0-9 -]{3,40}$/i.test(слово)) { отдать(200, { ok: false, сбой: 'слово для сбора не подходит' }); return; }
      if (сборИдёт) { отдать(200, { ok: false, сбой: 'сбор уже идёт' }); return; }
      сборИдёт = true;
      try {
        const { собрать, путьФайла } = require('./collect-protocols');
        const счёт = () => { try { return (JSON.parse(fs.readFileSync(путьФайла(слово), 'utf8')).наблюдения || []).length; } catch (e) { return 0; } };
        const было = счёт();
        await собрать(слово, 1);
        отдать(200, { ok: true, слово, было, стало: счёт() });
      } catch (e) {
        отдать(200, { ok: false, сбой: e.message });
      } finally {
        сборИдёт = false;
      }
      return;
    }
    if (req.method === 'POST' && куда === ТОЧКИ.ПРАЙС) {
      // Файл приходит в base64: предел тела - 10 МБ файла плюс треть на кодирование.
      const тело = await читатьТело(req, 14 * 1024 * 1024);
      const r = сохранитьПрайсСайта(тело.клиент, тело.имя, Buffer.from(String(тело.base64 || ''), 'base64'));
      лог(`прайс клиента сайта ${тело.клиент}: ${r.ok ? `принят, позиций ${r.позиций}` : 'отказ - ' + r.сбой}`);
      отдать(200, r);
      return;
    }
    if (req.method === 'POST' && куда === ТОЧКИ.НАСТРОЙКИ) {
      const тело = await читатьТело(req);
      const r = записатьНастройкиСайта(тело.клиент, тело.поля || {});
      лог(`настройки клиента сайта ${тело.клиент}: ${r.ok ? 'записаны' : 'отказ - ' + r.сбой}`);
      отдать(200, r);
      return;
    }

    // --- Поиск тендеров ---------------------------------------------------
    if (req.method === 'POST' && куда === ТОЧКИ.ПОИСК) {
      const тело = await читатьТело(req);
      const общие = общиеНастройки();
      const изФайла = тело.клиент ? настройкиКлиента(тело.клиент) : null;
      // `ид` — латинское имя клиента из запроса, оно же имя файла настроек.
      // По нему же называется файл состояния: кнопка «Рассчитать» ищет
      // сохранённую ссылку по `тело.клиент`. До 16.10.2026 поиск писал
      // состояние по русскому «имени» из файла, и кнопка искала не в том файле.
      const клиент = { имя: тело.клиент, ...(изФайла || {}), ...(тело.настройки || {}),
        ид: тело.клиент };

      // АДРЕСА ЧАТОВ ОТДАЮТСЯ В ОТВЕТЕ, И ВСЕГДА — ДАЖЕ ПРИ СБОЕ.
      //
      // До 07.10.2026 адреса брались из ноды «Настройки клиента» внутри
      // воркфлоу, а она же перебивала файл целиком. Владелец правил бы файл
      // и не видел результата — тихая ошибка. Теперь единственный источник
      // настроек это файл, а нода знает только имя клиента.
      //
      // При сбое адреса нужны больше, чем при успехе: именно тогда владельцу
      // уходит алерт. Поэтому они кладутся в ответ до всякой работы.
      const адреса = {
        clientChatId: клиент.clientChatId || '',
        ownerChatId: клиент.ownerChatId || общие.ownerChatIdЗапасной || ''
      };

      // ПРОПАВШИЙ ФАЙЛ КЛИЕНТА — ЭТО СБОЙ С ИМЕНЕМ, А НЕ «ТЕНДЕРОВ НЕТ».
      // Без него не окажется ни слов для поиска, ни адресов, и прогон молча
      // не сделает ничего. Причина называется вместе с путём к файлу.
      if (тело.клиент && !изФайла && !(тело.настройки && тело.настройки.searchWords)) {
        лог(`поиск для «${тело.клиент}»: файл настроек не прочитан`);
        отдать(200, {
          ok: false,
          ...адреса,
          сбой: `настройки клиента «${тело.клиент}» не прочитаны`,
          подробно: `Файл ${process.env.CLIENTS_DIR || '/data/clients'}/${тело.клиент}.json `
            + 'не найден или в нём ошибка JSON. Пока он не починен, поиск не идёт: '
            + 'без списка слов система не знает, что искать. '
            + 'Образец состава — deploy/clients/client-example.json'
        });
        return;
      }

      const начало = Date.now();
      const r = await найтиТендеры(клиент, общие);
      лог(`поиск для «${клиент.имя || '—'}»: ${r.ok ? JSON.stringify(r.сводка) : 'сбой — ' + r.сбой} `
        + `за ${Date.now() - начало} мс`);
      печататьЖурнал(r.журнал);

      отдать(200, { ...r, ...адреса });
      return;
    }

    отдать(404, { ok: false, issue: 'принимаются: ' + ПЕРЕЧЕНЬ });
  } catch (e) {
    лог('ОШИБКА обработки:', e.message);
    отдать(500, { ok: false, issue: e.message });
  }
});

