/**
 * Диагностика страниц результатов закупки — что на них реально написано.
 *
 * ЗАПУСКАТЬ НА РОССИЙСКОМ СЕРВЕРЕ:
 *
 *   docker compose exec -T app node app/diagnose-protocol.js --слово "бумага" \
 *     --номера "0322200001326000183,0117100015526000101"
 *
 * ЗАЧЕМ. Первый сбор 05.10.2026 дал два вопроса, на которые нельзя ответить
 * догадкой:
 *
 *   1. 36 закупок из 50 отброшены — не найдена цена победы. Это либо закупки,
 *      которые не состоялись (штатный исход), либо страницы, с которыми не
 *      справился разбор (ошибка в коде). Различить можно только посмотрев.
 *
 *   2. Снижения 89,9%, 81,6%, 76,3% на бумаге неправдоподобны. Самое вероятное
 *      объяснение — закупки с ценой за единицу товара (ч. 24 ст. 42): там НМЦК
 *      это максимальное значение цены контракта, а участник подаёт цену за
 *      единицу. Сравнивать их напрямую нельзя — получается фиктивное снижение.
 *
 * Печатается всё, что нужно для решения: пары «подпись → значение», шапки и
 * строки таблиц, найденные признаки несостоявшейся закупки и признаки цены за
 * единицу. Сами страницы не сохраняются — они большие, а решение принимается
 * по этим полям.
 *
 * По реестровому номеру портал не ищет (проверено 03.10.2026), поэтому нужное
 * слово обязательно: закупки находятся обычным поиском, затем из выдачи берутся
 * указанные номера.
 */
const { взятьТекст } = require('./http');
const { parseSearchPage } = require('../src/parser');
const {
  parseSupplierResults, parseBidList, наблюдение,
  адресРезультатов, адресСпискаЗаявок, ссылкиНаПротоколы,
  шапкиТаблиц, строкиТаблиц, таблицы,
  признакиНесостоявшейся, признакиЕдинственнойЗаявки
} = require('../src/protocol-page');
const { пары, СХЕМЫ } = require('../src/notice-page');
// Адрес выдачи берётся у сборщика, а не пишется здесь заново. Здесь стояла своя
// копия с `af=off&ca=off&pc=on&pa=off` — та самая сломанная, из-за которой в
// выборку попадали закупки, ещё принимающие заявки. Сборщик её починил, а
// диагностика осталась с прежней, то есть смотрела не на то, что работает в бою.
const { адресЗавершённых } = require('./collect-protocols');

const ждать = (мс) => new Promise((ok) => setTimeout(ok, мс));

/**
 * Признаки закупки с ценой за единицу товара.
 *
 * Такая закупка объявляется, когда заказчик не знает объём заранее (ч. 24
 * ст. 42). НМЦК в ней — максимальное значение цены контракта, а предложение
 * участника — цена за единицу. Разность между ними снижением не является.
 */
function признакиЦеныЗаЕдиницу(текст) {
  const низ = String(текст || '').toLowerCase();
  const найдено = [];
  if (/цена\s+единиц/.test(низ)) найдено.push('«цена единицы»');
  if (/максимальное\s+значение\s+цены/.test(низ)) найдено.push('«максимальное значение цены контракта»');
  if (/за\s+единицу\s+товар/.test(низ)) найдено.push('«за единицу товара»');
  if (/части\s+24\s+статьи\s+42|ч\.\s*24\s+ст\.\s*42/.test(низ)) найдено.push('ссылка на ч. 24 ст. 42');
  return найдено;
}

async function разобрать(слово, номера) {
  console.log(`ищу закупки по слову «${слово}», нужны номера: ${номера.join(', ')}`);

  const r = await взятьТекст(адресЗавершённых(слово, 1), 60000);
  if (!r.ok) { console.log('портал не ответил: ' + (r.ошибка || 'код ' + r.код)); return; }

  const карточки = parseSearchPage(String(r.тело || '')) || [];
  console.log(`в выдаче карточек: ${карточки.length}`);

  const нужные = карточки.filter((к) => номера.includes(к.number));
  const ненайденные = номера.filter((н) => !карточки.some((к) => к.number === н));
  if (ненайденные.length) {
    console.log(`НЕ НАЙДЕНЫ в выдаче (возможно, на другой странице): ${ненайденные.join(', ')}`);
  }

  for (const к of нужные) {
    console.log('\n' + '='.repeat(70));
    console.log(`ЗАКУПКА ${к.number}`);
    console.log(`объект из выдачи: ${к.object || '—'}`);
    console.log(`НМЦК из выдачи:   ${к.price}`);
    console.log(`карточка:         ${к.url}`);

    const адрес = адресРезультатов(к.url);
    console.log(`результаты:       ${адрес}`);

    const рр = await взятьТекст(адрес, 60000);
    await ждать(1500);
    if (!рр.ok) {
      console.log(`страница результатов НЕ ОТКРЫЛАСЬ: ${рр.ошибка || 'код ' + рр.код}`);
      continue;
    }
    const стр = String(рр.тело || '');
    console.log(`страница получена: ${стр.length} знаков, код ${рр.код}`);

    console.log('\n-- ПАРЫ «ПОДПИСЬ → ЗНАЧЕНИЕ» (подробности) --');
    for (const p of пары(стр, СХЕМЫ[0]).slice(0, 25)) {
      console.log(`   ${p.подпись} = ${p.значение}`);
    }
    console.log('-- ПАРЫ (шапка) --');
    for (const p of пары(стр, СХЕМЫ[1]).slice(0, 12)) {
      console.log(`   ${p.подпись} = ${p.значение}`);
    }

    console.log('\n-- ШАПКИ ТАБЛИЦ --');
    const шапки = шапкиТаблиц(стр);
    if (!шапки.length) console.log('   таблиц с шапками нет');
    for (const h of шапки.slice(0, 20)) console.log(`   «${h}»`);

    // ТАБЛИЦЫ ПО ОТДЕЛЬНОСТИ, А НЕ ВСЕ СТРОКИ ПОДРЯД. Отбор строки победителя
    // идёт внутри своей таблицы, поэтому и смотреть надо так же — иначе
    // диагностика показывает не то, на что смотрит разбор.
    console.log('\n-- ТАБЛИЦЫ ПО ОТДЕЛЬНОСТИ --');
    const табл = таблицы(стр);
    if (!табл.length) console.log('   таблиц не найдено');
    табл.slice(0, 8).forEach((т, i) => {
      console.log(`   [${i}] шапки: ${т.шапки.length ? т.шапки.map((h) => `«${h}»`).join(' ') : '—'}`);
      if (!т.строки.length) console.log('       строк нет (пустая или рисуется JavaScript)');
      for (const с of т.строки.slice(0, 4)) console.log(`       ${с.join('  ||  ')}`);
    });

    console.log('\n-- СТРОКИ ТАБЛИЦ ВСЕЙ СТРАНИЦЫ (первые 6) --');
    const строки = строкиТаблиц(стр);
    if (!строки.length) console.log('   строк нет — таблицы пустые или рисуются JavaScript');
    for (const с of строки.slice(0, 6)) console.log(`   ${с.join('  ||  ')}`);

    const результаты = parseSupplierResults(стр, к.url);

    // Признаки печатает ТА ЖЕ функция, которой пользуется разбор. Раньше здесь
    // была своя копия, более широкая: диагностика печатала «несостоявшаяся
    // закупка: «несостоявш…»», а разбор той же страницы — «не состоялась: false».
    // Два описания одного и того же разошлись, и поверить было нечему.
    const цзе = признакиЦеныЗаЕдиницу(стр);
    console.log('\n-- ПРИЗНАКИ --');
    console.log(`   несостоявшаяся закупка: ${результаты.признакиНесостоявшейся.length
      ? результаты.признакиНесостоявшейся.join(', ') : 'не найдено'}`);
    console.log(`   из них решающие: ${результаты.решающиеПризнакиНесостоявшейся.length
      ? результаты.решающиеПризнакиНесостоявшейся.join(', ')
      : 'нет — подпись пустого поля признаком не считается'}`);
    console.log(`   единственная заявка: ${результаты.признакиЕдинственнойЗаявки.length
      ? результаты.признакиЕдинственнойЗаявки.join(', ') : 'не найдено'}`);
    console.log(`   цена за единицу товара: ${цзе.length ? цзе.join(', ') : 'не найдено'}`);

    console.log('\n-- ЧТО ПОНЯЛ РАЗБОР --');
    console.log(`   способ: ${результаты.способ}`);
    console.log(`   НМЦК: ${результаты.нмцк}`);
    console.log(`   цена победы: ${результаты.ценаПобеды}`);
    console.log(`   не состоялась: ${результаты.неСостоялась}`);
    console.log(`   единственная заявка: ${результаты.единственнаяЗаявка}`);
    console.log(`   таблица предложений найдена: ${результаты.естьТаблицаПобедителей}`);
    console.log(`   победителей: ${результаты.победители.length} `
      + JSON.stringify(результаты.победители));
    if (результаты.issues.length) console.log(`   замечания: ${результаты.issues.join('; ')}`);

    const протоколы = ссылкиНаПротоколы(стр);
    console.log(`\n-- ПРОТОКОЛЫ (${протоколы.length}) --`);
    for (const u of протоколы) console.log(`   ${u}`);

    const главный = протоколы.find((u) => /protocol-main-info/.test(u));
    let список = null;
    if (главный) {
      const сз = await взятьТекст(адресСпискаЗаявок(главный), 60000);
      await ждать(1500);
      console.log(`\n-- СПИСОК ЗАЯВОК: код ${сз.код} --`);
      if (сз.ok) {
        список = parseBidList(String(сз.тело || ''));
        console.log(`   заявок: ${список.заявки.length}, число участников точно: `
          + `${список.участниковТочно}`);
        for (const з of список.заявки.slice(0, 12)) {
          console.log(`      ${з.ид}  ${з.место || '—'}  ${з.цена}`
            + (з.результат ? `  [${з.результат}]` : ''));
        }
        if (список.issues.length) console.log(`   замечания: ${список.issues.join('; ')}`);
      }
    }

    // Список заявок передаётся в отбор — как в сборщике. Раньше здесь стоял null,
    // и диагностика выносила вердикт по неполным данным: признак «предложения
    // участников несопоставимы» берётся как раз из списка заявок, то есть
    // диагностика и сбор могли разойтись в итоге по одной и той же закупке.
    const н = наблюдение(результаты, список);
    console.log(`\n-- ИТОГ ОТБОРА: ${н.годится ? 'ГОДИТСЯ' : 'ОТБРОШЕНО'}`
      + (н.причина ? ` — ${н.причина}` : ''));
    if (н.годится) {
      console.log(`   снижение ${н.наблюдение.снижение}%, участников `
        + `${н.наблюдение.участников !== null ? н.наблюдение.участников : '—'}`
        + (н.наблюдение.единственнаяЗаявка ? ', единственная заявка' : ''));
    }
  }
}

const арг = process.argv.slice(2);
const ключ = (имя, по) => {
  const i = арг.indexOf(имя);
  return i >= 0 && арг[i + 1] ? арг[i + 1] : по;
};

const слово = ключ('--слово', '');
const номера = ключ('--номера', '').split(/[,\s]+/).filter(Boolean);

if (!слово || !номера.length) {
  console.log('Нужны слово и номера закупок.');
  console.log('');
  console.log('  docker compose exec -T app node app/diagnose-protocol.js \\');
  console.log('    --слово "бумага" --номера "0322200001326000183,0117100015526000101"');
  process.exit(1);
}

разобрать(слово, номера).catch((e) => {
  console.log('--- ДИАГНОСТИКА УПАЛА ---');
  console.log(e && e.stack ? e.stack : String(e));
  process.exit(1);
});
