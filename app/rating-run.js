/**
 * Рейтинг тендеров клиента по готовым разборам — точка входа /rating.
 *
 * Отдельно от /search, потому что разбор документации идёт в фоне уже ПОСЛЕ
 * ответа поиска (app/parse-queue.js): в момент поиска считать звёзды не из чего.
 * n8n вызывает /rating вторым расписанием, когда очередь разобрана.
 *
 * На портал не ходит, денег не тратит: читает файлы на диске.
 */
const fs = require('fs');
const path = require('path');
const { состояние } = require('./parse-queue');
const { оценитьРазборы, сообщениеРейтинга, файлРейтинга } = require('../src/rating-digest');

/** Все собранные протоколы прошлых закупок, без повторов по номеру. */
function наблюденияПротоколов(каталог) {
  const все = new Map();
  let файлы = [];
  try { файлы = fs.readdirSync(каталог).filter((f) => /^protocols-.*\.json$/.test(f)); } catch (e) { файлы = []; }
  for (const ф of файлы) {
    try {
      const d = JSON.parse(fs.readFileSync(path.join(каталог, ф), 'utf8'));
      for (const н of d.наблюдения || []) if (н && н.номер && !все.has(н.номер)) все.set(н.номер, н);
    } catch (e) { /* испорченный файл пропускается, остальные читаются */ }
  }
  return [...все.values()];
}

/**
 * @param {string} ид латинское имя клиента
 * @param {object} клиент настройки
 * @param {object} общие общие настройки
 * @param {Date} [сейчас]
 */
function собратьРейтинг(ид, клиент, общие = {}, сейчас = new Date()) {
  const каталог = общие.каталогДанных || process.env.STATE_DIR || '/data/state';
  const с = состояние(ид, общие);

  // Только тендеры, по которым ещё принимаются заявки: просроченный тендер
  // в рейтинге — шум, по нему уже ничего не сделать.
  const живые = {};
  for (const [номер, р] of Object.entries(с.разборы || {})) {
    const срок = р && р.тендер && р.тендер.deadline;
    if (срок && new Date(срок) < сейчас) continue;
    живые[номер] = р;
  }

  const наблюдения = наблюденияПротоколов(каталог);
  const оценённые = оценитьРазборы(живые, наблюдения, клиент);
  const сЗвёздами = оценённые.filter((x) => x.оценка && x.оценка.звёзды).length;
  const журнал = [`рейтинг ${ид}: тендеров ${оценённые.length}, со звёздами ${сЗвёздами}, `
    + `прошлых закупок ${наблюдения.length}, ждут разбора ${с.очередь.length}`];

  // Ни одного тендера с расчётом прибыли - в Telegram ничего (правило владельца 25.10.2026).
  if (!сЗвёздами) {
    return { ok: true, пусто: true, тендеров: оценённые.length, сЗвёздами: 0, ждутРазбора: с.очередь.length, журнал };
  }
  const сообщение = сообщениеРейтинга(оценённые, (клиент.рейтинг && клиент.рейтинг.развёрнуты)
    ? { развёрнуты: клиент.рейтинг.развёрнуты } : {});
  const файл = файлРейтинга(оценённые, сейчас);
  // Очередь не дошла до конца — клиент должен знать, что список не весь,
  // иначе отсутствие тендера в рейтинге читается как «он не подошёл».
  const текст = с.очередь.length
    ? сообщение.text + `\n<i>Ещё ${с.очередь.length} разбираются — войдут в следующий рейтинг.</i>`
    : сообщение.text;
  return {
    ok: true,
    тендеров: оценённые.length,
    сЗвёздами,
    ждутРазбора: с.очередь.length,
    текст,
    файл: { имя: файл.fileName, base64: файл.buffer.toString('base64') },
    журнал
  };
}

module.exports = { собратьРейтинг, наблюденияПротоколов };
