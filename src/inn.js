/**
 * ИНН — проверка контрольных цифр (юрлицо 10 цифр, ИП и физлицо 12).
 * Опечатка в ИНН, ушедшем поставщику в запросе цены, стоит доверия: он
 * проверит компанию по ЕГРЮЛ и не найдёт её. Поэтому неверный ИНН не
 * сохраняется вовсе, а не «почти правильный».
 */
const ВЕСА10 = [2, 4, 10, 3, 5, 9, 4, 6, 8];
const ВЕСА12А = [7, 2, 4, 10, 3, 5, 9, 4, 6, 8];
const ВЕСА12Б = [3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8];

const контроль = (ц, веса) => (веса.reduce((с, в, i) => с + в * ц[i], 0) % 11) % 10;

function иннВерен(s) {
  const t = String(s || '').trim();
  if (!/^\d{10}$|^\d{12}$/.test(t)) return false;
  const ц = [...t].map(Number);
  if (ц.every((x) => x === 0)) return false;
  if (ц.length === 10) return контроль(ц, ВЕСА10) === ц[9];
  return контроль(ц, ВЕСА12А) === ц[10] && контроль(ц, ВЕСА12Б) === ц[11];
}

module.exports = { иннВерен };
