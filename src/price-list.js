/**
 * Прайс клиента из файла.
 *
 * @param {Buffer|string} данные содержимое файла
 * @param {object} [опции]
 * @param {string} [опции.имяФайла] для `evidence` у цены: откуда она взялась
 * @returns {object} {ok, позиции, замечания, отказ, лист, строкаШапки}
 */
function разобратьПрайс(данные, опции = {}) {
  const имяФайла = опции.имяФайла || 'прайс клиента';
  const прочитано = читатьТаблицу(данные, имяФайла);
  if (!прочитано.ok) return { ok: false, отказ: прочитано.отказ, позиции: [], замечания: [] };

  // Лист выбирается по наличию шапки, а не по номеру: в выгрузках первым листом
  // часто лежит титульный лист или инструкция.
  let найдено = null;
  for (const л of прочитано.листы) {
    const шапка = найтиШапку(л.строки);
    if (шапка) { найдено = { лист: л, шапка }; break; }
  }

  if (!найдено) {
    const виды = new Set();
    for (const л of прочитано.листы) {
      for (const стр of л.строки.slice(0, 30)) {
        for (const я of стр) { const в = чтоЗаСтолбец(я); if (в) виды.add(в); }
      }
    }
    const чего = ['наименование', 'цена'].filter((в) => !виды.has(в));
    return {
      ok: false,
      позиции: [],
      замечания: [],
      отказ: 'в файле не нашлась строка-шапка со столбцами «Наименование» и «Цена». '
        + (чего.length
          ? `Не найдено: ${чего.map((c) => `«${c}»`).join(', ')}. `
          : 'Оба слова в файле есть, но не в одной строке. ')
        + 'Подписи столбцов должны стоять в одной строке над данными; '
        + 'переименованный или удалённый столбец — самая частая причина'
    };
  }

  const { лист, шапка } = найдено;
  const выбор = выбратьЦену(шапка.цены);
  if (!выбор.выбран) {
    return { ok: false, позиции: [], замечания: [], отказ: выбор.отказ };
  }

  const замечания = [...выбор.замечания];
  const к = { ...шапка.столбцы, цена: выбор.выбран.индекс };
  const позиции = [];
  const пропущено = [];

  // Номер строки, как его видит человек в файле, а не порядковый в разборе:
  // пустые строки в разбор не попадают, и порядковый съезжает. По съехавшему
  // номеру владелец не найдёт цену в своём прайсе, то есть проверить расчёт
  // будет нечем.
  const номерВФайле = (i) => (лист.номера && лист.номера[i]) || i + 1;

  for (let i = шапка.строка + 1; i < лист.строки.length; i++) {
    const стр = лист.строки[i];
    const номерСтроки = номерВФайле(i);
    const наименование = чисто(стр[к.наименование]);

    if (!наименование) continue;

    // Строка-разделитель раздела («БУМАГА И КАРТОН») — в ней только название.
    // Это не позиция и не ошибка, поэтому в пропущенные не идёт.
    const ц = ценаИзЯчейки(стр[к.цена]);
    if (ц.цена === null) {
      if (ц.причина !== 'пусто') {
        пропущено.push({ строка: номерСтроки, наименование, причина: ц.причина });
      }
      continue;
    }

    позиции.push({
      наименование,
      артикул: к.артикул !== undefined ? артикулИзЯчейки(стр[к.артикул]) : '',
      цена: ц.цена,
      единица: к.единица !== undefined ? чисто(стр[к.единица]) : '',
      остаток: к.остаток !== undefined ? чисто(стр[к.остаток]) : '',
      поставщик: к.поставщик !== undefined ? чисто(стр[к.поставщик]) : '',
      город: к.город !== undefined ? чисто(стр[к.город]) : '',
      строка: номерСтроки,
      // Товар или работа/услуга - прайс делится сам, клиент ничего не размечает
      // (src/item-kind.js, владелец 28.10.2026).
      вид: видПозиции({ name: наименование, unit: к.единица !== undefined ? чисто(стр[к.единица]) : '' }).вид,
      ключ: нормализовать(наименование),
      числа: числаИз(наименование)
    });
  }

  if (позиции.length === 0) {
    return {
      ok: false,
      позиции: [],
      замечания,
      отказ: `шапка найдена (строка ${номерВФайле(шапка.строка)}, столбец цены «${выбор.выбран.подпись}»), `
        + 'но ни одной строки с наименованием и разобранной ценой под ней нет'
        + (пропущено.length
          ? `. Отвергнуто ${пропущено.length}: ${пропущено.slice(0, 3).map((p) => `строка ${p.строка} — ${p.причина}`).join('; ')}`
          : '')
    };
  }

  // ОДНО НАИМЕНОВАНИЕ ДВАЖДЫ — ОБЫЧНОЕ ДЕЛО, И ВЫБОР ЗДЕСЬ ЗНАЧИМ.
  // В прайсе одна и та же позиция встречается с разными ценами: разные партии,
  // разные склады, оптовая и розничная строка. Берём ХУДШУЮ (высшую) цену по
  // правилу проекта «занизить расход опаснее, чем завысить», и говорим об этом.
  const поКлючу = new Map();
  for (const п of позиции) {
    const был = поКлючу.get(п.ключ);
    if (!был || п.цена > был.цена) поКлючу.set(п.ключ, п);
  }
  const двойников = позиции.length - поКлючу.size;
  if (двойников > 0) {
    замечания.push(
      `одинаковых наименований: ${двойников}. По каждому в расчёт взята высшая цена — `
      + 'занизить расход опаснее, чем завысить'
    );
  }

  if (пропущено.length > 0) {
    замечания.push(
      `строк с наименованием, но без разобранной цены: ${пропущено.length}. `
      + 'Они в прайс не вошли и ценой не считаются'
    );
  }

  return {
    ok: true,
    позиции,
    поКлючу,
    замечания,
    пропущено,
    отказ: null,
    имяФайла,
    формат: прочитано.формат,
    лист: лист.лист,
    строкаШапки: номерВФайле(шапка.строка),
    столбецЦены: выбор.выбран.подпись,
    столбцы: Object.keys(к)
  };
}

// ------------------------------------------------------------- сопоставление

/** Слова, которые есть в любой позиции и различать не помогают. */
const ПУСТЫЕ_СЛОВА = new Set([
  'поставка', 'товар', 'шт', 'штука', 'упаковка', 'упак', 'уп', 'для', 'или',
  'и', 'в', 'с', 'на', 'по', 'из', 'без', 'тип', 'вид', 'класс', 'марка',
  // Общие слова услуг (23.10.2026): «Услуги по уборке» и «Уборка помещений»
  // в прайсе клиента - одна услуга, а «услуги» съедало половину похожести.
  'услуги', 'услуг', 'услуга', 'оказание', 'оказанию', 'оказания', 'выполнение', 'выполнению',
  'работы', 'работ', 'работ', 'комплекс', 'комплексные', 'комплексная'
]);

// Сокращения, которыми клиенты пишут услуги в прайсе, - раскрываются в обоих
// наименованиях, чтобы «Вывоз ТКО» нашёл «Вывоз твердых коммунальных отходов».
const СОКРАЩЕНИЯ = [
  [/(^|\s)тко(?=\s|$)/g, '$1твердых коммунальных отходов'],
  [/(^|\s)кго(?=\s|$)/g, '$1крупногабаритных отходов'],
  [/(^|\s)то(?=\s|$)/g, '$1техническое обслуживание']
];

/**
 * Наименование в вид, пригодный для сравнения.
 *
 * «ё» сводится к «е» намеренно: в прайсах его пишут и так, и так, а это одно и
 * то же слово. Кавычки, скобки и знаки убираются — «Бумага "Снегурочка" (А4)» и
 * «Бумага Снегурочка А4» одна позиция.
 */
function нормализовать(s) {
  let т = чисто(s)
    .toLowerCase()
    .replace(/ё/g, 'е')
    // «3x1,5», «3 х 1,5», «3*1,5», «3×1,5» - одна запись сечения кабеля.
    .replace(/(\d)\s*[xх×*]\s*(?=\d)/g, '$1х')
    .replace(/[«»"'`(),;:]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  for (const [шаблон, на] of СОКРАЩЕНИЯ) т = т.replace(шаблон, на);
  return т;
}

/**
 * Числа из наименования — главный защитный признак сопоставления.
 *
 * «Бумага А4 80 г/м²» и «Бумага А4 100 г/м²» похожи на 90% по словам и являются
 * РАЗНЫМИ товарами с разной ценой. Нечёткое совпадение без этого правила
 * подставило бы цену одного в смету другого — и это тихая ошибка: смета
 * соберётся, сумма будет правдоподобной, а закупка окажется другой.
 *
 * Поэтому числа сравниваются отдельно и строго: расходятся — совпадения нет,
 * какой бы высокой ни была похожесть слов.
 */
function числаИз(s) {
  const набор = new Set();
  for (const m of нормализовать(s).matchAll(/\d+(?:[.,]\d+)?/g)) {
    набор.add(m[0].replace(',', '.'));
  }
  return набор;
}

/** Значимые слова наименования. */
function слова(ключ) {
  return ключ.split(' ').filter((w) => w.length > 1 && !ПУСТЫЕ_СЛОВА.has(w));
}

/**
 * Похожесть двух наименований: доля общих значимых слов.
 *
 * Берётся доля от КОРОТКОГО из двух, а не от объединения. Причина в деле:
 * позиция тендера пишется подробно («Бумага для офисной техники А4, белизна
 * 146%, 500 листов, класс C»), а строка прайса коротко («Бумага А4 500л»). Доля
 * от объединения наказала бы за подробность заказчика и не нашла бы ничего.
 *
 * Слова сравниваются по основе (первые 5 букв): «бумага» и «бумаги» — одно
 * слово, и разбирать русскую морфологию здесь незачем.
 */
function похожесть(ключA, ключB) {
  const a = слова(ключA).map((w) => w.slice(0, 5));
  const b = слова(ключB).map((w) => w.slice(0, 5));
  if (a.length === 0 || b.length === 0) return 0;
  const мн = new Set(b);
  const общих = a.filter((w) => мн.has(w)).length;
  return общих / Math.min(a.length, b.length);
}

/**
 * МАРКИ РАСХОДЯТСЯ — ЭТО РАЗНЫЕ ТОВАРЫ. Найдено 20.10.2026 на слаботочке:
 * «Кабель ВВГ 3х1,5» сопоставился с «Кабель ВВГнг(А)-FRLS 3х1,5» — числа
 * совпали, два слова из трёх совпали, а кабель другой (негорючий, дороже).
 * Марка - слово, где две и больше заглавных букв (ВВГ, ПуГВнг, IEK). Если
 * марка одного наименования - начало марки другого, но не она целиком,
 * совпадения нет.
 */
function марки(s) {
  return String(s || '').split(/[\s«»"'`(),;:\/]+/)
    .filter((w) => (w.match(/[A-ZА-ЯЁ]/g) || []).length >= 2)
    .map((w) => w.replace(/^[-–]+|[-–.]+$/g, '').toLowerCase().replace(/ё/g, 'е'));
}

function маркиРасходятся(имяA, имяB) {
  const a = марки(имяA);
  const b = марки(имяB);
  for (const x of a) {
    for (const y of b) {
      if (x !== y && x.length >= 2 && y.length >= 2 && (x.startsWith(y) || y.startsWith(x))) return true;
    }
  }
  return false;
}

/** Порог похожести. Граница здравого смысла, не измерение — уточняется на деле. */
const ПОРОГ = 0.6;

/**
 * Ищет позицию тендера в прайсе клиента.
 *
 * Три способа по убыванию надёжности, и остановка на первом сработавшем:
 *
 *   1. АРТИКУЛ. Точное совпадение строк. Самый надёжный признак, но он есть
 *      далеко не во всех документациях — заказчик пишет артикул, когда закупает
 *      конкретную модель;
 *   2. ТОЧНОЕ НАИМЕНОВАНИЕ после нормализации;
 *   3. НЕЧЁТКОЕ — доля общих слов выше порога И совпадение чисел.
 *
 * НЕНАЙДЕННАЯ ПОЗИЦИЯ — ЧЕСТНЫЙ ИСХОД. Возвращается «не найдено», а не ближайшая
 * строка прайса: подставленная цена чужого товара выглядит как настоящая и
 * портит смету молча, тогда как отсутствие цены видно сразу и уходит человеку.
 *
 * @param {object} позиция позиция тендера: {name, article, unit}
 * @param {object} прайс результат `разобратьПрайс`
 */
function сопоставить(позиция, прайс) {
  if (!прайс || !прайс.ok || !прайс.позиции.length) {
    return { найдено: false, причина: 'прайс не загружен' };
  }

  const имя = позиция && (позиция.name || позиция.наименование) || '';
  const ключ = нормализовать(имя);
  if (!ключ) return { найдено: false, причина: 'у позиции нет наименования' };

  const артикул = артикулИзЯчейки(позиция.article || позиция.артикул || '');
  if (артикул) {
    const поАртикулу = прайс.позиции.filter((п) => п.артикул && п.артикул === артикул);
    if (поАртикулу.length) {
      const худшая = поАртикулу.reduce((a, b) => (b.цена > a.цена ? b : a));
      return {
        найдено: true, способ: 'артикул', уверенность: 'высокая', строка: худшая,
        пояснение: `артикул ${артикул} совпал со строкой ${худшая.строка} прайса`
      };
    }
  }

  const точные = прайс.позиции.filter((п) => п.ключ === ключ);
  if (точные.length) {
    const худшая = точные.reduce((a, b) => (b.цена > a.цена ? b : a));
    return {
      найдено: true, способ: 'наименование', уверенность: 'высокая', строка: худшая,
      пояснение: `наименование совпало дословно со строкой ${худшая.строка} прайса`
    };
  }

  const числаПозиции = числаИз(имя);
  const кандидаты = [];
  for (const п of прайс.позиции) {
    // ЧИСЛА ОБЯЗАНЫ СОВПАСТЬ. Сравниваются только числа строки прайса: в
    // позиции тендера их обычно больше (ГОСТ, класс, номер пункта), и требовать
    // равенства наборов значило бы не находить ничего. Но ни одно число прайса
    // не должно противоречить позиции.
    if (п.числа.size > 0) {
      let всеЕсть = true;
      for (const ч of п.числа) if (!числаПозиции.has(ч)) { всеЕсть = false; break; }
      if (!всеЕсть) continue;
    }
    if (маркиРасходятся(имя, п.наименование)) continue;
    const счёт = похожесть(ключ, п.ключ);
    if (счёт >= ПОРОГ) кандидаты.push({ п, счёт });
  }

  if (кандидаты.length === 0) {
    return {
      найдено: false,
      причина: 'в прайсе нет похожей позиции — ни по артикулу, ни по наименованию'
    };
  }

  кандидаты.sort((a, b) => b.счёт - a.счёт || b.п.цена - a.п.цена);
  const лучший = кандидаты[0];
  const равных = кандидаты.filter((к) => к.счёт === лучший.счёт);

  // НЕСКОЛЬКО РАВНО ПОХОЖИХ СТРОК — ВЫБОР НЕ ДЕЛАЕТСЯ НАУГАД. Берётся худшая
  // цена среди них, и уверенность понижается: решает человек, а смета пока
  // считается по безопасной стороне.
  const строка = равных.reduce((a, b) => (b.п.цена > a.п.цена ? b : a)).п;
  const многовариантно = равных.length > 1;

  return {
    найдено: true,
    способ: 'нечёткое',
    уверенность: многовариантно ? 'требует проверки' : 'средняя',
    строка,
    счёт: Math.round(лучший.счёт * 100) / 100,
    варианты: многовариантно ? равных.map((к) => к.п) : [],
    пояснение: многовариантно
      ? `в прайсе ${равных.length} равно похожих строк (${равных.map((к) => к.п.строка).join(', ')}); `
        + `взята высшая цена, строка ${строка.строка} — подтвердите вручную`
      : `похоже на строку ${строка.строка} прайса «${строка.наименование}» `
        + `(общих слов ${Math.round(лучший.счёт * 100)}%)`
  };
}

/**
 * Цена из прайса в виде, который принимает `makePrice` из `pricing.js`.
 *
 * `evidence` обязателен: `makePrice` не считает цену пригодной без ссылки или
 * документа-подтверждения, и это правильно — «цена без источника в расчёт не
 * идёт». Ссылки у прайса нет и быть не может, поэтому подтверждением служит
 * имя файла со строкой: по нему владелец найдёт цифру в прайсе за секунду.
 *
 * СПОСОБ СОВПАДЕНИЯ ПИШЕТСЯ В `evidence`, И ЭТО НЕ УКРАШЕНИЕ. `makePrice`
 * возвращает объект строго заданного вида и посторонние поля отбрасывает —
 * значит «совпадение нечёткое, требует проверки», положенное отдельным полем,
 * до сметы просто не доехало бы. Уверенность в сопоставлении и доверие к
 * источнику — разные вещи: цена в прайсе настоящая, но та ли это позиция,
 * решает человек. Положить это некуда, кроме подтверждения, которое доезжает.
 */
function ценаИзПрайса(сопоставление, прайс) {
  if (!сопоставление || !сопоставление.найдено) return null;
  const с = сопоставление.строка;
  const имя = (прайс && прайс.имяФайла) || 'прайс клиента';

  const как = сопоставление.способ === 'по ТЗ'
    ? ` · найдено по характеристикам из ТЗ («${сопоставление.ключ}») — подтвердите марку`
    : сопоставление.способ === 'нечёткое'
      ? ` · совпадение нечёткое (${сопоставление.уверенность}) — подтвердите позицию`
      : ` · совпадение по ${сопоставление.способ === 'артикул' ? 'артикулу' : 'наименованию'}`;

  return {
    price: с.цена,
    source: SOURCES.PRICE_LIST,
    evidence: `${имя}, строка ${с.строка}: «${с.наименование}» — ${с.цена}`
      + (с.единица ? ` за ${с.единица}` : '') + как,
    supplier: с.поставщик || ''
  };
}

/**
 * Сопоставление по ключу из характеристик ТЗ («Кабель 3х1,5») - для позиций,
 * названных в документе голым словом. Правила те же, что у `сопоставить`
 * (числа строки прайса обязаны быть в ключе, марки не противоречат), но
 * уверенность всегда «требует проверки»: марку (ВВГ, NYM, ППГ) ключ не
 * содержит, решает человек.
 */
function сопоставитьПоТЗ(ключ, прайс) {
  const р = сопоставить({ name: ключ }, прайс);
  if (!р.найдено) return р;
  return {
    ...р,
    способ: 'по ТЗ',
    уверенность: 'требует проверки',
    ключ,
    пояснение: `по характеристикам из ТЗ «${ключ}»: ${р.пояснение}`
  };
}

/**
 * Сводка по сопоставлению всех позиций тендера — то, что видит человек.
 *
 * Названо числом, а не словами: «сопоставлено 7 из 12» проверяемо, «сопоставление
 * выполнено» — нет.
 */
function сводка(результаты) {
  const всего = результаты.length;
  const найдено = результаты.filter((r) => r.найдено);
  const поСпособу = {};
  for (const r of найдено) поСпособу[r.способ] = (поСпособу[r.способ] || 0) + 1;
  const требуютПроверки = найдено.filter((r) => r.уверенность === 'требует проверки');

  return {
    всего,
    найдено: найдено.length,
    ненайдено: всего - найдено.length,
    поСпособу,
    требуютПроверки: требуютПроверки.length,
    строка: всего === 0
      ? 'позиций нет'
      : `по прайсу найдено ${найдено.length} из ${всего}`
        + (Object.keys(поСпособу).length
          ? ` (${Object.entries(поСпособу).map(([с, n]) => `${с}: ${n}`).join(', ')})`
          : '')
        + (требуютПроверки.length ? `, требуют проверки: ${требуютПроверки.length}` : '')
  };
}

/**
 * ИЗДЕРЖКИ ИСПОЛНЕНИЯ ИЗ ПРАЙСА (16.11.2026, решение владельца: прайс —
 * единственный источник, дублировать его настройками сайта незачем; система
 * стремится работать без человека). Ищет в прайсе строки, которые являются
 * не товарами закупки, а затратами на исполнение: суточные, транспорт бригады,
 * подача заявки, банковская гарантия. Найденное подставляется на лист
 * «Мои издержки» Excel-файла со ссылкой на строку прайса. Не нашлось — строка
 * остаётся пустой: цену не выдумываем (правило проекта).
 *
 * Шаблоны намеренно узкие: ложная цена в издержках хуже пустой строки.
 * «Доставка» товара сюда НЕ входит — это логистика, считается отдельно.
 */
const КАТЕГОРИИ_ИЗДЕРЖЕК = [
  { статья: 'Транспорт и развоз бригады', шаблон: /(транспорт|развоз|переезд)[^,;]{0,30}(бригад|монтажник|рабочих|персонала)|доставка[^,;]{0,20}бригад/i },
  { статья: 'Проживание и суточные', шаблон: /суточн|проживан/i },
  { статья: 'Подготовка и подача заявки (оператор площадки)', шаблон: /подач[аи]\s+заявк|оператор\s+электронн(ой\s+площадки)?|тариф\s+площадки/i },
  { статья: 'Банковская гарантия (комиссия 2–5% от обеспечения)', шаблон: /банковск[а-яё]*\s+гаранти|комисси[яи][^,;]{0,25}гаранти/i }
];

/**
 * @param {Array} позиции строки прайса ({наименование, цена, единица})
 * @returns {Array<{статья: string, цена: number, источник: string}>}
 */
function ценыИздержек(позиции) {
  const итог = [];
  for (const категория of КАТЕГОРИИ_ИЗДЕРЖЕК) {
    const строка = (позиции || []).find((п) =>
      typeof п.цена === 'number' && isFinite(п.цена) && категория.шаблон.test(String(п.наименование || '')));
    if (строка) {
      итог.push({
        статья: категория.статья,
        цена: строка.цена,
        источник: `из вашего прайса: «${String(строка.наименование).slice(0, 60)}»`
      });
    }
  }
  return итог;
}

