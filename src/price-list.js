/**
 * Цена из ячейки столбца цены.
 *
 * ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ `деньгиИзЯчейки` В `protocol-page.js` И ПОЧЕМУ. Там мы
 * просматривали произвольные ячейки страницы портала и не знали заранее, лежит
 * ли в них цена, — поэтому требовали либо копейки, либо знак рубля, иначе
 * `parseMoney` склеивал «ст. 14» и «44 ФЗ» в цену 1444 ₽. Здесь столбец уже
 * опознан по подписи, и «420» в столбце «Цена» — законная цена без копеек.
 * Разные правила для разных задач — это не непоследовательность, но назвать
 * разницу обязательно, иначе при следующей правке кто-то сведёт их к одному.
 *
 * ЧТО ОТВЕРГАЕТСЯ И ПОЧЕМУ ИМЕННО ЭТО:
 *
 *   — «1,58E+09» — научная запись. Так Excel молча портит длинные числа, и это
 *     самая частая порча данных в проекте (на номерах чатов её уже ловили).
 *     Восстановить потерянные разряды нельзя, поэтому значение не берётся:
 *     цена, ошибочная в тысячу раз, хуже отсутствующей;
 *   — «420/500», «от 420» — в ячейке не одно число или не только число. Выбрать
 *     из двух значит угадать;
 *   — ноль и отрицательные — это не цена.
 *
 * Принимается: «420», «420,50», «420.50», «1 234,56», «1 234,56 ₽», «420 руб.».
 */
function ценаИзЯчейки(v) {
  const s = чисто(v);
  if (!s) return { цена: null, причина: 'пусто' };

  if (/\d[eE][+\-]?\d/.test(s)) {
    return {
      цена: null,
      причина: `«${s}» — Excel записал число в научном виде и потерял разряды. `
        + 'Поставьте столбцу текстовый формат и впишите цену заново'
    };
  }

  // Знак рубля, «руб», «р.» и пробелы-разделители разрядов убираем, остальное
  // оставляем как есть: по тому, что осталось, и судим, одно ли там число.
  const без = s
    .replace(/(₽|руб\.?|р\.)/gi, '')
    .replace(/(?<=\d)[  ](?=\d)/g, '')
    .trim();

  if (!/^-?\d+([.,]\d+)?$/.test(без)) {
    return { цена: null, причина: `«${s}» — это не одно число, а значит не цена` };
  }

  const n = Number(без.replace(',', '.'));
  if (!Number.isFinite(n)) return { цена: null, причина: `«${s}» не разобралось в число` };
  if (n <= 0) return { цена: null, причина: `цена ${n} — ноль или меньше` };

  return { цена: Math.round(n * 100) / 100, причина: null };
}

/**
 * Артикул остаётся СТРОКОЙ, и это не мелочь.
 *
 * Артикул «000417» и число 417 — разные артикулы. Любое приведение к числу
 * съедает ведущие нули, а в проекте этот класс ошибки уже стоил двух проходов
 * проверки на реестровых номерах. Поэтому здесь нет ни `Number`, ни `parseInt`.
 *
 * Если Excel съел нули ДО нас — восстановить их нечем, и притворяться, что
 * сопоставление по такому артикулу надёжно, нельзя. Поэтому артикул служит
 * сильным признаком только при точном совпадении строк.
 */
function артикулИзЯчейки(v) {
  return чисто(v).replace(/\s+/g, '').toUpperCase();
}

