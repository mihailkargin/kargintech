/** Разделитель CSV по первой непустой строке: точка с запятой, табуляция, запятая. */
function разделитель(текст) {
  const строка = текст.split(/\r?\n/).find((s) => s.trim()) || '';
  const счёт = { ';': 0, '\t': 0, ',': 0 };
  let вКавычках = false;
  for (const ch of строка) {
    if (ch === '"') { вКавычках = !вКавычках; continue; }
    if (!вКавычках && счёт[ch] !== undefined) счёт[ch]++;
  }
  // Точка с запятой первой: в русском Excel это разделитель по умолчанию,
  // а запятая внутри цены («420,50») без кавычек встречается постоянно.
  if (счёт[';'] > 0) return ';';
  if (счёт['\t'] > 0) return '\t';
  return ',';
}

/**
 * Строки CSV с учётом кавычек: внутри поля бывают и разделитель, и перевод строки.
 *
 * Номера строк считаются по файлу, а не по полученному списку: пустые строки в
 * список не попадают, и без отдельного счёта номер в подтверждении цены съехал
 * бы относительно того, что человек видит в файле. Та же причина, что и у
 * `xlsxRows`.
 */
function разобратьCsv(текст) {
  const d = разделитель(текст);
  const строки = [];
  const номера = [];
  let поля = [];
  let поле = '';
  let вКавычках = false;
  let вФайле = 1;
  // Номер строки — тот, на которой она НАЧАЛАСЬ: значение в кавычках может
  // занимать несколько строк файла, и к концу счётчик уже уехал вперёд.
  let началоСтроки = 1;

  const закрыть = () => {
    поля.push(поле.replace(/\r$/, ''));
    if (поля.some((p) => p.trim())) { строки.push(поля); номера.push(началоСтроки); }
    поля = []; поле = '';
    началоСтроки = вФайле + 1;
  };

  for (let i = 0; i < текст.length; i++) {
    const ch = текст[i];
    if (вКавычках) {
      if (ch === '"') {
        if (текст[i + 1] === '"') { поле += '"'; i++; } else вКавычках = false;
      } else {
        // Перевод строки внутри кавычек — часть значения, но в файле это
        // следующая строка, и счёт обязан это учесть.
        if (ch === '\n') вФайле++;
        поле += ch;
      }
      continue;
    }
    if (ch === '"') { вКавычках = true; continue; }
    if (ch === d) { поля.push(поле); поле = ''; continue; }
    if (ch === '\n') { закрыть(); вФайле++; continue; }
    поле += ch;
  }
  закрыть();

  return { строки, номера };
}

/**
 * Файл прайса в строки и ячейки.
 *
 * Формат определяется по содержимому, а не по имени: расширение врёт. Книга
 * Excel всегда начинается с `PK` — это ZIP. Старые `.xls` здесь не читаются
 * намеренно: их путь в проекте уже есть — конвертер пересохраняет файл, и
 * дальше он приходит сюда обычной книгой. Заводить второй путь незачем.
 */
function читатьТаблицу(данные, имяФайла = '') {
  const расш = (имяФайла.match(/\.([a-z0-9]+)$/i) || [])[1] || '';
  const буфер = Buffer.isBuffer(данные) ? данные : null;

  if (буфер && буфер.length > 1 && буфер[0] === 0x50 && буфер[1] === 0x4b) {
    const листы = xlsxRows(буфер);
    const сСтроками = листы.filter((л) => л.строки.length > 0);
    if (сСтроками.length === 0) {
      return { ok: false, отказ: 'книга Excel открылась, но все листы пустые' };
    }
    return { ok: true, листы: сСтроками, формат: 'xlsx' };
  }

  if (буфер && буфер[0] === 0xd0 && буфер[1] === 0xcf) {
    return {
      ok: false,
      отказ: 'это старый формат Excel (.xls). Пересохраните файл как .xlsx '
        + '(в Excel: «Файл» → «Сохранить как» → «Книга Excel») или пришлите как есть — '
        + 'на сервере его пересохранит конвертер'
    };
  }

  const текст = буфер ? буфер.toString('utf8') : String(данные || '');
  if (!текст.trim()) return { ok: false, отказ: 'файл пустой' };
  if (/^%PDF/.test(текст)) {
    return { ok: false, отказ: 'это PDF. Прайс нужен таблицей — .xlsx или .csv' };
  }

  const { строки, номера } = разобратьCsv(текст);
  if (строки.length === 0) return { ok: false, отказ: 'в файле нет ни одной строки с данными' };
  return {
    ok: true,
    листы: [{ лист: 1, строки, номера }],
    формат: расш === 'csv' ? 'csv' : 'текст'
  };
}

