/**
 * Подписи столбцов, которые встречаются в прайсах.
 *
 * Список, а не одно слово на столбец: прайс выгружают из 1С, из «Моего склада»,
 * из рук менеджера, и подпись у одного и того же столбца везде своя. Угадывать
 * столбец по номеру («цена обычно третья») нельзя — это и есть тот самый тихий
 * отказ: порядок столбцов у клиента другой, и в цену поедет количество.
 *
 * Шаблоны без `\w` и `\b`: в JavaScript они считают буквами только латиницу, и
 * `\bцена` не совпадает никогда. В проекте эта ловушка срабатывала четыре раза.
 */
const ПОДПИСИ = {
  наименование: [
    /наименован/i, /^названи/i, /номенклатур/i, /^товар/i, /^позици/i,
    /^предмет/i, /описание товара/i
  ],
  артикул: [/артикул/i, /^код/i, /^sku$/i, /^кат\.?\s*номер/i, /каталожн/i],
  цена: [/цена/i, /стоимост/i, /^прайс/i, /^цен[аы]\s/i],
  единица: [/единиц/i, /^ед\.?\s*изм/i, /^ед\.?$/i],
  остаток: [/остат/i, /наличи/i, /^склад/i, /^количеств/i, /^кол-?во/i],
  поставщик: [/поставщик/i, /производител/i, /^завод/i, /^бренд/i],
  город: [/город/i, /^регион/i, /отгрузк/i, /^адрес/i]
};

/** Текст ячейки в пригодный для сравнения вид: без лишних пробелов и регистра. */
function чисто(v) {
  return String(v === undefined || v === null ? '' : v)
    .replace(/ /g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Какой это столбец по его подписи, или null.
 *
 * ПОРЯДОК ПРОВЕРОК ЗНАЧИМ. «Количество источников ценовой информации» в
 * обоснованиях НМЦК уже один раз утащило разбор не туда, и здесь та же ловушка
 * в другом виде: подпись «Цена за единицу» содержит и «цена», и «единиц».
 * Поэтому цена проверяется ДО единицы измерения, а остаток — после цены, иначе
 * «количество» в подписи «Цена за количество» перебило бы цену.
 */
function чтоЗаСтолбец(подпись) {
  const s = чисто(подпись);
  if (!s) return null;
  for (const вид of ['наименование', 'артикул', 'цена', 'единица', 'остаток', 'поставщик', 'город']) {
    if (ПОДПИСИ[вид].some((re) => re.test(s))) return вид;
  }
  return null;
}

/**
 * Ищет строку-шапку и раскладывает столбцы по видам.
 *
 * Шапка не обязана быть первой строкой: в выгрузках сверху лежат название
 * компании, дата прайса, телефон менеджера. Поэтому просматриваем первые
 * строки и берём ту, в которой нашлись И наименование, И цена: по отдельности
 * каждое слово встречается и в описательном тексте над таблицей.
 */
function найтиШапку(строки, предел = 30) {
  const до = Math.min(строки.length, предел);
  for (let i = 0; i < до; i++) {
    const столбцы = {};
    const цены = [];

    строки[i].forEach((ячейка, к) => {
      const вид = чтоЗаСтолбец(ячейка);
      if (!вид) return;
      if (вид === 'цена') { цены.push({ индекс: к, подпись: чисто(ячейка) }); return; }
      if (столбцы[вид] === undefined) столбцы[вид] = к;
    });

    if (столбцы.наименование !== undefined && цены.length > 0) {
      return { строка: i, столбцы, цены };
    }
  }
  return null;
}

/**
 * Выбор столбца цены, когда их несколько.
 *
 * ЭТО САМЫЙ ЧАСТЫЙ ВИД НАСТОЯЩЕГО ПРАЙСА: «цена без НДС» и «цена с НДС» рядом.
 * Отказаться от такого файла значит отказаться от большинства файлов, а выбрать
 * наугад — тихо ошибиться на 20% себестоимости.
 *
 * Берём цену С НДС, и причина не в удобстве: клиент платит её живыми деньгами,
 * а правило проекта «в расчёт идёт худшая цена, не средняя» выбирает именно
 * большую из двух оценок расхода. Выбор называется в замечаниях вслух, чтобы
 * владелец видел, какой столбец пошёл в расчёт, а не догадывался.
 *
 * Если ни один столбец про НДС ничего не говорит, а их несколько — это
 * настоящая неоднозначность, и файл отвергается с перечислением подписей.
 * Расхождение источников показывается, а не решается за владельца.
 */
function выбратьЦену(цены) {
  if (цены.length === 1) return { выбран: цены[0], замечания: [] };

  const сНдс = цены.filter((ц) => /с\s*ндс/i.test(ц.подпись));
  const безНдс = цены.filter((ц) => /без\s*ндс/i.test(ц.подпись));

  if (сНдс.length === 1) {
    return {
      выбран: сНдс[0],
      замечания: [
        `столбцов с ценой несколько (${цены.map((ц) => `«${ц.подпись}»`).join(', ')}), `
        + `в расчёт взят «${сНдс[0].подпись}»: клиент платит эту цену деньгами, `
        + 'а завысить расход безопаснее, чем занизить'
      ]
    };
  }

  if (безНдс.length === 1 && цены.length === 2) {
    const другой = цены.find((ц) => ц !== безНдс[0]);
    return {
      выбран: другой,
      замечания: [
        `столбцов с ценой два («${безНдс[0].подпись}» и «${другой.подпись}»), `
        + `в расчёт взят «${другой.подпись}» как цена с налогом`
      ]
    };
  }

  return {
    выбран: null,
    отказ: `столбцов с ценой несколько и ни один не помечен «с НДС» или «без НДС»: `
      + `${цены.map((ц) => `«${ц.подпись}»`).join(', ')}. `
      + 'Какой из них закупочная цена — из файла не следует, а выбирать наугад нельзя: '
      + 'ошибка здесь уходит прямо в себестоимость. Оставьте в файле один столбец с ценой '
      + 'или допишите к нужному «с НДС».',
    замечания: []
  };
}

