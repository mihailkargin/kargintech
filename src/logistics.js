/**
 * Насколько дорога длиннее прямой линии. Для европейской части России
 * коэффициент около 1,25–1,35; берём 1,3 как середину.
 * Это одно из мест, где оценка заведомо груба, — и потому она и остаётся
 * оценкой, а не заменяет ответ перевозчика.
 */
const ROAD_FACTOR = 1.3;

/**
 * Ориентиры тарифов сборного груза, рублей.
 *
 * КАЛИБРОВАНЫ ПО ОДНОМУ РЕАЛЬНОМУ ЗАМЕРУ — ответу ПЭК от 30.09.2026:
 * паллета 300 кг, Москва → Екатеринбург, 1842 км по нашему расчёту.
 * Ответ был разложен по составляющим: забор 2400, перевозка 8760,
 * доставка 1100, итого 12 260 ₽.
 *
 * ОДИН ЗАМЕР — ЭТО НЕ СТАТИСТИКА. Ставки подобраны так, чтобы оценка
 * попадала в этот ответ, и на других направлениях и весах она может
 * разойтись заметно. Это осознанно: оценка нужна не как цена, а как
 * проверка правдоподобия ответа перевозчика. Калибруются по мере
 * накопления фактических расчётов — как и допущение о падении цены
 * на торгах.
 *
 * Первая версия ставки за килограмм-километр была занижена почти в семь
 * раз, и оценка давала 3 700 ₽ вместо 12 260 ₽. На такой оценке проверка
 * правдоподобия работала бы наоборот: каждый нормальный ответ перевозчика
 * выглядел бы завышенным.
 */
const RATES = {
  pickupBase: 2000,      // забор груза у отправителя
  deliveryBase: 1200,    // доставка до двери получателя
  perKgPerKm: 0.016,     // основная ставка: рубль за килограмм-километр
  volumetricRatio: 250,  // кубометр приравнивается к такому весу, кг
  minCharge: 3000        // ниже этого перевозчики обычно не считают
};

const round2 = (n) => Math.round(n * 100) / 100;
const toRad = (deg) => (deg * Math.PI) / 180;

/** Прямое расстояние между точками по земной сфере, км. */
function greatCircle([lat1, lon1], [lat2, lon2]) {
  const R = 6371;
  const dLat = toRad(lat2 - lat1);
  const dLon = toRad(lon2 - lon1);
  const a = Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLon / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

/**
 * Достаёт название города из адреса поставки.
 *
 * Место поставки в документации пишут как придётся: «г. Москва, ул. Тверская»,
 * «Российская Федерация, Московская обл., г. Москва», «МОСКВА». Ищем известный
 * город внутри строки, а не пытаемся разобрать адрес целиком.
 */
function findCity(address) {
  const text = String(address || '').toLowerCase().replace(/ё/g, 'е');
  if (!text) return null;

  // Длинные названия проверяем раньше коротких: «нижний новгород» должен
  // выигрывать у «новгород», если тот появится в списке.
  const names = Object.keys(CITIES).sort((a, b) => b.length - a.length);
  for (const name of names) {
    if (text.includes(name.replace(/ё/g, 'е'))) return name;
  }
  return null;
}

/**
 * Расстояние между двумя адресами, км. null — если город не опознан.
 * Не опознали — так и говорим: подставлять среднее расстояние по стране
 * значит выдумывать основание для решения о деньгах.
 */
function distanceBetween(fromAddress, toAddress) {
  const a = findCity(fromAddress);
  const b = findCity(toAddress);
  if (!a || !b) {
    return { km: null, from: a, to: b, unknown: [!a && 'откуда', !b && 'куда'].filter(Boolean) };
  }
  if (a === b) return { km: 0, from: a, to: b, unknown: [] };
  return { km: Math.round(greatCircle(CITIES[a], CITIES[b]) * ROAD_FACTOR), from: a, to: b, unknown: [] };
}

/**
 * Расчётный вес груза. Перевозчики берут больший из двух: фактический вес
 * и объёмный. Считать только по фактическому — значит занизить стоимость
 * лёгкого габаритного груза в разы.
 */
function chargeableWeight(weightKg, volumeM3) {
  const real = typeof weightKg === 'number' && weightKg > 0 ? weightKg : null;
  const volumetric = typeof volumeM3 === 'number' && volumeM3 > 0
    ? volumeM3 * RATES.volumetricRatio : null;

  if (real === null && volumetric === null) return { kg: null, basis: 'нет данных' };
  if (real === null) return { kg: round2(volumetric), basis: 'объёмный вес' };
  if (volumetric === null) return { kg: real, basis: 'фактический вес' };

  return volumetric > real
    ? { kg: round2(volumetric), basis: 'объёмный вес больше фактического' }
    : { kg: real, basis: 'фактический вес' };
}

/**
 * Собственная оценка стоимости перевозки.
 *
 * НУЖНА НЕ ВМЕСТО ПЕРЕВОЗЧИКА, А РЯДОМ С НИМ. Её задача — заметить, что ответ
 * перевозчика странный: если он вдвое выше оценки, скорее всего посчитана
 * отдельная машина вместо сборного груза или добавлены услуги, которых мы
 * не заказывали.
 */
function estimate(shipment) {
  const dist = distanceBetween(shipment.from, shipment.to);
  const weight = chargeableWeight(shipment.weightKg, shipment.volumeM3);
  const issues = [];

  if (dist.km === null) {
    issues.push(`не удалось определить город: ${dist.unknown.join(' и ')} — расстояние неизвестно`);
  }
  if (weight.kg === null) {
    issues.push('не известны ни вес, ни объём груза — стоимость перевозки не оценить');
  }
  if (dist.km === null || weight.kg === null) {
    return { amount: null, distanceKm: dist.km, weight, issues, source: 'собственная оценка' };
  }

  const transport = weight.kg * dist.km * RATES.perKgPerKm;
  const raw = RATES.pickupBase + transport + RATES.deliveryBase;
  const amount = Math.max(raw, RATES.minCharge);

  return {
    amount: round2(amount),
    distanceKm: dist.km,
    weight,
    route: `${dist.from} → ${dist.to}`,
    parts: {
      забор: RATES.pickupBase,
      перевозка: round2(transport),
      доставка: RATES.deliveryBase
    },
    issues,
    source: 'собственная оценка',
    note: 'грубая оценка по расстоянию и весу, не заменяет ответ перевозчика'
  };
}

/**
 * Сводит ответы перевозчиков и собственную оценку в решение.
 *
 * @param {object} shipment груз: from, to, weightKg, volumeM3
 * @param {Array<object>} quotes ответы перевозчиков: {carrier, amount, days, parts}
 */
function resolveLogistics(shipment, quotes = []) {
  const own = estimate(shipment);
  const valid = quotes.filter((q) => typeof q.amount === 'number' && q.amount > 0);
  const warnings = [...own.issues];

  if (valid.length === 0) {
    // Ни один перевозчик не ответил. Работаем на своей оценке, но клиент
    // обязан знать, что это прикидка, а не цена.
    if (own.amount === null) {
      return {
        amount: null, min: null, max: null,
        confidence: 'нет данных',
        basis: 'логистика не рассчитана',
        quotes: [], own,
        warnings: [...warnings, 'логистику посчитать не удалось — проверить вручную, прибыль без неё неполна']
      };
    }
    return {
      amount: own.amount, min: own.amount, max: own.amount,
      confidence: 'требует проверки',
      basis: 'только собственная оценка',
      quotes: [], own,
      warnings: [...warnings,
        'ни один перевозчик не ответил — цифра получена своей формулой и может отличаться от реальной в разы']
    };
  }

  const amounts = valid.map((q) => q.amount);
  const min = Math.min(...amounts);
  const max = Math.max(...amounts);

  // БАЛАНС МЕЖДУ ПЕРЕВОЗЧИКОМ И СОБСТВЕННОЙ ОЦЕНКОЙ.
  //
  // Главный здесь перевозчик: он считает по конкретному грузу и знает свои
  // тарифы. Собственная формула груба и калибрована по одному замеру.
  //
  // Но есть случай, где слепо верить перевозчику опасно: когда он ОДИН
  // и его ответ вдвое НИЖЕ оценки. Так бывает, когда посчитан только
  // межтерминальный перевоз, без забора груза у поставщика и без доставки
  // до двери заказчика, — а это две трети стоимости на коротком плече.
  // Взять такую цифру значит завысить прибыль и привести клиента
  // в убыточный контракт. Ошибка ровно того вида, от которого защищаемся.
  //
  // Поэтому оценка работает СТРАХОВКОЙ СНИЗУ, и только когда источник один:
  // два согласных перевозчика — уже проверка друг для друга, и формуле
  // вмешиваться незачем.
  let amount = max;
  let basis = valid.length >= 2 ? 'ответы перевозчиков' : 'ответ одного перевозчика';

  if (own.amount !== null) {
    const ratio = own.amount > 0 ? max / own.amount : null;

    if (valid.length === 1 && ratio !== null && ratio < 0.5) {
      amount = own.amount;
      basis = 'собственная оценка выше ответа перевозчика, взята она';
      warnings.push(
        `единственный перевозчик (${valid[0].carrier}) насчитал ${Math.round(max)} ₽ — ` +
        `это вдвое меньше собственной оценки ${Math.round(own.amount)} ₽. ` +
        'Похоже, посчитан только перевоз между терминалами, без забора и доставки до двери. ' +
        'В расчёт взята оценка как более осторожная'
      );
    } else if (ratio !== null && (ratio > 2 || ratio < 0.5)) {
      warnings.push(
        `ответ перевозчика (${Math.round(max)} ₽) расходится с собственной оценкой ` +
        `(${Math.round(own.amount)} ₽) более чем вдвое — проверить тип отправки и состав услуг`
      );
    }
  }

  if (valid.length === 1) {
    warnings.push(`расчёт от единственного перевозчика (${valid[0].carrier}) — сверить не с чем`);
  }

  const spreadPct = min > 0 ? round2(((max - min) / min) * 100) : null;
  if (spreadPct !== null && spreadPct > 50) {
    warnings.push(`перевозчики расходятся на ${spreadPct}% — в расчёт взят самый дорогой`);
  }

  return {
    amount,
    min,
    max,
    spreadPct,
    confidence: valid.length >= 2 && (spreadPct === null || spreadPct <= 50) ? 'высокая'
      : (valid.length >= 2 ? 'требует проверки' : 'средняя'),
    basis,
    quotes: valid.map((q) => ({ carrier: q.carrier, amount: q.amount, days: q.days || null })),
    own,
    warnings
  };
}

/**
 * Логистика двуногая: от поставщика к клиенту и от клиента к заказчику.
 * Считать надо обе, иначе половина расходов потеряется.
 *
 * Когда клиент возит напрямую от поставщика заказчику, второе плечо
 * отсутствует — это законный случай, а не ошибка.
 */
function totalLogistics(legs) {
  const parts = (legs || []).filter(Boolean);
  const unresolved = parts.filter((p) => p.amount === null);

  const amount = parts
    .filter((p) => p.amount !== null)
    .reduce((s, p) => round2(s + p.amount), 0);

  const warnings = parts.flatMap((p) => p.warnings || []);
  if (unresolved.length) {
    warnings.push(
      `${unresolved.length} из ${parts.length} плеч перевозки не рассчитано — ` +
      'итог по логистике неполный'
    );
  }

  return {
    amount,
    complete: unresolved.length === 0 && parts.length > 0,
    legs: parts,
    warnings: [...new Set(warnings)]
  };
}

