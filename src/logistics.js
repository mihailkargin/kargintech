/**
 * Расчёт логистики: несколько источников, собственная оценка, диапазон.
 * Без внешних зависимостей — тело функции переносится в Code-ноду n8n как есть.
 *
 * РЕШЕНИЕ ВЛАДЕЛЬЦА: на глаз нельзя. Считаем точно; если точно не выходит —
 * выдаём диапазон, а прибыль считаем по худшей границе.
 *
 * ПОЧЕМУ НЕ ОДИН ПЕРЕВОЗЧИК. Единственный источник — это не только риск
 * остаться без расчёта, когда он недоступен. Хуже другое: его ответ не с чем
 * сверить. Перевозчик может вернуть цену для другого типа отправки, посчитать
 * без забора груза или просто ошибиться — и мы примем это за факт.
 *
 * ОТСЮДА ТРИ УРОВНЯ:
 *   1. Ответы перевозчиков — точные цифры по конкретному грузу.
 *   2. Собственная оценка по расстоянию и весу — грубая, но независимая.
 *      Нужна не вместо перевозчика, а чтобы заметить, что его ответ странный.
 *   3. Диапазон из всего, что собралось. В расчёт прибыли идёт верхняя граница.
 *
 * ЧЕГО ЗДЕСЬ НЕТ: попытки выдать одну цифру за истину. Точную стоимость знает
 * только перевозчик после запроса по конкретному грузу, и то до момента, когда
 * машина реально поедет.
 */

