/**
 * АНАЛИТИКА НИШИ ДЛЯ ВНЕДРЕНИЯ - 24.10.2026, пункт внедрения владельца:
 * «по прошлым закупкам ваших товаров - по какой цене выигрывали, насколько
 * падала цена, сколько было участников; сравнение с вашими закупочными ценами».
 *
 * Что здесь факт, а что расчёт - и это сказано в самом отчёте:
 *  - ЦЕНА ЗАКАЗЧИКА по товару - факт: обоснования НМЦК разобранных закупок,
 *    где этот товар есть (сопоставление со строкой прайса клиента тем же
 *    правилом, что в расчёте: числа строки прайса обязаны быть в наименовании);
 *  - ПАДЕНИЕ ЦЕНЫ И УЧАСТНИКИ - факт: протоколы прошлых закупок той же группы
 *    ОКПД2, без закупок с единственной заявкой (торга в них нет);
 *  - ОЖИДАЕМАЯ ЦЕНА ПОБЕДЫ по товару - РАСЧЁТ: цена заказчика минус обычное
 *    падение. Цена победы публикуется на закупку целиком, а не на товар;
 *  - БЕЗУБЫТОЧНАЯ ЦЕНА клиента - его закупочная цена с доставкой и налогом
 *    (ставки из его настроек, иначе 8% и 6%, как в расчёте за единицу).
 *
 * Прайс клиента в отчёт входит только его собственный и никуда не уходит;
 * сетевых обращений нет.
 */

const { сопоставить } = require('./price-list');
const { видЕдиницы } = require('./units');
const { распределение } = require('./discount-stats');

const МИНИМУМ_ЗАКУПОК = 3;
const округлить = (x, n = 2) => Math.round(x * 10 ** n) / 10 ** n;
const медиана = (а) => {
  const с = [...а].sort((x, y) => x - y);
  if (!с.length) return null;
  const м = Math.floor(с.length / 2);
  return с.length % 2 ? с[м] : (с[м - 1] + с[м]) / 2;
};

/** Цена заказчика по позиции: средняя предложений обоснования (так считает заказчик). */
function ценаПозиции(п) {
  const v = (п.prices || []).map((x) => x && x.value).filter((x) => typeof x === 'number' && x > 0);
  return v.length ? v.reduce((s, x) => s + x, 0) / v.length : null;
}

/** Единицы разного рода (метры и штуки) - не сравниваем; неизвестная - не мешает. */
function единицыСовместимы(a, b) {
  const x = видЕдиницы(a);
  const y = видЕдиницы(b);
  if (!x || !y) return true;
  return x.род === y.род;
}

/**
 * @param {{прайс: object, закупки: Array<{номер: string, группы?: string[], позиции: Array}>,
 *          протоколы: Array<object>, налог?: number, доставка?: number}} д
 */
function аналитикаНиши(д) {
  const налог = typeof д.налог === 'number' ? д.налог : 0.06;
  const доставка = typeof д.доставка === 'number' ? д.доставка : 0.08;
  if (!д.прайс || !д.прайс.ok || !д.прайс.позиции.length) {
    return { ok: false, причина: 'прайс не загружен: сравнивать ваши цены не с чем' };
  }

  // Строка прайса → закупки, где этот товар есть, с ценой заказчика.
  const поСтроке = new Map();
  const группыНиши = new Set();
  for (const з of д.закупки || []) {
    const видели = new Set();
    for (const п of з.позиции || []) {
      const цена = ценаПозиции(п);
      if (!цена || !п.name) continue;
      const с = сопоставить(п, д.прайс);
      if (!с.найдено || !единицыСовместимы(п.unit, с.строка.единица)) continue;
      const ключ = с.строка.строка;
      // Одна закупка на строку прайса - один раз (одинаковые позиции разных лотов).
      if (видели.has(ключ)) continue;
      видели.add(ключ);
      if (!поСтроке.has(ключ)) поСтроке.set(ключ, { строка: с.строка, закупки: [] });
      поСтроке.get(ключ).закупки.push({ номер: з.номер, цена, наименование: п.name, единица: п.unit || '' });
      for (const г of з.группы || []) группыНиши.add(г);
    }
  }

  // Падение цены и участники - протоколы той же группы ОКПД2, без единственной заявки.
  const вНише = (д.протоколы || []).filter((н) => !н.единственнаяЗаявка && typeof н.снижение === 'number'
    && [...(н.группыОкпд2 || []), н.группаОкпд2].filter(Boolean).some((г) => группыНиши.has(г)));
  const падение = распределение(вНише);
  const участники = медиана(вНише.map((н) => н.участников).filter((x) => typeof x === 'number' && x > 0));

  const товары = [];
  for (const { строка, закупки } of поСтроке.values()) {
    const ценаЗаказчика = медиана(закупки.map((з) => з.цена));
    const безубыточная = округлить(строка.цена * (1 + доставка) / (1 - налог));
    const ожидаемая = падение.медиана === null ? null : округлить(ценаЗаказчика * (1 - падение.медиана / 100));
    const запас = ожидаемая === null ? null : округлить(((ожидаемая - безубыточная) / ожидаемая) * 100, 1);
    let вывод;
    if (закупки.length < МИНИМУМ_ЗАКУПОК) вывод = `мало данных: закупок с этим товаром ${закупки.length}`;
    else if (ожидаемая === null) вывод = 'падение цены по нише не измерено';
    else if (запас >= 5) вывод = 'заходить: ваша цена ниже ожидаемой цены победы';
    else if (запас >= 0) вывод = 'на грани: запас меньше 5%';
    else вывод = 'ваша себестоимость выше ожидаемой цены победы';
    товары.push({
      товар: строка.наименование, единица: строка.единица || '', вашаЦена: строка.цена, безубыточная,
      закупок: закупки.length, ценаЗаказчика: округлить(ценаЗаказчика), ожидаемаяЦенаПобеды: ожидаемая, запасПроцент: запас, вывод,
      примеры: закупки.slice(0, 5).map((з) => ({ номер: з.номер, цена: округлить(з.цена), наименование: String(з.наименование).slice(0, 120) }))
    });
  }
  товары.sort((a, b) => b.закупок - a.закупок || String(a.товар).localeCompare(String(b.товар)));

  return {
    ok: true,
    падение: { n: падение.n, медиана: падение.медиана, q1: падение.q1, q3: падение.q3, достаточно: падение.достаточно, предупреждения: падение.предупреждения },
    участников: участники,
    группы: [...группыНиши],
    налог, доставка,
    строкПрайса: д.прайс.позиции.length,
    найденоТоваров: товары.length,
    товары
  };
}

module.exports = { аналитикаНиши, ценаПозиции, МИНИМУМ_ЗАКУПОК };
