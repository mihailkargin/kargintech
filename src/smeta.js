/**
 * ЛОКАЛЬНЫЙ СМЕТНЫЙ РАСЧЁТ (форма Минстроя № 421/пр, ГРАНД-Смета) - 25.10.2026.
 *
 * Решение владельца: «строительный и вся недвижка завязаны на тендерах… мы
 * должны считать безупречно». Работы по смете раньше получали отказ «считает
 * сметчик подрядчика». Подрядчику из сметы нужны две вещи:
 *   - материалы и оборудование, которые он закупает (здесь работает прайс
 *     клиента и поиск поставщиков), - строки ресурсов с кодом ФСБЦ
 *     («01.7.15.07-0012 | Дюбели … | 100 шт | 0.03 | | 0.03 | 978.09 | 1.36 | …»)
 *     и позиции по коммерческому предложению;
 *   - стоимость работ (оплата труда, машины, накладные, сметная прибыль) -
 *     одной строкой: «ВСЕГО по смете» минус материалы.
 *
 * Каждая строка материала проверена произведением: количество × цена за
 * единицу в текущих ценах = сумма строки (до 1,5%); не сошлось - строка не
 * берётся. Цены сметы - без НДС; если в итогах есть НДС, они пересчитываются
 * в цены с НДС (так считает НМЦК и так покупает подрядчик).
 *
 * @returns {null|{ok: true, positions: Array, header: string[], смета: object, issues: string[]}}
 */

const num = (c) => {
  const s = String(c || '').replace(/[\s ]/g, '').replace(',', '.');
  if (!/^-?\d+(\.\d+)?(e-?\d+)?$/i.test(s)) return null;
  const v = Number(s);
  return Number.isFinite(v) ? v : null;
};

const КОД_РЕСУРСА = /^(ФСБЦ-?)?\d{2}\.\d\.\d{2}\.\d{2}-\d{4}$|^ТЦ[_-]/i;
const КОД_МАШИНЫ = /^(ФСЭМ-?)?91\.\d{2}\.\d{2}-\d{3}$/i;
const ПО_КП = /коммерческ[а-яё]*\s+предложени|^прайс|^кп(\s|$)|^тц(\s|$)/i;
const НЕ_МАТЕРИАЛ = /^электроэнерги|^вода(\s|$)|^пар(\s|$)|^сжат[а-яё]*\s+воздух/i;

function этоСмета(текст) {
  return /локальн[а-яё]*\s+сметн[а-яё]*\s+расч[её]т/i.test(текст) && /всего\s+по\s+позиции/i.test(текст);
}

/** Количество и цена из чисел строки: последнее - сумма, пара q × p = сумма. */
function количествоИЦена(числа) {
  if (числа.length < 3) return null;
  const итог = числа[числа.length - 1];
  if (!(итог > 0)) return null;
  // Пара с наименьшим расхождением, допуск 0,5%: «базисная цена × индекс»
  // (9 090,65 × 1,7 = 15 454) отличается от суммы 15 577,74 всего на 0,8% и при
  // допуске 1,5% становилась «количеством и ценой» (кабель КСВВ,
  // 0321300225526000001); верная пара 1,008 × 15 454,11 сходится точно.
  let найдено = null; let лучшее = Infinity;
  for (let i = 0; i < числа.length - 1; i++) {
    for (let j = i + 1; j < числа.length - 1; j++) {
      const q = числа[i]; const p = числа[j];
      if (!(q > 0 && p > 0)) continue;
      const расхождение = Math.abs(q * p - итог);
      if (расхождение <= Math.max(итог * 0.005, 0.011) && расхождение < лучшее) { лучшее = расхождение; найдено = { количество: q, цена: p, сумма: итог }; }
      // Поправочный коэффициент к текущей цене после неё: «12 | 1 | 12 | 61.1
      // | 1.0075 | 738.7» - 12 × 61,1 × 1,0075 (0137600009126000242). Цена
      // единицы - цена × коэффициент.
      for (let l = j + 1; l < числа.length - 1; l++) {
        const к = числа[l];
        if (!(к >= 0.8 && к <= 1.3 && к !== 1)) continue;
        const р2 = Math.abs(q * p * к - итог);
        if (р2 <= Math.max(итог * 0.005, 0.011) && р2 < лучшее) { лучшее = р2; найдено = { количество: q, цена: p * к, сумма: итог }; }
      }
    }
  }
  return найдено;
}

function разборСметы(текст) {
  const т = String(текст || '');
  if (!этоСмета(т)) return null;
  const строки = т.split('\n');
  const материалы = new Map();
  let всегоБезНдс = null; let всегоПоСмете = null; let строкаИтога = '';
  let итогиНачаты = false; let материалыВИтогах = null; let оборудованиеВИтогах = null;
  for (const строка of строки) {
    const я = строка.split('\t').map((c) => c.replace(/ /g, ' ').trim()).filter(Boolean);
    if (!я.length) continue;
    const подпись = я.find((c) => num(c) === null) || '';
    if (/^всего\s+по\s+смете$/i.test(подпись)) {
      const ч = я.map(num).filter((v) => v !== null && v > 0);
      if (ч.length) { всегоПоСмете = ч[0]; строкаИтога = строка; }
      continue;
    }
    // «Итоги по смете: … Материалы 109813.19 … Оборудование 408.91» - сверка
    // своей суммы материалов с итогом сметщика.
    if (/^итоги\s+по\s+смете/i.test(подпись)) итогиНачаты = true;
    if (итогиНачаты && материалыВИтогах === null && /^материалы$/i.test(подпись)) {
      const ч = я.map(num).filter((v) => v !== null && v > 0); if (ч.length) материалыВИтогах = ч[0];
    }
    if (итогиНачаты && оборудованиеВИтогах === null && /^оборудование$/i.test(подпись)) {
      const ч = я.map(num).filter((v) => v !== null && v >= 0); if (ч.length) оборудованиеВИтогах = ч[0];
    }
    if (/^всего$/i.test(подпись) && всегоБезНдс === null) {
      const ч = я.map(num).filter((v) => v !== null && v > 0);
      if (ч.length) всегоБезНдс = ч[0];
      continue;
    }
    // Строка ресурса: код ФСБЦ / ТЦ, наименование, единица, числа. Позиция
    // по коммерческому предложению: № | «коммерческое предложение» | наименование | ед. | числа.
    let к = я.findIndex((c) => КОД_РЕСУРСА.test(c));
    const поКП = к === -1 && /^\d{1,4}$/.test(я[0]) && ПО_КП.test(я[1] || '');
    if (поКП) к = 1;
    if (к === -1 || я.some((c) => КОД_МАШИНЫ.test(c))) continue;
    const имя = я[к + 1] || '';
    const ед = я[к + 2] || '';
    if (имя.length < 3 || num(имя) !== null || НЕ_МАТЕРИАЛ.test(имя) || !/[а-яёa-z]/i.test(ед) || ед.length > 15) continue;
    const числа = я.slice(к + 3).map(num).filter((v) => v !== null);
    const кц = количествоИЦена(числа);
    if (!кц) continue;
    const ключ = `${имя.toLowerCase()}|${ед.toLowerCase()}|${кц.цена}`;
    const было = материалы.get(ключ);
    if (было) { было.количество += кц.количество; было.сумма += кц.сумма; }
    else материалы.set(ключ, { имя, ед, количество: кц.количество, цена: кц.цена, сумма: кц.сумма, цитата: строка });
  }
  if (!всегоПоСмете || !материалы.size) return null;
  // Цены сметы без НДС; итог «ВСЕГО по смете» - с НДС, если НДС выделен.
  const ндс = всегоБезНдс && всегоПоСмете > всегоБезНдс * 1.05 && всегоПоСмете < всегоБезНдс * 1.25 ? всегоПоСмете / всегоБезНдс : 1;
  const округ = (v) => Math.round(v * 100) / 100;
  const positions = [...материалы.values()].sort((a, b) => b.сумма - a.сумма).map((м) => {
    const цена = округ(м.цена * ндс);
    return { name: м.имя, quantity: Math.round(м.количество * 1e6) / 1e6, unit: м.ед, prices: [{ value: цена, column: 'смета' }],
      min: цена, max: цена, spreadPct: 0, sourceCount: 1, цитата: м.цитата, изСметы: true };
  });
  const суммаМатериалов = positions.reduce((s, п) => s + п.quantity * п.min, 0);
  const работы = округ(всегоПоСмете - суммаМатериалов);
  const issues = [];
  const поИтогам = материалыВИтогах !== null ? округ((материалыВИтогах + (оборудованиеВИтогах || 0)) * ндс) : null;
  const долясИтогов = поИтогам ? суммаМатериалов / поИтогам : null;
  if (долясИтогов !== null && (долясИтогов < 0.85 || долясИтогов > 1.15)) {
    issues.push(`материалов разобрано на ${Math.round(суммаМатериалов)} ₽, а в итогах сметы ${Math.round(поИтогам)} ₽ - часть строк ресурсов не прочитана`);
  }
  if (работы > 0) {
    positions.push({ name: 'Работы по смете (оплата труда, машины, накладные расходы, сметная прибыль)', quantity: 1, unit: 'смета',
      prices: [{ value: работы, column: 'смета' }], min: работы, max: работы, spreadPct: 0, sourceCount: 1, цитата: строкаИтога, работыСметы: true });
  } else {
    issues.push('сумма материалов не меньше итога сметы - материалы не отделены от работ');
  }
  return {
    ok: true, positions,
    header: ['локальный сметный расчёт: материалы и оборудование по строкам ресурсов, работы - итог сметы минус материалы'],
    смета: { всего: всегоПоСмете, безНдс: всегоБезНдс, ндсКоэф: округ(ндс * 10000) / 10000, материалов: материалы.size, суммаМатериалов: округ(суммаМатериалов), материалыПоИтогам: поИтогам, работы },
    issues
  };
}

module.exports = { разборСметы, этоСмета };
