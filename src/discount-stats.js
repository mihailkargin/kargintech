/**
 * Статистика снижения цены по протоколам прошлых закупок.
 *
 * ЗАЧЕМ. В расчёте стояло ожидаемое снижение 12% — выдуманное число. Владелец
 * убрал его 05.10.2026: «раз обоснования нет, зачем ты его пишешь». Этот модуль
 * заменяет догадку измерением.
 *
 * ГЛАВНОЕ ПРАВИЛО: ОДНОГО ЧИСЛА НА ВЫХОДЕ НЕ БЫВАЕТ. Снижение зависит от
 * условий, смешивать которые нельзя:
 *
 *   — СПОСОБ ЗАКУПКИ. В электронном аукционе цену давят шагами, снижение
 *     большое. В запросе котировок цена подаётся один раз, торга нет. В
 *     конкурсе цена лишь один из критериев рядом с опытом и сроками, поэтому
 *     снижение слабое. Среднее по трём способам не описывает ни один из них.
 *
 *   — ЧИСЛО УЧАСТНИКОВ, самый сильный множитель. Один участник выигрывает по
 *     начальной цене, снижение почти нулевое. Десять давят до предела.
 *
 *   — ЗАКУПКИ У ЕДИНСТВЕННОГО ПОСТАВЩИКА снижения не имеют по своей природе и
 *     выбрасываются ещё в protocol-page.js. Оставить их значит потянуть медиану
 *     к нулю и занизить ожидаемое снижение, то есть повторить ошибку с 12%.
 *
 * ПОЧЕМУ МЕДИАНА, А НЕ СРЕДНЕЕ. Одна закупка со снижением 70% (демпинг ради
 * входа на рынок) сдвигает среднее так, что оно перестаёт описывать типичный
 * случай. Медиана к одиночным выбросам нечувствительна. Среднее здесь не
 * считается вовсе, чтобы его нельзя было взять по ошибке.
 *
 * РАЗМЕР ВЫБОРКИ НАЗЫВАЕТСЯ ВСЕГДА — правило проекта. Статистика по трём
 * закупкам статистикой не является, и модуль обязан это говорить, а не выдавать
 * медиану трёх чисел за измерение.
 */

/** Ниже этого числа наблюдений результат не называется статистикой. */
const МИНИМУМ_ВЫБОРКИ = 10;

/**
 * Группы по числу участников. Границы выбраны по смыслу торга, а не ровными
 * числами: один участник — торга нет вовсе; два-три — слабый; четыре и больше —
 * настоящая конкуренция.
 */
const ГРУППЫ_УЧАСТНИКОВ = [
  { имя: 'один участник', от: 1, до: 1 },
  { имя: '2–3 участника', от: 2, до: 3 },
  { имя: '4–7 участников', от: 4, до: 7 },
  { имя: '8 и более участников', от: 8, до: Infinity }
];

/** Процентиль по готовому отсортированному массиву, линейной интерполяцией. */
function процентиль(отсортированные, доля) {
  if (!отсортированные.length) return null;
  if (отсортированные.length === 1) return отсортированные[0];
  const место = (отсортированные.length - 1) * доля;
  const низ = Math.floor(место);
  const верх = Math.ceil(место);
  if (низ === верх) return отсортированные[низ];
  const вес = место - низ;
  return отсортированные[низ] * (1 - вес) + отсортированные[верх] * вес;
}

const округлить1 = (n) => (n === null ? null : Math.round(n * 10) / 10);

/**
 * Считает распределение снижения по набору наблюдений.
 *
 * Наблюдения отбираются ДО вызова: здесь не фильтруется ни способ, ни число
 * участников. Смешать способы — ошибка вызывающего кода, и прятать её внутри
 * этой функции нельзя.
 *
 * @param {Array} наблюдения из protocol-page.наблюдение()
 * @returns {object} {n, медиана, q1, q3, мин, макс, достаточно, предупреждения}
 */
function распределение(наблюдения) {
  const значения = (наблюдения || [])
    .map((н) => (н && typeof н.снижение === 'number' ? н.снижение : null))
    .filter((v) => v !== null)
    .sort((a, b) => a - b);

  const предупреждения = [];
  const n = значения.length;

  if (n === 0) {
    return {
      n: 0, медиана: null, q1: null, q3: null, мин: null, макс: null,
      достаточно: false,
      предупреждения: ['наблюдений нет — снижение не измерено']
    };
  }

  const достаточно = n >= МИНИМУМ_ВЫБОРКИ;
  if (!достаточно) {
    предупреждения.push(
      `наблюдений ${n}, это меньше ${МИНИМУМ_ВЫБОРКИ} — не статистика, а отдельные случаи. `
      + 'Выдавать как ожидаемое снижение нельзя'
    );
  }

  // Разброс шире половины — признак того, что в выборку попали разные по природе
  // закупки. Чаще всего это смешанные способы или разное число участников.
  const q1 = процентиль(значения, 0.25);
  const q3 = процентиль(значения, 0.75);
  if (q3 - q1 > 25) {
    предупреждения.push(
      `половина случаев укладывается в ${округлить1(q1)}–${округлить1(q3)}% — разброс широкий. `
      + 'Вероятно, в выборке смешаны разные способы закупки или разное число участников'
    );
  }

  return {
    n,
    медиана: округлить1(процентиль(значения, 0.5)),
    q1: округлить1(q1),
    q3: округлить1(q3),
    мин: округлить1(значения[0]),
    макс: округлить1(значения[значения.length - 1]),
    достаточно,
    предупреждения
  };
}

/**
 * Раскладывает наблюдения по способу закупки и группе участников.
 *
 * Наблюдения без точно известного числа участников в группы НЕ попадают: у них
 * известно лишь «не менее десяти», потому что блок постраничности портал рисует
 * JavaScript. Но в разрез по способу они идут — для снижения число участников
 * знать не обязательно.
 */
function разложить(наблюдения) {
  const поСпособу = new Map();
  const поУчастникам = new Map();
  let безЧислаУчастников = 0;
  let единственныхЗаявок = 0;

  for (const н of (наблюдения || [])) {
    if (!н || typeof н.снижение !== 'number') continue;

    if (н.единственнаяЗаявка) единственныхЗаявок++;

    if (!поСпособу.has(н.способ)) поСпособу.set(н.способ, []);
    поСпособу.get(н.способ).push(н);

    if (typeof н.участников !== 'number' || н.участников <= 0) {
      безЧислаУчастников++;
      continue;
    }
    const группа = ГРУППЫ_УЧАСТНИКОВ.find((г) => н.участников >= г.от && н.участников <= г.до);
    if (!группа) continue;
    const ключ = `${н.способ} · ${группа.имя}`;
    if (!поУчастникам.has(ключ)) поУчастникам.set(ключ, []);
    поУчастникам.get(ключ).push(н);
  }

  // КАЖДЫЙ СРЕЗ СЧИТАЕТСЯ ДВАЖДЫ: СО ВСЕМИ НАБЛЮДЕНИЯМИ И БЕЗ ЕДИНСТВЕННЫХ
  // ЗАЯВОК. Выбирать за владельца нельзя — это его правило от 04.10.2026: «если
  // из разных источников результаты рознятся, нужно не выбирать и не выдумывать,
  // а показывать диапазон и его обоснование».
  //
  // Расхождение здесь закономерное, а не случайное. Закупка с единственной
  // заявкой — заключённый контракт, но торга в ней не было, и снижение в ней
  // почти нулевое: на сборе 05.10.2026 такие дали 1,6% и 14,0% против медиан
  // 18,5% и 24,3% у конкурентных. Смешав их, мы ЗАНИЗИЛИ бы ожидаемое снижение,
  // а занижение здесь — опасная сторона ошибки: система назовёт выгодным тендер,
  // который убыточен. Спрятав их, мы бы потеряли настоящий исход, который с
  // клиентом случится.
  const срез = (карта) => {
    const out = [];
    for (const [ключ, список] of карта) {
      const конкурентные = список.filter((н) => !н.единственнаяЗаявка);
      out.push({
        ключ,
        ...распределение(список),
        единственных: список.length - конкурентные.length,
        безЕдинственных: конкурентные.length === список.length
          ? null
          : распределение(конкурентные)
      });
    }
    return out.sort((a, b) => b.n - a.n);
  };

  return {
    всего: (наблюдения || []).length,
    безЧислаУчастников,
    единственныхЗаявок,
    поСпособу: срез(поСпособу),
    поУчастникам: срез(поУчастникам)
  };
}

/**
 * ВЕРДИКТ ПО ТЕНДЕРУ — сравнение двух фактов, а не прогноз.
 *
 * Первый факт — наша безубыточная цена: расходы известны, значит цена, ниже
 * которой контракт убыточен, выводится из них точно. Допущений не требует.
 *
 * Второй факт — цены, по которым РЕАЛЬНО выигрывали похожие закупки.
 *
 * Вывод — доля случаев, в которых победная цена оказалась выше нашей
 * безубыточной. Это проверяемое утверждение со ссылками на конкретные закупки,
 * а не оценка вероятности.
 *
 * ПОРЯДОК ОБЯЗАТЕЛЕН: без безубыточной цены вердикта нет. Она складывается из
 * расходов, а главный расход — закупка; пока не найден поставщик или не загружен
 * прайс клиента, её не существует. В таком случае возвращается отказ с причиной,
 * а не осторожный вывод.
 *
 * @param {number} безубыточность цена, ниже которой контракт убыточен
 * @param {Array} наблюдения похожие закупки
 * @returns {object} {исход, выше, всего, доля, минимальная, пояснение, issues}
 */
function вердикт(безубыточность, наблюдения) {
  const issues = [];

  if (typeof безубыточность !== 'number' || !Number.isFinite(безубыточность) || безубыточность <= 0) {
    return {
      исход: 'нет данных',
      выше: null, всего: 0, доля: null, минимальная: null,
      пояснение: 'безубыточная цена не посчитана — неизвестна стоимость закупки',
      issues: ['без стоимости закупки вердикт не выдаётся']
    };
  }

  const годные = (наблюдения || []).filter(
    (н) => н && typeof н.ценаПобеды === 'number' && Number.isFinite(н.ценаПобеды)
  );

  if (годные.length === 0) {
    return {
      исход: 'нет данных',
      выше: null, всего: 0, доля: null, минимальная: null,
      пояснение: 'похожих завершённых закупок не нашлось — сравнивать не с чем',
      issues: ['выборка пуста']
    };
  }

  if (годные.length < МИНИМУМ_ВЫБОРКИ) {
    issues.push(
      `похожих закупок всего ${годные.length}, это меньше ${МИНИМУМ_ВЫБОРКИ} — `
      + 'вывод опирается на отдельные случаи, а не на статистику'
    );
  }

  const выше = годные.filter((н) => н.ценаПобеды > безубыточность).length;
  const доля = Math.round((выше / годные.length) * 1000) / 10;
  const минимальная = Math.min(...годные.map((н) => н.ценаПобеды));

  // Границы исхода. Выбраны так, чтобы «идти» означало запас почти во всех
  // наблюдённых случаях, а не в большинстве: цена ошибки несимметрична —
  // убыточный контракт дороже упущенного тендера.
  let исход;
  if (доля >= 80) исход = 'идти';
  else if (доля >= 40) исход = 'идти осторожно';
  else исход = 'не идти';

  const пояснение = `в ${выше} из ${годные.length} похожих закупок победная цена была выше `
    + `вашей точки безубыточности. Самая низкая победная цена — ${Math.round(минимальная)} ₽`;

  return { исход, выше, всего: годные.length, доля, минимальная, пояснение, issues };
}

module.exports = {
  распределение,
  разложить,
  вердикт,
  процентиль,
  МИНИМУМ_ВЫБОРКИ,
  ГРУППЫ_УЧАСТНИКОВ
};
