/**
 * Вырезание контактных данных из тендерной документации.
 * Без внешних зависимостей — тело функции переносится в Code-ноду n8n как есть.
 *
 * ЗАЧЕМ ЭТО НУЖНО.
 * В модель уходит только публичная документация с портала, но портал публикует
 * в ней Ф.И.О., телефоны и почту контактных лиц заказчика. Формально это
 * персональные данные, пусть и общедоступные. Пока они вырезаются до отправки,
 * позиция «система не собирает и не хранит персональные данные» остаётся
 * правдой, и требования 152-ФЗ о локализации не возникают. Если этот модуль
 * отключить, рушится не техника, а весь ответ клиенту про безопасность.
 *
 * ПОЧЕМУ БЕЗ МОДЕЛИ.
 * Вырезание работает ДО отправки в модель. Значит, оно обязано быть
 * детерминированным: одинаковый вход — одинаковый выход, результат проверяется
 * тестами. Просить модель «убери персональные данные» нельзя — данные к этому
 * моменту уже улетели бы наружу.
 *
 * ГЛАВНАЯ ОПАСНОСТЬ — НЕ НЕДОЧИСТКА, А ПЕРЕЧИСТКА.
 * Имя человека и имя юрлица выглядят одинаково: «ГБУЗ им. Н.И. Пирогова»,
 * «ИП Иванов Иван Иванович». Первое — название больницы, второе — сторона
 * договора. Вырезать их нельзя: проверка контрагента пойдёт в пустоту, а
 * клиент увидит в уведомлении заказчика «[ФИО]». Такие случаи защищены
 * списком исключений KEEP_AFTER.
 */

const MASK = {
  email: '[EMAIL]',
  phone: '[ТЕЛЕФОН]',
  name: '[ФИО]',
  contact: '[КОНТАКТ]',
  snils: '[СНИЛС]',
  passport: '[ПАСПОРТ]'
};

/**
 * Границы слова для кириллицы.
 *
 * ЛОВУШКА: в JavaScript \b и \w считают буквами только латиницу и цифры.
 * Поэтому \bИНН не совпадает никогда, а паспорт\w* не добирает окончание.
 * Шаблон с русским словом и \b выглядит рабочим, тесты на нём написать легко —
 * и он молча не находит ничего. Здесь это означало бы, что защита реквизитов
 * не работает, а телефоны местами не вырезаются.
 */
const LB = '(?<![А-Яа-яЁёA-Za-z0-9])'; // граница слева
const RB = '(?![А-Яа-яЁёA-Za-z0-9])';  // граница справа

/**
 * Реквизиты, которые вырезать НЕЛЬЗЯ: они относятся к юрлицу, а не к человеку,
 * и нужны для проверки контрагента. ИНН из 10-12 цифр и счёт из 20 легко
 * принять за телефон, поэтому они выводятся из-под правил заранее.
 */
const KEEP_PATTERNS = [
  new RegExp(LB + '(?:ИНН|КПП|ОГРНИП|ОГРН|ОКПО|ОКТМО|ОКАТО|БИК|КБК|ОКВЭД|ОКПД2?)\\s*[:№]?\\s*[\\d.\\-/]{5,25}', 'gi'),
  new RegExp(LB + '(?:р\\/с|к\\/с|л\\/с|р\\/сч|расч[ёе]тный\\s+сч[ёе]т)\\s*[:№]?\\s*[\\d\\s-]{15,30}', 'gi'),
  // Денежные суммы: «8 000 000 000 ₽» по цифрам не отличается от телефона.
  /\d[\d\s.,]*\s*(?:₽|руб\.?|рубл[а-яё]*|коп\.?)/gi,
  // Даты: 19.09.2026 и 19.09.26
  /\b\d{1,2}\.\d{1,2}\.\d{2,4}\b/g,
  // Ссылки: в них встречаются и цифры, и почтоподобные фрагменты.
  /https?:\/\/\S+/gi,
  // Реестровые номера закупок: 44-ФЗ — 19 цифр, 223-ФЗ — 11.
  //
  // ЛОВУШКА: телефон без форматирования — 84951234567 — это тоже ровно 11 цифр.
  // Защитив все 11-значные последовательности, мы бы навсегда спрятали от
  // вырезания часть телефонов, и это не проявилось бы ни одной ошибкой в логах.
  // Номера 223-ФЗ начинаются с 3 (они строятся от года), телефоны — с 7 или 8,
  // поэтому номера с 7 и 8 в начале под защиту не берём.
  /\b\d{19}\b|\b(?![78])\d{11}\b/g
];

/**
 * Перед этими словами идёт имя юрлица или ИП, а не контактного лица.
 * Проверяется текст непосредственно слева от найденного имени.
 */
const KEEP_AFTER = new RegExp(
  LB + '(?:им\\.|имени|ИП|И\\.\\s?П\\.|индивидуальн[а-яё]*\\s+предпринимател[а-яё]*' +
  '|КФХ|глав[а-яё]*\\s+КФХ|нотариус[а-яё]*)\\s*$',
  'i'
);

const EMAIL = /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g;

/**
 * Телефон с кодом страны: +7 (495) 123-45-67, 8 495 123 45 67, 84951234567.
 * Требуем ровно 11 цифр и запрещаем цифру по краям — иначе шаблон откусывает
 * куски более длинных числовых последовательностей.
 */
const PHONE = /(?<!\d)(?:\+7|8)[\s\-(]{0,3}\d{3,4}[\s\-)]{0,3}\d{2,3}[\s-]?\d{2}[\s-]?\d{2}(?!\d)(?:\s*(?:доб\.?|вн\.?|внутренний)\s*\d{1,5})?/g;

const SNILS = /(?<!\d)\d{3}-\d{3}-\d{3}\s?\d{2}(?!\d)/g;
const PASSPORT = new RegExp(
  LB + '(?:паспорт[а-яё]*|сери[яи]\\s+и\\s+номер)\\s*[:№]?\\s*\\d{2}\\s?\\d{2}\\s?№?\\s?\\d{6}(?!\\d)',
  'gi'
);

/**
 * Подписи, после которых значение целиком является контактными данными.
 * Слово «Исполнитель» намеренно не включено: в тексте контракта так называется
 * сторона договора, и вырезание съело бы условия исполнения.
 */
const LABELED = new RegExp(
  '(Контактное\\s+лицо|Ответственное\\s+лицо|Ответственный\\s+исполнитель|Контактный\\s+телефон' +
  '|Телефон\\s+для\\s+связи|Телефон|Факс|Адрес\\s+электронной\\s+почты|Электронная\\s+почта|E-?mail' +
  '|Ф\\.?\\s?И\\.?\\s?О\\.?|Фамилия,?\\s*имя,?\\s*отчество)' +
  '\\s*[:–—-]\\s*([^\\n;|]{1,120})',
  'gi'
);

const SURNAME = '[А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?';
const PATRONYMIC = '[А-ЯЁ][а-яё]*(?:ович|евич|ьевич|овна|евна|ьевна|ична|инична)[а-яё]{0,3}';

/**
 * Имя человека узнаём по отчеству или по инициалам, а не по «трём словам
 * с большой буквы». Три слова с большой буквы — это ещё и «Управление
 * Федерального Казначейства», и вырезать такое нельзя.
 * Трёхсловные формы стоят первыми: разбор идёт слева направо и берёт
 * первое совпадение, поэтому короткая форма не должна перехватывать длинную.
 */
const FULL_NAME = new RegExp(
  [
    `${SURNAME}\\s+[А-ЯЁ][а-яё]+\\s+${PATRONYMIC}`,   // Иванов Иван Иванович
    `[А-ЯЁ][а-яё]+\\s+${PATRONYMIC}\\s+${SURNAME}`,   // Иван Иванович Иванов
    `${SURNAME}\\s+[А-ЯЁ]\\.\\s?[А-ЯЁ]\\.`,           // Иванов И.И.
    `[А-ЯЁ]\\.\\s?[А-ЯЁ]\\.\\s?${SURNAME}`,           // И.И. Иванов
    `[А-ЯЁ][а-яё]+\\s+${PATRONYMIC}`                  // Иван Иванович
  ].join('|'),
  'g'
);

/** Символ-заполнитель для защищённых фрагментов. В документации не встречается. */
const SENTINEL = '\u0001';

/**
 * Прячет фрагменты, которые нельзя вырезать, чтобы правила до них не добрались.
 * @returns {{text: string, restore: function(string): string}}
 */
function protect(text) {
  const kept = [];
  let out = text;
  for (const pattern of KEEP_PATTERNS) {
    out = out.replace(pattern, (m) => {
      kept.push(m);
      return `${SENTINEL}${kept.length - 1}${SENTINEL}`;
    });
  }
  const restore = (s) =>
    s.replace(new RegExp(`${SENTINEL}(\\d+)${SENTINEL}`, 'g'), (_, i) => kept[Number(i)]);
  return { text: out, restore };
}

/** Есть ли слева от совпадения признак имени юрлица или ИП. */
function isLegalEntityName(text, index) {
  return KEEP_AFTER.test(text.slice(Math.max(0, index - 60), index));
}

/**
 * Убирает контактные данные из текста.
 *
 * @param {string} raw текст документа
 * @returns {{text: string, removed: object, total: number, log: Array<object>}}
 *   text — то, что можно отправлять в модель;
 *   removed — сколько чего вырезано, для аудит-лога;
 *   log — тип, позиция и длина каждого вырезанного фрагмента.
 *
 * ВАЖНО: в log не попадает само значение. Журнал хранится, а хранение
 * вырезанных телефонов и Ф.И.О. — это ровно то, чего мы избегаем. Иначе
 * персональные данные просто переехали бы из документа в лог.
 */
function redactContacts(raw) {
  const removed = { emails: 0, phones: 0, names: 0, labeled: 0, snils: 0, passports: 0 };
  const log = [];
  const note = (type, index, length) => log.push({ type, at: index, length });

  const { text: protectedText, restore } = protect(String(raw || ''));
  let out = protectedText;

  // Порядок важен. Сначала подписанные блоки: они забирают значение целиком,
  // включая иностранные имена и фамилии без отчества, которые шаблон не поймает.
  out = out.replace(LABELED, (match, label, value, index) => {
    if (value.includes(SENTINEL)) return match; // внутри защищённый реквизит
    removed.labeled++;
    note(`подпись «${label.trim()}»`, index, match.length);
    return `${label}: ${MASK.contact}`;
  });

  out = out.replace(SNILS, (m, index) => {
    removed.snils++;
    note('СНИЛС', index, m.length);
    return MASK.snils;
  });

  out = out.replace(PASSPORT, (m, index) => {
    removed.passports++;
    note('паспорт', index, m.length);
    return MASK.passport;
  });

  out = out.replace(EMAIL, (m, index) => {
    removed.emails++;
    note('email', index, m.length);
    return MASK.email;
  });

  out = out.replace(PHONE, (m, index) => {
    removed.phones++;
    note('телефон', index, m.length);
    return MASK.phone;
  });

  out = out.replace(FULL_NAME, (m, ...rest) => {
    const index = rest[rest.length - 2];
    if (isLegalEntityName(out, index)) return m;
    removed.names++;
    note('ФИО', index, m.length);
    return MASK.name;
  });

  const total = Object.values(removed).reduce((a, b) => a + b, 0);
  return { text: restore(out), removed, total, log };
}

/**
 * Контрольная проверка перед отправкой наружу.
 *
 * Отдельная функция, а не доверие к redactContacts, потому что цена ошибки
 * несимметрична: одна утёкшая страница с телефонами обесценивает весь разговор
 * о безопасности. Вызывается на результате вырезания; findings не пусты —
 * отправку не делать, слать алерт владельцу сервиса.
 *
 * @param {string} text текст ПОСЛЕ вырезания
 * @returns {{safe: boolean, findings: Array<string>}}
 */
function isSafeToSend(text) {
  const findings = [];
  const { text: protectedText } = protect(String(text || ''));

  if (EMAIL.test(protectedText)) findings.push('в тексте остался адрес электронной почты');
  EMAIL.lastIndex = 0;
  if (PHONE.test(protectedText)) findings.push('в тексте остался телефон');
  PHONE.lastIndex = 0;
  if (SNILS.test(protectedText)) findings.push('в тексте остался СНИЛС');
  SNILS.lastIndex = 0;

  // Имя, не прикрытое исключением, — это пропущенное контактное лицо.
  let m;
  FULL_NAME.lastIndex = 0;
  while ((m = FULL_NAME.exec(protectedText)) !== null) {
    if (!isLegalEntityName(protectedText, m.index)) {
      findings.push('в тексте осталось имя, похожее на контактное лицо');
      break;
    }
  }
  FULL_NAME.lastIndex = 0;

  return { safe: findings.length === 0, findings };
}

module.exports = { redactContacts, isSafeToSend, MASK };
