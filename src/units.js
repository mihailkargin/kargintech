/**
 * СВЕРКА ЕДИНИЦЫ ЦЕНЫ ПОСТАВЩИКА С ЕДИНИЦЕЙ ПОЗИЦИИ — 21.10.2026.
 *
 * Проверка «цена в разы выше или ниже предложений обоснования НМЦК»
 * (estimate-run.js, отсеятьНесопоставимые) работает, только если в
 * документации есть цены. У позиций из ТЗ без цен (в пакетных прогонах -
 * 9 закупок из 15) сравнивать было не с чем, и цена упаковки молча шла в
 * расчёт как цена штуки. Живой случай: пенокартон 2 804 ₽ за упаковку на
 * 40 листов при цене за лист.
 *
 * Правила:
 *   — единицы совпали - цена как есть;
 *   — у поставщика фасовка (упаковка, пачка, рулон, бухта…), у позиции
 *     штуки, листы, метры или килограммы, и в тексте со страницы сказано,
 *     сколько их в фасовке - цена делится, пересчёт называется в пояснении;
 *   — фасовка без числа, или единицы разного рода (метры и килограммы) -
 *     цена в расчёт не идёт, причина называется. Ненайденная цена видна
 *     сразу, неверная портит расчёт молча;
 *   — единица неизвестна хотя бы с одной стороны - решить нельзя, цена
 *     остаётся (её дальше проверяет сравнение с обоснованием НМЦК).
 *
 * Сетевых обращений нет.
 */

const БАЗОВЫЕ = [
  ['шт', /^(шт|штук[а-яё]*|ед|единиц[а-яё]*|изд[а-яё]*|экз[а-яё]*)\.?$/],
  ['лист', /^(лист[а-яё]*|л)\.?$/],
  ['м', /^(м|метр[а-яё]*|пог\.?\s*м|п\.?\s*м|мп)\.?$/],
  ['кг', /^(кг|килограмм[а-яё]*)\.?$/],
  ['т', /^(т|тонн[а-яё]*|тн)\.?$/],
  ['л', /^(литр[а-яё]*)\.?$/],
  ['м2', /^(м2|м²|кв\.?\s*м)\.?$/]
];
const ФАСОВКИ = /^(упак[а-яё]*|уп|пач[а-яё]*|пачк[а-яё]*|короб[а-яё]*|кор|набор[а-яё]*|рул[а-яё]*|рулон[а-яё]*|бухт[а-яё]*|бобин[а-яё]*|компл[а-яё]*|комплект[а-яё]*|блок[а-яё]*|пак[а-яё]*|пакет[а-яё]*|ящик[а-яё]*|пачк)\.?$/;

/** Единица к виду: {род: 'шт'|'лист'|'м'|…|'фасовка', слово} или null. */
function видЕдиницы(u) {
  const s = String(u || '').toLowerCase().replace(/ё/g, 'е').replace(/[()]/g, '').trim().replace(/^за\s+/, '').replace(/^1\s*/, '');
  if (!s) return null;
  for (const [род, re] of БАЗОВЫЕ) if (re.test(s)) return { род, слово: s };
  if (ФАСОВКИ.test(s)) return { род: 'фасовка', слово: s };
  return null;
}

/** «Пачка», «упаковка», «уп» - одно и то же; рулон и бухта - другое. */
function группаФасовки(слово) {
  if (/^(уп|пач|пак)/.test(слово)) return 'упаковка';
  if (/^(рул|бух|боб)/.test(слово)) return 'рулон';
  if (/^(кор|ящ)/.test(слово)) return 'коробка';
  if (/^(компл|набор)/.test(слово)) return 'набор';
  return слово.slice(0, 3);
}

/** Слова, которыми на страницах пишут базовую единицу внутри фасовки. */
const СЛОВО_РОДА = {
  шт: 'шт\\.?|штук[а-яё]*|ед\\.?|изделий',
  лист: 'лист[а-яё]*|л\\.',
  м: 'м\\.?|метр[а-яё]*|пог\\.?\\s*м',
  кг: 'кг',
  л: 'л\\.?|литр[а-яё]*',
  т: 'т\\.?|тонн[а-яё]*'
};

/** Сколько базовых единиц в фасовке, по тексту со страницы. Несколько разных чисел - не решаем. */
function числоВФасовке(текст, род) {
  const слово = СЛОВО_РОДА[род];
  if (!слово) return null;
  const t = String(текст || '').toLowerCase().replace(/ё/g, 'е');
  // «40 листов», «по 500 шт», «100 м в бухте». Граница после единицы - не буква:
  // «м» не должно совпасть с началом «мм», «материал».
  const re = new RegExp(`(?:^|[^0-9a-zа-я.,])(\\d{1,5})\\s*(?:${слово})(?![а-яa-z0-9])`, 'g'); // кириллица-ок
  const числа = new Set();
  for (const m of t.matchAll(re)) {
    const n = Number(m[1]);
    if (n >= 2 && n <= 10000) числа.add(n);
  }
  return числа.size === 1 ? [...числа][0] : null;
}

/**
 * @param {{unit?: string}} позиция
 * @param {{price: number, unit?: string, evidence?: string}} цена
 * @returns {{вид: 'та же'|'пересчитано'|'другая'|'неизвестно', цена: number, пояснение: string}}
 */
function сверитьЕдиницу(позиция, цена) {
  const п = видЕдиницы(позиция && позиция.unit);
  const с = видЕдиницы(цена && цена.unit);
  const как = { вид: 'неизвестно', цена: цена.price, пояснение: '' };
  if (!п || !с) return как;
  if (п.род === с.род && (п.род !== 'фасовка' || группаФасовки(п.слово) === группаФасовки(с.слово))) return { ...как, вид: 'та же' };
  if (с.род === 'фасовка' && п.род !== 'фасовка') {
    const n = числоВФасовке(цена.evidence, п.род);
    if (n) {
      return {
        вид: 'пересчитано',
        цена: Math.round((цена.price / n) * 100) / 100,
        пояснение: `цена за ${с.слово} (${n} ${п.род}) ${цена.price} ₽ пересчитана за ${п.род}`
      };
    }
    return { ...как, вид: 'другая', пояснение: `цена за ${с.слово}, а нужна за ${п.слово}; сколько в фасовке, на странице не указано` };
  }
  return { ...как, вид: 'другая', пояснение: `цена за ${с.слово}, а нужна за ${п.слово}` };
}

/**
 * Род единицы услуги или объёма: площадь, объём, время, срок; прочее - null
 * (не сравниваем). Ставка прайса «за м²» на позицию «6 мес» дала бы цену в разы
 * ниже настоящей (услуги, 23.10.2026) - при разном роде цена не подставляется.
 */
function родЕдиницы(е) {
  const т = String(е || '').toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, '');
  if (!т) return null;
  if (/^(м2|м²|кв\.?м\.?|квм|кв\.метр)/.test(т)) return 'площадь';
  if (/^(м3|м³|куб\.?м\.?|кубм|куб\.метр)/.test(т)) return 'объём';
  if (/^(час|ч\.?$|чел\.?-?ч|нормо-?час|г\.ч)/.test(т)) return 'время';
  if (/^(мес|месяц|год|лет|сут|день|дн|квартал)/.test(т)) return 'срок';
  return null;
}

module.exports = { сверитьЕдиницу, видЕдиницы, числоВФасовке, родЕдиницы };
