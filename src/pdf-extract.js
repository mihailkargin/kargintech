/** Признак честного отказа модели. */
const НЕТ_ТАБЛИЦЫ = 'ТАБЛИЦЫ НЕТ';

/**
 * Собирает запрос к модели на чтение PDF.
 *
 * @param {string} имяФайла для сообщения об ошибке и для журнала
 * @param {Buffer} буфер содержимое PDF
 * @param {object} [опции] {модель, max_tokens}
 * @returns {{ok: boolean, request?: object, issue?: string}}
 */
function buildPdfTableRequest(имяФайла, буфер, опции = {}) {
  const имя = String(имяФайла || 'файл.pdf');

  if (!буфер || !буфер.length) {
    return { ok: false, issue: `«${имя}»: файл пустой` };
  }
  if (буфер.length > ПРЕДЕЛ_БАЙТ) {
    const мб = (буфер.length / 1024 / 1024).toFixed(1);
    return {
      ok: false,
      issue: `«${имя}»: ${мб} МБ, это больше предела в 20 МБ. `
        + 'Файл такого размера модель не примет'
    };
  }
  // Признак PDF — четыре байта в начале. Расширение врёт, и отправлять
  // в модель картинку под именем .pdf значит платить за отказ.
  if (буфер.slice(0, 4).toString('latin1') !== '%PDF') {
    return { ok: false, issue: `«${имя}»: содержимое не является PDF` };
  }

  return {
    ok: true,
    request: {
      model: опции.модель || опции.model || 'claude-sonnet-5-5',
      max_tokens: опции.max_tokens || MAX_TOKENS,

      // Кэширование: инструкция одинакова для всех файлов и всех клиентов,
      // поэтому выносится в system и помечается к кэшированию. Сам PDF
      // у каждой закупки свой и кэшироваться не может.
      cache_control: { type: 'ephemeral' },
      system: [
        {
          type: 'text',
          text: опции.вид === 'тз' ? ИНСТРУКЦИЯ_ТЗ : ИНСТРУКЦИЯ,
          cache_control: { type: 'ephemeral' }
        }
      ],

      messages: [{
        role: 'user',
        content: [
          // Документ ставится ПЕРЕД текстом: так требует формат запроса.
          // Base64 без переводов строк — иначе API отвергает данные.
          {
            type: 'document',
            source: {
              type: 'base64',
              media_type: 'application/pdf',
              data: буфер.toString('base64')
            }
          },
          {
            type: 'text',
            // Список товаров — в переменной части, после документа: инструкция
            // в system остаётся одинаковой и кэшируется.
            //
            // Зачем список: выход модели в пять раз дороже входа. Переписать
            // всё ТЗ на 57 позиций стоило $0,20 (замер 14.10.2026), а для
            // поиска нужны характеристики пяти товаров.
            text: Array.isArray(опции.товары) && опции.товары.length
              ? `Имя файла: ${имя}\n\nНужны строки только этих товаров:\n`
                + опции.товары.map((т, i) => `${i + 1}) ${т}`).join('\n')
              : `Имя файла: ${имя}`
          }
        ]
      }]
    }
  };
}

/**
 * Разбирает и ПРОВЕРЯЕТ ответ модели.
 *
 * Возвращает текст в том виде, который ждёт `parseNmckTable`, либо честный
 * отказ с названной причиной.
 *
 * @param {object|string} ответ тело ответа Claude API либо готовый текст
 * @returns {{ok: boolean, текст?: string, строк?: number, усечён?: boolean, issue?: string}}
 */
function parsePdfTableResponse(ответ) {
  let текст = '';
  let причинаОстановки = '';

  if (typeof ответ === 'string') {
    текст = ответ;
  } else if (ответ && typeof ответ === 'object') {
    причинаОстановки = String(ответ.stop_reason || '');

    // Модель отказалась отвечать. Проверять ДО чтения содержимого:
    // при отказе блоков с текстом может не быть вовсе.
    if (причинаОстановки === 'refusal') {
      const пояснение = (ответ.stop_details && ответ.stop_details.explanation) || '';
      return {
        ok: false,
        issue: 'модель отказалась читать документ'
          + (пояснение ? ` (${пояснение})` : '')
      };
    }

    текст = (ответ.content || [])
      .filter((b) => b && b.type === 'text')
      .map((b) => b.text)
      .join('\n');
  }

  текст = String(текст || '').replace(/\r\n/g, '\n').trim();

  if (!текст) {
    return { ok: false, issue: 'модель вернула пустой ответ' };
  }

  // Честный отказ модели. Распознаём до остальных проверок: эта строка
  // табуляций не содержит, и иначе её отвергла бы проверка формата ниже.
  if (текст.toUpperCase().indexOf(НЕТ_ТАБЛИЦЫ) === 0) {
    return { ok: false, issue: 'в документе нет таблицы с позициями', нетТаблицы: true };
  }

  // ОБРЕЗАННЫЙ ОТВЕТ — САМАЯ ОПАСНАЯ ИЗ ОШИБОК ЗДЕСЬ.
  //
  // При достижении предела вывода модель обрывается на середине таблицы.
  // Текст при этом выглядит правильным, разбор отработает и вернёт позиции —
  // просто не все. Смета соберётся, сумма будет правдоподобной и заниженной,
  // а клиент сравнит её с начальной ценой контракта и увидит несуществующий
  // запас. Поэтому обрыв называется вслух, а смета помечается неполной.
  const усечён = причинаОстановки === 'max_tokens';

  // Проверка формата: модель обязана была разделить ячейки табуляцией.
  // Без табуляций разбор увидит одну колонку и не найдёт ни одной позиции,
  // а выглядеть это будет как «в документе нет таблицы».
  if (текст.indexOf('\t') === -1) {
    return {
      ok: false,
      issue: 'модель вернула текст без табуляций — таблицу разобрать нечем. '
        + 'Первые 120 знаков ответа: ' + текст.slice(0, 120).replace(/\n/g, ' ⏎ ')
    };
  }

  // Пояснения вокруг таблицы ломают разбор: строка текста может быть принята
  // за шапку. Отрезаем строки без табуляций по краям, середину не трогаем —
  // внутри таблицы такая строка может быть подзаголовком раздела.
  const строки = текст.split('\n');
  let от = 0;
  let до = строки.length - 1;
  while (от <= до && строки[от].indexOf('\t') === -1) от++;
  while (до >= от && строки[до].indexOf('\t') === -1) до--;
  const очищенный = строки.slice(от, до + 1).join('\n');

  if (!очищенный.trim()) {
    return { ok: false, issue: 'после очистки от пояснений таблицы не осталось' };
  }

  return {
    ok: true,
    текст: очищенный,
    строк: очищенный.split('\n').length,
    отброшеноСтрок: строки.length - (до - от + 1),
    усечён
  };
}

/**
 * Вывод pdftotext -layout → вид, который ждут разборы таблиц проекта.
 *
 * pdftotext передаёт колонки пробелами, разборы ждут ячейки через табуляцию
 * (так их даёт чтение Word). Два и больше пробела подряд — граница ячеек,
 * одиночный пробел — внутри ячейки. Ведущие пробелы снимаются: иначе строка
 * начнётся с пустой ячейки, и признак «новая строка таблицы с номером»
 * (`spec.js`) не сработает. Разрывы страниц (\f) выбрасываются.
 *
 * Чего это не умеет, сказано прямо: ячейку, в которой сам текст содержит два
 * пробела подряд, разорвёт на две. Поэтому результат идёт через самопроверку
 * разбора, как любой другой текст.
 */
function текстPdfВТаблицу(текст) {
  return String(текст || '')
    .split(/\r?\n/)
    .map((строка) => строка.replace(/\f/g, '').trim().replace(/ {2,}/g, '\t'))
    .join('\n');
}

