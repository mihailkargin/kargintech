/**
 * КАТАЛОГИ ПОСТАВЩИКОВ И ПОДРЯДЧИКОВ НИШИ - решение владельца 30.10.2026:
 * «зачем каждый тендер заново искать поставщиков, если мы делаем это в начале
 * и это входит в оплату за 60к». На внедрении модель находит поставщиков ниши
 * в целом (оптовики со всем ассортиментом, подрядчики всего комплекса работ),
 * код скачивает их прайсы целиком и обновляет раз в неделю. В тендере каждая
 * позиция сверяется с этими прайсами кодом - бесплатно, по ВСЕМ позициям.
 *
 * Откуда берётся каталог, по убыванию надёжности:
 *   1. файл прайса (Excel, CSV) - разбирается тем же `разобратьПрайс`, что
 *      прайс клиента;
 *   2. выгрузка YML для Яндекс.Маркета - стандартный формат интернет-магазинов;
 *   3. страница расценок с таблицей (подрядчики: «Монтаж ... | м² | 450»);
 *   4. страницы товаров по карте сайта - цена из разметки schema.org.
 * Прайса нет ни в одном виде - поставщик остаётся контактом «прайс закрыт».
 *
 * Сверка позиции с каталогом строже, чем с прайсом клиента: каталог оптовика -
 * десятки тысяч строк, и короткая строка «Бумага» по правилам прайса клиента
 * совпала бы с любой бумагой. Здесь: не меньше двух общих значимых слов,
 * числа строки каталога есть в позиции, хотя бы одно число позиции есть в
 * строке, марки не противоречат, товар не сопоставляется с работой.
 *
 * Данные - публичные сведения с сайтов, каталоги общие для всех клиентов.
 * Прайсы клиентов сюда не попадают. Сетевых обращений в модуле нет.
 */

const path = require('path');
const { нормализовать, похожесть, числаИз, слова, маркиРасходятся, ПОРОГ } =
  require(path.join(__dirname, 'price-list'));
const { видПозиции } = require(path.join(__dirname, 'item-kind'));

/** Каталог старше этого в расчёт не идёт: цена без свежей даты - не цена. */
const СРОК_ДНЕЙ = 14;
/** Обновлять каталог, когда он старше. */
const ОБНОВЛЯТЬ_ДНЕЙ = 7;
/** Меньше двух общих слов - не совпадение, а соседство по одному слову. */
const ОБЩИХ_СЛОВ_МИН = 2;

// ----------------------------------------------------------------- разметка

function раскрыть(s) {
  return String(s || '')
    .replace(/<!\[CDATA\[([\s\S]*?)\]\]>/g, '$1')
    .replace(/&nbsp;/gi, ' ')
    .replace(/&quot;/gi, '"')
    .replace(/&apos;|&#39;/gi, "'")
    .replace(/&laquo;|&raquo;/gi, '"')
    .replace(/&[mn]dash;/gi, '-')
    .replace(/&#(\d+);/g, (_, n) => String.fromCharCode(Number(n)))
    .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCharCode(parseInt(n, 16)))
    .replace(/&lt;/gi, '<').replace(/&gt;/gi, '>')
    .replace(/&amp;/gi, '&')
    .replace(/\s+/g, ' ')
    .trim();
}

function тег(блок, имя) {
  const m = new RegExp(`<${имя}(?:\\s[^>]*)?>([\\s\\S]*?)</${имя}>`, 'i').exec(блок);
  return m ? раскрыть(m[1]) : '';
}

function деньги(v) {
  const s = String(v === undefined || v === null ? '' : v).replace(/(₽|руб\.?|р\.)/gi, '').replace(/\s/g, '').replace(',', '.');
  if (!/^\d+(\.\d+)?$/.test(s)) return null;
  const n = Number(s);
  return Number.isFinite(n) && n > 0 ? Math.round(n * 100) / 100 : null;
}

/**
 * Выгрузка YML (Яндекс.Маркет): <offer> с <name>, <price>, <currencyId>, <url>.
 * Не в рублях и «нет в наличии» не берутся: цену в валюте пересчитывать не по
 * чему, а цена товара, которого нет, - вчерашняя.
 */
function разобратьYml(xml) {
  const т = String(xml || '');
  if (!/<yml_catalog|<offers/i.test(т)) return { ok: false, отказ: 'это не выгрузка YML: нет <yml_catalog> и <offers>', позиции: [] };
  const позиции = [];
  let пропущено = 0;
  for (const m of т.matchAll(/<offer\b([^>]*)>([\s\S]*?)<\/offer>/gi)) {
    const атр = m[1];
    const б = m[2];
    if (/available\s*=\s*["']false["']/i.test(атр)) { пропущено++; continue; }
    const валюта = тег(б, 'currencyId').toUpperCase();
    if (валюта && !/^RU[BR]$/.test(валюта)) { пропущено++; continue; }
    const имя = тег(б, 'name') || [тег(б, 'typePrefix'), тег(б, 'vendor'), тег(б, 'model')].filter(Boolean).join(' ');
    const цена = деньги(тег(б, 'price'));
    if (!имя || цена === null) { пропущено++; continue; }
    const ед = (/<param\s+name=["']ед[^"']*["'][^>]*>([\s\S]*?)<\/param>/i.exec(б) || [])[1];
    позиции.push({ наименование: имя, цена, единица: ед ? раскрыть(ед) : '', url: тег(б, 'url'), артикул: тег(б, 'vendorCode') });
  }
  if (!позиции.length) return { ok: false, отказ: `в выгрузке нет предложений с ценой в рублях (пропущено ${пропущено})`, позиции: [] };
  return { ok: true, позиции, пропущено };
}

/**
 * Товар со страницы - только из разметки schema.org Product (JSON-LD), одна
 * цена в рублях. Несколько товаров на странице - это список, а не карточка:
 * какая цена к какому имени, из разметки не следует, страница не берётся.
 */
function товарИзСтраницы(html) {
  const товары = [];
  for (const m of String(html || '').matchAll(/<script[^>]*application\/ld\+json[^>]*>([\s\S]*?)<\/script>/gi)) {
    let j; try { j = JSON.parse(m[1].trim()); } catch (e) { continue; }
    const обойти = (о) => {
      if (!о || typeof о !== 'object') return;
      if (Array.isArray(о)) { о.forEach(обойти); return; }
      const тип = [].concat(о['@type'] || []).map(String);
      if (тип.includes('Product')) товары.push(о);
      if (о['@graph']) обойти(о['@graph']);
    };
    обойти(j);
  }
  if (!товары.length) return товарИзMicrodata(html);
  if (товары.length !== 1) return null;
  const т = товары[0];
  const имя = раскрыть(т.name);
  const предложения = [].concat(т.offers || []);
  const цены = new Set();
  for (const о of предложения) {
    if (!о || typeof о !== 'object') continue;
    const валюта = String(о.priceCurrency || '').toUpperCase();
    if (валюта && !/^RU[BR]$/.test(валюта)) continue;
    if (/OutOfStock|Discontinued/i.test(String(о.availability || ''))) continue;
    const ц = деньги(о.price);
    if (ц !== null) цены.add(ц);
    // Диапазон «от-до» - не одна цена; берётся, только если края совпали.
    else if (деньги(о.lowPrice) !== null && деньги(о.lowPrice) === деньги(о.highPrice)) цены.add(деньги(о.lowPrice));
  }
  if (!имя || цены.size !== 1) return null;
  return { наименование: имя, цена: [...цены][0], артикул: раскрыть(т.sku || ''), единица: '' };
}

/**
 * Тот же товар в разметке microdata (`itemtype=".../Product"`, `itemprop="price"`)
 * или в мета-тегах `product:price:amount` + `og:title` - другие стандартные
 * способы, которыми магазины отдают цену поисковикам. Правило то же: ровно один
 * товар и одна цена в рублях на странице, иначе страница не берётся.
 */
function товарИзMicrodata(html) {
  const т = String(html || '');
  const атр = (тег, имя) => { const m = new RegExp(`${имя}\\s*=\\s*["']([^"']*)["']`, 'i').exec(тег); return m ? m[1] : null; };
  const products = т.match(/itemtype\s*=\s*["']https?:\/\/schema\.org\/Product["']/gi) || [];
  if (products.length === 1) {
    const цены = new Set();
    let валюта = '';
    for (const m of т.matchAll(/<[^>]*itemprop\s*=\s*["']price["'][^>]*>([^<]*)/gi)) {
      const ц = деньги(атр(m[0], 'content') ?? m[1]);
      if (ц !== null) цены.add(ц);
    }
    for (const m of т.matchAll(/<[^>]*itemprop\s*=\s*["']priceCurrency["'][^>]*>/gi)) валюта = (атр(m[0], 'content') || '').toUpperCase();
    const имяТег = /<[^>]*itemprop\s*=\s*["']name["'][^>]*>([^<]*)/i.exec(т);
    const имя = имяТег ? раскрыть(атр(имяТег[0], 'content') ?? имяТег[1]) : '';
    if (имя && цены.size === 1 && (!валюта || /^RU[BR]$/.test(валюта)) && !/itemprop\s*=\s*["']availability["'][^>]*OutOfStock/i.test(т)) {
      return { наименование: имя, цена: [...цены][0], артикул: '', единица: '' };
    }
    return null;
  }
  if (products.length > 1) return null;
  const мета = (свойство) => {
    const m = new RegExp(`<meta[^>]*(?:property|name)\\s*=\\s*["']${свойство}["'][^>]*>`, 'gi');
    return [...т.matchAll(m)].map((x) => атр(x[0], 'content')).filter((x) => x !== null);
  };
  const суммы = мета('product:price:amount');
  const валюты = мета('product:price:currency').map((x) => x.toUpperCase());
  const заголовок = мета('og:title');
  if (суммы.length === 1 && заголовок.length === 1 && (!валюты.length || /^RU[BR]$/.test(валюты[0]))) {
    const ц = деньги(суммы[0]);
    if (ц !== null) return { наименование: раскрыть(заголовок[0]), цена: ц, артикул: '', единица: '' };
  }
  return null;
}

/** Карта сайта: вложенные карты (sitemapindex) или адреса страниц. */
function ссылкиИзSitemap(xml) {
  const т = String(xml || '');
  const адреса = [...т.matchAll(/<loc>\s*([\s\S]*?)\s*<\/loc>/gi)].map((m) => раскрыть(m[1]));
  return /<sitemapindex/i.test(т) ? { вложенные: адреса, страницы: [] } : { вложенные: [], страницы: адреса };
}

/**
 * robots.txt: можно ли нам на этот путь. Группы «*» и «KarginTech»; более
 * длинное правило побеждает, Allow при равной длине - тоже. Плюс карты сайта.
 */
function разобратьRobots(текст) {
  const группы = [];
  let тек = null;
  let былиПравила = false;
  const карты = [];
  for (const строка of String(текст || '').split(/\r?\n/)) {
    const [поле, ...ост] = строка.replace(/#.*/, '').split(':');
    const к = String(поле || '').trim().toLowerCase();
    const з = ост.join(':').trim();
    if (!к) continue;
    if (к === 'sitemap') { if (з) карты.push(з); continue; }
    if (к === 'user-agent') {
      if (!тек || былиПравила) { тек = { агенты: [], правила: [] }; группы.push(тек); былиПравила = false; }
      тек.агенты.push(з.toLowerCase());
    } else if ((к === 'allow' || к === 'disallow') && тек) {
      былиПравила = true;
      if (з) тек.правила.push({ можно: к === 'allow', путь: з });
    }
  }
  const наши = группы.filter((г) => г.агенты.some((а) => а.includes('kargintech')));
  const правила = (наши.length ? наши : группы.filter((г) => г.агенты.includes('*'))).flatMap((г) => г.правила);
  return { правила, карты };
}

function разрешено(robots, url) {
  let путь;
  try { const u = new URL(url); путь = u.pathname + u.search; } catch (e) { return false; }
  let лучшее = null;
  for (const п of (robots && robots.правила) || []) {
    const шаблон = new RegExp('^' + п.путь.replace(/[.+?^${}()|[\]\\]/g, '\\$&').replace(/\*/g, '.*').replace(/\\\$$/, '$'));
    if (!шаблон.test(путь)) continue;
    if (!лучшее || п.путь.length > лучшее.путь.length || (п.путь.length === лучшее.путь.length && п.можно)) лучшее = п;
  }
  return !лучшее || лучшее.можно;
}

/**
 * Таблицы страницы - текстом с табуляциями, по таблице на строку массива.
 * Точка с запятой в ячейке меняется на запятую: разбор CSV принял бы её за
 * разделитель столбцов.
 */
function таблицыИзHtml(html) {
  const итог = [];
  const чистый = String(html || '').replace(/<script\b[\s\S]*?<\/script>/gi, ' ').replace(/<style\b[\s\S]*?<\/style>/gi, ' ');
  for (const т of чистый.matchAll(/<table\b[\s\S]*?<\/table>/gi)) {
    const строки = [];
    for (const r of т[0].matchAll(/<tr\b[\s\S]*?<\/tr>/gi)) {
      const ячейки = [...r[0].matchAll(/<t[dh]\b[^>]*>([\s\S]*?)<\/t[dh]>/gi)]
        .map((c) => раскрыть(c[1].replace(/<br\s*\/?>/gi, ' ').replace(/<[^>]+>/g, ' ')).replace(/[\t;]/g, ','));
      if (ячейки.some(Boolean)) строки.push(ячейки.join('\t'));
    }
    if (строки.length >= 2) итог.push(строки.join('\n'));
  }
  return итог;
}

