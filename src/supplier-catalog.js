/**
 * Запись каталога с диска → каталог для сверки: ключи, числа, основы слов и
 * указатель «основа → строки», чтобы позицию не сравнивать с каждой из
 * десятков тысяч строк.
 */
function построитьКаталог(запись) {
  const позиции = [];
  const индекс = new Map();
  for (const [наименование, цена, единица, url, артикул] of (запись && запись.позиции) || []) {
    if (!наименование || !(цена > 0)) continue;
    const ключ = нормализовать(наименование);
    const основы = [...new Set(слова(ключ).map((w) => w.slice(0, 5)))];
    const i = позиции.length;
    позиции.push({ наименование, цена, единица: единица || '', url: url || '', артикул: артикул || '', ключ, числа: числаИз(наименование), основы, вид: видПозиции({ name: наименование, unit: единица }).вид });
    for (const о of основы) { if (!индекс.has(о)) индекс.set(о, []); индекс.get(о).push(i); }
  }
  return { ...запись, позиции, индекс };
}

/** Запись для диска: строки массивами - каталог в десятки тысяч строк остаётся компактным. */
function записьКаталога(сведения, позиции, когда = new Date()) {
  return {
    ...сведения,
    обновлено: когда.toISOString(),
    позиций: позиции.length,
    позиции: позиции.map((п) => [String(п.наименование).slice(0, 300), п.цена, п.единица || '', п.url || '', п.артикул || ''])
  };
}

function свежий(каталог, сегодня = new Date(), дней = СРОК_ДНЕЙ) {
  const к = Date.parse((каталог && каталог.обновлено) || '');
  return Number.isFinite(к) && сегодня - к <= дней * 86400000;
}

/**
 * Позиция тендера в каталоге одного поставщика. Не найдено - null, а не
 * ближайшая строка: цена чужого товара хуже отсутствующей.
 */
function найтиВКаталоге(позиция, каталог) {
  const имя = String((позиция && позиция.name) || '');
  const ключ = нормализовать(имя);
  const основы = [...new Set(слова(ключ).map((w) => w.slice(0, 5)))];
  if (основы.length < ОБЩИХ_СЛОВ_МИН || !каталог || !каталог.индекс) return null;
  const числа = числаИз(имя);
  const видП = видПозиции(позиция).вид;
  const счёт = new Map();
  for (const о of основы) for (const i of каталог.индекс.get(о) || []) счёт.set(i, (счёт.get(i) || 0) + 1);
  const кандидаты = [];
  for (const [i, общих] of счёт) {
    if (общих < ОБЩИХ_СЛОВ_МИН) continue;
    const п = каталог.позиции[i];
    let числаСходятся = true;
    for (const ч of п.числа) if (!числа.has(ч)) { числаСходятся = false; break; }
    if (!числаСходятся) continue;
    if (числа.size && !п.числа.size) continue;
    if (маркиРасходятся(имя, п.наименование)) continue;
    if ((видП === 'товар' && п.вид === 'работа') || (видП === 'работа' && п.вид === 'товар')) continue;
    const с = похожесть(ключ, п.ключ);
    if (с >= ПОРОГ) кандидаты.push({ п, с });
  }
  if (!кандидаты.length) return null;
  кандидаты.sort((a, b) => b.с - a.с || b.п.цена - a.п.цена);
  const равных = кандидаты.filter((к) => к.с === кандидаты[0].с);
  return {
    строка: равных[0].п,
    счёт: Math.round(кандидаты[0].с * 100) / 100,
    уверенность: равных.length > 1 ? 'требует проверки' : (кандидаты[0].с === 1 ? 'высокая' : 'средняя'),
    вариантов: равных.length
  };
}

/**
 * Поставщики позиции по всем свежим каталогам - в том же виде, в каком их
 * отдаёт поиск моделью (`parseSupplierResponse`), чтобы дальше шли общие
 * проверки расчёта: единица, сопоставимость с обоснованием НМЦК, без названия.
 */
function поставщикиИзКаталогов(позиция, каталоги, сегодня = new Date()) {
  const итог = [];
  for (const к of каталоги || []) {
    if (!свежий(к, сегодня)) continue;
    const н = найтиВКаталоге(позиция, к);
    if (!н) continue;
    const с = н.строка;
    const дата = String(к.обновлено).slice(0, 10);
    итог.push({
      name: к.имя || к.домен,
      url: с.url || (к.источник && к.источник.url) || к.сайт || `https://${к.домен}`,
      site: к.сайт || `https://${к.домен}`,
      domain: к.домен,
      price: с.цена,
      priceDropped: false,
      unit: с.единица || '',
      priceNote: `каталог поставщика (${(к.источник && к.источник.тип) || 'прайс'}) от ${дата}, совпадение ${н.уверенность}`
        + (н.вариантов > 1 ? ` - ${н.вариантов} равно похожих строк, взята высшая цена` : ''),
      region: к.регион || '',
      kind: к.вид === 'подрядчик' ? 'подрядчик' : (к.род || 'оптовик'),
      phone: к.телефон || '',
      evidence: `«${с.наименование}» - ${с.цена} ₽${с.единица ? ' за ' + с.единица : ''}${с.артикул ? `, арт. ${с.артикул}` : ''}`,
      изКаталога: true,
      уверенность: н.уверенность
    });
  }
  return итог;
}

