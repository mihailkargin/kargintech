const ЛАТИНИЦА = {
  а: ['a'], б: ['b'], в: ['v'], г: ['g'], д: ['d'], е: ['e'], ё: ['e'], ж: ['zh', 'j'], з: ['z'], и: ['i'],
  й: ['y', 'i', 'j'], к: ['k'], л: ['l'], м: ['m'], н: ['n'], о: ['o'], п: ['p'], р: ['r'], с: ['s'],
  т: ['t'], у: ['u'], ф: ['f'], х: ['h', 'kh', 'x'], ц: ['c', 'ts'], ч: ['ch'], ш: ['sh'], щ: ['sch', 'shch'],
  ъ: [''], ы: ['y', 'i'], ь: [''], э: ['e'], ю: ['yu', 'iu', 'ju'], я: ['ya', 'ia', 'ja']
};

/** Варианты латинского написания основы слова (не больше 8). */
function транслит(основа) {
  let варианты = [''];
  for (const ch of String(основа || '').toLowerCase()) {
    const з = ЛАТИНИЦА[ch] || (/[a-z0-9]/.test(ch) ? [ch] : ['']);
    варианты = варианты.flatMap((в) => з.map((x) => в + x)).slice(0, 8);
  }
  return [...new Set(варианты)].filter((в) => в.length >= 4);
}

/**
 * Страницы сайта, похожие на товары ниши: в адресе - латинское написание
 * основ слов из товаров ниши («bumag», «ruchk»). Большой магазин - десятки
 * тысяч страниц; обходить все раз в неделю нельзя ни нам, ни ему.
 */
function отобратьСтраницы(адреса, словаНиши, предел) {
  const основы = [...new Set((словаНиши || []).flatMap((с) => слова(нормализовать(с))).filter((w) => w.length >= 5 && /[а-я]/.test(w)).map((w) => w.slice(0, 5)))];
  const образцы = основы.flatMap((о) => транслит(о).map((t) => t.slice(0, Math.max(4, t.length - 1))));
  const оценка = (url) => {
    const п = String(url).toLowerCase();
    return образцы.reduce((s, о) => s + (п.includes(о) ? 1 : 0), 0);
  };
  return адреса.map((u) => ({ u, о: оценка(u) })).filter((x) => x.о > 0)
    .sort((a, b) => b.о - a.о).slice(0, предел).map((x) => x.u);
}

