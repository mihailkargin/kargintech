const HEAD_NAME = /наименован|предмет закупки|объект закупки|товар[а-яё]*\s*[,(]?\s*работ|^вид[а-яё]*\s+работ/i;
// «Основные характеристики объектА закупки» — колонка наименования в
// обосновании 0131200001026007400 (стоматология, 19.10.2026). Только когда в
