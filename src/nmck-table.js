const HEAD_NAME_ОБЪЕКТ = /объект[а-яё]*\s+закупки/i;
// «Коли-чество (v)» — перенос через дефис в шапке обоснования 0326100005026000005
// (20.10.2026): колонка количества не находилась, наименованием стала «пачка».
const HEAD_QTY = /кол-?во|коли-?честв|количеств|^объ[её]м\s+работ/i;
const HEAD_UNIT = /ед\.?\s*изм|единиц/i;

/**
 * Колонка с ценой предложения: так их подписывают заказчики.
 *
 * ЛОВУШКА: сокращения пишут по-разному — «КП 1», «КП № 1», «ТКП №1», «ТП 2».
 * Прежний шаблон ловил «КП 1» и «ТКП №1», но пропускал «КП № 1»: между
 * буквами и цифрой стоит знак номера. В разобранных до того документах
 * колонка называлась длинно — «Коммерческие предложения … / КП № 1» —
 * и попадалась по слову «предложени», поэтому пропуск не всплывал.
 * На таблице с короткими подписями разбор нашёл бы шапку и не нашёл ни одной
 * цены, то есть отдал бы документ человеку без объяснимой причины.
 */
// «КП б/н от 31.08.2026г» — коммерческое предложение без номера (шприцы
// 32616483363, 19.10.2026): без «б/н» колонка ценой не считалась.
// «Ценовая информация от потенциального поставщика» (32616490078, 20.10.2026):
// без неё ценой становилась сумма строки из соседней колонки «Цена (руб.)».
const HEAD_PRICE = /цена|стоимост|ценов[а-яё]*\s+информац|(ткп|кп|тп)\s*(№?\s*\d|б\/н)|предложени|источник|поставщик\s*№?\s*\d/i;

/**
 * Колонки, которые ценами предложений НЕ являются, хотя выглядят похоже.
 * Их включение испортит главное — разброс между источниками: средняя всегда
 * лежит внутри диапазона, а «итого» больше цены в разы и растянет его до
 * бессмыслицы.
 */
const HEAD_DERIVED = new RegExp(
  // «НДС» здесь намеренно НЕТ. Заказчики пишут «Цена из ИЦИ, в руб. без НДС» —
  // это обычная цена с уточнением валюты, а не отдельный расчёт. Отсев по слову
  // «НДС» выбрасывал единственную колонку с ценами, и весь файл переставал
  // разбираться. Колонки вроде «Сумма НДС» ловятся по слову «сумм».
  'итого|сумм|средн|миним|максим|вариац|отклонен|всего|разниц|%' +
  // Сокращения: «Цена за ед.изм.мин.», «Цена за ед.изм.ср.». Полные слова
  // их не ловят, и производные колонки уезжали в цены предложений —
  // позиция получала пять источников вместо трёх.
  '|(?:^|[\\s.(])(?:мин|макс|ср)\\.',
  'i'
);

/**
 * Число из ячейки.
 *
 * Заказчики пишут цену как придётся: «4532», «21 000,00», «21 000,00/тн»,
 * «1 001 735,86 руб. без НДС». Единица измерения и валюта прямо в ячейке —
 * обычное дело, и на них разбор спотыкался: строка не проходила как число,
 * позиция молча теряла цену.
 *
 * Берём число из НАЧАЛА ячейки. Если ячейка начинается со слов, это не цена,
 * а подпись — такую отбрасываем, иначе в цены попадёт номер строки из текста.
 */
const num = (s) => {
  if (typeof s === 'number') return Number.isFinite(s) ? s : null;
  const raw = String(s || '').replace(/ /g, ' ').trim();
  if (!raw) return null;

  // Степень обязательна: Excel пишет «4.2200000000000001E-2», и без неё
  // коэффициент вариации 0,042 читался как 4,22 — ошибка в сто раз
  // (0373200082126000566, 19.10.2026).
  const m = raw.match(/^-?\d[\d\s]*(?:[.,]\d+)?(?:[eE][-+]?\d+)?/);
  if (!m) return null;

  const v = parseFloat(m[0].replace(/\s/g, '').replace(',', '.'));
  return Number.isFinite(v) ? v : null;
};

const round2 = (n) => Math.round(n * 100) / 100;

// =====================================================================
//  ПЕРЕВЁРНУТАЯ ТАБЛИЦА ОБОСНОВАНИЯ НМЦК
// =====================================================================
//
// Найдена на реальном документе 12.10.2026, закупка 0373200638526000056
// («Расчет НМЦК(Д)», канцелярские товары, 436 строк). Устроена так: не
// «строка = товар», а БЛОК из нескольких строк на каждый товар, и в первой
// ячейке строки стоит НАЗВАНИЕ ПОЛЯ, а не значение:
//
//   Наименование поставщиков                 | Источник 1 | Источник 2 | Источник 3
//   Наименование товара, технические характ. | Палитра для рисования
//   Количество единиц товара, шт             | 78
//   Модель, производитель                    | ПИФАГОР | BRAUBERG | ЮЛАНДИЯ
//   Цена за ед. Товара                       | 45 | 54 | 47
//   Цена за единицу товара без учета НДС     | 36.89 | 44.26 | 38.52 | 39.89 | 48.67
//   Итого стоимость товара, включая НДС 22%  | Х | Х | Х | Х | 3796.26
//
// ЧЕМ ЭТО ОПАСНО. Обычный разбор здесь находит «шапку» («Наименование
// поставщиков | Источник 1 | Источник 2 | Источник 3»), после чего колонка
// наименования указывает на подписи полей, а колонки цен — на значения.
// Получается 172 «позиции» с правильными ценами и названиями вида «Цена за
// ед. Товара». Ошибка тихая: разбор уверен, цифры настоящие, смета собирается.
//
// ЕДИНИЦА ИЗМЕРЕНИЯ СПРЯТАНА В ПОДПИСИ: «Количество единиц товара, шт» и
// «Количество единиц товара, упак» — это одно поле с разной единицей.
// Брать её надо из названия поля, больше её взять негде.

/** Подписи полей в перевёрнутой таблице. */
const П_ИМЯ = /^наименование товара/i;
const П_КОЛ = /^количеств[оа] единиц товара/i;
const П_ЦЕНА_БЕЗ_НДС = /^цена за единицу товара без/i;
const П_ЦЕНА = /^цена за ед/i;
// «Поставщики | Источник 1 | …» — та же строка у 0373200315626000003: без неё
// колонки брались «до первой Х», и в предложения попадала средняя цена.
// «Категории | ОИ1 | ОИ2 | ОИ3 | КП1 | КП2» — 0373200082126000566: ОИ — открытый
// источник, КП — коммерческое предложение (19.10.2026).
const П_ИСТОЧНИКИ = /^(наименование поставщик|поставщики$|категории$)/i;
const П_ИСТОЧНИК = /^(источник|кп|ткп|ои|поставщик)\s*№?\s*\d/i;
const П_ЕДИНИЦА = /^единица измерения/i;

/**
 * Признак перевёрнутой таблицы.
 *
 * Требуются ТРИ РАЗНЫЕ подписи полей в НУЛЕВОЙ ячейке разных строк. У обычной
 * таблицы все эти слова стоят в одной строке шапки и в разных колонках, то
 * есть в нулевой ячейке оказывается максимум одно из них. Поэтому признак
 * не срабатывает на семи реальных обоснованиях, которые уже разбираются.
 */
function этоПеревёрнутая(rows) {
  let имя = 0;
  let кол = 0;
  let цена = 0;
  for (const cells of rows) {
    const первая = (cells[0] || '').trim();
    if (!первая) continue;
    if (П_ИМЯ.test(первая)) имя++;
    else if (П_КОЛ.test(первая)) кол++;
    else if (П_ЦЕНА.test(первая)) цена++;
  }
  return имя > 0 && кол > 0 && цена > 0;
}

/** Значения строки, кроме нулевой ячейки с подписью поля. */
function значения(cells) {
  return (cells || []).slice(1);
}

/**
 * Номера колонок с предложениями.
 *
 * Берутся из строки «Наименование поставщиков | Источник 1 | …», потому что
 * число предложений у заказчиков разное. Если такой строки нет, берутся все
 * колонки до первой заглушки «Х»: ею заказчик помечает неприменимое поле.
 *
 * Жёстко «колонки 1, 2, 3» писать нельзя — это ровно тот класс ошибки,
 * который в проекте уже трижды стоил проходов проверки (жёсткая длина
 * реестрового номера, длина идентификатора участника, содержимое ячейки).
 */
function колонкиПредложений(rows, от) {
  // До начала документа, а не 8 строк: у 0373200082126000566 строка
  // «Категории | ОИ1 …» одна на всю таблицу, и у поздних товаров без неё
  // колонки брались «до первой Х» — в цены попадал коэффициент вариации.
  for (let i = от; i >= 0; i--) {
    const cells = rows[i] || [];
    if (!П_ИСТОЧНИКИ.test((cells[0] || '').trim())) continue;
    const найдены = [];
    cells.forEach((c, idx) => {
      if (idx > 0 && П_ИСТОЧНИК.test((c || '').trim())) найдены.push(idx);
    });
    if (найдены.length) return найдены;
  }
  return null;
}

/**
 * Разбор перевёрнутой таблицы.
 *
 * Блок начинается строкой «Наименование товара …». Всё до следующей такой
 * строки относится к одному товару.
 */
function разборПеревёрнутой(rows) {
  const positions = [];
  const issues = [];
  let текущий = null;
  let пустыхИмён = 0;

  let нулевых = 0;
  const закрыть = () => {
    if (!текущий) return;
    // КОЛИЧЕСТВО 0 — НЕ ПОКУПКА. Совместная закупка школ, лист на школу
    // (0373200315626000003, 19.10.2026): школа, которой товар не нужен, ставит
    // 0. Такие 70 из 394 позиций уходили бы в поиск поставщиков впустую.
    if (текущий.quantity === 0) { нулевых++; текущий = null; return; }
    if (!текущий.name || текущий.prices.length === 0) {
      if (!текущий.name) пустыхИмён++;
      текущий = null;
      return;
    }
    const values = текущий.prices.map((p) => p.value);
    const min = Math.min(...values);
    const max = Math.max(...values);
    positions.push({
      name: текущий.name,
      quantity: текущий.quantity,
      unit: текущий.unit,
      prices: текущий.prices,
      min,
      max,
      spreadPct: min > 0 ? round2(((max - min) / min) * 100) : null,
      sourceCount: текущий.prices.length,
      itemTotal: текущий.itemTotal
    });
    текущий = null;
  };

  for (let i = 0; i < rows.length; i++) {
    const cells = rows[i];
    const подпись = (cells[0] || '').trim();
    if (!подпись) continue;

    if (П_ИМЯ.test(подпись)) {
      закрыть();
      // Наименование — первая непустая ячейка после подписи. Заглушку «Х»
      // за наименование не берём.
      let имя = значения(cells).find((c) => c && !/^[хx]$/i.test(c));
      // ЛОВУШКА РЕАЛЬНОГО ДОКУМЕНТА: подпись и значение могут стоять на
      // РАЗНЫХ строках — у закупки 0373200638526000056 так у «Емкость для
      // промывания кисточек». Без этой ветки товар терялся бы молча.
      if (!имя) {
        const след = rows[i + 1] || [];
        const перваяСлед = (след[0] || '').trim();
        const этоПодписьПоля = П_КОЛ.test(перваяСлед) || П_ЦЕНА.test(перваяСлед)
          || П_ИМЯ.test(перваяСлед) || П_ИСТОЧНИКИ.test(перваяСлед);
        if (!этоПодписьПоля) {
          имя = [перваяСлед, ...значения(след)].find((c) => c && !/^[хx]$/i.test(c));
          if (имя) i++;
        }
      }
      текущий = {
        name: (имя || '').trim(),
        quantity: null,
        unit: '',
        prices: [],
        itemTotal: null
      };
      continue;
    }

    if (!текущий) continue;

    if (П_КОЛ.test(подпись)) {
      let знач = значения(cells).map(num).find((v) => v !== null);
      // ПЕРЕНОС В ЯЧЕЙКЕ EXCEL: «Количество единиц товара, литр,кубический
      // дециметр» — подпись с переводом строки, число строкой ниже
      // (0373200315626000003, 19.10.2026). Берётся, только если следующая
      // строка — одно число и ничего больше.
      if (знач === undefined) {
        const след = (rows[i + 1] || []).map((c) => (c || '').trim()).filter(Boolean);
        if (след.length === 1 && num(след[0]) !== null) { знач = num(след[0]); i++; }
      }
      if (знач !== undefined) текущий.quantity = знач;
      // Единица измерения — в самой подписи: «…товара, шт», «…товара, упак».
      // «…товара, литр,кубический дециметр» — берётся первая единица.
      const ед = подпись.match(/товара\s*,\s*([а-яё.]+)/i) || подпись.match(/,\s*([а-яё.]+)\s*$/i);
      if (ед) текущий.unit = ед[1].replace(/\.$/, '');
      continue;
    }

    // Единица отдельной строкой (0373200082126000566): «Единица измерения | шт.».
    if (П_ЕДИНИЦА.test(подпись)) {
      const ед = значения(cells).find((c) => c && !/^[хx]$/i.test(c));
      if (ед && !текущий.unit) текущий.unit = ед.replace(/\.$/, '');
      continue;
    }

    // Порядок проверок: «без учёта НДС» СТРОГО ПЕРЕД «цена за ед», иначе
    // второй шаблон поглотит первый и в расчёт пойдёт цена без НДС, то есть
    // заниженная. Клиент платит цену с НДС.
    if (П_ЦЕНА_БЕЗ_НДС.test(подпись)) continue;

    if (П_ЦЕНА.test(подпись)) {
      const колонки = колонкиПредложений(rows, i) || null;
      const ячейки = cells;
      const набор = [];
      if (колонки) {
        for (const idx of колонки) {
          const v = num(ячейки[idx]);
          if (v !== null && v > 0) набор.push({ value: v, column: `источник ${набор.length + 1}` });
        }
      } else {
        for (let k = 1; k < ячейки.length; k++) {
          const c = (ячейки[k] || '').trim();
          if (/^[хx]$/i.test(c)) break;
          const v = num(c);
          if (v !== null && v > 0) набор.push({ value: v, column: `источник ${набор.length + 1}` });
        }
      }
      if (набор.length) текущий.prices = набор;
      continue;
    }

    if (/^итого стоимость товара/i.test(подпись)) {
      const знач = значения(cells).map(num).filter((v) => v !== null && v > 0);
      if (знач.length) текущий.itemTotal = знач[знач.length - 1];
    }
  }
  закрыть();

  if (пустыхИмён) {
    issues.push(`${пустыхИмён} блоков без наименования товара — пропущены, `
      + 'позиции по ним не выдуманы');
  }
  if (нулевых) issues.push(`${нулевых} блоков с количеством 0 пропущены — этот заказчик товар не берёт`);
  if (!positions.length) {
    issues.push('таблица похожа на перевёрнутую, но ни одного товара с ценой не собрано');
  }

  return {
    ok: positions.length > 0,
    positions,
    header: ['перевёрнутая таблица: подписи полей в первой ячейке'],
    перевёрнутая: true,
    issues
  };
}

/**
 * Склеивает два этажа шапки в один список подписей.
 *
 * ЗАЧЕМ. У реальных таблиц шапка часто в два этажа: сверху «кп 1 от
 * 25.09.2026» на две колонки, снизу «цена за ед.» и «итого». По одному
 * верхнему этажу отличить цену от суммы невозможно, по одному нижнему —
 * непонятно, к какому предложению колонка относится.
 */
function mergeHeader(rowA, rowB) {
  const width = Math.max(rowA.length, rowB ? rowB.length : 0);
  const out = [];
  let carried = '';
  for (let i = 0; i < width; i++) {
    const top = (rowA[i] || '').trim();
    // Объединённая ячейка верхнего этажа: подпись стоит в первой колонке,
    // дальше пусто. Тянем её вправо — но только на колонки, у которых есть
    // собственная подпись внизу.
    //
    // ЛОВУШКА, на которой это уже обожглось. Без этого ограничения подпись
    // растекалась на все пустые колонки справа. В реальном файле заголовок
    // «Метод сопоставимых рыночных цен» протянулся на колонки минимума
    // и среднего, слово «цен» внутри опознало их как цены предложений —
    // и позиция получила пять источников вместо трёх. Разброс при этом
    // остаётся верным, а вот «цена подтверждена пятью источниками» —
    // уже неправда, на которой клиент строит доверие к цифре.
    if (top) carried = top;
    const bottom = rowB ? (rowB[i] || '').trim() : '';
    if (!top && !bottom) { out.push(''); continue; }
    out.push([carried, bottom].filter(Boolean).join(' / '));
  }
  return out;
}

/** Ищет строку шапки и разбирает её на роли колонок. */
function findHeader(rows) {
  // Подпись колонки короткая. Ячейка-абзац («Форма оплаты: … Цена Договора
  // включает…») подписью не считается: слово «цена» внутри абзаца делало
  // колонку ценовой, и строка извещения «Требования к составу заявки» стала
  // позицией с ценами 1, 6.4, 6.5 - номерами пунктов (кафе 32616497177,
  // 23.10.2026). Длинная ячейка гасится, номера колонок не сдвигаются.
  const подписи = (r) => (r || []).map((c) => (String(c).length > 200 ? '' : c));
  for (let i = 0; i < Math.min(rows.length, 30); i++) {
    const cells = подписи(rows[i]);

    // Шапка таблицы состоит из нескольких колонок. Строка из одной ячейки —
    // это абзац текста, а не шапка. На этом разбор спотыкался: предложение
    // «Использованный метод расчёта НМЦ / цены единицы товара, работ, услуг»
    // содержит и «товар, работ», и «цены», выглядело шапкой и уводило разбор
    // от настоящей таблицы двумя строками ниже.
    if (cells.filter((c) => c.trim()).length < 2) continue;

    const сКоличеством = cells.some((c) => HEAD_QTY.test(c));
    // «Наименование контрагента / заказчика / участника» - не товар: бланк
    // опыта участника («… | Цена исполненного договора») давал позиции «у.е»
    // с ценами чужих договоров (кафе 32616497177, 23.10.2026).
    const НЕ_ТОВАР = /наименовани[а-яё]*\s+(контрагент|заказчик|участник|поставщик|организаци|исполнител|юридическ)/i;
    const этоИмя = (c) => !НЕ_ТОВАР.test(c) && (HEAD_NAME.test(c) || (сКоличеством && HEAD_NAME_ОБЪЕКТ.test(c)));
    if (!cells.some(этоИмя)) continue;

    // Одного слова «наименование» мало. В документах перед таблицей часто
    // идёт описательный блок — «1. Наименование объекта закупки: поставка
    // шрота», — и разбор цеплялся за него, принимая за шапку. Настоящая
    // шапка содержит ещё и количество или цену: ролей в ней несколько.
    // Количество - в СВОЕЙ ячейке: «Краткое описание предмета закупки, в том
    // числе количество товара» одна ячейка и шапкой не является
    // (32616488144, 20.10.2026: настоящая таблица ТЗ ниже не находилась).
    const hasSecondRole = cells.some((c) => HEAD_QTY.test(c) && !этоИмя(c)) ||
      cells.some((c) => HEAD_PRICE.test(c) && !HEAD_NAME.test(c)) ||
      подписи(rows[i + 1]).some((c) => HEAD_PRICE.test(c));
    if (!hasSecondRole) continue;

    // Второй этаж берём, только если он похож на продолжение шапки,
    // а не на первую строку данных.
    const next = подписи(rows[i + 1]);
    const looksLikeSecondFloor = next.some((c) => HEAD_PRICE.test(c) || HEAD_DERIVED.test(c)) &&
      !next.some((c) => num(c) !== null && String(c).length > 3);

    const header = looksLikeSecondFloor ? mergeHeader(cells, next) : mergeHeader(cells, null);

    // «Наименование по ОКПД2/КТРУ» рядом с «Наименование товара» - берётся
    // товар: в первой колонке у шести разных кабелей одно и то же «Кабель
    // силовой с пластмассовой изоляцией», и строку ТЗ по нему не найти
    // (0301100049626001767, 20.10.2026). Колонка классификатора - только
    // если другой нет.
    const классификатор = (h) => /окпд|ктру|классификатор/i.test(h);
    const имена = header.map((h, idx) => (этоИмя(h) ? idx : -1)).filter((idx) => idx !== -1);
    const nameAt = имена.find((idx) => !классификатор(header[idx])) ?? (имена.length ? имена[0] : -1);
    const qtyAt = header.findIndex((h) => HEAD_QTY.test(h) && !HEAD_DERIVED.test(h));
    // «Средняя цена за единицу» - цена, а не единица измерения (32616497177).
    const unitAt = header.findIndex((h) => HEAD_UNIT.test(h) && !HEAD_PRICE.test(h));

    const priceCols = [];
    header.forEach((h, idx) => {
      if (idx === nameAt || idx === qtyAt || idx === unitAt) return;
      if (HEAD_DERIVED.test(h)) return;
      // Колонка, подписанная как количество чего-либо, ценой не является.
      // В реальном файле встретилось «Количество источников ценовой
      // информации»: слово «источник» опознавало её как цену, а лежало
      // там число 3 — и позиция получала цену 3 рубля рядом с 36.
      // Разброс раздувался до 1100%, а вместе с ним и вся смета.
      if (HEAD_QTY.test(h)) return;
      if (HEAD_PRICE.test(h)) priceCols.push({ at: idx, title: h });
    });

    if (nameAt === -1) continue;

    // ЕСТЬ КОЛОНКИ ПРЕДЛОЖЕНИЙ — прочие «цены» предложениями не считаются.
    // «Цена за единицу» в обосновании 0131200001026007400 — цена, которую
    // вывел заказчик, а не предложение: с ней позиция «подтверждалась» четырьмя
    // источниками вместо трёх (19.10.2026).
    // «Источник» — только с номером: «Источник ценовой информации» в
    // обосновании электроматериалов — колонка с текстом «ТКП №1», цены рядом.
    const ПРЕДЛОЖЕНИЕ = /поставщик|(ткп|кп|тп)\s*(№?\s*\d|б\/н)|коммерческ|результат[а-яё]*\s+запрос|источник\s*№?\s*\d/i;
    if (priceCols.some((p) => ПРЕДЛОЖЕНИЕ.test(p.title))) {
      for (let k = priceCols.length - 1; k >= 0; k--) {
        if (!ПРЕДЛОЖЕНИЕ.test(priceCols[k].title)) priceCols.splice(k, 1);
      }
    }

    return {
      at: i,
      dataFrom: i + (looksLikeSecondFloor ? 2 : 1),
      header,
      nameAt,
      qtyAt,
      unitAt,
      priceCols
    };
  }
  return null;
}

/**
 * Склеивает строку с продолжением наименования.
 *
 * ЛОВУШКА, найденная на настоящем обосновании НМЦК 03.10.2026. Наименование
 * товара часто занимает две строки: само название, а под ним уточнение
 * в скобках. В извлечённом тексте это выглядит так:
 *
 *   1    Бланк из бумаги или картона
 *   (Бланк диплома о профессиональной переподготовке…)    штука   1500   355.42   371   316
 *
 * Разбор видел здесь ДВЕ строки таблицы и брал вторую. Все колонки съезжали
 * на одну: «штука» попадала в наименование, «1500» — в единицу измерения,
 * а количество получало цену первого коммерческого предложения.
 *
 * Отказа при этом не было: цены разбирались верно, сумма выглядела
 * правдоподобной, и смета собиралась. Терялось только название товара —
 * то есть ровно то, по чему потом ищут поставщика. Поиск шёл по слову
 * «штука» и честно не находил ничего.
 *
 * Склеиваем так, чтобы структура колонок сохранилась: последняя заполненная
 * ячейка первой строки соединяется с первой ячейкой второй, остальные
 * ячейки второй строки встают следом. Номер позиции при этом остаётся
 * на своём месте.
 *
 * Условие срабатывания узкое — в строке мало заполненных ячеек И нет
 * ни одной цены, а в следующей цены есть. Иначе склейка задела бы обычные
 * строки таблицы.
 */
function склеитьПереносыНаименований(rows, head) {
  const естьЦены = (cells) => head.priceCols.some((col) => {
    const v = num(cells[col.at]);
    return v !== null && v > 0;
  });

  const out = [];
  for (let i = 0; i < rows.length; i++) {
    const cur = rows[i];

    // Шапку и всё до неё не трогаем.
    if (i < head.dataFrom) { out.push(cur); continue; }

    const заполнено = cur.filter((c) => c !== '').length;
    const след = rows[i + 1];

    // «| Поставщик 3 | 5,80» - предложение к позиции выше, а не начало
    // наименования следующей (0372100001926000241, 23.10.2026).
    const предложение = cur.some((c) => /^(поставщик|источник|кп|ткп|коммерческое предложение|предложение)\s*(№\s*)?\d{1,2}$/i.test(String(c).trim()));
    const этоНачалоНаименования = заполнено > 0
      && заполнено <= 2
      && !предложение
      && !естьЦены(cur)
      && след
      && естьЦены(след);

    if (!этоНачалоНаименования) { out.push(cur); continue; }

    const последний = cur.map((c, k) => (c !== '' ? k : -1)).filter((k) => k !== -1).pop();
    const начало = cur[последний] || '';
    const продолжение = (след[0] || '').trim();

    out.push([
      ...cur.slice(0, последний),
      (начало + ' ' + продолжение).trim(),
      ...след.slice(1)
    ]);
    i++; // вторая строка уже вошла в склеенную
  }
  return out;
}

/**
 * Шапка по всему документу, а не в первых 30 строках.
 *
 * `findHeader` смотрит начало документа — так устроены обоснования НМЦК.
 * В ТЗ таблица начинается после общей части: на живом ТЗ 14.10.2026 — на
 * 355-й строке. Используется ЗАПАСНЫМ путём: семь проверенных обоснований
 * разбираются прежним способом, поведение на них не меняется.
 */
function findHeaderAnywhere(rows) {
  for (let s = 30; s < rows.length; s += 30) {
    const h = findHeader(rows.slice(s));
    if (h) return { ...h, at: h.at + s, dataFrom: h.dataFrom + s };
  }
  return null;
}

/**
 * ВСЕ ШАПКИ ДОКУМЕНТА ПО ПОРЯДКУ — для разбора, который пробует следующую,
 * если по первой позиций нет (19.10.2026, шприцы 32616483363: в одном .doc
 * подряд спецификация-бланк, ТЗ без цен и обоснование НМЦК; разбор цен
 * останавливался на ТЗ и до обоснования не доходил).
 */
function всеШапки(rows) {
  const out = [];
  let s = 0;
  while (s < rows.length) {
    const h = findHeader(rows.slice(s));
    if (!h) { s += 30; continue; }
    out.push({ ...h, at: h.at + s, dataFrom: h.dataFrom + s });
    s += h.at + 1;
  }
  // Тело таблицы кончается там, где начинается следующая шапка: иначе шапка
  // бланка спецификации применялась к строкам ТЗ и обоснования ниже и
  // выдавала их числа не из тех колонок (шприцы 32616483363).
  out.forEach((h, j) => { h.до = out[j + 1] ? out[j + 1].at : rows.length; });
  return out;
}

/**
 * КОЛИЧЕСТВО ПО ЗАКАЗЧИКАМ. Совместная закупка: под «Кол-во, шт.» вторая
 * строка шапки «Заказчик № 1 | … | Заказчик № 7», по колонке на заказчика
 * (шприцы 32616483363, семь больниц). Количество товара — их сумма; иначе
 * бралось количество первой больницы, 24 680 вместо 72 380. Подтверждено
 * числом заказчика: 35,13 × 72 380 = 2 542 709 ₽ — сумма строки НМЦК.
 * Возвращает число подколонок либо 0.
 */
function колонокЗаказчиков(rows, head) {
  if (head.qtyAt === -1) return 0;
  const след = rows[head.at + 1] || [];
  const к = след.filter((c) => /^(зак-?к|заказчик)[а-яё]*\s*№\s*\d+$/i.test(String(c).trim())).length;
  // Подколонки идут от колонки количества до конца строки: количество должно
  // быть последней подписью шапки, иначе с чем-то справа его не разделить.
  const последняя = head.header.reduce((m, h, i) => (String(h).trim() ? i : m), -1);
  return к >= 2 && последняя === head.qtyAt ? к : 0;
}

/**
 * Первая шапка тоже кончается на следующей товарной шапке: в одном документе
 * бланк спецификации стоит перед ТЗ, и без границы его колонки применялись к
 * строкам ТЗ и обоснования (шприцы 32616483363, 19.10.2026).
 */
function сГраницей(head, шапки, rows) {
  // Та же шапка ниже, и нумерация под ней снова с 1 - вторая копия таблицы (ТЗ
  // в документации и в приложении к договору, кровля 32616502960, 27.10.2026):
  // без границы позиции удваивались. Шапка, повторённая при переносе на новую
  // страницу, продолжает нумерацию (металл 32616503996: 81 позиция) - не граница.
  const сЕдиницы = (h) => rows.slice(h.dataFrom, h.dataFrom + 3)
    .some((r) => /^1\.?$/.test((r.find((c) => String(c).trim()) || '').trim()));
  const та = (h) => h.header.join('|') === head.header.join('|') && сЕдиницы(h);
  const след = шапки.find((h) => h.at > head.at && (товарнаяШапка(h) || та(h)));
  return { ...head, до: след ? след.at : rows.length };
}

/**
 * Шапка таблицы ТОВАРОВ: «наименование товара/объекта/продукции» и количество.
 * Для шапок после первой — обязательное условие: без него перебор находил
 * таблицу заказчиков с адресами поставки и делал позициями больницы
 * (шприцы 32616483363, 19.10.2026).
 */
function товарнаяШапка(h) {
  return h.qtyAt !== -1 && h.header.some((x) =>
    /наименован[а-яё]*\s+(поставляем[а-яё]*\s+)?(товар|объект|продукц|позиц|издели)/i.test(x));
}

/** Количества каждого заказчика — для самопроверки: все они стоят в строке документа. */
function частиПоЗаказчикам(cells, от, к) {
  const out = [];
  for (let j = от; j < от + к; j++) {
    const v = num(cells[j]);
    if (v !== null && v >= 0) out.push(v);
  }
  return out;
}

/** Сумма количества по подколонкам заказчиков; null — ни одного числа. */
function суммаПоЗаказчикам(cells, от, к) {
  let сумма = 0;
  let чисел = 0;
  for (let j = от; j < от + к; j++) {
    const v = num(cells[j]);
    if (v !== null && v >= 0) { сумма += v; чисел++; }
  }
  return чисел ? сумма : null;
}

/**
 * ПОЗИЦИИ БЕЗ ЦЕН — из ТЗ, спецификации, описания объекта закупки.
 *
 * Найдено пакетной проверкой 14.10.2026: на 8 закупках из 15 «таблица позиций
 * не найдена». Позиции брались только из таблицы С ЦЕНАМИ — обоснования НМЦК.
 * А оно часто лежит сканом или свободным текстом, зато в ТЗ есть таблица
 * «наименование — количество — единица» без цен. Для посредника это основной
 * случай: цены ему всё равно находим мы, ему нужно знать, ЧТО и СКОЛЬКО купить.
 *
 * Строгость та же, что у разбора с ценами: шапка ищется по подписям, строка
 * берётся, только если у неё есть наименование и количество — числом. Строки
 * без количества (подзаголовки, пояснения) пропускаются, а не выдумываются.
 * Подписи колонок и мусор отсекает самопроверка разбора в estimate-run.
 *
 * @returns {{ok: boolean, positions: Array, header: Array, issues: string[], безЦен: true}}
 */
function parseSpecTable(text) {
  const rows = String(text || '')
    .split('\n')
    .map((line) => line.split('\t').map((c) => c.replace(/ /g, ' ').trim()));

  // ЯЧЕЙКИ С ОДНИМ КОДОМ ОКПД2/КТРУ — убираются до выравнивания (19.10.2026).
  // Фоновый разбор 72 закупок: в таблицах КТРУ код товара стоит своей
  // ячейкой под общей шапкой «Наименование товара, код ОКПД 2, КТРУ», и
  // все колонки строки съезжали — наименованием становился код, единицей
  // «Марка бумаги». В другой таблице код стоял в конце строки, где цены и
  // суммы не было вовсе. Колонка «ОКПД2» в шапке убирается вместе с ними.
  const ТОЛЬКО_КОД = /^\d{2}\.\d{2}\.\d{2}\.\d{3}(-\d{8})?$/;
  const ПОДПИСЬ_КОДА = /^(код\s+)?(окпд\s*2?|ктру)$/i;
  for (let i = 0; i < rows.length; i++) {
    rows[i] = rows[i].filter((c) => !ТОЛЬКО_КОД.test(c) && !ПОДПИСЬ_КОДА.test(c));
  }

  // Форма ЕИС - первой: общий разбор взял бы «≥ 500» из характеристики
  // «Количество листов в пачке» за количество товара.
  const оозЕИС = позицииООЗ(rows, String(text || '').split('\n'));
  if (оозЕИС) return оозЕИС;
  const найдена = findHeader(rows) || findHeaderAnywhere(rows);
  const неудача = (head, причина) => ({ ok: false, positions: [], header: head ? head.header : [], безЦен: true, issues: [причина] });
  if (!найдена) return неудача(null, 'шапку таблицы распознать не удалось');
  const первая = сГраницей(найдена, всеШапки(rows), rows);
  // Первая шапка — прежний путь; по ней пусто — следующие шапки документа
  // (бланк спецификации «заполняется по заявке» перед настоящим ТЗ).
  let итог = null;
  // У первой шапки нет количества - годится любая следующая с количеством,
  // даже если в ней просто «Наименование» (32616488144, 20.10.2026: в
  // документе на 110 тыс. знаков ТЗ стояло после другой таблицы).
  const следующие = всеШапки(rows).filter((h) => h.at > первая.at
    && (товарнаяШапка(h) || (первая.qtyAt === -1 && h.qtyAt !== -1)));
  // Сомнительный разбор: наименованием у всех стала подпись поля («Наименование
  // культуры») или одно и то же слово - колонки съехали. Пробуем строки КТРУ.
  const сомнительный = (r) => r.positions.length >= 2 && (
    r.positions.filter((п) => /^(наименование|характеристик|значение)/i.test(String(п.name))).length * 2 >= r.positions.length
    || new Set(r.positions.map((п) => п.name)).size === 1);
  for (const head of [первая, ...следующие]) {
    const r = head.qtyAt === -1 ? неудача(head, 'в шапке нет колонки количества') : спецПоШапке(rows, head);
    if (r.ok && !сомнительный(r)) return r;
    итог = итог || r;
  }
  return позицииКТРУ(rows) || итог;
}

/**
 * СТРОКИ КТРУ - запасной путь, когда по шапке позиций не нашлось (пакетная
 * проверка 23.10.2026, посадочный материал 0335600003126000011). Шапка
 * «№ п/п | Наименование Товара, код позиции | Характеристики товара | Кол-во |
 * Ед. изм.», а строка товара шире шапки: «1. | Луковицы нарциссов | ОКПД2: … |
 * Наименование культуры | Нарцисс цикламеновидный | 140 | шт.», ниже - строки
 * с остальными характеристиками. Колонки по шапке разъезжаются.
 *
 * Берётся строка, где первая непустая ячейка - номер позиции, последняя -
 * единица измерения, предпоследняя - количество числом; наименование - вторая
 * ячейка без хвоста «ОКПД2: …». Только если в документе есть шапка с
 * количеством и единицей и строк таких две и больше: одна строка такого вида
 * может быть чем угодно.
 */
/**
 * ОПИСАНИЕ ОБЪЕКТА ЗАКУПКИ ПО ФОРМЕ ЕИС (24.10.2026). Шапка «№ п/п |
 * Наименование товара, работы, услуги… | Коды | Характеристики товара… |
 * Единица измерения | Количество…», строка позиции «1 | Бумага для офисной
 * техники | КТРУ: 17.12.14.110-00000004…», ниже строки характеристик, а
 * единица («ПАЧ») и количество («400.0000») - ОТДЕЛЬНЫМИ строками в конце
 * блока. Разбор по шапке брал количество из строки наименования и не находил.
 *
 * Позиция берётся, только если в блоке есть и единица, и число после неё.
 * Цитата - дословный блок от строки наименования до строки количества:
 * самопроверка сверяет его с документом буква в букву.
 */
// Ячейка кода: «17.12.14.110 17.12.14.110-00000004», «КТРУ: …», «ОКПД2: …».
const ЯЧЕЙКА_КОДА = /^((ктру|окпд\s*2?)\s*:?\s*)?\d{2}\.\d{2}(\.\d{1,3}){0,2}(-\d{8})?([\s,;]+((ктру|окпд\s*2?)\s*:?\s*)?\d{2}\.\d{2}(\.\d{1,3}){0,2}(-\d{8})?)*$/i;
/** Наименование в строке позиции ООЗ: первая ячейка после номера, кроме кода. */
function имяООЗ(я) {
  // Колонка национального режима («Ограничение», «Не установлен») стоит перед
  // наименованием в части форм (32616492897) - не товар.
  return я.slice(1).find((c) => c.length >= 3 && num(c) === null && !ЯЧЕЙКА_КОДА.test(c)
    && !/^(ограничени|запрет|преимуществ|не\s+установлен|не\s+устанавлива|национальн)/i.test(c)) || '';
}

function позицииООЗ(rows, строки = null) {
  // «Наименование товара, работы, услуги» (конструктор ЕИС) или «Наименование
  // товара/товарный знак» после колонки «Код позиции КТРУ» (0137200001226008281).
  const шапка = rows.findIndex((r, i) => r.some((c) => /наименование\s+(товара|объекта\s+закупки\s*\(товара\))/i.test(c))
    && [r, rows[i + 1] || [], rows[i - 1] || []].some((x) => x.some((c) => /характеристик/i.test(c))));
  if (шапка === -1) return null;
  // «300 шт», «3 500 шт» - количество с единицей в одной ячейке
  // (0167200003426008560: колонка «Количество, единица измерения»).
  const КОЛ_С_ЕД = /^(\d[\d\s ]*(?:[.,]\d+)?)\s*([а-яё][а-яё.\s]{0,12})$/i;
  const начало = (r) => {
    const я = r.filter((c) => c !== '');
    return я.length >= 2 && /^\d{1,4}\.?$/.test(я[0]) && имяООЗ(я).length >= 3
      && !(я.length >= 3 && я.every((c) => /^\d{1,2}$/.test(c)));
  };
  const positions = [];
  for (let i = шапка + 1; i < rows.length; i++) {
    if (!начало(rows[i])) continue;
    let до = i + 1;
    while (до < rows.length && !начало(rows[до]) && до - i < 80) до++;
    const я = rows[i].filter((c) => c !== '');
    let unit = ''; let qty = null; let конец = -1;
    const вСтроке = я.slice(2).map((c) => КОЛ_С_ЕД.exec(c)).find((м) => м && ЕДИНИЦА_КТРУ.test(м[2].trim().toLowerCase()));
    if (вСтроке) { qty = num(вСтроке[1]); unit = вСтроке[2].trim(); конец = i; }
    // С конца блока: строка из одного числа - количество, перед ней строка из
    // одной единицы; либо обе в последней строке характеристик.
    for (let k = до - 1; k > i && конец === -1; k--) {
      const яч = rows[k].filter((c) => c !== '');
      if (яч.length === 1 && num(яч[0]) !== null && num(яч[0]) > 0 && k - 1 > i) {
        const пред = rows[k - 1].filter((c) => c !== '');
        if (пред.length === 1 && ЕДИНИЦА_КТРУ.test(пред[0].toLowerCase())) { unit = пред[0]; qty = num(яч[0]); конец = k; }
      } else if (яч.length >= 2 && num(яч[яч.length - 1]) !== null && ЕДИНИЦА_КТРУ.test(яч[яч.length - 2].toLowerCase())) {
        unit = яч[яч.length - 2]; qty = num(яч[яч.length - 1]); конец = k;
      }
    }
    if (конец === -1 || !(qty > 0)) continue;
    // Хвост кода КТРУ/ОКПД2 в наименовании («Стол письменный 31.01.10.000-00000004») - не часть товара.
    const name = имяООЗ(я).replace(/\s*(окпд\s*2?|ктру)\s*:.*$/i, '')
      .replace(/(\s+\d{2}\.\d{2}(\.\d{1,3}){0,2}(-\d{8})?)+\s*$/, '').replace(/\s+/g, ' ').trim();
    if (name.length < 3 || ЕДИНИЦА_ВМЕСТО_ИМЕНИ.test(name) || МЕСЯЦ_ВМЕСТО_ИМЕНИ.test(name)) continue;
    positions.push({ name, quantity: qty, unit: unit.toLowerCase().replace(/\.$/, ''), prices: [], min: null, max: null, spreadPct: null, sourceCount: 0,
      // Цитата - из ИСХОДНЫХ строк текста: в rows ячейки с одним кодом КТРУ уже
      // убраны, и собранная из них цитата с документом не совпадала (0354300039326000110).
      цитата: (строки ? строки.slice(i, конец + 1) : rows.slice(i, конец + 1).map((r) => r.join('\t'))).join('\n') });
    i = до - 1;
  }
  if (!positions.length) return null;
  return { ok: true, positions, header: rows[шапка], безЦен: true, оозЕИС: true, issues: [] };
}

const ЕДИНИЦА_КТРУ = /^(шт|штук[аи]?|кг|г|гр|л|м|м2|м²|м3|м³|п\.?\s?м|упак|уп|пач|пачк[аи]|компл|комплект|набор|рул|рулон|т|тн|пар[аы]?|флак|флакон|бут|бутыл[ка]|бан|банк[аи]|меш|мешок|ящ|кор|короб|лист|услов\.?\s?ед|усл\.?\s?ед|ед)\.?$/i; // кириллица-ок
function позицииКТРУ(rows) {
  const шапка = rows.findIndex((r) => r.some((c) => /^кол(-|ичеств)/i.test(c)) && r.some((c) => /^ед(\.|иниц)/i.test(c)));
  if (шапка === -1) return null;
  const positions = [];
  for (const r of rows.slice(шапка + 1)) {
    const яч = r.filter((c) => c !== '');
    if (яч.length < 4 || !/^\d{1,4}\.?$/.test(яч[0])) continue;
    const единица = яч[яч.length - 1];
    const qty = num(яч[яч.length - 2]);
    if (!ЕДИНИЦА_КТРУ.test(единица) || qty === null || qty <= 0) continue;
    // «… | 2026 | г.» - год, а не граммы.
    if (/^г/i.test(единица) && qty >= 1900 && qty <= 2100) continue;
    const name = яч[1].replace(/\s*(окпд\s*2?|ктру)\s*:.*$/i, '').replace(/\s+/g, ' ').trim();
    if (name.length < 3 || num(name) !== null) continue;
    positions.push({ name, quantity: qty, unit: единица.replace(/\.$/, ''), prices: [], min: null, max: null, spreadPct: null, sourceCount: 0 });
  }
  if (positions.length < 2) return null;
  return { ok: true, positions, header: rows[шапка], безЦен: true, ктру: true, issues: [] };
}

const ЕДИНИЦА_ВМЕСТО_ИМЕНИ = /^(г\.?\s?ч\.?|куб\.?\s?м\.?|кв\.?\s?м\.?|м2|м²|м3|м³|п\.?\s?м\.?|шт\.?|штук[аи]?|усл\.?\s?ед\.?|услов\.?\s?ед\.?|ед\.?|час(ов|а)?|ч\.?|мес(яц|яцев|\.)?|год|лет|сут(ки|ок|\.)?|чел\.?-?час(ов)?|нормо-?час(ов)?|кг|т|тн|тонн[аы]?|л|компл\.?|комплект|упак\.?|рейс(ов)?|км)$/i;

const МЕСЯЦ_ВМЕСТО_ИМЕНИ = /^(январ[ья]|феврал[ья]|марта?|апрел[ья]|ма[йя]|июн[ья]|июл[ья]|августа?|сентябр[ья]|октябр[ья]|ноябр[ья]|декабр[ья])(\s+\d{4}(\s*г\.?)?)?$/i;

function спецПоШапке(rows, head) {
  const заказчиков = колонокЗаказчиков(rows, head);
  if (заказчиков) head = { ...head, dataFrom: Math.max(head.dataFrom, head.at + 2) };

  // ШАПКА С ПУСТЫМИ ЯЧЕЙКАМИ, строки без них (32616488144, 20.10.2026:
  // «| | № п/п | Наименование | | | Технические характеристики | | | Ед. изм.
  // | | | Кол-во» над «1 | Стол | … | шт. | 4»). Шапка сжимается до подписей,
  // только если ширина первых строк данных равна их числу - иначе не трогаем.
  {
    const ш = head.header || [];
    // Ячейка, начинающаяся со скобки, - продолжение подписи слева, а не своя
    // колонка (32616497504, 23.10.2026: «Единица измерения | (по ОКЕИ)» над
    // одной ячейкой «штука» - подписей выходило 5 при 4 ячейках данных).
    const подписи = ш.map((h, i) => (String(h || '').trim() && !/^\(/.test(String(h).trim()) ? i : -1)).filter((i) => i >= 0);
    const ширина = (r) => { for (let k = r.length - 1; k >= 0; k--) if (String(r[k] || '').trim()) return k + 1; return 0; };
    // Строки-подписи («Приложение №2 к извещению») - одна ячейка, в образцы не идут.
    const образцы = rows.slice(head.dataFrom, head.dataFrom + 5).filter((r) => ширина(r) >= 3);
    if (подписи.length < ш.length && подписи.length >= 3 && образцы.length
        && образцы.every((r) => ширина(r) === подписи.length) && подписи.includes(head.qtyAt)) {
      const куда = (i) => (i === -1 ? -1 : подписи.indexOf(i));
      head = { ...head, header: подписи.map((i) => ш[i]), nameAt: куда(head.nameAt), qtyAt: куда(head.qtyAt), unitAt: куда(head.unitAt) };
    }
  }

  // КОЛОНКА НАИМЕНОВАНИЯ ТОВАРА, а не первая со словом «наименование».
  // Пакетная проверка 14.10.2026: шапка «Наименование заказчика | Место
  // поставки | Наименование объекта закупки | Ед. изм. | Количество» — код
  // брал первую колонку, то есть название школы, и позиций не находил.
  const заголовок = head.header || [];
  // «Детализированное наименование» в приложении к умному контракту ЕИС
  // точнее колонки «Наименование объекта закупки по ОКПД 2»: там код и
  // название из справочника, а здесь — товар как в контракте.
  const детализированное = заголовок.findIndex((h) => /детализированн[а-яё]*\s+наименован/i.test(h));
  // «Наименование поставляемых товаров» (223-ФЗ, 32616473505) - тоже товар.
  const товарная = заголовок.findIndex((h) =>
    /наименован[а-яё]*\s+(поставляем[а-яё]*\s+)?(товар|объект|продукц|позиц|издели)/i.test(h));
  // Подписи шапки по порядку - для строки с пустыми ячейками посередине.
  const подписиШапки = заголовок.map((h, i) => (String(h || '').trim() ? i : -1)).filter((i) => i >= 0);
  const nameAt = детализированное !== -1 ? детализированное : товарная !== -1 ? товарная : head.nameAt;
  // Единица в подписи количества: «Количество, пачка». Своя колонка единицы
  // у таблиц КТРУ — единица ХАРАКТЕРИСТИКИ («г/м2»), не товара.
  const подписьКол = заголовок[head.qtyAt] || '';
  const единицаИзПодписи = (подписьКол.match(/,\s*([а-яё.]{2,12})\s*$/i) || [])[1] || '';
  // Колонка единицы — та, что начинается с «Ед. изм» / «Единица измерения»:
  // «Цена единицы» единицей не является (ПИК умного контракта, 19.10.2026).
  const явнаяЕдиница = заголовок.findIndex((h) =>
    /^(ед\.?\s*изм|единиц[аы]\s+измерени)/i.test(String(h).trim()) && !/характеристик/i.test(h));
  const колонкаЕдиницы = явнаяЕдиница !== -1 ? явнаяЕдиница
    : head.unitAt !== -1 && !/характеристик|цена/i.test(заголовок[head.unitAt] || '') ? head.unitAt : -1;

  const объёмРабот = /^объ[её]м\s+работ/i.test(String(заголовок[head.qtyAt] || '').trim());
  const positions = [];
  for (let i = head.dataFrom; i < Math.min(rows.length, head.до || Infinity); i++) {
    let cells = rows[i];

    // КОЛИЧЕСТВО С ЕДИНИЦЕЙ В ОДНОЙ ЯЧЕЙКЕ: «310 м2», «86 м.п.», «50,5 п.м. /
    // 47,5 м2» - ведомость объёмов работ (кровля 32616502960, 27.10.2026).
    // Только ровно в колонке количества с подписью «Объём работ»: в обычных
    // таблицах «1 шт.» в этой колонке стоит у строк характеристик (проект
    // контракта 0175200001626000034 - «Количество секций | 1 шт.»).
    let единицаВЯчейке = '';
    const сЕд = объёмРабот && /^(\d[\d\s ]*(?:[.,]\d+)?)\s*([а-яё][а-яё.]{0,6}\s?[23²³]?)\.?(\s*\/.*)?$/i.exec(String(cells[head.qtyAt] || '').trim());
    if (сЕд && num(сЕд[1]) > 0) {
      cells = [...cells];
      cells[head.qtyAt] = сЕд[1].trim();
      единицаВЯчейке = сЕд[2].trim();
    }

    // ВЫРАВНИВАНИЕ ПО КОЛОНКЕ КОЛИЧЕСТВА. Строки таблицы из Word и PDF
    // приходят сдвинутыми: объединённая ячейка номера даёт лишнюю пустую
    // слева, длинный адрес переносится на следующую строку и съедает
    // ячейку. Количество — последнее число в строке; на сколько оно сдвинуто
    // от своей колонки шапки, на столько сдвинуты и остальные.
    // КОЛИЧЕСТВО РОВНО В СВОЕЙ КОЛОНКЕ — берётся сразу (19.10.2026). В
    // приложении к умному контракту ЕИС после количества идут колонки НДС
    // и стоимости с «(не указано)*», у таблиц КТРУ — числовые характеристики;
    // правило «последнее число в строке» на них промахивалось. Сдвига здесь
    // нет, поэтому ошибка «цена вместо количества», от которой защищает
    // проверка ниже, сюда не проходит.
    const число = (c) => /^\d[\d\s ]*([.,]\d+)?$/.test((c || '').trim()) && num(c) > 0;
    let гдеКол = число(cells[head.qtyAt]) ? head.qtyAt : -1;
    const прямо = гдеКол !== -1;
    for (let k = cells.length - 1; !прямо && k >= 0; k--) {
      const c = (cells[k] || '').trim();
      if (/^\d[\d\s ]*([.,]\d+)?$/.test(c) && num(c) > 0) { гдеКол = k; break; }
    }
    if (гдеКол === -1) continue;
    const сдвиг = гдеКол - head.qtyAt;

    // ЧИСЛО ДОЛЖНО СТОЯТЬ В КОЛОНКЕ КОЛИЧЕСТВА, а не просто быть последним.
    // Найдено на пакетной проверке 14.10.2026: «туалетная бумага» — закупка
    // по цене за единицу, в колонке количества написано «Невозможно
    // определить количество», а последнее число в строке — предельная цена
    // единицы (128,68). Без этой проверки цена становилась количеством.
    //
    // Проверка: сдвиг найденного числа от колонки количества равен сдвигу
    // всей строки — разнице между последней заполненной ячейкой строки и
    // последней заполненной ячейкой шапки.
    const последняя = (м) => { for (let k = м.length - 1; k >= 0; k--) if ((м[k] || '').trim()) return k; return -1; };
    if (!прямо && последняя(cells) - последняя(заголовок) !== сдвиг) continue;
    // Совместная закупка: количество — сумма колонок заказчиков, и только
    // когда первое число стоит ровно в колонке количества. Сдвинутая строка
    // не берётся: последним числом в ней было бы количество одного заказчика.
    if (заказчиков && !прямо) continue;
    const qty = заказчиков && прямо ? суммаПоЗаказчикам(cells, гдеКол, заказчиков) : num(cells[гдеКол]);
    // «(не указано)*» — пустое поле формы ЕИС, не часть наименования.
    let name = (cells[nameAt + сдвиг] || '').replace(/\s*\/\s*\(не указано\)\*?/gi, '').trim();
    let unit = (колонкаЕдиницы !== -1 ? (cells[колонкаЕдиницы + сдвиг] || '').trim() : '') || единицаВЯчейке || единицаИзПодписи;
    // ПУСТЫЕ ЯЧЕЙКИ ПОСЕРЕДИНЕ СТРОКИ (25.10.2026, 32616473505): «| ножницы | | | |
    // Ножницы … | шт | 5» под шапкой из 4 подписей - общий сдвиг не подходит.
    // Непустых ячеек ровно столько, сколько подписей, и количество - на месте
    // своей подписи: ячейки сопоставляются по порядку.
    if (name.length < 3 && !заказчиков) {
      const я = cells.map((c) => (c || '').trim()).filter(Boolean);
      const кол = подписиШапки.indexOf(head.qtyAt);
      // Подписей не меньше трёх и количество правее наименования: «1 | Фотобумага…»
      // под двумя подписями - номер строки, не количество (32616498742).
      if (я.length === подписиШапки.length && подписиШапки.length >= 3 && кол > подписиШапки.indexOf(nameAt)
        && подписиШапки.indexOf(nameAt) !== -1 && num(я[кол]) === qty) {
        const по = (колонка) => (колонка === -1 ? '' : я[подписиШапки.indexOf(колонка)] || '');
        name = по(nameAt).replace(/\s*\/\s*\(не указано\)\*?/gi, '').trim();
        unit = по(колонкаЕдиницы) || единицаИзПодписи;
      }
    }

    if (/^(итого|всего)/i.test(name)) continue;
    // Голое число наименованием не бывает («5 208,68» - площадь уборки,
    // 0372100001926000241, 23.10.2026): то же правило, что в разборе с ценами.
    if (/^\d[\d\s ]*([.,]\d+)?$/.test(name)) continue;
    // Единица измерения наименованием не бывает: «г.ч.» (охрана 32616485839),
    // «КУБ.М.» (вывоз 0191300010926000092) - колонки съехали на одну.
    if (ЕДИНИЦА_ВМЕСТО_ИМЕНИ.test(name)) continue;
    // Месяц - не наименование: расчёт питания по месяцам («Январь | 7 | 18 |
    // 126 …» - дети, дни, порции; 32616499806) давал 673 «позиции»-месяца.
    if (МЕСЯЦ_ВМЕСТО_ИМЕНИ.test(name)) continue;

    // Строка с количеством, но без наименования — тот же товар по другому
    // адресу поставки (живой случай: 50 + 25 + 25 пачек). Количество
    // складывается, слагаемые сохраняются — по ним самопроверка сверяет
    // позицию с документом.
    if (name.length < 3) {
      const пред = positions[positions.length - 1];
      // Только при совпавшей единице: иначе номер страницы «2» отдельной
      // строкой прибавился бы к количеству товара.
      if (пред && unit && пред.unit && unit.toLowerCase() === пред.unit.toLowerCase()) {
        пред.quantity += qty;
        (пред.слагаемые = пред.слагаемые || [пред.quantity - qty]).push(qty);
      }
      continue;
    }

    positions.push({
      name,
      ...(заказчиков ? { слагаемыеВСтроке: частиПоЗаказчикам(cells, гдеКол, заказчиков) } : {}),
      quantity: qty,
      unit,
      prices: [],
      min: null,
      max: null,
      spreadPct: null,
      sourceCount: 0
    });
  }

  return {
    ok: positions.length > 0,
    positions,
    header: head.header,
    безЦен: true,
    issues: positions.length ? [] : ['шапка найдена, но строк с наименованием и количеством нет']
  };
}

/**
 * ЗАКУПКА ОДНОГО ТОВАРА: таблицы нет, количество написано в тексте ТЗ.
 *
 * Найдено пакетной проверкой 14.10.2026: две закупки 223-ФЗ («крафт-бумага
 * мешочная», «бумага книжная») с ТЗ на 2–3 тысячи знаков без таблицы.
 * Товар один — это объект закупки, количество — фраза вида «Количество:
 * 10 тонн».
 *
 * Защиты:
 *   — в тексте ровно одно количество (разные значения — значит товаров
 *     несколько, и угадывать, какое к чему, нельзя);
 *   — строка с количеством сохраняется ДОСЛОВНО (`цитата`): самопроверка
 *     сверяет её с документом, как всё остальное;
 *   — без объекта закупки позиция не собирается: называть её нечем.
 */
function позицияИзТекста(объект, текст) {
  const имя = String(объект || '')
    .replace(/^\s*право\s+заключения\s+(договора|контракта)\s+на\s+/i, '')
    .replace(/^\s*(на\s+)?(поставк[аиу]|закупк[аиу])\s+/i, '')
    .replace(/\s+для\s+нужд.*$/i, '')
    .replace(/\s+/g, ' ')
    .trim();
  if (имя.length < 4) return null;

  const шаблон = /(?:количеств[оа]|объ[её]м)[^:\n\d]{0,60}?[:–—-]\s*(\d[\d  ]{0,12}(?:[.,]\d+)?)\s*(?:\([^)]{0,40}\)\s*)?([а-яё]{1,12}\.?)?/gi;
  const найдено = new Map();
  for (const m of String(текст || '').matchAll(шаблон)) {
    const значение = num(m[1]);
    if (значение === null || значение <= 0) continue;
    if (!найдено.has(значение)) найдено.set(значение, { единица: (m[2] || '').replace(/\.$/, ''), цитата: m[0].trim() });
  }
  if (найдено.size !== 1) return null;

  const [[количество, { единица, цитата }]] = [...найдено.entries()];
  return {
    name: имя.charAt(0).toUpperCase() + имя.slice(1),
    quantity: количество,
    unit: единица,
    prices: [],
    min: null,
    max: null,
    spreadPct: null,
    sourceCount: 0,
    цитата
  };
}

/**
 * ПОЗИЦИИ НУМЕРОВАННЫМ СПИСКОМ, без таблицы: «3. Наконечник кабельный ТМЛ
 * 150-12-19 КВТ или аналог – 48 шт.;». Найдено 20.10.2026 на 32616487749
 * (кабельные конструкции, 223-ФЗ): таблицу сравнения предложений pdftotext
 * разнёс по клеткам, а предмет закупки в той же записке стоит списком.
 *
 * Защиты:
 *   — строка без табуляций (табуляция - это таблица, её разбирают другие);
 *   — количество и единица в КОНЦЕ строки после тире;
 *   — номера идут подряд с 1, не меньше двух позиций; из нескольких таких
 *     списков берётся самый длинный, при равной длине - первый.
 */
function позицииСписком(текст) {
  const строка = /^\s*(\d{1,3})\.\s+(\S.{2,300}?)\s*[–—-]\s*(\d[\d  ]{0,10}(?:[.,]\d+)?)\s*([а-яё]{1,8}[²³23]?\.?)\s*[;.,]?\s*$/i;
  const списки = [];
  let текущий = null;
  for (const сырая of String(текст || '').split('\n')) {
    if (сырая.includes('\t')) continue;
    const m = сырая.match(строка);
    if (!m) continue;
    const номер = Number(m[1]);
    const количество = num(m[3]);
    if (количество === null || количество <= 0) continue;
    const позиция = {
      name: m[2].replace(/\s+или\s+аналог[а-яё]*\s*$/i, '').replace(/\s+/g, ' ').trim(),
      quantity: количество,
      unit: m[4].replace(/\.$/, ''),
      prices: [], min: null, max: null, spreadPct: null, sourceCount: 0
    };
    if (номер === 1) { текущий = [позиция]; списки.push(текущий); }
    else if (текущий && номер === текущий.length + 1) текущий.push(позиция);
    else текущий = null;
  }
  const лучший = списки.reduce((a, b) => (b.length > a.length ? b : a), []);
  if (лучший.length < 2) return null;
  return { positions: лучший, header: null, безЦен: true, списком: true, issues: [] };
}

/**
 * ШАПКА С ПУСТЫМИ ЯЧЕЙКАМИ МЕЖДУ ПОДПИСЯМИ, а строки данных без них
 * (0326100005026000005, 20.10.2026: «| № п/п | | Наименование | | Ед. изм. |
 * | Коли-чество | | Ценовые предложения | | НМЦК» над «| 1 | Бумага | пачка |
 * 500 | 200000 | 212500 | 225000 | 200000»). Колонки съезжали, и
 * наименованием становилась «пачка». Шапка сжимается до непустых подписей,
 * объединённая «Ценовые предложения» раскрывается подписями второго этажа
 * («Источник №1…3»). Только при точном совпадении числа колонок с первой
 * строкой данных, иначе null — подгонять наугад нельзя.
 */
function сжатьШапку(rows, head) {
  const пусто = (c) => !String(c || '').trim();
  const верх = rows[head.at] || [];
  const низ = rows[head.at + 1] || [];
  const данные = rows.slice(head.at + 1, head.at + 6)
    .find((r) => r.filter((c) => !пусто(c)).length >= 3 && r.some((c) => num(c) !== null && String(c).length > 3));
  if (!данные) return null;
  const подписи = верх.filter((c) => !пусто(c));
  if (подписи.length < 3 || верх.length <= данные.length) return null;
  // Признак именно этой разметки: подписи через пустую ячейку. Без него
  // сжатие перекраивало бы обычные шапки с хвостом пустых колонок.
  let черезПустую = 0;
  верх.forEach((c, i) => { if (i > 0 && !пусто(c) && пусто(верх[i - 1])) черезПустую++; });
  if (черезПустую < (подписи.length - 1) * 0.6) return null;
  let ведущих = 0;
  while (ведущих < данные.length && пусто(данные[ведущих])) ведущих++;
  const шапка = [...Array(ведущих).fill(''), ...подписи];
  const нижние = низ === данные ? [] : низ.filter((c) => !пусто(c));
  if (нижние.length >= 2) {
    const k = шапка.findIndex((h) => /предложени|источник/i.test(h));
    if (k !== -1) шапка.splice(k, 1, ...нижние.map((п) => `${шапка[k]} / ${п}`));
  }
  if (шапка.length !== данные.length) {
    // ПУСТЫЕ ЯЧЕЙКИ И В СТРОКАХ ДАННЫХ, но расставлены иначе, чем в шапке
    // (32616490078, кабель, 20.10.2026: «| 1 | Кабель … | | м | | 2 000,00 | |
    // 137,24 | | 274 480,00»). Тогда сжимаются и шапка (без раскрытия второго
    // этажа), и строки таблицы — только если после сжатия числа колонок совпали.
    const сжатые = [...Array(ведущих).fill(''), ...данные.slice(ведущих).filter((c) => !пусто(c))];
    const безРаскрытия = [...Array(ведущих).fill(''), ...подписи];
    if (сжатые.length !== безРаскрытия.length) return null;
    const h2 = findHeader([безРаскрытия]);
    if (!h2) return null;
    return { ...h2, at: head.at, dataFrom: rows.indexOf(данные), до: head.до, сжата: true, сжатьСтроки: ведущих };
  }
  const h = findHeader([шапка]);
  if (!h) return null;
  return { ...h, at: head.at, dataFrom: rows.indexOf(данные), до: head.до, сжата: true };
}

/** Строка без пустых ячеек, ведущие пустые сохраняются (для `сжатьСтроки`). */
function сжатьСтроку(r, ведущих) {
  const пусто = (c) => !String(c || '').trim();
  let L = 0;
  while (L < ведущих && L < r.length && пусто(r[L])) L++;
  return [...Array(L).fill(''), ...r.slice(L).filter((c) => !пусто(c))];
}

/**
 * ПРЕДЛОЖЕНИЯ СУММОЙ НА ВСЁ КОЛИЧЕСТВО, а не ценой за единицу
 * (0326100005026000005: 500 пачек, предложения 200 000 / 212 500 / 225 000 ₽,
 * колонка «НМЦК» строки — 200 000, то есть минимальное предложение целиком).
 * В обычной таблице НМЦК строки = количество × цена и с ценой единицы не
 * совпадает (кроме количества 1, оно не трогается). Совпало до 1% — цены
 * делятся на количество, исходная сумма сохраняется для самопроверки.
 */
function ценыИзСумм(prices, qty, итогСтроки) {
  if (!(qty > 1) || !(итогСтроки > 0) || !prices.length) return null;
  const мин = Math.min(...prices.map((p) => p.value));
  if (Math.abs(мин - итогСтроки) > итогСтроки * 0.01) return null;
  return prices.map((p) => ({ ...p, value: round2(p.value / qty), сумма: p.value }));
}

/**
 * Разбирает текст обоснования НМЦК в позиции с ценами.
 *
 * @param {string} text текст из extract-text.js
 * @returns {{ok: boolean, positions: Array, header: Array, issues: Array<string>}}
 */
/**
 * ОБОСНОВАНИЕ НМЦК ПО ФОРМЕ ЕИС (24.10.2026, замер: самая частая неудача у
 * простых закупок 44-ФЗ). Строка позиции и строки предложений:
 *
 *   1 | Бумага для офисной техники | В соответствии с… | пачка | 400 | Источник № 1 | (i=1) | 330,38 | 1 | 330,38 | 3,47% | 343,60 | 137 440,00
 *     | Источник № 2 | (i=2) | 346,90 | 1 | 346,90
 *
 * После «(i=N)» - ценовая информация ЦИi, коэффициент ki и цена для расчёта
 * Цi = ki × ЦИi; в расчёт идёт Цi. Количество - последнее число перед
 * «Источник № 1», единица - ячейка перед ним, наименование - вторая ячейка.
 * Подтверждено числом заказчика: 400 × 343,60 = 137 440 - НМЦК.
 */
function нмцкЕИС(rows) {
  const ИСТОЧНИК = /^источник\s*№?\s*\d{1,2}$/i;
  const НОМЕР_И = /^\(i\s*=\s*\d{1,2}\)$/i;
  if (!rows.some((r) => r.some((c) => НОМЕР_И.test(c)))) return null;
  const positions = [];
  const ценаИз = (r) => {
    const j = r.findIndex((c) => НОМЕР_И.test(c));
    if (j === -1) return null;
    const ци = num(r[j + 1]);
    const k = num(r[j + 2]);
    const ц = num(r[j + 3]);
    const v = ц !== null && ц > 0 && k !== null && k > 0 && k < 5 ? ц : ци;
    return v !== null && v > 0 ? { value: v, column: r[j - 1] || `источник ${j}` } : null;
  };
  for (const r of rows) {
    const s = r.findIndex((c) => ИСТОЧНИК.test(c));
    if (s === -1) continue;
    const цена = ценаИз(r);
    const перед = r.slice(0, s).map((c) => c.trim());
    if (/^\d{1,4}\.?$/.test(перед[0] || '') && (перед[1] || '').length >= 3) {
      // Количество - последнее число перед «Источник № 1», единица - перед ним.
      let q = -1;
      for (let k = перед.length - 1; k >= 2; k--) if (num(перед[k]) !== null) { q = k; break; }
      const qty = q === -1 ? null : num(перед[q]);
      const unit = q > 2 && num(перед[q - 1]) === null ? перед[q - 1] : '';
      positions.push({ name: перед[1], quantity: qty, unit, prices: цена ? [цена] : [] });
    } else if (positions.length && цена && перед.every((c) => !c || num(c) === null)) {
      positions[positions.length - 1].prices.push(цена);
    }
  }
  const годные = positions.filter((п) => п.prices.length && п.name);
  if (!годные.length) return null;
  for (const п of годные) {
    const all = п.prices.map((x) => x.value);
    п.min = Math.min(...all); п.max = Math.max(...all);
    п.spreadPct = п.min > 0 ? round2(((п.max - п.min) / п.min) * 100) : null;
    п.sourceCount = all.length;
  }
  return { ok: true, positions: годные, header: ['обоснование НМЦК по форме ЕИС: «Источник № N | (i=N) | ЦИ | k | Ц»'], еис: true, issues: [] };
}

/**
 * СТРОКА, ПРОВЕРЕННАЯ ПРОИЗВЕДЕНИЕМ (24.10.2026, 0137200001226008281) - запасной
 * путь, когда колонки по шапке не сопоставились (пустые ячейки сдвигают их по-
 * разному в каждой строке):
 *
 *   | | Бумага для офисной техники (формат А4) | | | | пачка | 315,00 | 374,00 | 310,67 | | | | 333,22 | 1 000 | | | | 333 220,00
 *
 * Последнее число строки - её итог. Пара соседних чисел, произведение которых
 * равно итогу (до 0,5%), - цена для расчёта и количество; цена обязана лежать
 * между числами слева от пары (предложения, их не меньше двух). Каждая строка
 * подтверждена числом заказчика - иначе не берётся.
 */
function нмцкПоПроизведению(rows) {
  const positions = [];
  // Вид «одна цена» - только в документе с колонкой цены единицы: у работ
  // «полив | 20 | 10 219,91 м²» произведение кратности на объём - тоже итог
  // строки, а цены нет вовсе (озеленение 0335300000226000578).
  const естьЦенаЕдиницы = rows.some((r) => r.some((c) => /цен[а-яё]*\s+(за\s+)?единиц|цена\s+за\s+ед|предельн[а-яё]*\s+цен/i.test(c)));
  for (const r of rows) {
    const я = r.filter((c) => c !== '');
    const и = я.findIndex((c) => c.length >= 3 && num(c) === null && !ЯЧЕЙКА_КОДА.test(c));
    // Наименование - со словом, не подпись колонки и не «поле: значение»
    // характеристики (на сохранённых текстах сервера иначе брались «№103»,
    // «Наименование ОО», «Цвет: Серый», 24.10.2026).
    if (и === -1 || /^(итого|всего|нмцк|начальная|наименование|№|количество|цена|сумма|ед\.?\s|единица)/i.test(я[и])
      || !/[а-яёa-z]{3,}/i.test(я[и]) || /^[^:—]{2,40}(:|\s—)\s*\S/.test(я[и]) || /^[а-яё]/.test(я[и])) continue;
    const хвост = я.slice(и + 1);
    // Коэффициент («1,0494» - инфляция, «0,925» - пересчёт) ни ценой, ни
    // количеством не бывает: 370 695,60 × 1,0494 = итог строки, и ценой
    // становился коэффициент (оборудование 0995400000226000033, 25.10.2026).
    const коэффициент = (v) => v > 0 && v < 3 && (String(v).split('.')[1] || '').length >= 3;
    const числа = хвост.map((c) => num(c)).map((v, k) => ({ v, k })).filter((x) => x.v !== null && x.v > 0 && !коэффициент(x.v));
    // Вид 3: нормативный метод - одна предельная цена: «… | УПАК | 720 | 99,84 |
    // 71 884,80» (0372200081326000034). Ровно три числа, количество × цена = итог.
    // Дробное число при целом соседе - цена, а не количество («11 633,94 | 10 |
    // 116 339,40», 0330100010826000009); цена ровно 1 - коэффициент, не цена
    // (рассада 0335300000226000578: «356 830 | 1 | 356 830»).
    const целое = (v) => Number.isInteger(v);
    if (числа.length === 3 && !целое(числа[0].v) && целое(числа[1].v)) числа.splice(0, 2, числа[1], числа[0]);
    // Множитель 1 («7 853,6 | 1 | 7 853,6») - неоднозначно, что количество, а что
    // цена (площадь работ у озеленения стала ценой): такая строка не берётся.
    if (естьЦенаЕдиницы && числа.length === 3 && Math.abs(числа[0].v * числа[1].v - числа[2].v) <= числа[2].v * 0.005 && числа[2].v >= 10
      && числа[0].v !== 1 && числа[1].v !== 1
      && !/^[^:—]{2,40}(:|\s—)\s*\S/.test(я[и]) && /[а-яёa-z]{3,}/i.test(я[и]) && !/^[а-яё]/.test(я[и])
      && !/^(итого|всего|нмцк|начальная|наименование|№|количество|цена|сумма)/i.test(я[и])
      && (String(числа[0].v).split('.')[1] || '').length <= 3) {
      const единица = хвост.find((c) => num(c) === null && c.length <= 25 && !ЯЧЕЙКА_КОДА.test(c) && /[а-яёa-z]/i.test(c)) || '';
      positions.push({ name: я[и], quantity: числа[0].v, unit: единица, prices: [{ value: числа[1].v, column: 'предельная цена единицы' }],
        min: числа[1].v, max: числа[1].v, spreadPct: 0, sourceCount: 1 });
      continue;
    }
    if (числа.length < 5) continue;
    const итог = числа[числа.length - 1].v;
    let найдено = null;
    const внутри = (ц, ряд) => ряд.length >= 2 && ц >= Math.min(...ряд) * 0.999 && ц <= Math.max(...ряд) * 1.001;
    const равноИтогу = (a, b) => Math.abs(a * b - итог) <= итог * 0.005;
    // Вид 1: «предложения… | средняя | количество | … | итог» - пара соседняя,
    // предложения слева от неё (0137200001226008281).
    for (let k = 2; k + 1 < числа.length - 1 && !найдено; k++) {
      const a = числа[k].v; const b = числа[k + 1].v;
      if (!равноИтогу(a, b)) continue;
      const слева = числа.slice(0, k).map((x) => x.v);
      if (внутри(a, слева)) найдено = { цена: a, qty: b, предложения: слева };
      else if (внутри(b, слева)) найдено = { цена: b, qty: a, предложения: слева };
    }
    // Вид 2: «количество | предложения… | средняя | … | итог» - предложения между
    // количеством и средней (0301300174726000066: 120 × 436,28 = 52 353,60).
    for (let i = 0; i < числа.length - 1 && !найдено; i++) {
      for (let j = i + 3; j < числа.length - 1 && !найдено; j++) {
        const между = числа.slice(i + 1, j).map((x) => x.v);
        if (равноИтогу(числа[i].v, числа[j].v) && внутри(числа[j].v, между)) {
          найдено = { цена: числа[j].v, qty: числа[i].v, предложения: между };
        }
      }
    }
    if (!найдено) continue;
    // Предложения сопоставимы: не нумерация колонок (1, 2, 3) и не числа разного
    // порядка - самое большое не выше самого малого втрое (граница здравого
    // смысла, та же, что у отсева несопоставимых цен поставщиков).
    const пр = найдено.предложения;
    const нумерация = пр.every((v, k) => v === k + 1);
    const дробь = (String(найдено.qty).split('.')[1] || '').length;
    if (нумерация || Math.max(...пр) > Math.min(...пр) * 3 || !(найдено.qty > 0) || дробь > 3 || итог < 10) continue;
    const единица = хвост.find((c) => num(c) === null && c.length <= 15 && !ЯЧЕЙКА_КОДА.test(c) && /[а-яёa-z]/i.test(c)) || '';
    const prices = найдено.предложения.map((v, k) => ({ value: v, column: `источник ${k + 1}` }));
    const all = prices.map((x) => x.value);
    const min = Math.min(...all); const max = Math.max(...all);
    // Следующая текстовая ячейка - на случай, когда первой во всех строках стоит
    // название закупки («Приобретение бланочной продукции…», 0851100001926000597).
    const второе = хвост.find((c) => c.length >= 6 && num(c) === null && /[а-яёa-z]{3,}/i.test(c) && c !== единица && !ЯЧЕЙКА_КОДА.test(c)) || '';
    positions.push({ name: я[и], второе, quantity: найдено.qty, unit: единица, prices, min, max,
      spreadPct: min > 0 ? round2(((max - min) / min) * 100) : null, sourceCount: prices.length });
  }
  if (!positions.length) return null;
  if (positions.length > 1 && new Set(positions.map((п) => п.name)).size === 1 && positions.every((п) => п.второе)) {
    for (const п of positions) п.name = п.второе;
  }
  for (const п of positions) delete п.второе;
  return { ok: true, positions, header: ['строки, проверенные произведением: цена × количество = итог строки'], поПроизведению: true,
    issues: ['колонки по шапке не сопоставились - позиции взяты по строкам, где цена × количество равно итогу строки'] };
}

/**
 * ОБОСНОВАНИЕ АНКЕТОЙ «Показатели | Значения» (25.10.2026, 0134300097526001193) -
 * один товар, поля строками:
 *
 *   1 | Наименование объекта закупки | бумага для офисной техники
 *   3 | Количество закупаемых товаров (работ, услуг) и единицы измерения | 840 пачек
 *     |   | Поставщик № 1 (информация получена по письменному запросу…) | … | 360.8
 *     |   | ИТОГО НМЦК (ЦК), руб. |   | 307524
 *
 * Берётся, только если итог заказчика подтверждает количество: он лежит между
 * количеством × наименьшее и × наибольшее предложение (840 × 366,10 = 307 524).
 * Строка с количеством - цитата для самопроверки (поля в разных строках).
 */
function нмцкАнкетой(rows, lines) {
  const значениеПосле = (r, j) => r.slice(j + 1).find((c) => c !== '') || '';
  let name = ''; let qty = null; let unit = ''; let цитата = ''; let итог = null;
  const prices = [];
  rows.forEach((r, i) => {
    const j = r.findIndex((c) => c !== '' && num(c) === null);
    if (j === -1) return;
    const подпись = r[j];
    if (!name && /^наименование\s+объекта\s+закупки$/i.test(подпись)) name = значениеПосле(r, j);
    else if (qty === null && /^количество\s+(закупаемых\s+|поставляемых\s+)?товар/i.test(подпись)) {
      const m = значениеПосле(r, j).match(/^(\d[\d\s]*(?:[.,]\d+)?)\s*([а-яёa-z][а-яёa-z.\s]{0,20})?$/i);
      if (m) { qty = num(m[1]); unit = (m[2] || '').trim(); цитата = lines[i] || r.join('\t'); }
    } else if (/^(поставщик|коммерческое\s+предложение|источник)\s*№?\s*\d{1,2}(?![\d])/i.test(подпись)) {
      const числа = r.slice(j + 1).map((c) => num(c)).filter((v) => v !== null && v > 0);
      if (числа.length) prices.push({ value: числа[числа.length - 1], column: подпись.slice(0, 40) });
    } else if (итог === null && /^итого\s+нмц/i.test(подпись)) {
      const числа = r.slice(j + 1).map((c) => num(c)).filter((v) => v !== null && v > 0);
      if (числа.length) итог = числа[числа.length - 1];
    }
  });
  if (!name || !/[а-яёa-z]{3,}/i.test(name) || !(qty > 0) || prices.length < 2 || итог === null) return null;
  const all = prices.map((x) => x.value);
  const min = Math.min(...all); const max = Math.max(...all);
  if (max > min * 3 || итог < qty * min * 0.995 || итог > qty * max * 1.005) return null;
  return { ok: true, positions: [{ name, quantity: qty, unit, prices, min, max, цитата,
    spreadPct: min > 0 ? round2(((max - min) / min) * 100) : null, sourceCount: prices.length }],
  header: ['обоснование анкетой «Показатели | Значения»: один товар, итог заказчика подтверждает количество'], анкета: true, issues: [] };
}

function parseNmckTable(text) {
  const rows = String(text || '')
    .split('\n')
    .map((line) => line.split('\t').map((c) => c.replace(/ /g, ' ').trim()));

  // Форма ЕИС - своим разбором, раньше общего: общий сдвигал колонки и не
  // собирал предложения строками «Источник № N» (три числа в строке).
  const еис = нмцкЕИС(rows);
  if (еис) return еис;
  const анкета = нмцкАнкетой(rows, String(text || '').split('\n'));
  if (анкета) return анкета;

  // ПЕРЕВЁРНУТАЯ ТАБЛИЦА — проверяется ПЕРВОЙ, до поиска обычной шапки.
  // Обычный разбор на таком файле не отказывается, а выдаёт уверенный мусор:
  // наименованиями позиций становятся подписи полей. Значит выбирать между
  // двумя разборами по принципу «кто что-нибудь нашёл» нельзя.
  if (этоПеревёрнутая(rows)) return разборПеревёрнутой(rows);
  // ТА ЖЕ ТАБЛИЦА СО СДВИГОМ НА КОЛОНКУ: в Excel слева колонка номера блока
  // («1 | Поставщики | Источник 1 …», дальше « | Наименование товара | …»),
  // подписи полей во ВТОРОЙ ячейке (0373200315626000003, 19.10.2026).
  // Сдвиг — только когда первая ячейка пуста или номер блока.
  // До двух колонок: у 0373200082126000566 слева пустая и номер позиции.
  for (const n of [1, 2]) {
    // «№ п/п» — подпись колонки номера в строке шапки, её тоже сдвигаем.
    const сдвинутые = rows.map((c) => (c.slice(0, n).every((x) => /^(\d{0,3}|№\s*п\/п)$/i.test((x || '').trim())) ? c.slice(n) : c));
    if (этоПеревёрнутая(сдвинутые)) return { ...разборПеревёрнутой(сдвинутые), сдвиг: n };
  }

  // Запасной путь — шапка дальше 30-й строки (обоснование внутри большого
  // документа). Прежний путь идёт первым, на проверенных файлах ничего не меняется.
  const найдена = findHeader(rows) || findHeaderAnywhere(rows);
  if (!найдена) {
    const пп = нмцкПоПроизведению(rows);
    if (пп) return пп;
    return {
      ok: false,
      positions: [],
      header: [],
      issues: ['шапку таблицы распознать не удалось — документ уходит человеку, позиции не выдумываются']
    };
  }
  const первая = сГраницей(найдена, всеШапки(rows), rows);
  const итог = разборЦенПоШапке(rows, первая);
  // Разбор по шапке дал позиции без количества (шапка в три этажа склеилась
  // не с теми колонками, 0301300174726000066), а строки, подтверждённые
  // итогом заказчика (цена × количество = итог строки), есть - берутся они.
  if (итог.ok && итог.positions.some((п) => п.quantity === null || п.quantity === undefined)) {
    const пп = нмцкПоПроизведению(rows);
    if (пп && пп.positions.length >= итог.positions.filter((п) => п.quantity > 0).length) return пп;
  }
  if (итог.ok) return итог;
  // По первой шапке позиций нет — пробуем следующие (ТЗ без цен перед
  // обоснованием НМЦК в одном документе). Прежний путь идёт первым.
  for (const h of всеШапки(rows)) {
    if (h.at <= первая.at || !товарнаяШапка(h) || !h.priceCols.length) continue;
    const r = разборЦенПоШапке(rows, h);
    if (r.ok) return r;
  }
  return нмцкПоПроизведению(rows) || итог;
}

/**
 * ЕДИНИЦА И КОЛИЧЕСТВО ЭТАЖОМ ВЫШЕ (кафе 32616497177, 23.10.2026). Шапка в два
 * этажа, перепутанных по высоте:
 *
 *   Используемый метод … | Ед. Изм. | Кол-во | Коммерческие предложения … | …
 *   №   | Наименование   | Поставщик №1 | Поставщик №2 | Поставщик №3 | Средняя …
 *   1   | Услуги по обслуживанию… | у.е | 1,00 | 604800,00 | 633600,00 | …
 *
 * Нижний этаж найден шапкой, в нём нет единицы и количества, и единицей
 * становилось первое предложение. Подписи верхнего этажа вставляются после
 * наименования - только если строка данных это подтверждает: после
 * наименования текст (единица), за ним число.
 */
function этажВыше(rows, head) {
  if (head.qtyAt !== -1 || head.unitAt !== -1 || head.at < 1) return null;
  const выше = rows[head.at - 1] || [];
  const ед = выше.findIndex((c) => HEAD_UNIT.test(c));
  const кол = выше.findIndex((c) => HEAD_QTY.test(c) && !HEAD_DERIVED.test(c));
  if (ед === -1 || кол === -1 || ед > кол) return null;
  const n = head.nameAt;
  const строка = rows.slice(head.dataFrom, head.dataFrom + 15).find((r) => (r[n] || '').trim().length >= 3
    && r.length >= head.header.length + 2);
  if (!строка) return null;
  const единица = (строка[n + 1] || '').trim();
  if (!единица || num(единица) !== null || единица.length > 20 || num(строка[n + 2]) === null) return null;
  const header = [...head.header.slice(0, n + 1), 'Ед. изм.', 'Кол-во', ...head.header.slice(n + 1)];
  return {
    ...head,
    header,
    unitAt: n + 1,
    qtyAt: n + 2,
    priceCols: head.priceCols.map((p) => (p.at > n ? { ...p, at: p.at + 2 } : p))
  };
}

function разборЦенПоШапке(rows, head) {
  const issues = [];
  const выше = этажВыше(rows, head);
  if (выше) {
    head = выше;
    issues.push('единица и количество подписаны этажом выше шапки - колонки выровнены по строке данных');
  }
  const сжатая = сжатьШапку(rows, head);
  if (сжатая) {
    head = сжатая;
    issues.push('шапка таблицы с пустыми ячейками между подписями — колонки выровнены по строке данных');
    if (typeof сжатая.сжатьСтроки === 'number') {
      const до = сжатая.до || rows.length;
      rows = rows.map((r, i) => (i >= сжатая.dataFrom && i < до ? сжатьСтроку(r, сжатая.сжатьСтроки) : r));
    }
  }
  const заказчиков = колонокЗаказчиков(rows, head);
  if (заказчиков) {
    head = { ...head, dataFrom: Math.max(head.dataFrom, head.at + 2) };
    issues.push(`количество сложено по ${заказчиков} заказчикам (совместная закупка)`);
  }
  if (!head.priceCols.length) {
    issues.push('в шапке не нашлось ни одной колонки с ценой предложения');
  }
  if (head.qtyAt === -1) {
    issues.push('колонка количества не найдена — суммы по позициям посчитать нельзя');
  }

  const выровненные = rows.map((cells) => {
    if (cells.length !== 3 || cells[0] || !/^https?:\/\//i.test(cells[1]) || num(cells[2]) <= 0 || !head.priceCols.length) return cells;
    const полная = Array(head.header.length).fill('');
    const источник = head.header.findIndex((h) => /источник/i.test(h));
    if (источник !== -1) полная[источник] = cells[1];
    полная[head.priceCols[0].at] = cells[2];
    return полная;
  });
  const строки = склеитьПереносыНаименований(выровненные, head);

  const positions = [];
  const конец = Math.min(строки.length, head.до || Infinity);
  for (let i = head.dataFrom; i < конец; i++) {
    const cells = строки[i];
    const name = (cells[head.nameAt] || '').trim();

    // СТРОКА-ПРЕДЛОЖЕНИЕ «| Поставщик 2 | 6,05» (0372100001926000241, уборка,
    // 23.10.2026): короткая строка под позицией, подпись источника и цена.
    // Подпись стоит на месте наименования, и позицией становился «Поставщик 3».
    // Цена приклеивается к позиции выше как ещё одно предложение.
    {
      const непустые = cells.map((c) => (c || '').trim()).filter(Boolean);
      const подпись = непустые.find((c) => /^(поставщик|источник|кп|ткп|коммерческое предложение|предложение)\s*(№\s*)?\d{1,2}$/i.test(c));
      const числа = непустые.map((c) => num(c)).filter((v) => v !== null && v > 0);
      if (подпись && непустые.length <= 3 && числа.length === 1 && positions.length) {
        const last = positions[positions.length - 1];
        last.prices.push({ value: числа[0], column: подпись });
        const all = last.prices.map((p) => p.value);
        last.min = Math.min(...all);
        last.max = Math.max(...all);
        last.spreadPct = last.min > 0 ? round2(((last.max - last.min) / last.min) * 100) : null;
        last.sourceCount = last.prices.length;
        continue;
      }
    }

    // Строка НМЦК договора - конец таблицы: ниже идёт ТЗ, и номера его пунктов
    // («6.4.», «6.5.») приклеивались к последней позиции ценами (32616497177).
    if (/^начальная\s*\(максимальная\)\s*цена\s+(договора|контракта)/i.test((cells[0] || '').trim()) && positions.length) break;
    if (/^итого|^всего|^начальная|^заказчик вправе|^источник финанс/i.test(name)) continue;
    // Итог с подписью в первой ячейке: «Начальная (максимальная) цена договора
    // | 867 008,40 | …» — в колонке наименования число. Число товаром не бывает.
    if (/^итого|^всего|^начальная/i.test((cells[0] || '').trim())) continue;
    if (/^\d[\d\s ]*([.,]\d+)?$/.test(name)) continue;

    const prices = [];
    for (const col of head.priceCols) {
      const v = num(cells[col.at]);
      if (v !== null && v > 0) prices.push({ value: v, column: col.title });
    }
    if (!prices.length) continue;

    // ВТОРАЯ РАСКЛАДКА ТАБЛИЦЫ: предложения идут строками, а не колонками.
    // Наименование написано один раз в верхней строке, ячейка объединена
    // по вертикали, и у следующих строк это поле пустое:
    //
    //   Поставка электроматериалов | ТКП №1 | 1 001 735,86
    //                              | ТКП №2 | 1 077 447,82
    //                              | ТКП №3 | 1 251 031,46
    //
    // Раньше такие строки считались мусором и отбрасывались — позиция
    // получала одно предложение вместо трёх, то есть разброс исчезал,
    // а вместе с ним и понимание, насколько цена надёжна.
    //
    // НО СТРОКА СО СВОИМ КОЛИЧЕСТВОМ — ОТДЕЛЬНЫЙ ТОВАР (19.10.2026). На скане
    // 0190200000326011772 распознавание не прочло наименование фотобумаги,
    // а количество 10 и цены 600/650/730 прочло. По правилу выше её цены
    // приклеились к бумаге 250 г — позиция пропала, чужая получила разброс
    // втрое. У строки-предложения («ТКП №2») своего количества нет.
    const своёКол = head.qtyAt === -1 ? null
      : заказчиков ? суммаПоЗаказчикам(cells, head.qtyAt, заказчиков) : num(cells[head.qtyAt]);
    let безИмени = false;
    let имя = name;
    // Строка нумерации колонок («1 | 2 | 3 | 4 | 5») — не товар: её «2» в
    // колонке количества и «5 | 6 | 7» в ценах отсеивал прежний путь,
    // и новый обязан отсеивать тоже (обоснование «молоко», 19.10.2026).
    const числаСтроки = cells.map((c) => (c || '').trim()).filter(Boolean);
    const нумерация = числаСтроки.length >= 3 && числаСтроки.every((c, k) =>
      /^\d{1,2}$/.test(c) && (k === 0 || Number(c) === Number(числаСтроки[k - 1]) + 1));
    // Склейка ниже приклеила бы её «цены» 3 и 4 к товару выше.
    if (нумерация && name.length < 3) continue;
    if (name.length < 3 && своёКол !== null && своёКол > 0 && positions.length && !нумерация) {
      // Наименованием становится дословный текст соседней ячейки (описание,
      // код КТРУ) — он стоит в той же строке документа, и самопроверка его
      // сверит. Позиция помечается: человек должен посмотреть скан.
      const описание = cells.slice(head.nameAt + 1).map((c) => (c || '').trim())
        .find((c) => c.length >= 10 && !/^\d[\d\s ]*([.,]\d+)?$/.test(c));
      // Описания тоже нет (скан 0190200000326011756: прочитаны только
      // количество, единица и цены) — позиция всё равно своя. Название
      // честно говорит, что его нет: самопроверка такую строку не
      // подтвердит, в поиск поставщиков она не уйдёт, а сумма с НМЦК
      // сверится целиком.
      имя = описание ? описание.slice(0, 120).trim() : 'наименование не распознано';
      безИмени = true;
    }

    if (имя.length < 3 || (/^https?:\/\//i.test(имя) && своёКол === null)) {
      const last = positions[positions.length - 1];
      if (!last) continue;
      last.prices.push(...prices);
      const all = last.prices.map((p) => p.value);
      last.min = Math.min(...all);
      last.max = Math.max(...all);
      last.spreadPct = last.min > 0 ? round2(((last.max - last.min) / last.min) * 100) : null;
      last.sourceCount = last.prices.length;
      continue;
    }

    const qty = своёКол;
    // Колонка НМЦК строки («НМЦКрын, руб»): если она равна минимальному
    // предложению, предложения даны суммой на всё количество.
    const итогАт = head.header.findIndex((h, k) => /нмцк|начальн[а-яё]*\s*\(?\s*максим/i.test(h)
      && !head.priceCols.some((p) => p.at === k));
    const изСумм = итогАт !== -1 ? ценыИзСумм(prices, qty, num(cells[итогАт])) : null;
    if (изСумм) {
      prices.splice(0, prices.length, ...изСумм);
      issues.push(`«${имя.slice(0, 40)}»: предложения указаны суммой на ${qty} ед. — цена за единицу = сумма / количество`);
    }
    const values = prices.map((p) => p.value);
    const min = Math.min(...values);
    const max = Math.max(...values);

    if (безИмени) {
      issues.push(`позиция ${positions.length + 1}: наименование не распознано, взято описание из соседней ячейки — сверить с документом`);
    }
    positions.push({
      name: имя,
      ...(безИмени ? { наименованиеНеРаспознано: true } : {}),
      ...(заказчиков ? { слагаемыеВСтроке: частиПоЗаказчикам(cells, head.qtyAt, заказчиков) } : {}),
      quantity: qty,
      unit: head.unitAt !== -1 ? (cells[head.unitAt] || '') : единицаРядом(cells, head.header, head.qtyAt),
      prices,
      min,
      max,
      spreadPct: min > 0 ? round2(((max - min) / min) * 100) : null,
      sourceCount: prices.length
    });
  }

  if (!positions.length) {
    issues.push('шапка найдена, но ни одной строки с позицией и ценой не распознано');
  }

  return { ok: positions.length > 0, positions, header: head.header, issues };
}

/**
 * Превращает разобранные позиции в цены для `pricing.js`.
 *
 * Каждое предложение становится отдельной ценой со своим источником —
 * именно так `resolvePosition` увидит разброс и возьмёт худшую цену.
 *
 * @param {object} position позиция из parseNmckTable
 * @param {object} doc сведения о документе: url, date, name
 */
function toPriceRecords(position, doc = {}) {
  return position.prices.map((p, i) => ({
    price: p.value,
    source: 'обоснование НМЦК',
    url: doc.url || '',
    date: doc.date || null,
    supplier: '',
    evidence: `${doc.name || 'обоснование НМЦК'}, ${p.column || 'предложение ' + (i + 1)}, позиция «${position.name.slice(0, 40)}»`
  }));
}

