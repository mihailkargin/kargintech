/**
 * Разбор таблицы обоснования НМЦК: позиции и цены коммерческих предложений.
 * Без внешних зависимостей — тело функции переносится в Code-ноду n8n как есть.
 *
 * ОТКУДА БЕРЁТСЯ ВХОД. Текст даёт `extract-text.js`: ячейки разделены
 * табуляцией, строки — переводом строки. Для DOCX и XLSX это уже работает,
 * для старых форматов — после конвертера.
 *
 * ЗАЧЕМ ЭТО НУЖНО. Обоснование НМЦК — единственное место на портале, где
 * лежат цены поставщиков по позициям. Проверено 30.09.2026: по 44-ФЗ оно
 * есть в 10 закупках из 10, по 223-ФЗ — в 6 из 10.
 *
 * ЕДИНОГО ФОРМАТА НЕТ, и это главная сложность. Каждый заказчик верстает
 * таблицу по-своему: у одних колонки «цена за единицу» и «итого» на каждое
 * предложение, у других только цены; шапка бывает в один этаж и в два;
 * названия колонок пишут как придётся. Поэтому разбор идёт от шапки,
 * а не от фиксированных номеров колонок.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ: догадок. Не нашли шапку — возвращаем «не
 * разобрано», а документ уходит человеку или в модель. Подставить позицию
 * «по смыслу» нельзя: клиент увидит смету, поверит ей и зайдёт в убыточный
 * тендер.
 *
 * НАЗВАНИЙ ПОСТАВЩИКОВ В ЭТИХ ТАБЛИЦАХ НЕТ. Проверено на семи реальных
 * файлах: предложения обезличены — «КП 1», «ТКП №1», «Предложение № 57».
 * Имена поставщиков добываются из реестра контрактов, не отсюда.
 */

/**
 * ЕДИНИЦА В КОЛОНКЕ БЕЗ ПОДПИСИ (металл 32616503996, 28.10.2026): шапка
 * «Количество | (пусто) | Цена», строка «1,83 | т | 78 000» - у 81 позиции
 * единица была пустой. Берётся соседняя с количеством ячейка, если её подпись
 * в шапке пустая, а в ней - единица из короткого списка.
 */
const ЕДИНИЦА_ЯЧЕЙКИ = /^(шт|штук[а-яё]*|т|тн|тонн[а-яё]*|кг|г|л|литр[а-яё]*|м|м2|м²|м3|м³|п\.?\s*м|пог\.?\s*м|м\.?\s*п|пач[а-яё]*|упак[а-яё]*|уп|компл[а-яё]*|рул[а-яё]*|лист[а-яё]*|короб[а-яё]*|набор[а-яё]*|ед|усл\.?\s*ед)\.?$/i;
function единицаРядом(cells, header, qtyAt) {
  if (qtyAt === -1 || qtyAt === undefined) return '';
  const подписана = (k) => String((header || [])[k] || '').trim() !== '';
  // Объединённые ячейки Excel: между «Количество» (30) и «Цена» (42) пустые
  // колонки, единица в 36. Смотрим все неподписанные до следующей подписи.
  for (let k = qtyAt + 1; k < (cells || []).length && !подписана(k); k++) {
    const c = String(cells[k] || '').trim();
    if (c) return ЕДИНИЦА_ЯЧЕЙКИ.test(c) ? c : '';
  }
  const слева = String((cells || [])[qtyAt - 1] || '').trim();
  return слева && !подписана(qtyAt - 1) && ЕДИНИЦА_ЯЧЕЙКИ.test(слева) ? слева : '';
}

