/**
 * ЗАПРОСЫ КОММЕРЧЕСКИХ ПРЕДЛОЖЕНИЙ ПОСТАВЩИКАМ — тариф Макс, решение
 * владельца 21.10.2026: письма уходят автоматически от имени KarginTech.
 *
 * Зачем: цена с сайта отвечает «почём это продают», ответ поставщика на
 * запрос - «почём я куплю». Для посредника это главное.
 *
 * ПРАВИЛА, КОТОРЫЕ НЕЛЬЗЯ ОСЛАБЛЯТЬ:
 *   — почта поставщика берётся ТОЛЬКО со страницы его сайта, нашим кодом.
 *     Адрес от модели - догадка: письмо уйдёт в никуда или чужому человеку;
 *   — в письме нет ничего о клиенте: ни названия, ни цен, ни прайса. Только
 *     публичная закупка - товар, количество, характеристики из ТЗ;
 *   — в каждом письме есть способ отказаться, и отказ исполняется
 *     (стоп-список по адресу и домену): рассылка без этого - спам, и домен
 *     kargintech.ru попадёт в чёрные списки;
 *   — ответ поставщика показывается клиенту как есть, цена из него в расчёт
 *     сама не подставляется: в свободном тексте единица и условия могут быть
 *     любыми, решает человек.
 *
 * Сетевых обращений здесь нет.
 */

const ПОЧТА = /[a-z0-9._%+-]{1,64}@[a-z0-9.-]{1,190}\.[a-z]{2,24}/gi;
/** Адреса, которые на страницах есть, но писать туда бессмысленно или нельзя. */
const МУСОР = /^(no-?reply|noreply|donotreply|mailer-daemon|postmaster|abuse|webmaster|privacy|gdpr|dpo|hr|job|jobs|resume|career|rabota|vacancy)@|@(example\.(com|ru|org)|sentry\.io|.*sentry|wixpress\.com|domain\.(com|ru)|test\.ru|email\.com|yourmail\.ru|site\.ru)$/i;
const КАРТИНКА = /\.(png|jpe?g|gif|webp|svg)$/i;
/** Отдел продаж - предпочтительно: письмо попадёт к тому, кто называет цены. */
const ПРОДАЖИ = /^(sales?|opt|zakaz|order|orders|info|office|mail|manager|prodazhi|torg|snab)\b/i;

const домен = (u) => {
  try { return new URL(u).hostname.replace(/^www\./, '').toLowerCase(); } catch (e) { return ''; }
};
const корень = (h) => String(h || '').split('.').slice(-2).join('.');

/**
 * Почта со страницы: ссылки mailto и адреса в тексте. Сначала адреса домена
 * самого сайта и отдела продаж. Не больше двух: одному поставщику - одно письмо.
 */
function почтыСоСтраницы(html, url) {
  const s = String(html || '')
    .replace(/<script\b[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style\b[\s\S]*?<\/style>/gi, ' ')
    .replace(/&#64;|&commat;|\s*\[at\]\s*|\s*\(at\)\s*/gi, '@')
    .replace(/%40/g, '@');
  const найдено = new Set();
  for (const m of s.matchAll(/mailto:([^"'?\s>]+)/gi)) найдено.add(decodeURIComponent(m[1]).toLowerCase());
  for (const m of s.replace(/<[^>]+>/g, ' ').matchAll(ПОЧТА)) найдено.add(m[0].toLowerCase());
  const свой = корень(домен(url));
  return [...найдено]
    .map((a) => a.replace(/^[.]+|[.]+$/g, ''))
    .filter((a) => /^[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,24}$/i.test(a) && !МУСОР.test(a) && !КАРТИНКА.test(a))
    .sort((a, b) => {
      const ва = (корень(a.split('@')[1]) === свой ? 2 : 0) + (ПРОДАЖИ.test(a) ? 1 : 0);
      const вб = (корень(b.split('@')[1]) === свой ? 2 : 0) + (ПРОДАЖИ.test(b) ? 1 : 0);
      return вб - ва;
    })
    .slice(0, 2);
}

/** Метка запроса в теме: по ней ответ находит свою закупку. */
const метка = (ид) => `[КП-${ид}]`;
const МЕТКА = /\[КП-([A-Z0-9]{8})\]/i;

const числоРус = (x) => String(x).replace('.', ',');

/**
 * Письмо-запрос. Только публичная закупка: товар, количество, характеристики.
 * @param {{ид: string, позиции: Array<{наименование, количество, единица, характеристики}>, срокОтвета?: string, отправитель?: string}} з
 */
/**
 * Требования из строки ТЗ - читаемо: без разделителей таблицы, без повтора
 * наименования, служебных ячеек («Да», код КТРУ, ссылки на ГОСТ-основание)
 * и обрыва на полуслове.
 */
function требования(текст, наименование, предел = 500) {
  const мусор = /^(да|нет|-|—|шт\.?|штука|пачка|упаковка)$|^код позиции|^установлено |^обоснование |^информация включена|постановлени|правил использования ктру|^значение характеристики не может|^участник закупки указывает/i;
  const имя = String(наименование || '').toLowerCase();
  const части = String(текст || '').split(/\s*[|\t]\s*/).map((с) => с.replace(/\s+/g, ' ').trim())
    .filter((с) => с && !мусор.test(с) && с.toLowerCase() !== имя && !/^\d+([.,]\d+)?$/.test(с));
  let out = '';
  // Повтор характеристики («Масса бумаги…» второй раз) - начался следующий
  // товар из соседней строки ТЗ (живая закупка 0326100005026000005: после
  // офисной бумаги шли 200 г/м² и 10 листов фотобумаги). Дальше не берём.
  const видели = new Set();
  for (const ч of части) {
    const ключ = ч.toLowerCase();
    if (!/^[≥≤<>\d]/.test(ч) && ч.length > 12 && видели.has(ключ)) break;
    видели.add(ключ);
    if ((out + '; ' + ч).length > предел) break;
    out = out ? `${out}; ${ч}` : ч;
  }
  return out;
}

function письмоКП(з) {
  const строки = з.позиции.slice(0, 15).map((п, i) => {
    const кол = typeof п.количество === 'number' ? `\n   Количество: ${числоРус(п.количество)}${п.единица ? ` (${п.единица})` : ''}` : '';
    const т = требования(п.характеристики, п.наименование);
    const хар = т ? `\n   Требования: ${т}` : '';
    return `${i + 1}. ${п.наименование}${кол}${хар}`;
  });
  const тема = `Запрос цены ${метка(з.ид)}`;
  const текст = [
    'Здравствуйте.',
    '',
    'Просим сообщить цену и срок поставки по позициям:',
    '',
    ...строки,
    '',
    // Реквизиты покупателя - с его разрешения (решение владельца 21.10.2026):
    // крупный оптовик без них цену не называет (ответ Комуса).
    ...(з.покупатель ? [`Покупатель: ${з.покупатель.название}, ИНН ${з.покупатель.инн}.`, ''] : []),
    'Пожалуйста, укажите цену за единицу с НДС или без НДС, минимальную партию, срок и условия доставки.',
    `Ответ - на это письмо${з.срокОтвета ? `, желательно до ${з.срокОтвета}` : ''}.`,
    '',
    'С уважением,',
    з.отправитель || 'KarginTech, служба закупок',
    'kargintech.ru'
    // Строка «ответьте «отписаться»» убрана по решению владельца 21.10.2026.
    // Ответ «отписаться» по-прежнему исполняется (см. отписка ниже).
  ].join('\n');
  return { тема, текст };
}

/** Просьба больше не писать. */
const отписка = (текст) => /отпис(аться|ать|ываюсь|ка)|unsubscribe|не\s+присылайте|больше\s+не\s+пишите/i.test(String(текст || '').slice(0, 2000));

/**
 * Суммы в тексте ответа - подсказка клиенту, а не цена для расчёта.
 * Цитаты прошлых писем (строки с «>») и подпись не смотрим.
 */
function суммыВОтвете(текст) {
  const свежий = String(текст || '').split(/\r?\n/).filter((с) => !/^\s*>/.test(с))
    .join('\n').split(/\n-- ?\n|\n_{5,}|\nС уважением/i)[0];
  const out = [];
  const re = /(\d{1,3}(?:[  ]\d{3})+|\d+)(?:[.,](\d{1,2}))?\s*(?:₽|руб(?:\.|лей|ля|ль)?|р\.)/gi;
  for (const m of свежий.matchAll(re)) {
    const n = Number(m[1].replace(/[  ]/g, '') + (m[2] ? '.' + m[2] : ''));
    if (n > 0 && n < 1e9) out.push({ сумма: n, строка: свежий.slice(Math.max(0, m.index - 60), m.index + m[0].length + 30).replace(/\s+/g, ' ').trim() });
    if (out.length >= 10) break;
  }
  return out;
}

/** Свежая часть ответа без цитаты нашего письма - для показа клиенту. */
function текстОтвета(текст, предел = 3000) {
  const строки = String(текст || '').replace(/\r/g, '').split('\n');
  // Цитата нашего письма: «>», «Original Message», «On … wrote», а у Outlook -
  // черта из подчёркиваний и строка «From:»/«От:» (ответ Комуса 21.10.2026).
  const конец = строки.findIndex((с) => /^\s*>/.test(с) || /^(-{2,}\s*Original Message|-{2,}\s*Исходное сообщение)|^\s*(On|В)\s.+(wrote|пишет|написал)/i.test(с)
    || /^\s*_{10,}\s*$/.test(с) || /^\s*(From|От|Отправлено|Sent):\s/i.test(с));
  return (конец > 0 ? строки.slice(0, конец) : строки).join('\n').replace(/\n{3,}/g, '\n\n').trim().slice(0, предел);
}

/** Страницы контактов сайта: почту обычно пишут там, а не на странице товара. */
function страницыКонтактов(url) {
  let u;
  try { u = new URL(url); } catch (e) { return []; }
  return ['/contacts/', '/kontakty/', '/'].map((п) => `${u.protocol}//${u.host}${п}`);
}

