/**
 * РЕЙТИНГ ТЕНДЕРОВ — решения владельца 16.10.2026.
 *
 * Пять звёзд, и 5 — рентабельность выше 15%. Рентабельность считается только
 * по закупочным ценам клиента (прайс): платного поиска цен для рейтинга нет.
 * Цена победы — по САМОМУ ГЛУБОКОМУ падению цены у похожих прошлых закупок:
 * «самые низкие прошлые закупки похожие, и от этого будет идти расчёт».
 *
 * Почему минимум, а не медиана: ошибка тогда в безопасную сторону. Тендер,
 * выгодный даже при самом сильном прошлом падении, выгоден наверняка; а
 * заниженное падение рисует прибыль там, где её нет — худшая ошибка продукта.
 *
 * Убраны по решению владельца: заказчик, конкуренты. Попадание в нишу — потом.
 * Срок подачи — только для порядка внутри одинаковых звёзд.
 *
 * Сетевых обращений нет: всё, что нужно, приходит аргументами.
 */

const { определитьСпособ, СПОСОБ } = require('./protocol-page');

/** Похожая закупка: тот же способ, НМЦК не дальше чем в полтора раза. Граница здравого смысла, не измерение. */
const ДОПУСК_НМЦК = 0.5;
/** Меньше трёх похожих — один случайный демпинг решал бы за всю нишу. */
const МИНИМУМ_ПОХОЖИХ = 3;
/** Ст. 37 44-ФЗ: со снижения 25% обеспечение ×1,5 и аванс запрещён. */
const ПОРОГ_АНТИДЕМПИНГА = 25;
/** Обеспечение контракта выше этого — деньги заморожены на весь срок договора. */
const ВЫСОКОЕ_ОБЕСПЕЧЕНИЕ = 10;

/** Пороги звёзд по рентабельности, %. Настраиваются клиентом (потом — в кабинете). */
const ПОРОГИ_ПО_УМОЛЧАНИЮ = { 5: 15, 4: 10, 3: 5, 2: 0 };

/**
 * Падение цены по похожим прошлым закупкам.
 *
 * @param {Array<object>} наблюдения из протоколов (src/protocol-page.js, наблюдение)
 * @param {{нмцк: number, способ: string, группыОкпд2?: string[]}} тендер
 * @returns {{достаточно: boolean, похожих: number, падение: number|null,
 *   закупка: string|null, медиана: number|null, причина: string}}
 */
/**
 * Похожие прошлые закупки - одно правило на рейтинг и на шанс победы
 * (src/chance.js): два отбора разошлись бы, и числа на сайте и в рейтинге
 * противоречили бы друг другу.
 * @returns {{достаточно: boolean, похожие: object[], поТовару: string, причина: string}}
 */
function похожиеЗакупки(наблюдения, тендер, { допуск = ДОПУСК_НМЦК, минимум = МИНИМУМ_ПОХОЖИХ } = {}) {
  const нмцк = тендер && тендер.нмцк;
  const способ = тендер && тендер.способ;
  const нет = (причина, похожие = []) => ({ достаточно: false, похожие, поТовару: '', причина });
  if (!(typeof нмцк === 'number' && нмцк > 0)) return нет('НМЦК тендера неизвестна');
  if (!способ || способ === СПОСОБ.ИНОЙ || способ === СПОСОБ.ЕДИНСТВЕННЫЙ) {
    return нет(`способ закупки «${способ || 'не определён'}» - сравнивать не с чем`);
  }
  const поСпособуИСумме = (наблюдения || []).filter((н) => н && н.способ === способ
    && typeof н.нмцк === 'number' && н.нмцк >= нмцк * (1 - допуск) && н.нмцк <= нмцк * (1 + допуск)
    && typeof н.снижение === 'number');
  const группы = (тендер.группыОкпд2 || []).filter(Boolean);
  const похожие = группы.length
    ? поСпособуИСумме.filter((н) => (н.группыОкпд2 && н.группыОкпд2.length ? н.группыОкпд2 : [н.группаОкпд2])
      .some((г) => г && группы.includes(г)))
    : поСпособуИСумме;
  const поТовару = группы.length ? `, товар ОКПД2 ${группы.join(', ')}` : ', товар не сопоставлен - в закупке несколько кодов';
  if (похожие.length < минимум) {
    return { ...нет(`похожих прошлых закупок ${похожие.length}${поТовару} - нужно не меньше ${минимум}`, похожие), поТовару };
  }
  return { достаточно: true, похожие, поТовару, причина: `${похожие.length} похожих закупок (${способ}, НМЦК ±${Math.round(допуск * 100)}%${поТовару})` };
}

function падениеПоПохожим(наблюдения, тендер, опции = {}) {
  const допуск = опции.допуск === undefined ? ДОПУСК_НМЦК : опции.допуск;
  const способ = тендер && тендер.способ;
  // ПО ТОВАРУ — решение владельца: «закупки были одинаковыми, на одни и те же
  // суммы и товары». Если группа ОКПД2 тендера известна, берутся только
  // наблюдения той же группы, а нехватка не добирается чужими товарами:
  // падение цены на картриджи не говорит ничего о бумаге. У прошлой закупки с
  // несколькими кодами («0000» в ИКЗ) группы взяты с карточки списком.
  const отбор = похожиеЗакупки(наблюдения, тендер, опции);
  if (!отбор.достаточно) {
    return { достаточно: false, похожих: отбор.похожие.length, падение: null, закупка: null, медиана: null, причина: отбор.причина };
  }
  const { похожие, поТовару } = отбор;
  const группы = (тендер.группыОкпд2 || []).filter(Boolean);
  const поПорядку = [...похожие].sort((a, b) => b.снижение - a.снижение);
  const самое = поПорядку[0];
  const в = поПорядку.map((н) => н.снижение).sort((a, b) => a - b);
  const медиана = в.length % 2 ? в[(в.length - 1) / 2] : (в[в.length / 2 - 1] + в[в.length / 2]) / 2;
  return {
    достаточно: true,
    похожих: похожие.length,
    падение: самое.снижение,
    закупка: самое.номер || null,
    медиана: Math.round(медиана * 10) / 10,
    поТовару: группы.length > 0,
    причина: `самое глубокое падение у ${похожие.length} похожих закупок (${способ}, НМЦК ±${Math.round(допуск * 100)}%${поТовару})`
  };
}

/**
 * Оценка одного тендера.
 *
 * @param {object} в
 * @param {number} в.нмцк
 * @param {string} в.способ — текст закона/способа из карточки, распознаётся здесь
 * @param {number|null} в.закупка — стоимость закупки по прайсу клиента; null — прайса нет
 * @param {boolean} [в.закупкаПолная] — прайс покрыл все позиции
 * @param {number} [в.доставкаПроцент] — доставка, % от закупки (верхний край вилки клиента)
 * @param {number} [в.налог] — доля, 0.06 = 6%
 * @param {boolean} [в.ценаЗаЕдиницу]
 * @param {number|null} [в.обеспечениеКонтрактаПроцент]
 * @param {Array<object>} в.наблюдения — протоколы прошлых закупок
 * @param {object} [в.пороги] — звёзды по рентабельности
 * @returns {{звёзды: number|null, рентабельность: number|null, прибыль: number|null,
 *   ценаПобеды: number|null, падение: object, минусы: string[], почему: string}}
 */
function оценка(в) {
  const пороги = { ...ПОРОГИ_ПО_УМОЛЧАНИЮ, ...(в.пороги || {}) };
  const способ = определитьСпособ(в.способ);
  const падение = падениеПоПохожим(в.наблюдения, { нмцк: в.нмцк, способ, группыОкпд2: в.группыОкпд2 });
  const без = (почему) => ({ звёзды: null, рентабельность: null, прибыль: null, ценаПобеды: null, падение, минусы: [], почему });

  // Без звёзд — и каждая причина своими словами. Звезда по догадке хуже
  // отсутствия звезды: клиент читает её как расчёт.
  if (в.ценаЗаЕдиницу) return без('закупка по цене за единицу - объём не фиксирован, прибыль не считается');
  if (typeof в.закупка !== 'number' || !(в.закупка > 0)) return без('нет закупочных цен - нужен прайс клиента');
  if (в.закупкаПолная === false) return без('прайс покрыл не все позиции - сумма закупки неполная');
  if (!падение.достаточно) return без(падение.причина);

  const ценаПобеды = в.нмцк * (1 - падение.падение / 100);
  const доставка = в.закупка * ((в.доставкаПроцент || 0) / 100);
  const налог = ценаПобеды * (typeof в.налог === 'number' ? в.налог : 0);
  const прибыль = ценаПобеды - в.закупка - доставка - налог;
  const рентабельность = ценаПобеды > 0 ? (прибыль / ценаПобеды) * 100 : null;

  let звёзды = рентабельность > пороги[5] ? 5
    : рентабельность > пороги[4] ? 4
      : рентабельность > пороги[3] ? 3
        : рентабельность > пороги[2] ? 2 : 1;

  // Денежные риски: минус звезда каждый, с причиной. Не ниже одной звезды.
  const минусы = [];
  if (падение.падение >= ПОРОГ_АНТИДЕМПИНГА) {
    минусы.push(`при падении цены ${String(падение.падение).replace('.', ',')}% - антидемпинг: обеспечение ×1,5, аванс запрещён`);
  }
  if (typeof в.обеспечениеКонтрактаПроцент === 'number' && в.обеспечениеКонтрактаПроцент > ВЫСОКОЕ_ОБЕСПЕЧЕНИЕ) {
    минусы.push(`обеспечение контракта ${String(в.обеспечениеКонтрактаПроцент).replace('.', ',')}% - деньги заморожены на срок договора`);
  }
  звёзды = Math.max(1, звёзды - минусы.length);

  const r = (n) => Math.round(n);
  // Вилка для сообщения: худший край - самое глубокое падение (по нему звёзды),
  // лучший - медиана похожих. Правило владельца 25.10.2026: в Telegram вилка
  // прибыли и маржи или ничего.
  const победаМед = typeof падение.медиана === 'number' ? в.нмцк * (1 - падение.медиана / 100) : null;
  const прибыльМед = победаМед === null ? null
    : победаМед - в.закупка - доставка - победаМед * (typeof в.налог === 'number' ? в.налог : 0);
  return {
    звёзды,
    рентабельность: Math.round(рентабельность * 10) / 10,
    прибыль: r(прибыль),
    прибыльЛучшая: прибыльМед === null ? null : r(прибыльМед),
    рентабельностьЛучшая: прибыльМед === null || !(победаМед > 0) ? null : Math.round(прибыльМед / победаМед * 1000) / 10,
    ценаПобеды: r(ценаПобеды),
    падение,
    минусы,
    почему: `цена победы ${r(ценаПобеды)} ₽ при падении ${падение.падение}% (закупка ${падение.закупка || '—'}), `
      + `закупка по прайсу ${r(в.закупка)} ₽`
  };
}

/**
 * Порядок списка: звёзды по убыванию, внутри — прибыль по убыванию, срок
 * подачи в самом конце (решение владельца). Тендеры без звёзд — после всех.
 */
function упорядочить(список) {
  return [...список].sort((a, b) => {
    const з = (x) => (x.оценка && x.оценка.звёзды) || 0;
    if (з(b) !== з(a)) return з(b) - з(a);
    const п = (x) => (x.оценка && typeof x.оценка.прибыль === 'number' ? x.оценка.прибыль : -Infinity);
    if (п(b) !== п(a)) return п(b) - п(a);
    return String(a.срок || '9999').localeCompare(String(b.срок || '9999'));
  });
}

module.exports = { оценка, падениеПоПохожим, похожиеЗакупки, упорядочить, ПОРОГИ_ПО_УМОЛЧАНИЮ, МИНИМУМ_ПОХОЖИХ, ДОПУСК_НМЦК };
