/**
 * КОДЫ ОКПД2 — Общероссийский классификатор продукции по видам экономической
 * деятельности (ОК 034-2014). Нужны, чтобы «похожие закупки» были похожими
 * по товару, а не по слову: «бумага офисная» и «бумага туалетная» по слову
 * одинаковы, а рынки у них разные.
 *
 * ОТКУДА КОД, если фильтр портала по ОКПД2 не работает (проверено 30.09.2026
 * семью запросами) и в тексте выдачи кода нет:
 *
 * 1. ИЗ ИКЗ — идентификационного кода закупки (36 цифр). Портал печатает его
 *    в каждой карточке 44-ФЗ выдачи поиска — в ссылке «Позиция плана-графика»,
 *    и в выдаче по завершённым закупкам тоже. Знаки 30–33 — первые четыре
 *    цифры кода ОКПД2 («1712» — 17.12, бумага и картон). Это подтверждает сам
 *    портал: его функция openPlanGraphSearchUrl берёт ikz.substring(29, 33)
 *    как ОКПД2. Если в закупке несколько разных кодов, там «0000».
 *    Замер 19.10.2026 на 128 закупках из сохранённых выдач: конкретный код
 *    у 74 (58%), «0000» у 54 (42%). Бесплатно — выдача и так скачивается.
 *
 * 2. С КАРТОЧКИ ЗАКУПКИ — полные коды позиций («17.23.13.140»). Карточку
 *    фоновый разбор скачивает в любом случае.
 *
 * У 223-ФЗ ИКЗ нет — только коды из карточки или документации.
 *
 * Сетевых обращений нет.
 */

/** Полный код ОКПД2: «17.23.13.140». Только цифры — граница по нецифре явная. */
const ПОЛНЫЙ_КОД = /(?<![\d.])(\d{2}\.\d{2}\.\d{2}\.\d{3})(?![\d])/g;

/**
 * Группа ОКПД2 (первые четыре цифры, «17.12») из ИКЗ.
 * @returns {{группа: string|null, причина: string}}
 */
function группаИзИкз(икз) {
  const s = String(икз || '').trim();
  if (!/^\d{36}$/.test(s)) return { группа: null, причина: 'ИКЗ нет или он не из 36 цифр' };
  const к = s.substring(29, 33);
  if (к === '0000') return { группа: null, причина: 'в закупке несколько кодов ОКПД2 — нужен список с карточки' };
  return { группа: `${к.slice(0, 2)}.${к.slice(2)}`, причина: '' };
}

/** Все различные полные коды ОКПД2 в тексте или разметке, по порядку появления. */
function кодыИзТекста(текст) {
  const видели = new Set();
  for (const m of String(текст || '').matchAll(ПОЛНЫЙ_КОД)) видели.add(m[1]);
  return [...видели];
}

/** «17.23.13.140» → «17.23». */
function группаКода(код) {
  const m = String(код || '').match(/^(\d{2}\.\d{2})/);
  return m ? m[1] : null;
}

/**
 * Группы закупки: из кодов САМИХ ПОЗИЦИЙ, а если их нет - из ИКЗ.
 *
 * До 21.10.2026 было наоборот, и это ошибка: в ИКЗ стоит код позиции
 * плана-графика, а заказчик кладёт туда что угодно. Живой случай -
 * 0326100005026000005, бумага А4: в ИКЗ «2229» (пластмассовые изделия), у
 * позиции на карточке 17.12.14.110. Похожих закупок по 22.29 не нашлось,
 * и шанс на победу не оценился.
 */
function группыЗакупки({ икз = '', коды = [] } = {}) {
  const изКодов = [...new Set((коды || []).map(группаКода).filter(Boolean))];
  if (изКодов.length) return изКодов;
  const изИкз = группаИзИкз(икз).группа;
  return изИкз ? [изИкз] : [];
}

/**
 * Похожи ли закупки по товару. Неизвестно у любой стороны — «неизвестно»
 * (null), а не «да»: иначе фильтр по коду тихо выключался бы и выглядел
 * работающим.
 */
function похожиПоОкпд(группыА, группыБ) {
  if (!группыА || !группыА.length || !группыБ || !группыБ.length) return null;
  return группыА.some((г) => группыБ.includes(г));
}

module.exports = { группаИзИкз, кодыИзТекста, группаКода, группыЗакупки, похожиПоОкпд };
