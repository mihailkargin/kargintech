/**
 * Разбор страницы документации закупки — списка приложенных файлов.
 * Без внешних зависимостей — тело функции переносится в Code-ноду n8n как есть.
 *
 * ЧТО ЭТО ЗА СТРАНИЦА.
 * У каждой закупки есть отдельная страница с приложенными файлами: документация,
 * техническое задание, спецификация, проект договора. Именно из них извлекаются
 * условия и позиции лота. Ссылка на эту страницу лежит в карточке закупки
 * (поле docsUrl), и брать её надо из разметки: у 44-ФЗ и 223-ФЗ разные пути,
 * причём даже внутри 44-ФЗ путь зависит от типа процедуры.
 *
 * СОСТОЯНИЕ ПРОВЕРКИ.
 * Разбор выверен на реальной странице 223-ФЗ (`fixtures/docs-fz223-*.html`).
 * Страница 44-ФЗ на момент написания не собрана — портал вернул 404 по ссылке
 * из сохранённой выдачи. Поэтому для 44-ФЗ разбор считается НЕПРОВЕРЕННЫМ.
 * Защита от этого — не догадки в коде, а громкая жалоба: если на странице не
 * нашлось ни одного файла, validateDocumentsPage возвращает ошибку, по которой
 * уходит алерт владельцу. Тихо отдать пустой список нельзя: клиент в этом
 * случае просто не получает анализ документации и никогда об этом не узнает.
 */

const { decode, parseDate, tagEnd } = require('./parser');

/**
 * Ссылка на скачивание файла. У 223-ФЗ это
 * /223/filestore/public/1.0/download/fz223/file.html?uid=...
 * У 44-ФЗ путь другой, поэтому шаблон описывает общую форму, а не конкретную.
 */
const DOWNLOAD_LINK = /filestore\/[^"']*file\.html\?[^"']*uid=/i;

/** Расширения, из которых текст извлечь нельзя без распаковки или которые не документ. */
const ARCHIVES = ['rar', 'zip', '7z', 'tar', 'gz'];
const SIGNATURES = ['sig', 'p7s'];
const IMAGES = ['jpg', 'jpeg', 'png', 'gif', 'bmp', 'tif', 'tiff'];

/**
 * Назначение файла по имени. Нужно, чтобы не гонять в модель всё подряд:
 * разбор каждого документа стоит токенов, а «форма заявки» и «критерии оценки»
 * условий закупки не содержат — это бланки для заполнения.
 */
/**
 * ВНИМАНИЕ: окончания слов задаются классом [а-яё], а не \w.
 * В JavaScript \w и \b считают буквами только латиницу и цифры, поэтому
 * «техническ\w*\s+задани» не совпадает со словом «техническое задание»
 * никогда. Шаблон выглядит рабочим, а файл молча уезжает в категорию
 * «прочее» — здесь это означало бы, что бланк заявки отправляется в модель
 * за деньги, а техзадание с позициями лота не отправляется вовсе.
 */
const KINDS = [
  [/специфик/i, 'спецификация'],
  // У 44-ФЗ роль технического задания играет «Описание объекта закупки» —
  // именно там лежат позиции лота. Без этого правила самый нужный файл
  // уезжал в категорию «прочее» и не попадал в отбор.
  [/описани[а-яё]*\s+объекта\s+закупки/i, 'описание объекта закупки'],
  // «ОЗ» / «ООЗ» - сокращение того же. Найдено 20.10.2026 (0301100049626001767):
  // файл «ОЗ» с ТЗ на 33 позиции уезжал в «прочее» и как ТЗ не читался.
  [/(?:^|[^а-яё])о?оз(?:[^а-яё]|$)/i, 'описание объекта закупки'],
  [/техническ[а-яё]*\s+задани|(?:^|[^а-яё])тз(?:[^а-яё]|$)/i, 'техническое задание'],
  // «Проект МК» и «Проект ГК» — муниципальный и государственный контракт.
  // Сокращения встречаются наравне с полным словом.
  [/проект[а-яё]*\s+(?:договор|контракт|мк(?![а-яё])|гк(?![а-яё]))/i, 'проект договора'],
  // «Приложение 4 Контракт» — проект контракта без слова «проект». Только
  // слово целиком: «обеспечение исполнения контракта» сюда не попадает.
  [/(?:^|[^а-яё])(?:контракт|договор)(?![а-яё])/i, 'проект договора'],
  [/обоснован/i, 'обоснование НМЦК'],
  // Файлы про начальную цену называют по-разному: «Обоснование НМЦК»,
  // «Расчет НМЦК(Д)», «Протокол НМЦК(Д)». Для посредника это самый ценный
  // документ — в нём лежат коммерческие предложения поставщиков, поэтому
  // упустить его из-за формулировки в названии нельзя.
  [/нмц[кд]/i, 'обоснование НМЦК'],
  [/критери[а-яё]*\s+оценки/i, 'критерии оценки'],
  [/форм[а-яё]*\s+заявки/i, 'форма заявки'],
  // Типовой бланк, который портал прикладывает почти ко всем закупкам 44-ФЗ.
  // Условий конкретной закупки в нём нет — это инструкция по заполнению
  // извещения. Правило стоит до «документации», иначе слово «извещения»
  // в имени затянет его туда.
  [/требовани[а-яё]*\s+к\s+содержанию|инструкци[а-яё]*\s+по\s+(?:е[ёе]|его|заполнени)/i,
    'инструкция по заполнению'],
  [/документаци|извещени|информационн[а-яё]*\s+карт/i, 'документация']
];

/**
 * Порядок, в котором документы отправляются в модель.
 * Первыми идут те, где лежат условия и позиции; бланки — в конце.
 */
//
// ТЕХНИЧЕСКОЕ ЗАДАНИЕ — ПЕРВЫМ. Требование владельца 13.10.2026: «тз и
// документация тендера — приоритет, остальное второстепенно». До этого дня
// первой шла «документация», а обоснование НМЦК стояло после проекта договора:
// при пределе в шесть файлов ТЗ и расчёт цены могли не попасть в отбор вовсе.
// ТЗ говорит, ЧТО закупают (характеристики), обоснование НМЦК — ПОЧЁМ.
// Без первого цена ищется не на тот товар, без второго её не с чем сравнить.
const KIND_PRIORITY = [
  'описание объекта закупки',
  'техническое задание',
  'спецификация',
  'обоснование НМЦК',
  'документация',
  'проект договора',
  'критерии оценки',
  'форма заявки',
  'инструкция по заполнению',
  'прочее'
];

/**
 * Разметка подписей отличается у двух законов, и это не косметика: взяв только
 * один вариант, мы молча остаёмся без сведений о редакции документации.
 */
const META_SCHEMES = [
  ['attachment__text', 'attachment__value'], // 223-ФЗ
  ['section__attrib', 'section__value']      // 44-ФЗ
];

const extensionOf = (name) => {
  const m = String(name).match(/\.([A-Za-zА-Яа-я0-9]{1,5})\s*$/);
  return m ? m[1].toLowerCase() : '';
};

const kindOf = (name) => {
  // Подчёркивания вместо пробелов — частое написание на портале:
  // «Приложение_1_-_Описание_объекта_закупки.doc». Правила ищут слова через
  // пробел, и такой файл уезжал в «прочее» — не считался ТЗ и уходил в конец
  // очереди. Найдено пакетной проверкой 14.10.2026.
  const имя = String(name || '').replace(/_+/g, ' ');
  for (const [re, kind] of KINDS) if (re.test(имя)) return kind;
  return 'прочее';
};

/**
 * Текст ссылки, начинающейся в позиции tagStart.
 *
 * Границу открывающего тега ищем через tagEnd, а не шаблоном [^>]*: у ссылки
 * есть атрибут data-tooltip, внутри которого лежит HTML с угловыми скобками.
 * Наивный шаблон перескакивает через них и возвращает имя файла дважды —
 * сначала из подсказки, потом из текста ссылки.
 *
 * @returns {{tag: string, text: string}} tag — открывающий тег целиком
 */
function anchorParts(html, tagStart) {
  const gt = tagEnd(html, tagStart);
  if (gt === -1) return { tag: '', text: '' };
  const tag = html.slice(tagStart, gt + 1);
  const rest = html.slice(gt + 1);
  const close = rest.indexOf('</a>');
  return { tag, text: close === -1 ? '' : rest.slice(0, close) };
}

/** Значение атрибута из уже вырезанного открывающего тега. */
function attr(tag, name) {
  const m = tag.match(new RegExp(`${name}\\s*=\\s*(["'])([\\s\\S]*?)\\1`, 'i'));
  return m ? m[2] : '';
}

/** Текст элемента, чей класс найден в позиции idx. */
function textAt(html, idx) {
  const tagStart = html.lastIndexOf('<', idx);
  if (tagStart === -1) return { value: '', end: idx };
  const gt = tagEnd(html, tagStart);
  if (gt === -1) return { value: '', end: idx };
  const rest = html.slice(gt + 1);
  const close = rest.indexOf('</div>');
  return {
    value: decode(close === -1 ? rest : rest.slice(0, close)),
    end: close === -1 ? html.length : gt + 1 + close + 6
  };
}

/**
 * Все пары «подпись → значение» на странице вместе с их позициями.
 * Позиция нужна, чтобы привязать сведения к тому блоку, в котором лежат файлы:
 * на странице 44-ФЗ таких блоков несколько (события закупки), и первое
 * совпадение на странице может относиться к совсем другому событию.
 */
function collectMeta(html) {
  const pairs = [];
  for (const [titleClass, valueClass] of META_SCHEMES) {
    let pos = 0;
    while (true) {
      const idx = html.indexOf(titleClass, pos);
      if (idx === -1) break;
      const title = textAt(html, idx);
      const vIdx = html.indexOf(valueClass, title.end);
      pos = title.end;
      if (vIdx === -1) continue;
      // Значение должно идти сразу за подписью, а не через полстраницы.
      if (vIdx - title.end > 300) continue;
      pairs.push({ label: title.value, value: textAt(html, vIdx).value, at: idx });
    }
  }
  return pairs.sort((a, b) => a.at - b.at);
}

/**
 * Разбирает страницу документации в список приложенных файлов.
 *
 * @param {string} html
 * @returns {{files: Array<object>, revision: string, published: string|null, counts: object}}
 */
function parseDocumentsPage(html) {
  const text = String(html || '');
  const files = [];
  const seen = new Set();

  // Идём по открывающим тегам <a>. Ссылок на странице много: кроме скачивания
  // есть ещё просмотр электронной подписи (signview/listModal). Их у одного
  // файла может быть больше, чем самих файлов, поэтому отбираем строго по
  // признаку ссылки на файловое хранилище, а не «первая ссылка в блоке».
  let pos = 0;
  let firstFileAt = -1;
  while (true) {
    const tagStart = text.indexOf('<a', pos);
    if (tagStart === -1) break;
    const { tag, text: inner } = anchorParts(text, tagStart);
    if (!tag) break;
    pos = tagStart + tag.length;

    const href = decode(attr(tag, 'href'));
    if (!href || !DOWNLOAD_LINK.test(href)) continue;

    // Имя берём из текста ссылки; подсказка — запасной источник.
    let name = decode(inner);
    if (!name) name = decode(attr(tag, 'data-tooltip'));

    const uid = (href.match(/uid=([^&]+)/i) || [])[1] || '';
    if (uid && seen.has(uid)) continue;
    if (uid) seen.add(uid);

    // Тип берём из иконки, стоящей перед ссылкой. Это независимая от имени
    // подсказка: если имя файла пришло без расширения, тип всё равно известен.
    const before = text.slice(Math.max(0, tagStart - 800), tagStart);
    const iconMatches = [...before.matchAll(/icons\/type\/([A-Za-z0-9]+)\.svg/g)];
    const iconType = iconMatches.length ? iconMatches[iconMatches.length - 1][1].toLowerCase() : '';

    if (firstFileAt === -1) firstFileAt = tagStart;

    const ext = extensionOf(name) || iconType;
    files.push({
      name,
      url: href.startsWith('http') ? href : `https://zakupki.gov.ru${href}`,
      uid,
      ext,
      iconType,
      kind: kindOf(name),
      isArchive: ARCHIVES.includes(ext),
      isSignature: SIGNATURES.includes(ext),
      isImage: IMAGES.includes(ext)
    });
  }

  // Сведения о редакции. Документация закупки переиздаётся, и разбор
  // устаревшей редакции даст условия, которых уже нет.
  //
  // Берём подпись, ближайшую СЛЕВА от первого файла, а не первую на странице.
  // На странице 44-ФЗ блоков-событий несколько: в разобранной закупке событие
  // от 19.09 содержит файлы, а событие от 21.09 — нет. Первое совпадение на
  // странице запросто относится к чужому событию.
  const meta = collectMeta(text);
  const anchor = firstFileAt === -1 ? Infinity : firstFileAt;
  const near = (re) => {
    const before = meta.filter((p) => re.test(p.label) && p.at < anchor);
    if (before.length) return before[before.length - 1].value;
    const any = meta.find((p) => re.test(p.label));
    return any ? any.value : '';
  };

  const revision = near(/^Редакция/i);
  const publishedRaw = near(/^Размещено/i);
  const published = parseDate(publishedRaw);

  // Событие позже того, в котором лежат файлы, означает, что закупку меняли
  // уже после публикации этих документов.
  const laterEvents = meta
    .filter((p) => /^Размещено/i.test(p.label))
    .map((p) => parseDate(p.value))
    .filter((d) => d && published && d > published);
  const latestEvent = laterEvents.length ? laterEvents.sort().pop() : null;

  const counts = {};
  for (const f of files) counts[f.kind] = (counts[f.kind] || 0) + 1;

  return { files, revision, published, latestEvent, counts };
}

/**
 * Проверки страницы документации.
 *
 * Главная из них — первая. Пустой список файлов выглядит как штатная работа:
 * воркфлоу отработает, ошибок не будет, клиент просто не получит разбор
 * документации. Это тихий отказ, и он должен кричать.
 *
 * @param {object} parsed результат parseDocumentsPage
 * @returns {Array<string>} список проблем; пустой — можно работать дальше
 */
function validateDocumentsPage(parsed) {
  const issues = [];

  if (parsed.files.length === 0) {
    issues.push(
      'на странице документации не найдено ни одного файла — ' +
      'либо разбор не подходит к этому типу страницы, либо документы не приложены; ' +
      'нужен алерт владельцу сервиса, а не молчание'
    );
    return issues;
  }

  if (!parsed.files.some((f) => !f.isSignature && !f.isImage)) {
    issues.push('среди приложений нет ни одного документа — только подписи и картинки');
  }
  for (const f of parsed.files) {
    if (!f.name) issues.push(`файл ${f.uid || 'без идентификатора'}: не распознано имя`);
    if (!f.ext) issues.push(`файл «${f.name}»: не определён тип`);
  }
  // ZIP распаковывается при разборе; предупреждение — только о прочих архивах.
  const archives = parsed.files.filter((f) => f.isArchive && f.ext !== 'zip');
  if (archives.length) {
    issues.push(
      `архивов: ${archives.length} (${archives.map((f) => f.name).join(', ')}) — ` +
      'содержимое без распаковки недоступно'
    );
  }
  // Проверять вхождением «действующ» нельзя: слово «Недействующая» его содержит,
  // и устаревшая редакция прошла бы как нормальная. Значение должно начинаться
  // с «Действующ», а не просто включать это сочетание букв.
  if (!parsed.revision) {
    issues.push('редакция документации не определена — нельзя подтвердить, что документы действующие');
  } else if (!/^действующ/i.test(parsed.revision.trim())) {
    issues.push(`редакция документации «${parsed.revision}» — не действующая, условия могли измениться`);
  }

  if (parsed.latestEvent) {
    issues.push(
      `документы опубликованы ${parsed.published}, но закупку меняли ${parsed.latestEvent} — ` +
      'условия могли измениться после публикации этих файлов'
    );
  }

  return issues;
}

/**
 * Отбирает документы для отправки в модель и объясняет, что отброшено.
 *
 * Читаются ВСЕ документы, кроме служебных (подпись, инструкция портала, форма
 * заявки, критерии оценки) - решение владельца 28.10.2026: «чтобы находить всё
 * с первого раза». Документы читает код, не модель, поэтому прежний предел в
 * 6 файлов («разбор стоит токенов») устарел: таблица позиций оставалась в
 * отброшенном файле. Предел вызова - аварийный, бережёт портал (каждый файл -
 * обращение к нему). Отброшенное перечисляется поимённо.
 *
 * @param {Array<object>} files из parseDocumentsPage
 * @param {number} limit сколько документов отправлять максимум
 * @returns {{selected: Array<object>, skipped: Array<{name: string, reason: string}>}}
 */
function selectForExtraction(files, limit = 4) {
  const skipped = [];
  const usable = [];

  for (const f of files) {
    if (f.isSignature) skipped.push({ name: f.name, reason: 'электронная подпись, не документ' });
    else if (f.isImage) skipped.push({ name: f.name, reason: 'изображение, текста нет' });
    // ZIP распаковывает расчёт сам (распаковатьZip, 18.10.2026), RAR и 7z —
    // конвертер (bsdtar, 20.10.2026). Остальные форматы архивов называются вслух.
    else if (f.isArchive && !['zip', 'rar', '7z'].includes(f.ext)) {
      skipped.push({ name: f.name, reason: `архив ${f.ext.toUpperCase()} — распаковка пока не поддерживается` });
    }
    else if (f.kind === 'инструкция по заполнению') {
      skipped.push({ name: f.name, reason: 'типовая инструкция портала, условий закупки не содержит' });
    // Бланки для участника - позиций и цен в них нет (владелец 28.10.2026:
    // служебные файлы пропускать, остальные читать все).
    } else if (f.kind === 'форма заявки' || f.kind === 'критерии оценки') {
      skipped.push({ name: f.name, reason: `${f.kind} - бланк участника, позиций и цен не содержит` });
    } else usable.push(f);
  }

  // ПОВТОРЫ ИМЁН НЕ ЗАНИМАЮТ МЕСТА В ОТБОРЕ. Найдено на закупке
  // 0373200638526000056: на странице 18 файлов, и почти каждый лежит дважды
  // (две редакции). Предел в шесть съедался парами «Техническое задание» ×2,
  // «Проект контракта» ×2, а «Обоснование характеристик» не попадало вовсе.
  // Берётся первый по порядку страницы, второй называется в отброшенных.
  const виденные = new Set();
  for (let i = 0; i < usable.length; i++) {
    const ключ = `${usable[i].kind}|${String(usable[i].name).trim().toLowerCase()}`;
    if (виденные.has(ключ)) {
      skipped.push({ name: usable[i].name, reason: 'повтор имени — другая редакция того же документа' });
      usable.splice(i, 1);
      i--;
    } else виденные.add(ключ);
  }

  usable.sort((a, b) => KIND_PRIORITY.indexOf(a.kind) - KIND_PRIORITY.indexOf(b.kind));

  const selected = usable.slice(0, limit);
  for (const f of usable.slice(limit)) {
    skipped.push({ name: f.name, reason: `сверх лимита в ${limit} документов` });
  }
  return { selected, skipped };
}

/**
 * Файл, загруженный клиентом (расчёт по документам, 31.10.2026), - в том же
 * виде, что файл со страницы документов портала: назначение по имени, признаки
 * архива, подписи и картинки. Данные уже в памяти - расчёт их не скачивает.
 */
function файлЗагрузки(имя, данные) {
  const name = String(имя || 'файл');
  const ext = extensionOf(name);
  return {
    name, url: '', uid: '', ext, iconType: '', kind: kindOf(name),
    // Картинка от клиента - чаще всего фото документа: не пропускается, а
    // распознаётся тем же путём, что скан.
    isArchive: ARCHIVES.includes(ext), isSignature: SIGNATURES.includes(ext), isImage: false,
    данные
  };
}

