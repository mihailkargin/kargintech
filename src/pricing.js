/**
 * Определение закупочной цены по позициям спецификации.
 * Без внешних зависимостей — тело функции переносится в Code-ноду n8n как есть.
 *
 * ЭТО ЯДРО ПРОДУКТА. Конкурент просит пользователя ввести себестоимость руками:
 * значит работу по поиску товара и цены человек уже сделал сам, и их продукт —
 * последние десять процентов задачи. Мы эту цену находим. Пока этого нет,
 * отличия от конкурента не существует.
 *
 * ГЛАВНОЕ ПРАВИЛО: ПОЗИЦИЯ БЕЗ ЦЕНЫ НЕ ЗАПОЛНЯЕТСЯ ДОГАДКОЙ.
 * Подставить «примерно столько же, сколько у соседней позиции» — худшее, что
 * можно сделать. Клиент увидит полную смету, поверит ей и зайдёт в убыточный
 * тендер. Позиция без цены помечается и уходит человеку как есть.
 *
 * ПОЧЕМУ НЕ СРЕДНЕЕ ПО ИСТОЧНИКАМ.
 * Разброс между источниками — это не шум, который надо усреднить, а сведения
 * о риске. Две цены 100 и 300 означают не «200», а «мы не знаем, и в худшем
 * случае это 300». Прибыль считается по худшей границе, а клиенту показывается
 * весь разброс.
 */

/**
 * Источники в порядке доверия. Порядок важен: при прочих равных берётся
 * источник выше по списку, потому что он ближе к настоящей закупочной цене.
 */
const SOURCES = {
  SUPPLIER: 'пул поставщиков клиента',
  PRICE_LIST: 'прайс клиента',
  WEB_SUPPLIER: 'сайт поставщика',
  NMCK: 'обоснование НМЦК',
  CONTRACT_REGISTRY: 'реестр контрактов',
  MANUFACTURER: 'прайс производителя',
  MARKETPLACE: 'маркетплейс'
};

/**
 * Что каждый источник на самом деле показывает.
 *
 * Здесь лежит вся честность модуля. Цена из реестра контрактов — это цена,
 * по которой победитель ПРОДАЛ государству, в неё уже заложена его маржа.
 * Принять её за свою себестоимость значит посчитать прибыль там, где её нет.
 * Цена в обосновании НМЦК — тоже с маржой поставщика, дававшего предложение,
 * и обычно завышена: заказчику выгодно обосновать цену повыше, чтобы потом
 * было куда снижаться на торгах.
 */
const SOURCE_MEANING = {
  [SOURCES.SUPPLIER]: { kind: 'закупочная', trust: 'высокая', note: '' },
  [SOURCES.PRICE_LIST]: { kind: 'закупочная', trust: 'высокая', note: '' },

  // Найден поиском в интернете — первый источник, отвечающий на вопрос
  // «почём Я куплю», а не «почём это продают заказчику». Поэтому вид
  // закупочный. Но доверие среднее, и причины названы прямо: цена на сайте
  // указана без скидки за объём, могла устареть, и товар может оказаться
  // не тем, что в спецификации, — совпадение названий ещё не совпадение
  // характеристик. Проверяет это человек звонком.
  [SOURCES.WEB_SUPPLIER]: {
    kind: 'закупочная',
    trust: 'средняя',
    note: 'цена с сайта поставщика: без скидки за объём, может быть устаревшей — подтверждать звонком'
  },

  [SOURCES.NMCK]: {
    kind: 'верхняя граница',
    trust: 'средняя',
    note: 'цена из коммерческого предложения поставщика, включает его маржу и обычно завышена'
  },
  [SOURCES.CONTRACT_REGISTRY]: {
    kind: 'верхняя граница',
    trust: 'средняя',
    note: 'цена продажи государству, включает маржу победителя — это не себестоимость'
  },
  [SOURCES.MANUFACTURER]: { kind: 'закупочная', trust: 'средняя', note: 'цена по прайсу, без скидки за объём' },
  [SOURCES.MARKETPLACE]: {
    kind: 'верхняя граница',
    trust: 'низкая',
    note: 'розничная цена — потолок, дороже покупать бессмысленно'
  }
};

const TRUST_ORDER = ['высокая', 'средняя', 'низкая'];
const round2 = (n) => Math.round(n * 100) / 100;

/**
 * Одна найденная цена. Без источника и ссылки цена в расчёт не идёт —
 * иначе потом невозможно ответить на вопрос клиента «откуда эта цифра».
 *
 * @param {object} raw
 * @param {number} raw.price цена за единицу
 * @param {string} raw.source одно из SOURCES
 * @param {string} [raw.url] ссылка на подтверждение
 * @param {string} [raw.date] дата в формате ГГГГ-ММ-ДД
 * @param {string} [raw.supplier] название компании, если известно
 * @param {string} [raw.evidence] цитата или номер документа
 */
function makePrice(raw) {
  const meaning = SOURCE_MEANING[raw.source] || { kind: 'неизвестно', trust: 'низкая', note: '' };
  const problems = [];

  const price = typeof raw.price === 'number' && Number.isFinite(raw.price) ? raw.price : null;
  if (price === null) problems.push('цена не распознана');
  else if (price <= 0) problems.push('цена меньше или равна нулю');

  if (!raw.source || !SOURCE_MEANING[raw.source]) problems.push('источник не указан или неизвестен');
  if (!raw.url && !raw.evidence) problems.push('нет ссылки или документа-подтверждения');

  return {
    price,
    source: raw.source || null,
    kind: meaning.kind,
    trust: meaning.trust,
    note: meaning.note,
    url: raw.url || '',
    date: raw.date || null,
    supplier: raw.supplier || '',
    evidence: raw.evidence || '',
    usable: problems.length === 0,
    problems
  };
}

/**
 * Сводит найденные по позиции цены в решение.
 *
 * Возвращает не одно число, а картину: минимум, максимум, что берём в расчёт
 * и почему. Одно число здесь было бы враньём — оно скрывает, что источники
 * расходятся.
 *
 * @param {object} position позиция спецификации: name, quantity, unit
 * @param {Array<object>} found цены из makePrice
 */
function resolvePosition(position, found = []) {
  const name = (position && position.name) || '';
  const quantity = typeof position?.quantity === 'number' ? position.quantity : null;

  const usable = found.filter((p) => p.usable);
  const rejected = found.filter((p) => !p.usable);

  // Позиция без единой пригодной цены. Не выдумываем — помечаем.
  if (usable.length === 0) {
    return {
      name,
      quantity,
      unit: position?.unit || '',
      priceForCalc: null,
      min: null,
      max: null,
      spreadPct: null,
      basis: 'цена не определена',
      confidence: 'нет данных',
      sources: [],
      rejected,
      warnings: [
        found.length
          ? `найдено ${found.length} цен, но ни одна не пригодна: ${[...new Set(rejected.flatMap((r) => r.problems))].join('; ')}`
          : 'источники не дали ни одной цены'
      ]
    };
  }

  const values = usable.map((p) => p.price);
  const min = Math.min(...values);
  const max = Math.max(...values);
  const spreadPct = min > 0 ? round2(((max - min) / min) * 100) : null;

  // ХУДШАЯ ЦЕНА ВЫБИРАЕТСЯ СРЕДИ ОДНОРОДНЫХ ИСТОЧНИКОВ, А НЕ СРЕДИ ВСЕХ.
  //
  // Найдено 03.10.2026 на первом настоящем прогоне с поиском поставщиков.
  // Типографии давали комплект по 248,9 ₽, коммерческие предложения
  // заказчика — 371 ₽. Правило «берём худшую» выбрало 371, и тендер с живым
  // запасом показался убыточным на 240 тысяч.
  //
  // Ошибка была в сравнении разнородного. 248,9 — это ЗАКУПОЧНАЯ цена,
  // почём купит клиент. 371 — ВЕРХНЯЯ ГРАНИЦА, почём продают заказчику,
  // с чужой маржой внутри. Взяв максимум между ними, мы подставляли
  // в себестоимость чужую наценку.
  //
  // Правильно так: если известна хоть одна закупочная цена, считаем
  // по худшей ИЗ ЗАКУПОЧНЫХ. Верхние границы остаются видны клиенту
  // как справка о рынке, но в расчёт не идут. Если закупочных нет —
  // считаем по верхним границам, и это помечается отдельно.
  // ВТОРОЕ ПРАВИЛО, НАЙДЕННОЕ ТАМ ЖЕ: потолки и закупки считаются по-разному.
  //
  // «Берём худшую» верно для РАЗНЫХ ОЦЕНОК ОДНОЙ величины. Но коммерческие
  // предложения в обосновании НМЦК — это не оценки, а предложения разных
  // поставщиков, из которых можно выбрать.
  //
  // Если один поставщик готов продать заказчику за 316, значит купить этот
  // товар дороже 316 невозможно: он сам покупает дешевле и живёт с разницы.
  // То есть МИНИМАЛЬНОЕ предложение и есть верхняя граница себестоимости,
  // а максимальное не ограничивает ничего.
  //
  // Последствие старого правила было системным, а не частным. Заказчик считает
  // НМЦК по СРЕДНЕЙ цене предложений, мы брали МАКСИМУМ — и по любой позиции
  // без цен поставщиков наша сумма выходила выше НМЦК. Система отвечала
  // «убыточно» на всё подряд. Продукт, который на всё отвечает «не ходи»,
  // бесполезен ровно так же, как продукт, который на всё отвечает «иди».
  //
  // Итого:
  //   — закупочные цены (сайт поставщика, прайс клиента) — это РЕАЛЬНЫЕ
  //     варианты покупки. С 28.10.2026 (решение владельца) в расчёт идёт
  //     ЛУЧШАЯ из них - так клиент видит, что тендер стоит внимания; худшая
  //     остаётся нижним краем вилки прибыли (`worstPurchase`, `totalMax`);
  //   — верхние границы (обоснование НМЦК, реестр контрактов) — это ПОТОЛКИ,
  //     среди них берём самый низкий: он и есть настоящее ограничение.
  const закупочные = usable.filter((p) => p.kind === 'закупочная');
  const priceForCalc = закупочные.length
    ? Math.min(...закупочные.map((p) => p.price))
    : Math.min(...usable.map((p) => p.price));
  // Худшая закупочная - для края вилки. Потолок с чужой маржой сюда не идёт.
  const worstPurchase = закупочные.length ? Math.max(...закупочные.map((p) => p.price)) : priceForCalc;

  const warnings = [];

  // Верхние границы выше закупочной — обычное дело, но клиент должен
  // понимать, почему в расчёт пошла не самая высокая из найденных цен.
  if (закупочные.length && закупочные.length < usable.length) {
    const потолок = Math.max(...usable.filter((p) => p.kind !== 'закупочная').map((p) => p.price));
    if (потолок > priceForCalc) {
      warnings.push(
        `в расчёт взята закупочная цена ${priceForCalc}, а не ${потолок} из обоснования НМЦК: `
        + 'вторая — цена продажи заказчику с чужой маржой, себестоимостью она не является'
      );
    }
  }
  const byTrust = [...usable].sort(
    (a, b) => TRUST_ORDER.indexOf(a.trust) - TRUST_ORDER.indexOf(b.trust)
  );
  const best = byTrust[0];

  // Все найденные цены — только верхние границы. Значит настоящей закупочной
  // цены мы не знаем, и прибыль получится заниженной. Это лучше, чем завышенная,
  // но клиент должен понимать, что смотрит на пессимистичную оценку.
  const onlyCeilings = usable.every((p) => p.kind === 'верхняя граница');
  if (onlyCeilings) {
    warnings.push(
      'все найденные цены — верхняя граница: это цены продажи с чужой маржой, ' +
      'а не закупка у производителя. Настоящая себестоимость ниже, прибыль в расчёте занижена'
    );
  }

  if (spreadPct !== null && spreadPct > 50) {
    warnings.push(
      `цены источников расходятся на ${spreadPct}% — от ${min} до ${max}. ` +
      'В расчёт взята лучшая, худшая - в вилке прибыли; проверить, об одном ли товаре речь'
    );
  }

  if (usable.length === 1) {
    warnings.push('цена из единственного источника — сверить не с чем');
  }

  // Порядок проверок важен: большой разброс тревожнее всего остального
  // и должен перебивать прочие признаки. Если источники расходятся вдвое,
  // не имеет значения, насколько они сами по себе надёжны — скорее всего
  // речь о разных товарах, и это надо смотреть глазами.
  let confidence;
  if (spreadPct !== null && spreadPct > 50) confidence = 'требует проверки';
  else if (onlyCeilings || usable.length === 1) confidence = 'средняя';
  else confidence = 'высокая';

  return {
    name,
    quantity,
    unit: position?.unit || '',
    priceForCalc,
    worstPurchase,
    min,
    max,
    spreadPct,
    total: quantity !== null ? round2(priceForCalc * quantity) : null,
    basis: best.kind === 'закупочная' ? 'закупочная цена' : 'верхняя граница цены',
    confidence,
    sources: usable.map((p) => ({
      price: p.price, source: p.source, kind: p.kind,
      supplier: p.supplier, url: p.url, date: p.date, evidence: p.evidence
    })),
    rejected,
    warnings
  };
}

/**
 * Смета по всей спецификации.
 *
 * ВАЖНО ПРО ИТОГ. Когда часть позиций без цены, итоговая сумма — это НЕ
 * стоимость закупки, а стоимость только тех позиций, что нашлись. Выдавать
 * её как полную себестоимость нельзя: клиент сравнит с НМЦК, увидит хорошую
 * маржу и зайдёт в тендер, где недостающие позиции съедят её целиком.
 *
 * @param {Array<object>} positions позиции спецификации
 * @param {function} lookup функция поиска цен: (position) => Array<makePrice>
 */
function buildEstimate(positions, lookup) {
  const rows = (positions || []).map((p) => resolvePosition(p, lookup ? lookup(p) : []));

  const priced = rows.filter((r) => r.priceForCalc !== null);
  const unpriced = rows.filter((r) => r.priceForCalc === null);
  const noQuantity = rows.filter((r) => r.priceForCalc !== null && r.quantity === null);

  const total = priced
    .filter((r) => r.total !== null)
    .reduce((sum, r) => round2(sum + r.total), 0);

  const issues = [];
  if (unpriced.length) {
    issues.push(
      `${unpriced.length} из ${rows.length} позиций без цены — итог неполный, ` +
      'сравнивать его с НМЦК нельзя'
    );
  }
  if (noQuantity.length) {
    issues.push(`${noQuantity.length} позиций с ценой, но без количества — сумма по ним не посчитана`);
  }
  if (rows.length === 0) issues.push('спецификация пуста — считать нечего');

  const anyCeilingOnly = priced.some((r) => r.basis === 'верхняя граница цены');
  if (anyCeilingOnly) {
    issues.push('часть цен — верхняя граница с чужой маржой; настоящая себестоимость ниже');
  }

  return {
    rows,
    total,
    pricedCount: priced.length,
    unpricedCount: unpriced.length,
    complete: unpriced.length === 0 && rows.length > 0,
    // Диапазон итога: по самым дешёвым найденным ценам и по самым дорогим.
    // Показывает, насколько расходятся источники в деньгах, а не в процентах
    // по одной позиции.
    //
    // Считается по НАЙДЕННЫМ ценам, а не по той, что пошла в расчёт. Раньше
    // верхняя граница равнялась итогу — и после смены правила выбора цены
    // (потолки берутся по минимуму) обе границы совпали, то есть диапазон
    // перестал что-либо показывать.
    totalMin: priced.filter((r) => r.quantity !== null)
      .reduce((s, r) => round2(s + r.min * r.quantity), 0),
    totalMax: priced.filter((r) => r.quantity !== null)
      .reduce((s, r) => round2(s + r.max * r.quantity), 0),
    // Нижний край вилки прибыли - худшая ЗАКУПОЧНАЯ цена (владелец 28.10.2026),
    // не потолок обоснования: тот себестоимостью не является. totalMax выше -
    // диапазон источников для показа (правило 04.10.2026), не для прибыли.
    totalWorst: priced.filter((r) => r.quantity !== null)
      .reduce((s, r) => round2(s + (r.worstPurchase ?? r.priceForCalc) * r.quantity), 0),
    issues
  };
}

/** Строки для листа «Источники» в таблице клиента. */
function sourceRows(estimate) {
  const out = [];
  for (const row of estimate.rows) {
    for (const s of row.sources) {
      out.push({
        позиция: row.name,
        цена: s.price,
        источник: s.source,
        характер: s.kind,
        поставщик: s.supplier || '—',
        документ: s.evidence || '—',
        ссылка: s.url || '—',
        дата: s.date || '—'
      });
    }
    if (!row.sources.length) {
      out.push({
        позиция: row.name, цена: '—', источник: 'не найден',
        характер: '—', поставщик: '—', документ: '—', ссылка: '—', дата: '—'
      });
    }
  }
  return out;
}

module.exports = {
  makePrice,
  resolvePosition,
  buildEstimate,
  sourceRows,
  SOURCES,
  SOURCE_MEANING
};
