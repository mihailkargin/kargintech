/** 0 - тот же регион, 1 - тот же округ, 2 - другой округ, 3 - регион неизвестен. */
function близость(регионЗакупки, регионСклада) {
  if (!регионЗакупки || !регионСклада) return 3;
  if (String(регионЗакупки) === String(регионСклада)) return 0;
  const а = округРегиона(регионЗакупки);
  return а && а === округРегиона(регионСклада) ? 1 : 2;
}

