/**
 * НАКОПЛЕННАЯ БАЗА ПОСТАВЩИКОВ - 22.10.2026, идея владельца от 07.10.2026:
 * «один раз находим. в следующих тендерах на те же ниши - уже используем
 * имеющиеся контакты ... и будем искать только актуальную цену».
 *
 * Поиск поставщика - работа разовая и платная (модель, веб-поиск). Проверка
 * цены по известной странице - бесплатная: страницу скачивает наш код и
 * сверяет той же сверкой, что и свежие цены (src/verify.js).
 *
 * Три правила владельца, без которых идея обернётся против нас:
 *  1. «Продаёт ручки - вероятно, продаёт и карандаши» - это «вероятно». База
 *     хранит поставщика ПО ПОЗИЦИИ: цена подставляется только для той же
 *     позиции (тот же ключ), по той же странице товара. По профилю компании
 *     ничего не предполагается.
 *  2. У цены есть дата. Цена из базы в расчёт идёт только после проверки
 *     страницы сегодня; дата проверки пишется в подтверждение.
 *  3. Страница не ответила или цены на ней нет - не «цена прежняя», а
 *     «искать заново»: такой поставщик не засчитывается.
 *
 * База ОБЩАЯ для всех клиентов: в ней только публичные сведения с сайтов
 * поставщиков. Прайсы клиентов сюда не попадают никогда - в базу пишутся
 * только результаты веб-поиска (поставщики с сайтов).
 *
 * Сетевых обращений в модуле нет: страницы приносит вызывающий.
 */

const ПРЕДЕЛ_НА_ПОЗИЦИЮ = 12;

/** Ключ позиции: наименование без регистра, знаков и лишних пробелов; числа с единицами сохраняются. */
function ключПозиции(позиция) {
  const s = String((позиция && (позиция.ключПоиска || позиция.name)) || '').toLowerCase().replace(/ё/g, 'е');
  return s.replace(/[«»"'(),;:!?]/g, ' ').replace(/\s*([x×х*])\s*(?=\d)/g, 'х').replace(/\s+/g, ' ').trim().slice(0, 200);
}

const домен = (url) => { try { return new URL(url).hostname.replace(/^www\./, ''); } catch (e) { return ''; } };

/**
 * Запись найденных моделью поставщиков в базу (база меняется на месте).
 * Берутся только поставщики со ссылкой; цена - только подтверждённая
 * дословной строкой (поставщик без цены сохраняется как контакт).
 */
function записать(база, позиция, поставщики = [], когда = new Date()) {
  const ключ = ключПозиции(позиция);
  if (!ключ) return 0;
  база.поставщики = база.поставщики || {};
  база.позиции = база.позиции || {};
  const список = база.позиции[ключ] || [];
  let добавлено = 0;
  for (const п of поставщики) {
    const д = домен(п.url || п.site);
    if (!д || !/^https?:\/\//i.test(String(п.url || ''))) continue;
    база.поставщики[д] = {
      имя: String(п.name || '').slice(0, 160), сайт: п.site || `https://${д}`, телефон: String(п.phone || '').slice(0, 60),
      регион: String(п.region || '').slice(0, 80), вид: п.kind || '', обновлено: когда.toISOString()
    };
    const запись = {
      домен: д, url: п.url, цена: typeof п.price === 'number' ? п.price : null, единица: п.unit || '',
      цитата: String(п.evidence || '').slice(0, 300), найдено: когда.toISOString(), проверено: когда.toISOString()
    };
    const i = список.findIndex((x) => x.url === запись.url);
    if (i >= 0) список[i] = { ...список[i], ...запись, найдено: список[i].найдено };
    else { список.push(запись); добавлено++; }
  }
  // Свежие - первыми; не больше предела на позицию.
  список.sort((a, b) => String(b.проверено).localeCompare(String(a.проверено)));
  база.позиции[ключ] = список.slice(0, ПРЕДЕЛ_НА_ПОЗИЦИЮ);
  return добавлено;
}

/** Кандидаты из базы для позиции: только с ценой и страницей товара. */
function кандидаты(база, позиция) {
  const ключ = ключПозиции(позиция);
  const список = ((база && база.позиции) || {})[ключ] || [];
  return список.filter((x) => typeof x.цена === 'number' && x.url).map((x) => ({
    ...x, поставщик: ((база.поставщики || {})[x.домен]) || { имя: x.домен }
  }));
}

/**
 * Кандидат → поставщик в виде, как его отдаёт поиск (parseSupplierResponse),
 * если страница сегодня подтвердила цену. Иначе null («искать заново»).
 *
 * @param {object} к кандидат из кандидаты()
 * @param {{исход: string}} сверка результат сверитьПоставщика по сегодняшней странице
 */
function подтверждённый(к, сверка, когда = new Date()) {
  if (!сверка || сверка.исход !== 'подтверждено') return null;
  return {
    name: к.поставщик.имя || к.домен, url: к.url, site: к.поставщик.сайт || '', domain: к.домен,
    price: к.цена, priceDropped: false, unit: к.единица || '',
    priceNote: `из базы поставщиков, цена проверена на странице ${когда.toISOString().slice(0, 10)} (${сверка.сила || 'сверка'})`,
    region: к.поставщик.регион || '', kind: к.поставщик.вид || 'неизвестно', phone: к.поставщик.телефон || '',
    evidence: к.цитата || '', изБазы: true
  };
}

/** Отметить проверку: подтверждено - новая дата; не подтверждено - запись удаляется («искать заново»). */
function отметитьПроверку(база, позиция, url, подтверждено, когда = new Date()) {
  const ключ = ключПозиции(позиция);
  const список = ((база && база.позиции) || {})[ключ];
  if (!список) return;
  const i = список.findIndex((x) => x.url === url);
  if (i < 0) return;
  if (подтверждено) список[i].проверено = когда.toISOString();
  else список.splice(i, 1);
}

module.exports = { ключПозиции, записать, кандидаты, подтверждённый, отметитьПроверку, ПРЕДЕЛ_НА_ПОЗИЦИЮ };
