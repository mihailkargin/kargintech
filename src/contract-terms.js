// ОТВЕТСТВЕННОСТЬ, ГАРАНТИЯ, ПРИЁМКА, ПОСТАВКА - 24.10.2026, решение владельца
// «штрафы - можно делать и будет преимущество». Формулировки - из 134 проектов
// контракта на сервере (/data/state/fail-*.json, 24.10.2026): штрафы нашлись в
// 107, пени в 113, срок приёмки в 79, гарантия в 40. Правило то же: значение
// только с дословной цитатой, несколько разных значений - «не определено».
