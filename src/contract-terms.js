const РОЛЬ_ПОСТАВЩИКА = /(поставщик|подрядчик|исполнител)[а-яё]*\s+(обязательств|своих)|исполнени[яе]\s+(поставщик|подрядчик|исполнител)[а-яё]*|(поставщик|подрядчик|исполнител)[а-яё]*\s+уплачива|(поставщик|подрядчик|исполнител)[а-яё]*\s+выплачива/i;
const ЧИСЛО_ДР = '(\\d{1,3}(?:[.,]\\d+)?)';

/** Одно значение из найденных: варианты по ключу совпали - первое, иначе null. */
function единственное(найдено, ключ) {
  const в = [...new Set(найдено.map(ключ))];
  return в.length === 1 ? найдено[0] : null;
}

/**
 * Штраф поставщика за неисполнение - ступени по цене контракта (ПП РФ
 * № 1042): «10 процентов цены Контракта (этапа) в случае, если цена
 * Контракта (этапа) не превышает 3 млн. рублей; б) 5 процентов … от 3 млн.
 * рублей до 50 млн. рублей». Ступени - все, какие стоят в предложении.
 */
function штраф(предл) {
  const найдено = [];
  const одиночные = [];
  for (let i = 0; i < предл.length; i++) {
    let s = предл[i];
    // «… Поставщик уплачивает Заказчику штраф. Размер штрафа … составляет 1 %»
    // (0157100004326000040): роль - в предыдущем предложении.
    const роль = РОЛЬ_ПОСТАВЩИКА.test(s) || (/^размер\s+штрафа/i.test(s) && i > 0 && РОЛЬ_ПОСТАВЩИКА.test(предл[i - 1]) && /штраф/i.test(предл[i - 1]));
    if (!/штраф/i.test(s) || !роль || /заказчик[а-яё]*\s+обязательств/i.test(s)) continue;
    // Ступени «1) 10 процентов …; 2) 5 процентов …» делятся на предложения по
    // «; 2)» - собираются обратно, пока следующее начинается с номера ступени.
    for (let j = i + 1; j < предл.length && j <= i + 6 && /^([а-е]|\d{1,2})\)\s/i.test(предл[j]); j++) s += ' ' + предл[j];
    const ступени = [];
    const re = new RegExp(`${ЧИСЛО_ДР}\\s*(?:\\([а-яё\\s,]+\\)\\s*)?(?:%|процент[а-яё]*)\\s+(?:начальной\\s*\\(максимальной\\)\\s+)?цены\\s+(?:контракта|договора)[^;]{0,80}?(?:не\\s+превышает\\s+${ЧИСЛО_ДР}\\s*млн|от\\s+${ЧИСЛО_ДР}\\s*млн[^;]{0,40}?до\\s+${ЧИСЛО_ДР}\\s*млн|превышает\\s+${ЧИСЛО_ДР}\\s*млн)`, 'gi');
    // Не общая ответственность: контракт с СМП (п. 1 ч. 1 ст. 30), обязательство
    // без стоимостного выражения, штраф, который требует поставщик с заказчика.
    // «…предложившим наиболее высокую цену за право заключения контракта» -
    // особый случай торгов выше НМЦК (0131200001026007400), не общий штраф.
    if (/за\s+право\s+заключения|стать[а-яё]*\s+30|не\s+имеет\s+стоимостного|(поставщик|подрядчик|исполнител)[а-яё]*\s+вправе\s+потребовать|субподряд|соисполнител/i.test(s)) continue;
    let м;
    while ((м = re.exec(s))) {
      const ч = (x) => (x === undefined ? null : Number(x.replace(',', '.')));
      const до = ч(м[2]) ?? ч(м[4]);
      const от = ч(м[3]) ?? ч(м[5]);
      const ст = { процент: ч(м[1]), отМлн: от, доМлн: до };
      // Тот же набор дважды (варианты «цена ≤ НМЦК» и «цена снижена» с
      // одинаковыми ставками) - один раз; разные ставки на одну ступень - не решаем.
      const та = ступени.find((x) => x.отМлн === от && x.доМлн === до);
      if (!та) ступени.push(ст);
      else if (та.процент !== ст.процент) { ступени.length = 0; break; }
    }
    if (ступени.length >= 2) { найдено.push({ ступени, цитата: s }); continue; }
    // Одна ставка: «и составляет 10 процентов цены Контракта», «1 % цены
    // Контракта, но не более 5000 рублей», «штраф в размере 10% от цены договора».
    const од = s.match(new RegExp(`(?:составляет|в\\s+размере)\\s*-?\\s*${ЧИСЛО_ДР}\\s*(?:\\([а-яё\\s,]+\\)\\s*)?(?:%|процент[а-яё]*)\\s+(?:от\\s+)?(?:цены|стоимости)\\s+(?:контракта|договора)([^.;]{0,60})`, 'i'));
    if (од) {
      const макс = (од[2] || '').match(/не\s+более\s+(\d[\d\s]*)\s*(тыс)?/i);
      const р = макс ? Number(макс[1].replace(/\s/g, '')) * (макс[2] ? 1000 : 1) : null;
      одиночные.push({ ступени: [{ процент: Number(од[1].replace(',', '.')), отМлн: null, доМлн: null, ...(р ? { максимумРуб: р } : {}) }], цитата: s });
    }
  }
  const явный = единственное(найдено, (н) => JSON.stringify(н.ступени)) || (найдено.length ? null : единственное(одиночные, (н) => JSON.stringify(н.ступени)));
  if (явный || найдено.length || одиночные.length) return явный;
  // Сумма в проекте не проставлена («Размер штрафа определяется в соответствии
  // с Правилами … № 1042 … и составляет ______»), но для контракта 44-ФЗ её
  // задаёт закон (ч. 8 ст. 34): шкала ПП № 1042. Ступени - только те, что
  // подтверждены дословно договорами с сервера (до 500 млн ₽); у контракта с
  // СМП по п. 1 ч. 1 ст. 30 - 1%, не более 5 000 ₽: какая применится, решает
  // вид закупки, поэтому показываются обе (25.10.2026: 200 из 301 без штрафа).
  const ссылка = предл.find((s) => /штраф/i.test(s) && /1042/.test(s) && !/заказчик[а-яё]*\s+обязательств|за\s+право\s+заключения|стоимостного/i.test(s));
  if (!ссылка) return null;
  return { поПравилам: true, ступени: ПП1042, смп: { процент: 1, максимумРуб: 5000, минимумРуб: 1000 }, цитата: ссылка };
}

