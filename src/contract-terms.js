/**
 * УСЛОВИЯ КОНТРАКТА КОДОМ - 22.10.2026, решение владельца 14.10.2026
 * «условия из документации - просто текст, почему не код».
 *
 * Из проекта контракта (договора) берутся три условия, важные посреднику:
 * аванс, срок оплаты и срок поставки. Каждое значение - только с дословной
 * цитатой из документа: цитату можно найти в файле глазами, а значит и
 * проверить. Нашлось несколько РАЗНЫХ значений или не нашлось ничего -
 * значение не выбирается («не определено»), а не угадывается.
 *
 * Формулировки взяты из 15 настоящих проектов контракта с портала
 * (сохранены на сервере 17-21.10.2026). Ловушки оттуда же:
 *  - «требованием оплаты в течение 30 дней ... неустойки» - это срок уплаты
 *    штрафа поставщиком, а не срок оплаты товара;
 *  - «если Контрактом предусмотрена выплата аванса» - типовая оговорка
 *    44-ФЗ, ничего не говорит о самом авансе;
 *  - «Оплата производится Поставщиком ... налоговых последствий» - тоже не
 *    оплата товара.
 */

const ЧИСЛА = { одного: 1, один: 1, двух: 2, два: 2, трех: 3, трёх: 3, три: 3, пяти: 5, пять: 5, семи: 7, семь: 7, десяти: 10, десять: 10, пятнадцати: 15, двадцати: 20, тридцати: 30, тридцать: 30, сорока: 40, девяноста: 90 }; // кириллица-ок

const норм = (s) => String(s || '').replace(/ /g, ' ').replace(/\s+/g, ' ');

/** Предложения текста (по точке с пробелом и заглавной/цифрой). */
// После сокращений («2017 г. № 1042», «ст. 4721», «5 тыс. рублей», «ч. 7»)
// предложение не кончается: иначе «Размер штрафа … от 30 августа 2017 г.» и
// «… и составляет 1% цены Контракта» оказывались разными фразами (25.10.2026).
// «ст.», «ч.», «п.» фразу не кончают никогда; «г.», «руб.», «тыс.» - кончают
// («что составляет ___ руб.»), склеиваются, только если дальше номер или число.
const СОКРАЩЕНИЕ = /(?:^|[^А-ЯЁа-яё])(?:ст|ч|п|пп|подп|им|ул|обл|д|т|см|ред|Ст|Ч|П)\.$/;
const СОКРАЩЕНИЕ_ЧИСЛА = /(?:^|[^А-ЯЁа-яё])(?:г|гг|тыс|руб|коп|млн|млрд)\.$/;

function предложения(текст) {
  const куски = норм(текст).split(/(?<=[.;])\s+(?=[А-ЯЁA-Z0-9«"])/);
  const итог = [];
  for (const к of куски) {
    const пред = итог[итог.length - 1];
    if (пред && (СОКРАЩЕНИЕ.test(пред) || (СОКРАЩЕНИЕ_ЧИСЛА.test(пред) && /^(N|№|\d)/.test(к)))) итог[итог.length - 1] += ' ' + к;
    else итог.push(к);
  }
  return итог.map((s) => s.trim()).filter((s) => s.length > 10 && s.length < 4000);
}

/** «7 (семи) рабочих дней», «тридцати дней», «10 рабочих дней» → { дней, вид }. */
function срокВДнях(s) {
  const м = s.match(/(\d{1,3})\s*(?:\([а-яё\s-]+\)\s*)?(рабоч[а-яё]*|календарн[а-яё]*|банковск[а-яё]*)?\s*(?:дн[а-яё]*|день)/i)
    || s.match(/([а-яё]+)\s*(рабоч[а-яё]*|календарн[а-яё]*)?\s*(?:дн[а-яё]*|день)/i);
  if (!м) return null;
  const дней = /^\d+$/.test(м[1]) ? Number(м[1]) : ЧИСЛА[м[1].toLowerCase()];
  if (!дней || дней > 1000) return null;
  const вид = /рабоч/i.test(м[2] || '') ? 'рабочих' : (/банковск/i.test(м[2] || '') ? 'банковских' : (/календарн/i.test(м[2] || '') ? 'календарных' : ''));
  return { дней, вид };
}

const ШТРАФ = /неустойк|штраф|пен[ияюей]|претензи|налогов|возврат|обеспечени/i;

// Оговорки «если предусмотрен аванс», «в случае оплаты аванса» - ни да, ни нет.
const ОГОВОРКА = /если\s+[а-яё\s]{0,30}предусмотрен[а-яё]*\s+[а-яё\s]{0,20}аванс|в\s+случае\s+[а-яё\s]{0,40}аванс|при\s+оплате\s+аванса/i;

function аванс(предл) {
  const нет = предл.filter((s) => !ОГОВОРКА.test(s) && /(аванс[а-яё]*|авансов[а-яё]* платеж[а-яё]*|предоплат[а-яё]*)\s+(не\s+предусмотрен|не\s+выплачива|не\s+осуществля)/i.test(s));
  const есть = [];
  for (const s of предл) {
    if (ОГОВОРКА.test(s)) continue;
    // «Обеспечение исполнения … по возврату аванса … 20 процентов» - процент
    // обеспечения, не аванса (0121100006826000090, 24.10.2026: 3 таких из 135).
    if (/возврат[а-яё]*\s+аванс|обеспечени[а-яё]*\s+исполнени/i.test(s)) continue;
    // «предоплата 50%», «аванс в размере 30 (тридцати) процентов», «30 % предоплата».
    const м = s.match(/(?:аванс[а-яё]*|предоплат[а-яё]*)[^.;]{0,80}?(\d{1,3}(?:[.,]\d+)?)\s*(?:\([а-яё\s]+\)\s*)?(?:%|процент)/i)
      || s.match(/(\d{1,3}(?:[.,]\d+)?)\s*%\s*(?:\([а-яё\s]+\)\s*)?(?:предоплат|аванс)/i);
    if (м) есть.push({ процент: Number(м[1].replace(',', '.')), цитата: s });
  }
  if (нет.length && !есть.length) return { есть: false, цитата: нет[0] };
  if (есть.length && !нет.length) {
    const пр = [...new Set(есть.map((е) => е.процент))];
    if (пр.length === 1 && пр[0] > 0 && пр[0] <= 100) return { есть: true, процент: пр[0], цитата: есть[0].цитата };
  }
  return null;
}

// Неустойка и претензия - в любом месте фразы; «обеспечения», «налогов»,
// «возврат» - только ДО срока: «… с даты подписания документа о приемке, с
// учетом Положения о мерах по обеспечению исполнения федерального бюджета» -
// срок оплаты товара (25.10.2026: так терялось 2 из 30 в выборке).
const НЕУСТОЙКА = /неустойк|штраф|пен[ияюей]|претензи/i;

function срокОплаты(предл) {
  const найдено = [];
  for (const s of предл) {
    // «расчетного счета» - реквизит, не расчёт («в течение 1 рабочего дня
    // сообщить о смене расчетного счета», 0116300000126001143).
    if (!/оплат|оплач|расч[её]т(?!н)/i.test(s.replace(/расч[её]тн[а-яё]*\s+сч[её]т[а-яё]*/gi, '')) || НЕУСТОЙКА.test(s)) continue;
    if (/сообщ[а-яё]*\s+[а-яё\s]{0,40}(об\s+этом|об\s+изменени)|в\s+случае\s+изменени[яе]\s+(своего\s+)?(расч[её]тн|банковск|реквизит)/i.test(s)) continue;
    // Акт сверки расчётов, погашение задолженности, возмещение расходов
    // доставки - свои сроки, не срок оплаты товара (6 договоров из 301).
    if (/сверк[а-яё]*\s+(взаимных\s+)?расч|акт[а-яё]*\s+сверки|задолженност|возмещени/i.test(s)) continue;
    // Счёт выставляет поставщик («представить счет для оплаты не позднее 3 дней
    // со дня … документа о приемке») и платит поставщик - не срок оплаты товара.
    // «на основании выставленного Поставщиком счета» - обычная часть срока
    // оплаты, её не отсекать: только глагол действия поставщика (25.10.2026:
    // широкое правило потеряло 37 настоящих сроков из 301).
    if (/(представить|предоставить|выставить|направить|представляет|предоставляет|выставляет|направляет)\s+[а-яё\s]{0,30}сч[её]т(?![а-яё]*-?фактур)|должн[а-яё]*\s+быть\s+выставлен|оплат[а-яё]*\s+производится\s+поставщик|(поставщик|исполнител|подрядчик)[а-яё]*\s+(производит|осуществляет)\s+оплат/i.test(s)) continue;
    // Срок считается от приёмки/подписания документа о приёмке/счёта - иначе
    // это не срок оплаты товара («в течение 3 дней с момента подписания договора» - предоплата).
    // Срок и событие, от которого он считается, - рядом: в «предоплата в течение
    // 3 дней с подписания договора, окончательный расчёт в течение 7 дней со дня
    // приёмки» срок оплаты товара - 7, а не 3. До 170 знаков: «7 рабочих дней с
    // даты подписания усиленной электронной подписью лицом, имеющим право
    // действовать от имени Заказчика, документа о приемке» (25.10.2026).
    const r = /(в\s+течени[ея]|в\s+срок,?\s+не\s+более|не\s+позднее|не\s+более|не\s+превышающ[а-яё]*)\s+([^.;]{0,170}?)(приемк|приёмк|поставк|сч[её]т[аеу]?(?![а-яё])|акт[аеу]?(?![а-яё])|упд(?![а-яё])|накладн|передаточн)/gi;
    let м; let с = null;
    while ((м = r.exec(s))) {
      if (ШТРАФ.test(s.slice(0, м.index + м[0].length))) continue;
      // «В течение 7 дней с даты оплаты … представляет акт сверки» - срок от оплаты, не срок оплаты.
      if (/(с|со)\s+(даты|момента|дня)\s+оплат/i.test(м[2])) continue;
      const x = срокВДнях(м[2]); if (x) с = x;
    }
    if (с) найдено.push({ ...с, цитата: s });
  }
  const вар = [...new Set(найдено.map((н) => `${н.дней}|${н.вид}`))];
  return вар.length === 1 ? найдено[0] : null;
}

function срокПоставки(предл) {
  const найдено = [];
  for (const s of предл) {
    if (!/поставк|поставить/i.test(s) || ШТРАФ.test(s)) continue;
    // Дата с точками («29.02.2028») - [^;], а не [^.;].
    const окончание = s.match(/окончани[ея]\s+срока\s+поставки[:\s]+([^;]{3,80})/i);
    if (окончание) {
      const д = окончание[1].match(/\d{2}\.\d{2}\.\d{4}/);
      const с = срокВДнях(окончание[1]);
      if (д) { найдено.push({ до: д[0], цитата: s }); continue; }
      if (с) { найдено.push({ ...с, отсчёт: 'с даты заключения контракта', цитата: s }); continue; }
    }
    const м = s.match(/(?:срок[а-яё]*\s+поставки[^.;:]{0,30}[:\s]|поставка[^.;]{0,60}осуществляется[^.;]{0,40}?)\s*(?:в\s+течение\s+)?([^.;]{3,120}?(?:заключени[яе]|подписани[яе]|заявк[а-яё]*)\s+[^.;]{0,30})/i);
    if (м && /в\s+течение|не\s+позднее|не\s+более/i.test(s)) {
      const с = срокВДнях(м[1]);
      if (с) найдено.push({ ...с, отсчёт: /заявк/i.test(м[1]) ? 'с даты заявки' : 'с даты заключения контракта', цитата: s });
      continue;
    }
    const по = s.match(/срок[а-яё]*\s+поставки[^.;]{0,60}?по\s+(\d{2}\.\d{2}\.\d{4}|\d{1,2}\s+[а-яё]+\s+\d{4})/i);
    if (по) найдено.push({ до: по[1], цитата: s });
  }
  const вар = [...new Set(найдено.map((н) => `${н.дней || ''}|${н.вид || ''}|${н.до || ''}|${н.отсчёт || ''}`))];
  return вар.length === 1 ? найдено[0] : (найдено.length ? null : срокПоставкиШире(предл));
}

/**
 * СРОК ПОСТАВКИ - формулировки, которых прежнее правило не знало (25.10.2026,
 * 301 договор с сервера, найдено 101): «с даты заключения контракта в течение
 * 20 дней» (порядок наоборот), «по заявке … в течение 10 календарных дней с
 * момента получения заявки», «Срок поставки - 5 дней с даты направления
 * заявки», «до 01.12.2026», «01.02.2027 г. - 10.02.2027 г.», «с 01 января
 * 2027 г. по 31 декабря 2027 г.». Только когда прежнее правило не нашло ничего.
 */
function срокПоставкиШире(предл) {
  const ДАТА = '(\\d{2}\\.\\d{2}\\.\\d{4}|\\d{1,2}\\s+(?:января|февраля|марта|апреля|мая|июня|июля|августа|сентября|октября|ноября|декабря)\\s+\\d{4})';
  const найдено = [];
  for (const s of предл) {
    if (!/срок[а-яё]*\s+поставки|поставка[^.;]{0,60}осуществля/i.test(s) || ШТРАФ.test(s)) continue;
    // Отсылки без срока: «в срок и на условиях, предусмотренных Контрактом»,
    // «контроль сроков поставки», нарушение срока.
    if (/в\s+срок\s+и\s+на\s+условиях|в\s+установленные\s+сроки|контрол[а-яё]*\s+сроков|нарушени|просрочк/i.test(s)) continue;
    const н = {};
    const з = s.match(/(?:в\s+течение|не\s+позднее|не\s+более)\s+([^.;]{1,40}?)\s+(?:с\s+(?:даты|момента|дня)\s+)?(?:получени[яе]|направлени[яе]|подачи|передачи|поступлени[яе])?[^.;]{0,30}?заявк/i)
      || s.match(/срок[а-яё]*\s+поставки[^.;:]{0,20}[:\s–—-]+\s*(\d{1,3}\s*(?:\([а-яё\s-]+\)\s*)?(?:рабоч[а-яё]*|календарн[а-яё]*)?\s*дн[а-яё]*)\s+с\s+(?:даты|момента)[^.;]{0,40}заявк/i);
    // Срок - по всему совпадению: короткая группа при «7 рабочих дней с момента
    // передачи ему заявки» схватывала одно «7» без «дней».
    if (з) { const с = срокВДнях(з[0]); if (с) Object.assign(н, с, { отсчёт: 'с даты заявки' }); }
    if (!н.дней) {
      const зк = s.match(/с\s+(?:даты|момента)\s+заключени[яе](?:\s+(?:государственного\s+|муниципального\s+)?(?:контракта|договора))?[^.;]{0,20}?в\s+течение\s+([^.;]{1,40}?дн[а-яё]*)/i);
      if (зк) { const с = срокВДнях(зк[1]); if (с) Object.assign(н, с, { отсчёт: 'с даты заключения контракта' }); }
    }
    const диапазон = s.match(new RegExp(`${ДАТА}\\s*(?:г\\.?)?\\s*(?:[-–—]|по)\\s*${ДАТА}`, 'i'));
    const до = s.match(new RegExp(`(?:^|[^а-яё])(?:до|не\\s+позднее)\\s+${ДАТА}`, 'i'));
    // «с даты заключения контракта по 31 декабря 2026 г.» - тоже срок «до».
    const поЗакл = /с\s+(?:даты|момента)\s+заключени/i.test(s) && s.match(new RegExp(`(?:^|[^а-яё])по\\s+${ДАТА}`, 'i'));
    if (диапазон) н.до = диапазон[2]; else if (до) н.до = до[1]; else if (поЗакл) н.до = поЗакл[1];
    if (н.дней || н.до) найдено.push({ ...н, цитата: s });
  }
  return единственное(найдено, (н) => `${н.дней || ''}|${н.вид || ''}|${н.до || ''}|${н.отсчёт || ''}`);
}

