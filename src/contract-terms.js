/**
 * Условия из текстов документов закупки. Берутся только документы, похожие
 * на проект контракта (по имени), и общий текст - если проекта нет.
 *
 * @param {Array<{имя: string, текст: string}>} документы
 * @returns {{аванс: object|null, оплата: object|null, поставка: object|null, источник: string|null}}
 */
// Имя файла проекта (24.10.2026, 247 закупок с таким файлом шли без условий):
// «Проект государственного контракта», «Проект ГК», «Проект МК», «ПК (бумага
// офисная)», «Договор поставки №». Обоснование НМЦК и требования к заявке -
// не проект, хотя в имени «контракта».
const ИМЯ_ПРОЕКТА = /проект[^/]{0,40}(контракт|договор|гк(?![а-яё])|мк(?![а-яё]))|(^|[^а-яё])(гк|мк|пк)([^а-яё]|$)|(^|[^а-яё])(контракт|договор)[а-яё]*\s+(поставки|на\s+поставку|№)|^(\d+\.?\s*)?(контракт|договор)/i;
const НЕ_ПРОЕКТ = /обосновани|нмц|требовани[а-яё]*\s+к\s+(содержани|заявк|состав)|инструкци/i;
// Разделы, по которым договор узнаётся по содержимому (договор внутри
// «Документации» или «Извещения» 223-ФЗ; 310 закупок без файла проекта).
const РАЗДЕЛЫ = [/предмет\s+(договора|контракта)/i, /ответственност[а-яё]*\s+сторон/i, /порядок\s+(расч[её]тов|оплаты)|условия\s+оплаты/i, /форс-мажор|обстоятельств[а-яё]*\s+непреодолимой\s+силы/i];

/** Текст договора внутри документа: с раздела «Предмет договора» и до конца; не договор - null. */
function договорВнутри(текст) {
  const т = String(текст || '');
  if (РАЗДЕЛЫ.filter((re) => re.test(т)).length < 3) return null;
  // Начало договора - его шапка («ДОГОВОР ПОСТАВКИ № …», «Проект договора»)
  // не дальше 3 000 знаков до «1. Предмет договора»; шапки нет - сам раздел.
  // Извещение выше договора в расчёт не идёт: там свои сроки.
  const м = /(^|\n)\s*(\d+\.?\s*)?предмет\s+(договора|контракта)/i.exec(т);
  if (!м) return null;
  const окно = т.slice(Math.max(0, м.index - 3000), м.index);
  const шапки = [...окно.matchAll(/(ДОГОВОР|КОНТРАКТ)[А-ЯЁ\s]{0,40}№|[Пп]роект\s+(договора|контракта)|ПРОЕКТ\s+(ДОГОВОРА|КОНТРАКТА)/g)];
  const начало = шапки.length ? м.index - окно.length + шапки[шапки.length - 1].index : м.index;
  return т.slice(начало);
}

function условияКонтракта(документы = []) {
  const длинные = документы.filter((д) => String(д.текст || '').length > 1500);
  const проекты = длинные.filter((д) => ИМЯ_ПРОЕКТА.test(String(д.имя || '')) && !НЕ_ПРОЕКТ.test(String(д.имя || '')));
  // Файла проекта нет - договор по содержимому, в остальных документах.
  const откуда = проекты.length ? проекты
    : длинные.filter((д) => !НЕ_ПРОЕКТ.test(String(д.имя || ''))).map((д) => ({ имя: д.имя, текст: договорВнутри(д.текст) })).filter((д) => д.текст);
  const предл = откуда.flatMap((д) => предложения(д.текст));
  if (!предл.length) return { аванс: null, оплата: null, поставка: null, источник: null };
  // Срок поставки в проекте контракта часто не проставлен («в срок,
  // предусмотренный Спецификацией»), а стоит в описании объекта закупки или ТЗ
  // той же закупки - берётся оттуда, с названием документа (25.10.2026).
  let поставка = срокПоставки(предл);
  if (!поставка) {
    for (const д of документы) {
      if (откуда.some((о) => о.имя === д.имя) || !/описани[а-яё]*\s+объекта|техническ[а-яё]*\s+задани|(^|[^а-яё])(тз|ооз)([^а-яё]|$)|спецификац/i.test(String(д.имя || ''))) continue;
      const р = срокПоставки(предложения(д.текст));
      if (р) { поставка = { ...р, документ: String(д.имя || '').slice(0, 80) }; break; }
    }
  }
  return {
    аванс: аванс(предл),
    оплата: срокОплаты(предл),
    поставка,
    штраф: штраф(предл),
    пеня: пеня(предл),
    гарантия: обеспечениеГарантии(предл),
    гарантийныйСрок: гарантийныйСрок(предл),
    приёмка: срокПриёмки(предл),
    казначейство: казначейство(предл),
    разгрузка: разгрузка(предл),
    годность: остаточныйСрок(предл),
    партиями: партиями(предл),
    смп: толькоСмп(предл),
    источник: откуда.map((д) => д.имя).join('; ').slice(0, 200)
  };
}

/** Короткая строка для клиента: «аванс не предусмотрен», «оплата: 7 рабочих дней после приёмки». */
function текстУсловий(у) {
  if (!у) return [];
  const строки = [];
  if (у.аванс) строки.push(у.аванс.есть ? `аванс ${String(у.аванс.процент).replace('.', ',')}%` : 'аванс не предусмотрен');
  if (у.оплата) строки.push(`оплата в течение ${у.оплата.дней}${у.оплата.вид ? ` ${у.оплата.вид}` : ''} дн. после приёмки`);
  if (у.поставка) {
    const п = у.поставка;
    const дни = п.дней ? `в течение ${п.дней}${п.вид ? ` ${п.вид}` : ''} дн. ${п.отсчёт || ''}`.trim() : '';
    строки.push(п.до && дни ? `поставка ${дни}, до ${п.до}` : п.до ? `поставка до ${п.до}` : `поставка ${дни}`);
  }
  if (у.приёмка) строки.push(`приёмка до ${у.приёмка.дней}${у.приёмка.вид ? ` ${у.приёмка.вид}` : ''} дн.${у.приёмка.отсчёт ? ` ${у.приёмка.отсчёт}` : ''}`);
  if (у.гарантия) строки.push(у.гарантия.есть ? `обеспечение гарантии ${String(у.гарантия.процент).replace('.', ',')}%` : 'обеспечение гарантии не требуется');
  if (у.годность) строки.push(`остаточный срок годности не менее ${у.годность.значение} ${у.годность.ед}`);
  if (у.смп) строки.push('только для СМП и СОНКО');
  return строки;
}

/** Строки ответственности для клиента: штраф по цене контракта и пеня. */
function текстОтветственности(у, цена) {
  if (!у) return [];
  const строки = [];
  const ст = штрафДляЦены(у.штраф, цена);
  const р = (x) => String(Math.round(x)).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
  if (ст && у.штраф.поПравилам) {
    строки.push(`штраф за неисполнение - по ПП № 1042, в проекте сумма не проставлена: ${String(ст.процент).replace('.', ',')}% цены контракта (${р(ст.сумма)} ₽, если цена равна НМЦК ${р(цена)} ₽); для контракта с СМП - 1%, не более 5 000 ₽`);
  } else if (ст) строки.push(`штраф за неисполнение ${String(ст.процент).replace('.', ',')}% цены контракта (${р(ст.сумма)} ₽, если цена равна НМЦК ${р(цена)} ₽)`);
  if (у.пеня) строки.push(`пеня за просрочку - ${у.пеня.доля}`);
  return строки;
}

