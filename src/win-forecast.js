/**
 * ПРОГНОЗ ЦЕНЫ ПОБЕДЫ - тариф Макс, ВЕРОЯТНОСТИ-ЦЕНЫ.md и решения владельца
 * 28.10.2026. Цена победы одним числом не предсказывается (обратная проверка
 * 27.10: медиана ошибки 11,5% на 148 протоколах) - даются частоты по похожим
 * прошлым закупкам:
 *   - доля закупок с одной заявкой (контракт по цене около НМЦК);
 *   - процентили снижения: «95% закупок» = от 2,5-го до 97,5-го процентиля,
 *     по фактическим значениям, не по колоколу (пик в нуле, граница снизу);
 *   - среднее число участников;
 *   - вероятность победы при цене клиента и рекомендуемая цена: максимум
 *     (цена - безубыточность) × вероятность победы;
 *   - риск антидемпинга (снижение от 25%, ст. 37 44-ФЗ).
 *
 * «Вероятность победы при цене b» - ПРИБЛИЖЕНИЕ, принятое владельцем 28.10:
 * клиент выигрывает похожую закупку, если его снижение глубже, чем у её
 * победителя. Как поменялись бы ставки соперников с ещё одним участником, из
 * протоколов не следует.
 *
 * Вероятность победы - ТОЛЬКО ПО КОНКУРЕНТНЫМ закупкам (2+ участника). Найдено
 * тестом 30.10.2026: с закупками одной заявки в выборке лучшей ставкой выходило
 * «снижение 0,1%» - выиграть те, где соперник был один и подал по НМЦК. Но с
 * клиентом заявок уже две, и соперник снизит цену. Доля одной заявки
 * показывается отдельно (модель из двух частей, ВЕРОЯТНОСТИ-ЦЕНЫ.md, п. 2).
 *
 * Похожие: тот же способ, тот же товар по ОКПД2 (никогда не «любой» - падение
 * цены на картриджи не говорит ничего о бумаге), НМЦК рядом, свежие. Меньше 30 -
 * отбор расширяется на шаг; меньше 10 - не показывается. Очистка - по фактам
 * (несопоставимые предложения, цена за единицу, неправдоподобное снижение
 * отсеяны при сборе, src/protocol-page.js), не по IQR: IQR срезал бы хвост риска.
 *
 * До показа клиенту - обратная проверка (`калибровка`): каждая прошлая закупка
 * прогнозируется по остальным, и вероятность «70%» должна сбываться около 70%.
 *
 * Сетевых обращений нет.
 */
const { определитьСпособ, СПОСОБ } = require('./protocol-page');

const ЦЕЛЬ = 30;
const МИНИМУМ = 10;
const ПОРОГ_АНТИДЕМПИНГА = 25;
/** Шаг ставки над снижением победителя, п.п.: чтобы выиграть, надо быть ниже, а не вровень. */
const ШАГ = 0.1;

/** Год закупки из реестрового номера: 44-ФЗ - знаки 12-13 из 19, 223-ФЗ - 2-3 из 11. */
function годЗакупки(номер) {
  const н = String(номер || '').replace(/\D/g, '');
  const гг = н.length === 19 ? н.slice(11, 13) : н.length === 11 ? н.slice(1, 3) : null;
  return гг && /^\d\d$/.test(гг) ? 2000 + Number(гг) : null;
}

const группыНаблюдения = (н) => ((н.группыОкпд2 && н.группыОкпд2.length) ? н.группыОкпд2 : [н.группаОкпд2]).filter(Boolean).map(String);
const класс = (г) => String(г).slice(0, 2);

/** Ступени отбора: от узкой к широкой. Товар (ОКПД2) не отпускается никогда. */
const СТУПЕНИ = [
  { окпд: 'группа', от: 0.5, до: 2, лет: 1, текст: 'та же группа ОКПД2, НМЦК от 0,5 до 2 раз, этот и прошлый год' },
  { окпд: 'группа', от: 0.5, до: 2, лет: 2, текст: 'та же группа ОКПД2, НМЦК от 0,5 до 2 раз, за три года' },
  { окпд: 'группа', от: 1 / 3, до: 3, лет: 2, текст: 'та же группа ОКПД2, НМЦК от 1/3 до 3 раз, за три года' },
  { окпд: 'класс', от: 1 / 3, до: 3, лет: 2, текст: 'тот же класс ОКПД2 (две первые цифры), НМЦК от 1/3 до 3 раз, за три года' }
];

/**
 * @param {object[]} наблюдения протоколы (src/protocol-page.js, наблюдение)
 * @param {{нмцк: number, способ: string, группыОкпд2: string[], год?: number}} тендер
 * @param {{исключить?: string}} [о] номер, который не берётся (обратная проверка)
 */
function отобрать(наблюдения, тендер, о = {}) {
  const способ = определитьСпособ(String(тендер.способ || ''));
  if (!(тендер.нмцк > 0)) return { похожие: [], причина: 'НМЦК тендера неизвестна' };
  if (!способ || способ === СПОСОБ.ИНОЙ || способ === СПОСОБ.ЕДИНСТВЕННЫЙ) return { похожие: [], причина: `способ закупки «${способ || 'не определён'}» - сравнивать не с чем` };
  const группы = (тендер.группыОкпд2 || []).filter(Boolean).map(String);
  if (!группы.length) return { похожие: [], причина: 'товар закупки по ОКПД2 не определён - похожие не отбираются' };
  const год = тендер.год || new Date().getFullYear();
  const годные = (наблюдения || []).filter((н) => н && н.номер !== о.исключить && н.способ === способ
    && typeof н.снижение === 'number' && н.нмцк > 0);
  let лучший = null;
  for (const с of СТУПЕНИ) {
    const похожие = годные.filter((н) => {
      if (н.нмцк < тендер.нмцк * с.от || н.нмцк > тендер.нмцк * с.до) return false;
      const г = годЗакупки(н.номер);
      if (г === null || г > год || г < год - с.лет) return false;
      const гн = группыНаблюдения(н);
      return с.окпд === 'группа' ? гн.some((x) => группы.includes(x)) : гн.some((x) => группы.map(класс).includes(класс(x)));
    });
    if (!лучший || похожие.length > лучший.похожие.length) лучший = { похожие, ступень: с };
    if (похожие.length >= ЦЕЛЬ) return { похожие, ступень: с, способ };
  }
  return { ...лучший, способ };
}

/** Эмпирический процентиль (линейно между соседними значениями). */
function процентиль(отсортированные, q) {
  const с = отсортированные;
  if (!с.length) return null;
  const i = (с.length - 1) * q;
  const н = Math.floor(i);
  return с[н] + (с[Math.min(н + 1, с.length - 1)] - с[н]) * (i - н);
}

/**
 * ПОПРАВКА ПО ОБРАТНОЙ ПРОВЕРКЕ (31.10.2026). Обратная проверка на 215 реальных
 * закупках показала: доля по похожим завышает шанс (прогноз 87% - сбылось 76%).
 * Таблица поправки - точки «что прогноз говорил → что сбылось» по прошлым
 * закупкам; шанс между точками - по прямой, ниже первой - по прямой к нулю.
 * ВЫШЕ ПОСЛЕДНЕЙ ТОЧКИ ШАНС НЕ ПОВЫШАЕТСЯ: где данных нет, ожидание не
 * завышается (требование владельца 31.10).
 */
function поправить(p, таблица) {
  if (p === null || p === undefined || !таблица || !таблица.length) return p;
  const т = таблица;
  if (p <= т[0].p) return т[0].p > 0 ? т[0].f * p / т[0].p : т[0].f;
  for (let i = 1; i < т.length; i++) {
    if (p <= т[i].p) return т[i - 1].f + (т[i].f - т[i - 1].f) * (p - т[i - 1].p) / (т[i].p - т[i - 1].p);
  }
  return т[т.length - 1].f;
}

/** Доля похожих, где победитель снизил цену меньше, чем на d%: столько бы выиграл клиент со снижением d. */
function вероятностьПобеды(снижения, d) {
  if (!снижения.length) return null;
  return снижения.filter((s) => s < d).length / снижения.length;
}

/**
 * Рекомендуемое снижение: максимум ожидаемой прибыли (z - d) × P(d), где z -
 * запас до безубыточности, %. Кандидаты - на шаг глубже каждого прошлого
 * снижения: между ними вероятность не меняется, а прибыль падает.
 */
function рекомендация(снижения, z, нмцк, налог = 0, таблица = null) {
  if (typeof z !== 'number' || z <= 0) return null;
  let лучший = null;
  for (const s of new Set(снижения)) {
    const d = Math.round((s + ШАГ) * 10) / 10;
    if (d >= z) continue;
    const p = поправить(вероятностьПобеды(снижения, d), таблица);
    const прибыль = (1 - налог) * нмцк * (z - d) / 100;
    const e = прибыль * p;
    if (!лучший || e > лучший.e + 1e-9 || (Math.abs(e - лучший.e) <= 1e-9 && p > лучший.p)) лучший = { d, p, e, прибыль };
  }
  if (!лучший || лучший.p === 0) return null;
  return {
    снижение: лучший.d,
    цена: Math.round(нмцк * (1 - лучший.d / 100)),
    вероятность: Math.round(лучший.p * 1000) / 10,
    прибыльПриПобеде: Math.round(лучший.прибыль),
    ожидаемаяПрибыль: Math.round(лучший.e)
  };
}

const окр = (x) => (x === null || x === undefined ? null : Math.round(x * 10) / 10);

/**
 * @param {object[]} наблюдения
 * @param {{нмцк, способ, группыОкпд2, год?}} тендер
 * @param {{запас?: number, запасЛучший?: number, налог?: number, толькоПотолки?: boolean}} расчёт
 * @param {{калибровка?: {прошла: boolean, когда?: string}}} опции
 */
function прогнозЦеныПобеды(наблюдения, тендер, расчёт = {}, опции = {}) {
  const о = отобрать(наблюдения, тендер);
  const n = (о.похожие || []).length;
  if (n < МИНИМУМ) return { показан: false, похожих: n, причина: о.причина || `похожих прошлых закупок ${n} - нужно не меньше ${МИНИМУМ}` };
  const сн = о.похожие.map((н) => н.снижение).sort((a, b) => a - b);
  const конкурентные = о.похожие.filter((н) => !н.единственнаяЗаявка).map((н) => н.снижение).sort((a, b) => a - b);
  const уч = о.похожие.map((н) => н.участников).filter((x) => typeof x === 'number' && x >= 1);
  const нмцк = тендер.нмцк;
  const цена = (d) => Math.round(нмцк * (1 - d / 100));
  const п = {
    похожих: n,
    отбор: о.ступень.текст,
    мало: n < ЦЕЛЬ,
    одинУчастник: окр(100 * о.похожие.filter((н) => н.единственнаяЗаявка).length / n),
    снижение: { p2_5: окр(процентиль(сн, 0.025)), p25: окр(процентиль(сн, 0.25)), медиана: окр(процентиль(сн, 0.5)), p75: окр(процентиль(сн, 0.75)), p97_5: окр(процентиль(сн, 0.975)) },
    снижениеКонкурентных: конкурентные.length >= МИНИМУМ ? окр(процентиль(конкурентные, 0.5)) : null,
    участниковВСреднем: уч.length >= МИНИМУМ ? окр(уч.reduce((s, x) => s + x, 0) / уч.length) : null,
    антидемпинг: окр(100 * сн.filter((s) => s >= ПОРОГ_АНТИДЕМПИНГА).length / n)
  };
  п.ценаПобеды = { от: цена(п.снижение.p97_5), до: цена(п.снижение.p2_5), обычно: цена(п.снижение.медиана) };
  п.конкурентных = конкурентные.length;
  // Без закупочных цен безубыточность считается по потолкам с чужой маржой - вывода о выгоде нет (правило 04.10.2026).
  const к = опции.калибровка;
  // Поправка применяется, только если сама прошла проверку на закупках, на
  // которых не училась; иначе она - подгонка.
  const таблица = к && к.поправка && к.поправка.проверена ? к.поправка.таблица : null;
  if (!расчёт.толькоПотолки && конкурентные.length >= МИНИМУМ) {
    const налог = typeof расчёт.налог === 'number' ? расчёт.налог : 0;
    for (const [ключ, z] of [['поЛучшей', расчёт.запасЛучший], ['поХудшей', расчёт.запас]]) {
      if (typeof z !== 'number') continue;
      const сырая = z > 0 ? вероятностьПобеды(конкурентные, z) : 0;
      п[ключ] = {
        запас: z,
        безубыточность: цена(z),
        вероятностьПриБезубыточности: окр(100 * поправить(сырая, таблица)),
        вероятностьБезПоправки: окр(100 * сырая),
        рекомендация: рекомендация(конкурентные, z, нмцк, налог, таблица)
      };
    }
  } else if (!расчёт.толькоПотолки) {
    п.безВероятности = `закупок с 2+ участниками ${конкурентные.length} - для вероятности победы нужно не меньше ${МИНИМУМ}`;
  }
  п.показан = Boolean(к && (к.прошла || таблица));
  п.споправкой = Boolean(таблица) && !(к && к.прошла);
  if (!п.показан) {
    п.причина = !к ? 'обратная проверка ещё не проводилась'
      : `обратная проверка не пройдена: ${к.почему || ''}${к.поправка ? `; поправка: ${к.поправка.почему || 'не проверена'}` : ''}`;
  }
  return п;
}

/**
 * ОБРАТНАЯ ПРОВЕРКА (калибровка). Каждая прошлая закупка с 10+ похожими среди
 * остальных прогнозируется по ним; для ставок со снижением 5, 10, 15, 20, 25,
 * 30% сравнивается прогноз «выиграл бы с вероятностью p» с тем, что было
 * (снижение победителя меньше ставки). Прогнозы раскладываются по корзинам
 * вероятности по 20 п.п. Корзины по 10 п.п. давали ложные расхождения: когда
 * закупка исключена из своей выборки, прогноз около 50% сдвигается вниз, если
 * её снижение было ниже ставки, и вверх - если выше, и корзины 40-50 и 50-60
 * получали факт 100% и 0% (найдено тестом 30.10.2026).
 *
 * Проверяются только конкурентные закупки (2+ участника) - те же, по которым
 * считается вероятность победы.
 *
 * Проверка ОБЯЗАНА уметь не пройти. Прошла, если: в каждой корзине с 20+
 * парами прогноз и факт расходятся не больше чем на 10 п.п.; таких корзин не
 * меньше трёх; и прогноз по похожим не хуже (балл Брайера не выше более чем на
 * 0,005), чем одна доля по всем закупкам без отбора. Пороги 20 пар, 10 п.п. и
 * 0,005 - граница здравого смысла, не измерение; названы, чтобы их можно было
 * оспорить.
 *
 * Пары от одной закупки при разных ставках связаны - поэтому число закупок
 * называется отдельно от числа пар.
 */
/** Пары «прогноз - что было» по прошлым конкурентным закупкам (каждая - по остальным). */
function парыПроверки(наблюдения, ставки = [5, 10, 15, 20, 25, 30]) {
  const все = (наблюдения || []).filter((н) => н && typeof н.снижение === 'number' && н.нмцк > 0 && группыНаблюдения(н).length && годЗакупки(н.номер));
  const конк = все.filter((н) => !н.единственнаяЗаявка);
  const пары = [];
  let закупок = 0;
  for (const н of конк) {
    const отбор = отобрать(конк, { нмцк: н.нмцк, способ: н.способ, группыОкпд2: группыНаблюдения(н), год: годЗакупки(н.номер) }, { исключить: н.номер });
    if (!отбор.похожие || отбор.похожие.length < МИНИМУМ) continue;
    закупок++;
    const сн = отбор.похожие.map((x) => x.снижение);
    const остальные = конк.filter((x) => x.номер !== н.номер).map((x) => x.снижение);
    for (const d of ставки) {
      пары.push({ номер: н.номер, p: вероятностьПобеды(сн, d), базовая: вероятностьПобеды(остальные, d), было: н.снижение < d ? 1 : 0 });
    }
  }
  return { пары, закупок, наблюдений: все.length };
}

/** Сходится ли прогноз (поле `ключ` пар) с фактом: корзины по 20 п.п. и пороги проверки. */
function оценитьПары(пары, ключ = 'p') {
  const корзины = [];
  for (let i = 0; i < 5; i++) {
    const в = пары.filter((x) => (i === 4 ? x[ключ] >= 0.8 : x[ключ] >= i / 5 && x[ключ] < (i + 1) / 5));
    if (!в.length) continue;
    const предсказано = в.reduce((s, x) => s + x[ключ], 0) / в.length;
    const сбылось = в.reduce((s, x) => s + x.было, 0) / в.length;
    корзины.push({ от: i * 20, до: (i + 1) * 20, пар: в.length, предсказано: окр(100 * предсказано), сбылось: окр(100 * сбылось) });
  }
  const брайер = (к) => (пары.length ? пары.reduce((s, x) => s + (x[к] - x.было) ** 2, 0) / пары.length : null);
  const б = брайер(ключ);
  const бБаз = брайер('базовая');
  const весомые = корзины.filter((к) => к.пар >= 20);
  const плохие = весомые.filter((к) => Math.abs(к.предсказано - к.сбылось) > 10);
  const почему = [];
  if (весомые.length < 3) почему.push(`корзин с 20+ парами ${весомые.length} - нужно не меньше 3 (мало данных)`);
  if (плохие.length) почему.push(`расхождение больше 10 п.п.: ${плохие.map((к) => `${к.от}-${к.до}%: прогноз ${к.предсказано}%, факт ${к.сбылось}%`).join('; ')}`);
  if (б !== null && бБаз !== null && б > бБаз + 0.005) почему.push(`отбор похожих хуже одной доли по всем закупкам (Брайер ${б.toFixed(4)} против ${бБаз.toFixed(4)})`);
  return {
    корзины,
    брайер: б === null ? null : Math.round(б * 10000) / 10000,
    брайерБазовый: бБаз === null ? null : Math.round(бБаз * 10000) / 10000,
    прошла: пары.length > 0 && почему.length === 0,
    почему: почему.join('; ')
  };
}

/**
 * Таблица поправки по парам: корзины прогноза по 10 п.п. с 20+ парами →
 * точка «средний прогноз → доля сбывшихся». Точки выстраиваются по
 * неубыванию (больший прогноз не может дать меньший шанс): соседние точки с
 * нарушением сливаются с весом по числу пар.
 */
function таблицаПоправки(пары) {
  let точки = [];
  for (let i = 0; i < 10; i++) {
    const в = пары.filter((x) => (i === 9 ? x.p >= 0.9 : x.p >= i / 10 && x.p < (i + 1) / 10));
    if (в.length < 20) continue;
    точки.push({ p: в.reduce((s, x) => s + x.p, 0) / в.length, f: в.reduce((s, x) => s + x.было, 0) / в.length, n: в.length });
  }
  for (let i = 1; i < точки.length;) {
    if (точки[i].f >= точки[i - 1].f) { i++; continue; }
    const a = точки[i - 1];
    const b = точки[i];
    const n = a.n + b.n;
    точки.splice(i - 1, 2, { p: (a.p * a.n + b.p * b.n) / n, f: (a.f * a.n + b.f * b.n) / n, n });
    i = Math.max(1, i - 1);
  }
  return точки.map((т) => ({ p: Math.round(т.p * 10000) / 10000, f: Math.round(т.f * 10000) / 10000, n: т.n }));
}

/**
 * Поправка проверяется на закупках, на которых не училась: закупки делятся на
 * две половины по номеру, таблица строится по одной и проверяется на другой,
 * затем наоборот. Прошла на обеих - проверена.
 */
function проверитьПоправку(пары) {
  const половина = (номер) => String(номер).split('').reduce((s, ch) => s + ch.charCodeAt(0), 0) % 2;
  const итоги = [0, 1].map((h) => {
    const учить = пары.filter((x) => половина(x.номер) !== h);
    const проверять = пары.filter((x) => половина(x.номер) === h);
    const т = таблицаПоправки(учить);
    const о = оценитьПары(проверять.map((x) => ({ ...x, q: поправить(x.p, т) })), 'q');
    return { половина: h + 1, учились: учить.length, проверено: проверять.length, ...о };
  });
  const прошла = итоги.every((и) => и.прошла);
  return {
    таблица: таблицаПоправки(пары),
    проверена: прошла,
    половины: итоги.map((и) => ({ половина: и.половина, учились: и.учились, проверено: и.проверено, корзины: и.корзины, брайер: и.брайер, почему: и.почему })),
    почему: прошла ? '' : итоги.filter((и) => !и.прошла).map((и) => `половина ${и.половина}: ${и.почему}`).join('; ')
  };
}

function калибровка(наблюдения, о = {}) {
  const { пары, закупок, наблюдений } = парыПроверки(наблюдения, о.ставки);
  const оценка = оценитьПары(пары, 'p');
  return {
    когда: new Date().toISOString(),
    наблюдений,
    закупок,
    пар: пары.length,
    ...оценка,
    поправка: оценка.прошла ? null : проверитьПоправку(пары)
  };
}

/** Текст для клиента: частоты по прошлым закупкам, не обещание. */
function текстПрогноза(п) {
  if (!п || !п.показан) return '';
  const з = (x) => String(окр(x)).replace('.', ',');
  const р = (x) => String(Math.round(x)).replace(/\B(?=(\d{3})+(?!\d))/g, ' ') + ' ₽';
  const строки = [
    `По ${п.похожих} похожим прошлым закупкам (${п.отбор})${п.мало ? ' - выборка меньше 30, вывод приблизительный' : ''}.`,
    `Одна заявка, контракт по цене около начальной - в ${з(п.одинУчастник)}% закупок.`,
    `Цена победы в 95% закупок - от ${р(п.ценаПобеды.от)} до ${р(п.ценаПобеды.до)} (снижение от ${з(п.снижение.p2_5)}% до ${з(п.снижение.p97_5)}%), обычно ${р(п.ценаПобеды.обычно)} (${з(п.снижение.медиана)}%).`
  ];
  if (п.участниковВСреднем !== null) строки.push(`Участников в среднем ${з(п.участниковВСреднем)}.`);
  if (п.безВероятности) строки.push(`Вероятность победы при вашей цене не оценена: ${п.безВероятности}.`);
  const о = п.поЛучшей || п.поХудшей;
  if (о) {
    if (о.запас <= 0) строки.push('Расходы не ниже начальной цены: выиграть без убытка нельзя.');
    else {
      строки.push(`По цене безубыточности ${р(о.безубыточность)} вы выиграли бы в ${з(о.вероятностьПриБезубыточности)}% похожих закупок с двумя и более участниками (их ${п.конкурентных}).`);
      if (о.рекомендация) строки.push(`Рекомендуемая цена ${р(о.рекомендация.цена)} (снижение ${з(о.рекомендация.снижение)}%): победа в ${з(о.рекомендация.вероятность)}% таких закупок, прибыль при победе ${р(о.рекомендация.прибыльПриПобеде)}, ожидаемая прибыль ${р(о.рекомендация.ожидаемаяПрибыль)}.`);
    }
    if (п.поЛучшей && п.поХудшей && п.поХудшей.рекомендация && п.поЛучшей.рекомендация && п.поХудшей.рекомендация.цена !== п.поЛучшей.рекомендация.цена) {
      строки.push(`По худшей цене поставщика рекомендуемая цена ${р(п.поХудшей.рекомендация.цена)}, победа в ${з(п.поХудшей.рекомендация.вероятность)}%.`);
    }
  }
  строки.push(`Снижение на 25% и больше (обеспечение в 1,5 раза больше) - в ${з(п.антидемпинг)}% закупок.`);
  if (п.споправкой) строки.push('Шанс победы поправлен по тому, как прошлые прогнозы сбывались на деле.');
  строки.push('Это частоты по прошлым закупкам, не обещание: соперником считается победитель похожей закупки с двумя и более участниками.');
  return строки.join(' ');
}

