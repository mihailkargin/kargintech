/**
 * САМОПРОВЕРКА РАСЧЁТА.
 *
 * Зачем нужен отдельный модуль, а не доверие к разбору.
 *
 * Расчёт собирается из трёх разных по надёжности вещей:
 *   — позиции и количества достаёт наш код из таблицы документа;
 *   — цены поставщиков называет модель по страницам из интернета;
 *   — итоги считаются арифметикой по первым двум.
 * Ошибка в любой из них не падает, а даёт правдоподобное число. Проверить
 * глазами это может только человек, открывший и документ, и сайты поставщиков,
 * то есть работа, от которой продукт как раз и избавляет.
 *
 * Поэтому проверка делается кодом, и она НЕ повторяет разбор другим способом
 * (два разбора расходятся и спорят), а СВЕРЯЕТ результат с первоисточником:
 *
 *   позиция  — наименование, количество и цена обязаны стоять в ОДНОЙ строке
 *              исходного документа, дословно;
 *   цитата   — дословная строка, которой модель подтвердила цену, обязана
 *              находиться на той самой странице, на которую она дала ссылку;
 *   итоги    — пересчитываются здесь заново, по формулам, выписанным отдельно
 *              от `pricing.js`, и сравниваются с его результатом.
 *
 * ЧЕГО ЭТА ПРОВЕРКА НЕ ДОКАЗЫВАЕТ, сказано прямо:
 *   — что разобраны ВСЕ позиции документа. Она подтверждает, что найденное
 *     не выдумано, а не что ничего не пропущено;
 *   — что цена относится именно к нужной характеристике товара. «Бумага А4
 *     80 г/м²» и «100 г/м²» — разные товары, и соответствие решает человек;
 *   — что цена актуальна. Подтверждается её наличие на странице сегодня.
 *
 * Сетевых обращений в модуле нет и быть не может: страницу приносит
 * вызывающий, модуль работает с текстом. Это закреплено проверкой по
 * исходнику в `tests/test-verify.js`, а не обещанием в комментарии.
 */

// Подписи полей берутся у разбора, а логика проверки здесь своя. Повторять
// разбор вторым способом нельзя: два разбора расходятся, и кто прав —
// неизвестно. Но два разных набора подписей разошлись бы молча.
const { ПОДПИСИ_ПОЛЕЙ } = require('./nmck-table');

const ИСХОДЫ = {
  ПОДТВЕРЖДЕНО: 'подтверждено',
  НЕ_ПОДТВЕРЖДЕНО: 'не подтверждено',
  НЕ_ПРОВЕРЕНО: 'не проверено'
};

/**
 * Приведение текста к виду, в котором сравнение имеет смысл.
 *
 * Страница и документ пишут одно и то же по-разному: неразрывные пробелы,
 * мягкие переносы, разные тире, «ё» вместо «е». Сравнение «как есть» дало бы
 * «не найдено» на совпадающем тексте — то есть ложное обвинение модели во
 * выдумке, а это хуже, чем не проверить вовсе.
 */
function норм(текст) {
  return String(текст == null ? '' : текст)
    .replace(/ | | /g, ' ')   // неразрывные пробелы
    .replace(/­|​|‌|‍|﻿/g, '') // мягкий перенос, нулевой ширины
    .replace(/[‐-―−]/g, '-')  // все тире к дефису
    .replace(/[«»“”„]/g, '"')
    .replace(/ё/gi, 'е')
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Присутствие числа в тексте с любыми разделителями разрядов.
 *
 * «1250» на странице может быть написано как «1 250», «1250,00», «1.250 ₽».
 * Поэтому ищется последовательность цифр, между которыми допускается один
 * разделитель, с обязательной границей слева и справа: иначе 1250 нашлось бы
 * внутри 11250, и проверка подтверждала бы чужую цену.
 */
function числоВТексте(значение, текст) {
  if (значение === null || значение === undefined || !isFinite(значение)) return false;
  const целое = String(Math.trunc(Math.abs(Number(значение))));
  if (!целое || целое === '0') return false;

  const цифры = целое.split('');
  // Между цифрами допускаем пробел или точку как разделитель разрядов.
  const тело = цифры.join('[\\s.]?');
  const шаблон = new RegExp(`(?<![\\d,.])${тело}(?![\\d])`);
  return шаблон.test(норм(текст).replace(/\s+/g, ' '));
}

/**
 * ПОДПИСЬ КОЛОНКИ, А НЕ ТОВАР.
 *
 * Найдено на живом прогоне 12.10.2026, закупка `0373200638526000056`. Разбор
 * выдал 172 «позиции», и среди них: «Количество единиц товара, шт», «Цена за
 * ед. Товара», «Цена за единицу товара без учета налога на добавленную
 * стоимость». Это подписи колонок таблицы.
 *
 * ПОЧЕМУ ЭТОГО НЕ ЛОВИЛА ПОСТРОЧНАЯ СВЕРКА. Такая строка в документе есть,
 * значит не выдумана, значит сверка её подтверждала. Она отвечала на вопрос
 * «не сочинил ли разбор», а спросить надо было ещё и «то ли он взял».
 * Проверка была права и бесполезна одновременно — худший вид проверки.
 *
 * Отбор привязан к НАЧАЛУ наименования. Товар не называется «Цена за…»,
 * а «Бумага, цена за упаковку» начинается с товара — такую строку выбрасывать
 * нельзя, поэтому поиск вхождения здесь не годится.
 */
const ПОДПИСИ_КОЛОНОК = [
  // Границы выписаны явно — (\s|,|:|$) вместо `\b`. Причина: `\b` считает
  // буквами только латиницу, и `/^итого\b/` не совпадает со словом «Итого»
  // НИКОГДА. На этом шаблоне я сел ровно здесь, на пятый день после того,
  // как записал правило в проект; поймала отдельная проверка по исходникам.
  /^цена (за|единицы|ед\.?(\s|$)|контракта|товара|поставки)/,
  /^цена(,|:|$)/,
  /^(кол-?во|количество) (единиц|товара|,)/,
  /^наименование/,
  /^ед(иница|\.)? ?изм/,
  /^(итого|всего|итог)(\s|,|:|$)/,
  /^№/,
  /^(обоснование|расчет|расчёт|протокол) /,
  /^характеристик/,
  /^(сумма|стоимость|ставка|налог|ндс)(\s|,|:|$)/,
  /^(предложение|предложения|поставщик|источник) (\d+|цен[а-яё]*|информац[а-яё]*|поставщик[а-яё]*)(\s|$)/,
  /дата составления/,
  /^(серийный номер|функциональные|технические)/
];

/**
 * @returns {string|null} подпись, на которую похоже наименование, иначе null
 */
function подписьКолонки(наименование) {
  const имя = норм(наименование);
  if (!имя) return null;
  for (const ш of ПОДПИСИ_КОЛОНОК) {
    const m = имя.match(ш);
    if (m) return m[0];
  }
  return null;
}

/**
 * СВЕРКА ПОЗИЦИЙ ПЕРЕВЁРНУТОЙ ТАБЛИЦЫ — БЛОЧНАЯ.
 *
 * В перевёрнутой таблице товар занимает блок строк, и в первой ячейке каждой
 * строки стоит название поля, а не значение:
 *
 *   Наименование товара, технические характеристики | Палитра для рисования
 *   Количество единиц товара, шт                    | 78
 *   Цена за ед. Товара                              | 45 | 54 | 47
 *
 * Поэтому проверяется не «всё в одной строке», а «всё в одном блоке»:
 * наименование стоит в строке с подписью наименования, количество — в строке
 * с подписью количества ТОГО ЖЕ блока, цена — в строке с подписью цены того же
 * блока. Сила проверки сохраняется: количество из соседнего блока не пройдёт,
 * потому что блок обрывается на следующей подписи наименования.
 *
 * Это та же сверка с первоисточником, просто граница у неё блок, а не строка.
 */
function сверитьПозицииБлоками(позиции, текст, сдвиг = 0) {
  const сырые = String(текст || '').split(/\r?\n/);
  const результаты = [];
  // Подпись поля — в ячейке `сдвиг`: в Excel 0373200315626000003 слева стоит
  // колонка номера блока, и подписи во второй ячейке (19.10.2026).
  const подписьСтроки = (s) => (s.split('\t')[сдвиг] || '').trim();
  // Перенос в ячейке: число строкой ниже подписи, сама строка — одно число.
  const числоРядом = (v, i, до) => числоВТексте(v, сырые[i])
    || (i + 1 < до && /^[\s\d.,]+$/.test(сырые[i + 1] || '') && числоВТексте(v, сырые[i + 1]));

  // Границы блоков: строки, у которых в НУЛЕВОЙ ячейке стоит подпись
  // наименования. Проверять вхождение подписи где угодно в строке нельзя:
  // слово «наименование» встречается и в шапке «Наименование поставщиков».
  const началаБлоков = [];
  for (let i = 0; i < сырые.length; i++) {
    const первая = подписьСтроки(сырые[i]);
    if (ПОДПИСИ_ПОЛЕЙ.имя.test(первая)) началаБлоков.push(i);
  }

  for (const п of позиции || []) {
    const имя = норм(п.name);
    // Цена, выведенная из суммы на всё количество (nmck-table.js, ценыИзСумм), сверяется по самой сумме: в строке документа стоит она.
    const цены = (п.prices || []).map((c) => (typeof c.сумма === 'number' ? c.сумма : c.value)).filter((v) => isFinite(v));

    if (имя.length < 3) {
      результаты.push({
        наименование: п.name,
        исход: ИСХОДЫ.НЕ_ПОДТВЕРЖДЕНО,
        причина: 'наименование короче трёх знаков — сверять нечего'
      });
      continue;
    }

    const подпись = подписьКолонки(п.name);
    if (подпись) {
      результаты.push({
        наименование: п.name,
        исход: ИСХОДЫ.НЕ_ПОДТВЕРЖДЕНО,
        подписьКолонки: подпись,
        причина: `это подпись колонки таблицы («${подпись}…»), а не товар`
      });
      continue;
    }

    // Блок, в котором наименование стоит: либо в самой строке подписи, либо
    // строкой ниже — в реальном документе встречаются оба вида.
    //
    // БЛОКОВ С ОДНИМ НАИМЕНОВАНИЕМ БЫВАЕТ НЕСКОЛЬКО. На живом документе
    // 13.10.2026 «Подставка для книг, металл» стоит дважды — с разным
    // количеством и ценой. Проверка брала первый блок, и вторая позиция
    // не сходилась, хотя разобрана верно. Поэтому перебираются все блоки
    // с этим наименованием и берётся тот, где сошлось больше.
    const кандидаты = [];
    for (let b = 0; b < началаБлоков.length; b++) {
      const от = началаБлоков[b];
      const до = b + 1 < началаБлоков.length ? началаБлоков[b + 1] : сырые.length;
      const вПодписи = норм(сырые[от]).includes(имя);
      const вСледующей = от + 1 < до && норм(сырые[от + 1]).includes(имя);
      if (вПодписи || вСледующей) кандидаты.push({ от, до });
    }

    const вБлоке = (блок) => {
      let количествоТут = п.quantity === null || п.quantity === undefined ? null : false;
      let ценаТут = цены.length === 0 ? null : false;
      for (let i = блок.от; i < блок.до; i++) {
        const первая = подписьСтроки(сырые[i]);
        if (количествоТут === false && ПОДПИСИ_ПОЛЕЙ.количество.test(первая)
          && числоРядом(п.quantity, i, блок.до)) {
          количествоТут = true;
        }
        // Порядок как в разборе: «без учёта НДС» проверяется раньше, иначе
        // подтверждением цены с НДС стала бы строка цены без НДС.
        if (ПОДПИСИ_ПОЛЕЙ.ценаБезНДС.test(первая)) continue;
        if (ценаТут === false && ПОДПИСИ_ПОЛЕЙ.цена.test(первая)
          && цены.some((ц) => числоВТексте(ц, сырые[i]))) {
          ценаТут = true;
        }
      }
      return { количествоТут, ценаТут, промахов: (количествоТут === false) + (ценаТут === false) };
    };

    let блок = null;
    let лучшее = null;
    for (const к of кандидаты) {
      const р = вБлоке(к);
      if (!лучшее || р.промахов < лучшее.промахов) { лучшее = р; блок = к; }
    }

    if (!блок) {
      результаты.push({
        наименование: п.name,
        исход: норм(текст).includes(имя) ? ИСХОДЫ.НЕ_ПРОВЕРЕНО : ИСХОДЫ.НЕ_ПОДТВЕРЖДЕНО,
        причина: норм(текст).includes(имя)
          ? 'наименование в документе есть, но не в строке с подписью наименования товара'
          : 'наименования нет в тексте документа дословно'
      });
      continue;
    }

    const { количествоТут, ценаТут } = лучшее;

    const недостаёт = [];
    if (количествоТут === false) недостаёт.push('количество');
    if (ценаТут === false) недостаёт.push('цена');

    результаты.push({
      наименование: п.name,
      количество: п.quantity === null || п.quantity === undefined ? null : п.quantity,
      исход: недостаёт.length === 0 ? ИСХОДЫ.ПОДТВЕРЖДЕНО : ИСХОДЫ.НЕ_ПОДТВЕРЖДЕНО,
      причина: недостаёт.length === 0
        ? 'наименование, количество и цена стоят в одном блоке документа'
        : `в блоке товара не нашлось: ${недостаёт.join(', ')} — возможен сдвиг блока`,
      строка: сырые[блок.от].replace(/\s+/g, ' ').slice(0, 160)
    });
  }

  return результаты;
}

/**
 * СВЕРКА ПОЗИЦИЙ С ИСХОДНЫМ ДОКУМЕНТОМ.
 *
 * Главный вопрос: взяты ли наименование, количество и цена ИЗ ОДНОЙ строки
 * таблицы. Проверка построчная именно поэтому: сдвиг колонки на одну вправо
 * даёт правдоподобную позицию с чужим количеством, и при сверке по всему
 * тексту сразу такая ошибка прошла бы — оба значения в документе есть, просто
 * в разных строках.
 *
 * @param {Array} позиции результат parseNmckTable
 * @param {string} текст текст документа, из которого они разобраны
 */
function сверитьПозиции(позиции, текст, опции = {}) {
  // В ПЕРЕВЁРНУТОЙ ТАБЛИЦЕ ПОСТРОЧНАЯ СВЕРКА НЕПРИМЕНИМА, и это не мелочь.
  // Там наименование, количество и цена лежат в РАЗНЫХ строках по устройству
  // документа, поэтому требование «всё в одной строке» забраковало бы верный
  // разбор целиком. Ошибка в сторону отказа: клиент не получил бы расчёта по
  // годной закупке и узнать об этом ему было бы неоткуда.
  if (опции.перевёрнутая) return сверитьПозицииБлоками(позиции, текст, опции.сдвиг || 0);

  const строки = String(текст || '').split(/\r?\n/).map(норм).filter((с) => с.length > 0);
  const весь = норм(текст);
  const результаты = [];

  for (const п of позиции || []) {
    const имя = норм(п.name);
    // Цена, выведенная из суммы на всё количество (nmck-table.js, ценыИзСумм), сверяется по самой сумме: в строке документа стоит она.
    const цены = (п.prices || []).map((c) => (typeof c.сумма === 'number' ? c.сумма : c.value)).filter((v) => isFinite(v));

    // Позиция собрана из текста ТЗ (закупка одного товара): наименование —
    // объект закупки, его в тексте дословно может и не быть. Сверяется
    // цитата с количеством — она обязана стоять в документе буква в букву.
    if (п.цитата) {
      const есть = весь.includes(норм(п.цитата));
      результаты.push({
        наименование: п.name,
        количество: п.quantity,
        исход: есть ? ИСХОДЫ.ПОДТВЕРЖДЕНО : ИСХОДЫ.НЕ_ПОДТВЕРЖДЕНО,
        причина: есть
          ? `количество подтверждено строкой документа: «${String(п.цитата).slice(0, 80)}»`
          : 'строки с количеством в документе нет'
      });
      continue;
    }

    if (имя.length < 3) {
      результаты.push({
        наименование: п.name,
        исход: ИСХОДЫ.НЕ_ПОДТВЕРЖДЕНО,
        причина: 'наименование короче трёх знаков — сверять нечего'
      });
      continue;
    }

    // Подпись колонки проверяется ПЕРВОЙ: искать её в документе бессмысленно,
    // она там, конечно, есть — она и есть часть таблицы.
    const подпись = подписьКолонки(п.name);
    if (подпись) {
      результаты.push({
        наименование: п.name,
        исход: ИСХОДЫ.НЕ_ПОДТВЕРЖДЕНО,
        подписьКолонки: подпись,
        причина: `это подпись колонки таблицы («${подпись}…»), а не товар — `
          + 'разбор взял шапку за позицию'
      });
      continue;
    }

    const подходящие = строки.filter((с) => с.includes(имя));

    if (подходящие.length === 0) {
      // Наименование в документе может быть разорвано переносом внутри ячейки:
      // тогда оно есть в тексте, но ни в одной отдельной строке целиком.
      // Это слабее полного подтверждения, но не выдумка.
      результаты.push({
        наименование: п.name,
        исход: весь.includes(имя) ? ИСХОДЫ.НЕ_ПРОВЕРЕНО : ИСХОДЫ.НЕ_ПОДТВЕРЖДЕНО,
        причина: весь.includes(имя)
          ? 'наименование есть в документе, но не в одной строке — строка таблицы собрана из нескольких'
          : 'наименования нет в тексте документа дословно'
      });
      continue;
    }

    // Строка считается сопоставленной, только если в ней же стоят количество
    // и хотя бы одна из цен позиции.
    let лучшая = null;
    // Количество, сложенное из нескольких строк (товар по разным адресам),
    // в строке с наименованием стоит своим первым слагаемым, а не суммой.
    const проверяемое = Array.isArray(п.слагаемые) && п.слагаемые.length ? п.слагаемые[0] : п.quantity;
    // Совместная закупка: количество — сумма колонок заказчиков, и в строке
    // обязаны стоять ВСЕ слагаемые (шприцы 32616483363, 19.10.2026).
    const вСтроке = Array.isArray(п.слагаемыеВСтроке) && п.слагаемыеВСтроке.length ? п.слагаемыеВСтроке : null;
    for (const с of подходящие) {
      const количествоТут = вСтроке ? вСтроке.every((ч) => числоВТексте(ч, с))
        : проверяемое === null || проверяемое === undefined
          ? null : числоВТексте(проверяемое, с);
      const ценаТут = цены.length === 0 ? null : цены.some((ц) => числоВТексте(ц, с));
      const очки = (количествоТут === true ? 2 : 0) + (ценаТут === true ? 1 : 0);
      if (!лучшая || очки > лучшая.очки) лучшая = { с, количествоТут, ценаТут, очки };
    }

    const недостаёт = [];
    if (лучшая.количествоТут === false) недостаёт.push('количество');
    if (лучшая.ценаТут === false) недостаёт.push('цена');

    результаты.push({
      наименование: п.name,
      количество: п.quantity === null || п.quantity === undefined ? null : п.quantity,
      исход: недостаёт.length === 0 ? ИСХОДЫ.ПОДТВЕРЖДЕНО : ИСХОДЫ.НЕ_ПОДТВЕРЖДЕНО,
      причина: недостаёт.length === 0
        ? (лучшая.количествоТут === null
          ? 'наименование и цена стоят в одной строке; количество в документе не указано'
          : 'наименование, количество и цена стоят в одной строке документа')
        : `в строке с наименованием не нашлось: ${недостаёт.join(', ')} — возможен сдвиг колонки`,
      строка: лучшая.с.slice(0, 160)
    });
  }

  return результаты;
}

/**
 * ГОДЕН ЛИ РАЗБОР ЦЕЛИКОМ.
 *
 * Отдельный вердикт поверх отдельных позиций, и он нужен потому, что
 * проверка «каждая позиция по отдельности» пропустила негодный разбор целиком:
 * строки настоящие, а таблица прочитана не та.
 *
 * Три признака, каждый найден на живом прогоне, а не придуман:
 *
 *   — ПОДПИСИ КОЛОНОК СРЕДИ ПОЗИЦИЙ. Одна может попасться и в нормальном
 *     документе; три означают, что разбор читает шапку как данные;
 *   — НИ У ОДНОЙ ПОЗИЦИИ НЕТ КОЛИЧЕСТВА. Колонка количества не сопоставлена.
 *     Самый сильный признак из трёх: без количества смета не считается
 *     вообще, то есть расчёта нет, а 172 строки выглядят как результат;
 *   — ПОДТВЕРЖДЕНО МЕНЬШЕ ДВУХ ТРЕТЕЙ. Разбор местами попал, местами нет,
 *     и какая часть сметы настоящая — неизвестно.
 *
 * Негодный разбор это НЕ повод тихо выдать смету с пометкой. Пометку клиент
 * прочитает после того, как посмотрит на сумму. Поэтому вердикт отдельный,
 * и по нему расчёт останавливается до человека.
 */
function годностьРазбора(результаты, позиции = []) {
  const всего = результаты.length;
  if (!всего) return { годен: true, причины: [], подписей: 0 };

  const подписей = результаты.filter((р) => р.подписьКолонки).length;
  const подтверждено = результаты.filter((р) => р.исход === ИСХОДЫ.ПОДТВЕРЖДЕНО).length;
  const сКоличеством = (позиции || [])
    .filter((п) => п.quantity !== null && п.quantity !== undefined).length;

  const причины = [];
  if (подписей >= 3) {
    причины.push(`${подписей} из ${всего} «позиций» — подписи колонок таблицы: `
      + 'разбор прочитал шапку как данные');
  }
  if (позиции.length >= 3 && сКоличеством === 0) {
    причины.push(`ни у одной из ${позиции.length} позиций нет количества — `
      + 'колонка количества не сопоставлена, смета по такому разбору не считается');
  }
  if (подтверждено * 3 < всего * 2) {
    причины.push(`со строкой документа сошлось ${подтверждено} из ${всего} — `
      + 'меньше двух третей, какая часть сметы настоящая, неизвестно');
  }

  return { годен: причины.length === 0, причины, подписей, подтверждено, всего };
}

/**
 * СВЕРКА ЦИТАТЫ ПОСТАВЩИКА С ЕГО СТРАНИЦЕЙ.
 *
 * Три исхода, и различать их обязательно.
 *
 * Страница не пришла — «не проверено», а не «выдумано». Сайт мог лежать,
 * ответить отказом, отдать содержимое скриптом. Называть это выдумкой
 * означало бы выбрасывать настоящих поставщиков, то есть делать ровно ту
 * ошибку в сторону отказа, из-за которой клиент проходит мимо выгодного
 * тендера.
 *
 * Цитаты на странице нет, а число цены есть — отдельный исход. Значит модель
 * пересказала строку своими словами: цена на странице стоит, дословность
 * нарушена. Это замечание к формату ответа, а не к цене.
 *
 * @param {object} поставщик {name, url, price, evidence, priceNote}
 * @param {string|null} текстСтраницы текст страницы или null, если не пришла
 * @param {string} [почему] причина, по которой страница не пришла
 */
/**
 * ЦЕНЫ ИЗ ДАННЫХ РАЗМЕТКИ СТРАНИЦЫ (21.10.2026). Магазины электрики рисуют
 * цену скриптом: в видимом тексте числа нет, и сверка давала «не
 * подтверждено» на 16 ценах из 25 (0316100017526000044). Но цену товара
 * магазин кладёт в стандартные поля: `"price": "105.40"` (JSON-LD),
 * `itemprop="price" content="…"`, `product:price:amount`, `data-price`.
 * Берутся только эти поля - не любые числа из скриптов: списки цен других
 * товаров («"283276":"354.57"») подтверждением не считаются.
 *
 * @returns {number[]} различные цены из разметки
 */
function ценыИзРазметки(html) {
  const т = String(html || '');
  const набор = new Set();
  const шаблоны = [
    /"price"\s*:\s*"?\s*(\d[\d\s]*(?:[.,]\d{1,2})?)\s*"?/gi,
    /itemprop=["']price["'][^>]*?content=["']\s*(\d[\d\s]*(?:[.,]\d{1,2})?)/gi,
    /content=["']\s*(\d[\d\s]*(?:[.,]\d{1,2})?)["'][^>]*?itemprop=["']price["']/gi,
    /product:price:amount["'][^>]*?content=["']\s*(\d[\d\s]*(?:[.,]\d{1,2})?)/gi,
    /data-price=["']\s*(\d[\d\s]*(?:[.,]\d{1,2})?)/gi
  ];
  for (const ш of шаблоны) {
    for (const m of т.matchAll(ш)) {
      const ч = Number(m[1].replace(/\s/g, '').replace(',', '.'));
      if (isFinite(ч) && ч > 0) набор.add(Math.round(ч * 100) / 100);
    }
  }
  return [...набор];
}

/** Сколько разных цен в разметке - больше этого значит каталог, совпадение не доказательство. */
const РАЗМЕТКА_ЦЕН_ПРЕДЕЛ = 5;

function сверитьПоставщика(поставщик, текстСтраницы, почему = '', ценыРазметки = []) {
  const общее = {
    поставщик: (поставщик && поставщик.name) || '(без названия)',
    ссылка: (поставщик && поставщик.url) || '',
    цена: поставщик ? поставщик.price : null
  };

  if (текстСтраницы === null || текстСтраницы === undefined) {
    return { ...общее, исход: ИСХОДЫ.НЕ_ПРОВЕРЕНО, причина: почему || 'страница не получена' };
  }

  const страница = норм(текстСтраницы);
  if (страница.length < 200) {
    return {
      ...общее,
      исход: ИСХОДЫ.НЕ_ПРОВЕРЕНО,
      причина: `со страницы снято ${страница.length} знаков текста — содержимое рисуется скриптом либо отдан отказ`
    };
  }

  const цитата = норм(поставщик && поставщик.evidence);
  const цена = ценаНаСтранице(общее.цена, страница);
  const безЦены = общее.цена === null || общее.цена === undefined;

  if (цитата.length >= 8 && страница.includes(цитата)) {
    return {
      ...общее,
      исход: ИСХОДЫ.ПОДТВЕРЖДЕНО,
      сила: 'дословно',
      причина: безЦены
        ? 'дословная строка найдена на странице — подтверждено наличие товара, цены у поставщика нет'
        : 'дословная строка найдена на странице'
    };
  }

  if (цена === 'точно') {
    return {
      ...общее,
      исход: ИСХОДЫ.ПОДТВЕРЖДЕНО,
      сила: 'число',
      причина: 'дословной строки на странице нет, но цена стоит на ней точно — модель пересказала строку'
    };
  }

  // ЦЕНА В ДАННЫХ РАЗМЕТКИ: магазин рисует её скриптом. Точное совпадение
  // (до копейки), цена не короче трёх цифр или с копейками, и разных цен на
  // странице не больше предела - иначе это каталог.
  if (!безЦены && Array.isArray(ценыРазметки) && ценыРазметки.length) {
    const ц = Math.round(Number(общее.цена) * 100) / 100;
    const достаточноДлинная = String(Math.trunc(ц)).length >= 3 || ц % 1 !== 0;
    if (ценыРазметки.includes(ц) && достаточноДлинная) {
      if (ценыРазметки.length <= РАЗМЕТКА_ЦЕН_ПРЕДЕЛ) {
        return {
          ...общее,
          исход: ИСХОДЫ.ПОДТВЕРЖДЕНО,
          сила: 'разметка',
          причина: 'цена есть в данных страницы (поле цены товара); в видимом тексте её рисует скрипт'
        };
      }
      return {
        ...общее,
        исход: ИСХОДЫ.НЕ_ПРОВЕРЕНО,
        причина: `цена есть в данных страницы, но там ${ценыРазметки.length} разных цен - похоже на каталог, совпадение ничего не доказывает`
      };
    }
  }

  // КОРОТКОЕ ЧИСЛО НИЧЕГО НЕ ДОКАЗЫВАЕТ. На живом прогоне 13.10.2026 цена
  // «4,2 ₽» считалась подтверждённой, потому что на странице каталога нашлась
  // цифра 4. Она там есть всегда. Такое совпадение — «не проверено».
  if (цена === 'слабо') {
    return {
      ...общее,
      исход: ИСХОДЫ.НЕ_ПРОВЕРЕНО,
      причина: 'дословной строки нет; число цены на странице встречается, но оно слишком '
        + 'короткое, чтобы совпадение что-то доказывало'
    };
  }

  return {
    ...общее,
    исход: ИСХОДЫ.НЕ_ПОДТВЕРЖДЕНО,
    причина: безЦены
      ? 'дословной строки на странице нет'
      : 'на странице нет ни дословной строки, ни числа цены'
  };
}

/**
 * Насколько надёжно цена найдена на странице: 'точно' | 'слабо' | 'нет'.
 *
 * Цена с копейками ищется ВМЕСТЕ с копейками («21,56», «21.56»); нулевой хвост
 * допускается («4,2» и «4,20» — одно число). Цена без копеек считается точной
 * от трёх цифр. Одно- и двузначное целое на странице каталога встретится
 * почти наверняка — в количествах, размерах, номерах, — поэтому оно «слабо».
 */
function ценаНаСтранице(значение, текст) {
  if (значение === null || значение === undefined || !isFinite(значение)) return 'нет';
  const число = Math.abs(Number(значение));
  const целое = String(Math.trunc(число));
  const дробь = (число.toFixed(2).split('.')[1] || '').replace(/0+$/, '');
  const т = норм(текст);
  const тело = целое.split('').join('[\\s.]?');

  if (дробь) {
    const точный = new RegExp(`(?<![\\d,.])${тело}[.,]${дробь}0?(?!\\d)`);
    if (точный.test(т)) return 'точно';
    return числоВТексте(значение, т) ? 'слабо' : 'нет';
  }

  if (!числоВТексте(значение, т)) return 'нет';
  return целое.length >= 3 ? 'точно' : 'слабо';
}

/**
 * ПЕРЕСЧЁТ ИТОГОВ НЕЗАВИСИМО ОТ `pricing.js`.
 *
 * Формулы выписаны здесь заново, а не взяты вызовом: вызов той же функции
 * подтвердил бы только то, что она работает одинаково два раза. Ошибку
 * в самой формуле ловит лишь второй, отдельно написанный счёт.
 */
function сверитьАрифметику(estimate) {
  const замечания = [];
  const строки = (estimate && estimate.rows) || [];

  let сумма = 0;
  let сЦеной = 0;
  for (const r of строки) {
    if (r.priceForCalc === null || r.priceForCalc === undefined) continue;
    сЦеной += 1;

    if (r.min !== null && r.max !== null
      && (r.priceForCalc < r.min - 0.005 || r.priceForCalc > r.max + 0.005)) {
      замечания.push(`«${r.name}»: цена в расчёте ${r.priceForCalc} вне найденного `
        + `диапазона ${r.min}–${r.max}`);
    }

    if (r.quantity === null || r.quantity === undefined) {
      if (r.total !== null) замечания.push(`«${r.name}»: количество неизвестно, а итог по строке посчитан`);
      continue;
    }

    const должно = Math.round(r.priceForCalc * r.quantity * 100) / 100;
    if (Math.abs((r.total || 0) - должно) > 0.02) {
      замечания.push(`«${r.name}»: итог по строке ${r.total}, а цена × количество даёт ${должно}`);
    }
    сумма += должно;
  }

  сумма = Math.round(сумма * 100) / 100;
  if (Math.abs((estimate.total || 0) - сумма) > 0.02) {
    замечания.push(`итог закупки ${estimate.total}, а сумма строк даёт ${сумма}`);
  }

  // НОЛЬ, СОШЁДШИЙСЯ С НУЛЁМ, — НЕ «СХОДИТСЯ».
  // Найдено на живом прогоне 12.10.2026: 172 строки, у каждой цена есть,
  // количества нет ни у одной, итог закупки ноль. Пересчёт дал тот же ноль,
  // и проверка напечатала «сходится» — то есть подтвердила отсутствие
  // расчёта как успешный расчёт.
  if (сЦеной > 0 && сумма === 0) {
    замечания.push(`строк с ценой ${сЦеной}, а итог закупки ноль — `
      + 'ни у одной позиции нет количества, считать сумму не из чего');
  }
  if (сЦеной !== estimate.pricedCount) {
    замечания.push(`строк с ценой ${сЦеной}, а в смете указано ${estimate.pricedCount}`);
  }
  if (estimate.totalMin !== undefined && estimate.totalMax !== undefined
    && estimate.totalMin > estimate.totalMax + 0.02) {
    замечания.push(`нижняя граница итога ${estimate.totalMin} выше верхней ${estimate.totalMax}`);
  }

  return { сумма, замечания };
}

/**
 * ПРОВЕРКА ТЕКСТА, КОТОРЫЙ УВИДИТ КЛИЕНТ.
 *
 * Два класса ошибок, оба уже случались в этом проекте и оба тихие:
 * `null` и `NaN`, доехавшие до сообщения, и ноль, подставленный вместо
 * неизвестного значения. Второе опаснее: «Доставка: 0 ₽» читается как
 * бесплатная доставка, а не как отсутствие данных.
 */
function сверитьТекст(подпись, итоги = {}) {
  const замечания = [];
  const т = String(подпись || '');

  for (const слово of ['null', 'undefined', 'NaN', 'Infinity']) {
    if (т.includes(слово)) замечания.push(`в тексте для клиента встречается «${слово}»`);
  }
  if (/-0\s*₽|−0\s*₽/.test(т)) замечания.push('в тексте для клиента есть «−0 ₽»');

  // Границу слева пишем явной проверкой «перед нулём не цифра», а не `\b`:
  // `\b` рядом с кириллицей в этом проекте уже четыре раза молча ничего
  // не находил, и отдельная проверка по исходникам такие шаблоны ловит.
  if (итоги && итоги.закупкаИзвестна === false) {
    if (/доставка[^\n]*?(?<![\d,.])0\s*₽/i.test(т)) {
      замечания.push('стоимость закупки неизвестна, а доставка напечатана нулём');
    }
    if (/безубыточн[а-яё]*[^\n]*?(?<![\d,.])0\s*₽/i.test(т)) {
      замечания.push('стоимость закупки неизвестна, а безубыточность напечатана нулём');
    }
  }

  return замечания;
}

/**
 * Одна строка итога самопроверки — для журнала прогона и для сообщения.
 *
 * Размер выборки называется всегда: «подтверждено 2 из 2» и «подтверждено
 * 2 из 40» — разные утверждения, и скрывать знаменатель нельзя.
 */
function сводка(позиции = [], поставщики = []) {
  const счёт = (список, исход) => список.filter((r) => r.исход === исход).length;
  const части = [];

  if (позиции.length) {
    части.push(`позиции: ${счёт(позиции, ИСХОДЫ.ПОДТВЕРЖДЕНО)} из ${позиции.length} `
      + 'сверены со строкой документа');
  }
  if (поставщики.length) {
    части.push(`цены поставщиков: ${счёт(поставщики, ИСХОДЫ.ПОДТВЕРЖДЕНО)} из ${поставщики.length} `
      + 'подтверждены на странице');
  }
  return части.length ? 'самопроверка — ' + части.join('; ') : 'самопроверка: сверять нечего';
}

/**
 * СВЕРКА СУММЫ ПОЗИЦИЙ С НМЦК — найдено 16.10.2026.
 *
 * Обоснование НМЦК — это сама НМЦК, разложенная по позициям: заказчик вывел
 * начальную цену из этих количеств и цен. Значит сумма «количество × цена»
 * по разобранной таблице обязана лечь рядом с НМЦК. Если нет — количество
 * или цена взяты не из той колонки, даже когда каждая строка по отдельности
 * сошлась с документом.
 *
 * Живой случай: закупка 32616468091, 153 позиции, все «подтверждены»
 * построчно, сумма около 59 тыс. ₽ при НМЦК 1,54 млн. Клиенту ушло бы
 * «рентабельность 89,7%». Построчная сверка такое не ловит в принципе.
 *
 * Проверка не наша и не модели — число заказчика из карточки. Денег не стоит.
 *
 * Допуск — вдвое в обе стороны. Это граница здравого смысла, не измерение:
 * НДС (×1,22), разница между минимальной и средней ценой и округления дают
 * десятки процентов, но не разы.
 *
 * @returns {{проверено: boolean, сходится: boolean|null, мин: number|null,
 *   макс: number|null, причина: string}}
 */
function сверкаСНмцк(позиции, нмцк) {
  const ДОПУСК = 2;
  const нет = (причина) => ({ проверено: false, сходится: null, мин: null, макс: null, причина });
  if (!(typeof нмцк === 'number' && нмцк > 0)) return нет('НМЦК неизвестна');
  const список = позиции || [];
  if (!список.length) return нет('позиций нет');
  const годна = (p) => typeof p.quantity === 'number' && p.quantity > 0
    && typeof p.min === 'number' && p.min > 0;
  // Только когда цены и количества есть у ВСЕХ позиций: сумма части
  // таблицы с НМЦК не сравнивается.
  if (!список.every(годна)) return нет('не у всех позиций есть количество и цена');

  let мин = 0;
  let макс = 0;
  for (const p of список) {
    мин += p.quantity * p.min;
    макс += p.quantity * (typeof p.max === 'number' && p.max > 0 ? p.max : p.min);
  }
  мин = Math.round(мин);
  макс = Math.round(макс);
  const р = (n) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');

  if (макс * ДОПУСК < нмцк) {
    return { проверено: true, сходится: false, мин, макс,
      причина: `сумма позиций по обоснованию ${р(мин)}–${р(макс)} ₽ меньше НМЦК `
        + `${р(Math.round(нмцк))} ₽ больше чем вдвое — количество или цена взяты не из той колонки` };
  }
  if (мин > нмцк * ДОПУСК) {
    return { проверено: true, сходится: false, мин, макс,
      причина: `сумма позиций по обоснованию ${р(мин)}–${р(макс)} ₽ больше НМЦК `
        + `${р(Math.round(нмцк))} ₽ больше чем вдвое — количество или цена взяты не из той колонки` };
  }
  return { проверено: true, сходится: true, мин, макс,
    причина: `сумма позиций ${р(мин)}–${р(макс)} ₽ согласуется с НМЦК ${р(Math.round(нмцк))} ₽` };
}

