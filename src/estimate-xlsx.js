/**
 * Лист «Мои издержки» (владелец 15.11.2026: работы — и почасовая, и сдельная,
 * оба варианта предоставляем; клиент не обязан считать бухгалтерию сам).
 *
 * Структура с пустыми ячейками вместо выдуманных чисел: окладная бухгалтерия
 * бизнеса клиента в контрактную смету не входит, но его затраты на исполнение
 * — входят. Клиент вписывает три-числа-под-закупку, ИТОГО сам падает в
 * «Прочие расходы» листа «Расчёт». Строки — категории из живых разборов
 * (комиссия гарантии 2–5%, оператор площадки) плюс оба способа оплаты работ.
 */
function издержкиSheet(подстановки = []) {
  const изПрайса = new Map(подстановки.map((п) => [п.статья, п]));
  const b = sheetBuilder();
  b.push([{ v: 'МОИ ИЗДЕРЖКИ НА ИСПОЛНЕНИЕ', s: STYLE.ЗАГОЛОВОК_ДОКУМЕНТА }]);
  b.push([{ v: 'Впишите суммы под эту закупку. Итог автоматически попадёт в «Прочие расходы» '
    + 'на листе «Расчёт» — весь расчёт пересчитается. Что нашлось в вашем прайсе — '
    + 'уже подставлено и подписано. Не нужная строка — оставьте пустой.', s: STYLE.ПОЯСНЕНИЕ }]);
  b.blank();
  b.push([{ v: 'Статья', s: STYLE.ШАПКА_ТАБЛИЦЫ }, { v: 'Сумма, ₽', s: STYLE.ШАПКА_ТАБЛИЦЫ }]);
  const строки = [
    ['Работы своей бригады, почасовая оплата', 'часы × ставка, например 120 ч × 450 ₽'],
    ['Работы сдельно (договор с бригадой/подрядчиком)', 'за результат: за точку, м², объект'],
    ['Транспорт и развоз бригады', ''],
    ['Проживание и суточные', ''],
    ['Снабжение: расходники и мелочи', ''],
    ['Подготовка и подача заявки (оператор площадки)', ''],
    ['Банковская гарантия (комиссия 2–5% от обеспечения)', ''],
    ['Своё', '']
  ];
  const first = b.rows.length + 1;
  for (const [статья, подсказка] of строки) {
    const подставлено = изПрайса.get(статья);
    b.push([
      { v: статья + (подставлено ? ` — ${подставлено.источник}` : подсказка ? ` — ${подсказка}` : ''), s: STYLE.ПЕРЕНОС },
      подставлено ? { v: подставлено.цена, s: STYLE.ДЕНЬГИ } : { v: null, s: STYLE.ДЕНЬГИ }
    ]);
  }
  const last = b.rows.length;
  const итог = b.push([
    { v: 'ИТОГО издержки', s: STYLE.ЖИРНЫЙ },
    { f: `SUM(B${first}:B${last})`, s: STYLE.ДЕНЬГИ_ИТОГ }
  ], 'итого_издержек');
  return { sheet: { name: 'Мои издержки', columns: [{ width: 62 }, { width: 18 }], rows: b.rows }, итогRow: итог };
}

