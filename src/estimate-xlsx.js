/**
 * Собирает книгу Excel по одной закупке.
 *
 * @param {object} data
 * @param {object} data.tender карточка из parseSearchPage
 * @param {object} data.estimate результат buildEstimate из pricing.js
 * @param {object} [data.logistics] результат resolveLogistics/totalLogistics
 * @param {object} [data.economics] настройки клиента
 * @param {object} [data.scored] результат scoreTender — нужен для обеспечения
 * @returns {{buffer: Buffer, fileName: string}}
 */
function buildEstimateWorkbook(data) {
  const estimate = data.estimate || { rows: [], issues: [], complete: false, pricedCount: 0 };
  const pos = positionsSheet(estimate);
  const издержки = издержкиSheet(data.издержкиИзПрайса || []);
  const calc = calcSheet({ ...data, estimate, ссылкаИздержек: `'Мои издержки'!B${издержки.итогRow}` }, `Позиции!E${pos.totalRow}`);

  const buffer = writeXlsx([
    calc,
    pos.sheet,
    sourcesSheet(estimate),
    издержки.sheet,
    helpSheet({ ...data, estimate })
  ]);

  // Имя файла: номер закупки первым, чтобы в папке клиента они сортировались
  // осмысленно и искались поиском по номеру.
  const num = String((data.tender && data.tender.number) || 'без-номера').replace(/[^\d A-Za-zА-Яа-я-]/g, '');
  return { buffer, fileName: `Расчёт ${num}.xlsx` };
}

/**
 * Те же числа, что считает файл формулами — но посчитанные здесь.
 *
 * ЗАЧЕМ. Сообщение в Telegram должно отвечать на вопрос «идти или нет»
 * без открытия файла: что покупают, за сколько, сколько заработаем и сколько
 * денег надо вложить. Человек читает чат с телефона, и если там только
 * «позиций 2, закупка 328 тысяч», решение по нему принять нельзя.
 *
 * ВАЖНО ПРО ДУБЛИРОВАНИЕ. Это повторение арифметики, которая в файле живёт
 * формулами. Расхождение между сообщением и файлом — худший вид ошибки:
 * клиент увидит в чате одно, в таблице другое и перестанет верить обоим.
 * Поэтому формулы и эта функция меняются только вместе, а числа сверены
 * тестом (`tests/test-estimate-xlsx.js`, раздел про итоги).
 *
 * Логистика при неизвестной цене даёт ДВЕ границы, и прибыль возвращается
 * вилкой: по худшей оценке доставки и по лучшей.
 */
function посчитатьИтоги(data) {
  const { tender = {}, estimate = {}, logistics = {}, economics = {} } = data;

  const нмцк = typeof tender.price === 'number' && Number.isFinite(tender.price) ? tender.price : null;

  // ОЖИДАЕМОЕ СНИЖЕНИЕ НЕ ИМЕЕТ ЗНАЧЕНИЯ ПО УМОЛЧАНИЮ — И НЕ ДОЛЖНО ИМЕТЬ.
  //
  // Здесь стояло 0.12. Числа под этим не было: я взял его как «средний
  // ориентир», то есть выдумал. Владелец это поймал 04.10.2026: «раз
  // обоснования нет, зачем ты его пишешь». Он прав, и это прямое нарушение
  // правила проекта — расчёт не выдаёт за факт то, что не измерено.
  //
  // Чем это опасно именно здесь. Снижение определяет цену победы, то есть ВСЮ
  // выручку. Ошибка в нём переворачивает вывод о выгодности целиком, причём
  // в опасную сторону: заниженное снижение делает убыточный тендер выгодным
  // на вид. Это худший вид ошибки в продукте.
  //
  // Теперь: нет значения — нет цены победы и нет прибыли. Вместо них считается
  // БЕЗУБЫТОЧНАЯ ЦЕНА, которой допущение не нужно вовсе: расходы известны, и
  // цена, ниже которой контракт убыточен, выводится из них точно.
  //
  // Откуда значение берётся законно: либо клиент называет его сам под свою
  // нишу на онбординге, либо оно измеряется по протоколам прошлых закупок той
  // же категории (Фаза 3; доступность протоколов проверена 26.09.2026).
  const снижениеЗадано = typeof economics.expectedDiscount === 'number'
    && Number.isFinite(economics.expectedDiscount);
  const снижениеДоля = снижениеЗадано ? economics.expectedDiscount : null;
  const ставкаНалога = typeof economics.taxRate === 'number' ? economics.taxRate : 0.06;
  // ОБЕСПЕЧЕНИЯ — ТОЛЬКО ФАКТ ИЗ КАРТОЧКИ (владелец 15.11.2026: «мы не
  // пишем допущение»). Ставки приходят сюда только из карточки закупки;
  // не указаны — null: суммы не выводятся, в «деньги» не входят, клиенту
  // прямо сказано проверить документацию. Раньше здесь молча жили 1% и 5%.
  const ставкаЗаявки = typeof economics.bidSecurityRate === 'number' && Number.isFinite(economics.bidSecurityRate)
    ? economics.bidSecurityRate : null;
  const ставкаКонтракта = typeof economics.contractSecurityRate === 'number' && Number.isFinite(economics.contractSecurityRate)
    ? economics.contractSecurityRate : null;
  const прочее = typeof economics.otherCosts === 'number' ? economics.otherCosts : 0;

  // НЕИЗВЕСТНАЯ СТОИМОСТЬ ЗАКУПКИ — ЭТО НЕ НОЛЬ.
  //
  // Найдено на живом прогоне 07.10.2026. В закупке «Поставка канцелярских
  // товаров» таблица позиций не нашлась ни в одном файле, цен не было ни одной,
  // и `estimate.total` оказался нулём. Дальше ноль разошёлся по всему расчёту:
  // доставка «3–8% от закупки» дала 0 ₽, и клиент прочитал бы «Доставка: 0 ₽»
  // как бесплатную доставку; требуемый объём средств вышел 4 575 ₽ с подписью
  // «закупка, доставка, обеспечение…», хотя закупки и доставки в нём нет вовсе;
  // безубыточная цена получилась нулём, то есть «выгодно при любой цене».
  //
  // Это ТОТ ЖЕ класс ошибки, что уже ловили со снижением цены: отсутствие
  // данных молча превратилось в число, числа выглядят настоящими, ничего не
  // падает. Правило прежнее — проверяется ФЛАГ, а не значение.
  const закупкаИзвестна = typeof estimate.total === 'number'
    && Number.isFinite(estimate.total) && estimate.total > 0;
  const закупка = закупкаИзвестна ? estimate.total : 0;

  // Цена победы существует только если снижение задано. Проверять именно
  // снижениеЗадано, а не null: выражение (1 - null) в JavaScript равно 1, то
  // есть расчёт молча решил бы, что цену никто не снижал, и назвал бы ценой
  // победы саму НМЦК. Ошибка не падает и выглядит как результат.
  const ценаПобеды = (нмцк === null || !снижениеЗадано)
    ? null
    : round2(нмцк * (1 - снижениеДоля));

  const логИзвестна = typeof logistics.amount === 'number' && Number.isFinite(logistics.amount);
  const доляМин = typeof economics.logisticsMinPct === 'number' ? economics.logisticsMinPct : 3;
  const доляМакс = typeof economics.logisticsMaxPct === 'number' ? economics.logisticsMaxPct : 8;
  // Вилка доставки считается ОТ СТОИМОСТИ ЗАКУПКИ. Неизвестна закупка —
  // неизвестна и доставка: «0 ₽» здесь означало бы «везут бесплатно».
  const логМакс = логИзвестна ? logistics.amount
    : (закупкаИзвестна ? round2(закупка * доляМакс / 100) : null);
  const логМин = логИзвестна ? logistics.amount
    : (закупкаИзвестна ? round2(закупка * доляМин / 100) : null);

  const налог = ценаПобеды === null ? null : round2(ценаПобеды * ставкаНалога);

  // ДИАПАЗОН ЗАКУПКИ — когда источники расходятся, показываем оба края.
  //
  // Требование владельца 04.10.2026: «если из разных источников результаты
  // рознятся, нужно не выбирать и не выдумывать, а показывать диапазон и его
  // обоснование». Раньше диапазон считался в pricing.js и там же оставался:
  // в итоги шло одно число, и клиент не видел, насколько источники не согласны.
  //
  // Если расхождения нет (или цен вообще не нашлось), оба края равны той цене,
  // что пошла в расчёт, — диапазон просто не показывается.
  const закупкаМин = (typeof estimate.totalMin === 'number' && estimate.totalMin > 0)
    ? estimate.totalMin : закупка;
  const закупкаМакс = (typeof estimate.totalMax === 'number' && estimate.totalMax > 0)
    ? estimate.totalMax : закупка;
  const разбросЗакупки = закупкаМин > 0
    ? round2(((закупкаМакс - закупкаМин) / закупкаМин) * 100)
    : null;

  // Прибыль без известной закупки не существует. Считать её при закупке «ноль»
  // означало бы выдать всю цену победы за прибыль — то есть назвать выгодным
  // любой тендер, по которому мы не смогли разобрать позиции. Это худшая
  // сторона ошибки из возможных.
  const прибыльПри = (зак, лог) =>
    (ценаПобеды === null || !закупкаИзвестна)
      ? null
      : round2(ценаПобеды - зак - (лог || 0) - прочее - налог);
  const маржаПри = (п) =>
    (п === null || !ценаПобеды) ? null : round2((п / ценаПобеды) * 100);

  // В основной расчёт идёт ХУДШАЯ граница доставки: занизить расходы опаснее,
  // чем завысить. Убыточный контракт дороже упущенного тендера.
  const прибыль = прибыльПри(закупка, логМакс);

  // Края диапазона складывают обе неопределённости: расхождение источников по
  // цене и вилку доставки. Лучший край — дешёвая закупка и дешёвая доставка,
  // худший — дорогая и дорогая.
  const прибыльЛучшая = прибыльПри(закупкаМин, логМин);
  // Худший край - худшая ЗАКУПОЧНАЯ цена (totalWorst, 28.10.2026), а не
  // верхний край диапазона источников: тот включает потолок обоснования НМЦК.
  // Не меньше основной закупки: худший край дешевле расчётного не бывает.
  const закупкаХудшая = (typeof estimate.totalWorst === 'number' && estimate.totalWorst > 0)
    ? Math.max(estimate.totalWorst, закупка || 0) : закупкаМакс;
  const прибыльХудшая = прибыльПри(закупкаХудшая, логМакс);

  const заявка = (нмцк === null || ставкаЗаявки === null) ? null : round2(нмцк * ставкаЗаявки);

  // Антидемпинг, статья 37: при снижении от 25% обеспечение контракта растёт
  // в полтора раза, а при НМЦК свыше 15 млн — не менее 10% начальной цены.
  // Та же логика, что в формуле файла.
  //
  // Снижение не задано — об антидемпинге сказать нечего. Писать здесь 0 нельзя:
  // round2(null * 100) даёт именно ноль, то есть расчёт утверждал бы «снижения
  // не будет», а это утверждение, а не отсутствие данных.
  const снижениеПроцент = снижениеЗадано ? round2(снижениеДоля * 100) : null;
  let контракт = (нмцк === null || ставкаКонтракта === null) ? null : нмцк * ставкаКонтракта;
  const антидемпинг = снижениеПроцент !== null && снижениеПроцент >= 25;
  if (контракт !== null && антидемпинг) {
    контракт = Math.max(контракт * 1.5, нмцк > 15000000 ? нмцк * 0.1 : 0);
  }
  if (контракт !== null) контракт = round2(контракт);

  // Обеспечение гарантийных обязательств - только если ставка взята из проекта
  // контракта (24.10.2026); нет ставки - не выдумывается, в деньги не входит.
  const ставкаГарантии = typeof economics.warrantySecurityRate === 'number' ? economics.warrantySecurityRate : null;
  const гарантия = нмцк === null || ставкаГарантии === null ? null : round2(нмцк * ставкаГарантии);

  // Требуемый объём средств считается и без закупки — обеспечения выводятся из
  // НМЦК и от наших цен не зависят, а знать их полезно. Но теперь обеспечения
  // берутся в сумму ТОЛЬКО когда ставка известна из карточки: ставка не
  // указана — в сумме их нет, и сообщение обязано сказать, чего в ней нет,
  // иначе сумма читается как полная потребность (владелец 15.11.2026:
  // допущение убрано).
  const деньги = нмцк === null
    ? null
    : round2(закупка + (логМакс || 0) + прочее + (заявка || 0) + (контракт || 0) + (гарантия || 0));
  const обеспеченияИзвестны = ставкаЗаявки !== null && ставкаКонтракта !== null;

  // Цена безубыточности: при которой прибыль равна нулю.
  //   Ц = Расходы_без_налога + Ц × ставка  =>  Ц = Расходы / (1 − ставка)
  // Налог берётся с выручки, поэтому при снижении цены падает и он —
  // прямое вычитание расходов дало бы неверную границу.
  // БЕЗУБЫТОЧНОСТИ БЕЗ ЗАКУПКИ НЕ СУЩЕСТВУЕТ. Главный расход — сама закупка;
  // без неё формула даёт ноль, то есть «контракт выгоден при любой цене».
  // В проекте это записано правилом: вердикт без стоимости закупки не выдаётся.
  const расходыБезНалога = закупка + (логМакс || 0) + прочее;
  const безубыточность = (ставкаНалога >= 1 || !закупкаИзвестна)
    ? null
    : round2(расходыБезНалога / (1 - ставкаНалога));

  // Запас: на сколько процентов можно снизить цену от НМЦК и остаться в нуле.
  const запасПроцент = (нмцк === null || нмцк === 0 || безубыточность === null)
    ? null
    : round2(((нмцк - безубыточность) / нмцк) * 100);

  // ВТОРАЯ БЕЗУБЫТОЧНОСТЬ — ПО ЛУЧШЕЙ ЗАКУПОЧНОЙ ЦЕНЕ.
  //
  // Найдено на живом прогоне 07.10.2026 (закупка 0119200000826000018). Цены
  // поставщиков разошлись от 330 до 384 ₽ за пачку, и по худшей безубыточность
  // вышла 236 500 ₽ против НМЦК 227 119 — сообщение объявило «расходы превышают
  // начальную цену, участие нерентабельно». По лучшей цене безубыточность
  // 193 800 ₽, то есть запас 15%: тот же тендер выгоден.
  //
  // Один край диапазона был выдан за приговор. Это прямое нарушение правила
  // владельца от 04.10.2026 — «если источники рознятся, показывать диапазон
  // и его обоснование, а не выбирать за человека», — и ошибка в сторону отказа:
  // клиент прошёл бы мимо выгодного тендера, а узнать об этом было бы неоткуда.
  //
  // Берётся именно `закупкаМин`, а не `закупкаМакс`: верхний край включает
  // потолки из обоснования НМЦК, а они себестоимостью не являются. Сравниваются
  // две ЗАКУПОЧНЫЕ цены — худшая и лучшая, то есть два реальных варианта покупки.
  const расходыЛучшие = закупкаМин + (логМин || 0) + прочее;
  const безубыточностьЛучшая = (ставкаНалога >= 1 || !закупкаИзвестна)
    ? null
    : round2(расходыЛучшие / (1 - ставкаНалога));
  const запасПроцентЛучший = (нмцк === null || нмцк === 0 || безубыточностьЛучшая === null)
    ? null
    : round2(((нмцк - безубыточностьЛучшая) / нмцк) * 100);

  // Исход зависит от выбора поставщика: по одной цене убыточно, по другой нет.
  // Это не «примерно» — это две разные закупки, и решать должен человек.
  const исходЗависитОтЦены = запасПроцент !== null && запасПроцентЛучший !== null
    && запасПроцент <= 0 && запасПроцентЛучший > 0;

  // ЗДЕСЬ БЫЛ БЛОК «ЦЕЛЕВАЯ ЗАКУПОЧНАЯ ЦЕНА» — УДАЛЁН 05.10.2026.
  //
  // Он считал, за сколько надо купить, чтобы получить желаемую маржу, и
  // насколько это дешевле цен из обоснования НМЦК. Владелец отверг саму
  // мысль: «нам нужно купить это за 100 рублей и тогда мы заработаем 189 900.
  // нужно понятно дешевле. мы продаем факты». Утверждение «дешевле купишь —
  // больше заработаешь» это арифметика, а не аналитика.
  //
  // Код остался считаться впустую и попал бы обратно в сообщение при первой же
  // правке — поэтому удалён целиком, а не закомментирован. Вместе с ним ушло
  // ещё одно выдуманное число: желаемая маржа 10% по умолчанию, под которой
  // так же не было никакого обоснования.
  // Порог антидемпинга — вторая граница, и она часто наступает раньше первой.
  const порогАнтидемпинга = нмцк === null ? null : round2(нмцк * 0.75);

  // Что из двух границ бьёт раньше. Это и есть ответ на вопрос «до какой цены
  // опускаться»: либо упрёшься в убыток, либо в требование доложить денег.
  let граница = null;
  if (безубыточность !== null && нмцк !== null) {
    if (безубыточность > нмцк) граница = 'уже убыточно';
    else if (безубыточность > порогАнтидемпинга) граница = 'безубыточность раньше антидемпинга';
    else граница = 'запас уходит ниже порога антидемпинга';
  }

  return {
    безубыточность,
    запасПроцент,
    безубыточностьЛучшая,
    запасПроцентЛучший,
    исходЗависитОтЦены,
    порогАнтидемпинга,
    граница,
    нмцк,
    ценаПобеды,
    снижениеПроцент,
    закупка,

    // Известна ли стоимость закупки. Проверять ФЛАГ, а не `закупка > 0`:
    // смысл «данных нет» и «данные есть, и там ноль» разный, а выглядят они
    // одинаково. На этом уже обожглись со снижением цены.
    закупкаИзвестна,

    логистикаИзвестна: логИзвестна,
    логистика: логМакс,
    логистикаЛучшая: логМин,
    налог,
    прибыль,
    прибыльЛучшая,
    прибыльХудшая,
    маржа: маржаПри(прибыль),
    маржаЛучшая: маржаПри(прибыльЛучшая),
    маржаХудшая: маржаПри(прибыльХудшая),
    закупкаМин,
    закупкаМакс,
    разбросЗакупки,
    обеспечениеЗаявки: заявка,
    обеспечениеКонтракта: контракт,
    обеспечениеГарантии: гарантия,
    // Известны ли обе ставки обеспечения (из карточки). false — «всего денег»
    // посчитано БЕЗ обеспечений, и сообщение обязано это назвать.
    обеспеченияИзвестны,
    антидемпинг,
    деньги,

    // Задано ли ожидаемое снижение. Без него нет цены победы и нет прибыли —
    // сообщение обязано сказать об этом прямо, а не печатать ноль.
    снижениеЗадано,

    // Считать можно только если известна НМЦК. Без неё сравнивать смету
    // не с чем, и прибыль не существует — не ноль, а именно не существует.
    посчитано: нмцк !== null
  };
}

