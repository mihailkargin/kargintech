/**
 * Смета по тендеру в виде книги Excel.
 *
 * ЧТО ЭТО ТАКОЕ И ЗАЧЕМ. Это главное, чем сервис отличается от поиска по сайту.
 * Агрегатор присылает ссылку на закупку. Мы присылаем файл, в котором разобрана
 * спецификация, по каждой позиции найдена цена с указанием источника, посчитана
 * логистика, налоги, обеспечение и антидемпинг — и всё это ЖИВЫМИ ФОРМУЛАМИ.
 *
 * ПОЧЕМУ ФОРМУЛЫ, А НЕ ГОТОВЫЕ ЧИСЛА. Клиент лучше нас знает, почём купит
 * у своего завода. Смета с готовыми числами — картинка, которой надо верить.
 * Смета с формулами — расчёт: он подставляет свою цену в столбец и мгновенно
 * видит новую маржу. Наша работа — структура, источники и проверки, а не
 * угадывание его себестоимости.
 *
 * ЧЕСТНОСТЬ ЗАЛОЖЕНА В СТРУКТУРУ, А НЕ В ПРИПИСКИ.
 *   — позиция без найденной цены видна отдельной строкой, а не замазана нулём;
 *   — неполная смета помечена прямо в итоге, потому что сравнивать её с НМЦК
 *     нельзя: клиент увидит хорошую маржу и зайдёт в тендер, где недостающие
 *     позиции съедят её целиком;
 *   — у каждой цены указан источник и ссылка, цены без источника в расчёт
 *     не идут вовсе;
 *   — цены из реестра контрактов и обоснования НМЦК помечены как верхняя
 *     граница с чужой маржой, а не как себестоимость;
 *   — в расчёт идёт ХУДШАЯ из найденных цен: убыточный контракт дороже
 *     упущенного тендера.
 */
const { writeXlsx, STYLE } = require('./xlsx-write');

const round2 = (n) => Math.round(n * 100) / 100;

/** Ширины колонок листа позиций. Подобраны так, чтобы читалось без правки. */
const POS_COLUMNS = [
  { width: 46 }, // наименование
  { width: 10 }, // количество
  { width: 9 },  // единица
  { width: 18 }, // цена закупки
  { width: 18 }, // сумма
  { width: 22 }, // основание
  { width: 16 }, // достоверность
  { width: 12 }, // разброс
  { width: 60 }  // замечания
];

/**
 * Накопитель строк с запоминанием адресов.
 *
 * Формулы ссылаются на номера строк, а строки добавляются по ходу. Считать
 * их в уме — надёжный способ получить смету, где прибыль берётся из ячейки
 * с налогом. Поэтому каждая значимая строка получает имя и запоминает адрес.
 */
function sheetBuilder() {
  const rows = [];
  const at = {};
  return {
    rows,
    at,
    /** Добавляет строку. Возвращает её номер (с единицы, как в Excel). */
    push(cells, name) {
      rows.push(cells);
      const n = rows.length;
      if (name) at[name] = n;
      return n;
    },
    blank() { rows.push([]); return rows.length; }
  };
}

// --------------------------------------------------------------- Позиции

function positionsSheet(estimate) {
  const b = sheetBuilder();

  b.push([
    { v: 'Наименование позиции', s: STYLE.ШАПКА_ТАБЛИЦЫ },
    { v: 'Кол-во', s: STYLE.ШАПКА_ТАБЛИЦЫ },
    { v: 'Ед.', s: STYLE.ШАПКА_ТАБЛИЦЫ },
    { v: 'Цена закупки за ед.', s: STYLE.ШАПКА_ТАБЛИЦЫ },
    { v: 'Сумма', s: STYLE.ШАПКА_ТАБЛИЦЫ },
    { v: 'Откуда цена', s: STYLE.ШАПКА_ТАБЛИЦЫ },
    { v: 'Достоверность', s: STYLE.ШАПКА_ТАБЛИЦЫ },
    { v: 'Разброс', s: STYLE.ШАПКА_ТАБЛИЦЫ },
    { v: 'Замечания', s: STYLE.ШАПКА_ТАБЛИЦЫ }
  ]);

  const first = 2;
  // РАЗДЕЛЫ ТОВАРЫ / РАБОТЫ (владелец 28.10.2026). Только если в закупке есть
  // оба вида; строка раздела без суммы, поэтому итог SUM по колонке не меняется.
  const РАЗДЕЛЫ = [['товар', 'Товары и материалы'], ['товар+работа', 'Товары с монтажом'], ['работа', 'Работы и услуги']];
  const всеСтроки = estimate.rows || [];
  const виды = new Set(всеСтроки.map((r) => r.вид || 'товар'));
  const сРазделами = виды.size > 1;
  const порядок = сРазделами
    ? РАЗДЕЛЫ.flatMap(([вид, заголовок]) => {
      const свои = всеСтроки.filter((r) => (r.вид || 'товар') === вид);
      return свои.length ? [{ раздел: заголовок }, ...свои] : [];
    })
    : всеСтроки;
  for (const r of порядок) {
    if (r.раздел) {
      b.push([{ v: r.раздел, s: STYLE.ЖИРНЫЙ }]);
      continue;
    }
    const n = b.rows.length + 1;
    // Позиция без цены: ячейка цены остаётся ПУСТОЙ, а не нулевой.
    // Ноль означал бы «посчитано, вышло даром» — и итог молча занизился бы.
    const noPrice = r.priceForCalc === null;
    b.push([
      { v: r.name, s: STYLE.ПЕРЕНОС },
      { v: r.quantity, s: STYLE.ЧИСЛО },
      { v: r.unit, s: STYLE.ЧИСЛО },
      noPrice ? { v: null, s: STYLE.ПРЕДУПРЕЖДЕНИЕ } : { v: r.priceForCalc, s: STYLE.ДЕНЬГИ },
      // Сумма формулой: клиент правит цену — сумма пересчитывается сама.
      { f: `IF(OR(B${n}="",D${n}=""),"",B${n}*D${n})`, s: STYLE.ДЕНЬГИ },
      { v: noPrice ? 'цена не найдена' : r.basis, s: STYLE.ПЕРЕНОС },
      { v: r.confidence, s: STYLE.ПЕРЕНОС },
      { v: r.spreadPct === null || r.spreadPct === undefined ? '' : r.spreadPct, s: STYLE.ЧИСЛО },
      { v: (r.warnings || []).join(' • '), s: noPrice ? STYLE.ПРЕДУПРЕЖДЕНИЕ : STYLE.ПЕРЕНОС }
    ]);
  }

  const last = Math.max(first, b.rows.length);
  b.blank();

  const totalRow = b.push([
    { v: 'ИТОГО закупка', s: STYLE.ЖИРНЫЙ },
    null, null, null,
    { f: `SUM(E${first}:E${last})`, s: STYLE.ДЕНЬГИ_ИТОГ },
    { v: estimate.complete ? 'смета полная' : 'СМЕТА НЕПОЛНАЯ', s: estimate.complete ? STYLE.ЖИРНЫЙ : STYLE.ПРЕДУПРЕЖДЕНИЕ },
    null, null,
    estimate.complete
      ? { v: '', s: STYLE.ПЕРЕНОС }
      : {
          v: `цены найдены по ${estimate.pricedCount} позициям из ${(estimate.rows || []).length}. `
            + 'Сравнивать этот итог с НМЦК НЕЛЬЗЯ: недостающие позиции съедят маржу',
          s: STYLE.ПРЕДУПРЕЖДЕНИЕ
        }
  ], 'итого');

  b.blank();
  b.push([{ v: 'Столбец «Цена закупки за ед.» можно править: вы знаете свою закупку лучше. '
    + 'Сумма и весь расчёт на листе «Расчёт» пересчитаются сами.', s: STYLE.ПОЯСНЕНИЕ }]);

  return {
    sheet: {
      name: 'Позиции',
      freezeRow: 1,
      columns: POS_COLUMNS,
      rows: b.rows
    },
    totalRow
  };
}

