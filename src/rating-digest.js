/**
 * СООБЩЕНИЕ С РЕЙТИНГОМ — решения владельца 16.10.2026.
 *
 * «Где весь список, человек будет смотреть каждый тендер? Нужно рейтинговать
 * тендеры». Пять звёзд, порядок по убыванию выгоды, группы по звёздам
 * сворачиваются («потом это можно развернуть»), полный список — файлом.
 *
 * Сообщение собирается из ГОТОВЫХ разборов документации (app/parse-queue.js),
 * поэтому оно отдельное от сообщения поиска: в момент поиска разбора ещё нет.
 *
 * Налог и доставка — только из настроек клиента. Не заданы — звёзд нет с
 * причиной: подставленное «типичное» число рисует прибыль, которой нет.
 * Доставка — верхняя граница вилки клиента: худший случай.
 *
 * Сетевых обращений нет: разборы, протоколы и настройки приходят аргументами.
 */
const { оценка, упорядочить } = require('./rating');
const { groupDigits, TELEGRAM_LIMIT, закрытьТеги } = require('./notify');
const { writeXlsx, STYLE } = require('./xlsx-write');

const esc = (s) => String(s === null || s === undefined ? '' : s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const деньги = (n) => `${groupDigits(n)} ₽`;
const пр = (n) => String(Math.round(n * 10) / 10).replace('.', ',') + '%';
const датаРу = (iso) => {
  const м = /^(\d{4})-(\d{2})-(\d{2})/.exec(String(iso || ''));
  return м ? `${м[3]}.${м[2]}` : '';
};
const ЗВЁЗДЫ = (n) => '★'.repeat(n) + '☆'.repeat(5 - n);

/** Подписи групп — пороги по умолчанию из src/rating.js. */
const ПОДПИСЬ_ГРУППЫ = {
  5: 'рентабельность выше 15%',
  4: '10–15%',
  3: '5–10%',
  2: '0–5%',
  1: 'убыток или денежные риски'
};

/**
 * Причина «без звёзд» — короткой категорией, чтобы 30 тендеров с одной
 * причиной стали одной строкой «нет прайса: 30», а не тридцатью.
 */
function категория(почему) {
  const т = String(почему || '');
  if (/цене за единицу/.test(т)) return 'закупка по цене за единицу';
  if (/нужен прайс/.test(т)) return 'нет закупочных цен — нужен прайс';
  if (/прайс покрыл не все/.test(т)) return 'прайс покрыл не все позиции';
  if (/похожих прошлых закупок/.test(т)) return 'мало похожих прошлых закупок';
  if (/способ закупки/.test(т)) return 'способ закупки не сравнивается';
  if (/налог|доставк/.test(т)) return 'в настройках не заданы налог или доставка';
  if (/документаци/.test(т)) return 'документация не разобрана';
  return т.slice(0, 60);
}

/**
 * Оценивает все разобранные тендеры клиента.
 *
 * @param {object} разборы — `<клиент>-parsed.json`: номер → итогРазбора
 * @param {Array<object>} наблюдения — протоколы прошлых закупок
 * @param {object} клиент — настройки (economics, рейтинг)
 * @returns {Array<{номер, тендер, оценка, срок}>} в порядке рейтинга
 */
function оценитьРазборы(разборы, наблюдения, клиент = {}) {
  const эк = клиент.economics || {};
  const налог = typeof эк.taxRate === 'number' ? эк.taxRate : null;
  const доставка = typeof эк.logisticsMaxPct === 'number' ? эк.logisticsMaxPct : null;
  const прочие = typeof эк.otherCosts === 'number' ? эк.otherCosts : 0;
  const пороги = (клиент.рейтинг && клиент.рейтинг.пороги) || undefined;

  const список = [];
  for (const [номер, р] of Object.entries(разборы || {})) {
    if (!р || р.отменена || р.пропущен) continue;
    // Отсеянное стоп-словами по ТЗ клиенту не показывается вовсе: он сам
    // сказал, что это не его товар.
    if (р.фильтрПоТЗ && р.фильтрПоТЗ.прошёл === false) continue;
    const т = р.тендер || {};
    const без = (почему) => ({ звёзды: null, почему, минусы: [] });

    let о;
    if (!р.ок || !р.позиций) {
      о = без('документация не разобрана — позиции не найдены');
    } else if (!р.ценаЗаЕдиницу && налог === null) {
      о = без('в настройках клиента не задан налог (economics.taxRate)');
    } else if (!р.ценаЗаЕдиницу && доставка === null) {
      о = без('в настройках клиента не задана доставка (economics.logisticsMaxPct)');
    } else {
      const группы = (р.группыОкпд2 && р.группыОкпд2.length) ? р.группыОкпд2
        : (т.okpdGroup ? [т.okpdGroup] : []);
      о = оценка({
        нмцк: т.price,
        способ: т.law || '',
        // Прочие расходы на контракт входят в закупку: так их учитывает и
        // прибыль, и рентабельность, без отдельного поля в rating.js.
        // Сумма закупки в разборе считается и по ценам обоснования НМЦК
        // (потолок с чужой маржой). Ни одной закупочной цены — значит
        // прайса нет, а не «прайс покрыл не все» (живые данные, 19.10.2026).
        закупка: typeof р.закупка === 'number' && р.сЗакупочнойЦеной > 0 ? р.закупка + прочие : null,
        закупкаПолная: р.сЗакупочнойЦеной === р.позиций,
        доставкаПроцент: доставка,
        налог,
        ценаЗаЕдиницу: р.ценаЗаЕдиницу,
        обеспечениеКонтрактаПроцент: р.обеспечениеКонтрактаПроцент,
        группыОкпд2: группы,
        наблюдения,
        пороги
      });
    }
    список.push({ номер, тендер: т, оценка: о, срок: т.deadline || null });
  }
  return упорядочить(список);
}

/** Строка тендера в сообщении: ссылка, деньги, срок, риски. */
function строкаТендера(x, i) {
  const т = x.тендер;
  const о = x.оценка;
  const объект = String(т.object || x.номер);
  const имя = объект.length > 60 ? объект.slice(0, 57) + '…' : объект;
  const ссылка = т.url ? `<a href="${esc(т.url)}">${esc(имя)}</a>` : esc(имя);
  const части = [];
  if (typeof т.price === 'number') части.push(`НМЦК ${деньги(т.price)}`);
  if (typeof о.прибыль === 'number') {
    части.push(typeof о.прибыльЛучшая === 'number' && о.прибыльЛучшая !== о.прибыль
      ? `прибыль от ${деньги(о.прибыль)} до ${деньги(о.прибыльЛучшая)} (от ${пр(о.рентабельность)} до ${пр(о.рентабельностьЛучшая)})`
      : `прибыль ${деньги(о.прибыль)} (${пр(о.рентабельность)})`);
  }
  if (x.срок) части.push(`до ${датаРу(x.срок)}`);
  const строки = [`${i}. ${ссылка}`, `   ${части.join(' · ')}`];
  for (const м of о.минусы || []) строки.push(`   ⚠ ${esc(м)}`);
  return строки.join('\n');
}

/**
 * Текст для Telegram.
 *
 * @param {Array} оценённые — результат оценитьРазборы
 * @param {object} [опции] { развёрнуты: [5, 4], наГруппу: 8 }
 */
function сообщениеРейтинга(оценённые, опции = {}) {
  const развёрнуты = опции.развёрнуты || [5, 4];
  let наГруппу = опции.наГруппу || 8;

  const поЗвёздам = { 5: [], 4: [], 3: [], 2: [], 1: [] };
  const безЗвёзд = [];
  for (const x of оценённые) {
    if (x.оценка && x.оценка.звёзды) поЗвёздам[x.оценка.звёзды].push(x);
    else безЗвёзд.push(x);
  }

  const собрать = (предел) => {
    const строки = [`<b>Рейтинг тендеров: ${оценённые.length - безЗвёзд.length}</b>`];
    const счёт = [5, 4, 3, 2, 1].filter((з) => поЗвёздам[з].length)
      .map((з) => `${'★'.repeat(з)} ${поЗвёздам[з].length}`);
    строки.push(счёт.join(' · '));

    let номер = 1;
    for (const з of [5, 4, 3, 2, 1]) {
      const группа = поЗвёздам[з];
      if (!группа.length) continue;
      строки.push('', `<b>${ЗВЁЗДЫ(з)} — ${ПОДПИСЬ_ГРУППЫ[з]}: ${группа.length}</b>`);
      const тело = группа.slice(0, предел).map((x) => строкаТендера(x, номер++));
      номер += Math.max(0, группа.length - предел);
      if (группа.length > предел) тело.push(`…ещё ${группа.length - предел} — в файле`);
      // Свёрнутая цитата Telegram: клиент раскрывает группу нажатием.
      строки.push(`<blockquote${развёрнуты.includes(з) ? '' : ' expandable'}>${тело.join('\n')}</blockquote>`);
    }

    // Тендеры без оценки в сообщение не идут - правило владельца 25.10.2026:
    // «не присылай в тг мусор, либо вилку прибыли и маржи, либо ничего».
    // Они остаются в файле и в кабинете.
    строки.push('', '<i>Полный список с расчётом — в файле.</i>');
    return строки.join('\n');
  };

  // Предел сообщения Telegram — 4096 знаков. Сначала сокращаем число строк в
  // группах, и только в крайнем случае режем текст с закрытием тегов.
  let текст = собрать(наГруппу);
  while (текст.length > TELEGRAM_LIMIT && наГруппу > 2) текст = собрать(--наГруппу);
  if (текст.length > TELEGRAM_LIMIT) {
    // Срез по границе строки: внутри тега он сломал бы разметку, и Telegram
    // отверг бы сообщение целиком (так было с подписью к файлу 09.10.2026).
    const кусок = текст.slice(0, TELEGRAM_LIMIT - 200);
    текст = закрытьТеги(кусок.slice(0, кусок.lastIndexOf('\n')));
  }
  return { parseMode: 'HTML', text: текст, disableWebPagePreview: true };
}

/** Полный список файлом Excel — все тендеры, и с оценкой, и без. */
function файлРейтинга(оценённые, now = new Date()) {
  const ш = (v) => ({ v, s: STYLE.ШАПКА_ТАБЛИЦЫ });
  const rows = [[ш('№'), ш('Звёзды'), ш('Номер закупки'), ш('Объект'), ш('НМЦК, ₽'),
    ш('Цена победы, ₽'), ш('Падение у похожих, %'), ш('Прибыль, ₽'), ш('Рентабельность, %'),
    ш('Срок подачи'), ш('Денежные риски'), ш('Как посчитано / почему без оценки'), ш('Ссылка')]];
  оценённые.forEach((x, i) => {
    const о = x.оценка || {};
    const т = x.тендер || {};
    rows.push([
      { v: i + 1, s: STYLE.ЧИСЛО },
      о.звёзды ? ЗВЁЗДЫ(о.звёзды) : '—',
      String(x.номер),
      { v: т.object || '', s: STYLE.ПЕРЕНОС },
      typeof т.price === 'number' ? { v: т.price, s: STYLE.ДЕНЬГИ } : '—',
      typeof о.ценаПобеды === 'number' ? { v: о.ценаПобеды, s: STYLE.ДЕНЬГИ } : '—',
      о.падение && typeof о.падение.падение === 'number' ? { v: о.падение.падение, s: STYLE.ЧИСЛО } : '—',
      typeof о.прибыль === 'number' ? { v: о.прибыль, s: STYLE.ДЕНЬГИ } : '—',
      typeof о.рентабельность === 'number' ? { v: о.рентабельность, s: STYLE.ЧИСЛО } : '—',
      x.срок ? String(x.срок).slice(0, 10) : '—',
      { v: (о.минусы || []).join('; ') || '—', s: STYLE.ПЕРЕНОС },
      { v: о.почему || '', s: STYLE.ПЕРЕНОС },
      т.url || '—'
    ]);
  });
  const buffer = writeXlsx([{
    name: 'Рейтинг',
    freezeRow: 1,
    columns: [{ width: 5 }, { width: 9 }, { width: 22 }, { width: 50 }, { width: 15 }, { width: 15 },
      { width: 12 }, { width: 14 }, { width: 12 }, { width: 12 }, { width: 40 }, { width: 60 }, { width: 50 }],
    rows
  }]);
  return { buffer, fileName: `Рейтинг тендеров ${now.toISOString().slice(0, 10)}.xlsx` };
}

module.exports = { оценитьРазборы, сообщениеРейтинга, файлРейтинга, категория };
