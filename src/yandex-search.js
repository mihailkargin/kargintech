/**
 * ПОИСК ПОСТАВЩИКОВ ЧЕРЕЗ ЯНДЕКС - замена поиска моделью Anthropic
 * (31.10.2026: Anthropic требует проверки организации, OpenRouter запрещает
 * доступ через прокси; решение владельца - законная цепочка в России).
 *
 * Цепочка, по убыванию дешевизны:
 *   1. поисковый API Яндекса находит страницы поставщиков (~0,5 ₽ запрос);
 *   2. цену со страницы берёт код - из разметки schema.org/microdata/og,
 *      бесплатно и без ошибок прочтения;
 *   3. страницу без разметки читает модель в Yandex Cloud (DeepSeek и др.),
 *      и только если на ней есть слова позиции: пустые страницы не оплачиваются;
 *   4. цитату и цену модели код сверяет с той же страницей - неподтверждённая
 *      цена выбрасывается (правило «цена без источника в расчёт не идёт»).
 *
 * В модель уходит только текст публичной страницы поставщика и наименование
 * позиции с выдержкой ТЗ (контакты вырезаны). Прайса клиента здесь нет.
 * Сетевых обращений в модуле нет - они в `app/yandex-run.js`.
 */

const path = require('path');
const { НЕ_ИСТОЧНИКИ, parseSupplierResponse } = require(path.join(__dirname, 'suppliers'));
const { товарИзСтраницы, построитьКаталог, найтиВКаталоге } = require(path.join(__dirname, 'supplier-catalog'));
const { слова, нормализовать } = require(path.join(__dirname, 'price-list'));
const { видПозиции } = require(path.join(__dirname, 'item-kind'));
const { сверитьПоставщика, ИСХОДЫ } = require(path.join(__dirname, 'verify'));

/** Сколько знаков страницы отдаём модели: карточка товара укладывается, меню и подвал - нет. */
const ТЕКСТА_МОДЕЛИ = 12000;

/**
 * Суть позиции: содержимое скобок, если наименование записано по ОКПД2
 * (см. suppliers.js), без кодов КТРУ и ОКПД2 - «Бумага для офисной техники
 * 17.12.14.110-00000005» (эталон 0373100010426000011): код в запросе уводил
 * выдачу на справочники.
 */
function суть(позиция) {
  const н = String((позиция && позиция.name) || '').trim();
  const вСкобках = (н.match(/\(([^)]{10,})\)/) || [])[1] || '';
  // Скобки - суть, только если снаружи длинное обобщение по ОКПД2 («Бумага
  // для офисной техники (...)»). У короткого «Пенокартон (белый, 70*100)»
  // в скобках признаки, а товар снаружи: поиск по «белый, 70*100» нашёл
  // термоэтикетки (0373200638526000056, 31.10.2026).
  const снаружи = н.replace(/\([^)]*\)/g, ' ').trim().split(/\s+/).filter(Boolean).length;
  const изСкобок = вСкобках.length > 10 && снаружи >= 4;
  return (изСкобок ? вСкобках : н.replace(/[()]/g, ' '))
    .replace(/\d{2}\.\d{2}\.\d{2}\.\d{3}-\d{5,8}/g, ' ')
    .replace(/(^|\s)\d{2}\.\d{2}(\.\d{1,3}){1,3}(?=\s|$)/g, ' ')
    .replace(/\s+/g, ' ').trim();
}

/**
 * Признаки товара из ТЗ, которые ищут в магазине: формат, плотность, число
 * листов, марка, объём, размер. У позиции «Бумага для офисной техники» всё,
 * что отличает её от любой бумаги, лежит в ТЗ, а не в наименовании.
 * Кириллица - явными классами: \b её не видит.
 */
function признакиИзТЗ(spec) {
  const т = String(spec || '').replace(/\s+/g, ' ');
  const п = [];
  const взять = (re, f) => { const m = т.match(re); if (m) п.push(f(m)); };
  взять(/(?:^|[^A-Za-zА-Яа-яЁё])([AА][0-6])(?![A-Za-zА-Яа-яЁё0-9])/, (m) => m[1].replace('A', 'А'));
  взять(/(\d{2,3})\s*г\s*\/\s*(?:кв\.?\s*)?м/i, (m) => `${m[1]} г/м2`);
  взять(/(\d{2,4})\s*(?:лист|л\.)/i, (m) => `${m[1]} листов`);
  взять(/марк[аи]\s*(?:бумаги)?[:\s]*(?:не ниже\s*)?[«"]?([ABCАВС])(?![A-Za-zА-Яа-яЁё])/i, (m) => `марка ${m[1].replace('A', 'А').replace('B', 'В').replace('C', 'С')}`);
  взять(/(\d+(?:[.,]\d+)?)\s*(мл|л|кг|мм|см)(?![A-Za-zА-Яа-яЁё])/i, (m) => `${m[1]} ${m[2]}`);
  return [...new Set(п)];
}

/**
 * Поисковые запросы по позиции: суть с признаками из ТЗ. Второй - короче
 * (первые шесть слов): длинная формулировка из документа у магазинов не
 * встречается, и выдача по ней бедная.
 */
function запросыПоиска(позиция) {
  const с = суть(позиция);
  if (с.length < 4) return [];
  const работа = видПозиции(позиция || {}).вид === 'работа';
  const признаки = работа ? [] : признакиИзТЗ(позиция && позиция.spec).slice(0, 3);
  const хвост = работа ? 'цена расценки' : 'купить оптом цена';
  const короче = с.split(/\s+/).slice(0, 6).join(' ');
  const первый = [с.slice(0, 200), ...признаки, хвост].join(' ');
  const второй = [короче, ...признаки, работа ? 'стоимость работ прайс' : 'цена прайс поставщик'].join(' ');
  return первый === второй ? [первый] : [первый, второй];
}

/**
 * Совпадение товара со страницы с позицией: два общих слова сути, все числа
 * из признаков ТЗ есть в названии товара, марки не противоречат. Обратного
 * не требуем (как у каталога): у магазина в названии всегда больше чисел,
 * чем в обобщённой позиции, - плотность 80 г/м² при ТЗ без плотности
 * не делает товар чужим.
 */
function товарПодходит(позиция, наименование) {
  const { числаИз, маркиРасходятся } = require(path.join(__dirname, 'price-list'));
  const основы = [...new Set(слова(нормализовать(суть(позиция))).map((w) => w.slice(0, 5)))];
  const т = нормализовать(наименование);
  const общих = основы.filter((о) => т.includes(о)).length;
  if (общих < Math.min(2, основы.length)) return false;
  // «г/м2» и «м²» - степень единицы, а не число товара: иначе «80 г/м²» на
  // странице не совпал бы с «80 г/м2» из ТЗ по лишней двойке.
  const безСтепени = (s) => String(s || '').replace(/м\s*[23²³]/g, 'м');
  const нужно = числаИз(безСтепени([суть(позиция), ...признакиИзТЗ(позиция && позиция.spec)].join(' ')));
  const есть = числаИз(безСтепени(наименование));
  for (const ч of нужно) if (!есть.has(ч)) return false;
  return !маркиРасходятся(суть(позиция), наименование);
}

/** Тело запроса к Search API v2 (web/search). */
function телоПоиска(текст, папка) {
  return {
    query: { searchType: 'SEARCH_TYPE_RU', queryText: текст, familyMode: 'FAMILY_MODE_NONE' },
    folderId: папка,
    responseFormat: 'FORMAT_XML',
    groupSpec: { groupMode: 'GROUP_MODE_DEEP', groupsOnPage: 10, docsInGroup: 1 }
  };
}

function доменИз(url) {
  const m = String(url || '').match(/^https?:\/\/([^/?#]+)/i);
  return m ? m[1].replace(/^www\./i, '').toLowerCase() : '';
}

function раскрытьXml(s) {
  return String(s || '').replace(/<[^>]+>/g, '').replace(/&quot;/g, '"').replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>').replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim();
}

/**
 * Ссылки из ответа Search API: rawData - XML в base64. Маркетплейсы и доски
 * объявлений отсекаются тем же списком, что при поиске моделью; один домен -
 * одна ссылка.
 */
function ссылкиИзВыдачи(ответ) {
  let xml = '';
  try {
    const о = typeof ответ === 'string' ? JSON.parse(ответ) : ответ;
    xml = Buffer.from(String((о && о.rawData) || ''), 'base64').toString('utf8');
  } catch (e) { return { ссылки: [], ошибка: 'ответ поиска не разобран: ' + e.message }; }
  const ошибка = (xml.match(/<error[^>]*>([\s\S]*?)<\/error>/) || [])[1];
  if (ошибка) return { ссылки: [], ошибка: раскрытьXml(ошибка) };
  const ссылки = [];
  const видели = new Set();
  for (const m of xml.matchAll(/<doc\b[\s\S]*?<\/doc>/g)) {
    const url = раскрытьXml((m[0].match(/<url>([\s\S]*?)<\/url>/) || [])[1]);
    const домен = доменИз(url);
    if (!домен || видели.has(домен)) continue;
    if (НЕ_ИСТОЧНИКИ.some((d) => домен.includes(d))) continue;
    видели.add(домен);
    ссылки.push({ url, домен, заголовок: раскрытьXml((m[0].match(/<title>([\s\S]*?)<\/title>/) || [])[1]) });
  }
  return { ссылки, ошибка: null };
}

/** Название компании со страницы: og:site_name, иначе домен. */
function имяКомпании(html, домен) {
  const m = String(html || '').match(/<meta[^>]*property\s*=\s*["']og:site_name["'][^>]*content\s*=\s*["']([^"']{2,80})["']/i)
    || String(html || '').match(/<meta[^>]*content\s*=\s*["']([^"']{2,80})["'][^>]*property\s*=\s*["']og:site_name["']/i);
  return m ? раскрытьXml(m[1]) : домен;
}

/**
 * Шаг 2 - цена из разметки. Товар на странице сверяется с позицией теми же
 * правилами, что строка каталога оптовика (два общих слова, числа, марки).
 * Не совпал - null: цена чужого товара хуже отсутствующей.
 */
function изРазметки(позиция, html, url) {
  const т = товарИзСтраницы(html);
  if (!т) return null;
  const каталог = построитьКаталог({ позиции: [[т.наименование, т.цена, т.единица, url, т.артикул]] });
  // Главное слово (первое в сути) обязано быть в названии товара: «белый» и
  // «70х100» совпадают и у термоэтикетки, а пенокартоном она от этого не становится.
  const главное = (слова(нормализовать(суть(позиция)))[0] || '').slice(0, 5);
  const н = главное && нормализовать(т.наименование).includes(главное)
    ? (найтиВКаталоге({ ...позиция, name: суть(позиция) }, каталог)
      || (товарПодходит(позиция, т.наименование) ? { уверенность: 'средняя' } : null))
    : null;
  if (!н) return { совпало: false, товар: т };
  const домен = доменИз(url);
  return {
    совпало: true,
    поставщик: {
      name: имяКомпании(html, домен), url, site: `https://${домен}`, domain: домен,
      price: т.цена, priceDropped: false, unit: т.единица || '',
      priceNote: `цена из разметки страницы, совпадение ${н.уверенность}`,
      region: '', kind: 'неизвестно', phone: '',
      evidence: `«${т.наименование}» - ${т.цена} ₽`,
      изРазметки: true, уверенность: н.уверенность
    }
  };
}

/**
 * Стоит ли платить модели за страницу: на ней должно быть хотя бы два слова
 * сути позиции (по основам). Иначе это не та страница - модель не вызывается.
 */
function страницаПоТеме(позиция, текст) {
  const основы = [...new Set(слова(нормализовать(суть(позиция))).map((w) => w.slice(0, 5)))];
  if (!основы.length) return false;
  const т = нормализовать(String(текст || '').slice(0, 60000));
  const есть = основы.filter((о) => т.includes(о)).length;
  return есть >= Math.min(2, основы.length);
}

/**
 * Шаг 3 - запрос к модели (OpenAI-совместимый API Yandex Cloud). Модель
 * читает ОДНУ страницу и отвечает про неё; поиск она не ведёт.
 */
function запросКМодели(позиция, текст, url, модельUri, ценыРазметки = []) {
  const вид = видПозиции(позиция || {}).вид;
  const инструкция = [
    'Ты читаешь страницу сайта и определяешь, продаёт ли эта компания нужный товар (или выполняет работу) и по какой цене.',
    'Цену бери ТОЛЬКО со страницы. Не оценивай, не усредняй, не пересчитывай.',
    'Если на странице нет нужного товара или он не совпадает по характеристикам (размер, плотность, фасовка, материал, марка) - found=false.',
    'Цена «от 450» - нижняя граница: price=null, в priceNote напиши как есть.',
    'Если цен несколько (розница, опт, по объёму) - бери оптовую для указанного количества, в priceNote перечисли.',
    'evidence - ДОСЛОВНЫЙ кусок текста страницы, где стоит эта цена (10-150 знаков), скопированный без изменений.',
    вид === 'товар+работа' ? 'Позиция включает товар и монтаж: installPrice и installEvidence - цена монтажа со страницы, нет - null.' : '',
    'Ответь ТОЛЬКО JSON:',
    '{"found":true|false,"company":"название компании","product":"название товара на странице","price":число|null,"unit":"за что цена","priceNote":"что написано про цену","evidence":"дословная строка","phone":"телефон со страницы или пусто","region":"город или пусто","kind":"производитель|оптовик|подрядчик|магазин|неизвестно"'
      + (вид === 'товар+работа' ? ',"installPrice":число|null,"installEvidence":"строка"' : '') + '}'
  ].filter(Boolean).join('\n');
  const { redactContacts, isSafeToSend } = require(path.join(__dirname, 'redact'));
  const сырые = String((позиция && позиция.spec) || '').replace(/\s+/g, ' ').trim().slice(0, 1200);
  const очищенные = сырые ? redactContacts(сырые).text : '';
  const характеристики = очищенные && isSafeToSend(очищенные).safe ? очищенные : '';
  const задача = [
    `Нужно: ${суть(позиция)}`,
    позиция && позиция.quantity ? `Количество: ${позиция.quantity} ${позиция.unit || ''}` : '',
    характеристики ? `Характеристики по ТЗ: ${характеристики}` : '',
    `Страница: ${url}`,
    // Магазины часто рисуют цену скриптом: в тексте её нет, а в разметке для
    // поисковиков есть. Без этой строки модель честно отвечала «цены нет»
    // (эталон 0373100010426000011, 31.10.2026).
    ценыРазметки.length ? `Цены из разметки страницы (для поисковиков): ${ценыРазметки.slice(0, 5).join(', ')} руб. Если цена товара есть только здесь - бери её, evidence = это число.` : '',
    '--- текст страницы ---',
    String(текст || '').slice(0, ТЕКСТА_МОДЕЛИ)
  ].filter(Boolean).join('\n');
  return {
    model: модельUri,
    temperature: 0,
    max_tokens: 3000,
    messages: [{ role: 'system', content: инструкция }, { role: 'user', content: задача }]
  };
}

/**
 * Шаг 4 - ответ модели в поставщика, с проверкой кодом по той же странице.
 * Цена, цитаты которой нет на странице, выбрасывается; компания остаётся
 * контактом, если товар подтверждён.
 */
function поставщикИзОтвета(текстОтвета, позиция, url, текстСтраницы, разметка = []) {
  const кусок = String(текстОтвета || '').match(/\{[\s\S]*\}/);
  if (!кусок) return { поставщик: null, почему: 'в ответе модели нет JSON' };
  let о;
  try { о = JSON.parse(кусок[0]); } catch (e) { return { поставщик: null, почему: 'JSON модели не разобран' }; }
  if (!о || о.found !== true) return { поставщик: null, почему: 'товара на странице нет' };
  // Товар, названный моделью, должен содержать одно из двух первых слов сути:
  // DeepSeek выдал «пластину оцинкованную 28 мм» за скрепки 28 мм
  // (0373200638526000056, 31.10.2026).
  const первые = слова(нормализовать(суть(позиция))).slice(0, 2).map((w) => w.slice(0, 5));
  // Короткое название («SvetoCopy») - марка без вида товара, по нему не судим.
  const полное = String(о.product || '').trim().split(/\s+/).length >= 3;
  if (полное && первые.length && !первые.some((w) => нормализовать(о.product).includes(w))) {
    return { поставщик: null, почему: `на странице другой товар: ${String(о.product).slice(0, 80)}` };
  }
  const домен = доменИз(url);
  const разбор = parseSupplierResponse({ suppliers: [{
    name: о.company || домен, url, site: `https://${домен}`, price: о.price, unit: о.unit,
    priceNote: [о.product ? `на странице: ${о.product}` : '', о.priceNote || ''].filter(Boolean).join('; '),
    region: о.region, kind: о.kind, phone: о.phone, evidence: о.evidence,
    installPrice: о.installPrice, installEvidence: о.installEvidence
  }] }, позиция);
  const п = разбор.suppliers[0];
  if (!п) return { поставщик: null, почему: (разбор.rejected[0] || { reasons: ['отброшен'] }).reasons.join('; ') };
  // «от 357,65 рублей» - нижняя граница, а не цена (правило инструкции).
  // Модель Alice AI Flash взяла её как цену (эталон 0373100010426000011,
  // 31.10.2026), поэтому проверяет код: перед числом в цитате стоит «от».
  if (п.price !== null) {
    const целая = String(Math.floor(п.price));
    const разряды = целая.replace(/\B(?=(\d{3})+(?!\d))/g, '[\\s\\u00a0]?');
    if (new RegExp(`(^|[^А-Яа-яЁёA-Za-z])от\\s*:?\\s*${разряды}(?!\\d)`, 'i').test(String(о.evidence || '') + ' ' + String(о.priceNote || ''))) {
      п.priceNote = `«от ${п.price}» - нижняя граница, не цена; в расчёт не идёт; ${п.priceNote}`;
      п.price = null;
      п.priceDropped = true;
    }
  }
  // Страница-каталог: модель берёт «минимальную из представленных» - цену
  // какого-то товара из списка, не обязательно нужного (шкаф медицинский,
  // 0373100056626001462, 31.10.2026). Такая цена в расчёт не идёт.
  if (п.price !== null && /минимальн|варьиру|диапазон|самая низк|наименьш/i.test(String(о.priceNote || ''))) {
    п.priceNote = `цена выбрана из списка товаров каталога - в расчёт не идёт; ${п.priceNote}`;
    п.price = null;
    п.priceDropped = true;
  }
  if (п.price !== null) {
    const сверка = сверитьПоставщика({ name: п.name, url, price: п.price, evidence: о.evidence }, текстСтраницы, '', разметка);
    if (сверка.исход !== ИСХОДЫ.ПОДТВЕРЖДЕНО) {
      п.priceNote = `цена ${п.price} не найдена на странице - в расчёт не идёт; ${п.priceNote}`;
      п.price = null;
      п.priceDropped = true;
    } else п.сила = сверка.сила;
  }
  п.изЯндекса = true;
  return { поставщик: п, почему: '' };
}

