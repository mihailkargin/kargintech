/** Запрос к поиску по позиции ниши: суть и «оптом прайс» (работы - «расценки»). */
function запросНиши(позиция) {
  const с = суть(позиция).split(/\s+/).slice(0, 6).join(' ');
  if (с.length < 4) return '';
  return `${с} ${видПозиции(позиция || {}).вид === 'работа' ? 'расценки подрядчик' : 'оптом прайс'}`;
}

/**
 * Поставщики ниши из выдач по её позициям. Берётся сайт, найденный не меньше
 * чем по двум позициям (при одной позиции в группе - по ней); найденные по
 * большему числу позиций - первыми; не больше `сколько`. Вид - как у поиска моделью.
 *
 * @param {Array<{позиция: object, ссылки: Array<{url:string, домен:string, заголовок?:string}>}>} выдачи
 * @param {'товар'|'работа'} вид
 */
function поставщикиНишиИзВыдач(выдачи, вид = 'товар', сколько = 15) {
  const поДомену = new Map();
  for (const в of выдачи || []) {
    for (const с of в.ссылки || []) {
      const д = String(с.домен || '').toLowerCase();
      if (!д || НЕ_ПОСТАВЩИКИ_НИШИ.some((x) => д === x || д.endsWith('.' + x))) continue;
      const б = поДомену.get(д) || { домен: д, url: с.url, заголовок: с.заголовок || '', позиции: new Set() };
      б.позиции.add(String((в.позиция && в.позиция.name) || ''));
      поДомену.set(д, б);
    }
  }
  const порог = (выдачи || []).length >= 2 ? 2 : 1;
  return [...поДомену.values()]
    .filter((б) => б.позиции.size >= порог)
    .sort((a, b) => b.позиции.size - a.позиции.size || a.домен.localeCompare(b.домен))
    .slice(0, сколько)
    .map((б) => ({
      домен: б.домен, имя: б.домен, сайт: `https://${б.домен}/`, телефон: '', регион: '',
      вид: вид === 'работа' ? 'подрядчик' : 'поставщик', род: 'найден поиском Яндекса',
      покрывает: [...б.позиции].slice(0, 5).join('; ').slice(0, 200),
      цитата: `в выдаче по ${б.позиции.size} позициям ниши из ${выдачи.length}`,
      источники: [], чужиеАдреса: []
    }));
}

