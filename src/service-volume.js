/**
 * ОБЪЁМ УСЛУГИ ИЗ ТЗ - 23.10.2026 (услуги, решение владельца «услуги туда же»).
 *
 * У услуг без таблицы в обосновании (или где позиция - «6 мес») сумму не из
 * чего считать. Но в ТЗ почти всегда есть объём: «Площадь убираемых помещений -
 * 5 429,98 кв. м.», посты и часы охраны, м³ вывоза, и срок договора. Из них
 * выводится факт, нужный клиенту: сколько заказчик платит за единицу объёма в
 * месяц (НМЦК ÷ объём ÷ месяцы). Клиент сравнивает это со своей себестоимостью.
 *
 * Правила: значение - только с дословной цитатой строки ТЗ; несколько разных
 * значений без «общая / итого / всего» - объём не выбирается (список
 * кандидатов показывается); срок - по датам «с … по …» или «в течение N месяцев».
 * Сетевых обращений нет.
 */

const ЧИСЛО = '(\\d[\\d\\s\\u00a0]*(?:[.,]\\d+)?)';
const ВИДЫ = [
  { вид: 'площадь', ед: 'м²', шаблон: new RegExp(`${ЧИСЛО}\\s*(?:кв\\.?\\s?м\\.?|м\\.?\\s?кв\\.?|м2|м²|квадратн[а-яё]*\\s+метр[а-яё]*)`, 'gi'), контекст: /площад|убор|убира|помещен|территор|газон|озелен/i },
  { вид: 'часы', ед: 'час', шаблон: new RegExp(`${ЧИСЛО}\\s*(?:час(?:ов|а)?|ч\\.)(?![а-яё])`, 'gi'), контекст: /пост|охран|дежур|работ[а-яё]*\s+специалист|человек/i },
  { вид: 'объём', ед: 'м³', шаблон: new RegExp(`${ЧИСЛО}\\s*(?:куб\\.?\\s?м\\.?|м3|м³|кубическ[а-яё]*\\s+метр[а-яё]*)`, 'gi'), контекст: /вывоз|отход|тко|кго|мусор/i },
  // Перевозки (0116300000126001143, 23.10.2026): «Пробег автобуса на срок
  // контракта | 13 977 | км» по каждому маршруту; заказчик платит за км.
  // Только «пробег» - «протяжённость маршрута 23,53 км» объёмом не является.
  { вид: 'пробег', ед: 'км', заСрок: true, шаблон: new RegExp(`${ЧИСЛО}\\s*(?:км|километр[а-яё]*)(?![а-яё])`, 'gi'), контекст: /пробег/i },
  // «Количество рейсов на срок контракта | 1 134» - число после слова.
  { вид: 'рейсы', ед: 'рейс', заСрок: true, шаблон: new RegExp(`рейс[а-яё]*[^\\d\\n]{0,40}?${ЧИСЛО}`, 'gi'), контекст: /рейс/i }
];
const ИТОГ = /общ[а-яё]*|итого|всего|суммарн/i;

const число = (s) => {
  const n = Number(String(s).replace(/[\s ]/g, '').replace(',', '.'));
  return Number.isFinite(n) ? n : null;
};

/** Кандидаты объёма по видам: [{вид, ед, значение, цитата, итог}] */
function кандидатыОбъёма(текст) {
  const итог = [];
  for (const строка of String(текст || '').split(/\r?\n/)) {
    const чистая = строка.replace(/\t/g, ' ').replace(/\s+/g, ' ').trim();
    if (!чистая) continue;
    for (const в of ВИДЫ) {
      в.шаблон.lastIndex = 0;
      let m;
      while ((m = в.шаблон.exec(чистая))) {
        const v = число(m[1]);
        if (v === null || v <= 0) continue;
        // Контекст и «итого» - в окне вокруг числа, а не во всей строке: ТЗ
        // бывает уложено в несколько огромных абзацев (охрана 32616485839).
        const окно = чистая.slice(Math.max(0, m.index - 120), m.index + m[0].length + 20);
        if (!в.контекст.test(окно)) continue;
        // Подпись - текст перед числом без цифр: одинаковая подпись у строк по
        // разным объектам («Пробег автобуса на срок контракта» по маршрутам).
        const метка = чистая.slice(Math.max(0, m.index - 60), m.index).replace(/[\d\s.,№]+/g, ' ').trim().toLowerCase();
        итог.push({ вид: в.вид, ед: в.ед, заСрок: !!в.заСрок, значение: v, метка, цитата: окно.trim().slice(-200), итог: ИТОГ.test(чистая.slice(Math.max(0, m.index - 80), m.index)) });
      }
    }
  }
  return итог;
}

/**
 * Какой объём осмыслен для услуги - по её названию: охрана - часы (цена за м²
 * охраны бессмысленна, 32616485839), вывоз - м³, уборка и озеленение - площадь.
 * Название не подсказывает - все три по порядку.
 */
function видыДляУслуги(объект) {
  const о = String(объект || '');
  if (/перевоз|пассажир|маршрут|транспортн[а-яё]*\s+обслуж/i.test(о)) return ['пробег', 'рейсы'];
  if (/охран|дежур|вахт/i.test(о)) return ['часы'];
  if (/вывоз|отход|тко|кго|мусор|снег/i.test(о)) return ['объём'];
  if (/убор|клининг|озелен|газон|территори|чистк/i.test(о)) return ['площадь'];
  return ['площадь', 'часы', 'объём'];
}

/** Один однозначный объём: итоговая строка, иначе единственное значение. */
function объёмУслуги(текст, виды = ['площадь', 'часы', 'объём']) {
  const все = кандидатыОбъёма(текст);
  for (const вид of виды) {
    const свои = все.filter((к) => к.вид === вид);
    if (!свои.length) continue;
    const итоговые = [...new Set(свои.filter((к) => к.итог).map((к) => к.значение))];
    if (итоговые.length === 1) return { ...свои.find((к) => к.итог && к.значение === итоговые[0]), однозначно: true };
    const разные = [...new Set(свои.map((к) => к.значение))];
    if (разные.length === 1) return { ...свои[0], однозначно: true };
    // Все строки с ОДНОЙ подписью - объём по разным объектам (маршрутам,
    // корпусам), он складывается. Разные подписи («здание А», «здание Б») не
    // складываются: это может быть и часть, и целое.
    const метки = new Set(свои.map((к) => к.метка));
    if (метки.size === 1 && свои[0].метка.length >= 8) {
      // Две редакции одного ТЗ в закупке («ТЗ.docx» и «ТЗ_от_23.10.docx») дали
      // бы двойную сумму: одинаковая подпись с тем же числом - один раз.
      const слагаемые = [...new Set(свои.map((к) => к.значение))];
      const сумма = Math.round(слагаемые.reduce((s, x) => s + x, 0) * 100) / 100;
      return { ...свои[0], значение: сумма, однозначно: true, слагаемых: слагаемые.length,
        цитата: `${слагаемые.length} строк «${свои[0].цитата.replace(/[\d\s.,]+[^\d]*$/, '').slice(-60).trim()} …» - сумма` };
    }
    return { вид, ед: свои[0].ед, однозначно: false, кандидаты: свои.slice(0, 6) };
  }
  return null;
}

const МЕСЯЦЕВ_В_ДНЕ = 12 / 365;

/** Срок оказания услуг в месяцах: даты «с … по …» или «в течение N месяцев». */
function срокМесяцев(текст) {
  const т = String(текст || '').replace(/\s+/g, ' ');
  const даты = /(?:с|c)\s*(\d{2})\.(\d{2})\.(\d{4})\s*(?:г\.?|года)?\s*(?:по|до)\s*(\d{2})\.(\d{2})\.(\d{4})/i.exec(т);
  if (даты) {
    const от = Date.UTC(+даты[3], +даты[2] - 1, +даты[1]);
    const до = Date.UTC(+даты[6], +даты[5] - 1, +даты[4]);
    const дней = (до - от) / 86400000 + 1;
    if (дней > 0 && дней < 3700) return { месяцев: Math.round(дней * МЕСЯЦЕВ_В_ДНЕ * 10) / 10, цитата: даты[0] };
  }
  const мес = /в\s+течени[еи]\s+(\d{1,3})\s*(?:\([а-яё\s-]+\)\s*)?месяц/i.exec(т);
  if (мес) return { месяцев: +мес[1], цитата: мес[0] };
  return null;
}

/**
 * Цена заказчика за единицу объёма в месяц.
 * @returns {null | {объём, срок, заЕдиницуВМесяц, заЕдиницуЗаСрок, пояснение}}
 */
function ценаЗаказчикаЗаОбъём(текст, нмцк, объект = '') {
  const объём = объёмУслуги(текст, видыДляУслуги(объект));
  if (!объём) return null;
  const срок = срокМесяцев(текст);
  if (!объём.однозначно || !(нмцк > 0)) return { объём, срок, заЕдиницуВМесяц: null, заЕдиницуЗаСрок: null };
  const заСрок = Math.round((нмцк / объём.значение) * 100) / 100;
  // Пробег и рейсы заданы на весь срок - цена за км/рейс, а не в месяц.
  const вМесяц = !объём.заСрок && срок && срок.месяцев > 0 ? Math.round((нмцк / объём.значение / срок.месяцев) * 100) / 100 : null;
  return { объём, срок, заЕдиницуВМесяц: вМесяц, заЕдиницуЗаСрок: заСрок };
}

const деньги = (x) => String(Math.round(x * 100) / 100).replace('.', ',').replace(/\B(?=(\d{3})+(?!\d))/g, ' ') + ' ₽';
const экран = (s) => String(s || '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/** Строки для сообщения клиенту (HTML Telegram). */
function текстОбъёма(р) {
  if (!р) return '';
  const о = р.объём;
  if (!о.однозначно) {
    return `Объём услуги в ТЗ указан несколькими значениями (${о.кандидаты.map((к) => `${String(к.значение).replace('.', ',')} ${к.ед}`).join(', ')}) - `
      + 'итога нет, цена за единицу не считается: проверьте ТЗ.';
  }
  const стр = [`Объём по ТЗ: <b>${String(о.значение).replace('.', ',')} ${о.ед}</b> («${экран(о.цитата).slice(0, 120)}»)`
    + (р.срок ? `, срок ${String(р.срок.месяцев).replace('.', ',')} мес.` : '') + '.'];
  if (р.заЕдиницуВМесяц !== null) стр.push(`Заказчик платит <b>${деньги(р.заЕдиницуВМесяц)} за ${о.ед} в месяц</b> (НМЦК ÷ объём ÷ месяцы) - сравните со своей себестоимостью.`);
  else if (р.заЕдиницуЗаСрок !== null) {
    стр.push(`Заказчик платит <b>${деньги(р.заЕдиницуЗаСрок)} за ${о.ед}</b>`
      + (о.заСрок ? ' (НМЦК ÷ объём на весь срок) - сравните со своей себестоимостью.' : ' за весь срок (срок в ТЗ не найден).'));
  }
  return стр.join('\n');
}

module.exports = { кандидатыОбъёма, объёмУслуги, видыДляУслуги, срокМесяцев, ценаЗаказчикаЗаОбъём, текстОбъёма };
