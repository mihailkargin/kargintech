/**
 * ЗАКУПКА ПО ЦЕНЕ ЗА ЕДИНИЦУ - расчёт, 23.10.2026 (решение владельца
 * «сделаем просчёт закупок по цене за единицу»).
 *
 * Что это за закупка. Ч. 24 ст. 42 44-ФЗ (у 223-ФЗ - «сумма единичных
 * расценок»): заказчик заранее не знает объём - больнице бинты по мере
 * расхода, школе продукты по числу детей. Он фиксирует потолок договора (НМЦК)
 * и предельную цену каждой единицы, поставки идут по заявкам. Сумму закупки
 * посчитать нельзя по закону - поэтому обычная смета здесь бессмысленна.
 *
 * Что считаем вместо неё - только факты:
 *  - цена заказчика за единицу: среднее предложений обоснования - так её
 *    выводит сам заказчик (метод сопоставимых цен);
 *  - закупочная цена за единицу: прайс клиента или поставщики - худшая и лучшая;
 *  - безубыточная цена за единицу: закупка, доставка и налог (из настроек
 *    клиента; не заданы - не учитываются, и это сказано);
 *  - запас: на сколько процентов можно снизить цену заказчика и остаться в нуле;
 *  - сценарий «выберут весь потолок в тех же долях, что в обосновании»: прибыль
 *    = потолок × средний запас. Это допущение, и оно называется допущением.
 *
 * Правило 04.10.2026 действует и здесь: по одним ценам обоснования (потолкам)
 * вывода нет - сравнивать цену заказчика с ней же бессмысленно.
 *
 * Сетевых обращений нет: на входе разобранные позиции и строки сметы.
 */

const r2 = (x) => Math.round(x * 100) / 100;
const среднее = (м) => (м.length ? м.reduce((s, x) => s + x, 0) / м.length : null);

/**
 * @param {{позиции: Array, строки: Array, нмцк?: number|null, налог?: number|null, доставка?: number|null}} д
 *   позиции - из разбора обоснования (prices - предложения за единицу);
 *   строки - estimate.rows в том же порядке (sources с kind 'закупочная').
 */
function расчётЗаЕдиницу(д) {
  const позиции = д.позиции || [];
  const строки = д.строки || [];
  const налог = Number.isFinite(д.налог) && д.налог >= 0 && д.налог < 1 ? д.налог : null;
  const доставка = Number.isFinite(д.доставка) && д.доставка >= 0 ? д.доставка : null;
  const множитель = (1 + (доставка || 0)) / (1 - (налог || 0));
  const итог = [];
  for (let i = 0; i < позиции.length; i++) {
    const п = позиции[i];
    const с = строки[i] && строки[i].name === п.name ? строки[i] : строки.find((x) => x && x.name === п.name) || null;
    const предложения = (п.prices || []).map((x) => x.value).filter((v) => v > 0);
    const цена = предложения.length ? r2(среднее(предложения)) : null;
    const закупочные = ((с && с.sources) || []).filter((x) => x.kind === 'закупочная').map((x) => x.price).filter((v) => v > 0);
    const худшая = закупочные.length ? Math.max(...закупочные) : null;
    const лучшая = закупочные.length ? Math.min(...закупочные) : null;
    const безубыточно = худшая !== null ? r2(худшая * множитель) : null;
    const безубыточноЛучшая = лучшая !== null ? r2(лучшая * множитель) : null;
    итог.push({
      наименование: п.name,
      ед: п.unit || (с && с.unit) || '',
      ценаЗаказчика: цена,
      предложений: предложения.length,
      закупка: худшая,
      закупкаЛучшая: лучшая,
      откуда: закупочные.length ? ((с.sources.find((x) => x.kind === 'закупочная' && x.price === худшая) || {}).source || 'закупочная цена') : null,
      безубыточно,
      безубыточноЛучшая,
      запас: цена && безубыточно !== null ? r2(((цена - безубыточно) / цена) * 100) : null,
      запасЛучший: цена && безубыточноЛучшая !== null ? r2(((цена - безубыточноЛучшая) / цена) * 100) : null
    });
  }
  const сЗакупкой = итог.filter((x) => x.запас !== null);
  // Средний запас - взвешенный ценой заказчика: деньги заказчика делятся между
  // позициями в тех же долях, что в обосновании (допущение сценария).
  const доля = (поле, цена) => {
    const вес = сЗакупкой.reduce((s, x) => s + x.ценаЗаказчика, 0);
    return вес > 0 ? сЗакупкой.reduce((s, x) => s + (x.ценаЗаказчика - x[цена]), 0) / вес : null;
  };
  const запасСредний = сЗакупкой.length ? r2(доля('', 'безубыточно') * 100) : null;
  const запасСреднийЛучший = сЗакупкой.length ? r2(доля('', 'безубыточноЛучшая') * 100) : null;
  const нмцк = Number.isFinite(д.нмцк) && д.нмцк > 0 ? д.нмцк : null;
  return {
    позиции: итог,
    всего: итог.length,
    сЗакупкой: сЗакупкой.length,
    запасСредний,
    запасСреднийЛучший,
    // Прибыль при выборке всего потолка - только если закупочная цена есть у
    // всех позиций с ценой заказчика: иначе неизвестные позиции молча выпали бы.
    прибыльПриПотолке: нмцк && сЗакупкой.length && сЗакупкой.length === итог.filter((x) => x.ценаЗаказчика).length
      ? { худшая: Math.round(нмцк * запасСредний / 100), лучшая: Math.round(нмцк * запасСреднийЛучший / 100) } : null,
    нмцк,
    налогУчтён: налог !== null,
    доставкаУчтена: доставка !== null
  };
}

const деньги = (x) => (x === null || x === undefined ? '-' : String(Math.round(x * 100) / 100).replace('.', ',').replace(/\B(?=(\d{3})+(?!\d))/g, ' ') + ' ₽');
const процент = (x) => (x === null || x === undefined ? '-' : `${String(Math.round(x * 10) / 10).replace('.', ',')}%`);

/** Текст для Telegram и страницы расчёта (HTML Telegram: <b>, без лишней разметки). */
function текстЗаЕдиницу(р, объект = '', пояснение = '') {
  const стр = [];
  стр.push(`🧾 <b>Закупка по цене за единицу</b>${объект ? `: ${экран(объект).slice(0, 160)}` : ''}`);
  стр.push('Объём заказчик не фиксирует: платит за каждую поставленную единицу, поставки по заявкам'
    + (р.нмцк ? `, потолок договора ${деньги(р.нмцк)}.` : '.'));
  стр.push('');
  стр.push('<b>По позициям</b> (цена заказчика за ед. → безубыточно от → запас):');
  for (const п of р.позиции.slice(0, 15)) {
    стр.push(`• ${экран(п.наименование).slice(0, 70)}${п.ед ? ` (${экран(п.ед)})` : ''}: ${деньги(п.ценаЗаказчика)}`
      + (п.безубыточно !== null ? ` → ${деньги(п.безубыточно)} → <b>${процент(п.запас)}</b>` : ' → закупочной цены нет'));
  }
  if (р.позиции.length > 15) стр.push(`… и ещё ${р.позиции.length - 15} - в файле`);
  стр.push('');
  if (!р.сЗакупкой) {
    стр.push('Закупочных цен нет ни по одной позиции - вывода о выгоде нет: цены заказчика выведены из тех же '
      + 'предложений, сравнивать их с ними же бессмысленно. Загрузите прайс или включите поиск поставщиков.');
  } else {
    стр.push(`Средний запас по ${р.сЗакупкой} из ${р.всего} позиций: <b>${процент(р.запасСредний)}</b>`
      + (р.запасСреднийЛучший !== р.запасСредний ? ` (у самых дешёвых поставщиков ${процент(р.запасСреднийЛучший)})` : '')
      + ' - на столько можно снизить цены заказчика и остаться в нуле.');
    if (р.прибыльПриПотолке) {
      стр.push(`Если заказчик выберет весь потолок в тех же долях, что в обосновании: прибыль около `
        + `<b>${деньги(р.прибыльПриПотолке.худшая)}</b>`
        + (р.прибыльПриПотолке.лучшая !== р.прибыльПриПотолке.худшая ? ` (до ${деньги(р.прибыльПриПотолке.лучшая)})` : '')
        + ' при ценах заказчика. Это допущение: заказчик может выбрать меньше потолка.');
    } else if (р.сЗакупкой < р.всего) {
      стр.push(`Прибыль на весь потолок не считается: у ${р.всего - р.сЗакупкой} позиций нет закупочной цены.`);
    }
  }
  const неУчтено = [!р.налогУчтён && 'налог', !р.доставкаУчтена && 'доставка'].filter(Boolean);
  if (неУчтено.length) стр.push(`Не учтено (не задано в настройках): ${неУчтено.join(', ')}.`);
  if (пояснение) стр.push(экран(пояснение));
  return стр.join('\n');
}

function экран(s) { return String(s || '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;'); }

/** Лист Excel «Цена за единицу» (src/xlsx-write.js). */
function листЗаЕдиницу(р, STYLE) {
  const ш = (v) => ({ v, s: STYLE.ШАПКА_ТАБЛИЦЫ });
  const rows = [[{ v: 'Закупка по цене за единицу: объём не фиксирован, поставки по заявкам' + (р.нмцк ? `, потолок договора ${деньги(р.нмцк)}` : ''), s: STYLE.ЗАГОЛОВОК_ДОКУМЕНТА }], [],
    [ш('Наименование'), ш('Ед.'), ш('Цена заказчика за ед.'), ш('Закупка за ед. (худшая)'), ш('Закупка за ед. (лучшая)'), ш('Откуда закупка'), ш('Безубыточно от'), ш('Запас, %')]];
  for (const п of р.позиции) {
    rows.push([{ v: п.наименование, s: STYLE.ПЕРЕНОС }, { v: п.ед, s: STYLE.ЧИСЛО }, { v: п.ценаЗаказчика, s: STYLE.ДЕНЬГИ },
      п.закупка === null ? { v: null, s: STYLE.ПРЕДУПРЕЖДЕНИЕ } : { v: п.закупка, s: STYLE.ДЕНЬГИ },
      п.закупкаЛучшая === null ? { v: null, s: STYLE.ПРЕДУПРЕЖДЕНИЕ } : { v: п.закупкаЛучшая, s: STYLE.ДЕНЬГИ },
      { v: п.откуда || 'закупочной цены нет', s: STYLE.ПЕРЕНОС },
      п.безубыточно === null ? { v: null, s: STYLE.ПРЕДУПРЕЖДЕНИЕ } : { v: п.безубыточно, s: STYLE.ДЕНЬГИ },
      п.запас === null ? { v: null, s: STYLE.ПРЕДУПРЕЖДЕНИЕ } : { v: п.запас, s: STYLE.ЧИСЛО }]);
  }
  rows.push([]);
  rows.push([{ v: 'Цена заказчика - среднее предложений обоснования (так её считает заказчик). Безубыточно - закупка + доставка + налог из ваших настроек. '
    + 'Запас - на сколько процентов можно снизить цену заказчика и остаться в нуле.', s: STYLE.ПОЯСНЕНИЕ }]);
  if (р.запасСредний !== null) rows.push([{ v: `Средний запас (взвешен ценами заказчика): ${процент(р.запасСредний)}`, s: STYLE.ЖИРНЫЙ }]);
  if (р.прибыльПриПотолке) rows.push([{ v: `Если выберут весь потолок в тех же долях: прибыль около ${деньги(р.прибыльПриПотолке.худшая)} - допущение`, s: STYLE.ЖИРНЫЙ }]);
  return { name: 'Цена за единицу', freezeRow: 3, columns: [{ width: 46 }, { width: 8 }, { width: 16 }, { width: 16 }, { width: 16 }, { width: 30 }, { width: 16 }, { width: 10 }], rows };
}

module.exports = { расчётЗаЕдиницу, текстЗаЕдиницу, листЗаЕдиницу };
