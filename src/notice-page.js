/**
 * Разбор страницы САМОЙ ЗАКУПКИ (карточки) — common-info.html.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Раньше все сведения о закупке брались из выдачи
 * поиска: там и НМЦК, и заказчик, и срок подачи. Но 03.10.2026 выяснилось,
 * что портал **не ищет по реестровому номеру** — закупка, найденная по слову,
 * по собственному номеру даёт ноль результатов. Значит вернуться к закупке
 * через поиск нельзя, и единственный способ получить её данные по ссылке —
 * разобрать саму карточку.
 *
 * Без этого расчёт по ссылке невозможен: нет НМЦК — не с чем сравнивать смету,
 * и прибыль с маржой не считаются вовсе.
 *
 * РАЗМЕТКА. На странице две схемы подряд, и обе нужны:
 *   — шапка: cardMainInfo__title -> cardMainInfo__content
 *     (объект, начальная цена, окончание подачи — крупно и коротко);
 *   — подробности: section__title -> section__info
 *     (то же самое точнее, плюс заказчик, площадка, регион, этап).
 *
 * Берём из подробностей, шапку держим запасной: в подробностях значения
 * полнее (например «09.10.2026 09:00 (МСК)» против «09.10.2026»), но у части
 * процедур часть разделов отсутствует.
 */
const { parseMoney, parseDate, decode, tagEnd } = require('./parser');
const { кодыИзТекста, группыЗакупки } = require('./okpd');

/** Классы подписей и значений, в порядке предпочтения. */
const СХЕМЫ = [
  { подпись: 'section__title', значение: 'section__info' },
  { подпись: 'cardMainInfo__title', значение: 'cardMainInfo__content' }
];

// НОВАЯ ВЁРСТКА РАЗДЕЛА 223-ФЗ (замечена 14–15.11.2026): старые классы
// section__/cardMainInfo__ исчезли, карточка свёрстана на registry-entry:
//   — common-text__title -> common-text__value: блок «Информация о закупке»
//     (срок подачи, площадка, даты, организация);
//   — registry-entry__body-title -> registry-entry__body-value: объект
//     закупки и заказчик (значение — ссылка на карточку организации);
//   — price-block__title -> price-block__value: «Начальная цена».
// Три схемы, а не одна: поля разбиты по разным блокам страницы.
const СХЕМЫ_223_НОВЫЕ = [
  { подпись: 'common-text__title', значение: 'common-text__value' },
  { подпись: 'registry-entry__body-title', значение: 'registry-entry__body-value' },
  { подпись: 'price-block__title', значение: 'price-block__value' }
];

/** Очистка текста элемента: теги прочь, сущности развернуть, пробелы сжать. */
function чисто(s) {
  return decode(String(s || '').replace(/<[^>]*>/g, ' '))
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Собирает все элементы с указанными классами в порядке появления.
 *
 * ЛОВУШКА: в атрибутах разметки лежит HTML. У data-tooltip значение вида
 * <span class="custom-tooltiptext">…</span>, и шаблон [^>]* обрывает захват
 * на скобке внутри атрибута, утаскивая текст подсказки в данные. Поэтому
 * конец открывающего тега ищем посимвольно с учётом кавычек — функцией
 * tagEnd из parser.js, написанной ровно для этого.
 */
function элементы(html, классы) {
  const найдено = [];
  for (const класс of классы) {
    let from = 0;
    for (;;) {
      const idx = html.indexOf(класс, from);
      if (idx === -1) break;

      const открыт = html.lastIndexOf('<', idx);
      if (открыт === -1) { from = idx + класс.length; continue; }

      const имяТега = (html.slice(открыт + 1).match(/^([a-zA-Z0-9]+)/) || [])[1];
      const конецТега = tagEnd(html, открыт);
      if (!имяТега || конецТега === -1) { from = idx + класс.length; continue; }

      const закрывающий = '</' + имяТега + '>';
      const хвост = html.slice(конецТега + 1);
      const закрытие = хвост.indexOf(закрывающий);
      const тело = закрытие === -1 ? хвост.slice(0, 2000) : хвост.slice(0, закрытие);

      найдено.push({ класс, текст: чисто(тело), позиция: открыт });
      from = конецТега + 1;
    }
  }
  return найдено.sort((a, b) => a.позиция - b.позиция);
}

/**
 * Сопоставляет подписи со значениями.
 *
 * ЛОВУШКА: подпись без значения — обычное дело. На разобранной карточке
 * «Размещение осуществляет» встречается дважды: первый раз как заголовок
 * раздела без значения, второй — с значением «Заказчик». Если брать
 * «следующий элемент любого вида», заголовок раздела съел бы подпись
 * следующего поля, и всё поехало бы на одну позицию.
 */
function пары(html, схема) {
  const все = элементы(html, [схема.подпись, схема.значение]);
  const out = [];
  for (let i = 0; i < все.length; i++) {
    if (все[i].класс !== схема.подпись) continue;
    const след = все[i + 1];
    if (след && след.класс === схема.значение && след.текст) {
      out.push({ подпись: все[i].текст, значение: след.текст });
    }
  }
  return out;
}

/** Ищет значение по части подписи. Сравнение по очищенному тексту. */
function поле(списки, ...варианты) {
  for (const список of списки) {
    for (const в of варианты) {
      const низ = в.toLowerCase();
      const найдено = список.find((p) => p.подпись.toLowerCase().includes(низ));
      if (найдено && найдено.значение) return найдено.значение;
    }
  }
  return '';
}

/**
 * ОБЕСПЕЧЕНИЕ ЗАЯВКИ И КОНТРАКТА — ИЗ КАРТОЧКИ, А НЕ ДОПУЩЕНИЕМ.
 *
 * Найдено 14.10.2026 по вопросу владельца «условия — просто текст, почему не
 * код». До этого дня обеспечения в расчёте были допущением: 1% заявки и 5%
 * контракта, с подписью «в расчёте принято 5%». А в карточке они стоят готовым
 * полем: на сохранённой карточке закупки 44-ФЗ — «Размер обеспечения
 * исполнения контракта: 10 %». Мы напечатали бы 5% и занизили потребность
 * клиента в деньгах вдвое — опасная сторона ошибки.
 *
 * Значение бывает в процентах («10 %») либо суммой («58 425,00 ₽»). Строгий
 * разбор: произвольный текст числом не становится — та же ловушка, что
 * «ст. 14 Закона № 44» → 1444 в протоколах.
 *
 * @returns {{требуется: boolean|null, процент: number|null, сумма: number|null, текст: string}}
 */
function обеспечение(списки, требуетсяПодпись, размерПодпись) {
  const требТекст = поле(списки, требуетсяПодпись);
  const размер = поле(списки, размерПодпись);
  const требуется = /^да/i.test(требТекст) ? true : (/^нет/i.test(требТекст) ? false : null);

  const п = размер.match(/^(\d{1,2}(?:[.,]\d+)?)\s*%/);
  const с = размер.match(/^(\d[\d\s ]*(?:,\d{1,2})?)\s*(?:₽|руб|Российский рубль)/i);

  return {
    требуется: требуется === null && (п || с) ? true : требуется,
    процент: п ? parseFloat(п[1].replace(',', '.')) : null,
    сумма: с ? parseFloat(с[1].replace(/[\s ]/g, '').replace(',', '.')) : null,
    текст: размер
  };
}

/**
 * Адрес страницы документов из разметки — ссылка вкладки «Документы».
 * Сущности разворачиваются: в разметке «&amp;», а запросу нужен «&».
 */
function ссылкаНаДокументы(html) {
  const m = String(html || '').match(/href="([^"]*documents\.html\?[^"]+)"/);
  if (!m) return '';
  const адрес = decode(m[1]);
  return адрес.startsWith('http') ? адрес : `https://zakupki.gov.ru${адрес.startsWith('/') ? '' : '/'}${адрес}`;
}

/**
 * НАЦИОНАЛЬНЫЙ РЕЖИМ (ст. 14 44-ФЗ, ПП РФ № 1875) - таблица карточки
 * «Объект закупки | Вид требований | Обоснование» (id national-regimen-table…,
 * 24.10.2026). Вид: запрет, ограничение или преимущество российским товарам.
 * Посреднику это решает выбор поставщика: при запрете импорта расчёт по
 * импортному товару ложный. Таблицы нет - null («не указано», а не «нет»).
 * @returns {null | {виды: string[], строки: Array<{объект: string, вид: string}>}}
 */
function нацРежим(html) {
  const т = String(html || '');
  const н = т.indexOf('national-regimen-table');
  if (н < 0) return null;
  const тело = т.slice(н, т.indexOf('</table>', н) + 8);
  const чисто = (s) => decode(String(s).replace(/<br\s*\/?>/gi, '; ').replace(/<[^>]+>/g, ' ')).replace(/\s+/g, ' ').replace(/(;\s*)+$/, '').trim();
  const строки = [];
  for (const р of тело.matchAll(/<tr class="table__row">([\s\S]*?)<\/tr>/g)) {
    const я = [...р[1].matchAll(/<td[^>]*>([\s\S]*?)<\/td>/g)].map((м) => чисто(м[1]));
    if (я.length >= 2 && я[1]) строки.push({ объект: я[0].slice(0, 200), вид: я[1].slice(0, 300) });
  }
  if (!строки.length) return null;
  const виды = [];
  for (const с of строки) {
    if (/запрет/i.test(с.вид) && !виды.includes('запрет')) виды.push('запрет');
    if (/ограничени/i.test(с.вид) && !виды.includes('ограничение')) виды.push('ограничение');
    if (/преимуществ/i.test(с.вид) && !виды.includes('преимущество')) виды.push('преимущество');
  }
  // Повторы строк (одна позиция КТРУ на каждого заказчика) - один раз.
  const уник = [...new Map(строки.map((с) => [с.объект + '|' + с.вид, с])).values()];
  return { виды, строки: уник.slice(0, 20) };
}

/**
 * Разбирает карточку закупки.
 *
 * @param {string} html
 * @param {string} [url] адрес карточки — из него берётся реестровый номер
 * @returns {object} поля в том же виде, что отдаёт parseSearchPage
 */
function parseNoticePage(html, url = '') {
  const текст = String(html || '');
  const подробности = пары(текст, СХЕМЫ[0]);
  const шапка = пары(текст, СХЕМЫ[1]);
  // Старая разметка найдена — новую не читаем: на странице не бывает обеих,
  // а лишние пары не мешают, но и не нужны. Считаем «не найдена» по нулю пар:
  // именно так выглядел слом 14.11.2026, пойманный validateNoticePage.
  const старойНет = подробности.length + шапка.length === 0;
  const новая223 = старойНет ? СХЕМЫ_223_НОВЫЕ.map((с) => пары(текст, с)) : [[], [], []];
  // Порядок важен: список с registry-entry (объект, заказчик) идёт РАНЬШЕ
  // common-text. Подпись «заказчик» по части слова матчит и «(по местному
  // времени заказчика)» в common-text — без порядка вместо организации
  // подставился бы срок подачи (поймано тестом на живой фикстуре 15.11).
  const оба = [подробности, шапка, новая223[1], новая223[2], новая223[0]];

  // Номер берём из адреса: на самой странице он встречается в разном виде,
  // а в ссылке лежит однозначно.
  const номер = (String(url).match(/regNumber=(\d+)/) || [])[1]
    || (текст.match(/№\s*(\d{11,19})/) || [])[1]
    || '';

  // Длина реестрового номера различает законы: 44-ФЗ — 19 цифр, 223-ФЗ — 11.
  // Жёсткая привязка к 19 обнулила бы всю выдачу по 223-ФЗ без единой ошибки.
  const law = номер.length === 19 ? '44-ФЗ' : (номер.length === 11 ? '223-ФЗ' : '');

  const объект = поле(оба, 'наименование объекта закупки', 'объект закупки');
  const ценаТекст = поле(оба, 'начальная (максимальная) цена контракта', 'начальная цена');
  const срокТекст = поле(оба, 'дата и время окончания срока подачи заявок', 'окончание подачи заявок');

  // Коды ОКПД2 позиций и ИКЗ (src/okpd.js). Полные коды карточка печатает
  // в таблице позиций; при «0000» в ИКЗ это единственный их источник.
  const ikz = (текст.match(/openPlanGraphSearchUrl\('(\d{36})'\)/) || [])[1] || '';
  const окпд2 = кодыИзТекста(текст);

  return {
    number: номер,
    law,
    url: url || '',
    object: объект,
    ikz,
    окпд2,
    группыОкпд2: группыЗакупки({ икз: ikz, коды: окпд2 }),
    обеспечениеЗаявки: обеспечение(оба, 'требуется обеспечение заявки', 'размер обеспечения заявки'),
    обеспечениеКонтракта: обеспечение(оба,
      'требуется обеспечение исполнения контракта', 'размер обеспечения исполнения контракта'),
    нацРежим: нацРежим(текст),
    price: parseMoney(ценаТекст),
    priceRaw: ценаТекст,
    deadline: parseDate(срокТекст),
    deadlineRaw: срокТекст,

    // «Заказчик» и «Организация, осуществляющая размещение» — РАЗНЫЕ юрлица.
    // При централизованных закупках уполномоченный орган публикует тендер
    // за заказчика. Смешивать нельзя: проверка контрагента пойдёт не по тому
    // лицу, поэтому роль хранится отдельным полем.
    orgName: поле(оба, 'организация, осуществляющая размещение', 'заказчик'),
    orgRole: поле(оба, 'размещение осуществляет') || 'не указана',

    method: поле(оба, 'способ определения поставщика', 'способ осуществления закупки'),
    stage: поле(оба, 'этап закупки'),
    region: поле(оба, 'регион'),
    platform: поле(оба, 'наименование электронной площадки'),
    published: parseDate(поле(оба, 'размещено', 'размещения извещения')),
    updated: parseDate(поле(оба, 'обновлено', 'текущей редакции')),

    // Два кандидата на адрес документов, как в разборе поиска.
    //
    // ИЗ РАЗМЕТКИ — вкладка «Документы» на самой странице. У 223-ФЗ это
    // ЕДИНСТВЕННЫЙ рабочий путь: адрес содержит noticeGuid, из номера его не
    // вывести. До 14.10.2026 здесь стояла пустая строка, и расчёт по ссылке
    // на закупку 223-ФЗ не открыл документацию НИ РАЗУ — пять попыток из пяти.
    // Выглядело это как «страница документации недоступна», то есть как беда
    // портала, а не нашего разбора.
    //
    // ЗАМЕНОЙ ИМЕНИ СТРАНИЦЫ — для 44-ФЗ это рабочий путь: ссылка в разметке
    // содержит стадию процедуры и отдаёт 404, когда закупка уходит со стадии
    // подачи заявок. Порядок кандидатов для закона выбирает documentsUrls().
    docsUrl: ссылкаНаДокументы(текст),
    docsUrlAlt: url ? String(url).replace('common-info.html', 'documents.html') : '',

    // Сколько пар разобрано — нужно, чтобы отличить «поля нет» от «разметка
    // изменилась и не разобралось ничего». Сумма по всем схемам, включая
    // новую вёрстку 223-ФЗ: validateNoticePage смотрит именно на сумму.
    counts: {
      подробности: подробности.length,
      шапка: шапка.length,
      новая223: новая223.reduce((s, список) => s + список.length, 0)
    }
  };
}

/**
 * Проверки карточки.
 *
 * Главная — первая. Ноль разобранных пар означает, что изменилась разметка
 * портала: страница при этом скачалась, ошибки нет, и дальше всё отработает
 * на пустых данных. Это тихий отказ, и он должен кричать.
 *
 * @returns {Array<string>} пустой список — можно работать дальше
 */
function validateNoticePage(parsed) {
  const проблемы = [];

  const всегоПар = Object.values(parsed.counts || {}).reduce((s, n) => s + (n || 0), 0);
  if (!parsed.counts || всегоПар === 0) {
    проблемы.push(
      'со страницы закупки не разобрано ни одного поля — изменилась разметка портала. '
      + 'Это не «данных нет»: страница получена, но прочитать её не удалось'
    );
    return проблемы;
  }

  if (!parsed.number) проблемы.push('не определён реестровый номер закупки');

  if (parsed.price === null) {
    проблемы.push(
      'НМЦК не распознана' + (parsed.priceRaw ? ` (в разметке: «${parsed.priceRaw}»)` : '')
      + ' — прибыль и маржа не посчитаются'
    );
  }

  // Срок подачи есть не всегда: у 223-ФЗ способом «Иной способ» поля может
  // не быть вовсе. Это не ошибка разбора — значение не выдумываем,
  // а карточку помечаем на проверку.
  if (!parsed.deadline) {
    проблемы.push('не определён срок подачи заявок — проверить по ссылке на закупку');
  }

  // Объект закупки есть не всегда: у закупок по ч.12 ст.93 (электронный
  // магазин) поля нет. Отбор клиента идёт по ключевым словам в объекте,
  // то есть такую закупку нельзя ни отфильтровать, ни уверенно отбросить.
  if (!parsed.object) {
    проблемы.push('не указан объект закупки — отбор по ключевым словам по ней невозможен');
  }

  if (!parsed.orgName) проблемы.push('не определена организация-заказчик');

  return проблемы;
}

// Помощники разбора отдаются наружу намеренно: страницы протоколов, списка
// заявок и результатов определения поставщика устроены той же разметкой, и
// второй её разбор, написанный заново, со временем разошёлся бы с этим. Именно
// так в проекте уже было с командой запуска конвертера — два описания одного и
// того же дали два разных поведения, и разницу заметил бы только клиент.
module.exports = { parseNoticePage, validateNoticePage, нацРежим, пары, элементы, поле, чисто, СХЕМЫ };
