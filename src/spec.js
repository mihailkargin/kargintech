/**
 * ХАРАКТЕРИСТИКИ ТОВАРА ИЗ ТЕХНИЧЕСКОГО ЗАДАНИЯ.
 *
 * Требование владельца 13.10.2026: «тз и документация тендера — приоритет,
 * остальное второстепенно». Повод — живой расчёт закупки 0373200638526000056:
 * поиск поставщиков шёл по одному наименованию из расчёта НМЦК, «Тетрадь
 * ученическая общая», и нашёл тетради по 3–9 ₽ при цене в обосновании
 * 39–45 ₽. Десятикратная разница — это другой товар, а не выгодная закупка.
 * Стоимость закупки по тендеру вышла вилкой 768 тыс. — 1,28 млн ₽.
 *
 * ЧТО ДЕЛАЕТ МОДУЛЬ. Для каждой позиции находит в тексте ТЗ её строку и берёт
 * оттуда характеристики ДОСЛОВНО. Ничего не обобщает и не пересказывает:
 * в поиск уходит ровно то, что написал заказчик. Поэтому результат проверяем —
 * каждая характеристика есть в документе буква в букву.
 *
 * ЧЕГО НЕ ДЕЛАЕТ. Не решает, какая характеристика важна для цены. Это делает
 * модель при поиске и человек при звонке поставщику.
 *
 * Наименования в ТЗ и в расчёте НМЦК заказчик пишет по-разному, поэтому
 * сопоставление идёт двумя шагами: дословное вхождение, затем совпадение всех
 * значимых слов. Способ называется в результате — «дословно» или «по словам».
 * Позиция, не найденная в ТЗ, остаётся без характеристик, и это называется
 * вслух: молча искать по одному наименованию — та самая ошибка, из-за
 * которой модуль появился.
 *
 * Сетевых обращений нет. Данные клиента сюда не попадают: на входе только
 * позиции и текст публичной документации закупки.
 */
const { норм } = require('./verify');

/** Сколько знаков характеристик брать на позицию. Больше — дороже запрос. */
const ПРЕДЕЛ_ЗНАКОВ = 1200;
/** Сколько строк продолжения просматривать после строки с наименованием. */
const ПРЕДЕЛ_СТРОК = 30;

/**
 * Значимые СЛОВА наименования (без чисел), по основе.
 *
 * ЧИСЛА СЮДА НЕ ВХОДЯТ — найдено на живом ТЗ 14.10.2026. Прежняя версия
 * считала число словом, и голое «10» совпадало с чем угодно: «Скобы для
 * степлера (№10)» получили строку скоб №24/6, потому что в ней было «c 1-го
 * по 10-й»; «Скрепки (50 мм)» — строку пункта «50. Скрепки металлические»;
 * «Зажим (19 мм)» — пункт «19.». Пять совпадений «по словам» из семи были
 * чужими, и по чужим характеристикам искался бы не тот товар.
 * Числа теперь сравниваются только с единицей — см. `уточнения`.
 */
function основыСлов(наименование) {
  return норм(String(наименование || '').replace(/\([^)]*\)/g, ' '))
    .replace(/[^a-zа-я ]+/g, ' ')
    .split(' ')
    .filter((с) => с.length >= 4)
    .map((с) => с.slice(0, 5));
}

/** Единицы, при которых число в наименовании — характеристика, а не номер. */
const ЕДИНИЦЫ = 'мм|см|г/м2|г|кг|мл|л|шт|лист[а-яё]*|м';

/** Приводит текст к виду, где «10 мм» и «10мм», «30*40» и «30×40» совпадают. */
function видУточнений(текст) {
  return норм(текст)
    .replace(/(\d)\s*[*×xх]\s*(\d)/g, '$1x$2')
    .replace(new RegExp(`(\\d)\\s+(${ЕДИНИЦЫ})(?![а-яё])`, 'g'), '$1$2')
    .replace(/№\s+(\d)/g, '№$1')
    .replace(/,(\d)/g, '.$1');
}

/**
 * Уточнения из наименования: размеры с единицей, номера «№», габариты.
 * «Зажим для бумаг (10 мм)» → ['10мм']; «Скобы (№24/6)» → ['№24/6'];
 * «Рамка 30*40 см» → ['30x40']. Голое число уточнением не считается.
 */
function уточнения(наименование) {
  const т = видУточнений(наименование);
  const найдено = new Set();
  for (const m of т.matchAll(/(\d+(?:\.\d+)?)x(\d+(?:\.\d+)?)/g)) найдено.add(`${m[1]}x${m[2]}`);
  for (const m of т.matchAll(/№(\d+(?:\/\d+)?)/g)) найдено.add(`№${m[1]}`);
  for (const m of т.matchAll(new RegExp(`(?<![\\d.x])(\\d+(?:\\.\\d+)?)(${ЕДИНИЦЫ})(?![а-яё])`, 'g'))) {
    найдено.add(m[1] + m[2]);
  }
  return [...найдено];
}

/** Уточнение есть в тексте целиком: «№10» не находится в «№10х» и «№104». */
function естьУточнение(вид, у) {
  const экр = у.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');
  // Точка после уточнения допустима («Размер скоб: №24/6.»), точка с цифрой —
  // нет: «№10» не должно находиться в «№10.5».
  return new RegExp(`(?<![\\d.])${экр}(?![\\d/x]|\\.\\d|[а-яё])`).test(вид);
}

/** Строка начинает новый пункт: «1.», «1.8», «50.» в первой ячейке. */
const НОВЫЙ_ПУНКТ = /^\d{1,3}(?:\.\d{1,3})*\.?(?:\t|\s)/;

/**
 * Блок ТЗ, описывающий позицию: строка с наименованием и строки
 * характеристик под ней, до начала следующего пункта.
 */
function блокОт(строки, от, имя, всеИмена) {
  const куски = [строки[от].сырая];
  let знаков = строки[от].сырая.length;
  for (let i = от + 1; i < строки.length && i <= от + ПРЕДЕЛ_СТРОК; i++) {
    const с = строки[i];
    if (НОВЫЙ_ПУНКТ.test(с.сырая)) break;
    if (всеИмена.some((другое) => другое !== имя && !имя.includes(другое) && с.н.includes(другое))) break;
    if (знаков + с.сырая.length > ПРЕДЕЛ_ЗНАКОВ) break;
    куски.push(с.сырая);
    знаков += с.сырая.length;
  }
  return куски;
}

/**
 * Где в ТЗ описана позиция.
 *
 * 1. Наименование целиком, дословно — точнее не бывает.
 * 2. Иначе: строки со всеми значимыми словами наименования, и в БЛОКЕ такой
 *    строки обязаны встретиться все уточнения («10 мм», «№9», «30×40»).
 *    Подошёл ровно один блок — берём. Несколько — не угадываем: у шести
 *    «Зажимов для бумаг» в одном ТЗ слова одинаковые, различает их размер,
 *    и без размера выбор был бы наугад.
 *
 * @returns {{номер: number, способ: string}|{номер: -1, причина: string}|null}
 */
function найтиСтроку(наименование, строки, всеИмена = []) {
  const имя = норм(наименование);
  if (имя.length < 3) return null;

  // ДОСЛОВНО — но не первая попавшаяся строка. Короткое наименование
  // «Дырокол» входит и в «Дырокол металлический», и в «Дырокол пластиковый».
  // Если строк несколько, берётся та, где наименование стоит ОТДЕЛЬНОЙ
  // ячейкой; если таких тоже несколько или ни одной — выбор не делается.
  const дословно = [];
  строки.forEach((с, i) => { if (с.н.includes(имя)) дословно.push(i); });
  if (дословно.length === 1) return { номер: дословно[0], способ: 'дословно' };
  if (дословно.length > 1) {
    const ячейкой = дословно.filter((i) => строки[i].сырая.split('\t')
      .some((ячейка) => норм(ячейка).replace(/^[(\d.)\s]+/, '').trim() === имя));
    if (ячейкой.length === 1) return { номер: ячейкой[0], способ: 'дословно' };
    return { номер: -1, причина: `наименование стоит в ${дословно.length} строках ТЗ — выбор был бы наугад` };
  }

  const основы = основыСлов(наименование);
  if (!основы.length) return null;
  const нужно = уточнения(наименование);

  const подходящие = [];
  строки.forEach((с, i) => {
    if (!основы.every((о) => с.н.includes(о))) return;
    const вид = видУточнений(блокОт(строки, i, имя, всеИмена).join(' '));
    if (нужно.every((у) => естьУточнение(вид, у))) подходящие.push(i);
  });

  if (подходящие.length === 1) {
    return { номер: подходящие[0], способ: нужно.length ? 'по словам и размеру' : 'по словам' };
  }
  if (подходящие.length > 1) {
    return { номер: -1, причина: `в ТЗ ${подходящие.length} подходящих строк — выбор был бы наугад` };
  }
  return null;
}

/**
 * ХАРАКТЕРИСТИКИ ПО НОМЕРУ ПУНКТА — основной способ.
 *
 * Найдено на живом ТЗ закупки 0373200638526000056, 14.10.2026. ТЗ — это
 * пронумерованный «Перечень объектов закупки» в ТОМ ЖЕ порядке, что расчёт
 * НМЦК: «4. Тетрадь ученическая общая» — четвёртая позиция расчёта,
 * «25. Пенокартон» (длина ≥ 1000 мм) — двадцать пятая, «Пенокартон 70*100».
 * Наименования в ТЗ короче («11. Пенокартон», «15. Кисть художественная»),
 * и по названию пятнадцать пенокартонов неотличимы. Номер различает их
 * однозначно.
 *
 * Номеру не верим на слово: заголовок пункта обязан содержать хотя бы одно
 * значимое слово из наименования позиции. Если у заказчика порядок в ТЗ
 * другой, пункт «4.» окажется не тетрадью, проверка это поймает, и позиция
 * пойдёт другими способами, а не получит чужие характеристики.
 *
 * Из блока берётся ПЕРВАЯ ЯЧЕЙКА каждой строки — колонка «Характеристики».
 * Остальные колонки в этом ТЗ — адрес поставки и сроки; в поиск поставщика
 * они не нужны.
 *
 * @param {Array<{name: string, номерВДокументе?: number}>} позиции
 */
function характеристикиПоПорядку(позиции, текстТЗ) {
  const строки = String(текстТЗ || '').split(/\r?\n/);
  // Заголовок пункта: «11. Пенокартон». Подпункты «1.8», «10.13» сюда не
  // попадают — после номера обязательна точка и пробел, а не цифра.
  const заголовки = [];
  строки.forEach((с, i) => {
    const m = с.match(/^(\d{1,3})\.\s+(\S.*)$/);
    if (m) заголовки.push({ номер: Number(m[1]), заголовок: m[2], строка: i });
  });

  const поПозициям = new Map();
  const ШУМ = /^(объ[её]м|характеристики|измерения\)|дополнительные условия|адрес|срок|\d{1,3})$/i;

  for (const п of позиции || []) {
    const н = п.номерВДокументе;
    if (!н || поПозициям.has(п.name)) continue;
    // Пунктов с одним номером в ТЗ несколько: в начале документа идут его
    // собственные разделы «1. Общая информация», «2. Стандарт товаров».
    // Найдено на живом ТЗ 14.10.2026: брался первый «1.», проверка по слову
    // его отвергала, и позиции 1–6 оставались без характеристик. Теперь
    // берётся пункт с этим номером, в заголовке которого есть слово из
    // наименования, — проверка по смыслу та же, просто среди всех кандидатов.
    const словаИмени = основыСлов(п.name);
    const з = заголовки.find((x) => x.номер === н
      && основыСлов(x.заголовок).some((с) => словаИмени.includes(с)));
    if (!з) continue;

    const следующий = заголовки.find((x) => x.строка > з.строка && x.номер === н + 1);
    const до = Math.min(следующий ? следующий.строка : строки.length, з.строка + 1 + ПРЕДЕЛ_СТРОК);
    const характеристики = [];
    let знаков = 0;
    for (let i = з.строка + 1; i < до; i++) {
      const первая = (строки[i].split('\t')[0] || '').trim();
      if (!первая || ШУМ.test(первая)) continue;
      if (знаков + первая.length > ПРЕДЕЛ_ЗНАКОВ) break;
      характеристики.push(первая);
      знаков += первая.length;
    }
    if (!характеристики.length) continue;
    поПозициям.set(п.name, {
      текст: `${з.заголовок} | ${характеристики.join(' ')}`.slice(0, ПРЕДЕЛ_ЗНАКОВ),
      способ: 'по номеру пункта'
    });
  }
  return поПозициям;
}

/**
 * Характеристики для каждой позиции.
 *
 * @param {Array<{name: string}>} позиции
 * @param {string} текстТЗ текст техзадания: ячейки через табуляцию
 * @returns {{поПозициям: Map<string, {текст: string, способ: string}>,
 *            найдено: number, всего: number, безХарактеристик: string[]}}
 */
function характеристикиИзТЗ(позиции, текстТЗ) {
  const строки = String(текстТЗ || '').split(/\r?\n/)
    .map((сырая) => ({ сырая, н: норм(сырая) }))
    .filter((с) => с.н.length > 0);

  // Сначала по номеру пункта — самый надёжный способ, когда ТЗ пронумеровано
  // в порядке расчёта. Остальные — для позиций, которых он не покрыл.
  const поПозициям = характеристикиПоПорядку(позиции, текстТЗ);
  const безХарактеристик = [];
  const всеИмена = (позиции || []).map((п) => норм(п.name)).filter((и) => и.length >= 3);

  for (const п of позиции || []) {
    if (поПозициям.has(п.name)) continue;
    const место = найтиСтроку(п.name, строки, всеИмена);
    if (!место || место.номер < 0) { безХарактеристик.push(п.name); continue; }

    const имя = норм(п.name);
    // Продолжение: строки ниже, пока не начался следующий пункт ТЗ или
    // не встретилось наименование другой позиции.
    const куски = блокОт(строки, место.номер, имя, всеИмена);

    const текст = куски.join(' | ')
      .replace(/\t+/g, ' | ')
      .replace(/\s+/g, ' ')
      .replace(/(\| )+\|/g, '|')
      .trim()
      .slice(0, ПРЕДЕЛ_ЗНАКОВ);

    // Строка, в которой кроме самого наименования ничего нет, характеристик
    // не содержит. Отдавать её в поиск значило бы изображать, что ТЗ учтено.
    if (норм(текст).replace(имя, '').replace(/[^a-zа-я0-9]+/g, '').length < 12) {
      безХарактеристик.push(п.name);
      continue;
    }

    поПозициям.set(п.name, { текст, способ: место.способ });
  }

  return {
    поПозициям,
    найдено: поПозициям.size,
    всего: new Set((позиции || []).map((п) => п.name)).size,
    безХарактеристик
  };
}

/**
 * Характеристики из ответа модели, где каждая строка помечена номером товара.
 *
 * Зачем номер. Наименования в ТЗ и в расчёте НМЦК заказчик пишет по-разному,
 * и на закупке 0373200638526000056 наш код нашёл в ТЗ только 12 позиций из 55.
 * Модель понимает, что «Тетрадь общая 48 л.» и «Тетрадь ученическая общая» —
 * один товар; код по словам этого не видит.
 *
 * РАЗДЕЛЕНИЕ РАБОТЫ то же, что везде в проекте: модель указывает, КАКАЯ строка
 * про какой товар, а содержимое строки переписывает дословно. Указание —
 * суждение модели, поэтому код его проверяет: в строках, помеченных номером
 * товара, обязано встретиться хотя бы одно значимое слово его наименования.
 * Иначе пометка считается ошибкой, характеристики не берутся, причина
 * называется. Чужая характеристика в поиске — это цена не на тот товар.
 *
 * @param {string} текст ответ модели: «номер<TAB>строка документа»
 * @param {Array<{name: string}>} позиции в том же порядке, что список в запросе
 */
function характеристикиПоНомерам(текст, позиции) {
  const группы = new Map();
  for (const строка of String(текст || '').split(/\r?\n/)) {
    const m = строка.match(/^\s*(\d{1,3})[.)]?\t(.*)$/);
    if (!m) continue;
    const н = Number(m[1]);
    if (н < 1 || н > (позиции || []).length) continue;
    if (!группы.has(н)) группы.set(н, []);
    группы.get(н).push(m[2]);
  }

  const поПозициям = new Map();
  const безХарактеристик = [];
  const отвергнуты = [];

  (позиции || []).forEach((п, i) => {
    const куски = группы.get(i + 1);
    if (!куски || !куски.length) { безХарактеристик.push(п.name); return; }

    const текстТовара = куски.join(' | ')
      .replace(/\t+/g, ' | ').replace(/\s+/g, ' ').replace(/(\| )+\|/g, '|').trim()
      .slice(0, ПРЕДЕЛ_ЗНАКОВ);
    const н = норм(текстТовара);
    const основы = основыСлов(п.name).filter((о) => !/^\d+$/.test(о));
    const совпало = н.includes(норм(п.name)) || основы.some((о) => н.includes(о));

    if (!совпало) {
      отвергнуты.push(п.name);
      безХарактеристик.push(п.name);
      return;
    }
    поПозициям.set(п.name, { текст: текстТовара, способ: 'по пометке модели' });
  });

  return {
    поПозициям,
    найдено: поПозициям.size,
    всего: (позиции || []).length,
    безХарактеристик,
    отвергнуты
  };
}

/**
 * ХАРАКТЕРИСТИКИ ПОЗИЦИИ ПО НОМЕРУ СТРОКИ ТЗ. Для одинаковых наименований:
 * «Кабель» шесть раз подряд (0301100049626001767, 20.10.2026), характеристики
 * у каждого свои, и поиск по имени их различить не может. Строка ТЗ берётся,
 * только если в ней номер позиции И её наименование: «1<TAB>Кабель<TAB>…».
 * Продолжение - следующие строки до строки с другим номером.
 *
 * @param {{name: string, номерВДокументе?: number}} позиция
 * @returns {string|null} характеристики дословно
 */
function характеристикиПоСтроке(позиция, текстТЗ) {
  const н = позиция && позиция.номерВДокументе;
  if (!н) return null;
  const имя = норм(позиция.name);
  if (!имя) return null;
  const строки = String(текстТЗ || '').split(/\r?\n/);
  const начало = /^\s*(\d{1,3})\.?\s*$/;
  // Текст из PDF приходит БЕЗ табуляции: «1. Кабель характеристики…» (живой
  // расчёт 0121200000526000036, 13.11.2026: шесть «Кабелей» остались без
  // характеристик, потому что разбор ждал ячеек через таб). Имя обязано идти
  // сразу после номера — строка без имени не берётся, наугад не угадываем.
  const имяЭкр = имя.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const безТаб = new RegExp(`^\\s*(\\d{1,3})[.)]?\\s+${имяЭкр}(?=\\s|$)\\s*([\\s\\S]*)$`, 'i');
  for (let i = 0; i < строки.length; i++) {
    const я = строки[i].split('\t');
    const номер = (я[0] || '').match(начало);
    let куски = null;
    if (номер && Number(номер[1]) === н && норм(я[1] || '') === имя) {
      куски = [я.slice(2).join(' ')];
    } else {
      const m = строки[i].match(безТаб);
      if (m && Number(m[1]) === н && m[2] && m[2].trim()) куски = [m[2]];
    }
    if (!куски) continue;
    for (let j = i + 1; j < строки.length && j <= i + ПРЕДЕЛ_СТРОК; j++) {
      const с = строки[j].split('\t');
      if ((с[0] || '').match(начало) && (с[1] || '').trim()) break;
      куски.push(строки[j].replace(/\t/g, ' '));
    }
    const текст = куски.join(' ').replace(/\s+/g, ' ').trim();
    return текст.length >= 12 ? текст.slice(0, ПРЕДЕЛ_ЗНАКОВ * 2) : null;
  }
  return null;
}

/**
 * КЛЮЧ ДЛЯ ПРАЙСА ИЗ ХАРАКТЕРИСТИК ТЗ: то, что сильнее всего меняет цену и
 * записано полем с подписью. Кабель: число жил × сечение («3х1,5»; 1,5 и 16 мм²
 * различаются по цене в разы). Лампа: цоколь, мощность (нижняя граница
 * диапазона КТРУ), цветовая температура, если min и max совпадают. Ничего не
 * выводится догадкой: нет поля - нет признака.
 *
 * @returns {string|null} «Кабель 3х1,5» или null, если признаков нет
 */
function ключПоТЗ(имя, характеристики) {
  const т = String(характеристики || '');
  const признаки = [];
  const число = (s) => String(s).replace('.', ',').replace(/,0+$/, '');

  const жил = т.match(/(?:числ[а-яё]*\s+(?:токопроводящих\s+)?жил|кол(?:-во|ичеств[а-яё]*)\s+жил)[^:;\n]{0,40}:\s*(\d{1,2})(?!\d|[.,]\d)/i);
  const сеч = [...т.matchAll(/сечени[а-яё]*[^:;\n]{0,60}:\s*(\d+(?:[.,]\d+)?)/gi)][0];
  if (жил && сеч) признаки.push(`${жил[1]}х${число(сеч[1])}`);

  const цоколь = т.match(/цокол[а-яё]*\s*:?\s*([EЕ]\s?\d{2}|G[XUY]?\s?\d{1,2}(?:[.,]\d)?)(?![\d])/i);
  if (цоколь) признаки.push(цоколь[1].replace(/\s/g, '').replace(/^Е/i, 'E').toUpperCase());

  const мощн = т.match(/мощност[а-яё]*[^:;\n]{0,20}:\s*(?:≥|>=|не менее|от)?\s*(\d+(?:[.,]\d+)?)/i);
  if (мощн && признаки.length) признаки.push(`${число(мощн[1])}Вт`);

  const tmax = т.match(/температур[а-яё]*,?\s*max[^:]{0,5}:\s*[≤<=]*\s*(\d{4})/i);
  const tmin = т.match(/температур[а-яё]*,?\s*min[^:]{0,5}:\s*[≥>=]*\s*(\d{4})/i);
  if (tmax && tmin && tmax[1] === tmin[1] && признаки.length) признаки.push(`${tmax[1]}К`);

  if (!признаки.length) return null;
  return `${String(имя || '').trim()} ${признаки.join(' ')}`;
}

/** Документы, которые играют роль технического задания. */
function этоТЗ(вид, имя = '') {
  return /техническ[а-яё]* задани|описание объекта закупки|спецификац/i.test(String(вид || ''))
    || /характеристик/i.test(String(имя || ''));
}

