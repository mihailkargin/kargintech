  //   «Бланк из бумаги или картона (Бланк диплома о профессиональной
  //    переподготовке, приложение к нему в комплекте с твердой обложкой)»
  //
  // Поиск по всей фразе целиком дал НОЛЬ поставщиков — так товар не называет
  // ни один магазин. Поиск по одной только сути из скобок на той же позиции
  // дал восемь типографий.
  //
  // Это не случайность, а свойство документов: заказчик обязан указывать
  // наименование по классификатору. Значит с этим жить всегда.
  const вСкобках = (наименование.match(/\(([^)]{10,})\)/) || [])[1] || '';
  const безСкобок = наименование.replace(/\s*\([^)]*\)\s*/g, ' ').replace(/\s+/g, ' ').trim();

  // Суть — то, что в скобках, если оно содержательнее классификатора.
  // Если скобок нет, суть и есть само наименование.
  const суть = вСкобках.length > 10 ? вСкобках : наименование;
  const классификатор = вСкобках.length > 10 ? безСкобок : '';

  const количество = (позиция && typeof позиция.quantity === 'number')
    ? `${позиция.quantity} ${позиция.unit || ''}`.trim()
    : '';

  // Выдержка из ТЗ - публичный документ, но в нём бывают Ф.И.О. и телефон
  // контрактного управляющего. Найдено 21.10.2026: на сайте было обещано
  // «контакты вырезаются до отправки», а вырезания на этом пути не было.
  // Теперь вырезаются; если контрольная проверка что-то нашла и после этого,
  // характеристики не отправляются вовсе - поиск пойдёт по наименованию.
