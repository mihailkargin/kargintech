/**
 * Поиск поставщиков под позицию спецификации.
 *
 * КЛЮЧЕВАЯ ФУНКЦИЯ ПРОДУКТА. Решение владельца 03.10.2026: смета с формулами
 * не продукт — её тендерный специалист соберёт сам за вечер. Продукт в том,
 * кто подставляет в неё цифры. Сегодня клиент добывает их обзвоном: два часа
 * на тендер, поэтому смотрит пять закупок в неделю вместо пятидесяти.
 *
 * Реестр контрактов отвечает на вопрос «почём это обычно продают заказчику».
 * Посредник спрашивает другое — «почём я это куплю у завода», и живёт со второго.
 *
 * ЧТО ЗДЕСЬ ЕСТЬ И ЧЕГО НЕТ. Сам вызов модели здесь не делается — он живёт
 * в ноде n8n, которая ходит через зарубежного посредника. Здесь только то,
 * что проверяется тестами: сборка запроса, разбор ответа и его проверка.
 *
 * ГЛАВНОЕ ПРАВИЛО. Поставщик без ссылки на источник — выдумка модели, а не
 * «менее точные данные». Модель никогда не отвечает «не нашёл» охотно: она
 * отвечает уверенно и выдаёт правдоподобное название с правдоподобным телефоном.
 * Клиент позвонит по нему, попадёт не туда и перестанет верить всему расчёту.
 * Поэтому запись без проверяемой ссылки отбрасывается, а не помечается.
 *
 * ЧТО УХОДИТ В МОДЕЛЬ. Только наименование позиции из спецификации закупки —
 * то, что заказчик уже опубликовал на портале. Прайс клиента, его наценка,
 * остатки и экономика сюда не попадают физически: в запрос подставляется
 * строка наименования, а не объект настроек.
 */

