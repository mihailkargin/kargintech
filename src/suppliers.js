  if (!наименование) {
    return { ok: false, issue: 'у позиции нет наименования — искать нечего' };
  }
  // Слишком короткое наименование даст мусорную выдачу и потратит деньги.
  if (наименование.length < 4) {
    return { ok: false, issue: `наименование «${наименование}» слишком короткое для поиска` };
  }

  const найти = опции.найти || ПО_УМОЛЧАНИЮ_НАЙТИ;
  const регион = String(опции.регион || '').trim();

  // РАЗБОР НАИМЕНОВАНИЯ НА КЛАССИФИКАТОР И СУТЬ.
  //
  // Найдено 03.10.2026 на настоящей закупке. В обосновании НМЦК наименование
  // пишется по справочнику ОКПД2, а конкретика уходит в скобки:
