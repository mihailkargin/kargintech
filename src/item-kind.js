/**
 * ТОВАР ИЛИ РАБОТА - решение владельца 28.10.2026: разделить товары и
 * работы/услуги по всему сайту (лента, прайс, расчёт, поиск цен). Работы
 * считаются по прайсу клиента или расценкам подрядчиков, товары - по ценам
 * поставщиков. Один расчёт на тендер: «поставка и монтаж» - одна позиция с
 * двумя частями цены.
 *
 * Признаки по надёжности:
 *   1. Код ОКПД2 позиции: разделы 01-33 - товары, 41-43 - строительные
 *      работы, 35-39 и 45-99 - услуги. Код ставит заказчик, ошибок в нём
 *      почти не бывает.
 *   2. Действие в начале наименования: «Устройство…», «Монтаж…», «Разборка…»,
 *      «Вывоз…» - работа; «Поставка…» - товар; и то и другое - товар+работа.
 *   3. Единица, у которой однозначный род: час, смена, выезд, услуга, рейс -
 *      работа; кг, т, шт, упаковка - товар. Метры и м² бывают у обоих и
 *      сами ничего не решают.
 *   4. Иначе - товар: большинство закупок клиентов - поставки, и ошибка в
 *      эту сторону видна (цена товара на работу не найдётся), а не молчит.
 *
 * Сетевых обращений нет.
 */

const ВИД = { ТОВАР: 'товар', РАБОТА: 'работа', ОБА: 'товар+работа' };

// Действие в начале наименования. Границы - не \b: кириллицу он не видит.
const РАБОТА_В_НАЧАЛЕ = /^(?:[\d.)\s-]*)(устройств|монтаж|демонтаж|разборк|ремонт|окраск|очистк|обработк|установк|прокладк|укладк|герметизац|огрунтовк|грунтовк|выравниван|укрыти|вывоз|погрузк|разгрузк|уборк|обслуживан|техническ[а-яё]*\s+обслуживан|проведени|оказани|выполнени|пусконаладк|наладк|испытани|замен[аы]|восстановлен|заделк|облицовк|штукатурк|шпаклевк|утеплени|снятие|подготовк|посев|посадк|кошени|покос|стрижк|перевозк|транспортировк|охран|дезинфекц|дезинсекц|дератизац|обучени|разработк|проектировани|изыскани|диагностик|поверк|сопровождени|аренд|подвеск|оценк[аи]\s|комплектаци)/i;
// «Установка ультрафиолетовая…», «Установка для дезинфекции» - оборудование,
// не работа: после «установка» прилагательное или «для».
const УСТАНОВКА_ОБОРУДОВАНИЕ = /^(?:[\d.)\s-]*)установк[аи]\s+(для\s|[а-яё]+(ая|ый|ой|ий|ые|ых)(\s|$))/i;
const ТОВАР_В_НАЧАЛЕ =/^(?:[\d.)\s-]*)(поставк|приобретени|закупк|покупк)/i;
const ПОСТАВКА_ГДЕ_УГОДНО = /(^|[\s,])поставк[а-яё]*/i;
const МОНТАЖ_ГДЕ_УГОДНО = /(с\s+|и\s+|,\s*)((его|их|этого|этих)\s+)?(монтаж|установк|укладк|подключени|пусконаладк|доставк[а-яё]*\s+и\s+монтаж)|монтаж[а-яё]*\s+и\s+поставк/i;

const ЕДИНИЦА_РАБОТЫ = /^(час|ч|чел\.?\s*-?\s*ч(ас)?|маш\.?\s*-?\s*ч(ас)?|смен[а-яё]*|выезд[а-яё]*|рейс[а-яё]*|услуг[а-яё]*|мес(яц)?[а-яё]*|сут(ки|ок)?|вызов[а-яё]*|чел\.?\s*-?\s*д(ень|н)?[а-яё]*|раб\.?\s*мест[а-яё]*)\.?$/i;
const ЕДИНИЦА_ТОВАРА = /^(кг|килограмм[а-яё]*|т|тн|тонн[а-яё]*|шт|штук[а-яё]*|упак[а-яё]*|уп|пач[а-яё]*|рулон[а-яё]*|рул|компл[а-яё]*|комплект[а-яё]*|набор[а-яё]*|л|литр[а-яё]*|бут[а-яё]*|флак[а-яё]*|пар[аы]?|лист[а-яё]*|короб[а-яё]*)\.?$/i;

/** Раздел ОКПД2 по коду «41.20.40.000» → 41; null, если кода нет. */
function разделОкпд(код) {
  const м = /^(\d{2})\.\d{2}/.exec(String(код || '').trim());
  return м ? Number(м[1]) : null;
}

function видПоОкпд(код) {
  const р = разделОкпд(код);
  if (р === null) return null;
  if (р >= 1 && р <= 33) return ВИД.ТОВАР;
  return ВИД.РАБОТА;
}

/**
 * Вид позиции расчёта.
 * @param {{name: string, unit?: string, okpd?: string}} p
 * @returns {{вид: string, почему: string}}
 */
function видПозиции(p) {
  const имя = String((p && p.name) || '').trim();
  const ед = String((p && p.unit) || '').toLowerCase().replace(/ё/g, 'е').trim();
  const работаВНачале = РАБОТА_В_НАЧАЛЕ.test(имя) && !УСТАНОВКА_ОБОРУДОВАНИЕ.test(имя);
  const товарВНачале = ТОВАР_В_НАЧАЛЕ.test(имя);
  const сМонтажом = МОНТАЖ_ГДЕ_УГОДНО.test(имя);

  // «Поставка и монтаж», «Кондиционер с установкой» - одна позиция, две части цены.
  if (сМонтажом && (товарВНачале || ПОСТАВКА_ГДЕ_УГОДНО.test(имя) || (!работаВНачале && !ЕДИНИЦА_РАБОТЫ.test(ед)))) {
    return { вид: ВИД.ОБА, почему: 'поставка вместе с монтажом или установкой' };
  }
  const поКоду = видПоОкпд(p && p.okpd);
  if (поКоду) return { вид: поКоду, почему: `раздел ОКПД2 ${разделОкпд(p.okpd)}` };
  if (работаВНачале) return { вид: ВИД.РАБОТА, почему: 'наименование начинается с работы' };
  if (товарВНачале) return { вид: ВИД.ТОВАР, почему: 'наименование начинается с поставки' };
  if (ЕДИНИЦА_РАБОТЫ.test(ед)) return { вид: ВИД.РАБОТА, почему: `единица «${ед}» - работы или услуги` };
  if (ЕДИНИЦА_ТОВАРА.test(ед)) return { вид: ВИД.ТОВАР, почему: `единица «${ед}» - товара` };
  return { вид: ВИД.ТОВАР, почему: 'признаков работы нет' };
}

/**
 * Вид закупки целиком - для ленты и фильтров.
 * @param {{object?: string, группыОкпд2?: string[], okpdGroup?: string}} tender
 * @param {Array} [позиции] - если документация уже разобрана
 * @returns {'товары'|'работы и услуги'|'товары и работы'}
 */
function видЗакупки(tender, позиции = []) {
  if (позиции && позиции.length) {
    const виды = позиции.map((p) => видПозиции(p).вид);
    const работ = виды.filter((в) => в !== ВИД.ТОВАР).length;
    const товаров = виды.filter((в) => в !== ВИД.РАБОТА).length;
    if (!работ) return 'товары';
    if (!товаров) return 'работы и услуги';
    return 'товары и работы';
  }
  const коды = [...((tender && tender.группыОкпд2) || []), (tender && tender.okpdGroup) || ''].filter(Boolean);
  const поКодам = коды.map(видПоОкпд).filter(Boolean);
  if (поКодам.length && поКодам.every((в) => в === ВИД.ТОВАР)) return 'товары';
  if (поКодам.length && поКодам.every((в) => в === ВИД.РАБОТА)) return 'работы и услуги';
  if (поКодам.length) return 'товары и работы';
  const объект = String((tender && tender.object) || '');
  const п = видПозиции({ name: объект });
  return п.вид === ВИД.ТОВАР ? 'товары' : п.вид === ВИД.РАБОТА ? 'работы и услуги' : 'товары и работы';
}

module.exports = { ВИД, видПозиции, видЗакупки, разделОкпд };
