/**
 * Разбор страниц РЕЗУЛЬТАТОВ закупки: кто победил, за сколько, сколько было
 * участников. Это источник статистики снижения цены.
 *
 * ЗАЧЕМ ЭТО СУЩЕСТВУЕТ. В расчёте стояло ожидаемое снижение цены 12% — число,
 * под которым не было основания. Владелец его убрал 05.10.2026: «раз
 * обоснования нет, зачем ты его пишешь». Снижение определяет цену победы, то
 * есть всю выручку, поэтому ошибка в нём переворачивает вывод о выгодности
 * целиком, причём в опасную сторону: заниженное снижение делает убыточный
 * тендер выгодным на вид.
 *
 * Правильный источник — протоколы прошлых закупок: портал публикует и начальную
 * цену, и цену победы, и все поданные предложения. Доступность проверена
 * 26.09.2026 обычными запросами, без входа в кабинет.
 *
 * ЧТО РАЗБИРАЕТСЯ И ОТКУДА
 *
 *   Страница «Результаты определения поставщика» — НМЦК и цена победы на одном
 *   экране. Постраничности нет, таблица победителей отдаётся сервером.
 *
 *   Вкладка «Список заявок» внутри протокола — все поданные цены с местами и,
 *   у аукциона, причины отклонения.
 *
 * ТРИ ОГРАНИЧЕНИЯ, НАЙДЕННЫЕ НА РЕАЛЬНЫХ СТРАНИЦАХ. Каждое — повод для честной
 * пометки, а не для догадки:
 *
 *   1. СПИСОК ЗАЯВОК РАЗБИТ ПО 10, А БЛОК ПОСТРАНИЧНОСТИ ПУСТОЙ. В разметке
 *      лежит <div id="bidsListNavigation"></div> — его наполняет JavaScript,
 *      которого у нас нет. Значит по странице НЕЛЬЗЯ узнать, есть ли ещё
 *      заявки. Если строк ровно столько, сколько вмещает страница, число
 *      участников считается НЕ ОПРЕДЕЛЁННЫМ, а не равным десяти. Иначе
 *      статистика поехала бы в опасную сторону: потерялись бы самые дорогие
 *      предложения, и конкуренция выглядела бы выше, чем есть.
 *
 *   2. ТАБЛИЦА ПОБЕДИТЕЛЕЙ СОДЕРЖИТ ТОЛЬКО ПОБЕДИТЕЛЕЙ. Называется «Участники,
 *      с которыми планируется заключить контракт» — по ней число участников
 *      закупки не определяется никак.
 *
 *   3. У АУКЦИОНА ПРОТОКОЛ ПОДАЧИ ЦЕНОВЫХ ПРЕДЛОЖЕНИЙ (тип cpa) В СЕРВЕРНОЙ
 *      РАЗМЕТКЕ ПУСТ — таблицы нет вовсе, она рисуется JavaScript. Брать ходы
 *      аукциона оттуда нельзя. Цены берутся из списка заявок (тип iea).
 *
 * ИМЁН УЧАСТНИКОВ ПОРТАЛ НЕ ПУБЛИКУЕТ — только идентификационные номера.
 * Название известно лишь для победителя и лишь через реестр контрактов после
 * подписания. Для статистики снижения имена не нужны.
 */
const { parseMoney, parseDate, decode } = require('./parser');
const { пары, поле, чисто, СХЕМЫ } = require('./notice-page');

/** Сколько заявок портал показывает на одной странице по умолчанию. */
const ЗАЯВОК_НА_СТРАНИЦЕ = 10;

/**
 * Способы закупки. Разделять их обязательно: снижение у них разное по природе,
 * и среднее по всем способам — число, не означающее ничего.
 *
 *   аукцион    — участники давят цену шагами, снижение самое большое;
 *   котировки  — цена подаётся один раз, торга нет;
 *   конкурс    — цена лишь один из критериев рядом с опытом и сроками,
 *                поэтому снижение слабое;
 *   единственный поставщик — снижения нет вовсе, такие закупки выбрасываются.
 */
const СПОСОБ = {
  АУКЦИОН: 'электронный аукцион',
  КОТИРОВКИ: 'запрос котировок',
  КОНКУРС: 'конкурс',
  ЕДИНСТВЕННЫЙ: 'единственный поставщик',
  ИНОЙ: 'иной способ'
};

/**
 * Определяет способ закупки по тексту страницы.
 *
 * ЛОВУШКА КИРИЛЛИЦЫ: шаблоны здесь без \b и \w — они считают буквами только
 * латиницу, и «\bаукцион» не совпал бы никогда. В проекте эта ошибка срабатывала
 * пять раз, и каждый раз код выглядел рабочим, молча ничего не находя.
 * Проверку делает tests/test-patterns.js.
 *
 * Порядок проверок важен: «запрос котировок» содержит слово «запрос», которое
 * есть и в «запросе предложений», поэтому сначала ищется более длинное.
 */
function определитьСпособ(текст) {
  const t = String(текст || '').toLowerCase();
  if (/единственн[а-яё]*\s+поставщик/.test(t)) return СПОСОБ.ЕДИНСТВЕННЫЙ;
  if (/запрос\s+котировок/.test(t)) return СПОСОБ.КОТИРОВКИ;
  if (/аукцион/.test(t)) return СПОСОБ.АУКЦИОН;
  if (/конкурс/.test(t)) return СПОСОБ.КОНКУРС;
  return СПОСОБ.ИНОЙ;
}

/**
 * Деньги из ячейки таблицы — СТРОГО, иначе число берётся из воздуха.
 *
 * ЛОВУШКА, НАЙДЕННАЯ НА РЕАЛЬНОЙ СТРАНИЦЕ 05.10.2026. У отклонённых заявок
 * колонки цены нет, зато есть причина отклонения: «Несоответствие требованиям
 * ст. 14 Закона № 44 ФЗ». Общая parseMoney выбрасывает из строки всё, кроме
 * цифр, склеивает «14» и «44» и возвращает 1444. В выводе это выглядело как
 * цена предложения — четыре отклонённые заявки получили цену 1444 ₽.
 *
 * Чем это опасно: такие «цены» попадают в статистику предложений и тянут её
 * вниз, то есть закупка выглядит дешевле, чем была. Ошибка тихая — числа
 * правдоподобные, ничего не падает.
 *
 * Отдельно: идентификационный номер участника (121939621) для parseMoney тоже
 * законное число. Взяв «последнее похожее на деньги», можно получить его.
 *
 * Поэтому признак денег строгий: только цифры, пробелы и необязательные копейки
 * через запятую, с необязательным знаком рубля — и обязательно либо копейки,
 * либо знак рубля. Оба вида, встреченные на портале, проходят: «52 041,28 ₽» в
 * списке заявок и «52 041,28» в таблице победителей. Идентификатор без копеек и
 * без рубля не проходит, текст с буквами не проходит.
 *
 * Цена без копеек и без знака рубля будет пропущена — и это правильная сторона
 * ошибки: ненайденная цена помечается, выдуманная портит расчёт молча.
 */
function деньгиИзЯчейки(ячейка) {
  const s = String(ячейка || '').replace(/ /g, ' ').trim();
  if (!s) return null;
  // Любая буква означает, что это не число, а текст. Знак рубля буквой не
  // считается, он разрешён ниже шаблоном.
  if (/[A-Za-zА-Яа-яЁё]/.test(s)) return null;
  if (!/^[\d\s]+(,\d{1,2})?\s*₽?$/.test(s)) return null;
  // Требуем явный признак денег: копейки или знак рубля. Иначе под шаблон
  // подходит идентификационный номер участника.
  if (!/,/.test(s) && !/₽/.test(s)) return null;
  return parseMoney(s);
}

/** Строки таблицы: массив массивов очищенных ячеек. */
function строкиТаблиц(html) {
  const out = [];
  const тела = String(html || '').match(/<tbody[\s\S]*?<\/tbody>/g) || [];
  for (const тело of тела) {
    const trs = тело.match(/<tr[\s\S]*?<\/tr>/g) || [];
    for (const tr of trs) {
      const tds = tr.match(/<td[\s\S]*?<\/td>/g) || [];
      const ячейки = tds.map((td) => чисто(td));
      // Пустые строки портал вставляет между данными — это скрытые блоки
      // «подробнее», которые наполняет JavaScript. Они не данные.
      if (ячейки.some((c) => c)) out.push(ячейки);
    }
  }
  return out;
}

/** Шапки всех таблиц страницы, в порядке появления. */
function шапкиТаблиц(html) {
  return (String(html || '').match(/<th[\s\S]*?<\/th>/g) || []).map((th) => чисто(th));
}

/**
 * Таблицы страницы по отдельности: каждая со своими шапками и своими строками.
 *
 * ЗАЧЕМ ЭТО ПОЯВИЛОСЬ. Раньше строки собирались со всей страницы разом, и чтобы
 * отличить строку победителя от строки заказчика, приходилось требовать слово
 * «Победитель» в одной из ячеек. На сборе 05.10.2026 это выбросило 7 закупок из
 * 50: у закупки с единственной заявкой колонка «Порядковые номера» ПУСТАЯ —
 * ранжировать нечего, когда заявка одна. Строка выглядит так:
 *     121996875  ||  (пусто)  ||  25 125,00
 * и признака «Победитель» в ней нет вовсе.
 *
 * Привязка строк к своей таблице убирает нужду в этом признаке: достаточно
 * найти таблицу, у которой в шапке «Предложения участников», и взять её строки.
 * Шапка таблицы — свойство разметки, а не содержания, и пустой она не бывает.
 *
 * Границы таблиц ищутся с учётом вложенности: портал кладёт таблицы в таблицы
 * для вёрстки, и шаблон «до первого </table>» закрыл бы внешнюю таблицу на
 * закрытии внутренней.
 */
function таблицы(html) {
  const s = String(html || '');
  const блоки = [];
  const re = /<table\b|<\/table>/gi;
  const стек = [];
  let m;
  while ((m = re.exec(s))) {
    if (m[0].charAt(1) === '/') {
      const начало = стек.pop();
      if (начало !== undefined && стек.length === 0) {
        блоки.push(s.slice(начало, m.index + m[0].length));
      }
    } else {
      стек.push(m.index);
    }
  }
  return блоки.map((блок) => ({ шапки: шапкиТаблиц(блок), строки: строкиТаблиц(блок) }));
}

/**
 * Признаки того, что закупка признана несостоявшейся.
 *
 * ОДНА ФУНКЦИЯ НА ПРОЕКТ — И ЭТО НЕ ПРИДИРКА. Признаки были описаны дважды:
 * здесь и в app/diagnose-protocol.js, разными шаблонами. Описания разошлись, и
 * 05.10.2026 это дало прямое противоречие в выводе: диагностика печатала
 * «несостоявшаяся закупка: «несостоявш…»», а разбор той же страницы — «не
 * состоялась: false». Поверить было нечему. Это уже второй такой случай в
 * проекте: первым была команда запуска конвертера, описанная в двух местах.
 *
 * ГЛАВНЫЙ ПРИЗНАК — СТРУКТУРНЫЙ, А НЕ ПОИСК СЛОВ. Портал печатает отдельное
 * поле «Основание признания торгов несостоявшимися», и его заполненность
 * означает факт, а не совпадение слова где-то в тексте страницы. Поиск по
 * тексту оставлен запасным: шаблон `призна[а-яё]*\s+несостоявш` не совпадал с
 * настоящей подписью «признания ТОРГОВ несостоявшимися» — между словами стоит
 * третье слово, и проверка молча не находила ничего.
 *
 * РЕШАЮЩИЕ ПРИЗНАКИ ОТДЕЛЕНЫ ОТ ПРОСТО НАЙДЕННЫХ, и это не формальность.
 * Слово «несостоявшимися» встречается в самой ПОДПИСИ поля, а подпись портал
 * может печатать всегда — в том числе с пустым значением. Если считать её
 * признаком, несостоявшимися окажутся все закупки подряд, и настоящие ошибки
 * разбора спрячутся под штатной причиной. Это та же ошибка, что уже была в
 * проекте с «Недействующей» редакцией документации: подстрока «действующ»
 * содержится и в слове «недействующая».
 *
 * Поэтому решающими считаются только заполненное значение поля и формулировки,
 * которые подписью быть не могут. Остальное печатается как наблюдение.
 *
 * @param {string} текст страница целиком
 * @param {string} [основание] значение поля «Основание признания… несостоявшимися»
 * @returns {{признаки: Array<string>, решающие: Array<string>}}
 */
function признакиНесостоявшейся(текст, основание = '') {
  const низ = String(текст || '').toLowerCase();
  const признаки = [];
  const решающие = [];

  const вНиз = String(основание || '').trim();
  if (вНиз) {
    const п = 'поле «Основание признания торгов несостоявшимися» заполнено: '
      + вНиз.slice(0, 80);
    признаки.push(п);
    решающие.push(п);
  }

  const фразы = [
    [/не\s+подано\s+ни\s+одной\s+заявки/, '«не подано ни одной заявки»'],
    [/все\s+заявки\s+отклонен/, '«все заявки отклонены»'],
    [/закупка\s+не\s+состоял|торги\s+не\s+состоял|аукцион\s+не\s+состоял/, '«…не состоялась»']
  ];
  for (const [шаблон, имя] of фразы) {
    if (шаблон.test(низ)) { признаки.push(имя); решающие.push(имя); }
  }

  // Не решающий: это слово стоит в подписи поля, которая может быть и пустой.
  if (/призна[а-яё]*\s+(торгов\s+|закупки\s+)?несостоявш/.test(низ)) {
    признаки.push('«признан… несостоявш…» встречается в тексте (может быть подписью пустого поля)');
  }

  return { признаки, решающие };
}

/**
 * Признаки того, что заявка была ровно одна.
 *
 * ПОЧЕМУ ЭТО ВАЖНО ОТДЕЛЬНО. По пункту 1 части 1 статьи 52 закупка с одной
 * заявкой признаётся несостоявшейся — но контракт с этим участником ЗАКЛЮЧАЕТСЯ,
 * по его цене. То есть формально «не состоялась», а фактически это заключённый
 * контракт с известной ценой победы, и он отвечает требованию владельца «бери
 * только те контракты, которые были заключены».
 *
 * При этом торга в такой закупке не было вовсе, и смешивать её с конкурентными
 * нельзя: на сборе 05.10.2026 единственные заявки дали снижение 1,6% и 14,0%
 * против медиан 18,5% и 24,3% у конкурентных. Смешав, мы занизили бы ожидаемое
 * снижение — ровно та опасная сторона ошибки, из-за которой убрали 12%.
 */
function признакиЕдинственнойЗаявки(текст, основание = '') {
  const низ = (String(основание || '') + ' ' + String(текст || '')).toLowerCase();
  const найдено = [];
  if (/подана\s+(только\s+)?одна\s+заявка/.test(низ)) найдено.push('«подана только одна заявка»');
  if (/единственн[а-яё]*\s+заявк/.test(низ)) найдено.push('«единственная заявка»');
  if (/п\.\s*1\s+ч\.\s*1\s+ст\.\s*52|пункт[а-яё]*\s+1\s+част[а-яё]*\s+1\s+стат[а-яё]*\s+52/.test(низ)) {
    найдено.push('ссылка на п. 1 ч. 1 ст. 52');
  }
  return найдено;
}

/**
 * Разбирает страницу «Результаты определения поставщика».
 *
 * @param {string} html
 * @param {string} [url]
 * @returns {object} {номер, объект, способ, нмцк, ценаПобеды, победители, issues}
 */
function parseSupplierResults(html, url = '') {
  const текст = String(html || '');
  const issues = [];

  const подробности = пары(текст, СХЕМЫ[0]);
  const шапка = пары(текст, СХЕМЫ[1]);
  const оба = [подробности, шапка];

  const номер = (String(url).match(/regNumber=(\d+)/) || [])[1]
    || (текст.match(/№\s*(\d{11,19})/) || [])[1]
    || '';

  const объект = поле(оба, 'наименование объекта закупки', 'объект закупки');
  const нмцк = parseMoney(поле(оба, 'начальная (максимальная) цена контракта', 'начальная цена'));
  const способ = определитьСпособ(текст);

  // Победители: таблица с колонкой «Предложения участников». Берём её по
  // подписи колонки, а не по порядку таблиц на странице: порядок меняется от
  // процедуры к процедуре, а подпись — нет.
  //
  // ДЛИНУ ИДЕНТИФИКАТОРА УЧАСТНИКА ЗАДАВАТЬ НЕЛЬЗЯ. Здесь стояло /^\d{6,12}$/.
  // На первом сборе 05.10.2026 это выбросило 38 закупок из 50. Пример —
  // 0322200001326000183: строка победителя есть и выглядит так
  //     6  ||  1 - Победитель  ||  129 336,00
  // то есть идентификатор ОДНОСИМВОЛЬНЫЙ. Это тот же класс ошибки, что с
  // реестровыми номерами (19 цифр у 44-ФЗ против 11 у 223-ФЗ). Длина поля на
  // портале не обещана никем, поэтому идентификатор здесь — необязательная
  // подробность: для статистики снижения он не нужен вовсе.
  //
  // СЛОВО «ПОБЕДИТЕЛЬ» В СТРОКЕ ТРЕБОВАТЬ ТОЖЕ НЕЛЬЗЯ — и это следующая та же
  // ошибка. На третьем сборе 05.10.2026 требование выбросило 7 закупок из 50: у
  // закупки с единственной заявкой колонка «Порядковые номера» пустая, потому
  // что ранжировать нечего. Строка 0323200011526000001 выглядит так:
  //     121996875  ||  (пусто)  ||  25 125,00
  // Цена победы там есть, а признака не было, и отказ выглядел как ошибка
  // разбора, которой не было в том месте, где её искали.
  //
  // Теперь строки берутся из СВОЕЙ таблицы — той, у которой в шапке
  // «Предложения участников», — и строкой победителя считается строка с ценой.
  // Признаком служит разметка, а не содержание ячейки.
  const всеТаблицы = таблицы(текст);
  const таблицаПобедителей = всеТаблицы.find(
    (т) => т.шапки.some((h) => /предложени[а-яё]*\s+участник/i.test(h))
  );
  const естьТаблицаПобедителей = Boolean(таблицаПобедителей);

  // ЦЕНА БЕРЁТСЯ ИЗ СВОЕЙ КОЛОНКИ, А НЕ «ПЕРВАЯ ПОХОЖАЯ НА ДЕНЬГИ В СТРОКЕ».
  //
  // Колонку задаёт шапка «Предложения участников»: её номер и есть номер ячейки
  // с ценой. «Первая похожая на деньги» — догадка, и она ломается, как только в
  // таблице появляется ещё одна числовая колонка (размер снижения, цена за
  // единицу, рейтинг заявки). Такая подмена тихая: число правдоподобное,
  // ничего не падает, а снижение уезжает в любую сторону.
  //
  // Запасной путь оставлен: если число ячеек не совпало с числом подписей,
  // берётся первая ячейка с деньгами, и это помечается — чтобы на такой закупке
  // было видно, что колонку определить не удалось.
  const подписи = таблицаПобедителей ? таблицаПобедителей.шапки : [];
  const колонкаЦены = подписи.findIndex((h) => /предложени[а-яё]*\s+участник/i.test(h));

  const победители = [];
  let ценаНеИзКолонки = false;
  if (таблицаПобедителей) {
    for (const ячейки of таблицаПобедителей.строки) {
      const деньги = ячейки.map(деньгиИзЯчейки);

      let индексЦены = -1;
      const колонкаПодходит = колонкаЦены >= 0
        && ячейки.length === подписи.length
        && деньги[колонкаЦены] !== null
        && деньги[колонкаЦены] > 0;
      if (колонкаПодходит) {
        индексЦены = колонкаЦены;
      } else {
        индексЦены = деньги.findIndex((v) => v !== null && v > 0);
        if (индексЦены !== -1 && колонкаЦены >= 0) ценаНеИзКолонки = true;
      }
      if (индексЦены === -1) continue;

      const место = ячейки.find((c) => /победител|^\d+\s*-\s*[А-Яа-яЁё]/i.test(c)) || '';
      // Идентификатор — любая ячейка из одних цифр, кроме той, где цена.
      const ид = ячейки.find((c, i) => i !== индексЦены && /^\d+$/.test(c)) || '';
      победители.push({ ид, место, цена: деньги[индексЦены] });
    }
  }

  // Цена победы — предложение того, у кого в месте написано «Победитель».
  // Брать «первую строку» нельзя: порядок строк портал не обещает.
  //
  // Если слова «Победитель» нет ни в одной строке, но строка всего одна — это
  // она и есть: в таблице «Участники, с которыми планируется заключить контракт»
  // других участников не бывает. Несколько строк без явного победителя — это
  // многолотовая закупка, и тогда цену победы выбирать нельзя: угадывание здесь
  // дало бы тихо неверное снижение. Такой случай помечается замечанием.
  let победитель = победители.find((p) => /победител/i.test(p.место)) || null;
  let многоБезПобедителя = false;
  if (!победитель && победители.length === 1) победитель = победители[0];
  if (!победитель && победители.length > 1) многоБезПобедителя = true;
  const ценаПобеды = победитель ? победитель.цена : null;

  // ЗАКУПКА НЕ СОСТОЯЛАСЬ — ЭТО НЕ ОШИБКА РАЗБОРА, И ПУТАТЬ ИХ НЕЛЬЗЯ.
  //
  // Первый сбор 05.10.2026 отбросил 36 закупок из 50 с одной формулировкой
  // «нет начальной цены или цены победы». Под ней смешались два совершенно
  // разных случая: закупка, которая действительно не состоялась (заявок не
  // подали, или все отклонили), и страница, с которой мой разбор не справился.
  // Пока они под одной подписью, ошибку в коде не видно вовсе.
  //
  // Признаки собирает одна общая функция — см. признакиНесостоявшейся(). Главный
  // из них структурный: заполненность поля «Основание признания торгов
  // несостоявшимися». Поиском слов по тексту это делалось раньше и не работало.
  const низ = текст.toLowerCase();
  const основаниеНесостоявшейся = поле(оба,
    'основание признания торгов несостоявшимися',
    'основание признания закупки несостоявшейся',
    'основание признания несостоявш');
  const признакиНС = признакиНесостоявшейся(текст, основаниеНесостоявшейся);
  const неСостоялась = признакиНС.решающие.length > 0;

  // ЕДИНСТВЕННАЯ ЗАЯВКА — ЭТО ЗАКЛЮЧЁННЫЙ КОНТРАКТ, А НЕ ПРОВАЛЕННАЯ ЗАКУПКА.
  //
  // По п. 1 ч. 1 ст. 52 закупка с одной заявкой признаётся несостоявшейся, но
  // контракт с этим участником заключается по его цене. Отбрасывать такие
  // наблюдения нельзя — цена победы в них есть и она настоящая. Смешивать с
  // конкурентными тоже нельзя — торга в них не было. Поэтому помечаем, а решение
  // о смешивании принимается в статистике, на виду.
  const признакиЕЗ = признакиЕдинственнойЗаявки(текст, основаниеНесостоявшейся);
  const единственнаяЗаявка = признакиЕЗ.length > 0;

  // ЗАКУПКА С ЦЕНОЙ ЗА ЕДИНИЦУ ТОВАРА — СНИЖЕНИЕ ИЗ НЕЁ НЕ СЧИТАЕТСЯ.
  //
  // Найдено на первом сборе 05.10.2026. В выборке по слову «бумага» появились
  // снижения 89,9%, 81,6%, 76,3% — бумагу втрое дешевле не продают.
  //
  // Объяснение: когда заказчик не знает объём заранее (часть 24 статьи 42),
  // он объявляет закупку с ценой единицы товара. НМЦК в такой закупке — это
  // МАКСИМАЛЬНОЕ ЗНАЧЕНИЕ ЦЕНЫ КОНТРАКТА, а участник подаёт ЦЕНУ ЗА ЕДИНИЦУ.
  // Это величины разного порядка, и их разность снижением не является вовсе.
  //
  // Исключаем по признаку на странице, а не по величине результата: отбрасывать
  // наблюдение за то, что число большое, значит подгонять выборку под ожидание.
  // Настоящие глубокие снижения бывают, и терять их нельзя.
  const ценаЗаЕдиницу = /цена\s+единиц/.test(низ)
    || /максимальное\s+значение\s+цены\s+контракт/.test(низ)
    || /за\s+единицу\s+товар/.test(низ);

  if (нмцк === null) issues.push('начальная цена на странице не найдена');
  if (ценаПобеды === null) {
    if (многоБезПобедителя) {
      issues.push(`в таблице предложений ${победители.length} строк, и ни в одной не сказано, `
        + 'кто победитель — похоже на многолотовую закупку. Цена победы не выбирается: '
        + 'угадывание дало бы тихо неверное снижение');
    } else if (!естьТаблицаПобедителей) {
      issues.push('на странице нет таблицы «Предложения участников» — '
        + (неСостоялась ? 'закупка не состоялась' : 'вероятна ошибка разбора'));
    } else {
      issues.push(неСостоялась
        ? 'закупка признана несостоявшейся — победителя нет'
        : 'цена победителя не найдена, при этом признаков несостоявшейся закупки '
          + 'на странице нет — вероятна ошибка разбора');
    }
  }

  if (ценаЗаЕдиницу) {
    issues.push('закупка с ценой за единицу товара — НМЦК и предложение участника '
      + 'величины разного порядка, снижение из них не выводится');
  }

  if (ценаНеИзКолонки) {
    issues.push('колонку «Предложения участников» в таблице сопоставить не удалось — '
      + 'цена взята как первая похожая на деньги ячейка строки. Значение под сомнением');
  }

  // Контракт заключается, хотя закупка формально признана несостоявшейся. Это
  // не замечание о сбое, а факт, который должен попасть в наблюдение.
  if (единственнаяЗаявка && ценаПобеды !== null) {
    issues.push('подана единственная заявка: закупка признана несостоявшейся, но контракт '
      + 'заключается по цене этого участника. Торга не было — с конкурентными '
      + 'закупками такое наблюдение смешивать нельзя');
  }

  return {
    номер, объект, способ, нмцк, ценаПобеды, победители,
    неСостоялась, основаниеНесостоявшейся,
    признакиНесостоявшейся: признакиНС.признаки,
    решающиеПризнакиНесостоявшейся: признакиНС.решающие,
    единственнаяЗаявка, признакиЕдинственнойЗаявки: признакиЕЗ,
    естьТаблицаПобедителей, многоБезПобедителя,
    колонкаЦены, ценаНеИзКолонки,
    ценаЗаЕдиницу, issues
  };
}

/**
 * Разбирает вкладку «Список заявок».
 *
 * @param {string} html
 * @param {object} [опции] {наСтранице}
 * @returns {object} {заявки, участников, участниковТочно, issues}
 */
function parseBidList(html, опции = {}) {
  const текст = String(html || '');
  const наСтранице = опции.наСтранице || ЗАЯВОК_НА_СТРАНИЦЕ;
  const issues = [];

  const шапки = шапкиТаблиц(текст);
  const естьСписок = шапки.some((h) => /идентификационный\s+номер\s+участник/i.test(h));
  if (!естьСписок) {
    return {
      заявки: [],
      участников: null,
      участниковТочно: false,
      issues: ['таблица заявок на странице не найдена']
    };
  }

  const заявки = [];
  for (const ячейки of строкиТаблиц(текст)) {
    // Длину идентификатора не проверяем — она не обещана. Строку заявки
    // определяет дата подачи либо результат рассмотрения: без них это не заявка.
    const естьДата = ячейки.some((c) => /\d{2}\.\d{2}\.\d{4}/.test(c));
    const естьРезультат = ячейки.some((c) => /соответствует|отклонен/i.test(c));
    if (!естьДата && !естьРезультат) continue;

    const ид = ячейки.find((c) => /^\d+$/.test(c)) || '';

    const цены = ячейки.map(деньгиИзЯчейки).filter((v) => v !== null && v > 0);
    const место = ячейки.find((c) => /\d+\s*-\s*[А-Яа-яЁё]/.test(c)) || '';
    const результат = ячейки.find((c) => /соответствует|отклонен|не соответствует/i.test(c)) || '';
    const отклонена = /отклонен/i.test(результат);

    заявки.push({
      ид,
      место,
      // У отклонённой заявки цены на портале нет. Если она всё же нашлась —
      // это признак того, что разбор взял чужую ячейку, и значение не берём.
      цена: (!отклонена && цены.length) ? цены[цены.length - 1] : null,
      результат,
      отклонена,
      победитель: /победител/i.test(место)
    });
  }

  // ЧИСЛО УЧАСТНИКОВ ЗНАЕМ ТОЧНО ТОЛЬКО ЕСЛИ СТРАНИЦА НЕ ЗАПОЛНЕНА ДОВЕРХУ.
  //
  // Блок постраничности в разметке пустой — его рисует JavaScript. Если заявок
  // ровно столько, сколько вмещает страница, их может быть и больше. Назвать
  // это число участниками означало бы занизить конкуренцию, а занижение здесь
  // опаснее отказа: тендер выглядел бы менее конкурентным, чем он есть.
  const участниковТочно = заявки.length < наСтранице;
  if (!участниковТочно && заявки.length > 0) {
    issues.push(`заявок на странице ровно ${заявки.length} — возможно, есть ещё. `
      + 'Число участников не определено');
  }

  // РАЗБРОС ПРЕДЛОЖЕНИЙ — ПРИЗНАК ЗАКУПКИ С НЕОПРЕДЕЛЁННЫМ ОБЪЁМОМ.
  //
  // Найдено 05.10.2026. Закупка 0117100015526000101 («заправка картриджей и
  // ремонт печатной техники», НМЦК 1 412 900) дала «снижение 89,9%». Предложения
  // участников там: 143 145, 147 762, 401 730, 914 281 — разброс в шесть раз на
  // один и тот же лот.
  //
  // В обычной закупке предложения кучкуются: участники считают одну и ту же
  // поставку и приходят к близким числам. Шестикратный разброс означает, что
  // участники считали РАЗНОЕ — так бывает при неопределённом объёме, когда цена
  // подаётся за единицу или за условный объём работ. Сравнивать такое с НМЦК
  // нельзя: получается фиктивное снижение.
  //
  // Признак берётся из самих цен на странице, а не из величины снижения. Это
  // важно: отбрасывать наблюдение за то, что снижение большое, значит подгонять
  // выборку под ожидание, а настоящие глубокие снижения бывают.
  //
  // Порог «более чем втрое» — не измерение, а граница здравого смысла, и названа
  // здесь прямо как таковая. Уточнить её можно будет на накопленной выборке,
  // когда станет видно, как распределён разброс в обычных закупках.
  const цены = заявки.map((з) => з.цена).filter((c) => typeof c === 'number' && c > 0);
  let разбросПредложений = null;
  if (цены.length >= 2) {
    const мин = Math.min(...цены);
    const макс = Math.max(...цены);
    разбросПредложений = мин > 0 ? Math.round((макс / мин) * 100) / 100 : null;
  }
  const предложенияНесопоставимы = разбросПредложений !== null && разбросПредложений > 3;
  if (предложенияНесопоставимы) {
    issues.push(`предложения участников различаются в ${разбросПредложений} раза — `
      + 'участники считали разное. Признак закупки с неопределённым объёмом, '
      + 'снижение из неё не выводится');
  }

  return {
    заявки,
    участников: заявки.length,
    участниковТочно,
    разбросПредложений,
    предложенияНесопоставимы,
    issues
  };
}

/**
 * Снижение цены в процентах от НМЦК.
 *
 * Возвращает null, когда считать нечего. Ноль и null — разные ответы: ноль
 * означает «цену не снижали», null — «неизвестно».
 */
function снижение(нмцк, ценаПобеды) {
  if (typeof нмцк !== 'number' || !Number.isFinite(нмцк) || нмцк <= 0) return null;
  if (typeof ценаПобеды !== 'number' || !Number.isFinite(ценаПобеды) || ценаПобеды < 0) return null;
  return Math.round(((нмцк - ценаПобеды) / нмцк) * 1000) / 10;
}

/**
 * Собирает одно наблюдение для статистики из двух страниц.
 *
 * @param {object} результаты вывод parseSupplierResults
 * @param {object} [список] вывод parseBidList, если страница доступна
 * @returns {object} {годится, причина, наблюдение}
 */
function наблюдение(результаты, список = null) {
  const r = результаты || {};
  const сниж = снижение(r.нмцк, r.ценаПобеды);

  // ТОЛЬКО ЗАКУПКИ, ГДЕ ПОБЕДИТЕЛЬ ОПРЕДЕЛЁН. Требование владельца 05.10.2026:
  // «не бери в расчёт несостоявшиеся тендеры, бери только те контракты, которые
  // были заключены».
  //
  // ПРИЗНАК ЗАКЛЮЧЁННОГО КОНТРАКТА — НАЛИЧИЕ ЦЕНЫ ПОБЕДЫ, А НЕ ОТСУТСТВИЕ
  // СЛОВА «НЕСОСТОЯВШАЯСЯ». Здесь стояла проверка `if (r.неСостоялась) отказ`, и
  // она была неверна по сути: по п. 1 ч. 1 ст. 52 закупка с единственной заявкой
  // признаётся несостоявшейся, НО контракт с этим участником заключается по его
  // цене. Таких на сборе 05.10.2026 было 7 из 50, и все семь терялись.
  //
  // Поэтому порядок такой: несостоявшаяся закупка без цены победы — отказ (и
  // причина называется отдельно от ошибки разбора, потому что первое штатный
  // исход, а второе повод чинить код); несостоявшаяся с ценой победы —
  // наблюдение с пометкой «единственная заявка».
  //
  // Если бы закупка без цены попала в выборку как «снижение 0%», медиана поехала
  // бы к нулю — та же ошибка, из-за которой убрали допущение 12%.

  // Цена за единицу товара: НМЦК это максимальное значение цены контракта, а
  // предложение участника — цена за единицу. Разность снижением не является.
  if (r.ценаЗаЕдиницу) {
    return {
      годится: false,
      причина: 'закупка с ценой за единицу товара — НМЦК и предложение несравнимы',
      наблюдение: null
    };
  }

  // Предложения участников разошлись более чем втрое — значит они считали разное,
  // то есть объём закупки не определён. На странице результатов про это не
  // написано, поэтому признак берётся из самих цен в списке заявок.
  if (список && список.предложенияНесопоставимы) {
    return {
      годится: false,
      причина: `предложения участников различаются в ${список.разбросПредложений} раза `
        + '— объём закупки не определён, снижение несопоставимо',
      наблюдение: null
    };
  }

  if (сниж === null) {
    let причина;
    if (r.ценаПобеды !== null) {
      причина = 'нет начальной цены';
    } else if (r.многоБезПобедителя) {
      причина = 'несколько строк предложений, победитель не назван — похоже на многолотовую '
        + 'закупку, цену победы выбирать нельзя';
    } else if (r.неСостоялась) {
      // Текст причины ОДИНАКОВЫЙ для всех таких закупок, и это намеренно:
      // сборщик группирует отказы по тексту причины, чтобы видеть, какая сколько
      // весит. Подставив сюда основание со страницы, я получил бы столько групп,
      // сколько закупок, то есть вернул бы список из 36 одинаковых строк, от
      // которого и уходил. Основание печатает диагностика по конкретной закупке.
      причина = 'закупка не состоялась — победителя нет';
    } else {
      причина = 'цена победы не найдена, признаков несостоявшейся закупки нет — проверить разбор';
    }
    return { годится: false, причина, наблюдение: null };
  }

  // Закупка у единственного поставщика снижения не имеет по своей природе.
  // Оставить её в выборке значит потянуть медиану к нулю и занизить ожидаемое
  // снижение — то есть сделать ровно ту ошибку, из-за которой убрали 12%.
  if (r.способ === СПОСОБ.ЕДИНСТВЕННЫЙ) {
    return { годится: false, причина: 'закупка у единственного поставщика', наблюдение: null };
  }

  // Снижение вне разумных границ — признак того, что со страницы взято не то
  // число, а не рыночное явление. Отрицательное означает цену выше начальной,
  // что для 44-ФЗ невозможно.
  if (сниж < 0) {
    return { годится: false, причина: `цена победы выше НМЦК (${сниж}%) — разбор неверен`, наблюдение: null };
  }
  if (сниж > 95) {
    return { годится: false, причина: `снижение ${сниж}% неправдоподобно — разбор неверен`, наблюдение: null };
  }

  // ЕДИНСТВЕННАЯ ЗАЯВКА — ДВА НЕЗАВИСИМЫХ ПРИЗНАКА, ЛЮБОГО ДОСТАТОЧНО.
  //
  // Первый — слова на странице результатов («подана только одна заявка»,
  // ссылка на п. 1 ч. 1 ст. 52). Второй — список заявок, в котором ровно одна
  // строка И число заявок известно точно. Второй признак сильнее, но страница
  // списка заявок доступна не всегда, поэтому полагаться только на неё нельзя.
  const одинаИзСписка = Boolean(список && список.участниковТочно && список.участников === 1);
  const единственнаяЗаявка = Boolean(r.единственнаяЗаявка) || одинаИзСписка;

  // Когда заявка единственная, число участников известно точно и без списка
  // заявок: портал называет это основанием признания закупки несостоявшейся.
  let участников = список && список.участниковТочно ? список.участников : null;
  if (участников === null && единственнаяЗаявка) участников = 1;

  return {
    годится: true,
    причина: '',
    наблюдение: {
      номер: r.номер || '',
      объект: r.объект || '',
      способ: r.способ,
      нмцк: r.нмцк,
      ценаПобеды: r.ценаПобеды,
      снижение: сниж,
      участников,
      участниковНеМенее: список && !список.участниковТочно ? список.участников : null,
      // Последние предложения ВСЕХ участников (владелец 28.10.2026: в прогноз
      // цены победы), по возрастанию; отклонённые заявки цены не имеют.
      предложения: список ? список.заявки.map((з) => з.цена).filter((c) => typeof c === 'number' && c > 0).sort((a, b) => a - b).slice(0, 30) : [],

      // Пометка доходит до статистики, а не остаётся здесь: разрезы обязаны
      // показывать медиану и с такими закупками, и без них. Выбрать за владельца
      // нельзя — правило 04.10.2026: «если из разных источников результаты
      // рознятся, нужно не выбирать и не выдумывать, а показывать диапазон и его
      // обоснование».
      единственнаяЗаявка
    }
  };
}

/** Имя сайта для достройки путей от корня. */
const БАЗА = 'https://zakupki.gov.ru';

/**
 * Адрес страницы «Результаты определения поставщика» из ссылки на карточку.
 *
 * Заменяется только имя страницы. Путь целиком конструировать нельзя: в нём
 * закодирован тип процедуры (ea20, zk20, ok20), которого из реестрового номера
 * не вывести. Это то же исключение из правила «ссылки брать из разметки», что и
 * для страницы документов.
 *
 * ПРОВЕРЕНО 05.10.2026 по разметке сохранённых карточек: обе печатают ровно
 * такой адрес, то есть замена имени страницы даёт то же, что портал.
 */
function адресРезультатов(ссылкаНаКарточку) {
  const s = String(ссылкаНаКарточку || '');
  if (!s) return '';
  return s.replace(/\/[a-z-]+\.html/, '/supplier-results.html');
}

/**
 * Адрес вкладки «Список заявок» из адреса протокола.
 *
 * ИМЯ СТРАНИЦЫ — `protocol-bid-list.html`, В ЕДИНСТВЕННОМ ЧИСЛЕ. Сначала было
 * написано `protocol-bids-list` по аналогии с подписью вкладки — это был
 * домысел. Настоящее имя взято из разметки сохранённых страниц протоколов
 * 05.10.2026: обе печатают три вкладки — protocol-main-info.html,
 * protocol-bid-list.html, protocol-docs.html.
 *
 * Такая опечатка не падает, а даёт 404, то есть выглядела бы как «списка заявок
 * у этой закупки нет», и число участников молча не определялось бы никогда.
 */
function адресСпискаЗаявок(адресПротокола) {
  return String(адресПротокола || '').replace(/protocol-main-info\.html/, 'protocol-bid-list.html');
}

/**
 * Ссылки на протоколы со страницы.
 *
 * АДРЕС ПРОТОКОЛА СКОНСТРУИРОВАТЬ НЕЛЬЗЯ: в нём тип протокола и номер версии
 * (`…?regNumber=…&type=izk&version=1`). У электронного аукциона типов два — cpa
 * (подача ценовых предложений) и iea (подведение итогов), у запроса котировок
 * один — izk. Из номера закупки это не выводится. Ссылки печатает сама страница.
 *
 * Страница результатов определения поставщика содержит ссылку на нужный
 * протокол — проверено на обеих сохранённых страницах, по одной ссылке на
 * каждой. Значит отдельный запрос карточки ради этих ссылок не нужен.
 */
function ссылкиНаПротоколы(html) {
  const out = new Set();
  const re = /href="([^"]*protocol[^"]*)"/gi;
  let m;
  while ((m = re.exec(String(html || '')))) {
    const u = decode(m[1]);
    out.add(u.indexOf('http') === 0 ? u : БАЗА + u);
  }
  return [...out];
}

