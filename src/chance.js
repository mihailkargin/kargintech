/**
 * ШАНС НА ПОБЕДУ — тариф Макс, решение владельца 21.10.2026.
 *
 * Это не прогноз и не обещание, а сравнение двух фактов: до какой цены клиент
 * может опуститься без убытка (безубыточность из расчёта) и по каким ценам
 * выигрывали похожие прошлые закупки (протоколы с портала). Ответ всегда с
 * размером выборки: «в 7 из 9 похожих закупок».
 *
 * Похожие - то же правило, что у рейтинга (src/rating.js, похожиеЗакупки):
 * тот же способ, НМЦК не дальше полутора раз, тот же товар по ОКПД2, если он
 * известен. Меньше трёх похожих - шанс не оценивается.
 *
 * Вывод по одним ценам обоснования НМЦК не делается (правило 04.10.2026):
 * безубыточность по потолку с чужой маржой ничего не говорит.
 *
 * Сетевых обращений нет.
 */
const { определитьСпособ } = require('./protocol-page');
const { похожиеЗакупки } = require('./rating');

const медиана = (в) => {
  if (!в.length) return null;
  const с = [...в].sort((a, b) => a - b);
  return с.length % 2 ? с[(с.length - 1) / 2] : (с[с.length / 2 - 1] + с[с.length / 2]) / 2;
};
const окр = (x) => Math.round(x * 10) / 10;

/**
 * @param {object[]} наблюдения протоколы прошлых закупок
 * @param {{нмцк: number, способ: string, группыОкпд2?: string[]}} тендер способ - текст закона/способа
 * @param {{запас: number|null, запасЛучший?: number|null, толькоПотолки?: boolean}} расчёт запас в % от НМЦК
 */
function шансПобеды(наблюдения, тендер, расчёт = {}) {
  const нет = (причина) => ({ оценён: false, причина });
  if (расчёт.толькоПотолки) return нет('закупочных цен нет - сравнивать безубыточность по ценам заказчика бессмысленно');
  const запас = typeof расчёт.запас === 'number' ? расчёт.запас : null;
  const лучший = typeof расчёт.запасЛучший === 'number' ? расчёт.запасЛучший : null;
  if (запас === null && лучший === null) return нет('безубыточность не рассчитана');
  const способ = определитьСпособ(String(тендер.способ || ''));
  const отбор = похожиеЗакупки(наблюдения, { нмцк: тендер.нмцк, способ, группыОкпд2: тендер.группыОкпд2 });
  if (!отбор.достаточно) return нет(отбор.причина);

  // Конкурентные закупки: с единственной заявкой торга не было, снижение там
  // почти нулевое - они завысили бы шанс.
  const конкурентные = отбор.похожие.filter((н) => !н.единственнаяЗаявка);
  const база = конкурентные.length >= 3 ? конкурентные : отбор.похожие;
  // Победили по цене, до которой клиент может опуститься без убытка:
  // снижение победителя не больше нашего запаса.
  const могли = (з) => (з === null ? null : база.filter((н) => н.снижение <= з).length);
  const участники = база.map((н) => н.участников).filter((x) => typeof x === 'number');
  return {
    оценён: true,
    похожих: база.length,
    единственных: отбор.похожие.length - конкурентные.length,
    поХудшей: могли(запас),
    поЛучшей: лучший !== null && лучший !== запас ? могли(лучший) : null,
    запас, запасЛучший: лучший,
    медианаСнижения: окр(медиана(база.map((н) => н.снижение))),
    снижениеОт: окр(Math.min(...база.map((н) => н.снижение))),
    снижениеДо: окр(Math.max(...база.map((н) => н.снижение))),
    медианаУчастников: участники.length ? медиана(участники) : null,
    причина: отбор.причина
  };
}

/** Текст для клиента. Без «гарантии» и «вероятности»: только счёт по прошлым закупкам. */
function текстШанса(ш) {
  if (!ш || !ш.оценён) return `Шанс на победу не оценён: ${ш ? ш.причина : 'нет данных'}.`;
  const з = (x) => String(окр(x)).replace('.', ',');
  const строки = [];
  const лучший = ш.запасЛучший !== null ? ш.запасЛучший : ш.запас;
  if (лучший !== null && лучший <= 0) {
    строки.push('Расходы не ниже начальной цены даже по лучшей цене поставщика: выиграть без убытка нельзя.');
  } else if (ш.запас !== null && ш.запас <= 0) {
    строки.push(`По худшей цене поставщика расходы выше начальной цены. По лучшей запас ${з(ш.запасЛучший)}% - так выигрывали в ${ш.поЛучшей} из ${ш.похожих} похожих закупок.`);
  } else if (ш.поХудшей !== null) {
    строки.push(`В ${ш.поХудшей} из ${ш.похожих} похожих закупок победитель выиграл со снижением не больше ${з(ш.запас)}% - до такой цены вы можете опуститься без убытка${ш.поЛучшей !== null ? ' по худшей цене поставщика' : ''}.`);
  }
  if (ш.поЛучшей !== null && ш.запас !== null && ш.запас > 0) строки.push(`По лучшей цене поставщика запас ${з(ш.запасЛучший)}% - так выигрывали в ${ш.поЛучшей} из ${ш.похожих}.`);
  строки.push(`Снижение у похожих: от ${з(ш.снижениеОт)}% до ${з(ш.снижениеДо)}%, обычно ${з(ш.медианаСнижения)}%${ш.медианаУчастников !== null ? `, участников обычно ${з(ш.медианаУчастников)}` : ''}.`);
  return строки.join(' ');
}

/**
 * Как падала цена у похожих прошлых закупок - для карточки тендера, ДО
 * расчёта (22.10.2026). Безубыточность не нужна: это факт о рынке, не вывод.
 * Отбор - тот же, что у рейтинга и шанса (похожиеЗакупки).
 */
function историяПохожих(наблюдения, тендер) {
  const способ = определитьСпособ(String(тендер.способ || ''));
  const отбор = похожиеЗакупки(наблюдения, { нмцк: тендер.нмцк, способ, группыОкпд2: тендер.группыОкпд2 });
  if (!отбор.достаточно) return { оценена: false, похожих: отбор.похожие.length, причина: отбор.причина };
  const конкурентные = отбор.похожие.filter((н) => !н.единственнаяЗаявка);
  const база = конкурентные.length >= 3 ? конкурентные : отбор.похожие;
  const сн = база.map((н) => н.снижение).sort((a, b) => a - b);
  const четверть = (q) => { const i = (сн.length - 1) * q; const н = Math.floor(i); return сн[н] + (сн[Math.min(н + 1, сн.length - 1)] - сн[н]) * (i - н); };
  const участники = база.map((н) => н.участников).filter((x) => typeof x === 'number');
  return {
    оценена: true,
    похожих: база.length,
    единственных: отбор.похожие.length - конкурентные.length,
    медиана: окр(медиана(сн)),
    от: окр(сн[0]), до: окр(сн[сн.length - 1]),
    q1: окр(четверть(0.25)), q3: окр(четверть(0.75)),
    медианаУчастников: участники.length ? медиана(участники) : null,
    примеры: [...база].sort((a, b) => String(b.дата || '').localeCompare(String(a.дата || ''))).slice(0, 5)
      .map((н) => ({ номер: н.номер, нмцк: н.нмцк, снижение: окр(н.снижение), участников: н.участников ?? null })),
    причина: отбор.причина
  };
}

module.exports = { шансПобеды, текстШанса, историяПохожих };
